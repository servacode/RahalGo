/**
 * ══════════════════════════════════════════════════════════════════════
 * **قاموسُ المسافات والمخارج — ولا رقمَ يُرسَل إلى المحرّك**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (مواصفةُ المالك ٢٠٢٦-٠٨-٢٣، البندان ٦ و٧.)
 *
 * **ممنوعٌ إرسالُ الأرقام الرقميّة** — `300 متر` يقرؤها المحرّكُ كما
 * يشاء: «ثلاثمئة» أو «ثلاث صفر صفر» أو بالإنكليزيّة. **ولا يُترك
 * القرارُ له.**
 *
 * # والتشكيلُ للنطق لا للإعراب
 *
 * (البند ٤.) **لا تشكيلَ نحويّاً كاملاً** — `بَعْدَ ثَلَاثِمِئَةِ
 * مِتْرٍ` تُقرأ خطبةً لا إرشادَ سائق. **بل `بَعْد ثَلاثمِئَة مِتْر`:**
 * حركاتٌ داخلَ الكلمة تمنع الخطأ، **وأواخرُ الكلمات تُترك ساكنةً كما
 * ينطقها الناس.**
 */

/**
 * **مسافةٌ منطوقة** — بالمتر، ونصُّها كما يُسمع.
 *
 * # وتمييزُ العدد ليس زينةً
 *
 * **بعد العشرين إلى التسعة والتسعين يُنصب المعدودُ ويُنوَّن**: «خَمسين
 * **مِترًا**» لا «خمسين مِتر». **والساكنُ يخرج مبتوراً** — الأذنُ
 * العربيّةُ تنتظر التنوينَ فتسمع كلمةً مقطوعة. (بلاغُ المالك
 * ٢٠٢٦-٠٨-٢٤: «مشكلة بنطق الأرقام… مثلاً ٢٥٠ مترًا».)
 *
 * **وبعد المئة والمئتين والثلاثمئة إضافةٌ لا تمييز**: «مِئَة مِتر»
 * بالجرّ بلا تنوين. **والمئتان في الإضافة تُسقط نونَها**: «مِئَتَي
 * مِتر» لا «مئتين متر» — **وهذه كانت خطأً صريحاً.**
 *
 * **والقاعدةُ تنقلب عند العطف**: «مِئَتَين **وخَمسين مِترًا**» — لأنّ
 * العددَ الأخيرَ هو الذي يحكم المعدود، وهو من عقود العشرات.
 */
export const DISTANCES: ReadonlyMap<number, string> = new Map([
  [50, 'خَمسين مِتْرًا'],
  [100, 'مِئَة مِتْر'],
  [150, 'مِئَة وخَمسين مِتْرًا'],
  [200, 'مِئَتَي مِتْر'],
  [250, 'مِئَتَين وخَمسين مِتْرًا'],
  [300, 'ثَلاثمِئَة مِتْر'],
  [400, 'أَربَعمِئَة مِتْر'],
  [500, 'خَمسمِئَة مِتْر'],
  [600, 'سِتّمِئَة مِتْر'],
  [700, 'سَبعمِئَة مِتْر'],
  [800, 'ثَمانِمِئَة مِتْر'],
  [900, 'تِسعمِئَة مِتْر'],
  [1000, 'كيلومِتْر واحِد'],
  [1500, 'كيلومِتْر ونِصف'],
  [2000, 'كيلومِتْرَين'],
  [3000, 'ثَلاثَة كيلومِتْرات'],
]);

/** **وترتيبُ المخرج** — من الأوّل إلى الثاني عشر. */
export const ORDINALS: ReadonlyMap<number, string> = new Map([
  [1, 'الأَوَّل'],
  [2, 'الثّاني'],
  [3, 'الثّالِث'],
  [4, 'الرّابِع'],
  [5, 'الخامِس'],
  [6, 'السّادِس'],
  [7, 'السّابِع'],
  [8, 'الثّامِن'],
  [9, 'التّاسِع'],
  [10, 'العاشِر'],
  [11, 'الحادِي عَشَر'],
  [12, 'الثّاني عَشَر'],
]);

export class LexiconError extends Error {}

/** **ونصُّ المسافة يُطلب ولا يُشتقّ** — **ورقمٌ لا قراءةَ له خطأٌ يُقال.** */
export function spokenDistance(meters: number): string {
  const s = DISTANCES.get(meters);
  if (s === undefined) throw new LexiconError(`لا قراءةَ لمسافة ${meters}`);
  return s;
}

export function spokenOrdinal(exit: number): string {
  const s = ORDINALS.get(exit);
  if (s === undefined) throw new LexiconError(`لا قراءةَ لمخرجٍ رقمُه ${exit}`);
  return s;
}

/** **واسمُ الملفّ للمسافة** — `300m` · `1500m` كما هي بالمتر. */
export function distanceSlug(meters: number): string {
  return `${meters}m`;
}
