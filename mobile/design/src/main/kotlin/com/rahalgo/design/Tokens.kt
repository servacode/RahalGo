package com.rahalgo.design

import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

// ══════════════════════════════════════════════════════════════════════
// **الشكلُ والمسافة — توكنزُ كما الألوان**
// ══════════════════════════════════════════════════════════════════════
//
// (طلبُ المالك ٢٠٢٦-٠٨-١٨: «بدنا نوحّد ستايلَ التطبيقات مشان كلّ
//
//	التطبيقات تطلع بنفس التصميم والستايل، الألوان والأزرار وشكلها وكلّ
//	شيءٍ بيها يكون موحّد — يعني مو كلّ تطبيقٍ وكلّ صفحةٍ وكلّ قسمٍ
//	تصميمه على كيفه».)
//
// # ما كان يقع
//
// **الألوانُ موحّدةٌ منذ البداية** — صفرُ لونٍ مكتوبٍ بيدٍ خارجَ هذه
// الوحدة في التطبيقات الثلاثة. **والشكلُ لم يكن.** قِيس ٢٠٢٦-٠٨-١٨:
// **اثنان وخمسون نصفَ قطرٍ مكتوباً بيد** وسبعُ مئةٍ وخمسٌ وعشرون مسافةً
// خاما.
//
// **فزرٌّ في تطبيق السائق نصفُ قطره ١٢ وفي الزبون ٨ وفي المندوب ١٦** —
// **ولا أحدَ قرّر ذلك**: كلٌّ كتب ما بدا له في لحظته، فصارت المنصّةُ
// الواحدةُ ثلاثةَ تطبيقاتٍ تبدو من ثلاث شركات.
//
// # ولماذا القِيَمُ من الشيفرة لا من رأسي
//
// **أُخذ السلّمُ ممّا هو مستعملٌ فعلاً** — لا من كتابِ تصميم. (وهو
// قرارُ المالك نفسُه في الألوان ٢٠٢٦-٠٨-١٦: «الألوانَ نأخذها من
// تصميمنا ولا نضيف ألواناً جديدة».)
//
// **وسلّمٌ مخترَعٌ يعني أن تتغيّر كلُّ شاشةٍ يومَ يُعتمَد** — فتصير
// الدفعةُ «توحيدُ توكنز» في الحقيقة **إعادةَ تصميمٍ لم يطلبها أحد.**

/**
 * أنصافُ الأقطار — **أربعةٌ لا أكثر.**
 *
 * **والقِيَمُ هي الغالبةُ في الشيفرة**: ١٤ أكثرُها (خمسَ عشرةَ مرّة)،
 * ثمّ ٢٠ و١٠. **وما بينها (١٢ · ١٦ · ١٨) فروقٌ لا تُرى بالعين**
 * وتُرى في الشيفرة — وهي عينُ التشتّت.
 */
data class RahalShapes(
    /** **الرقائقُ والوسومُ الصغيرة.** */
    val sm: RoundedCornerShape = RoundedCornerShape(10.dp),
    /** **البطاقاتُ والحقولُ والأزرار** — وهو الغالب. */
    val md: RoundedCornerShape = RoundedCornerShape(14.dp),
    /** **الألواحُ والنوافذُ المنبثقة.** */
    val lg: RoundedCornerShape = RoundedCornerShape(20.dp),
    /**
     * **الدائريُّ الكامل** — للأزرار العائمة والصور الشخصيّة.
     *
     * **ونسبةٌ لا رقمٌ ثابت**: `RoundedCornerShape(50)` تعني «نصفَ
     * الارتفاع مهما كان»، **ورقمٌ ثابتٌ يجعل زرّاً طويلاً بيضويّاً
     * وقصيراً مربّعَ الزوايا.**
     */
    val pill: RoundedCornerShape = RoundedCornerShape(percent = 50),

    /**
     * **اللوحُ الصاعدُ من الأسفل** — أعلاه مستديرٌ وأسفلُه على الحافّة.
     *
     * **وأسفلٌ مستديرٌ يترك خطّاً من الشاشة تحته** يُقرأ فراغاً لا
     * تصميما.
     */
    val sheet: RoundedCornerShape = RoundedCornerShape(topStart = 20.dp, topEnd = 20.dp),
    /** **فقاعةُ رسالتي** — ذيلُها في زاويتي السفلى (مراجعةُ التصميم ٢٠٢٦-١١-٠٩). */
    val bubbleMine: RoundedCornerShape =
        RoundedCornerShape(topStart = 18.dp, topEnd = 18.dp, bottomStart = 18.dp, bottomEnd = 4.dp),
    /** **فقاعةُ الطرف الآخر** — ذيلُها في الزاوية المقابلة. */
    val bubbleTheirs: RoundedCornerShape =
        RoundedCornerShape(topStart = 18.dp, topEnd = 18.dp, bottomStart = 4.dp, bottomEnd = 18.dp),
)

/**
 * المسافات — **سلّمٌ من أربعةٍ ومضاعفاتها.**
 *
 * **ولا نصفَ درجةٍ فيه.** الشيفرةُ اليومَ فيها ٦ و١٠ و١٤ بكثرة
 * (٢٤٦ موضعاً) — **وهي درجاتٌ بين الدرجات**، ووجودُها هو ما يجعل
 * حشوتين متجاورتين تختلفان بمقدارِ شعرةٍ بلا سبب.
 *
 * **وتقريبُها إلى السلّم يُغيّر الشكلَ قليلاً** — فلا يقع في هذه
 * الدفعة، **ولا يقع إلّا وعينُ المالك عليه.**
 */
data class RahalSpace(
    /** **لا مسافة** — لبطاقةِ صورةٍ تملأ حوافَّها. */
    val none: Dp = 0.dp,
    /** **شعرةٌ بين سطرين متلاصقين** — اسمٌ وتحته سطرُه. */
    val xxs: Dp = 2.dp,
    val xs: Dp = 4.dp,
    val sm: Dp = 8.dp,
    val md: Dp = 12.dp,
    val lg: Dp = 16.dp,
    val xl: Dp = 24.dp,
    val xxl: Dp = 32.dp,
    /** **حشوةُ الشاشة من الجانبين** — رقمٌ واحدٌ لكلّ الشاشات (`ScreenPad`). */
    val gutter: Dp = 16.dp,
    /** **الفراغُ تحت آخر سطرٍ في الشاشة** — لا تنتهي القائمةُ عند حافّة الشريط. */
    val tail: Dp = 32.dp,
)

/**
 * سماكاتُ الخطوط — **الحدُّ شعرةٌ والمُختارُ ضِعفُها.**
 *
 * **وحدٌّ بسماكةٍ ثالثةٍ يُقرأ عطباً في الرسم** لا اختياراً.
 */
data class RahalStroke(
    val hair: Dp = 1.dp,
    val focus: Dp = 2.dp,
)

/**
 * **الارتفاعُ (الظلّ)** — خمسُ درجاتٍ لا أكثر (نظامُ التصميم ٢٠٢٦-١١-١١).
 *
 * **والظلُّ يقول «هذا يُضغط أو يطفو»** — فبطاقةُ معلومةٍ لا ظلَّ لها (`tinted`/`outlined`)،
 * **وبطاقةٌ بظلٍّ تُقرأ زرّاً** (D9: بطاقةُ الرسوم بظلٍّ بدت زرّاً).
 */
data class RahalElevation(
    val none: Dp = 0.dp,
    /** **رقاقةٌ مرفوعةٌ شعرة.** */
    val low: Dp = 1.dp,
    /** **البطاقةُ المرفوعة** (`RahalCard` الافتراضيّة). */
    val card: Dp = 3.dp,
    /** **ما يطفو فوق المحتوى** — الشريطُ السفليُّ الثابت، الزرُّ العائم. */
    val raised: Dp = 6.dp,
    /** **النوافذُ والألواح.** */
    val overlay: Dp = 8.dp,
)

/** **مقاساتُ الأيقونات** — خمسةٌ (نظامُ التصميم ٢٠٢٦-١١-١١). */
data class RahalIconSize(
    /** **داخل شارةٍ أو بجانب نصٍّ صغير.** */
    val xs: Dp = 16.dp,
    /** **بجانب سطرٍ عاديّ** — أيقونةُ زرٍّ أو `ListRow`. */
    val sm: Dp = 20.dp,
    /** **الافتراضيّة** — شريطُ الرأس، `IconTile`، `IconAction`. */
    val md: Dp = 24.dp,
    /** **أيقونةُ حالةٍ فارغة.** */
    val lg: Dp = 32.dp,
    /** **أيقونةٌ بطلة** — شاشةُ نجاح. */
    val xl: Dp = 48.dp,
)

/** **مقاساتُ القطع** — ما يتكرّر من الأحجام الثابتة (نظامُ التصميم ٢٠٢٦-١١-١١). */
data class RahalSize(
    /** **أصغرُ مساحةِ لمس** — ٤٨ (إرشادُ أندرويد)؛ لا زرَّ أصغرَ منها لمساً. */
    val touch: Dp = 48.dp,
    /** **زرُّ أيقونةٍ مدوَّر** (`IconAction`) — الاتّصال والواتساب والكاميرا. */
    val action: Dp = 48.dp,
    /** **مربّعُ أيقونةٍ ملوّن** (`IconBox`) بجانب سطر. */
    val iconBox: Dp = 40.dp,
    /** **صورةٌ شخصيّةٌ صغيرة** — في سطر. */
    val avatarSm: Dp = 40.dp,
    /** **صورةٌ متوسّطة** — رأسُ القائمة الجانبيّة، بطاقةُ متجر. */
    val avatarMd: Dp = 56.dp,
    /** **صورةٌ كبيرة** — رأسُ صفحة المتجر وصاحبه (`AvatarWithEdit`). */
    val avatarLg: Dp = 72.dp,
    /** **أقلُّ ارتفاعٍ لمربّع وظيفة** (`IconTile`) — فتتساوى المربّعاتُ في صفّها. */
    val tileMin: Dp = 88.dp,
    /** **نقطةُ الحال** (`StatusDot`). */
    val dot: Dp = 8.dp,
    /** **دائرةُ العدد** (`CountBadge`). */
    val count: Dp = 18.dp,
    /** **دائرةُ أيقونة الحالة الفارغة** (`StateMessage`). */
    val stateCircle: Dp = 72.dp,
    /** **الصورةُ المصغّرة في سطر** — صنفٌ في سلّة، طلبٌ في قائمة. */
    val thumb: Dp = 56.dp,
)

/** **ثوابتُ الشكل** — لا تتبدّل بالسمة، فلا تحتاج `CompositionLocal`. */
val RahalShapeTokens = RahalShapes()
val RahalElevationTokens = RahalElevation()
val RahalIconSizeTokens = RahalIconSize()
val RahalSizeTokens = RahalSize()
val RahalSpaceTokens = RahalSpace()
val RahalStrokeTokens = RahalStroke()
