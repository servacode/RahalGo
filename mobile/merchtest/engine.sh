#!/usr/bin/env bash
# ══════════════════════════════════════════════════════════════════════
# **اختبارُ تطبيق المتجر · المرحلةُ الأولى — المحرّك**
# ══════════════════════════════════════════════════════════════════════
#
# **ومصدرُها العقدُ في `docs/تطبيق-المتجر.md`** — كلُّ فحصٍ بندٌ مرقَّمٌ
# يُطبع رقمُه مع نتيجته، **فمن قرأ سطراً في المخرَج وجد بندَه بلا بحث.**
#
# **ولا يُفحص ما لم نتّفق أنّه صواب** — ولا يبقى بندٌ بلا فحصٍ إلّا
# معلَّماً `؟`.
#
# # وما يميّز المتجرَ عن المندوب
#
# **الطلباتُ حالةٌ تتحرّك** — ولا تُنشأ إلّا من تطبيق الزبون. **فبنودُ
# الطلب تبقى `؟` حتّى يوجد طلبٌ حقيقيّ**، ولا تُدّعى.

set -u
A="${API:-https://api.rahalgo.com/api/v1}"
PHONE="${MERCH_PHONE:-}"
PASS="${MERCH_PASS:-}"

OKN=0; NON=0; SKN=0; FAILED=""
ok(){ OKN=$((OKN+1)); printf '  \033[32m✔\033[0m %-8s %s\n' "$1" "$2"; }
no(){ NON=$((NON+1)); FAILED="$FAILED\n  $1  $2 — $3"
      printf '  \033[31m✗\033[0m %-8s %s\n      \033[31m%s\033[0m\n' "$1" "$2" "$3"; }
sk(){ SKN=$((SKN+1)); printf '  \033[33m؟\033[0m %-8s %s — %s\n' "$1" "$2" "$3"; }
hdr(){ printf '\n\033[1m%s\033[0m\n' "$1"; }

code(){ curl -s -o /tmp/mt.json -w '%{http_code}' --max-time 30 "$@"; }
errc(){ grep -oP '"code":"\K[^"]+' /tmp/mt.json 2>/dev/null | head -1; }

TOKEN=""; STORE=""

# ══════════════════════════════════════════════════════════════════════
# **أ · الأبوابُ مقفلةٌ بلا توكن**
# ══════════════════════════════════════════════════════════════════════
stage_anon(){
  hdr "أ · الأبوابُ بلا توكن"
  local p
  for p in stores warnings my-reports report-reasons platform-sections; do
    local c; c=$(code "$A/merchant/$p")
    [ "$c" = 401 ] && ok "أ-٤" "/merchant/$p يردّ ٤٠١" \
                   || no "أ-٤" "/merchant/$p" "مفتوحٌ بلا توكن — ردّ $c"
  done
}

# ══════════════════════════════════════════════════════════════════════
# **ب · الدخولُ ومتجره**
# ══════════════════════════════════════════════════════════════════════
stage_login(){
  hdr "ب · الدخولُ ومتجره"
  local c
  c=$(code -X POST "$A/auth/login" -H 'Content-Type: application/json' \
        -H 'X-RahalGo-Client: merchtest' \
        -d "{\"phone\":\"$PHONE\",\"password\":\"$PASS\"}")
  [ "$c" != 200 ] && { no "أ-٥" "الدخول" "ردّ $c"; return 1; }
  TOKEN=$(grep -oP '"access_token":"\K[^"]+' /tmp/mt.json)
  ok "أ-٥" "الدخولُ بكلمة المرور"

  [ "$(code -X POST "$A/auth/login" -H 'Content-Type: application/json' \
        -H 'X-RahalGo-Client: merchtest' \
        -d "{\"phone\":\"$PHONE\",\"password\":\"XXwrong99XX\"}")" = 401 ] \
    && ok "أ-٥" "كلمةٌ خاطئةٌ تُردّ" || no "أ-٥" "كلمةٌ خاطئة" "قُبلت"

  local h="Authorization: Bearer $TOKEN"

  # **ومتجرُه** — ومن لا متجرَ له لا يُفحص شيءٌ بعده.
  if [ "$(code "$A/merchant/stores" -H "$h")" = 200 ]; then
    STORE=$(grep -oP '"id":"\K[^"]+' /tmp/mt.json | head -1)
    [ -n "$STORE" ] && ok "ج-١" "متجرُه يُقرأ" \
                    || no "أ-٥" "متجرُه" "**الحسابُ بلا متجر** — طلبُه لم يُوافَق عليه؟"
  else
    no "ج-١" "قائمةُ متاجره" "لم تُقرأ"
  fi
}

# ══════════════════════════════════════════════════════════════════════
# **ج · شاشاتُ القراءة**
# ══════════════════════════════════════════════════════════════════════
stage_read(){
  hdr "ج · شاشاتُ القراءة"
  local h="Authorization: Bearer $TOKEN" row ep id name
  for row in "warnings|ز-١١|الإنذارات" \
             "my-reports|هـ-٢|بلاغاتي" \
             "report-reasons|ز-١٠|أسبابُ البلاغ" \
             "platform-sections|ج-٥|أقسامُ السوق"; do
    ep=${row%%|*}; id=$(echo "$row"|cut -d'|' -f2); name=$(echo "$row"|cut -d'|' -f3)
    [ "$(code "$A/merchant/$ep" -H "$h")" = 200 ] \
      && ok "$id" "$name تُقرأ" || no "$id" "$name" "لم تُقرأ"
  done

  # **وأسبابُ البلاغ أربعةٌ يردّها المحرّك** — والشاشةُ لا تكتبها.
  code "$A/merchant/report-reasons" -H "$h" >/dev/null
  # **وهي نصوصٌ لا كائنات** — `{"reasons":["driver_late_pickup",...]}`.
  # **وعددتُ `"code"` أوّلَ مرّةٍ فخرج صفراً**، وحسبتُها عيباً.
  local n; n=$(grep -oP '"reasons":\[\K[^]]*' /tmp/mt.json | tr ',' '
' | grep -c '"')
  [ "$n" -ge 4 ] && ok "ز-١٠" "أسبابُ البلاغ $n" \
                 || no "ز-١٠" "أسبابُ البلاغ" "عددُها $n — والمتوقّع ٤"

  [ -z "$STORE" ] && return 0
  for row in "reports|ز-١٢|تقاريرُ المتجر" "reports-against|ز-٧|شكاوى عليّ" "menu|د-١|قائمتُه"; do
    ep=${row%%|*}; id=$(echo "$row"|cut -d'|' -f2); name=$(echo "$row"|cut -d'|' -f3)
    [ "$(code "$A/merchant/stores/$STORE/$ep" -H "$h")" = 200 ] \
      && ok "$id" "$name تُقرأ" || no "$id" "$name" "لم تُقرأ"
  done
}

# ══════════════════════════════════════════════════════════════════════
# **د · الحارس — متجرُ غيره**
# ══════════════════════════════════════════════════════════════════════
#
# **والمعرّفاتُ تُخمَّن** — فلا يكفي أن تُخفى الأزرارُ في الشاشة.
stage_guard(){
  hdr "د · حارسُ الملكيّة"
  local h="Authorization: Bearer $TOKEN"
  local Z=00000000-0000-0000-0000-000000000000
  local row ep name c
  for row in "menu|قائمةُ متجرٍ ليس له" "reports|تقاريرُ متجرٍ ليس له" \
             "reports-against|شكاوى متجرٍ ليس له"; do
    ep=${row%%|*}; name=${row##*|}
    c=$(code "$A/merchant/stores/$Z/$ep" -H "$h")
    [ "$c" = 403 ] || [ "$c" = 404 ] \
      && ok "و-٤" "$name يُردّ ($c)" \
      || no "و-٤" "$name" "مرّ — ردّ $c"
  done

  c=$(code -X PATCH "$A/merchant/menu/items/$Z" -H "$h" \
        -H 'Content-Type: application/json' -d '{"price":9}')
  [ "$c" = 403 ] || [ "$c" = 404 ] \
    && ok "و-٤" "تعديلُ صنفٍ ليس له يُردّ ($c)" \
    || no "و-٤" "تعديلُ صنفِ غيره" "**مرّ — ويبدّل أسعارَ سوقٍ لا يعرفه صاحبُه**"
}

# ══════════════════════════════════════════════════════════════════════
# **هـ · الأصنافُ — الفروعُ السالبة**
# ══════════════════════════════════════════════════════════════════════
#
# **ولا يُنشأ صنفٌ ناجحٌ هنا** — يكتب في سوقٍ حقيقيّ. الموجبُ على الزجاج.
stage_menu(){
  [ -z "$STORE" ] && return 0
  hdr "هـ · الأصنافُ — الفروعُ السالبة"
  local h="Authorization: Bearer $TOKEN"
  post(){ code -X POST "$A/merchant/stores/$STORE/menu/items" -H "$h" \
            -H 'Content-Type: application/json' -d "$1"; }

  local sec c
  code "$A/merchant/platform-sections" -H "$h" >/dev/null
  sec=$(grep -oP '"id":"\K[^"]+' /tmp/mt.json | head -1)

  c=$(post "{\"name\":\"\",\"price\":100,\"platform_section_id\":\"$sec\"}")
  [ "$c" = 400 ] && ok "د-٤" "اسمٌ فارغٌ يُردّ" || no "د-٤" "اسمٌ فارغ" "ردّ $c"

  c=$(post "{\"name\":\"QA\",\"price\":100,\"platform_section_id\":\"$Z\"}")
  [ "${c:-0}" -ge 400 ] 2>/dev/null && ok "د-٦" "قسمٌ مخترَعٌ يُردّ ($c)" \
                                   || no "د-٦" "قسمٌ مخترَع" "ردّ $c"
}

# ══════════════════════════════════════════════════════════════════════
# **و · ما لا يُفحص بلا طلبٍ حقيقيّ**
# ══════════════════════════════════════════════════════════════════════
stage_human(){
  hdr "و · ما يحتاج طلباً حقيقيّاً"
  sk "ب-٤" "«استلمت الطلب» ينقل إلى التحضير آليّاً" "لا طلبَ يُنشأ إلّا من الزبون"
  sk "ب-٥" "«رفض» يطلب سبباً" "كذلك"
  sk "ب-٦" "«جاهز» ينزل الطلبَ للسائقين" "كذلك"
  sk "ب-٧" "«لك %s» مستحقُّه لا قيمةُ الطلب" "كذلك"
  sk "ب-٩" "إشعارُ طلبٍ جديدٍ يوقظ" "بشريّ"
  sk "ز-٤" "إحدى عشرةَ حالةً لرحلة الطلب" "تحتاج طلباً يمشي"
  sk "هـ-٢" "البلاغُ بعد الانتهاء لا في أثنائه" "يحتاج طلباً مُغلقاً"
  sk "و-٢" "مستحقُّه يُقيَّد عند التسليم" "يحتاج تسليماً"
}

main(){
  [ -z "$PHONE" ] && { echo "MERCH_PHONE و MERCH_PASS مطلوبان"; exit 2; }
  printf '\033[1m══ اختبارُ تطبيق المتجر · المرحلةُ الأولى: المحرّك ══\033[0m\n   %s\n' "$A"
  Z=00000000-0000-0000-0000-000000000000
  stage_anon
  stage_login || true
  [ -n "$TOKEN" ] && { stage_read; stage_guard; stage_menu; }
  stage_human
  printf '\n\033[1m══ الحصيلة ══\033[0m\n  نجح %d · سقط %d · بشريّ %d\n' "$OKN" "$NON" "$SKN"
  [ "$NON" -gt 0 ] && printf '\n\033[31mالساقط:\033[0m%b\n' "$FAILED"
  [ "$NON" -eq 0 ]
}
main "$@"
