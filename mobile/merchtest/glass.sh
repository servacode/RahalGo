#!/usr/bin/env bash
# ══════════════════════════════════════════════════════════════════════
# **اختبارُ تطبيق المتجر · المرحلةُ الثانية — الزجاج**
# ══════════════════════════════════════════════════════════════════════
#
# **والمحرّكُ يقول إنّ الجوابَ صحيح — والزجاجُ يقول إنّ صاحبَ المتجر
# رآه.** وبينهما وقعت كلُّ عيوبِ المندوب: نصٌّ لا يُعرض، وزرٌّ لا يظهر،
# **وحقولٌ تُمسح حين يعود من الخريطة.**
#
# **ولا نقرةَ عمياء** — كلُّ ضغطةٍ من حدودِ عنصرٍ عُثر عليه بنصّه أو
# بوصفه، **فمن نقر بإحداثيّةٍ محفوظةٍ نقر شاشةً تبدّلت.**
#
# # وثلاثُ قواعدَ تعلّمناها في أوّل تشغيل
#
# **١ · لا مفتاحَ رجوعٍ في الشاشة الجذر** — أخرجني من التطبيق إلى
# تطبيقٍ آخرَ على جهاز المالك، **ثمّ نقرتُ فيه.** فالرجوعُ يكون
# بتبويبٍ سفليٍّ لا بمفتاح النظام.
#
# **٢ · أزرارُ الشريط العلويّ بلا نصّ** — «القائمة» و«الإشعارات»
# و«محفظتك» أوصافٌ لا نصوص.
#
# **٣ · وشرحُ الإغلاق الطارئ لا يُعرض حتّى يُضغط الزرّ** — وهي خطوةُ
# تأكيدٍ صحيحة. **وحسبتُها عيباً قبل أن أقرأ الشيفرة.**

set -u
cd "$(dirname "$0")"
. ../reptest/lib.sh
P=com.rahalgo.merchant

# cd_ **مركزُ عنصرٍ بوصفه** — للأزرار التي لا نصَّ فيها.
cd_(){ local B X1 Y1 X2 Y2
  B=$(grep -F "content-desc=\"$1\"" /tmp/u.xml | grep -oP 'bounds="\[[0-9,]+\]\[[0-9,]+\]' | head -1)
  [ -z "$B" ] && return 1
  X1=$(echo "$B"|grep -oP '\[\K[0-9]+'|sed -n 1p); Y1=$(echo "$B"|grep -oP ',\K[0-9]+'|sed -n 1p)
  X2=$(echo "$B"|grep -oP '\[\K[0-9]+'|sed -n 2p); Y2=$(echo "$B"|grep -oP ',\K[0-9]+'|sed -n 2p)
  echo "$(( (X1+X2)/2 )) $(( (Y1+Y2)/2 ))"; }
tc(){ local Q; Q=$(cd_ "$1") || return 1; a shell input tap $Q; sleep "${2:-3}"; d; }

boot(){ a shell am force-stop $P; a shell am start -n $P/.MainActivity >/dev/null
        sleep 7; d; }
# tab **تبويبٌ سفليٌّ** — ويُلتقط الأدنى في الشاشة لا الأوّل.
#
# **وكلمةُ «الأصناف» تُكتب داخل بطاقة كلّ طلبٍ أيضاً** — فمن نقر أوّلَ
# مطابقةٍ نقر طلبَ زبونٍ حقيقيّ. (وقع في أوّل تشغيل.)
tab(){ local B Y
  B=$(grep -F "text=\"$1\"" /tmp/u.xml | grep -oP 'bounds="\[[0-9,]+\]\[[0-9,]+\]'       | awk -F'[][,]' '{print $6, $2, $3, $5}' | sort -n | tail -1)
  [ -z "$B" ] && return 1
  set -- $B
  a shell input tap $(( ($2+$4)/2 )) $(( ($3+$1)/2 )); sleep 4; d; }
# **والعودةُ بتبويبٍ سفليٍّ لا بمفتاح الرجوع** — القاعدةُ الأولى.
home(){ tab "الطلبات"; }

# ══════════════════════════════════════════════════════════════════════
# **أ · الإقلاعُ وما يُرى أوّلَ ثانية**
# ══════════════════════════════════════════════════════════════════════
stage_boot(){
  printf '\nأ · الإقلاع\n'
  boot
  has "لا متجر مرتبط بحسابك" && { no "أ-٥" "متجرُه" "**الحسابُ بلا متجر**"; return 1; }
  has "تسجيل الدخول" && { no "أ-٥" "الجلسة" "خرج — الجلسةُ انتهت أو أبطلها دخولٌ آخر"; return 1; }
  ok "أ-٥" "الجلسةُ المحفوظةُ تدخل مباشرةً"

  # **ب-١ · الطلباتُ أوّلُ ما يُرى** — ومن فتح تطبيقَه وطلبٌ ينتظر يجب
  # أن يراه بلا ضغطة.
  has "اقبل الطلب ثم حضّره" || has "لك " || has "بانتظار سائق" \
    && ok "ب-١" "الطلباتُ أوّلُ تبويبٍ يُفتح" \
    || no "ب-١" "أوّلُ تبويب" "ليس الطلبات — أوّلُ نصٍّ: $(T|head -1)"

  local s
  for s in الطلبات متجري "أضف صنفاً" الأصناف حسابي; do
    has "$s" && ok "ب-٣" "تبويبُ «$s» معروض" || no "ب-٣" "التبويبات" "لا «$s»"
  done
  for s in القائمة الإشعارات محفظتك; do
    cd_ "$s" >/dev/null && ok "هـ-١" "زرُّ «$s» في الشريط" || no "هـ-١" "الشريط" "لا زرَّ «$s»"
  done
}

# ══════════════════════════════════════════════════════════════════════
# **ب · الطلبُ الحيّ — قراءةٌ بلا ضغط**
# ══════════════════════════════════════════════════════════════════════
#
# **ولا يُضغط زرٌّ يقبل طلبَ زبونٍ حقيقيّ** — يُقرأ ولا يُمسّ.
stage_orders(){
  printf '\nب · الطلباتُ — قراءةٌ بلا ضغط\n'
  if has "لا طلبات الآن"; then
    ok "ب-٢" "«سنُعلمك حين يصل طلب» — وعدٌ لا فراغ"
    sk "ب-٤" "أزرارُ الطلب" "لا طلبَ الآن — ولا يُنشأ إلّا من الزبون"
    return
  fi
  has "استلمت الطلب" && ok "ب-٤" "«استلمت الطلب» معروض"
  has "رفض — غير متوفر" && ok "ب-٥" "«رفض — غير متوفر» معروض"
  has "جاهز للاستلام" && ok "ب-٦" "«جاهز للاستلام» معروض"
  has "لك " && ok "ب-٧" "«لك» — مستحقُّه لا قيمةُ الطلب" \
             || no "ب-٧" "مستحقُّه" "غيرُ مكتوب — فبأيّ رقمٍ يحاسب؟"
  local s n=0
  for s in "بانتظار سائق" "أُسند لسائق" "السائق عندك" "استلمه السائق" \
           "في الطريق" "وصل الزبون" "سُلّم" "اعتذرت عنه" "أُلغي" \
           "تعذّر تسليمه" "استُرجع"; do
    has "$s" && { ok "ز-٤" "حالُ الطلب: $s"; n=$((n+1)); }
  done
  [ "$n" -lt 11 ] && sk "ز-٤" "بقيّةُ الحالات ($n/١١ ظهرت)" "لا طلبَ فيها الآن"
  # **ز-٦ · وحالٌ مجهولةٌ لا تُعرض «بانتظار السائق» كذباً** — لا تُصنَع.
  sk "ز-٦" "حالٌ مجهولةٌ لا تكذب" "لا تُصنَع — تُقرأ في الشيفرة"
}

# ══════════════════════════════════════════════════════════════════════
# **ج · متجري — والإغلاقُ الطارئُ يُفتح ثمّ يُلغى**
# ══════════════════════════════════════════════════════════════════════
stage_store(){
  printf '\nج · متجري\n'
  tab "متجري"
  has "إغلاق طارئ" || { no "ج-١" "تبويبُ متجري" "لم يُفتح"; return; }

  has "مفتوح" || has "مغلق" && ok "ج-١" "مفتاحُ الدوام معروض"
  has "مستحق اليوم" && ok "ز-١٣" "**«مستحق اليوم» لا «مبيعات اليوم»**" \
                    || no "ز-١٣" "أرقامُ اليوم" "لا «مستحق اليوم»"
  has "مدة التحضير" && ok "ج-٣" "مدةُ التحضير معروضة"

  # **ز-١٥ · ساعاتُ الدوام** — وهي الشاشةُ التي كانت تُغلق التطبيق.
  has "ساعات العمل" && {
    ok "ج-٢" "ساعاتُ العمل معروضة"
    t "ساعات العمل" 4 >/dev/null
    a shell "pidof $P" | grep -q . \
      && ok "ز-١٥" "**ساعاتُ الدوام لا تُغلق التطبيق**" \
      || { no "ز-١٥" "ساعاتُ الدوام" "**التطبيقُ مات**"; return; }
    tab "متجري"; }

  # **ز-٣ · والشرحُ يظهر بعد الضغط** — ثمّ يُلغى ولا يُغلق متجرٌ حيّ.
  t "إغلاق طارئ" 3 >/dev/null && {
    has "يُقرأ فوراً من الإدارة، ولا يُحسب رفضاً عليك" \
      && ok "ز-٣" "**«لا يُحسب رفضاً عليك» — وهي كلُّ فكرته**" \
      || no "ز-٣" "شرحُ الإغلاق الطارئ" "**لا يظهر عند التأكيد**"
    t "إلغاء" 3 >/dev/null && ok "ز-٣" "«إلغاء» يتراجع — ولم يُغلق المتجر" \
                           || no "ز-٣" "التراجع" "**لا مخرجَ من نافذة الإغلاق**"; }

  up 2
  has "أقسام السوق" && ok "ج-٥" "أقسامُ السوق معروضة"
  has "لا قسم بعد — متجرك لا يظهر في السوق حتى تختار" \
    && ok "ز-١" "**«متجرك لا يظهر في السوق حتى تختار»**"
  has "أضفت كل الأقسام" && ok "ز-٢" "«أضفت كل الأقسام»"
  has "أضف قسماً" && ok "ج-٥" "«أضف قسماً» — تُختار ولا تُنشأ"

  has "العنوان" && ok "ج-٤" "العنوانُ معروض"
  has "موقع المتجر على الخريطة" && ok "ج-٤" "نقطةُ الخريطة معروضة"
  has "لم يُحدَّد بعد" && ok "ز-١٦" "**نقطةٌ لم تُحدَّد تُقال صراحةً**"
  home
}

# ══════════════════════════════════════════════════════════════════════
# **د · الأصناف**
# ══════════════════════════════════════════════════════════════════════
stage_menu(){
  printf '\nد · الأصناف\n'
  tab "الأصناف"
  has "أصنافي" || has "لا أصناف بعد" || { no "د-١" "شاشةُ الأصناف" "لم تُفتح"; return; }
  ok "د-١" "شاشةُ الأصناف تُفتح"
  has "لا أصناف بعد — تُضاف من لوحة الإدارة أو من مندوبك" \
    && ok "ز-١٨" "**فراغُ الأصناف يقول من يملؤه**"
  has "اضغط الصنف" && ok "ز-١٧" "«اضغط الصنف لتبدّل توفره»"

  # **د-٣ · ولا يُقال «غير متوفر» بلفظٍ آخر** — وحّدها المالك.
  local s
  for s in "غير موجود" "منتهي" "نافد"; do
    has "$s" && no "د-٣" "لفظُ التوفّر" "«$s» — والمتّفق «غير متوفر»"
  done

  tab "أضف صنفاً"
  has "اختر أقسام متجرك أولاً" \
    && ok "ز-١" "**من لا قسمَ له يُمنع من إضافة صنفٍ ويُقال له لماذا**"
  has "السعر" && ok "د-٢" "«السعر» عامّاً"
  has "سعر المتجر" && no "د-٢" "لفظُ السعر" "«سعر المتجر» — والمتّفق «السعر»"
  home
}

# ══════════════════════════════════════════════════════════════════════
# **هـ · القائمةُ والشكاوى والتقارير**
# ══════════════════════════════════════════════════════════════════════
stage_drawer(){
  printf '\nهـ · القائمةُ والشكاوى\n'
  tc "القائمة" 4 || { no "هـ-١" "القائمة" "لم تُفتح"; return; }
  local s
  for s in "الإنذارات" "الشكاوي والبلاغات" "التقارير"; do
    has "$s" && ok "هـ-١" "القائمةُ فيها «$s»" || no "هـ-١" "القائمة" "لا «$s»"
  done

  t "الشكاوي والبلاغات" 5 >/dev/null && {
    # **ز-٧ · تبويبان لا قائمة** — والخلطُ يجعله يقرأ شكوى عليه شكواه.
    has "شكاوى عليّ" && has "شكاوى رفعتها" \
      && ok "ز-٧" "**تبويبان: «شكاوى عليّ» و«شكاوى رفعتها»**" \
      || no "ز-٧" "الشكاوى" "**ليسا تبويبين — والخلطُ يقلب المعنى**"
    t "شكاوى عليّ" 4 >/dev/null
    has "لا شكاوى على متجرك — أحسنت" && ok "ز-٨" "**الفراغُ يُمدح لا يُترك صامتاً**"
    home; }

  tc "القائمة" 4 && t "الإنذارات" 5 >/dev/null && {
    ok "ز-١١" "شاشةُ الإنذارات تُفتح"
    has "لا إنذارات عليك" && ok "ز-١١" "«لا إنذارات عليك»"
    home; }

  tc "القائمة" 4 && t "التقارير" 5 >/dev/null && {
    has "٧ أيّام" && has "٣٠ يوماً" && ok "ز-١٢" "التقاريرُ بمدىً متعدّد" \
      || no "ز-١٢" "مدى التقارير" "ليست ثلاثة"
    has "طباعة التقرير" && ok "ز-١٢" "زرُّ الطباعة موجود" \
                        || no "ز-١٢" "الطباعة" "لا زرّ"
    home; }
}

# ══════════════════════════════════════════════════════════════════════
# **و · الأزرارُ المكرَّرةُ والانهيار**
# ══════════════════════════════════════════════════════════════════════
#
# **والضغطُ المزدوجُ هو ما كسر تطبيقَ المندوب** — يُجرَّب هنا قبل أن
# يجرّبه صاحبُ المتجر بطلبٍ حقيقيّ.
stage_stress(){
  printf '\nو · الضغطُ المكرَّرُ والتنقّلُ السريع\n'
  local i
  for i in 1 2 3; do tf "متجري"; tf "الأصناف"; tf "حسابي"; tf "الطلبات"; done
  sleep 4
  a shell "pidof $P" | grep -q . \
    && ok "و-٦" "تنقّلٌ سريعٌ ١٢ مرّةً — والتطبيقُ حيّ" \
    || { no "و-٦" "التنقّلُ السريع" "**التطبيقُ مات**"; return; }

  d; tc "القائمة" 2 >/dev/null; tf "القائمة"; sleep 3; d
  a shell "pidof $P" | grep -q . \
    && ok "و-٦" "القائمةُ بلا انهيار" || no "و-٦" "القائمة" "**انهارت**"
  home
}

main(){
  [ -z "${S:-}" ] && { echo "لا جهاز"; exit 2; }
  printf '══ اختبارُ تطبيق المتجر · المرحلةُ الثانية: الزجاج ══\n  %s\n' "$S"
  stage_boot || { printf '\nنجح %d · سقط %d\n' "$OKN" "$NON"; exit 1; }
  stage_orders; stage_store; stage_menu; stage_drawer; stage_stress
  printf '\n══ الحصيلة ══\n  نجح %d · سقط %d\n' "$OKN" "$NON"
  [ "$NON" -eq 0 ]
}
main "$@"
