package com.rahalgo.navigation

import kotlin.math.abs
import kotlin.math.roundToLong

/**
 * ══════════════════════════════════════════════════════════════════════
 * **بصمةُ المسار — أهو الطريقُ نفسُه؟**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (المرحلة ٣ب، أمرُ المالك ٢٠٢٦-٠٨-٢٠، البند ١٤.)
 *
 * # ولماذا لا يكفي الطولُ وعددُ الرؤوس
 *
 * (أمرُ المالك: «هذه مقارنةٌ ضعيفة… حتّى لا نرفض Route مختلفاً لأنّه
 *  صادف أن له نفسَ الطول وعددَ الرؤوس تقريباً».)
 *
 * **وشارعان متوازيان في الرقّة يتشابهان طولاً وعدداً** — ومسارٌ يذهب
 * شرقاً وآخرُ غرباً بالطول نفسِه **متطابقان في تلك المقارنة**، وهما
 * طريقان مختلفان تماماً.
 *
 * # والبصمةُ من الهندسة المكمَّمة
 *
 *     كلُّ رأسٍ  →  يُقرَّب إلى نحو مترٍ  →  يدخل خلطاً متتابعا
 *
 * **والتقريبُ يمنع أن تختلف البصمةُ لفرقِ سنتيمترٍ في ترميزٍ عائم** —
 * **والتتابعُ يجعل الترتيبَ جزءاً منها**، فمسارٌ معكوسٌ بصمتُه غيرُ
 * بصمة الأصل.
 *
 * # وليست حمايةً تعمويّة
 *
 * (أمرُ المالك: «الهدفُ ليس Cryptographic Security».)
 *
 * **الهدفُ سؤالٌ واحد: أعاد الخادمُ الطريقَ نفسَه تقريباً؟** — ولا
 * يُبنى على جوابه قرارُ رفضٍ وحدَه: انظر `RerouteEngine` والبند ١٥.
 */
object RouteFingerprint {

    /** **درجةُ التكميم** — نحو مترٍ عند خطوط عرضنا. */
    const val QUANTUM = 100_000.0

    /** **بصمةٌ ثابتةٌ لهندسة مسار.** */
    fun of(route: NavRoute): Long {
        var h = 1125899906842597L // بذرةٌ فردية
        for (p in route.geometry) {
            h = 31 * h + (p.lat * QUANTUM).roundToLong()
            h = 31 * h + (p.lng * QUANTUM).roundToLong()
        }
        // **والطولُ يدخلها أيضاً** — رأسان متطابقان بمسافتين مختلفتين
        // **مساران مختلفان.**
        h = 31 * h + (route.totalM).roundToLong()
        return h
    }

    /** **أهما الطريقُ نفسُه بالبصمة؟** */
    fun same(a: NavRoute, b: NavRoute): Boolean = of(a) == of(b)

    /**
     * ══════════════════════════════════════════════════════════════════
     * **ونسبةُ التشابه حين لا تتطابق البصمتان**
     * ══════════════════════════════════════════════════════════════════
     *
     * **البصمةُ تقول «هو هو» أو «ليس هو» ولا تقول «يكاد»** — ومسارٌ
     * أُعيد حسابُه من موضعٍ يبعد عشرةَ أمتارٍ **بصمتُه مختلفةٌ وطريقُه
     * واحد.**
     *
     * **فتُقاس نسبةُ رؤوس الجديد التي تقع قربَ رأسٍ في القديم** —
     * حسابٌ بسيطٌ يكفي للسؤال المطروح.
     */
    fun similarity(a: NavRoute, b: NavRoute, withinM: Double = 15.0): Double {
        if (a.geometry.isEmpty() || b.geometry.isEmpty()) return 0.0
        var near = 0
        for (p in b.geometry) {
            val hit = a.geometry.any {
                abs(it.lat - p.lat) < 0.0005 && abs(it.lng - p.lng) < 0.0006 &&
                    GpsQuality.metersBetween(it.lat, it.lng, p.lat, p.lng) <= withinM
            }
            if (hit) near++
        }
        return near.toDouble() / b.geometry.size
    }
}
