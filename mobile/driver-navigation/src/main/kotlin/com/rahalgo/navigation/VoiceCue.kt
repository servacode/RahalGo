package com.rahalgo.navigation

/**
 * ══════════════════════════════════════════════════════════════════════
 * **ما يجب أن يُقال — بياناتٌ لا نصّ**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (المرحلة ٤، أمرُ المالك ٢٠٢٦-٠٨-٢٠.)
 *
 * # والنصُّ ليس الهُويّة
 *
 * (أمرُ المالك نصّاً: «`text` ليس هو Identity».)
 *
 * **جملتان متطابقتان لمناورتين مختلفتين شيئان** — «انعطف يميناً» عند
 * الكيلومتر الأوّل غيرُها عند الثالث. **ومن ميّز بالنصّ خرس عند
 * المنعطف الثاني.**
 *
 * **والهُويّةُ ثلاثيّة**: جيلُ المسار · موضعُ المناورة بالمتر · الطور.
 *
 * **و`atDistanceM` لا `atIndex`** — قرارُ المرحلة الثانية: الفهرسُ
 * يتبدّل إن بُسِّطت الهندسةُ يوماً، **والمسافةُ على الطريق لا تتبدّل.**
 */
data class VoiceCue(
    val id: CueId,
    val kind: CueKind,
    val stage: CueStage,
    /** **المناورةُ المقصودة** — وفارغةٌ في إعادة الحساب والوصول. */
    val maneuver: NavManeuver? = null,
    /** **المسافةُ كما تُنطق** — مقرَّبةً، وفارغةٌ في `NOW`. */
    val roundedDistanceM: Int? = null,
    val priority: Int,
    /**
     * **حتّى أيّ تقدّمٍ تبقى صالحة.**
     *
     * (أمرُ المالك، البند ٢٢: «قبل كلّ `speak()` تحقّق أنّ Cue ما زالت
     *  صالحة».)
     *
     * **وتُفحص عند التسليم لا عند التوليد** — **وبينهما قد ينعطف
     * السائقُ وينتهي**، فتُقال له تعليمةٌ عن منعطفٍ خلفَه.
     */
    val validUntilProgressM: Double,
    /** **بُعدُ المناورة لحظةَ الإطلاق** — للقياس لا للمنطق. */
    val firedAtM: Double = -1.0,
    /** **والسرعةُ المستعملةُ في الحساب** — كذلك. */
    val firedSpeedMps: Double = -1.0,
    val text: String,
)

/**
 * **هُويّةُ التعليمة.**
 *
 * **والجيلُ أوّلُها** — فمسارٌ جديدٌ يعطي هُويّاتٍ جديدةً كلَّها،
 * **ولا يرث شيئاً ممّا قيل على مسارٍ تُرك.**
 */
data class CueId(
    val generation: Long,
    val maneuverAtM: Double,
    val stage: CueStage,
)

/** **نوعُ ما يُقال.** */
enum class CueKind {
    /** **مناورةٌ على الطريق.** */
    MANEUVER,

    /** **إعادةُ حساب** — بدأت أو أخفقت. */
    REROUTE,

    /** **وصولٌ إلى طرفٍ من طرفَي الرحلة.** */
    ARRIVE,

    /** **يسير بعكس اتّجاه المسار** — المرحلة ٥. */
    WRONG_WAY,

    /**
     * **انتهى الخطُّ ولمّا يُبلَغ الهدف** — آخرُ ميل، ٢٠٢٦-٠٨-٢١.
     *
     * **ولا يدّعي وصولاً** — تلك [ARRIVE] وحدَها.
     */
    ROUTE_END,
}

/**
 * ══════════════════════════════════════════════════════════════════════
 * **ثلاثةُ أطوارٍ لا واحد**
 * ══════════════════════════════════════════════════════════════════════
 *
 *     PREPARE   بعد خمسِ مئةِ متر…      — ليعرف أنّ شيئاً قادم
 *     APPROACH  بعد مئةٍ وخمسين…        — ليستعدّ ويغيّر المسرب
 *     NOW       الآن                    — ليفعل
 *
 * **والواحدُ لا يكفي**: من سمع «انعطف يميناً» عند المنعطف بلا تمهيدٍ
 * **لا يستطيع أن يغيّر مسربه**، ومن سمعها قبل كيلومترٍ نسيها.
 */
enum class CueStage {
    PREPARE,
    APPROACH,
    NOW,

    /** **لا طورَ لها** — إعادةُ الحساب والوصول. */
    EVENT,
}

/**
 * **طرفُ الرحلة كما تعرفه الملاحة.**
 *
 * (أمرُ المالك، البند ٢٥: «لا تجعل `VoicePlanner` تعرف Order أو Status
 *  الخام».)
 *
 * **فكلمتان لا حالُ طلب** — والتطبيقُ يترجم `TripStep` إليهما.
 */
enum class TripTarget {
    PICKUP,
    DROPOFF,
}

/**
 * ══════════════════════════════════════════════════════════════════════
 * **بابُ الكلام — ولا يعرف من خلفه**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (أمرُ المالك، البند ٣: «لا أريد Android side effects داخل محرّك
 *  الملاحة».)
 *
 * **دالّتان**: قُل · اسكت. **ولا `TextToSpeech` ولا `AudioManager` في
 * هذه الوحدة** — وما ينفّذها يعيش في تطبيق السائق.
 */
interface Speaker {

    /** **أثمّةَ صوتٌ صالحٌ أصلاً؟** — وكاذبٌ يعني «الملاحةُ صامتة». */
    val available: Boolean

    /**
     * **يقول جملةً** — ويردّ حين تنتهي أو تتعذّر.
     *
     * `id` يُعاد كما هو ليُعرف ما انتهى.
     */
    fun speak(id: String, text: String, flush: Boolean, done: (Boolean) -> Unit)

    /** **يقطع ما يُقال ويُفرغ ما ينتظر.** */
    fun stop()
}
