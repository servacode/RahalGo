package com.rahalgo.navigation

/**
 * ══════════════════════════════════════════════════════════════════
 * **ألوانُ خطوط المسار — موضعٌ واحد**
 * ══════════════════════════════════════════════════════════════════
 *
 * (إغلاقُ واجهة ٧، قرارُ المالك ٢٠٢٦-٠٨-٢١، البندان ١٤ و٤٨.)
 *
 * **أمرُ المالك نصّاً**: «لا تنشر Hex values جديدة في عدة ملفات…
 * اجعل Route visualization palette مركزية».
 *
 * **وكانت متفرّقةً**: `#02678F` و`#1E88E5` في `TripMarkers`،
 * و`#8A94A6` في `AltRouteLayer`. **فمن بدّل لوناً بدّل نصفَه.**
 *
 * # **وثلاثةُ أدوارٍ لا لونان**
 *
 * **الفعّالُ** — ما يُلاحَ عليه الآن. **والبديلُ** — معروضٌ ولم
 * يُختر. **والمعايَنُ** — بديلٌ يُنظر فيه ولم يُعتمد بعد.
 *
 * **والمعايَنُ لا يأخذ لونَ الفعّال** (البند ١٤): «لا تستخدم لونًا
 * يوحي أن Preview أصبحت Route الفعالة». **فالسائقُ لم يعتمده، ولو
 * لبس لونَه لظنّ أنّ الملاحةَ تبدّلت** وهي لم تتبدّل.
 *
 * **والفعّالُ يبقى واضحاً أثناء المعاينة** — فهو الذي يقوده الآن.
 */
object MapRoutePalette {

    /** **المسارُ الفعّال** — أزرقُ رحّال غو. */
    const val ACTIVE = "#1E88E5"

    /** **وهالتُه** — تحتَه، فيُرى على خريطةٍ فاتحة. */
    const val ACTIVE_GLOW = "#02678F"

    /** **بديلٌ معروضٌ ولم يُختر** — رماديٌّ محايد. */
    const val ALTERNATIVE = "#8A94A6"

    /**
     * **بديلٌ قيدَ المعاينة** — كهرمانيٌّ منبِّه.
     *
     * **مختلفٌ عن الأزرق في اللون والقيمة معاً** — فلا يلتبس بالفعّال
     * ولو رآه طرفُ العين، **ولا يعتمد على تمييز اللون وحدَه**: عرضُه
     * أكبرُ وشفافيّتُه أقلّ (البند ٢٩).
     */
    const val PREVIEW = "#F5A524"

    // ══════════════════════════════════════════════════════════════
    // **ودبابيسُ الرحلة** — من الموضع نفسِه
    // ══════════════════════════════════════════════════════════════
    //
    // **كانت في `TripMarkers` وحدَها** — والخطُّ في مكانٍ والدبّوسُ في
    // آخر. **فمن بدّل هويّةَ اللون بدّل نصفَها.**

    /** **دبّوسُ السائق** — لونُ المسار الفعّال، فهو عليه. */
    const val DRIVER_PIN = ACTIVE

    /** **ودبّوسُ المتجر** — برتقاليُّ رحّال غو. */
    const val PICKUP_PIN = "#FE9501"

    /** **ودبّوسُ الزبون** — أزرقُ الهالة، فيُميَّز عن المتجر. */
    const val DROPOFF_PIN = ACTIVE_GLOW

    // ══════════════════════════════════════════════════════════════
    // **والأعراضُ تُميّز أيضاً — لا اللونُ وحدَه**
    // ══════════════════════════════════════════════════════════════
    //
    // (البند ٢٩: «لا تعتمد على اللون وحده لمعرفة المسار المختار أو
    //  المعاين».)

    const val ACTIVE_WIDTH = 7f
    const val ALTERNATIVE_WIDTH = 5f
    const val PREVIEW_WIDTH = 7f

    const val ALTERNATIVE_OPACITY = 0.55f
    const val PREVIEW_OPACITY = 0.95f
}
