package com.rahalgo.navigation

/**
 * ══════════════════════════════════════════════════════════════════════
 * **التنعيم — استيفاءٌ بين قراءتين لا ترشيحٌ للقراءة**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (أمرُ المالك ٢٠٢٦-٠٨-٢٠: «لا أريد Driver Marker يقفز… وثّق
 *  الخوارزمية التي اخترتها ولماذا»، **و«Smoothing لا يجوز أن يجعل
 *  السائق متأخّراً بوضوح عن موقعه الحقيقيّ»**.)
 *
 * ══════════════════════════════════════════════════════════════════════
 * # الخوارزميّةُ المختارة ولماذا
 * ══════════════════════════════════════════════════════════════════════
 *
 * **المختار: استيفاءٌ خطّيٌّ زمنيٌّ بين آخرِ موضعٍ معروضٍ والقراءةِ
 * الجديدة، مدّتُه مقيَّدةٌ بسقف.**
 *
 * ## وما رُفض ولماذا
 *
 * **١ · مُرشِّح كالمان.** أدقُّ ما في الباب نظريّاً، **وثمنُه أنّه
 * يحتاج نموذجَ حركةٍ وضبطَ تباينات** — ومن ضبطها خطأً حصل على تأخّرٍ
 * ثابتٍ لا يراه في الاختبار ويراه السائق. **وأمرُ المالك صريح: «لا
 * تطبّق خوارزميّةً ثقيلةً أو معقّدةً لمجرّد التعقيد».**
 *
 * **٢ · متوسّطٌ متحرّكٌ أُسّيّ على الموضع.** سطران، **وعيبُه قاتلٌ
 * هنا**: يُنتج **تأخّراً دائماً**. الدرّاجةُ تسير والنقطةُ خلفها أبداً
 * بمقدارٍ يتناسب مع السرعة، **فيرى السائقُ نفسَه قبل المنعطف وهو
 * فيه.** وهذا عينُ ما نهى عنه المالك.
 *
 * **٣ · الاستيفاء** — **لا يُرشِّح الموضعَ أصلاً**: القراءةُ تُصدَّق
 * كما جاءت، **والعرضُ وحدَه يتحرّك إليها بسلاسة.**
 *
 *     التأخّرُ الأقصى = مدّةُ الحركة، وتنتهي عند وصولها.
 *     ولا يتراكم: كلُّ قراءةٍ تبدأ من حيث انتهى العرض.
 *
 * ## وحدُّ التأخّر مقيَّدٌ بسقف
 *
 * **ومدّةُ الحركة هي الفاصلُ المتوقَّع بين قراءتين** — فتصل النقطةُ
 * إلى هدفها في اللحظة التي تصل فيها القراءةُ التالية، **فلا فجوة ولا
 * وقوف.**
 *
 * **وتُقيَّد بسقفٍ** (`MAX_ANIM_MS`): **قراءةٌ تأخّرت خمسَ ثوانٍ لا
 * تُمشي النقطةَ خمسَ ثوانٍ** — يصير التأخّرُ محسوساً. فتُقطع المسافةُ
 * في سقفٍ ثمّ تقف حتّى تأتي التالية.
 *
 * ## والقراءةُ المتدهورةُ تُبطئ ولا تُقفز
 *
 * **دقّةٌ سيّئةٌ تعني موضعاً مشكوكاً فيه** — فتُمدّ مدّةُ الحركة قليلاً
 * (لا يُرفض الموضع): **الشكُّ يُترجَم بطئاً لا رفضا.**
 *
 * ══════════════════════════════════════════════════════════════════════
 *
 * **وهذا الصنفُ حسابٌ محضٌ بلا أندرويد** — يُختبر بلا جهاز.
 */
object PathSmoother {

    /** **سقفُ زمن الحركة** — ما فوقه تأخّرٌ محسوس. */
    const val MAX_ANIM_MS = 1_500L

    /** **وأدناه** — ما دونه لا تُرى الحركة أصلاً. */
    const val MIN_ANIM_MS = 120L

    /** **إطالةٌ للقراءة المشكوك فيها** — انظر أعلاه. */
    const val DEGRADED_FACTOR = 1.4

    /**
     * **كم تدوم حركةُ الأيقونة إلى هذه القراءة.**
     *
     * @param dtMs الفاصلُ بين هذه القراءة وسابقتها — **صفرٌ في الأولى**.
     * @param expectedIntervalMs الفاصلُ المتوقَّعُ بين قراءتين.
     */
    fun animationMs(dtMs: Long, expectedIntervalMs: Long, grade: FixGrade): Long {
        // **والفاصلُ الفعليُّ أصدقُ من المتوقَّع حين يُعرف** — النظامُ
        // يسلّم أبطأَ ممّا طُلب حين تسوء السماء.
        val base = if (dtMs > 0) dtMs else expectedIntervalMs
        val scaled = if (grade == FixGrade.DEGRADED) (base * DEGRADED_FACTOR).toLong() else base
        return scaled.coerceIn(MIN_ANIM_MS, MAX_ANIM_MS)
    }

    /**
     * **موضعٌ بين نقطتين بنسبة `t`** — `0` عند الأولى و`1` عند الثانية.
     *
     * **وخطّيٌّ لا قوسيّ**: على مسافةِ ثانيةٍ من السير **الفرقُ بين
     * الخطّ والقوس أقلُّ من سنتيمتر** — وقوسٌ يُحسب في كلّ إطارٍ يأكل
     * معالجاً لا يُشترى بشيء.
     */
    fun lerp(
        fromLat: Double,
        fromLng: Double,
        toLat: Double,
        toLng: Double,
        t: Double,
    ): Pair<Double, Double> {
        val c = t.coerceIn(0.0, 1.0)
        return (fromLat + (toLat - fromLat) * c) to (fromLng + (toLng - fromLng) * c)
    }

    /**
     * **زاويةٌ بين زاويتين بنسبة `t`** — بأقصر الطريقين.
     *
     * **ومن استوفى بالطرح المباشر جعل السهمَ يلفّ لفّةً كاملة** حين
     * يعبر الشمال.
     */
    fun lerpAngle(from: Float, to: Float, t: Double): Float {
        val c = t.coerceIn(0.0, 1.0)
        return GpsQuality.normalize(from + (GpsQuality.angleDelta(from, to) * c).toFloat())
    }

    /**
     * **تخفيفُ البداية والنهاية** — `easeInOut`.
     *
     * **والخطّيُّ المحضُ يبدأ ويقف فجأةً** فيُقرأ قفزاً صغيراً
     * متكرّراً، **وهذا يجعل الحركةَ تبدو آليّةً لا سائرة.**
     */
    fun ease(t: Double): Double {
        val c = t.coerceIn(0.0, 1.0)
        return if (c < 0.5) 2 * c * c else 1 - (-2 * c + 2) * (-2 * c + 2) / 2
    }
}
