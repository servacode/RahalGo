package com.rahalgo.navigation

/**
 * ══════════════════════════════════════════════════════════════════════
 * **بابٌ واحدٌ إلى الشبكة — ولا تعرف الملاحةُ ما وراءه**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (المرحلة ٣ب، أمرُ المالك ٢٠٢٦-٠٨-٢٠: «بحيث `driver-navigation` لا
 *  تعرف Retrofit/Ktor · HTTP · Order API · JSON · OSRM».)
 *
 * # ولماذا نداءٌ بردٍّ مؤجَّل لا `suspend`
 *
 * **الاختبارُ يحتاج أن يمسك الجوابَ في يده** ثمّ يطلقه متى شاء:
 * **سباقُ الرد المتأخّر لا يُختبر إن كان النداءُ يعود فوراً.** فالجوابُ
 * يُسلَّم عبر `done`، **والرفيدةُ تحتفظ به وتُشغّله بعد عشر قراءات.**
 *
 * **ولا خيطَ ولا مؤقّتَ هنا** — من ينفّذها في التطبيق يعرف خيوطَه.
 */
fun interface RouteSource {

    /**
     * **يطلب مساراً من هذه النقطة.**
     *
     * **ولا يُرسَل غيرُها**: لا وجهةَ ولا مسافةَ ولا زمن — **الخادمُ
     * يقرأ الوجهةَ من الطلب ويحسب الباقي.** (قاعدةُ المشروع: الجهازُ
     * يرسل واقعةً والخادمُ يقرّر.)
     *
     * @param seq رقمُ الطلب — **يُعاد كما هو** ليُعرف الجوابُ المتأخّر.
     */
    fun request(lat: Double, lng: Double, seq: Long, done: (RouteReply) -> Unit)
}

/** **جوابُ الطلب** — مسارٌ أو سببُ إخفاق. */
sealed interface RouteReply {
    data class Ok(val route: NavRoute) : RouteReply
    data class Failed(val reason: RerouteFailure) : RouteReply
}

/**
 * ══════════════════════════════════════════════════════════════════════
 * **ولا رايةُ `failed` واحدة**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (أمرُ المالك ٢٠٢٦-٠٨-٢٠: «لا أريد Boolean واحد… يكفي enum صغيرة
 *  تساعد الـCooldown والاختبارات».)
 *
 * **والفرقُ ليس تصنيفاً للتصنيف**: **شبكةٌ انقطعت تُعاد المحاولةُ فيها
 * بمجرّد عودتها**، **ومسارٌ ردّه المحرّكُ غيرَ صالحٍ لا تُصلحه إعادةُ
 * الطلب من الموضع نفسِه** — انظر `RerouteEngine.Tuning`.
 */
enum class RerouteFailure {
    /** **لا شبكة** — أو تعذّر الوصول. */
    NETWORK,

    /** **طال الانتظار.** */
    TIMEOUT,

    /** **ردّ الخادمُ `available:false`** — أو لا مسار. */
    NO_ROUTE,

    /** **جاء مسارٌ لا يصلح** — بلا هندسةٍ، أو يترك السائقَ خارجَه. */
    INVALID_ROUTE,

    /** **جوابٌ لطلبٍ لم يعد الحاليّ** — سباقٌ، ويُطرح بلا عقوبة. */
    STALE_RESPONSE,

    /** **أُلغي قبل أن يصل** — عاد السائقُ إلى مساره. */
    CANCELLED,
}

/**
 * ══════════════════════════════════════════════════════════════════════
 * **ولماذا طُلب مسارٌ جديد**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (المرحلة ٥، أمرُ المالك ٢٠٢٦-٠٨-٢١، البند ٢١.)
 *
 * **بابٌ واحدٌ لا محرّكان** — والسببُ يُقرأ في التشخيص، **ولا يغيّر
 * حارساً من حرّاس ٣ب.**
 */
enum class RerouteReason {
    /** **ترك المسارَ هندسيّاً.** */
    OFF_ROUTE,

    /** **بقي فيه وسار بعكسه — ومضت نافذةُ التصحيح.** */
    WRONG_WAY,
}

/**
 * **ما تعرضه الشاشةُ عن إعادة الحساب.**
 *
 * (أمرُ المالك: «لا تعيد تصميمَ الشاشة… يكفي State يسمح بعرضٍ
 *  لاحقاً».)
 *
 * **وهي غيرُ `OffRouteDetector.State`**: تلك دليلُ ملاحة، **وهذه فعلُ
 * شبكة.** وخلطُهما هو ما يجعل الحالَ تكذب.
 */
enum class RerouteStatus {
    NONE,
    REROUTING,
    REROUTE_FAILED,
}

/** **ما وقع حين حاولنا تركيبَ المسار الجديد.** */
enum class InstallOutcome {
    /** **رُكّب** — والملاحةُ تتابع عليه. */
    INSTALLED,

    /** **هندستُه لا تصلح للملاحة** — بلا مناوراتٍ أو تراكميّةٍ مطابقة. */
    INVALID,

    /**
     * **صالحٌ في نفسه ولا يصلح لنا** — يترك السائقَ خارجَه فوراً.
     *
     * **وهذا ما يقطع الحلقة**: `install → OFF_ROUTE → reroute →
     * install` — **ولا تُقطع بالبصمة وحدَها.** (أمرُ المالك، البند ١٦.)
     */
    UNUSABLE,
}
