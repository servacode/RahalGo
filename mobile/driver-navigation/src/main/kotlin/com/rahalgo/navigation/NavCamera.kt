package com.rahalgo.navigation

/**
 * ══════════════════════════════════════════════════════════════════════
 * **حالُ الكاميرا — يُقرّرها المنطق وتنفّذها الخريطة**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (أمرُ المالك ٢٠٢٦-٠٨-٢٠: «طوّر Camera Controller ضمن `map-core`،
 *  **لكن قرار الملاحة يبقى داخل `driver-navigation`**».)
 *
 * # فصلٌ يُقرأ في سطر
 *
 *     driver-navigation  →  **أين تنظر الكاميرا وبأيّ ميلٍ ودوران**
 *     map-core           →  **كيف تصل إلى هناك**
 *
 * **و`map-core` لا تعرف أنّ ثمّةَ رحلةً أصلاً** — تتلقّى أرقاماً
 * وتنفّذها. **وحارسُ المرحلة ٠ يحرس هذا الحدّ.**
 *
 * # ولماذا وضعان لا وضعٌ واحد
 *
 * **من قلّب الخريطةَ بيده لا يريدها أن تُنتزع منه** — والملاحقةُ
 * تُطفأ حتّى يطلبها. (وهو سلوكٌ قائمٌ اليوم بزرّ «اتبعني»، **ولا
 * يُغيَّر في هذه المرحلة.**)
 */
data class NavCameraState(
    val lat: Double,
    val lng: Double,
    /** **درجةُ دوران الخريطة** — `0` شمالٌ إلى الأعلى. */
    val bearingDeg: Float,
    /** **الميل** — `0` نظرةٌ عموديّة. */
    val tiltDeg: Float,
    val zoom: Double,
    /** **زمنُ الانتقال بالميلي** — يوافق زمنَ حركة الأيقونة. */
    val durationMs: Long,
)

/**
 * **يقرّر أين تنظر الكاميرا أثناء الملاحة.**
 *
 * # والأرقامُ مختارةٌ بسبب — لا مذاق
 *
 * **التقريبُ ١٧٫٥**: عندها يُقرأ اسمُ الشارع الذي تحته وتُرى
 * التقاطعاتُ التالية. **و١٦ يُري المدينةَ ولا يُري المنعطف، و١٩ يُري
 * المنعطفَ ولا يُري ما بعده.**
 *
 * **والميلُ ٤٥ درجة**: يعطي إحساسَ الطريق الممتدّ أمامه. **والصفرُ
 * خريطةٌ مسطّحةٌ يقرأها كخارطةِ ورق، والستّون يُخفي ما وراء الأفق
 * ويجعل ما تحت الدرّاجة ضخماً.**
 *
 * **والدورانُ يتبع اتّجاهَ السائق** — فما أمامه على الشاشة أمامه على
 * الأرض. **وهو أصلُ الفرق بين خريطةٍ وملاحة.**
 *
 * # والتقريبُ يتبع السرعةَ والمنعطف (المرحلة ٣ من `docs/navigation/PLAN.md`)
 *
 * (كان أمرُ المالك القديم: «لا تبنِ Dynamic Zoom الآن». **ورفعه ٢٠٢٦-١٠-٠٢**
 *  بمواصفة الملاحة، الجزء ١٠: «zoom ديناميكيّ حسب السرعة وقرب المناورة».)
 *
 * - **واقفٌ أو بطيء (≤ ٤م/ث)**: ١٧٫٥ كما كان.
 * - **وكلّما أسرع ابتعدت** عُشرَ مستوىً لكلّ م/ث — ٥٠ كم/س ≈ ١٦٫٥، ولا أبعدَ من ١٥٫٥.
 * - **وقربَ منعطفٍ (≤ ١٥٠م) يعود ١٧٫٥** — ليُرى المنعطفُ واضحاً.
 *
 * **والانتقالُ بين القيم لا يقفز** — تحدّه الشاشةُ بنصف مستوىً في الثانية.
 */
object NavCamera {

    const val NAV_ZOOM = 17.5
    const val NAV_TILT = 45f

    /**
     * **يبني حالَ الكاميرا من الموضع المعروض والاتّجاه المنعَّم.**
     *
     * **ويأخذ ما يُعرض لا ما وصل**: الكاميرا تلاحق الأيقونةَ لا
     * القراءةَ الخام، **وإلّا سبقت الكاميرا الأيقونةَ فبدت تنزلق.**
     *
     * **و`bearing` فارغٌ حين لم يُعرف اتّجاهٌ بعد** — فتُترك الخريطةُ
     * على دورانها الحاليّ: **دورانٌ إلى الشمال عند بدء الرحلة يقلب
     * الشاشةَ فجأةً بلا سبب.**
     */
    fun follow(
        lat: Double,
        lng: Double,
        bearingDeg: Float?,
        currentBearingDeg: Float,
        durationMs: Long,
        speedMps: Double = 0.0,
        toManeuverM: Double = -1.0,
    ): NavCameraState = NavCameraState(
        lat = lat,
        lng = lng,
        bearingDeg = bearingDeg ?: currentBearingDeg,
        tiltDeg = NAV_TILT,
        zoom = zoomFor(speedMps, toManeuverM),
        durationMs = durationMs,
    )

    /** **التقريبُ المطلوب** — انظر الشرح أعلاه. */
    fun zoomFor(speedMps: Double, toManeuverM: Double): Double {
        val bySpeed = (NAV_ZOOM - ZOOM_PER_MPS * (speedMps - SLOW_MPS).coerceAtLeast(0.0))
            .coerceIn(MIN_NAV_ZOOM, NAV_ZOOM)
        return if (toManeuverM in 0.0..NEAR_MANEUVER_M) NAV_ZOOM else bySpeed
    }

    const val MIN_NAV_ZOOM = 15.5
    const val SLOW_MPS = 4.0
    const val ZOOM_PER_MPS = 0.1
    const val NEAR_MANEUVER_M = 150.0

    /** **أقصى تغيّرٍ للتقريب في الثانية** — لا قفز. */
    const val ZOOM_RATE_PER_S = 0.5

    /**
     * **حالُ الخروج من الملاحة** — تُعاد الخريطةُ إلى وضعها المألوف.
     *
     * **ومن أنهى رحلتَه ثمّ فتح الخريطةَ فوجدها مائلةً مستديرةً** ظنّ
     * أنّ شيئاً عطب. **والعودةُ جزءٌ من الدخول.**
     */
    fun rest(lat: Double, lng: Double, durationMs: Long = 500L): NavCameraState =
        NavCameraState(
            lat = lat,
            lng = lng,
            bearingDeg = 0f,
            tiltDeg = 0f,
            zoom = 16.5,
            durationMs = durationMs,
        )
}
