package com.rahalgo.navigation

import org.maplibre.android.geometry.LatLng

/**
 * ══════════════════════════════════════════════════════════════════════
 * **يُطوى ما قُطع — ولا يبقى الخطُّ الأزرقُ خلفَك**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (طلبُ المالك ٢٠٢٦-٠٨-٢٤: «الخطُّ الأزرقُ يجب أن يختفي بعد تجاوز
 *  الطريق المقطوع» — وهو سلوكُ خرائط غوغل.)
 *
 * # ولماذا يهمّ
 *
 * **الخطُّ الكاملُ يكذب على العين**: يبدو للسائق أنّ أمامه ما خلفَه،
 * **وعند دوّارٍ أو تقاطعٍ يلتبس الفرعُ الذي جاء منه بالفرع الذي يقصده.**
 *
 * # والقصُّ بالتقدّم لا بأقرب نقطة
 *
 * **و`RouteProgress.progressM` محسوبةٌ أصلاً** ومستقرّةٌ ولا ترتدّ —
 * **ومن قصّ بأقرب نقطةٍ إلى السائق قصّ الطريقَ كلَّه** عند مسارٍ يعود
 * على نفسه: نقطةُ العودة قريبةٌ من نقطة الذهاب، **فيُطوى ما لم يُقطَع.**
 *
 * # ولا تُترك حافّةٌ حادّة
 *
 * **والقطعُ عند رأسٍ من رؤوس الخطّ يجعله يقفز مترين كلَّ ثانية.**
 * فتُحسب النقطةُ الوسطى بالاستكمال، **فيزحف الطرفُ زحفاً.**
 */
object RouteTrim {

    const val TAIL_M = 0.0

    /**
     * **يردّ ما بقي من الخطّ** — من موضع السائق إلى آخره.
     *
     * @param progressM ما قُطع على الخطّ بالمتر — من [RouteProgress].
     */
    /**
     * ══════════════════════════════════════════════════════════════════
     * **نسبةُ ما قُطع من الخطّ — صفرٌ إلى واحد**
     * ══════════════════════════════════════════════════════════════════
     *
     * (بلاغُ المالك ٢٠٢٦-٠٨-٢٤: «طريقة قصّ الخطّ الأزرق غير سلسة وغير
     *  احترافيّة، بدائيّة جدّاً — يجب ألّا يلاحظ الشخصُ قصَّها أصلاً،
     *  يجب أن يكون الخطُّ تحت السهم ويختفي مع السهم».)
     *
     * # ولماذا نسبةٌ لا هندسة
     *
     * **وقصُّ الهندسة يُعيد بناءَ الخطّ** — فلا يقع إلّا مع قراءة موقعٍ
     * جديدة، **مرّةً في الثانية**. والسهمُ يمشي ستّين مرّةً فيها،
     * **فيقفز الخطُّ خلفه قفزاتٍ من ثمانية أمتار** وتُرى القفزة.
     *
     * **والنسبةُ تُبدَّل في خاصّيّةِ لونٍ لا في هندسة** — فتُحدَّث في
     * كلّ إطارٍ بلا ثمن، **ويزحف حدُّ الشفافيّة تحت السهم زحفاً.**
     *
     * **والطولُ يُمرَّر ولا يُحسب هنا** — يُحسب مرّةً لكلّ مسارٍ لا
     * ستّين مرّةً في الثانية.
     */
    fun fraction(progressM: Double, totalM: Double): Double {
        if (totalM <= 0.0 || !progressM.isFinite() || !totalM.isFinite()) return 0.0
        val cut = progressM - TAIL_M
        if (cut <= 0.0) return 0.0
        // **ولا يُبتلع الخطُّ كلُّه** — **وخطٌّ يختفي تماماً يُقرأ عطباً
        // لا وصولاً**، فيبقى منه ما يُرى.
        return (cut / totalM).coerceIn(0.0, 0.999)
    }

    /** **طولُ الخطّ بالمتر** — يُحسب مرّةً لكلّ مسار. */
    fun lengthM(route: List<LatLng>): Double {
        var d = 0.0
        for (i in 0 until route.size - 1) {
            d += ArrivalGuard.distanceM(
                route[i].latitude, route[i].longitude,
                route[i + 1].latitude, route[i + 1].longitude,
            )
        }
        return d
    }
}
