package com.rahalgo.navigation

/**
 * ══════════════════════════════════════════════════════════════════════
 * **ذاكرةُ نسبةِ القصّ — لخطٍّ واحدٍ لا للعمليّة كلِّها**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (عيبٌ كامنٌ قِيس ٢٠٢٦-٠٩-٢٩ بعد الرحلة المحاكاة: الرحلةُ الحقيقيّةُ
 *  فتحت بعدها فأبلغت `traveled=0.5811` — **نسبةَ خطٍّ آخرَ انتهى.**)
 *
 * # ما تفعله
 *
 * **تمنع بناءَ تعبيرِ تدرّجٍ لفرقٍ لا تراه عين** — جزءٌ من ألفٍ من مسارٍ
 * طولُه كيلومترٌ مترٌ واحد، **وبناءُ تعبيرٍ ستّين مرّةً في الثانية ثمنٌ
 * بلا مقابل.**
 *
 * # والعيبُ الذي بُنيت لتمنعه
 *
 * **وكانت النسبةُ حقلاً في `object Markers`** — أي واحدةً للعمليّة
 * كلِّها. **فتنتقل من مسارٍ إلى مسار:**
 *
 *	الخطُّ (أ) انتهى على ٠٫٥٨١
 *	الخطُّ (ب) يبدأ، وأوّلُ نسبةٍ له ٠٫٥٨١٥
 *	الفرقُ أقلُّ من ٠٫٠٠١  ⇒  **تُهمَل**
 *	فيبقى (ب) بتدرّجِ (أ) — أو بلا تدرّجٍ والذاكرةُ تحسبه مطبَّقا
 *
 * **وطبقاتُ الخطّ تُعاد بناءً مع كلّ تحميلِ نمط** — بلا تدرّج. **فذاكرةٌ
 * تقول «مطبَّقٌ» عن طبقةٍ وُلدت الآن تكذب.**
 *
 * # ومتى تُنسى
 *
 * **مع كلّ خطٍّ جديد**: مسارٌ يُركَّب · ساقٌ تبدأ · إعادةُ حسابٍ تبدّل
 * المسار · طلبٌ أو جلسةٌ تتبدّل. **ومع كلّ بناءٍ جديدٍ للطبقات.**
 *
 * **ولا يُمَسُّ سلوكُ القصّ نفسُه** — النسبةُ تُحسب كما كانت
 * (`RouteTrim.fraction`)، وهذه ذاكرةُ «أطُبِّقت أم لا» وحدَها.
 */
internal class TrimMemo {

    /** **أصغرُ فرقٍ يستحقّ بناءَ تعبير** — جزءٌ من ألف. */
    private val epsilon = 0.001

    /** **آخرُ نسبةٍ طُبّقت** — وسالبٌ يعني «لا شيءَ مطبَّقٌ بعد». */
    private var applied = -1.0

    /** **تُقرأ في القياس والاختبار** — لا يُبنى عليها منطقُ رسم. */
    internal val lastApplied: Double get() = applied

    /**
     * **أيُبنى التعبيرُ لهذه النسبة؟** — ويُسجّل أنّها طُبّقت إن نعم.
     */
    fun shouldApply(traveled: Double): Boolean {
        if (applied >= 0.0 && kotlin.math.abs(traveled - applied) < epsilon) return false
        applied = traveled
        return true
    }

    /**
     * **يُنسى ما طُبّق** — فأوّلُ نسبةٍ للخطّ التالي تُطبَّق حتماً.
     *
     * **ولا تُترك النسبةُ صفراً**: صفرٌ قيمةٌ صالحةٌ («لم يُقطع شيء»)،
     * **ومن صفَّرها جعل أوّلَ صفرٍ حقيقيٍّ يُهمَل.**
     */
    fun reset() {
        applied = -1.0
    }
}
