package com.rahalgo.navigation

/**
 * ══════════════════════════════════════════════════════════════════════
 * **سرعةٌ يُصدَّق عليها — والواقفُ يستقرّ على صفر**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (بلاغُ المالك ٢٠٢٦-٠٩-٢٩: «الهاتفُ واقفٌ وأندرويد يقول ٢ و٤ و٥ و٦
 *  كم/س — **وضجيجُ التموضع لا يُعرض حركةً**».)
 *
 * # ما قِيس على الجهاز
 *
 * **SM-A525F واقفٌ على طاولة**، ونظامُ التموضع نفسُه يقول `vel=0.0`،
 * **ومع ذلك عرضت اللوحةُ ٤ ثمّ ٥ ثمّ ٦ كم/س.** وسببُه أنّ كلَّ قراءةٍ
 * تُقرأ وحدَها: **قراءةٌ واحدةٌ لا تعرف أواقفٌ هو أم يزحف.**
 *
 * # وثلاثةُ شهودٍ لا شاهدٌ واحد
 *
 *	ما قاله الجهاز    `speedMps` — وقد يغيب أو يكذب على الواقف
 *	ما قطعه فعلاً     الإزاحةُ بين قراءتين مقسومةً على زمنهما
 *	كم يثق بنفسه      `accuracyM` — ونقطةٌ بدقّة ٣٠م تتراقص ٣٠م
 *
 * **وإزاحةٌ أصغرُ من شكِّ القراءة ليست حركة**: نقطتان بدقّة ١٣م تفترقان
 * ١٠م **قد تكونان النقطةَ نفسَها** — وهذا بعينه ما يصنع «٤ كم/س» لهاتفٍ
 * لا يتحرّك.
 *
 * # وعتبتان لا عتبة — وإلّا تراقص الرقم
 *
 * **عتبةٌ واحدةٌ تجعل الرقمَ يقفز حولها**: من كانت سرعتُه على الحدّ
 * ظهرت وغابت في كلّ ثانية. **فيُشترط للانطلاق أكثرُ مما يُشترط
 * للبقاء** — وهي الهدنةُ المعروفة (hysteresis).
 *
 *	واقفٌ ⇒ يسير   إذا بلغت [MOVING_ON] وصدّقتها الإزاحة
 *	يسيرٌ ⇒ واقف   إذا نزلت تحت [MOVING_OFF]
 *
 * # ولا يُخترع رقم
 *
 * **والصفرُ هنا قياسٌ لا اختلاق**: قراءةٌ حديثةٌ وصلت، وشهودُها تقول
 * «لم يتحرّك» — **فصفرٌ هو الحقّ.** وأمّا انعدامُ القراءة أصلاً فليس من
 * شأن هذا المرشِّح، **تردّه `SpeedReadout` فراغا.**
 */
class SpeedFilter {

    /** **ما دونها لا تُعدّ حركةً بحال** — ٨ كم/س. */
    private val movingOnMps = 2.2f

    /** **وما دونها يعود واقفا** — ٤ كم/س. */
    private val movingOffMps = 1.1f

    /** **أقصى دقّةٍ تُصدَّق فيها الإزاحة** — وما فوقها نقطةٌ تتراقص. */
    private val trustedAccuracyM = 35f

    /** **أدنى إزاحةٍ تُعدّ انتقالا** — أو نصفُ شكِّ القراءة، أيّهما أكبر. */
    private val minDisplacementM = 4.0

    private var prevLat = Double.NaN
    private var prevLng = Double.NaN
    private var prevAtMs = 0L
    private var moving = false

    /** **يُنسى كلُّ شيءٍ** — جلسةٌ جديدةٌ لا ترث سرعةَ سابقتها. */
    fun reset() {
        prevLat = Double.NaN
        prevLng = Double.NaN
        prevAtMs = 0L
        moving = false
    }

    /**
     * **يردّ السرعةَ المعروضةَ كم/س** — وصفرٌ يعني «واقفٌ بقراءةٍ حديثة».
     */
    fun next(fix: NavFix): Int {
        // **ما قطعه بين القراءتين** — الشاهدُ الذي لا يكذب على الواقف.
        var measuredMps: Float? = null
        var displacementM = 0.0
        if (!prevLat.isNaN() && prevAtMs > 0L) {
            val dtSec = (fix.atMs - prevAtMs) / 1000.0
            displacementM = ArrivalGuard.distanceM(prevLat, prevLng, fix.lat, fix.lng)
            // **وفاصلٌ سالبٌ أو بعيدٌ لا يُقاس عليه** — قراءةٌ تأخّرت أو
            // عودةٌ من نومٍ طويل.
            if (dtSec in 0.25..10.0) {
                measuredMps = (displacementM / dtSec).toFloat()
            }
        }
        prevLat = fix.lat
        prevLng = fix.lng
        prevAtMs = fix.atMs

        val reported = fix.speedMps?.takeIf { it.isFinite() && it >= 0f }

        // ══════════════════════════════════════════════════════════════
        // **وإزاحةٌ دون شكِّ القراءة ليست حركة**
        // ══════════════════════════════════════════════════════════════
        //
        // **نقطتان بدقّة ٦٠م تفترقان ٢٥م قد تكونان النقطةَ نفسَها** —
        // **وسرعةٌ محسوبةٌ من إزاحةٍ لا تُصدَّق لا تُصدَّق هي أيضاً.**
        val doubtM = maxOf(minDisplacementM, (fix.accuracyM / 2f).toDouble())
        val displacementTrusted = fix.accuracyM <= trustedAccuracyM && displacementM > doubtM
        val measuredTrusted = measuredMps?.takeIf { displacementTrusted }

        // ══════════════════════════════════════════════════════════════
        // **وما يقوله الجهازُ عن سرعته مقدَّمٌ على ما نحسبه من موضعين**
        // ══════════════════════════════════════════════════════════════
        //
        // **وسرعةُ الجهاز من إزاحةِ التردّد (دوبلر) لا من الموضع** —
        // **فتبقى صادقةً حيث يسوء الموضعُ**: بين البنايات وتحت الجسور.
        // **ولو شُرط لها تصديقُ الإزاحة لَاختفت سرعةُ سائقٍ يسير حقّاً.**
        //
        // **وهي في الوقوف ضعيفةٌ لا كاذبة**: قِيس على الجهاز ١٫١–١٫٧ م/ث
        // **وكلُّها دون عتبة الانطلاق** — فتُصفَّر بالعتبة وحدَها بلا
        // حاجةٍ إلى إزاحة.
        val candidateMps = reported ?: measuredTrusted

        if (candidateMps == null) {
            // **لا رقمَ من الجهاز ولا إزاحةً تُصدَّق** — لا شاهدَ على
            // حركة، **والواقفُ أولى من المخترَع.**
            moving = false
            return 0
        }

        moving = if (moving) {
            // **والباقي يبقى حتّى ينزل تحت الأدنى** — هدنةٌ لا تراقص.
            candidateMps >= movingOffMps
        } else {
            candidateMps >= movingOnMps
        }

        if (!moving) return 0
        return Math.round(candidateMps * 3.6f)
    }
}
