package com.rahalgo.navigation

/**
 * ══════════════════════════════════════════════════════════════════════
 * **الجملُ العربيّة — قصيرةٌ يفهمها السائقُ وهو يقود**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (المرحلة ٤، أمرُ المالك ٢٠٢٦-٠٨-٢٠.)
 *
 * # ولماذا هنا لا في `strings.xml`
 *
 * **الجملةُ قرارٌ ملاحيٌّ لا زخرفةُ شاشة**: «انعطف يميناً، ثمّ يساراً
 * مباشرةً» **دمجٌ اتُّخذ في المخطِّط**، ونصُّها جزءٌ من الحكم.
 *
 * **وفي `strings.xml` لا تُختبر إلّا بأندرويد** — وكلُّ اختبارات هذه
 * المرحلة تعمل بلا جهاز.
 *
 * # ولا فصحى ثقيلةٌ ولا عامّيّةٌ مربكة
 *
 * (أمرُ المالك: «إرشادٌ عربيٌّ واضحٌ ومفهومٌ للسائق السوريّ».)
 */
object VoicePhrases {

    // ══════════════════════════════════════════════════════════════════
    // **مصفوفةُ المناورات — لكلّ نوعٍ جملةٌ ومَخرجٌ آمن**
    // ══════════════════════════════════════════════════════════════════

    /**
     * **فعلُ المناورة بلا مسافة.**
     *
     * **و`UNKNOWN` لا تصمت ولا تسقط** (أمرُ المالك): **نوعٌ جديدٌ من
     * الخادم يُقرأ نصّاً**، والسائقُ يُقال له «تابع المسار» — وهو صحيحٌ
     * دائماً.
     */
    fun action(m: NavManeuver): String = when (m.kind) {
        ManeuverKinds.DEPART -> "ابدأ السير"
        ManeuverKinds.STRAIGHT -> "تابع مستقيماً"
        ManeuverKinds.TURN_RIGHT -> "انعطف يميناً"
        ManeuverKinds.TURN_LEFT -> "انعطف يساراً"
        ManeuverKinds.SLIGHT_RIGHT -> "مِل يميناً"
        ManeuverKinds.SLIGHT_LEFT -> "مِل يساراً"
        ManeuverKinds.SHARP_RIGHT -> "انعطف يميناً بحدّة"
        ManeuverKinds.SHARP_LEFT -> "انعطف يساراً بحدّة"
        ManeuverKinds.U_TURN -> "در للخلف"
        ManeuverKinds.MERGE -> "اندمج مع الطريق"
        ManeuverKinds.FORK -> fork(m)
        ManeuverKinds.OFF_RAMP -> "اسلك المخرج"
        ManeuverKinds.ROUNDABOUT -> roundabout(m)
        // **وجملةُ الدخول قالت المخرجَ أصلاً** — انظر `speaks`.
        ManeuverKinds.EXIT_ROUNDABOUT -> "اخرج من الدوار"
        ManeuverKinds.ARRIVE -> "لقد وصلت"
        else -> FOLLOW_ROUTE
    }

    /** **تابع المسار** — مَخرجُ كلّ ما لا نعرفه. */
    const val FOLLOW_ROUTE = "تابع المسار"

    /**
     * **والتفرّعُ بلا معدِّلٍ لا يُخترع له اتّجاه.**
     *
     * **ومن قال «خذ اليمين» وهو لا يعرف أضلّ من سكت.**
     */
    private fun fork(m: NavManeuver): String = when (m.modifier) {
        "right", "slight right" -> "عند التفرّع، خذ اليمين"
        "left", "slight left" -> "عند التفرّع، خذ اليسار"
        else -> "انتبه، الطريق يتفرّع"
    }

    /**
     * ══════════════════════════════════════════════════════════════════
     * **والدوّارُ يُقال بمخرجه — واسمُه إن صحّ**
     * ══════════════════════════════════════════════════════════════════
     *
     * **وقِيس على محرّكنا** (المرحلة ٢): `exit` حاضرٌ دائماً،
     * و`rotary_name` عربيٌّ حين يوجد. **وخمسةٌ من سبعة أسماءٍ عربيّةٍ في
     * مُدوَّنة الرقّة أسماءُ دوّارات** (قِيس ٢٠٢٦-٠٨-٢١) — فهذا أنفعُ
     * مواضع الاسم.
     */
    private fun roundabout(m: NavManeuver): String {
        val where = m.roundaboutName
            ?.let { StreetName.speakable(it) }
            ?.let { "عند $it" }
            ?: "عند الدوار"
        val exit = ordinal(m.roundaboutExit)
            ?: return "$where، تابع الاتّجاه"
        return "$where، خذ المخرج $exit"
    }

    /** **ترتيبُ المخرج** — وفارغٌ لما لا نعرف. */
    fun ordinal(n: Int?): String? = when (n) {
        1 -> "الأول"
        2 -> "الثاني"
        3 -> "الثالث"
        4 -> "الرابع"
        5 -> "الخامس"
        6 -> "السادس"
        else -> null
    }

    // ══════════════════════════════════════════════════════════════════
    // **الجملةُ الكاملة**
    // ══════════════════════════════════════════════════════════════════

    /**
     * **بالمسافة أو بلاها.**
     *
     *     PREPARE/APPROACH  →  «بعد مئتي متر، انعطف يميناً»
     *     NOW               →  «انعطف يميناً الآن»
     */
    fun maneuver(m: NavManeuver, distanceM: Int?): String {
        val act = action(m)
        val named = withStreet(act, m)
        return when {
            distanceM == null -> if (m.kind == ManeuverKinds.ARRIVE) named else "$named الآن"
            else -> "بعد ${meters(distanceM)}، $named"
        }
    }

    /** **ومناورتان متقاربتان في جملةٍ واحدة.** */
    fun combined(first: NavManeuver, second: NavManeuver, distanceM: Int?): String {
        val a = action(first)
        val b = action(second)
        val head = if (distanceM == null) a else "بعد ${meters(distanceM)}، $a"
        return "$head، ثمّ $b مباشرةً"
    }

    /**
     * **والمسافةُ تُنطق كما تُقال لا كما تُكتب.**
     *
     * **و«بعد مئة وسبعة وثلاثين متراً» لا يقولها إنسان** — فتُقرَّب في
     * `VoicePlanner` قبل أن تصل هنا.
     */
    fun meters(m: Int): String = when (m) {
        50 -> "خمسين متراً"
        100 -> "مئة متر"
        150 -> "مئة وخمسين متراً"
        200 -> "مئتي متر"
        300 -> "ثلاث مئة متر"
        400 -> "أربع مئة متر"
        500 -> "خمس مئة متر"
        700 -> "سبع مئة متر"
        1000 -> "كيلومتر"
        else -> "$m متراً"
    }

    /**
     * **واسمُ الشارع زيادةٌ لا أساس.**
     *
     * **و٨٣٪ من خطوات الرقّة بلا اسم** (قِيس في المرحلة ٢) — **فالجملةُ
     * تُبنى بلا اسمٍ ثمّ يُضاف إن صحّ.**
     *
     * **ولا يُضاف إلى الوصول ولا إلى الدوّار** — الأوّلُ لا معنى له،
     * **والثاني اسمُه في جملته أصلاً.**
     */
    private fun withStreet(action: String, m: NavManeuver): String {
        if (m.kind == ManeuverKinds.ARRIVE || m.isRoundabout) return action
        val name = m.streetName?.let { StreetName.speakable(it) } ?: return action
        return "$action إلى $name"
    }

    // ══════════════════════════════════════════════════════════════════
    // **جملُ الأحداث**
    // ══════════════════════════════════════════════════════════════════

    /**
     * ══════════════════════════════════════════════════════════════════
     * **وصفٌ لا أمرٌ بمناورة**
     * ══════════════════════════════════════════════════════════════════
     *
     * (قرارُ المالك ٢٠٢٦-٠٨-٢١، البندان ٢ و٢٤.)
     *
     * **ولا يُقال «غيّر اتّجاه السير»** — تُقرأ أمراً بدورانٍ فوريّ،
     * **وقد يكون الدورانُ هنا محرَّماً أو خطرا.** ومن يقرّر المناورةَ
     * هو محرّكُ المسارات لا جملةُ تحذير.
     *
     * **ولا «بعكس اتّجاه الشارع»** — **لا نملك قاعدةَ اتّجاهاتِ شوارع**،
     * فلا ندّعي مخالفةً قانونيّة. **نقول عكسَ مسارِنا نحن.**
     */
    const val WRONG_WAY = "أنت تسير بعكس اتجاه المسار"

    const val REROUTING = "جارٍ إعادة حساب المسار"
    const val REROUTE_FAILED = "تعذّرت إعادة حساب المسار"

    fun arrival(target: TripTarget): String = when (target) {
        TripTarget.PICKUP -> "وصلت إلى نقطة الاستلام"
        TripTarget.DROPOFF -> "وصلت إلى وجهة التوصيل"
    }

    /**
     * ══════════════════════════════════════════════════════════════
     * **انتهى الخطُّ ولمّا يصل — TD-ROUTE-END-CUE**
     * ══════════════════════════════════════════════════════════════
     *
     * (قرارُ المالك ٢٠٢٦-٠٨-٢١، البند ٩.)
     *
     * **ولا تدّعي وصولاً ولا قُرباً**: الهدفُ قد يبعد مئةً وثمانين
     * متراً، **فـ«اقتربت» كذبٌ مثلُ «وصلت».**
     *
     * **وتقول ما وقع بالضبط**: الطريقُ المرسومُ انتهى، **والباقي
     * على السائق.**
     *
     * **ولفظٌ واحدٌ للطرفين** — البند ٩: «الموقع» يصلح للمتجر
     * وللزبون، **ولا حاجةَ لصيغتين حيث المعنى واحد.**
     */
    const val ROUTE_END = "انتهى المسار المرسوم، تابع نحو الموقع"
}

/**
 * ══════════════════════════════════════════════════════════════════════
 * **حارسُ الأسماء — ما لا يُنطق عربيّاً لا يُقال**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (المرحلة ٤، أمرُ المالك: «أريد سياسةً تمنع أن يقرأ TTS اسماً رديئاً
 *  فيفسد التعليمات كلَّها».)
 *
 * # والقياسُ حسم السياسة
 *
 * **مُدوَّنةٌ من ثمانية مساراتٍ حقيقيّةٍ في الرقّة** (٢٠٢٦-٠٨-٢١):
 *
 *	١٠٦ خطوة · ٥٢ مسمّاة · ١٦ اسماً فريداً
 *	تسعةٌ لاتينيّة   —  Adnan Malki Street · Aleppo Road · Nene Road 4 …
 *	سبعةٌ عربيّة     —  الجسر الجديد · دوار النعيم · دوار الصوامع …
 *
 * **وأكثرُ أسماء الرقّة في OSM كُتبت بحروفٍ لاتينيّة** — **ومحرّكُ
 * النطق العربيُّ يقرؤها حرفاً حرفاً أو يتخطّاها**، فتنقطع الجملةُ في
 * منتصفها. **فاسمٌ رديءٌ لا يُفسد كلمةً بل يُفسد التعليمة.**
 *
 * **وأطولُ اسمٍ عربيٍّ في المُدوَّنة اثنا عشرَ محرفاً** (`دوار الصوامع`)
 * — **فحدُّ الخمسةِ والعشرين لا يرفض اسماً صالحاً واحداً فيها.**
 */
object StreetName {

    /** **أقصرُ ما يُنطق** — حرفان لا يصنعان اسما. */
    const val MIN_CHARS = 3

    /**
     * **وأطولُ ما يُقال في جملةِ ملاحة.**
     *
     * **وقِيس ألّا يرفض اسماً عربيّاً في المُدوَّنة** — وأطولُها اثنا
     * عشر.
     */
    const val MAX_CHARS = 25

    /**
     * **ما يُقال منه — أو فارغٌ فتُقال الجملةُ بلا اسم.**
     *
     * ══════════════════════════════════════════════════════════════════
     * **والتنقيةُ تسبقه ولا تُكرَّر هنا**
     * ══════════════════════════════════════════════════════════════════
     *
     * (المرحلة ٦أ، قرارُ المالك ٢٠٢٦-٠٨-٢١، البند ١٧: «لا تنشئ
     *  Sanitizer ثانية».)
     *
     * **ومحارفُ التحكّم الاتّجاهيّةُ كانت تُرفض «رمزاً»** — فيسقط
     * خمسةٌ من خمسةٍ وعشرين اسماً عربيّاً سليماً (قِيس ٢٠٢٦-٠٨-٢١).
     * **والتنقيةُ في `MapLabel.normalize` وحدَها**، وهذه تحكم بعدها.
     */
    fun speakable(raw: String?): String? {
        val name = MapLabel.normalize(raw)?.trim() ?: return null
        if (name.length < MIN_CHARS || name.length > MAX_CHARS) return null
        var arabic = 0
        for (ch in name) {
            when {
                ch.isArabic() -> arabic++
                // **واللاتينيُّ يُسقط الاسمَ كلَّه** — لا يُنقّى منه:
                // **«شارع Aleppo Road» أسوأُ من «شارع».**
                ch in 'a'..'z' || ch in 'A'..'Z' -> return null
                ch.isDigit() -> return null
                ch == ' ' || ch == '-' || ch == '،' -> Unit
                // **ورموزٌ لا تُنطق** — نقطةٌ أو قوسٌ أو شرطةٌ مائلة.
                else -> return null
            }
        }
        // **ولا اسمَ بلا حروفٍ عربيّةٍ كافية.**
        return if (arabic >= MIN_CHARS) name else null
    }

    /**
     * **الحكمُ بلا تنقية** — للقياس وحدَه.
     *
     * **ويُقاس به أثرُ التنقية**: كم اسماً عربيّاً سليماً كان يسقط
     * بسبب محارفِ تحكّمٍ لا تُرى. (`LBL-001`.)
     */
    fun speakableRaw(raw: String?): String? {
        val name = raw?.trim() ?: return null
        if (name.length < MIN_CHARS || name.length > MAX_CHARS) return null
        var arabic = 0
        for (ch in name) {
            when {
                ch.isArabic() -> arabic++
                ch in 'a'..'z' || ch in 'A'..'Z' -> return null
                ch.isDigit() -> return null
                ch == ' ' || ch == '-' || ch == '،' -> Unit
                else -> return null
            }
        }
        return if (arabic >= MIN_CHARS) name else null
    }

    /** **سببُ الرفض** — يُقرأ في قياس المُدوَّنة لا في المنطق. */
    fun reject(raw: String?): String? {
        val name = raw?.trim() ?: return "فارغ"
        if (speakable(name) != null) return null
        if (name.length < MIN_CHARS) return "قصير"
        if (name.length > MAX_CHARS) return "طويل"
        if (name.any { it in 'a'..'z' || it in 'A'..'Z' }) return "لاتينيّ"
        if (name.any { it.isDigit() }) return "رقم"
        if (name.none { it.isArabic() }) return "بلا عربيّة"
        return "رمز"
    }

    private fun Char.isArabic(): Boolean = this in '؀'..'ۿ' || this in 'ﹰ'..'﻿'
}
