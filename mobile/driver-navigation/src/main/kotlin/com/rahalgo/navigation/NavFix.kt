package com.rahalgo.navigation

/**
 * ══════════════════════════════════════════════════════════════════════
 * **قراءةُ موقعٍ واحدة — كما وصلت من الجهاز**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (المرحلة ١، بأمر المالك ٢٠٢٦-٠٨-٢٠.)
 *
 * # ولماذا صنفٌ عندنا لا `android.location.Location`
 *
 * **`Location` صنفٌ من النظام لا يُبنى في اختبار** — يحتاج جهازاً أو
 * محاكياً. **ومنطقٌ لا يُختبر إلّا على جهازٍ لا يُختبر.**
 *
 * **وهذا الصنفُ بياناتٌ محضة**: يُبنى بسطر، ويُمرَّر مجرىً وهميّاً في
 * الاختبار، **ويُعاد تشغيلُ رحلةٍ مسجَّلةٍ منه** في المراحل التالية.
 *
 * # وما فيه هو ما يلزم الملاحةَ لا أكثر
 *
 * **والاتّجاهُ والسرعةُ قد يغيبان**: أوّلُ قراءةٍ بعد الإقلاع بلا
 * اتّجاه، **ومن قرأ `bearing` صفراً حين يغيب وجّه الدرّاجةَ شمالاً وهي
 * تسير جنوبا.**
 */
data class NavFix(
    val lat: Double,
    val lng: Double,
    /** **نصفُ قطر الشكّ بالأمتار** — أصغرُ أدقّ. */
    val accuracyM: Float,
    /** **متر/ثانية** — وفارغٌ يعني «لم يقلها الجهاز». */
    val speedMps: Float?,
    /** **درجةٌ من الشمال** `0..360` — وفارغٌ يعني «لم يقلها الجهاز». */
    val bearingDeg: Float?,
    /** **لحظةُ الالتقاط** بالميلي — **لا لحظةُ الوصول إلينا.** */
    val atMs: Long,
)

/**
 * **حالُ القراءة بعد الفحص.**
 *
 * (أمرُ المالك: «حدّد سياسة واضحة للقراءات: Accepted · Degraded ·
 *  Rejected».)
 */
enum class FixGrade {
    /** **تُصدَّق كاملةً** — موضعُها واتّجاهُها. */
    ACCEPTED,

    /**
     * **يُؤخذ موضعُها ولا يُصدَّق اتّجاهُها.**
     *
     * **ودقّةٌ سيّئةٌ تعني موضعاً تقريبيّا** — والاتّجاهُ المحسوبُ من
     * موضعين تقريبيّين **يدور مع الضجيج لا مع الطريق.**
     */
    DEGRADED,

    /** **تُرمى** — ولا تُحرّك شيئاً على الشاشة. */
    REJECTED,
}

/** **ولماذا رُفضت** — يُقرأ في التشخيص لا في الإنتاج. */
enum class RejectReason {
    NONE,

    /** **دقّةٌ أسوأُ من أن تُصدَّق** — بناءٌ أو نفقٌ أو سماءٌ محجوبة. */
    ACCURACY,

    /** **قفزةٌ لا يقطعها راكبُ درّاجة** — خطأُ قمرٍ صناعيٍّ لا تنقّل. */
    TELEPORT,

    /** **أقدمُ من التي عُرضت** — تصل الدفعاتُ مختلطةَ الترتيب أحيانا. */
    STALE,
}
