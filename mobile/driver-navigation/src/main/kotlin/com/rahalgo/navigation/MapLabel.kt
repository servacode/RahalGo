package com.rahalgo.navigation

/**
 * ══════════════════════════════════════════════════════════════════════
 * **تنقيةُ الأسماء — مرّةً واحدةً لكلّ من يقرؤها**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (المرحلة ٦أ، قرارُ المالك ٢٠٢٦-٠٨-٢١، البندان ١٦ و١٧.)
 * **يُغلق `TD-BIDI-NAMES`.**
 *
 *     الاسمُ الخامّ من OSM
 *           ↓  normalize()          ← هنا، ومرّةً واحدة
 *     اسمٌ نظيف
 *           ↓                    ↓
 *     سياسةُ الخريطة        سياسةُ النطق
 *
 * # وما كشفه القياس
 *
 * **مُدوَّنةٌ من خمس مدنٍ سوريّة** (٢٠٢٦-٠٨-٢١): خمسةٌ من خمسةٍ وعشرين
 * اسماً تحمل **محارفَ تحكّمٍ ثنائيّةَ الاتّجاه** لا تُرى ولا تُنطق:
 *
 *	'‫شارع البعث‬‎'
 *	'روضة الميدان‬‎'
 *	'‫قاسم أمين‬‎'
 *
 * **وحارسُ المرحلة ٤ كان يرفضها «رمزاً»** — فيُسقط اسماً عربيّاً سليماً
 * ويُخرس النطقَ عنه.
 *
 * # ولا يُحذف يونيكود عشوائيّاً
 *
 * (أمرُ المالك نصّاً.)
 *
 * **تُحذف محارفُ التحكّم الاتّجاهيّةُ وحدَها** — وهي عشرةٌ معدودة.
 * **والتشكيلُ والهمزاتُ والمدّاتُ تبقى**: `الصدّيق` تبقى بشدّتها،
 * **ومن جرّدها غيّر الاسم.**
 */
object MapLabel {

    /**
     * ══════════════════════════════════════════════════════════════════
     * **محارفُ التحكّم الاتّجاهيّة — وهي وحدَها ما يُحذف**
     * ══════════════════════════════════════════════════════════════════
     *
     * **ووظيفتُها ترتيبُ العرض في محرّرِ نصٍّ** — لا معنى لها في اسمٍ
     * يُرسَم على خريطةٍ أو يُنطَق. **والمحرّكُ يرتّب الاتّجاهَ بنفسه**
     * (`ubidi_*` في `libmaplibre.so`، قِيس في PREFLIGHT).
     */
    private val BIDI_CONTROLS = setOf(
        '‎', // LRM — علامةُ يسارٍ-إلى-يمين
        '‏', // RLM — علامةُ يمينٍ-إلى-يسار
        '؜', // ALM — علامةٌ عربيّة
        '‪', // LRE
        '‫', // RLE
        '‬', // PDF — إنهاءُ التضمين
        '‭', // LRO
        '‮', // RLO
        '⁦', // LRI
        '⁧', // RLI
        '⁨', // FSI
        '⁩', // PDI
    )

    /**
     * **والفراغاتُ الصفريّةُ تُحذف أيضاً** — لا عرضَ لها ولا نطق،
     * **وتُفسد المقارنةَ والطول.**
     */
    private val ZERO_WIDTH = setOf(
        '﻿', // BOM في وسط النصّ
        '​', // ZWSP
    )

    /**
     * **يُنقّي اسماً خامّاً** — وفارغٌ يعني «لا اسم».
     *
     * **ويُنادى قبل كلّ سياسة** — الخريطةِ والنطق معاً.
     */
    fun normalize(raw: String?): String? {
        val src = raw ?: return null
        val sb = StringBuilder(src.length)
        for (ch in src) {
            when {
                ch in BIDI_CONTROLS -> Unit
                ch in ZERO_WIDTH -> Unit
                // **ومحارفُ التحكّم C0/C1 لا تُرسَم** — سطرٌ في اسمِ
                // شارعٍ خطأُ بياناتٍ لا تنسيق.
                ch.code < 0x20 || ch.code == 0x7F -> sb.append(' ')
                else -> sb.append(ch)
            }
        }
        // **والفراغاتُ المتكرّرةُ تُطوى** — وحذفُ محرفٍ بينها يترك اثنين.
        val cleaned = sb.toString().trim().replace(SPACES, " ")
        return cleaned.ifEmpty { null }
    }

    private val SPACES = Regex("\\s{2,}")

    /**
     * ══════════════════════════════════════════════════════════════════
     * **سياسةُ الخريطة — تقبل ما لا يُنطق**
     * ══════════════════════════════════════════════════════════════════
     *
     * (قرارُ المالك، البند ١٧: «الخريطةُ يمكن أن تعرض Latin · Voice
     *  يمكن أن ترفضه».)
     *
     * **واسمٌ لاتينيٌّ على الخريطة يُقرأ بالعين ويُفيد** — وقياسُنا
     * وجد أنّ ٦٪ من أسماء الطرق لاتينيّةٌ وطنيّاً و٥٦٪ في الرقّة.
     * **فحذفُها من الخريطة خسارةٌ بلا مقابل.**
     */
    fun forMap(raw: String?): String? = normalize(raw)

    /**
     * **وسياسةُ النطق أضيق** — انظر `StreetName.speakable`.
     *
     * **ولا سياستان في موضعين**: هذه تُنقّي، وتلك تحكم.
     */
    fun forVoice(raw: String?): String? = StreetName.speakable(normalize(raw))
}
