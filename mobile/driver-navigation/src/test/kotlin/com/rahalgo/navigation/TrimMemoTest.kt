package com.rahalgo.navigation

import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * ══════════════════════════════════════════════════════════════════════
 * **حارسٌ: تقدّمُ مسارٍ لا يتسرّب إلى مسارٍ آخر**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (عيبٌ كامنٌ قِيس على الجهاز ٢٠٢٦-٠٩-٢٩: بعد رحلةٍ محاكاةٍ انتهت على
 *  `traveled=0.5811`، فُتحت رحلةٌ حقيقيّةٌ فأبلغت النسبةَ نفسَها.)
 *
 * **والنسبةُ كانت حقلاً في `object Markers`** — واحدةً للعمليّة كلِّها.
 * **فأوّلُ نسبةٍ للخطّ الثاني تقع داخلَ هدنةِ الأوّل فتُهمَل**، فيبقى
 * الثاني بتدرّج الأوّل أو بلا تدرّجٍ والذاكرةُ تحسبه مطبَّقا.
 */
class TrimMemoTest {

    /**
     * **الشاهدُ الحاكم**: ما طُبّق على المسار (أ) لا يمنع تطبيقَ أوّلِ
     * نسبةٍ على المسار (ب).
     */
    @Test
    fun `تقدم مسار لا يلوث مسارا اخر`() {
        val memo = TrimMemo()
        // ── المسارُ (أ): يسير حتّى ٠٫٥٨١ ──
        assertTrue("**أوّلُ نسبةٍ لم تُطبَّق**", memo.shouldApply(0.0))
        assertTrue(memo.shouldApply(0.300))
        assertTrue(memo.shouldApply(0.5811))
        // **وفرقٌ لا يُرى يبقى مُهمَلاً** — الهدنةُ نفسُها لم تُمَسّ.
        assertFalse(
            "**بُني تعبيرٌ لفرقٍ أقلَّ من جزءٍ من ألف**",
            memo.shouldApply(0.58115),
        )

        // ── خطٌّ جديد: مسارٌ يُركَّب · ساقٌ تبدأ · إعادةُ حساب ──
        memo.reset()

        // **وأوّلُ نسبةٍ للمسار (ب) تُطبَّق حتماً** — ولو كانت مطابقةً
        // لما انتهى عليه (أ). **وهذا هو العيبُ الذي وقع على الجهاز.**
        assertTrue(
            "**تقدّمُ المسار (أ) سرى إلى (ب) فأُهمِلت أوّلُ نسبةٍ له**",
            memo.shouldApply(0.5811),
        )
    }

    /**
     * **والصفرُ نسبةٌ صالحة** — «لم يُقطع شيء». **فمن نسِيَ بتصفيرٍ لا
     * بسالبٍ جعل أوّلَ صفرٍ حقيقيٍّ يُهمَل** فيبقى الخطُّ مقصوصاً.
     */
    @Test
    fun `الصفر بعد الإنساء يُطبَّق لا يُهمَل`() {
        val memo = TrimMemo()
        assertTrue(memo.shouldApply(0.45))
        memo.reset()
        assertTrue("**صفرٌ حقيقيٌّ أُهمِل بعد الإنساء**", memo.shouldApply(0.0))
    }

    /** **والإنساءُ يُبطل القراءةَ المحفوظة** — لا يُبقيها للقياس. */
    @Test
    fun `الإنساء يمحو ما طُبّق`() {
        val memo = TrimMemo()
        memo.shouldApply(0.72)
        memo.reset()
        assertTrue("**بقيت النسبةُ محفوظةً بعد الإنساء**", memo.lastApplied < 0.0)
    }
}
