package com.rahalgo.shared.geo

import com.rahalgo.shared.net.ApiClient
import kotlinx.serialization.Serializable

/**
 * ══════════════════════════════════════════════════════════════════════
 * **العناوينُ والنقاط — من المحرّك لا من مزوّدٍ في الجهاز**
 * ══════════════════════════════════════════════════════════════════════
 *
 * # ولماذا يمرّ بالمحرّك
 *
 * **مزوّدُ العناوين يتبدّل** — ومفتاحُه سرّ. **ولو نادته التطبيقاتُ
 * مباشرةً لَحمل كلُّ تطبيقٍ مفتاحاً في شيفرته**، **ومن فكّ نسخةً قرأه.**
 *
 * **والمحرّكُ يخبّئه ويُوحّد الجواب** — فيبحث الويبُ والتطبيقُ في
 * المصدر نفسِه، **ولا يجد أحدُهما عنواناً لا يجده الآخر.**
 */
class GeoApi(private val api: ApiClient) {

    /**
     * **من نقطةٍ إلى عنوان.**
     *
     * **ويُنادى بعد أن يستقرّ الدبّوس لا مع كلّ حركة** — **ونداءٌ في كلّ
     * إطارٍ يُغرق المزوّدَ ويستنزف الحزمة.**
     */
    suspend fun reverse(lat: Double, lng: Double): Place =
        api.call("/api/v1/geo/reverse?lat=$lat&lng=$lng")

    /**
     * **بحثٌ بالاسم** — لمن يضيف متجراً وهو في مكتبه.
     *
     * **ويلزمه حساب** — **قِيس (٢٠٢٦-٠٨-١٤)**: البابان تحت
     * `RequireAuth` («لأيّ مستخدمٍ مسجّل»)، **لا عامّان كما ظُنّ.**
     *
     * **والمزوّدُ يُستنزف بنداءٍ مفتوحٍ للعالم** — فالحسابُ حدُّه.
     */
    suspend fun search(query: String): List<Place> =
        api.call("/api/v1/geo/search?q=" + query.trim())
}

/** **موضعٌ باسمه** — كما يردّه المحرّك (`geo.Place`). */
@Serializable
data class Place(
    val label: String = "",
    val lat: Double = 0.0,
    val lng: Double = 0.0,
)
