package com.rahalgo.shared.net

import kotlinx.coroutines.sync.withLock

/**
 * ══════════════════════════════════════════════════════════════════════
 * **سلطةُ الوصل — رمزٌ صالحٌ قبل كلّ مصافحة** (`D19`)
 * ══════════════════════════════════════════════════════════════════════
 *
 * # العطب
 *
 * **`LiveSocket` كانت تقرأ `session.accessToken()` عند كلّ محاولة ولا
 * تجدّد أبداً.** **ورمزُ الوصول يعيش ربعَ ساعة** — **فإذا انتهى
 * وصاحبُه في نفقٍ أو في الخلفيّة**: تعود الشبكةُ فتُعاد المصافحةُ
 * **بالرمز المنتهي نفسِه**، فتُردّ، فتُضاعَف المهلة، **فتُعاد بالرمز
 * المنتهي نفسِه إلى الأبد.**
 *
 * **وعائلةُ التجديد سليمةٌ طوالَ ذلك** — **والتطبيقُ مفتوحٌ صامتٌ
 * وصاحبُه يظنّه يعمل**، **ولا مخرجَ إلّا خروجٌ ودخولٌ من يده.**
 *
 * # ولماذا المنتهى لا الاستثناء
 *
 * **المصافحةُ الفاشلةُ لا تقول رقمَها في حقل**: قِيس (دورةُ ٥٨) أنّ
 * **٤٠١ ترمي `WebSocketException` و٤٠٣ و٥٠٣ ترميان
 * `ProtocolException`** — **والرقمُ في نصّ الرسالة.** **وقرارُ أمنٍ
 * يُبنى على مطابقة نصٍّ يتبدّل بتبديل محرّكِ الشبكة.**
 *
 * **والمحرّكُ يقول المنتهى صراحةً** (`access_expires_at`) — **فهو
 * السلطة.**
 *
 * # ولا تجديدَ عند كلّ انقطاع
 *
 * **الانقطاعُ ليس انتهاءً**: نفقٌ · تبديلُ شبكة · إقلاعُ خادم ·
 * سكونٌ. **ومن جدّد عند كلّ انقطاعٍ أغرق بابَ التجديد**، **ودوّر
 * رمزَ تجديدٍ لا حاجةَ إلى تدويره** — **وكلُّ تدويرٍ فرصةُ سباق.**
 *
 * **فلا يُجدَّد إلّا إذا قال المنتهى إنّه انتهى.**
 *
 * # والمحظورُ والمُبطَلُ لا يدوران
 *
 * **حسابٌ حُظر أو جلسةٌ أُبطلت رمزُها لم ينتهِ بعدُ** — **فلا تجديدَ
 * لهما أصلاً**: تُردّ المصافحةُ وتتضاعف المهلةُ إلى سقفها.
 * **فالحلقةُ تهدأ ولا تطرق بابَ التجديد.**
 */
class RealtimeAuth(
    private val session: SessionStore,
    /**
     * **التجديدُ من مالكه لا نسخةٌ عنه** — `ApiClient.refresh`.
     *
     * **وهو وحدَه يملك القفلَ ورايةَ «جدّده غيري»** (٢٠٢٦-٠٨-١٣):
     * **ومن كتب نداءَ `/auth/refresh` ثانياً للبثّ** أعاد السباقَ
     * الذي طرد سائقاً وهو على الدرّاجة.
     */
    private val refresher: suspend () -> Unit,
    private val now: () -> Long = { System.currentTimeMillis() },
) {

    /**
     * **يردّ رمزاً صالحاً للمصافحة** — **ويجدّد مرّةً واحدةً إن لزم.**
     *
     * **ويُقرأ الرمزُ بعد التجديد لا قبله** — **وهو موضعُ العطب
     * الثاني**: **من التقط الرمزَ ثمّ جدّد، صافح بالقديم وقد صار في
     * المخزن جديد.**
     */
    suspend fun tokenForConnect(): String {
        if (expired()) {
            gate.withLock {
                // ══════════════════════════════════════════════════════
                // **ويُسأل المنتهى ثانيةً تحت القفل**
                // ══════════════════════════════════════════════════════
                //
                // **قِيس (دورةُ ٥٨): بلا هذه، اثنتان وعشرون جولةً من
                // مئةٍ دوّرت رمزَ التجديد مرّتين.**
                //
                // **والسببُ أنّ السؤالَ كان خارجَ القفل**: **من سأل
                // فوجده منتهياً ثمّ نام حتّى جدّده غيرُه، يستيقظ
                // فيجدّد ثانيةً** — **ورايةُ «جدّده غيري» في
                // `ApiClient` تقارن بما رآه هو، ومن قرأ بعد التجديد
                // رأى الجديدَ فظنّه لم يتبدّل.**
                //
                // **وكلُّ تدويرٍ زائدٍ يُبطل رمزاً قد يحمله نداءٌ
                // آخر** — **وذاك سباقُ ٢٠٢٦-٠٨-١٣ بعينه.**
                if (expired()) {
                    // **وتعثّرُ التجديد لا يمنع المحاولة** — **قد
                    // يكون انقطاعَ شبكةٍ لا رفضَ سلطة**،
                    // **والمصافحةُ تحكم.**
                    runCatching { refresher() }
                }
            }
        }
        return session.accessToken()
    }

    /**
     * **بابُ البثّ إلى التجديد** — **لا يدخله اثنان معاً.**
     *
     * **ولا يُغني عنه قفلُ `ApiClient`**: **ذاك يمنع نداءين
     * متزامنين، وهذا يمنع نداءً لا حاجةَ إليه أصلاً.**
     */
    private val gate = kotlinx.coroutines.sync.Mutex()

    /**
     * **أانتهى رمزُ الوصول؟** — **بحسب ما قاله مُصدِرُه.**
     *
     * **وصفرٌ يعني لا يُعرف ⇒ لا تجديد**: **الجهلُ يُبقي السلوكَ
     * القديمَ ولا يخترع نداءً.**
     */
    fun expired(): Boolean {
        val at = session.accessExpiresAt()
        if (at == 0L) return false
        return now() >= at - SKEW_MS
    }

    private companion object {
        /**
         * **وهامشٌ قبل المنتهى** — **ساعةُ الجهاز ليست ساعةَ
         * المحرّك**، **ورمزٌ ينتهي وهو في الطريق يُردّ.**
         */
        const val SKEW_MS = 30_000L
    }
}
