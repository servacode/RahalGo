package com.rahalgo.shared.net

import io.ktor.client.plugins.websocket.WebSockets
import io.ktor.client.plugins.websocket.webSocket
import io.ktor.websocket.Frame
import io.ktor.websocket.readText
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Job
import kotlinx.coroutines.delay
import kotlinx.coroutines.isActive
import kotlinx.coroutines.launch

/**
 * ══════════════════════════════════════════════════════════════════════
 * **البثّ الحيّ — الشاشة تتحدّث بنفسها**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (`GET /api/v1/ws?token=…` — والمحرّك يشترك للسائق في موضوعين:
 * `drivers:queue` أي «الطابور تغيّر»، و`driver:<id>` أي «طلبك تغيّر».)
 *
 * # ولماذا مع الدفع لا بدلا منه
 *
 * **الدفع يوقظ الجيب المغلق، والبثّ يحدّث الشاشة المفتوحة.** ومن اكتفى
 * بالدفع **أبقى القائمة على حالها والتطبيق أمام عين صاحبه**، فيرى طلبا
 * أخذه غيره ويضغطه فيُقال له «سبقك غيرك».
 *
 * # والحمولة لا تُقرأ
 *
 * **المحرّك يرسل إشارة لا محتوى** («تغيّر شيء») — **وما يراه كلّ سائق
 * تقرّره نقطة الطابور** بحسب ورديّته ونمط التوزيع. **ومن بنى القائمة من
 * الحمولة** بنى نسخة ثانية من قواعد لا يملكها.
 *
 * # ويعيد الوصل بنفسه
 *
 * **الاتّصال ينقطع كثيرا**: نفق، أو تبديل شبكة، أو نوم الجهاز. **ومن لم
 * يُعد الوصل** بقي التطبيق مفتوحا وصامتا — وهو أسوأ من مغلق: **صاحبه
 * يظنّه يعمل.**
 *
 * **والمهلة تتضاعف** — فلا يُستنزف الجهاز بمحاولةٍ كلّ ثانية حين يكون
 * الخادم نائما.
 */
class LiveSocket(
    private val baseUrl: String,
    private val client: String,
    /**
     * ══════════════════════════════════════════════════════════════════
     * **وسلطةُ الرمز قبل المصافحة** — `D19`
     * ══════════════════════════════════════════════════════════════════
     *
     * **وكانت الحلقةُ تقرأ المخزنَ مباشرةً ولا تجدّد** — **فرمزٌ
     * انتهى يُعاد به الوصلُ أبداً** (`RealtimeAuth`).
     *
     * **ولا قيمةَ افتراضيّةَ له**: **مُعينٌ صامتٌ يُعيد العطبَ في
     * موضعٍ يُنسى** — **والمترجِمُ يسأل عنه في كلّ موضعِ بناء.**
     */
    private val auth: RealtimeAuth,
    /**
     * **ومهلتا التراجع تُحقَنان لتُقاسا** — **وقيمتاهما في الإنتاج
     * كما كانتا**: ثانيتان ثمّ تضاعفٌ إلى ثلاثين.
     *
     * **ولا يُقاس تراجعٌ بانتظاره حقيقةً**: **مئةُ جولةِ تعافٍ
     * بثانيتين لكلٍّ ثلاثُ دقائقَ من غير فائدة** — **والمقيسُ هو
     * الرمزُ المعروضُ وعددُ التجديدات لا طولُ النوم.**
     */
    private val firstRetryMs: Long = FIRST_RETRY_MS,
    private val maxRetryMs: Long = MAX_RETRY_MS,
) {

    private val http = io.ktor.client.HttpClient {
        install(WebSockets) {
            // ══════════════════════════════════════════════════════════
            // **نبضٌ يكشف الوصلةَ الميتةَ في زمنٍ محدود** (CUST-DEF-012)
            // ══════════════════════════════════════════════════════════
            //
            // **المقبسُ طويلُ العمرِ لا مهلةَ قراءةٍ له**: خادمٌ يسقط
            // بلا FIN يُبقي القراءةَ معلّقةً بلا حدّ، **فيبقى خيطُ العرضِ
            // في الخريطة عالقاً على شبكةٍ ميتة** — وهو ما أطال تجمّدَ
            // `nativeReset` عند الفصل.
            //
            // **نبضُ WebSocket الأصليّ (ping/pong)** — آليّةُ Ktor نفسِها،
            // لا مهلةَ HTTP: يرسل إطارَ ping كلَّ ٢٠ث، **وغيابُ pong
            // ضمنَ المهلة يُغلق الوصلةَ الميتةَ** فتعيد الحلقةُ الوصلَ.
            // **وعشرون ثانيةً كريمةٌ**: لا تُثقل وصلةً سليمةً ولا تقطعها،
            // **وتكشف الميتةَ في نحو نصفِ دقيقة.**
            //
            // **والخاصّيّةُ `pingIntervalMillis` محقَّقةٌ على Ktor 3.5.2 عينِها**
            // (`WebSockets$Config.setPingIntervalMillis(long)` في
            // `ktor-client-core-jvm-3.5.2.jar`) — لا `pingInterval` (غيرُ موجودة).
            pingIntervalMillis = 20_000L
        }
    }

    private var job: Job? = null

    /**
     * يبدأ الإصغاء — **و`onEvent` تُنادى عند كلّ إشارة.**
     *
     * **وتُنادى مرّة واحدة لكلّ حياة شاشة** — والبدء مرّتين يفتح وصلتين.
     */
    fun start(
        scope: CoroutineScope,
        // **وحال الوصلة يُرى** — «لا انهيار» ليس دليل اتّصال: **وصلة
        // صامتة تبدو كوصلة هادئة**، ولا يُعرف الفرق إلّا بأثر.
        onState: (Boolean) -> Unit = {},
        onEvent: () -> Unit,
    ) {
        if (job?.isActive == true) return
        job = scope.launch {
            var wait = firstRetryMs
            while (isActive) {
                try {
                    // **والتوكن في الرابط لا في ترويسة** — مقبس الويب لا
                    // يحمل ترويسة تفويض في المتصفّح، **والمحرّك يقرأه من
                    // الاستعلام** (`ws.go`).
                    // **والرمزُ يُطلب لا يُقرأ** — **فإن انتهى جُدّد
                    // مرّةً، ثمّ يُقرأ الجديدُ من المخزن** (`D19`).
                    //
                    // **وداخلَ الحلقة لا خارجَها**: **ملتقَطٌ فوقها
                    // يبقى قديماً بعد التجديد** — **فيُجدَّد المخزنُ
                    // وتُصافح الحلقةُ بالقديم أبداً.**
                    val token = auth.tokenForConnect()
                    val url = baseUrl.replace("https://", "wss://").replace("http://", "ws://") +
                        "/api/v1/ws?token=" + token
                    http.webSocket(url) {
                        wait = firstRetryMs
                        onState(true)
                        for (frame in incoming) {
                            if (frame is Frame.Text) {
                                frame.readText()
                                onEvent()
                            }
                        }
                    }
                } catch (e: CancellationException) {
                    // ══════════════════════════════════════════════════
                    // **وإلغاءُ النطاق ليس انقطاعَ وصل**
                    // ══════════════════════════════════════════════════
                    //
                    // **وهو أخطرُ من عرضه رسالةً**: لو ابتُلع هنا
                    // **لَمضت الحلقةُ تنتظر ثمّ تعيد الوصل** بعد أن
                    // أُغلقت الشاشةُ وأُتلف نموذجُها — **مقبسٌ حيٌّ بلا
                    // صاحب** يستنزف البطّاريّةَ ويعدّه الخادمُ متّصلاً.
                    //
                    // (كشفه `check-cancellation.mjs` ٢٠٢٦-٠٨-١٨ لحظةَ
                    //  كتابته، وهو موضعٌ لم يُشكَ منه بعد.)
                    throw e
                } catch (e: Exception) {
                    // **وانقطاع الوصل ليس عطبا** — يقع كلّ يوم عشرات
                    // المرّات، **ولا يُكتب في السجلّ كخطأ** فيغرقه.
                }
                onState(false)
                delay(wait)
                wait = (wait * 2).coerceAtMost(maxRetryMs)
            }
        }
    }

    fun stop() {
        job?.cancel()
        job = null
    }

    private companion object {
        const val FIRST_RETRY_MS = 2_000L
        const val MAX_RETRY_MS = 30_000L
    }
}
