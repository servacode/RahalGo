package com.rahalgo.shared.net

/**
 * ══════════════════════════════════════════════════════════════════════
 * **متى تكون الجلسةُ قد ماتت — مصنِّفٌ واحدٌ للتطبيقات الأربعة**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (بلاغُ المالك ٢٠٢٦-١٠-١٦: دخل بحساب المتجر من جهازٍ ثانٍ، **فبقي
 *  الأوّلُ يعرض «مغلق» والمتجرُ مفتوح** — والسحبُ وإعادةُ الفتح لا تفعل
 *  شيئاً، **ولا أحدَ قال له إنّه خرج.**)
 *
 * # الفرقُ بين «ماتت» و«تعثّرت»
 *
 * **ماتت**: المحرّكُ رفض الجلسةَ نفسَها — ٤٠١ بعد أن فشل التجديد، أو
 * رمزٌ صريحٌ يقول ذلك (`session_superseded` · `invalid_refresh` ·
 * `unauthorized` · `user_blocked` · `user_suspended`) أو حسابٌ لم يعد
 * بصفةِ هذا التطبيق. **فلا نداءَ بعدها يُصلحها** — والصوابُ خروجٌ ظاهرٌ
 * برسالة.
 *
 * **تعثّرت**: ٥٠٣ `auth_unavailable` · ٥٠٠ · ٤٢٩ · ٤٠٣ `forbidden` ·
 * تبديلُ كلمةٍ مطلوب · نسخةٌ قديمة. **المحرّكُ لم يقل «جلستُك ميّتة»** —
 * **ومن طُرد على عطلِ خادمٍ لحظيٍّ أُخرج والطلبُ في يده.**
 *
 * # و`not_signed_in` ليست موتاً
 *
 * **يرميها الجهازُ نفسُه لا المحرّك** — حين لا توكنَ أصلاً (ضيفٌ أو جلسةٌ
 * مُسحت). **ولا جلسةَ هناك تُنهى**: الزائرُ يتصفّح بها كلَّ يوم.
 *
 * # ولماذا هنا لا في `:ui`
 *
 * **`ApiClient` يحتاجه في لحظة فشل التجديد**، **والواجهةُ تحتاجه عند
 * الإقلاع** — ومصنِّفان يفترقان يومَ يُصحَّح أحدُهما. **ودالّةٌ صافيةٌ بلا
 * أندرويد** فيقيسها فحصٌ بلا جهاز.
 */
object SessionFailure {

    /** **الرموزُ التي تقول «الجلسةُ انتهت» بصريحها** — أيّاً كان رقمُ الحال. */
    val ENDING_CODES: Set<String> = setOf(
        "session_superseded",
        "invalid_refresh",
        "unauthorized",
        "user_blocked",
        "user_suspended",
        // **حسابٌ فقد صفةَ هذا التطبيق** — يرفض المحرّكُ تجديدَه (٢٠٢٦-١٠-٠١).
        "not_merchant_account",
        "not_rep_account",
        "not_driver_account",
    )

    /** **رمزُ الجهاز حين لا توكنَ أصلاً** — ليس رفضاً من المحرّك. */
    const val NOT_SIGNED_IN = "not_signed_in"

    /** **رمزُ «دخلتَ من جهازٍ آخر»** — له رسالتُه الصريحة. */
    const val SUPERSEDED = "session_superseded"

    /**
     * **أهذا الفشلُ ينهي الجلسة؟**
     *
     * **٤٠١ من المحرّك موتٌ دائماً** (بعد أن فشل التجديد) — **والرمزُ
     * الصريحُ موتٌ بأيّ رقم.** وما عداهما تعثّرٌ يمرّ.
     */
    fun endsSession(status: Int, code: String): Boolean {
        if (code == NOT_SIGNED_IN) return false
        return status == 401 || code in ENDING_CODES
    }

    /**
     * **سببُ الخروج للعرض** — **ويُفضَّل «جهازٌ آخر»** من أيّ الإشارتين
     * ظهر: رفضُ رمزِ الوصول أوّلاً، أو ردُّ التجديد. **ويبقى ظاهراً ولو
     * زالت مرآةُ Redis** — ردُّ التجديد يحمله من القاعدة.
     */
    fun reason(first: String, refresh: String): String =
        if (first == SUPERSEDED || refresh == SUPERSEDED) SUPERSEDED else refresh.ifEmpty { first }
}
