package com.rahalgo.shared.customer

import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow

/**
 * ══════════════════════════════════════════════════════════════════════
 * **من أين يتسوّق — نقطةٌ واحدةٌ تسأل عنها كلُّ نداءات التصفّح**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (قرارُ المالك ٢٠٢٦-٠٨-٢٠: «مو معقول شخصٌ بالشام يطلب من الرقّة».)
 *
 * # ولماذا موضعٌ واحدٌ لا وسيطٌ في كلّ نداء
 *
 * **نداءاتُ التصفّح خمسةٌ في أربع شاشات** — الرئيسيّةُ والأقسامُ والبحثُ
 * والعروضُ والمدن. **ووسيطٌ يُمرَّر في خمسةٍ يُنسى في السادس**، فتُعرض
 * شاشةٌ واحدةٌ من سوقٍ آخر **ولا يظهر ذلك في أيّ خطأ.**
 *
 * # وترتيبُ ما يُصدَّق
 *
 *     المدينةُ التي اختارها بيده   إن اختار — **واختيارُه يسبق كلَّ حَدْس**
 *       ↓ وإلّا عنوانُه الافتراضيّ   — حيث يستقبل طلباته فعلاً
 *         ↓ وإلّا موضعُ الجهاز       — لمن لم يحفظ عنواناً بعد
 *           ↓ وإلّا لا شيء          — **والخادمُ لا يُرشِّح**
 *
 * **ولا شيءَ تعني «أرِني كلَّ شيء» لا «لا تُرِني شيئاً»** — من فتح
 * التطبيقَ أوّلَ مرّةٍ ورفض الإذنَ يجب أن يرى سوقاً، **وشاشةٌ فارغةٌ
 * تُقرأ عطباً فيُحذف التطبيق.**
 *
 * # ومن يكتبها ليس من يقرؤها
 *
 * **يكتبها تطبيقُ الزبون** (يعرف العنوانَ والإذنَ والاختيار)،
 * **وتقرؤها `CustomerApi`** (لا تعرف شيئاً من ذلك). **وحاملٌ بينهما
 * أصدقُ من أن تعرف طبقةُ الشبكة ما هو حسابُ المستخدم.**
 */
object BrowseScope {

    private val _point = MutableStateFlow<Point?>(null)

    /** **تتغيّر فتُعيد الشاشاتُ سؤالَها** — انظر مَن يجمعها في التطبيق. */
    val point: StateFlow<Point?> = _point.asStateFlow()

    /**
     * **يضبط النقطةَ ويردّ أتغيّرت** — والمنادي يُعيد التحميل عند
     * التغيّر وحدَه.
     *
     * **وضبطٌ بالقيمة نفسِها لا يُعيد شيئاً**: يُنادى في كلّ دورةِ حياةٍ
     * وكلّ دورانِ جهاز، **ونداءٌ يُعيد التحميلَ في كلّ دورانٍ يستنزف
     * شبكةً على هاتفٍ في الرقّة.**
     */
    fun set(lat: Double?, lng: Double?): Boolean {
        val next = when {
            lat == null || lng == null -> null
            lat == 0.0 && lng == 0.0 -> null
            else -> Point(lat, lng)
        }
        if (_point.value == next) return false
        _point.value = next
        return true
    }

    /**
     * **ذيلُ الاستعلام** — `""` حين لا موضع.
     *
     * **والفاصلُ يُمرَّر لأنّ نصفَ النداءات فيها `?q=` ونصفَها لا** —
     * **و`?` مرّتين في مسارٍ واحدٍ يجعل الخادمَ يقرأ الثانيةَ جزءاً من
     * القيمة.**
     */
    fun query(sep: Char): String {
        val p = _point.value ?: return ""
        return "$sep" + "lat=${p.lat}&lng=${p.lng}"
    }

    data class Point(val lat: Double, val lng: Double)
}
