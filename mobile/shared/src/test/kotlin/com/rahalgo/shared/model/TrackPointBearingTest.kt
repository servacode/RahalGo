package com.rahalgo.shared.model

import kotlinx.serialization.json.Json
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * ══════════════════════════════════════════════════════════════════════
 * **عقدُ نقطة الأثر — والاتّجاهُ لا يضيع في الطابور**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (المرحلة ١، تصحيحُ المالك ٢٠٢٦-٠٨-٢٠: «GPS يحمل Bearing → لا توجد
 *  شبكة → Offline Queue → الشبكة تعود → Batch → **نفس Bearing
 *  الأصلي**».)
 *
 * # ولماذا يُختبر الطابورُ نصّاً لا كائنا
 *
 * **الطابورُ ملفُّ `points.jsonl` على القرص** — يُكتب اليومَ ويُقرأ
 * غداً بنسخةٍ أحدث. **فما يُختبر هو النصُّ المكتوبُ فيه**، لا الكائنُ
 * في الذاكرة.
 *
 * **وسطرٌ كُتب قبل أن يوجد الحقلُ يجب أن يُقرأ** — وإلّا خسر السائقُ
 * طابورَه كلَّه يومَ يحدّث تطبيقَه.
 */
class TrackPointBearingTest {

    /** **وهو الضبطُ نفسُه الذي في `PointQueue`** — لا نسخةٌ ثانية. */
    private val json = Json { ignoreUnknownKeys = true }

    private fun encode(p: TrackPoint) = json.encodeToString(TrackPoint.serializer(), p)
    private fun decode(s: String) = json.decodeFromString(TrackPoint.serializer(), s)

    // ══════════════════════════════════════════════════════════════════
    // **١ · الاتّجاهُ يصل إلى العقد**
    // ══════════════════════════════════════════════════════════════════

    @Test
    fun `الاتّجاهُ الصالحُ يُكتب باسمه في العقد`() {
        val line = encode(
            TrackPoint(lat = 35.9506, lng = 39.0094, at = "2026-08-20T10:00:00Z", bearingDeg = 137.5),
        )
        assertTrue("لم يُكتب باسم العقد: $line", line.contains("\"bearing_deg\":137.5"))
    }

    // ══════════════════════════════════════════════════════════════════
    // **٢ · ولا يُخترع حين يغيب**
    // ══════════════════════════════════════════════════════════════════

    /**
     * **وصفرٌ ليس فراغاً**: `Location.getBearing()` تردّ صفراً حين لا
     * اتّجاه، **ومن كتبها وجّه الدرّاجةَ شمالاً وهي واقفة.**
     */
    @Test
    fun `النقطةُ بلا اتّجاهٍ تبقى بلا اتّجاه`() {
        val p = TrackPoint(lat = 35.9506, lng = 39.0094, at = "2026-08-20T10:00:00Z")
        assertNull(p.bearingDeg)
        assertNull(decode(encode(p)).bearingDeg)
    }

    // ══════════════════════════════════════════════════════════════════
    // **٣ · ويبقى في الطابور حتّى تعود الشبكة**
    // ══════════════════════════════════════════════════════════════════

    @Test
    fun `الاتّجاهُ يعبر الكتابةَ والقراءةَ كما هو`() {
        val p = TrackPoint(
            lat = 35.9506, lng = 39.0094, at = "2026-08-20T10:00:00Z",
            speedMps = 11.2, accuracyM = 6.0, bearingDeg = 271.25,
        )
        val back = decode(encode(p))
        assertEquals(p, back)
        assertEquals(271.25, back.bearingDeg!!, 1e-9)
    }

    // ══════════════════════════════════════════════════════════════════
    // **٤ · ونقطةٌ قديمةٌ بلا حقلٍ تُقرأ**
    // ══════════════════════════════════════════════════════════════════

    /**
     * **وهذا سطرٌ كتبته النسخةُ المنشورةُ اليوم حرفاً بحرف** — بلا
     * `bearing_deg`. **ومن كسره خسر طابورَ سائقٍ انقطعت شبكتُه ساعة.**
     */
    @Test
    fun `سطرٌ من نسخةٍ قديمةٍ يُقرأ ولا ينكسر`() {
        val old = """{"lat":35.9506,"lng":39.0094,"at":"2026-08-20T10:00:00Z",""" +
            """"speed_mps":9.0,"accuracy_m":8.0}"""
        val p = decode(old)
        assertEquals(35.9506, p.lat, 1e-9)
        assertEquals(9.0, p.speedMps!!, 1e-9)
        assertNull("اخترع اتّجاهاً لسطرٍ قديم", p.bearingDeg)
    }

    // ══════════════════════════════════════════════════════════════════
    // **٥ · وخليطٌ في الطابور نفسِه**
    // ══════════════════════════════════════════════════════════════════

    /**
     * **وهي الحالُ الواقعيّة**: الجهازُ يصمت عن الاتّجاه عند الوقوف،
     * **فطابورُ رحلةٍ فيها إشاراتُ مرورٍ خليطٌ بطبعه.**
     */
    @Test
    fun `طابورٌ فيه ما يحمل الاتّجاه وما لا يحمله`() {
        val lines = listOf(
            """{"lat":35.9506,"lng":39.0094,"at":"2026-08-20T10:00:00Z","bearing_deg":45.0}""",
            """{"lat":35.9510,"lng":39.0098,"at":"2026-08-20T10:00:20Z"}""",
            """{"lat":35.9514,"lng":39.0102,"at":"2026-08-20T10:00:40Z","bearing_deg":200.0}""",
        )
        val points = lines.map { decode(it) }
        assertEquals(3, points.size)
        assertEquals(45.0, points[0].bearingDeg!!, 1e-9)
        assertNull(points[1].bearingDeg)
        assertEquals(200.0, points[2].bearingDeg!!, 1e-9)
    }

    // ══════════════════════════════════════════════════════════════════
    // **٦ · وقيمةٌ شاذّةٌ تعبر ولا تكسر**
    // ══════════════════════════════════════════════════════════════════

    /**
     * **ولا تُنقَّح في الجهاز** — التنقيةُ في المحرّك (`cleanBearing`).
     *
     * **وحارسان لقاعدةٍ واحدةٍ يفترقان**: يُشدَّد أحدُهما ويُنسى الآخر،
     * **فيصير الجهازُ يرفض ما يقبله الخادمُ أو العكس.**
     *
     * **والذي لا يجوز هو أن تسقط النقطةُ كلُّها** — الموضعُ أهمُّ من
     * الاتّجاه.
     */
    @Test
    fun `قيمةٌ شاذّةٌ لا تكسر الكتابةَ ولا القراءة`() {
        for (bad in listOf(360.0, -1.0, 4000.0)) {
            val p = TrackPoint(lat = 35.9506, lng = 39.0094, at = "x", bearingDeg = bad)
            val back = decode(encode(p))
            assertEquals(bad, back.bearingDeg!!, 1e-9)
            assertEquals(35.9506, back.lat, 1e-9)
        }
    }
}
