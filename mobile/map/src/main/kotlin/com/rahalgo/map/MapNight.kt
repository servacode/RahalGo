package com.rahalgo.map

/**
 * ══════════════════════════════════════════════════════════════════════
 * **الخريطةُ ليلاً — تحويلُ ألوانٍ لا نمطٌ ثانٍ**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (طلبُ المالك ٢٠٢٦-٠٨-٢٥: «مشكلة الثيم الغامق… طبّقها كلَّها، برأيي
 *  أفضلُ واحترافيٌّ أكثر — نتأخّر ساعةً أحسنُ ما نخسر عملاءَ بسبب هذه
 *  الأخطاء».)
 *
 * # ولماذا تحويلٌ لا ملفٌّ ثانٍ
 *
 * **ونمطان في المستودع يفترقان يومَ يُضاف طبقة** — والنهاريُّ يكبر
 * والليليُّ يشيخ. **وقد وقع ذلك في هذا المشروع مرّاتٍ**: وثيقتان
 * تتناقضان صامتتين.
 *
 * **والبنيةُ واحدةٌ في الحالين** — خمسٌ وعشرون طبقةً بترتيبها ومرساتها
 * وفلاترها. **والفرقُ ألوانٌ لا غير**، فيُبدَّل ما يتبدّل وحدَه.
 *
 * # وليست عكساً حسابيّاً
 *
 * **وعكسُ اللون رياضيّاً يُخرج خريطةً مريضة**: الماءُ يصير برتقاليّاً
 * والخضرةُ بنفسجيّة. **فلكلّ لونٍ نظيرُه المختار** — يحفظ معناه
 * (ماءٌ أزرقُ وخضرةٌ خضراء) ويخفض ضوءه.
 *
 * # والشوارعُ تبقى أفتحَ من الأرض
 *
 * **وهي القاعدةُ التي تجعل خريطةً ليليّةً تُقرأ**: الأرضُ أغمقُ ما
 * فيها، **والشارعُ يعلو عليها بدرجتين** — كما يفعل غوغل وأوبر.
 */
object MapNight {

    /**
     * **الألوانُ النهاريّةُ ونظائرُها الليليّة.**
     *
     * **ومقيسةٌ من النمط نفسِه** — واحدٌ وثلاثون لوناً (٢٠٢٦-٠٨-٢٥).
     */
    private val PAIRS = mapOf(
        // ── الأرضُ والاستعمال ────────────────────────────────────────
        "#F1ECE3" to "#12161C", // الأرضُ العامّة
        "#E8E1D6" to "#171C24", // سكنيّ
        "#E9E3DE" to "#191D25", // صناعيٌّ وتجاريّ
        "#DFE6D5" to "#16201A", // غطاءٌ نباتيّ
        "#CFDFBC" to "#19291D", // خضرةٌ ومقابرُ وملاعب
        "#C8DCB4" to "#1B2D1F", // حدائق
        // ── الماء ────────────────────────────────────────────────────
        "#A4C6DA" to "#16344A",
        "#EAF3F8" to "#0E1A24", // هالةُ اسم الماء
        "#3F6D88" to "#7FB3D0", // اسمُ الماء
        // ── البناء ───────────────────────────────────────────────────
        "#DCD4C8" to "#1E242C",
        // ── حوافُّ الشوارع ───────────────────────────────────────────
        // **والحافّةُ أغمقُ من الشارع ليلاً كما هي أغمقُ نهاراً** —
        // فيبقى الشارعُ بارزاً لا ذائبا.
        "#DCD3C3" to "#0D1116", // حافّةُ الفرعيّ
        "#D9C89A" to "#2A2417", // حافّةُ الثانويّ
        "#D9A63C" to "#4A3411", // حافّةُ الرئيسيّ
        // ── ألوانُ الشوارع ───────────────────────────────────────────
        // **وتبقى أفتحَ من الأرض بدرجتين** — وهي قاعدةُ قراءة الخريطة
        // ليلاً.
        "#FFFFFF" to "#39414C", // فرعيّ
        "#FFF6DE" to "#4A4636", // ثانويّ
        "#F6C96B" to "#6B5424", // رئيسيّ
        "#CFC5B2" to "#2B3038", // ممرّاتُ مشاة
        "#B9AE9B" to "#2E3239", // سكّةُ حديد
        // ── الحبرُ والأسماء ──────────────────────────────────────────
        "#3A342A" to "#E8EAED", // اسمُ المدينة
        "#4A4438" to "#C6CBD2", // اسمُ الشارع
        "#5A5245" to "#AEB4BC", // اسمُ الحيّ والمعلم
        "#6A6152" to "#989EA7", // معالمُ ثانويّة
        // ── نقاطُ المعالم ────────────────────────────────────────────
        "#D9713C" to "#E08A5C", // مطاعم
        "#C9962F" to "#D6AA55", // متاجر
        "#3E8A5B" to "#57A87A", // مصارف
        "#5A8F4A" to "#77AC66", // حدائق
        "#7A5FA8" to "#9A82C4", // فنادق
        "#5B7DA8" to "#7A9CC6", // مواصلات
        "#A79C88" to "#7C8189", // ما لا يُصنَّف
        "#8A7F6C" to "#868C95", // افتراضيّ
    )

    /**
     * **يحوّل نمطاً نهاريّاً إلى ليليّ.**
     *
     * **والتبديلُ نصّيٌّ على JSON المربوط** — بعد أن حُقنت فيه عناوينُ
     * البلاطات والحروف، **فلا يُعاد تحليلُ الملفّ ولا تُلمس بنيتُه.**
     *
     * **وهالةُ النصّ تُقلب معه**: كانت بيضاءَ حول حبرٍ داكن، **فتصير
     * داكنةً حول حبرٍ فاتح** — وإلّا صار حول كلّ اسمٍ ضوءٌ يعمي.
     */
    fun apply(json: String): String {
        var out = json
        for ((day, night) in PAIRS) {
            out = out.replace("\"$day\"", "\"$night\"")
        }
        // **وهالةُ الأسماء** — أُخّرت لأنّ الأبيضَ استُعمل للشوارع أيضاً،
        // وقد بُدّل قبلها.
        out = out.replace("\"text-halo-color\": \"#39414C\"", "\"text-halo-color\": \"#0B0E12\"")
        out = out.replace("\"text-halo-color\":\"#39414C\"", "\"text-halo-color\":\"#0B0E12\"")
        return out
    }
}
