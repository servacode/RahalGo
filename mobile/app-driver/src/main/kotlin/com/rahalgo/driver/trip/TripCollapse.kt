/**
 * ══════════════════════════════════════════════════════════════════════
 * **شريطان مستقلّان — لكلٍّ مقبضُه**
 * ══════════════════════════════════════════════════════════════════════
 *
 * **(تصحيحُ المالك ٢٠٢٦-٠٩-٠١:** «الشريطُ العلويُّ لا علاقةَ له بالشريط
 * السفليّ · هناك الآن ربطٌ بينهما وهذا غلط · **لازم كلُّ شريطٍ منفصلٌ
 * عن الثاني**».)
 *
 * **وجعلتُهما حالاً واحدةً بالأمس** — فمن طوى الأعلى طوى الأسفلَ معه.
 * **وهما شيئان**: الأعلى يقول **أين صار من الرحلة**، والأسفلُ يقول
 * **ما يفعله الآن**. **ومن أراد أن يُخفي أحدَهما لا يريد الآخر.**
 *
 * # ولماذا هنا لا في الشاشة
 *
 * **اللوحتان في دالّتين لا تعرف إحداهما الأخرى** — ورفعُ الحال إلى
 * أمّهما يمرّ بستّة توقيعات. **وهي حالُ عرضٍ لا حالُ عمل**: لا تُحفظ
 * ولا تُرسل، وتموت مع الرحلة.
 */
internal object TripCollapse {
    /** **شريطُ المراحل الأعلى.** */
    var top by mutableStateOf(true)

    /**
     * **بطاقةُ الطلب السفلى — ومعها أزرارُ المرحلة وشريطُ التبويبات.**
     *
     * **(طلبُ المالك ٢٠٢٦-٠٩-٠١:** «وقتَ ننزّله للأسفل يجب أن تختفي
     * معه حتّى أزرارُ الرحلة والطلبات ولوحتي وحسابي، **لتكون شاشةً
     * كبيرةً للخرائط**».)
     *
     * **وشريطُ التبويبات يأخذ عرضَ الشاشة وارتفاعَ إصبع** — ومن طوى
     * بطاقتَه ليرى الطريقَ **وجده باقياً يقضم أسفلَها.**
     */
    var bottom by mutableStateOf(true)
}
