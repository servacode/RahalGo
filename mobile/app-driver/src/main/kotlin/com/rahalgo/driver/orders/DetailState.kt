package com.rahalgo.driver.orders

import com.rahalgo.shared.model.DriverOrder
import com.rahalgo.shared.model.FailReasonItem

/**
 * ══════════════════════════════════════════════════════════════════════
 * **حالُ الطلب المفتوح — تقرؤه شاشةُ الرحلة**
 * ══════════════════════════════════════════════════════════════════════
 *
 * **وكانت معها شاشةُ تفصيلٍ ثانيةٌ (`OrderDetailScreen`) لا تُفتح من أيّ موضع**
 * (حُذفت ٢٠٢٦-١٠-٠٢) — بنافذة «تعذّر» ثانيةٍ وزرّ إعادةٍ بلا تأكيد. **وشاشةٌ ميّتةٌ
 * تُصلَح فيها الأشياءُ فيُظنّ أنّها أُصلحت** (كتبت «لدي توصيلة» فيها وحدَها). فبقي
 * الحالُ وذهبت الشاشة.
 */
data class DetailState(
    val order: DriverOrder,
    val busy: Boolean = false,
    val error: String = "",
    /** أسباب التعذّر المعروضة الآن — **وفارغ يعني لا سؤال مفتوح.** */
    val failReasons: List<FailReasonItem>? = null,
    /** **سقط تحميلُ الخيارات** — يُقال ويُعاد، ولا يُفتح الطارئُ بدلَه. */
    val problemError: String = "",
    /** **متى حُمّلت** — منها يُعدّ انتظارُ الباب. */
    val reasonsAtMs: Long = 0L,
    /** **حالُ الطلب حين فُتحت** — يقرّر لفظَ «مشكلتي»: إعادةٌ قبل الاستلام وطارئٌ بعده. */
    val problemStatus: String = "",
    /** **خبرٌ لا خطأ** — «وصل بلاغُك للإدارة». */
    val notice: String = "",
    /**
     * **لأيّ طلبٍ وأيّ مرحلةٍ قيل الخبر** — `id/status` (بلاغُ المالك ٢٠٢٦-١٠-٠٣: «وصل بلاغك
     * للإدارة» ظهرت على طلبٍ جديدٍ لم يُبلَّغ عنه). **فيُعرض لصاحبه في مرحلته وحدَها.**
     */
    val noticeFor: String = "",
)
