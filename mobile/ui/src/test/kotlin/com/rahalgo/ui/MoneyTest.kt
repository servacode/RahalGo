package com.rahalgo.ui

/**
 * **طبقةُ الوحدة — صياغةُ المال والمسافة والزمن.**
 *
 * المعرّفات: `FMT-*` · الوسم: `@unit @critical`
 *
 * (قرارُ المالك ٢٠٢٦-٠٨-١٩: «إذا كان شيءٌ يمكن أتمتتُه فقُم بأتمتته…
 *
 *  لا تطلب منّي اختبارَ ٦٢٪ من التطبيق بيدي».)
 *
 * # لماذا يبدأ هنا
 *
 * **هذه أوّلُ اختبارٍ في تاريخ التطبيق** — كان فيه صفرٌ حتّى اليوم.
 * **والصياغةُ منطقٌ نقيٌّ بلا شاشةٍ ولا شبكة**، فتُقاس بلا جهاز.
 *
 * # وما تحرسه فعلاً
 *
 * **كلُّ رقمٍ يراه الزبونُ يمرّ من هنا** — السعرُ والأجرةُ والإجماليّ.
 * **وفاصلةٌ في غير موضعها تجعل ٢٣٠ تُقرأ ٢٣٠٠**، وهو خطأٌ صامتٌ لا
 * يُسقط شيئاً ويُغيّر كلَّ شيء.
 */
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

class MoneyTest {

    /** FMT-001 **الآحادُ والعشراتُ والمئاتُ بلا فاصلة.** */
    @Test
    fun `المبالغُ الصغيرةُ بلا فاصلة`() {
        assertEquals("0 ل.س", money(0))
        assertEquals("7 ل.س", money(7))
        assertEquals("80 ل.س", money(80))
        assertEquals("230 ل.س", money(230))
        assertEquals("999 ل.س", money(999))
    }

    /**
     * FMT-002 **والألوفُ تُفصَل — وهنا يقع الخطأُ الصامت.**
     *
     * **ورقمٌ بلا فاصلةٍ يُقرأ خطأً بمرتبة**: من رأى `12000` قرأها
     * `1200` في لمحة. **والفاصلةُ ليست زينة.**
     */
    @Test
    fun `الألوفُ مفصولةٌ بفاصلة`() {
        assertEquals("1,000 ل.س", money(1_000))
        assertEquals("12,000 ل.س", money(12_000))
        assertEquals("999,999 ل.س", money(999_999))
        assertEquals("1,000,000 ل.س", money(1_000_000))
    }

    /**
     * FMT-003 **والسالبُ يبقى سالباً بعلامته.**
     *
     * **ورصيدُ محفظةٍ سالبٌ حقيقيّ** — دَينٌ على سائقٍ أو حسمٌ زائد.
     * **ومن ابتلع الإشارةَ عرض الدَّينَ رصيدا.**
     */
    @Test
    fun `السالبُ يحتفظُ بإشارته`() {
        assertTrue("السالبُ فقد إشارته: ${money(-500)}", money(-500).startsWith("-"))
        assertEquals("-1,500 ل.س", money(-1_500))
    }

    /**
     * FMT-010 **والمسافةُ بالمتر تحت الكيلو وبالكيلو فوقه.**
     *
     * **و«١٢٠٠ متر» تُقرأ أبعدَ من «١٫٢ كم»** وهي هي — والوحدةُ
     * الصحيحةُ تختصر الحكم.
     */
    @Test
    fun `المسافةُ تتبدّلُ وحدتُها عند الكيلو`() {
        assertTrue("دون الكيلو يجب أن تكون متراً: ${dist(300.0)}", dist(300.0).contains("م"))
        assertTrue("فوق الكيلو يجب أن تكون كم: ${dist(2_400.0)}", dist(2_400.0).contains("كم"))
    }

    /** FMT-011 **والصفرُ لا يُسقط الصياغة.** */
    @Test
    fun `الصفرُ في المسافةِ لا يكسر`() {
        assertTrue(dist(0.0).isNotEmpty())
    }

    /**
     * FMT-020 **وسرعةُ صفرٍ تعني «لا أعرف» لا صفرَ دقائق.**
     *
     * **والعقدُ المكتوب**: «فارغٌ إن لم يُعرف». **وشاشةٌ تقول ‏«~٠ د»
     * تعِد بوصولٍ فوريّ** — والصمتُ أصدقُ من رقمٍ مخترَع.
     *
     * **ولا قسمةَ على صفر** — الحارسُ قبل القسمة.
     *
     * (كُتب هذا الاختبارُ أوّلاً بتوقّعِ «نصٌّ غيرُ فارغ» فسقط،
     *  **وقراءةُ العقد صحّحت التوقّعَ لا الشيفرة.**)
     */
    @Test
    fun `سرعةُ صفرٍ تُعطي فارغا لا رقما`() {
        assertEquals("", etaText(5_000.0, 0))
        assertEquals("", etaText(5_000.0, -10))
        assertEquals("", etaText(-1.0, 30))
    }

    /** FMT-021 **والمقدَّرُ يطول بطول المسافة.** */
    @Test
    fun `الزمنُ يزيدُ بزيادةِ المسافة`() {
        val near = etaText(1_000.0, 30)
        val far = etaText(20_000.0, 30)
        assertTrue("المسافتان أعطتا النصَّ نفسَه: $near", near != far)
    }
}
