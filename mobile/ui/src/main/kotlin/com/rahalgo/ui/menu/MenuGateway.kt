package com.rahalgo.ui.menu

import com.rahalgo.shared.merchant.MediaRef

/**
 * ══════════════════════════════════════════════════════════════════════
 * **بابُ القائمة إلى المحرّك — ما يختلف بين التطبيقين**
 * ══════════════════════════════════════════════════════════════════════
 *
 * **المتجرُ يحرّر قائمتَه، والمندوبُ يحرّر قائمةَ عميله** — والنداءان
 * مختلفان (`/merchant/…` و`/rep/…`). **وما عدا ذلك واحد.**
 *
 * # ولماذا واجهةٌ لا وراثة
 *
 * **`MerchantApi` و`RepApi` صنفان لا يشتركان في أب** — ولا يصحّ أن
 * يشتركا: **لكلٍّ نقاطُه وصلاحيّاتُه.**
 *
 * **والواجهةُ تصف ما تحتاجه الشاشةُ لا ما يملكه المحرّك** — خمسةُ
 * أفعالٍ لا أكثر، **فمن أراد تطبيقاً ثالثاً كتب خمسةَ أسطر.**
 */
interface MenuGateway {

    /** **يحفظ صنفاً** — جديداً إن كان `itemId` فارغاً، وإلّا تعديلاً. */
    suspend fun save(draft: ItemDraft)

    /** **يحذف صنفاً.** */
    suspend fun delete(itemId: String)

    /** **يقلب توفّرَ صنف.** */
    suspend fun toggle(itemId: String, available: Boolean)

    /**
     * **يرفع صورةً ويعيد معرّفَها ومصغّرتَها.**
     *
     * **والمصغّرةُ تُعاد ولا تُرمى** — وإلّا رُسم الحرفُ الاحتياطيُّ بعد
     * رفعٍ ناجح، **فيُظنّ أنّ الصورةَ لم تُحفظ** (بلاغُ المالك ٢٠٢٦-٠٨-٢٩).
     */
    suspend fun uploadImage(bytes: ByteArray): MediaRef

    /** **يحوّل مساراً نسبيّاً إلى عنوانٍ كامل** — أو لا شيء. */
    fun media(path: String?): String?
}
