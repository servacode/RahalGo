package com.rahalgo.ui

import android.content.Context
import com.rahalgo.shared.auth.AuthApi
import com.rahalgo.shared.driver.AccountApi
import com.rahalgo.shared.driver.MeApi
import com.rahalgo.shared.net.ApiClient
import com.rahalgo.shared.net.LiveSocket
import com.rahalgo.shared.push.DevicesApi

/**
 * ══════════════════════════════════════════════════════════════════════
 * **وصلةُ التطبيق بالمحرّك — ما يستوي في كلّ تطبيق**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (قرارُ المالك ٢٠٢٦-٠٨-١٤: «هناك الكثيرُ من الأمور المشتركة بين كلّ
 *  التطبيقات، يجب أن تكون مركزيّةً فلا نبنيها بكلّ تطبيق».)
 *
 * # ما فيها وما ليس
 *
 * **الجلسةُ والعميلُ والدخولُ و`me` والحسابُ والأجهزةُ والبثُّ الحيّ** —
 * **يحتاجها الزبونُ كما يحتاجها السائق.** وما يخصّ دوراً بعينه
 * (`DriverApi` · طلباتُ السائق · دردشتُه) **يبقى في تطبيقه.**
 *
 * # ونسخةٌ واحدةٌ لا نسخةٌ لكلّ شاشة
 *
 * **كلُّ عميلٍ يفتح تجمّعَ اتّصالاتٍ خاصّا به**، وعشرُ شاشاتٍ تعني عشرةَ
 * تجمّعاتٍ تستنزف الذاكرةَ والبطّاريّة.
 *
 * **وأخطرُ منه أن يتصادم التجديد**: شاشتان تكتشفان انتهاءَ التوكن معاً
 * فتُجدّدان معاً، **والثانيةُ تُجدّد بتوكنٍ أبطلته الأولى** — فيخرج
 * صاحبُه وهو يعمل.
 */
class Core(context: Context, val baseUrl: String, val client: String) {

    val session = AndroidSession(context)
    val api = ApiClient(baseUrl, client, session)
    val auth = AuthApi(api)
    val me = MeApi(api)

    /** **إدارةُ الحساب** — الاسمُ والصورةُ وكلمةُ المرور والعناوين. */
    val account = AccountApi(api)
    val devices = DevicesApi(api)

    /** **البثّ الحيّ** — واحدٌ للتطبيق كلّه، لا واحدٌ لكلّ شاشة. */
    val live = LiveSocket(baseUrl, session, client)

    /**
     * ══════════════════════════════════════════════════════════════════
     * **عنوانُ ملفٍّ من المحرّك — من مسارٍ نسبيّ**
     * ══════════════════════════════════════════════════════════════════
     *
     * (شكوى المالك ٢٠٢٦-٠٨-١٣: «الصورة ما زالت حرف خ مع أنّني قمتُ برفع
     *  صورة».)
     *
     * **والمحرّكُ يرسل `/media/...` نسبيّا** — والشريطُ العلويُّ كان
     * يُكمله بيده، **وشاشةُ الحساب نسيت** فمرّرت المسارَ خاماً إلى
     * محمّل الصور. **فلا يُفتح، فتظهر الحرفُ الأوّلُ بدلَ الصورة** —
     * ولا خطأَ ولا سجلّ: **الصورةُ الاحتياطيّةُ تبتلع العطب.**
     *
     * **وموضعان يُكملان عنواناً واحداً** يفترقان يوماً — **وقد افترقا
     * في أوّل يوم.**
     */
    fun media(path: String?): String? =
        path?.takeIf { it.isNotEmpty() }?.let { if (it.startsWith("http")) it else baseUrl + it }
}

/**
 * ══════════════════════════════════════════════════════════════════════
 * **نواةُ التطبيق الجارية — تُركَّب مرّةً عند الإقلاع**
 * ══════════════════════════════════════════════════════════════════════
 *
 * # ولماذا مُسجَّلٌ لا وسيطٌ يُمرَّر
 *
 * **`AuthViewModel` يصنعها أندرويدُ لا نحن** (`viewModel()`)، **ولا
 * تُمرَّر إليها وسائط.** وصانعٌ خاصٌّ لكلّ تطبيقٍ يعني أن يكتب كلُّ
 * تطبيقٍ تركيبَه — **وهو عينُ ما نرفعه.**
 *
 * **والعنوانُ ونوعُ العميل يختلفان** (`android-driver` · `android-customer`)
 * **فلا يُكتبان هنا** — يُعطيهما التطبيقُ في إقلاعه.
 */
object AppCore {

    @Volatile private var wired: Core? = null

    /**
     * **ما يقع بعد أن يثبت الدخول** — تسجيلُ نقطة الإشعارات مثلاً.
     *
     * **ولا يقع قبله**: النقطةُ تحتاج توكنَ حساب، **ومن سجّلها قبل
     * الجلسة سجّلها بلا صاحب** فلا يصل إشعارٌ ولا يظهر خطأ.
     */
    @Volatile var afterSignIn: () -> Unit = {}
        private set

    /**
     * **يُنادى مرّةً في `Application.onCreate` أو أوّلِ استعمال.**
     *
     * **والثانيةُ لا تُبدّل الأولى**: عميلٌ ثانٍ يعني تجمّعَ اتّصالاتٍ
     * ثانياً وتجديداً يتصادم.
     */
    fun install(
        context: Context,
        baseUrl: String,
        client: String,
        afterSignIn: () -> Unit = {},
    ): Core =
        wired ?: synchronized(this) {
            wired ?: Core(context.applicationContext, baseUrl, client).also {
                wired = it
                this.afterSignIn = afterSignIn
            }
        }

    /** **النواةُ أو انفجار** — من طلبها قبل تركيبها أخطأ في إقلاعه. */
    fun get(): Core = wired
        ?: error("AppCore.install لم تُنادَ — النواةُ تُركَّب قبل أوّل شاشة")
}
