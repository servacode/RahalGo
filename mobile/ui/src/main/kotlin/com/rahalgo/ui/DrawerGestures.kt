package com.rahalgo.ui

import androidx.compose.material3.DrawerState
import androidx.compose.material3.DrawerValue
import androidx.compose.runtime.Composable
import androidx.compose.runtime.DisposableEffect
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableIntStateOf
import androidx.compose.runtime.setValue

/**
 * ══════════════════════════════════════════════════════════════════════
 * **سياسةُ إيماءةِ الدرج — موضعٌ واحدٌ للأربعة** (`DWR`، ٢٠٢٦-٠٩-١٤)
 * ══════════════════════════════════════════════════════════════════════
 *
 * # ما كان
 *
 * **بلاغُ المالك ٢٠٢٦-٠٩-٠١**: «عند سحب الخريطة تُفتح القائمةُ الجانبيّة
 * — بكلّ التطبيقات». **وحافّةُ الشاشة تلتقط السحبَ قبل الخريطة** — فمن
 * حرّك الخريطةَ فتح الدرجَ على نفسه، **ومن أراد أن يزيح الدبّوسَ وجد
 * قائمةً.**
 *
 * **فعُطِّلت الإيماءةُ عامّاً** في الأربعة، **وكُتب سببُ التعميم**:
 * «شرطٌ يُكتب لكلّ شاشةٍ يُنسى في الشاشة الخامسة». **وهو محقٌّ — ولذلك
 * ليس هذا شرطاً لكلّ شاشة.**
 *
 * # والقاعدةُ الواحدة
 *
 *	الدرجُ مفتوحٌ أو في طريقه    ⇒ الإيماءةُ مفتوحةٌ (ليُغلَق بسحبةٍ)
 *	خريطةٌ تفاعليّةٌ حاضرة        ⇒ إيماءةُ الفتح مقفلة
 *	وما سوى ذلك                 ⇒ الإيماءةُ مفتوحة
 *
 * **والدرجُ المفتوحُ مستثنىً بقصد**: **لا يُترَك أحدٌ محبوساً بدرجٍ لا
 * يُغلَق بالسحب** — **والخريطةُ خلفَ حاجبٍ حينها فلا تنازعَ على الإيماءة.**
 *
 * # ومن يُعلن؟ الخريطةُ لا الشاشة
 *
 * **وكلُّ سطحِ خريطةٍ تفاعليٍّ ينادي `MapGestureLock()` في مكوّنه
 * المشترك** (`MapCanvas` · `PickPoint`) — **فمن أضاف شاشةً سادسةً
 * بخريطةٍ نال القفلَ بلا أن يكتب سطراً.**
 *
 * # ولمَ كائنٌ واحدٌ للعمليّة لا حالٌ في الشجرة
 *
 * **ولكلّ تطبيقٍ قشرةٌ واحدةٌ ودرجٌ واحد** — **فحالٌ واحدةٌ للعمليّة
 * تصفُ الواقعَ بلا زيادة.**
 *
 * **وخريطةُ الزبون تُرسم خارجَ شجرة الدرج** (`AddressHost` يسبق
 * `ModalNavigationDrawer` ويعود قبله) — **فحالٌ تُزوَّد في شجرة الدرج
 * وحدَها لا تراها**، **وتزويدُها في موضعين يصنع سياستين تفترقان.**
 *
 * # ولمَ عدّادٌ لا رايةٌ ثنائيّة
 *
 * **وشاشتان بخريطتين قد تتراكبان لحظةَ الانتقال** — **ورايةٌ ثنائيّةٌ
 * تُطفئها الأولى وهي تختفي فتفتح القفلَ والثانيةُ حاضرة.** **والعدّادُ
 * لا يُخطئ**، **ويعود صفراً عند خروج آخرِ خريطةٍ فترجع الإيماءةُ بلا
 * إعادةِ تشغيلٍ ولا حالٍ عالقة.**
 */
object DrawerGestures {

    /** **عددُ أسطحِ الخريطة التفاعليّة الحاضرة الآن.** */
    var interactiveMaps by mutableIntStateOf(0)
        private set

    /** **أخريطةٌ تفاعليّةٌ تملك الإيماءةَ الآن؟** */
    val mapActive: Boolean get() = interactiveMaps > 0

    /**
     * enabledFor **أتُفتَح الإيماءةُ لهذا الدرج؟**
     *
     * **والمفتوحُ — أو المتوجّهُ إلى الفتح — يبقى قابلاً للإغلاق بالسحب.**
     */
    fun enabledFor(state: DrawerState): Boolean =
        state.currentValue == DrawerValue.Open ||
            state.targetValue == DrawerValue.Open ||
            !mapActive

    /** **تُنادى عند ظهور سطحِ خريطةٍ تفاعليّ.** */
    fun enterMap() {
        interactiveMaps += 1
    }

    /** **وعند اختفائه** — ولا تنزل تحت الصفر ولو اختلّ ترتيبُ الاستدعاء. */
    fun exitMap() {
        if (interactiveMaps > 0) interactiveMaps -= 1
    }

    /** **تُصفَّر في الفحوص وحدَها** — **ولا يناديها منتَج.** */
    fun resetForTest() {
        interactiveMaps = 0
    }
}

/**
 * MapGestureLock **يقفل إيماءةَ فتحِ الدرج ما دام هذا السطحُ حاضراً.**
 *
 * **ويُنادى في المكوّن المشترك للخريطة لا في الشاشة** — **فلا يُنسى.**
 *
 * **ويُفتَح القفلُ عند الخروج حتماً** (`onDispose`) — **ولو خرج
 * المستخدمُ برجوعٍ أو بتبديلِ تبويبٍ أو بانهيارِ تركيب** — **فلا حالَ
 * معطَّلةٌ دائمةٌ ولا حاجةَ إلى إعادة تشغيل.**
 */
@Composable
fun MapGestureLock() {
    DisposableEffect(Unit) {
        DrawerGestures.enterMap()
        onDispose { DrawerGestures.exitMap() }
    }
}
