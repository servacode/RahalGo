package com.rahalgo.ui

import com.google.firebase.crashlytics.FirebaseCrashlytics

/**
 * ══════════════════════════════════════════════════════════════════════
 * **تقاريرُ الانهيار — بابٌ واحدٌ إليها**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (قرارُ المالك ٢٠٢٦-٠٨-١٣: «نبدأ بالإغلاق واحدةً تلو الأخرى» — وهذه
 *  الثانية.)
 *
 * # لماذا قبل الإطلاق لا بعده
 *
 * **بعد الإطلاق، من سقط تطبيقُه في الرقّة لا يخبرك.** يفتحه فيُغلق،
 * فيفتحه ثانيةً، **ثمّ يتصل بالمكتب ويقول «التطبيق خربان»** — ولا أحدَ
 * يعرف أيَّ شاشةٍ ولا أيَّ سطر.
 *
 * **وسقوطٌ واحدٌ في يد سائقٍ يعني طلباً ضائعاً وزبوناً ينتظر.**
 *
 * # ولماذا غلافٌ لا نداءٌ مباشر
 *
 * **أربعةُ تطبيقاتٍ ستحتاجها** (السائق · المتجر · المندوب · الزبون) —
 * **وكلُّ شاشةٍ تنادي `FirebaseCrashlytics` مباشرةً تربط نفسَها بمزوّدٍ
 * بعينه.** ويومَ يُبدَّل يُفتح خمسون ملفّاً.
 *
 * # وما لا يُرسَل
 *
 * **لا رقمَ هاتفٍ ولا اسم** — المعرّفُ يكفي لربط التقرير بصاحبه في
 * لوحتك، **ورقمُ هاتفٍ في خدمةٍ خارجيّةٍ لا يعود.**
 *
 * **ولا انهياراتُ البناء التجريبيّ**: تلك انهياراتي أنا وأنا أعدّل،
 * **وتُختلط بها فتُقرأ الأرقامُ كاذبة** — عشرةُ سقوطٍ في التطوير تُقرأ
 * عشرةَ سائقين.
 */
object Crash {

    private val client: FirebaseCrashlytics? by lazy {
        runCatching { FirebaseCrashlytics.getInstance() }.getOrNull()
    }

    /**
     * **يُنادى مرّةً عند الإقلاع** — والتطبيقُ يُخبرها أتجريبيٌّ بناؤه.
     *
     * **ولا تقرؤه الوحدةُ بنفسها**: `BuildConfig` لكلّ وحدةٍ غيرُه،
     * **وقراءةُ بنائها هي لا بناءَ التطبيق تقول «تجريبيّ» في نسخةٍ
     * موقّعة** — فتُطفأ التقاريرُ في الميدان وهي أحوجُ ما تكون.
     */
    fun start(debug: Boolean) {
        client?.isCrashlyticsCollectionEnabled = !debug
    }

    /**
     * **يربط التقريرَ بصاحبه** — بالمعرّف لا بالاسم.
     *
     * **وتقريرٌ بلا صاحبٍ لا يُتابَع**: تعرف أنّ التطبيقَ سقط ثلاثاً،
     * **ولا تعرف أثلاثةُ سائقين أم واحدٌ ثلاث مرّات.**
     */
    fun who(userId: String) {
        runCatching { client?.setUserId(userId) }
    }

    /** **فتاتُ الطريق** — آخرُ ما فعله قبل السقوط. */
    fun trail(message: String) {
        runCatching { client?.log(message) }
    }

    /**
     * **خطأٌ لم يُسقط التطبيقَ ويستحقّ أن يُعرف.**
     *
     * **وخمسمئةٌ من المحرّك تُعرض للسائق جملةً مهذّبةً وتمضي** — فيُعاد
     * الفعلُ ويُعاد، **ولا يعلم أحدٌ أنّ بابا في الخادم مكسور.**
     */
    fun soft(e: Throwable, where: String) {
        runCatching {
            client?.log(where)
            client?.recordException(e)
        }
    }
}
