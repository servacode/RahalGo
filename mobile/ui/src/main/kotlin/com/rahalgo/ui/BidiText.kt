package com.rahalgo.ui

/**
 * **عزلُ الأرقام والرموز داخل الجملة العربيّة عند العرض** — لا يُغيَّر النصُّ نفسُه.
 *
 * (ملاحظةُ المالك ٢٠٢٦-١١-١٠: «طلب #1201 – +100 ل.س» تنقلب، و«الـ5» تلتصق.)
 * **كلُّ `#1201` وكلُّ مبلغٍ (`+100 ل.س`) وكلُّ رقمٍ يُحاط بعازلٍ (`FSI … PDI`)** فيبقى وحدةً
 * ولا يجرّ ما حولَه معه. **ونصوصُ الخادم تبقى كما وصلت** — العزلُ هنا في الرسم وحدَه.
 */
object BidiText {
    private const val FSI = "\u2068"
    private const val PDI = "\u2069"
    private val token = Regex("[+\\-−]?#?\\d[\\d.,:/]*(?:\\s?ل\\.س)?")

    private val arrow = Regex("(" + token.pattern + ")\\s*←\\s*(" + token.pattern + ")")

    /**
     * **سهمُ «جديد ← قديم» مقلوبٌ في السطر العربيّ** (D12: «1x ← 2x») — الخادمُ يكتب الجديدَ أوّلاً فيقع
     * على اليمين، والسهمُ يشير إلى القديم. **فيُبدَّل الطرفان للعرض** ليقرأ العينُ من القديم (يميناً) إلى
     * الجديد (يساراً)، وكلُّ رقمٍ معزول. والنصُّ المخزَّن لا يتغيّر.
     */
    fun fixArrows(text: String): String =
        if (!text.contains('←')) text else arrow.replace(text) { FSI + it.groupValues[2] + PDI + " ← " + FSI + it.groupValues[1] + PDI }

    /**
     * **الجزءُ اللاتينيُّ بأرقامه كتلةً واحدة** (ملاحظةُ المالك ٢٠٢٦-١١-١١: متجر «QA-Money-Model2» يظهر
     * «2QA-Money-Model» في عنوان الإشعار). **عزلُ الرقم وحدَه يترك «QA-Money-Model» لاتينيّاً مكشوفاً
     * فيلتصق به الرقمُ المعزول من الجهة الخطأ.** فيُعزل المقطعُ كلُّه: كلماتٌ لاتينيّةٌ تفصلها مسافةٌ أو
     * شرطةٌ أو نقطةٌ أو شرطةٌ سفليّة، وينتهي بحرفٍ أو رقم. **ولا يُعزل ما لا رقمَ فيه** (يبقى كما كان).
     */
    private val latinRun = Regex("[A-Za-z](?:[A-Za-z0-9_.\\- ]*[A-Za-z0-9])?")

    private val any = Regex(latinRun.pattern + "|" + token.pattern)

    fun isolateNumbers(text: String): String =
        if (text.isEmpty()) text else any.replace(text) { m ->
            val v = m.value
            // مقطعٌ لاتينيٌّ بلا رقمٍ لا يُمسّ؛ وما سواه (لاتينيٌّ برقم، أو رقمٌ عاديّ) يُعزل كاملاً.
            if (v[0].let { it in 'A'..'Z' || it in 'a'..'z' } && v.none { it.isDigit() }) v else FSI + v + PDI
        }
}

/**
 * **رقمُ هاتفٍ للعرض داخل أيّ نصٍّ عربيّ** (D4: «963900555001+») — معزولٌ يساراً (`LRI … PDI`) فلا تقفز
 * «+» إلى الطرف الآخر ولا ينقلب الرقمُ. **والنصُّ المخزَّن لا يتغيّر**، والفارغُ يبقى فارغاً.
 * **موضعٌ واحدٌ** — ومن كتب `"⁦$phone⁩"` بيده أعاد المشكلةَ في موضعٍ آخر.
 */
fun phoneText(phone: String?): String {
    val p = phone?.trim().orEmpty()
    return if (p.isEmpty()) "" else "⁦" + p + "⁩"
}
