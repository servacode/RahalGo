package com.rahalgo.ui

import android.content.Context
import coil3.disk.DiskCache
import coil3.disk.directory
import coil3.memory.MemoryCache
import coil3.ImageLoader
import coil3.SingletonImageLoader
import coil3.network.okhttp.OkHttpNetworkFetcherFactory
import okhttp3.Dispatcher
import okhttp3.OkHttpClient
import coil3.request.crossfade

/**
 * ══════════════════════════════════════════════════════════════════════
 * **جالبُ الصور يُسجَّل بيدنا — لا يُترك لـ`ServiceLoader`**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (شكوى المالك ٢٠٢٦-٠٨-١٨ بصورةِ شاشة: لافتاتُ السلايدر إطاراتٌ فارغة.)
 *
 * # ما كان يقع
 *
 * **`coil3` تكتشف جالبَ الشبكة بـ`ServiceLoader`** — سطرٌ في
 * `META-INF/services` يشير إلى صنفٍ **لا تناديه شيفرةٌ أبدا.**
 *
 * **وR8 يحذف ما لا يُنادى.** فيُبنى الإصدارُ بلا جالبِ شبكة: **كلُّ
 * صورةٍ بعيدةٍ تفشل** — ولا انهيارَ ولا رسالة، **بل إطارٌ فارغ.**
 *
 * **وفي التطوير تعمل** (`isMinifyEnabled = false`) — **وهو أخبثُ ما
 * يكون**: يُبنى ويُجرَّب فيُرى سليماً، **ولا يظهر العطبُ إلّا في
 * النسخة التي تصل الناس.**
 *
 * # ولماذا لم يُكتشف قبل اليوم
 *
 * **لم تكن في المنصّة صورةٌ بعيدةٌ تُعرض فعلاً**: أقسامُ السوق بلا
 * صور، **وصورةُ الحساب لم يرفعها أحد** — فكان يُرى حرفُها الاحتياطيُّ
 * ويُظنّ صواباً. **واللافتاتُ أوّلُ صورةٍ حقيقيّة، فكشفتها.**
 *
 * # ولماذا تسجيلٌ صريحٌ لا قاعدةُ إبقاء
 *
 * **قاعدةٌ في `proguard-rules` تُبقي أصنافاً بالاسم** — وتُكسر يومَ
 * تُبدَّل المكتبةُ أسماءَها الداخليّة، **بلا أن يصرخ شيء.**
 *
 * **والتسجيلُ الصريحُ نداءٌ في الشيفرة** — يُكسَر عند البناء لا عند
 * التشغيل.
 */
object Images {

    @Volatile private var wired = false

    /** **يُنادى مرّةً في `onCreate`** — قبل أوّل صورةٍ تُطلب. */
    fun install(context: Context) {
        if (wired) return
        wired = true
        val app = context.applicationContext
        SingletonImageLoader.setSafe {
            ImageLoader.Builder(app)
                // ══════════════════════════════════════════════════════
                // **وخمسةُ طلباتٍ للمضيف الواحد لا تكفي سوقاً**
                // ══════════════════════════════════════════════════════
                //
                // **وسقفُ OkHttp افتراضاً خمسة** — لا يُغيَّر ما لم
                // يُكتب، **وهو مقاسُ متصفّحٍ يفتح صفحةً لا مقاسُ شبكةِ
                // صورٍ في شاشةٍ واحدة.**
                //
                // **وقِيس ٢٠٢٦-٠٨-٢٦**: الشاشةُ الرئيسة **خمسٌ وأربعون
                // صورة**، والمصغّرةُ ٢٤ ك.ب تصل في ٠٫٣٩ ثانية. **فخمسةٌ
                // معاً تعني تسعَ موجات: ٣٫٦ ثانيةً** قبل أن تكتمل.
                //
                // **وذاك ما يراه المالكُ مربّعاتٍ فارغةً عند الفتح** —
                // لا بطءَ شبكةٍ ولا ثقلَ ملفّ، **بل طابورٌ من صنعنا.**
                //
                // # ولماذا خمسةَ عشرَ لا خمسين
                //
                // **والمصغّراتُ صغيرةٌ فالوصلاتُ رخيصة** — لكنّ كلَّ
                // وصلةٍ مصافحةُ TLS على شبكةِ الرقّة. **وخمسةَ عشرَ
                // تردّها إلى ثلاث موجاتٍ (١٫٢ ثانية)** ولا تُغرق
                // الشبكة، **وخمسون تزاحم نداءَ الواجهة نفسَه.**
                .components {
                    add(
                        OkHttpNetworkFetcherFactory(
                            callFactory = {
                                OkHttpClient.Builder()
                                    .dispatcher(
                                        Dispatcher().apply {
                                            maxRequests = 32
                                            maxRequestsPerHost = 15
                                        },
                                    )
                                    .build()
                            },
                        ),
                    )
                }
                // ══════════════════════════════════════════════════════
                // **وذاكرةُ قرصٍ — وإلّا نُزّلت الصورُ في كلّ إقلاع**
                // ══════════════════════════════════════════════════════
                //
                // (بلاغُ المالك ٢٠٢٦-٠٨-٢٤: «الصور تتأخّر جدّاً… ولم
                //  تُحمّل بعد» · و٢٠٢٦-٠٨-٢٥: «الأصناف بعد ما أضيفها
                //  على المفضّلة بدها شوي لتجلب الصور».)
                //
                // **وكان المُحمِّلُ بلا ذاكرةِ قرصٍ إطلاقاً** — فذاكرةُ
                // الرام وحدَها، **وهي تُمحى بإغلاق التطبيق.** فكلُّ
                // فتحةٍ تُنزّل الصورَ كلَّها من جديد.
                //
                // **وقِيس ٢٠٢٦-٠٨-٢٤**: الشاشةُ الرئيسة خمسٌ وأربعون
                // صورةً — **١٫٣ ميغا بالمصغَّرات** تُعاد في كلّ إقلاع.
                // **وعلى شبكة الرقّة ذاك ما يراه المالكُ مربّعاتٍ
                // فارغة.**
                //
                // # ومئتان لا خمسون
                //
                // **والصورُ لا تتبدّل** — عناوينُها فيها بصمةُ الملفّ
                // (`uuid.jpg`)، **فما نُزّل مرّةً صالحٌ أبداً.** والخادمُ
                // يرسل `max-age` سنةً كاملةً (قِيس)، فالذاكرةُ تحترمه.
                //
                // **ومئتا ميغا تسع سوقاً كاملةً بصورها** ولا تُثقل
                // جهازاً.
                .diskCache {
                    DiskCache.Builder()
                        .directory(app.cacheDir.resolve("images"))
                        .maxSizeBytes(200L * 1024 * 1024)
                        .build()
                }
                // **وذاكرةُ الرام رُبعُ المتاح** — **والافتراضُ أقلُّ**،
                // فيُطرد من الذاكرة ما يُعاد طلبُه بعد تمريرةٍ واحدة.
                .memoryCache {
                    MemoryCache.Builder()
                        .maxSizePercent(app, 0.25)
                        .build()
                }
                // **وذوبانٌ خفيفٌ عند الوصول** — **وصورةٌ تظهر فجأةً
                // فوق أرضٍ باهتةٍ تُقرأ ومضة.**
                .crossfade(true)
                .build()
        }
    }
}
