package com.rahalgo.ui

import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue

/**
 * ══════════════════════════════════════════════════════════════════════
 * **آخر موضع عُرف — يكتبه من يعرفه وتقرؤه الشاشة**
 * ══════════════════════════════════════════════════════════════════════
 *
 * **ويكتبه في السائق خدمةُ الورديّة** (تعمل والتطبيق مغلق)، **وفي
 * الزبون قراءةٌ واحدةٌ عند حفظ عنوان** — **والقارئُ لا يعرف أيَّهما.**
 *
 * **والخدمة والشاشة لا تلتقيان**: الأولى تعمل والتطبيق مغلق، والثانية
 * تُبنى وتُهدم مع كلّ دوران جهاز. **فالموضع يُترك في مكان يعرفه
 * الاثنان.**
 *
 * **ولا يُحفظ على القرص**: قيمة عمرها ثوانٍ، **وموضع الأمس على خريطة
 * اليوم كذب.** والخدمة تكتبه ثانيةً بعد ثوانٍ من كلّ إقلاع.
 *
 * **وحالة Compose لا متغيّر عاديّ** — فالخريطة تتحرّك معه بلا أن يسأل
 * أحد.
 */
object LastPoint {

    var value by mutableStateOf<Point?>(null)
        private set

    /**
     * **ويُحفظ اسمُه معه** — **ورقمان بستّ منازلَ لا يقرؤهما أحد**:
     * لا يعرف أصحيحان أم لا، ولا يعرف أين هما.
     *
     * **وفارغٌ حين يأتي الموضعُ من جهاز التموضع** — لا اسمَ معه،
     * **فتُعرض إحداثيّاته**: رقمان يُقرآن بصعوبةٍ خيرٌ من حقلٍ فارغ.
     */
    fun set(lat: Double, lng: Double, name: String = "") {
        value = Point(lat, lng, name)
    }

    data class Point(val lat: Double, val lng: Double, val name: String = "")
}
