package com.rahalgo.ui

/**
 * ══════════════════════════════════════════════════════════════════════
 * **حالُ الاتّصال من أحداث النظام نفسِها — لا من سؤاله أثناءها**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (`P8-DEF-001` · ٢٠٢٦-٠٩-١٨.)
 *
 * # ما كان يقع
 *
 * **كان كلُّ حدثٍ يسأل النظامَ عن حاله** — `cm.activeNetwork` ثمّ
 * `getNetworkCapabilities` — **ويتجاهل ما جاء به الحدثُ نفسُه.**
 *
 * **وأندرويد يحذّر من هذا بنصّه** في `NetworkCallback`: «لا تنادِ
 * `getNetworkCapabilities` ولا غيرَها من أساليب `ConnectivityManager`
 * المتزامنة داخلَ هذا النداء — **فلا ضمانَ أن تكون الكائناتُ المردودةُ
 * حاليّة**».
 *
 * **فحين سقط الواي فاي والبياناتُ معاً** قرأ `onLost` الشبكةَ التي
 * تزول بعد — **بقدرتها `VALIDATED` القديمة** — **فبقي «متّصل»**. **ولا
 * حدثَ بعده يُصحّحه: فلا شبكةَ بقيت لتُرسل حدثاً.**
 *
 * **فعلق التطبيقُ على «متّصل» والشبكةُ ميّتة** — وشريطُ الانقطاع لا
 * ينزل، **ومن سحب للتحديث لا يرى جواباً.**
 *
 * # ولماذا صحّ الفتحُ البارد
 *
 * **القراءةُ الأولى تقع في `install` خارجَ أيّ نداء** — **فلا سباق.**
 * **وشاشةُ الفتح المقطوع تأتي أصلاً من `vm.offline` لا من هنا.**
 *
 * # والآن
 *
 * **كلُّ شبكةٍ تُتتبَّع بما قاله حدثُها**: `onCapabilitiesChanged` يقول
 * أهي مُتحقَّقة، و`onLost` يُسقطها. **و«متّصل» = شبكةٌ واحدةٌ على الأقلّ
 * مُتحقَّقة.** **ولا سؤالَ للنظام داخلَ نداء.**
 *
 * **ومنطقٌ خالصٌ بلا أندرويد** — فيُختبَر على الحاسوب (`NetTrackerTest`).
 */
internal class NetTracker<N : Any>(initialOnline: Boolean) {

    /** **الشبكاتُ الحيّةُ وأهي مُتحقَّقة** — كما قالتها أحداثُها. */
    private val nets = LinkedHashMap<N, Boolean>()

    var online: Boolean = initialOnline
        private set

    /**
     * **شبكةٌ ظهرت — ولا حكمَ قبل قدرتها.**
     *
     * **ولا يُعاد الحسابُ هنا**: `onCapabilitiesChanged` يتبعها فوراً
     * (منذ API 26) — **ولو حُسب الآن لَقال «مقطوع» لحظةً عند كلّ إقلاع.**
     */
    @Synchronized
    fun onAvailable(n: N) {
        nets.putIfAbsent(n, false)
    }

    /** **القدرةُ قالت كلمتَها** — وهي ما يُحكَم به. */
    @Synchronized
    fun onCapabilitiesChanged(n: N, internet: Boolean, validated: Boolean) {
        nets[n] = internet && validated
        online = nets.values.any { it }
    }

    /** **الشبكةُ ذهبت** — ولا يُسأل النظامُ عمّا بقي. */
    @Synchronized
    fun onLost(n: N) {
        nets.remove(n)
        online = nets.values.any { it }
    }
}
