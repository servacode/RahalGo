package com.rahalgo.ui

/**
 * ══════════════════════════════════════════════════════════════════════
 * **السرعةُ المعروضة — ثلاثةُ أحوالٍ لا حالان**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (قرارُ المالك ٢٠٢٦-٠٩-٢٨: «حين يكون السائقُ واقفاً اعرض `0 كم/س`،
 *  وحين يتحرّك اعرض سرعتَه الحقيقيّة، **ولا تختلق حركة**».)
 *
 * # وما كان قبلَه
 *
 * **كانت السرعةُ إمّا رقماً وإمّا لا شيء** — **فالواقفُ كالذي لا موضعَ
 * له**: تختفي الشريحةُ في الحالين. **والسائقُ الواقفُ على إشارةٍ يرى
 * لوحتَه وقد نقص منها حقلٌ**، فيحسب العطبَ في التطبيق.
 *
 * # والفرقُ الذي يُقاس
 *
 *	لا قراءةَ موقعٍ أصلاً (أو شاخت)  ⇒ لا شريحةَ — **ولا صفرٌ يُختلق**
 *	قراءةٌ صالحةٌ ولا سرعةَ فيها      ⇒ `0 كم/س` — **واقفٌ**
 *	قراءةٌ صالحةٌ وفيها سرعة          ⇒ السرعةُ كما قالها الجهاز
 *
 * **والصفرُ حين لا سرعةَ في القراءة صحيحٌ لا اختلاق**: **`hasSpeed()`
 * تكذب على الواقف** — الجهازُ لا يقيس سرعةً لمن لا يتحرّك، **فيردّ
 * فراغاً حيث الحقُّ صفر.** ومَن ملأ الفراغَ صفراً وله قراءةٌ حديثةٌ
 * قال الحقّ؛ **ومن ملأه صفراً بلا قراءةٍ ادّعى وقوفاً لا يعرفه.**
 *
 * # ولمَ هنا لا في الشريحة
 *
 * **والقرارُ في حالِ الموقع لا في لونِ الشريحة** — **فمن كتبه في
 * الواجهة كتبه ثانيةً في الواجهة الثانية** وافترقا. **وهنا يقرؤه
 * الاثنان.**
 *
 * # ولا يُعرض اليوم
 *
 * **حُذفت شريحةُ `كم/س` من رأس الرحلة** (قرارُ المالك ٢٠٢٦-٠٩-٢٩) —
 * **فهذه الدالّةُ لا يناديها عرضٌ الآن.** وتُركت بمنطقها واختبارها
 * **لأنّ حسابَ «متى يُعرض صفرٌ ومتى لا يُعرض شيء» هو ما كلّف القياسَ**،
 * فإن أُعيدت الشريحةُ يوماً عادت بقواعدها لا بقواعدَ تُخترع ثانية.
 */
object SpeedReadout {

    /**
     * **ما بعده تُعدُّ القراءةُ شائخة** — عشرُ ثوانٍ.
     *
     * **وقراءةٌ عمرُها دقيقةٌ لا تصف واقفاً ولا سائراً** — قد يكون قطع
     * كيلومتراً منذها. **فلا يُقال عنها صفرٌ ولا رقم.**
     */
    const val FRESH_MS = 10_000L

    /**
     * **ما دونها لا تُعرض حركةً** — ٢٫٢ م/ث ≈ ٨ كم/س.
     *
     * **ونظيرُها `movingOnMps` في `SpeedFilter`** — تُكتب هنا ثانيةً
     * لأنّ `ui` لا تعرف وحدةَ الملاحة، **وقيمةٌ واحدةٌ في موضعين
     * تفترقان يوماً** فيُذكَر الأصلُ صراحةً هنا.
     */
    const val STATIONARY_MPS = 2.2f

    /**
     * **يردّ ما يُعرض** — وفارغٌ يعني **لا تعرض شيئاً**.
     *
     * @param navSpeedKmh سرعةُ جلسةِ الملاحة إن كانت تعمل — وهي الأدقّ:
     *   محسوبةٌ من قراءاتٍ متتابعةٍ لا من قراءةٍ واحدة.
     * @param navFixAtMs وقتُ آخرِ قراءةٍ بلغت الملاحة — بالمقياس الرتيب.
     * @param point آخرُ موضعٍ عُرف — [LastPoint.value].
     * @param nowMs `elapsedRealtime` الآن.
     */
    fun kmh(navSpeedKmh: Int?, navFixAtMs: Long, point: LastPoint.Point?, nowMs: Long): Int? {
        // **والملاحةُ إن نطقت حديثاً فهي الحقّ** — قراءتُها متتابعةٌ
        // ومُرشَّحة. **وسرعةٌ من جلسةٍ توقّفت قراءاتُها ليست حاضراً** —
        // **ورقمٌ متجمّدٌ على الشاشة أسوأُ من حقلٍ غائب**: يقرؤه السائقُ
        // سرعتَه الآن.
        if (navSpeedKmh != null && navFixAtMs > 0L && nowMs - navFixAtMs <= FRESH_MS) {
            return navSpeedKmh.coerceAtLeast(0)
        }
        val p = point ?: return null
        // **وقراءةٌ بلا وقتٍ لا يُعرف عمرُها** — فلا يُبنى عليها صفر.
        if (p.atMs <= 0L) return null
        if (nowMs - p.atMs > FRESH_MS) return null
        val mps = p.speedMps
        // **وفراغُ السرعةِ مع قراءةٍ حديثةٍ وقوفٌ** — انظر أعلاه.
        if (mps == null || !mps.isFinite() || mps < 0f) return 0
        // ══════════════════════════════════════════════════════════════
        // **وضجيجُ الواقف يُصفَّر هنا أيضاً**
        // ══════════════════════════════════════════════════════════════
        //
        // (بلاغُ المالك ٢٠٢٦-٠٩-٢٩: «٢ و٤ و٥ و٦ كم/س لهاتفٍ واقف».)
        //
        // **وهذا الطريقُ بلا تاريخ**: نقطةٌ واحدةٌ بلا سابقةٍ ولا دقّة،
        // **فلا إزاحةَ تُصدَّق ولا تُكذَّب** — والمرشِّحُ الكاملُ في
        // `SpeedFilter` على مجرى قراءات الملاحة.
        //
        // **فيُكتفى هنا بالعتبة الدنيا** — ثمانيةُ كم/س: ما دونها في
        // مدينةٍ إمّا وقوفٌ أو زحفٌ لا يُقاس، **والرقمُ المتراقصُ أسوأُ
        // من صفرٍ ساكن.** (`MOVING_ON` في `SpeedFilter` نفسُها.)
        if (mps < STATIONARY_MPS) return 0
        return Math.round(mps * 3.6f)
    }
}
