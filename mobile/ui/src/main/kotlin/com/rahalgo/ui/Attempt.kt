package com.rahalgo.ui

import android.content.Context
import android.content.SharedPreferences

/**
 * ══════════════════════════════════════════════════════════════════════
 * **هويّةُ المحاولة — تبقى بعد موت العمليّة** (`SR`، ٢٠٢٦-٠٩-١٤)
 * ══════════════════════════════════════════════════════════════════════
 *
 * # العطبُ الذي كان
 *
 * **وكان المفتاحُ يعيش في النموذج** (`ViewModel`) — **ويموت بموته.**
 *
 * **فمن ضغط «أرسل» فأنشأ المحرّكُ طلبَه ثمّ قُتل التطبيقُ قبل الجواب**
 * — **مكالمةٌ، أو ذاكرةٌ تُدار** — **عاد فوجد سلّتَه كما هي** (فهي
 * تُفرَّغ بعد النجاح لا قبله)، **فضغط ثانيةً بمفتاحٍ جديد**:
 * **فطلبان وسائقان وخصمان.**
 *
 * **والحمايةُ في المحرّك قائمةٌ منذ زمن** — `idempotency.go` يحفظ
 * الردَّ أربعاً وعشرين ساعةً ويعيده لمن حمل المفتاحَ نفسَه.
 * **وإنّما كان الجهازُ ينسى المفتاح.**
 *
 * # فيُكتب على القرص لا في الذاكرة
 *
 * **ومحاولةٌ واحدةٌ منطقيّةٌ مفتاحٌ واحد** — **مهما مات التطبيقُ
 * بينهما.** **ويُمحى بعد النجاح**: **ومفتاحٌ يبقى يجعل الطلبَ التالي
 * يردّ جوابَ الذي قبله.**
 *
 * # وخانةٌ لكلّ نوعِ إنشاء
 *
 * **والطلبُ العاديُّ والمخصَّصُ فعلان مختلفان** — **ومفتاحٌ واحدٌ
 * لهما يجعل المخصَّصَ يردّ جوابَ العاديّ.**
 */
object Attempt {

    /**
     * **مخزنٌ صغير** — **والقرصُ خلفَه.**
     *
     * **ولا يُفحَص `SharedPreferences` في آلةٍ بلا أندرويد** —
     * **وواجهةٌ من ثلاثة أفعالٍ تُفحَص بخريطةٍ في الذاكرة**،
     * **و«موتُ العمليّة» يُحاكى بأن تُعاد التهيئةُ فوق المخزن عينِه.**
     */
    interface Store {
        fun get(key: String): String?
        fun put(key: String, value: String)
        fun remove(key: String)
    }

    private class Prefs(private val p: SharedPreferences) : Store {
        override fun get(key: String): String? = p.getString(key, null)

        // **ويُكتب الآن لا بعد حين** (`commit`) — **ومفتاحٌ يُكتب
        // كسولاً لا ينفع من قُتل تطبيقُه بعد سطر.**
        override fun put(key: String, value: String) {
            p.edit().putString(key, value).commit()
        }

        override fun remove(key: String) {
            p.edit().remove(key).apply()
        }
    }

    private var store: Store? = null

    /** **خانةُ الطلب العاديّ.** */
    const val ORDER = "order"

    /** **خانةُ الطلب المخصَّص.** */
    const val CUSTOM = "custom"

    /**
     * **تُنادى مرّةً عند الإقلاع** — قبل أوّل شاشة.
     *
     * **ومن نسي ندَاءها لم يُحفظ مفتاحٌ ولا ظهر خطأ** — **فيعود
     * الخطرُ صامتاً كما كان.**
     */
    fun install(context: Context) {
        if (store != null) return
        store = Prefs(
            context.applicationContext.getSharedPreferences(FILE, Context.MODE_PRIVATE),
        )
    }

    /**
     * **مفتاحُ هذه المحاولة** — **يُولَّد مرّةً ويبقى حتّى تنجح.**
     *
     * **وإعادةُ المحاولة تحمله نفسَه** — **فيردّ المحرّكُ الطلبَ
     * الأوّلَ بعينه ولا يُنشئ ثانياً.**
     */
    fun key(slot: String): String {
        val saved = store?.get(slot)
        if (!saved.isNullOrBlank()) return saved
        val fresh = java.util.UUID.randomUUID().toString()
        // **ويُكتب قبل أن يُرسَل** — **ومفتاحٌ يُكتب بعد الجواب لا
        // ينفع من مات تطبيقُه قبله**، **وهي الحالةُ كلُّها.**
        store?.put(slot, fresh)
        return fresh
    }

    /** **أثمّةَ محاولةٌ لم تُحسَم؟** — تقرؤها شاشةُ التعافي. */
    fun pending(slot: String): Boolean = !store?.get(slot).isNullOrBlank()

    /** **يُمحى بعد أن يُحسَم الأمرُ يقيناً** — نجاحاً أو رفضاً صريحاً. */
    fun clear(slot: String) {
        store?.remove(slot)
    }

    /** **تُصفَّر في الفحوص وحدَها** — **ولا يناديها منتَج.** */
    fun resetForTest(s: Store?) {
        store = s
    }

    private const val FILE = "rahalgo_attempt"
}

/**
 * ══════════════════════════════════════════════════════════════════════
 * **أحُسم الأمرُ أم لا يُدرى؟** (`SR-07`)
 * ══════════════════════════════════════════════════════════════════════
 *
 * **وردُّ المحرّك حسمٌ** — **وصل النداءُ وأجاب**، فالمفتاحُ يُمحى
 * ويُعاد الأمرُ إلى صاحبه.
 *
 * **وانقطاعُ الشبكة ليس حسماً** — **قد يكون الطلبُ قُيِّد وضاع
 * الجواب.** **ومن قيل له «فشل» وهو لم يفشل يعيد الكرّةَ فيُنشئ
 * ثانياً** — **فيُقال «لا ندري» ويُحمَل المفتاحُ نفسُه.**
 *
 * ══════════════════════════════════════════════════════════════════════
 * **و«قيد المعالجة» ردٌّ لا حسمَ فيه** — `CUST-DEF-002` (٢٠٢٦-٠٩-١٩)
 * ══════════════════════════════════════════════════════════════════════
 *
 * **وكلُّ ردِّ خادمٍ كان يُعدّ حسماً** — **فردُّ `409 in_progress`
 * (المفتاحُ محجوزٌ، والطلبُ الأوّلُ ما زال يُعالَج) كان يمحو المفتاح**:
 * **فإعادةُ الضغط تحمل مفتاحاً جديداً، فيُنشئ المحرّكُ طلباً ثانياً.**
 * **وقِيس: نداءٌ تجاوز مهلةَ التطبيق والمحرّكُ ما زال يعمل ⇒ طلبان.**
 *
 * **وهو ردٌّ يقول «لم أفرغ بعد» لا «فشلتَ»** — ومثلُه
 * `idempotency_reclaimed` (استُرجعت المطالبةُ، يُعاد النداءُ فيقرأ
 * الحقيقة). **كلاهما 409 برسالة `errors.in_progress`**: **يُحمَل
 * المفتاحُ نفسُه، وإعادةُ النداء تردّ الطلبَ المثبَّت** (`writeReplay`).
 *
 * ══════════════════════════════════════════════════════════════════════
 * **و«مفتاحٌ لجسمين» ليس حسماً كذلك** — `CAF-02` · `13-029` (٢٠٢٦-٠٩-٢١)
 * ══════════════════════════════════════════════════════════════════════
 *
 * **المحرّكُ الآن يحرس محتوى الطلب**: **مفتاحٌ عاد بجسمٍ مختلفٍ** — سلّةٌ
 * عُدّلت والمفتاحُ نفسُه — **يُرَدّ `409 idempotency_key_reused` ولا
 * يُنفَّذ.** **وهذا لا يقع إلّا وثمّةَ محاولةٌ سابقةٌ لم تُحسَم** عُدِّل
 * جسمُها. **فهو ليس حسماً بالفشل**: مصيرُ السابقةِ ما زال مجهولاً.
 *
 * **فيبقى المفتاحُ ويبقى «لا ندري»** — **ولا يُمحى صامتاً فيُنشأ طلبٌ
 * جديدٌ فوق سابقٍ قد نجح.** **والخروجُ منه بإقرارٍ صريحٍ من صاحبه** بعد
 * أن يتحقّق من «طلباتي» (انظر `acknowledgeUncertain` في السلّة) — **لا
 * بتعديلٍ صامتٍ يُدوّر المفتاح.**
 *
 * **وما عداها من ردود الخادم حسمٌ** — `400 validation`، و`409`
 * الأخرى (متجرٌ مغلقٌ، نقدٌ موقوفٌ، متجرٌ غريب): **يُمحى المفتاحُ
 * كما كان، فالطلبُ لم يُنشأ ولن يُنشأ بهذه المحاولة.**
 */
fun isDecided(e: Throwable): Boolean {
    if (e !is com.rahalgo.shared.net.ApiClient.ApiException) return false
    if (e.status == 409 && (
            // **«قيد المعالجة» ليس حسماً** — يُحمَل المفتاحُ نفسُه لا يُمحى.
            e.body.code == "in_progress" ||
                e.body.code == "idempotency_reclaimed" ||
                // **و«مفتاحٌ لجسمين» ليس حسماً** — محاولةٌ سابقةٌ مجهولةُ
                // المصير عُدِّل جسمُها؛ **لا يُمحى المفتاحُ إلّا بإقرار.**
                e.body.code == "idempotency_key_reused"
            )
    ) {
        return false
    }
    return true
}
