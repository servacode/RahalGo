/**
 * ══════════════════════════════════════════════════════════════════════
 * **إطارُ التطبيق — السمةُ وشريطا النظام**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (قرارُ المالك ٢٠٢٦-٠٨-١٤: «نرى ما المركزيّ وهي الأمور بشكلٍ كامل».)
 *
 * # ولماذا هذا وحدَه لا الغلافُ كلُّه
 *
 * **قِيس (٢٠٢٦-٠٨-١٤)**: غلافُ الزبون والمندوب متطابقان **٦١٪**،
 * **وغلافُ السائق والزبون ٢٦٪** — تبويباتُه وخريطتُه ورحلتُه تختلف.
 *
 * **ورفعُ «غلافٍ واحدٍ للثلاثة» يُخرج قطعةً بوسائطَ تصف الجميعَ ولا
 * تصف أحدا** — وهو ضدُّ ما تُرفع القِطعُ لأجله.
 *
 * **فيُرفع ما يتطابق حقّا**: السمةُ وشريطا النظام.
 *
 * # وشريطا النظام يأخذان أرضَ الصفحة
 *
 * **وإلّا بقيا فاتحين فوق شاشةٍ كحليّة** — **شريطان أبيضان يحدّان شاشةً
 * داكنةً يُقرآن عطبا.** (قِيس على جهاز المالك ٢٠٢٦-٠٨-١٣.)
 *
 * **واللوحةُ تُقرأ من القرار لا من الشجرة**: هذا خارج `RahalGoTheme`،
 * **فـ`Rahal.colors` فيه يردّ الفاتحةَ دائماً** مهما كان الاختيار.
 */
@Composable
fun AppFrame(
    /**
     * ══════════════════════════════════════════════════════════════════
     * **أذونُ الإقلاع — تُطلب هنا فتُصيب التطبيقاتِ الأربعة**
     * ══════════════════════════════════════════════════════════════════
     *
     * (بلاغُ المالك ٢٠٢٦-٠٨-٢٤ وطلبُ التعميم ٢٠٢٦-٠٨-٢٦.)
     *
     * **و`AppFrame` تلفّ الأربعة كلَّها** — فسطرٌ هنا يغني عن أربعةٍ
     * تُنسى إحداها. **وقد نُسيت ثلاثةٌ فعلاً**: كانت في الزبون وحدَه.
     *
     * **والافتراضُ إشعاراتٌ وموقع** — وهما ما تحتاجه الأربعة:
     * الزبونُ يحدّد عنوانه ويتابع طلبه، والسائقُ يُلاحَق، والمتجرُ
     * يُنبَّه بطلب، والمندوبُ يسجّل متجراً في موضعه.
     *
     * **ومن أراد غيرها مرّرها** — ولا تُطلب أذونٌ لا يستعملها تطبيق.
     */
    permissions: List<String> = startupPermissions(),
    content: @Composable (theme: ThemeState, dark: Boolean) -> Unit,
) {
    val context = LocalContext.current

    // **ولا شيءَ قبلها** — من رأى الشاشةَ قبل أن يُسأل ضغط زرّاً لا
    // يستجيب، **ثمّ بحث عن العطب في التطبيق لا في النظام.**
    AskStartupPermissions(permissions)
    // **والسمةُ قرارُه هو وتبقى بعد إغلاق التطبيق** — لا تتبع النظامَ
    // وحدَه: **من فضّل الفاتحةَ في هاتفٍ غامقٍ أراد ذلك.**
    val theme = rememberTheme(context)
    val dark = theme.isDark()

    val activity = context as? android.app.Activity
    val canvas = (if (dark) DarkPalette else LightPalette).canvas
    LaunchedEffect(dark, activity) {
        val window = activity?.window ?: return@LaunchedEffect
        window.statusBarColor = canvas.toArgb()
        window.navigationBarColor = canvas.toArgb()
        WindowCompat.getInsetsController(window, window.decorView).apply {
            isAppearanceLightStatusBars = !dark
            isAppearanceLightNavigationBars = !dark
        }
    }

    RahalGoTheme(dark = dark) {
        // ══════════════════════════════════════════════════════════════
        // **والرسالةُ تطفو فوق كلّ شاشة — تُركَّب هنا مرّةً**
        // ══════════════════════════════════════════════════════════════
        //
        // (قرارُ المالك ٢٠٢٦-٠٨-١٨: «رسالةً منبثقةً تطلع ع شاشة بكلّ
        //  التطبيق… ما نلاحقها وين تروح ووين تجي».)
        //
        // **وهذا الإطارُ يلفّ التطبيقاتِ الثلاثة** — **وثلاثةُ تركيباتٍ
        // تُنسى في واحد.**
        androidx.compose.foundation.layout.Box(Modifier.fillMaxSize()) {
            content(theme, dark)

            // ══════════════════════════════════════════════════════════
            // **وافتتاحُ العلامة — للثلاثة لا للسائق وحدَه**
            // ══════════════════════════════════════════════════════════
            //
            // (ملاحظةُ المالك ٢٠٢٦-٠٨-١٩: «تطبيق الزبون لا يحوي واجهةَ
            //  الدخول التي اتّفقنا عليها وقمنا ببنائها… واتّفقنا يجب
            //  أن تكون مركزيّة، نستخدم نفس واجهة البداية بكلّ
            //  التطبيقات».)
            //
            // **وقِيس أنّها في السائق وحدَه** — بُنيت ٢٠٢٦-٠٨-١١ ورُكّبت
            // في `DriverApp` بيدها، **فوُلدت في تطبيقٍ وبقيت فيه.**
            //
            // **وهذا الإطارُ يلفّ الثلاثة** — كالرسالة الطافية وشريط
            // الشبكة: **وثلاثةُ تركيباتٍ تُنسى في واحد**، وقد نُسيت في
            // اثنين.
            //
            // # ولا تُرسَم إلّا مرّةً في عمر العمليّة
            //
            // **ودورانُ الجهاز يُعيد بناءَ الشجرة** — **ومن أمال هاتفَه
            // فرأى الافتتاحَ من جديدٍ يظنّ التطبيقَ أُقلع.** فالرايةُ
            // ساكنةٌ لا حالُ شاشة.
            //
            // # ولا تقرّر الوجهة
            //
            // (شرطُ المالك: «يجب ألّا تقرّر Splash بنفسها أين يذهب
            //  المستخدم».) **وهي تطفو فوق ما تحتها** — والوجهةُ تُقرَّر
            // تحتها وتظهر حين تنصرف.
            BrandIntroHost()

            // ══════════════════════════════════════════════════════════
            // **وشريطُ انقطاع الشبكة فوق كلّ شيء — ويُركَّب هنا مرّةً**
            // ══════════════════════════════════════════════════════════
            //
            // (طلبُ المالك ٢٠٢٦-٠٨-١٨: «شاشةُ عدم توفّر إنترنت… يجب أن
            //  تكون مركزيّة».)
            //
            // **وشريطٌ لا شاشةٌ تحجب**: من انقطع عنه الإنترنتُ وهو يقرأ
            // سلّتَه **لا يريد أن تُمحى الشاشةُ من أمامه** — ما جُلب
            // لا يزال صالحاً للقراءة.
            //
            // **وتحت الرسالة الطافية**: تلك تنصرف بعد ثوانٍ وهذا يبقى،
            // **فلو فوقه لَقفز الشريطُ حين تنصرف.**
            NetBanner(Modifier.align(androidx.compose.ui.Alignment.TopCenter))
            FlashHost()
        }
    }
}

/**
 * ══════════════════════════════════════════════════════════════════════
 * **بوّابةُ الدخول — أربعُ حالاتٍ وترتيبُها واحد**
 * ══════════════════════════════════════════════════════════════════════
 *
 * **وترتيبُها ليس ذوقا**: التسجيلُ والاستعادةُ يغطّيان الدخول،
 * **والدخولُ يغطّي ما بعده**، **وشاشةُ الانتظار تسبقهنّ جميعاً** ما دام
 * التوكنُ المحفوظُ يُفحص.
 *
 * **ومن قلب اثنتين رأى شاشةَ دخولٍ فوق حسابٍ مفتوح.**
 *
 * # وشاشةُ انتظارٍ لا شاشةُ دخول
 *
 * **من له حسابٌ لا يُطلب منه أن يدخل من جديد** لأنّ النداءَ لم يعد بعد.
 */
@Composable
fun AuthGate(
    vm: AuthViewModel,
    /** **عنوانُ شاشة الدخول** — «دخول السائق» أو «دخول». */
    title: String,
    /** **أيُعرض بابُ إنشاء الحساب؟** — الزبونُ وحدَه يُنشئ حسابَه. */
    signup: Boolean = false,
    /** **يُفتح الدخولُ صراحةً؟** — لتطبيقٍ يتصفّح ضيفاً قبل أن يدخل. */
    asking: Boolean = true,
    onSignedIn: @Composable () -> Unit,
    /** **ما يُعرض لضيفٍ لم يطلب الدخولَ بعد** — أو فارغ. */
    guest: (@Composable () -> Unit)? = null,
) {
    // ══════════════════════════════════════════════════════════════════
    // **وأرضُ السمة تُوضع هنا — بوّابةً واحدةً لثلاث شاشات**
    // ══════════════════════════════════════════════════════════════════
    //
    // (بلاغُ المالك ٢٠٢٦-٠٨-٢٥: «شاشة تسجيل الدخول واستعادة كلمة
    //  المرور وإنشاء حساب جديد خلفيّتها ما تزال بيضاء، وهذا الغلط
    //  الأكبر — هو ثيمٌ غامقٌ كيف فيه خلفيّةٌ بيضاء؟».)
    //
    // # ولماذا وقع
    //
    // **ولا واحدةٌ من الثلاث تضع أرضَها**: `AuthScreen` عمودٌ بلا
    // خلفيّة، و`SignupScreen` مثلُه، وشاشةُ الانتظار صندوقٌ فارغ.
    // **فتُرسم كلُّها على أرض النافذة** — وهي بيضاءُ من سمة النظام لا
    // من سمتنا.
    //
    // **والأشرطةُ غامقةٌ فوقها وتحتها** — فيبدو التطبيقُ نصفَه ليلٌ
    // ونصفُه نهار.
    //
    // # وموضعٌ واحدٌ لا ثلاثة
    //
    // **ومن وضعها في كلّ شاشةٍ نسي رابعةً تُضاف غدا** — والبوّابةُ
    // تمرّ منها الثلاثُ كلُّها، **فأرضُها أرضُهنّ.**
    // ══════════════════════════════════════════════════════════════════
    // **ونسخةٌ متخلّفةٌ تُغلق كلَّ شيء**
    // ══════════════════════════════════════════════════════════════════
    //
    // (طلبُ المالك ٢٠٢٦-٠٨-٢٥.)
    //
    // **والرايةُ تُرفع في `ApiClient` عند أوّل ٤٢٦** — وتُقرأ هنا،
    // **فتُغلق الأبوابُ كلُّها معاً** ولا تبقى شاشةٌ منسيّةٌ تعمل وهي
    // مكسورة.
    //
    // **وتُقرأ مع كلّ إعادة رسم** — فلا تحتاج مراقباً ولا مؤقّتا.
    if (com.rahalgo.shared.net.ApiClient.outdated) {
        UpdateGate(pkg = LocalContext.current.packageName)
        return
    }

    Surface(
        modifier = Modifier.fillMaxSize(),
        color = Rahal.colors.canvas,
    ) {
    when {
        vm.restoring -> Box(Modifier.fillMaxSize(), contentAlignment = Alignment.Center) {
            RahalLoader()
        }

        vm.signup != null -> SignupScreen(
            state = vm.signup!!,
            actions = SignupActions(
                setPhone = vm::setSignupPhone,
                sendCode = vm::sendSignupCode,
                verifyCode = vm::verifySignupCode,
                confirm = vm::confirmSignup,
                cancel = vm::closeSignup,
            ),
        )

        vm.reset != null -> ResetScreen(
            state = vm.reset!!,
            actions = ResetActions(
                setPhone = vm::setResetPhone,
                sendCode = vm::sendResetCode,
                verifyCode = vm::verifyResetCode,
                confirm = vm::confirmReset,
                cancel = vm::closeReset,
            ),
        )

        vm.user != null -> onSignedIn()

        // ══════════════════════════════════════════════════════════════
        // **ومن فشلت استعادةُ جلسته لانقطاعٍ لا يُرمى إلى الدخول**
        // ══════════════════════════════════════════════════════════════
        //
        // **كانت هذه الحالةُ في تطبيق السائق وحدَه** — يبنيها بنفسه خارج
        // `AuthGate` (قِيس ٢٠٢٦-٠٨-٢٦). **والثلاثةُ الباقية تسقط إلى
        // شاشة الدخول.**
        //
        // **ومن فتح تطبيقَه على شبكةٍ رديئةٍ وهو داخلٌ منذ شهر رأى
        // «سجّل الدخول»** — فظنّ حسابَه ضاع، **وأدخل رقمَه من جديدٍ
        // فطلب رمزاً لا يصل** لأنّ الشبكةَ هي العاطلة.
        //
        // **وحسابُه لم يضع**: الجلسةُ في الجهاز، والاستعادةُ وحدَها
        // فشلت. **فالصوابُ أن يُقال له ذلك ويُعطى زرَّ إعادة.**
        vm.offline -> OfflineScreen(onRetry = vm::retryRestore)

        guest != null && !asking -> guest()

        else -> AuthScreen(
            state = vm.state,
            title = title,
            signup = signup,
            actions = LoginActions(
                login = vm::login,
                setMode = vm::setMode,
                sendCode = vm::sendLoginCode,
                verifyCode = vm::verifyLoginCode,
                resetCode = vm::clearCode,
                forgot = vm::openReset,
                signup = { vm.openSignup() },
            ),
        )
    }
    }
}
