#!/usr/bin/env bash
# ══════════════════════════════════════════════════════════════════════
# **اختبارُ تطبيق السائق · المرحلةُ الأولى — المحرّك**
# ══════════════════════════════════════════════════════════════════════
#
# **ومصدرُها العقدُ في `TASKS.md`** — كلُّ فحصٍ بندٌ مرقَّمٌ يُطبع رقمُه
# مع نتيجته، **فمن قرأ سطراً في المخرَج وجد بندَه بلا بحث.**
#
# # وما يميّز السائقَ عن المتجر
#
# **لا شيءَ فيه يعمل بلا طلبٍ حقيقيّ** — لا رحلةَ ولا ملاحةَ ولا
# إثباتَ ولا مال. **فما يُقاس هنا الأبوابُ والحرّاسُ والقراءةُ وحدَها.**
#
# **ولا تُفتح ورديّةٌ ولا يُقبل عرضٌ** — **فطلبُ زبونٍ حقيقيٍّ قد ينزل
# على سائقٍ هو نصٌّ آليّ.**

set -u
A="${API:-https://api.rahalgo.com/api/v1}"
PHONE="${DRV_PHONE:-}"
PASS="${DRV_PASS:-}"
Z=00000000-0000-0000-0000-000000000000

OKN=0; NON=0; SKN=0; FAILED=""
ok(){ OKN=$((OKN+1)); printf '  \033[32m✔\033[0m %-8s %s\n' "$1" "$2"; }
no(){ NON=$((NON+1)); FAILED="$FAILED\n  $1  $2 — $3"
      printf '  \033[31m✗\033[0m %-8s %s\n      \033[31m%s\033[0m\n' "$1" "$2" "$3"; }
sk(){ SKN=$((SKN+1)); printf '  \033[33m؟\033[0m %-8s %s — %s\n' "$1" "$2" "$3"; }
hdr(){ printf '\n\033[1m%s\033[0m\n' "$1"; }
code(){ curl -s -o /tmp/dt.json -w '%{http_code}' --max-time 30 "$@"; }

TOKEN=""

# ══════════════════════════════════════════════════════════════════════
# **أ · الأبوابُ مقفلةٌ بلا توكن**
# ══════════════════════════════════════════════════════════════════════
stage_anon(){
  hdr "أ · الأبوابُ بلا توكن"
  local p c
  for p in me queue orders orders/history orders/report-reasons incentives shift; do
    c=$(code "$A/driver/$p")
    [ "$c" = 401 ] && ok "أ-٤" "/driver/$p يردّ ٤٠١" \
                   || no "أ-٤" "/driver/$p" "مفتوحٌ بلا توكن — ردّ $c"
  done
  # **والكتابةُ أخطرُ من القراءة** — موقعٌ يُدفع بلا توكن يزوّر خريطة.
  c=$(code -X POST "$A/driver/location" -H 'Content-Type: application/json' \
        -d '{"lat":0,"lng":0}')
  [ "$c" = 401 ] && ok "أ-٤" "دفعُ الموقع بلا توكن يُردّ" \
                 || no "أ-٤" "دفعُ الموقع" "**مرّ بلا توكن — ردّ $c**"
}

# ══════════════════════════════════════════════════════════════════════
# **ب · الدخول**
# ══════════════════════════════════════════════════════════════════════
stage_login(){
  hdr "ب · الدخول"
  local c
  c=$(code -X POST "$A/auth/login" -H 'Content-Type: application/json' \
        -H 'X-RahalGo-Client: drivertest' \
        -d "{\"phone\":\"$PHONE\",\"password\":\"$PASS\"}")
  [ "$c" != 200 ] && { no "أ-١" "الدخول" "ردّ $c"; return 1; }
  TOKEN=$(grep -oP '"access_token":"\K[^"]+' /tmp/dt.json)
  ok "أ-١" "الدخولُ بكلمة المرور"
  [ "$(code -X POST "$A/auth/login" -H 'Content-Type: application/json' \
        -H 'X-RahalGo-Client: drivertest' \
        -d "{\"phone\":\"$PHONE\",\"password\":\"XXwrong99XX\"}")" = 401 ] \
    && ok "أ-١" "كلمةٌ خاطئةٌ تُردّ" || no "أ-١" "كلمةٌ خاطئة" "قُبلت"
}

# ══════════════════════════════════════════════════════════════════════
# **ج · شاشاتُ القراءة**
# ══════════════════════════════════════════════════════════════════════
stage_read(){
  hdr "ج · شاشاتُ القراءة"
  local h="Authorization: Bearer $TOKEN" row ep id name
  for row in "me|أ-١|بطاقتُه" \
             "queue|ب-٣|الطابور" \
             "orders|ج-١|طلباتُه" \
             "orders/history|ط-١|سجلُّه" \
             "orders/report-reasons|ط-٤|أسبابُ البلاغ" \
             "incentives|ي-٦|الهدفُ ومكافأتُه" \
             "cash|ي-٤|الصندوق"; do
    ep=${row%%|*}; id=$(echo "$row"|cut -d'|' -f2); name=$(echo "$row"|cut -d'|' -f3)
    [ "$(code "$A/driver/$ep" -H "$h")" = 200 ] \
      && ok "$id" "$name يُقرأ" || no "$id" "$name" "لم يُقرأ ($ep)"
  done

  # **ط-٤ · وأسبابُ البلاغ من المحرّك لا من الشاشة** — نصوصٌ لا كائنات.
  code "$A/driver/orders/report-reasons" -H "$h" >/dev/null
  local n; n=$(grep -oP '"reasons":\[\K[^]]*' /tmp/dt.json | tr ',' '\n' | grep -c '"')
  [ "$n" -ge 3 ] && ok "ط-٤" "أسبابُ البلاغ $n من المحرّك" \
                 || no "ط-٤" "أسبابُ البلاغ" "عددُها $n"

  # **ز-٣ · وأسبابُ التعذّر كذلك** — ولو كُتبت في الشاشة لاختلفت
  # عمّا يقبله المحرّكُ يومَ يُضاف سبب.
  code "$A/driver/orders/fail-reasons" -H "$h" >/dev/null
  n=$(grep -oP '"reasons":\[\K[^]]*' /tmp/dt.json | tr ',' '\n' | grep -c '"')
  [ "$n" -ge 3 ] && ok "ز-٣" "أسبابُ التعذّر $n من المحرّك" \
                 || sk "ز-٣" "أسبابُ التعذّر" "مسارٌ آخر — عددُها $n"
}

# ══════════════════════════════════════════════════════════════════════
# **د · الحارس — طلبُ غيره**
# ══════════════════════════════════════════════════════════════════════
#
# **والمعرّفاتُ تُخمَّن** — فلا يكفي أن تُخفى الأزرارُ في الشاشة.
# **ولا تُرسل حالةٌ صحيحة** — تُجرَّب على معرّفٍ لا وجودَ له.
stage_guard(){
  hdr "د · حارسُ الملكيّة"
  local h="Authorization: Bearer $TOKEN" c
  c=$(code "$A/driver/orders/$Z" -H "$h")
  [ "$c" = 403 ] || [ "$c" = 404 ] \
    && ok "ط-٥" "قراءةُ طلبٍ ليس له تُردّ ($c)" \
    || no "ط-٥" "طلبُ غيره" "**مرّ — ردّ $c**"

  c=$(code -X POST "$A/driver/orders/$Z/accept" -H "$h" -H 'Content-Type: application/json' -d '{}')
  [ "${c:-0}" -ge 400 ] 2>/dev/null \
    && ok "ط-٥" "قبولُ طلبٍ ليس له يُردّ ($c)" \
    || no "ط-٥" "قبولُ طلبِ غيره" "**مرّ — ويسرق رحلةَ سائقٍ آخر**"

  c=$(code -X POST "$A/driver/orders/$Z/transition" -H "$h" \
        -H 'Content-Type: application/json' -d '{"to":"delivered"}')
  [ "${c:-0}" -ge 400 ] 2>/dev/null \
    && ok "ط-٥" "تسليمُ طلبٍ ليس له يُردّ ($c)" \
    || no "ط-٥" "تسليمُ طلبِ غيره" "**مرّ — ويقيّد مالاً بلا تسليم**"

  c=$(code -X POST "$A/driver/orders/$Z/release" -H "$h" -H 'Content-Type: application/json' -d '{}')
  [ "${c:-0}" -ge 400 ] 2>/dev/null \
    && ok "ط-٥" "إعادةُ طلبٍ ليس له تُردّ ($c)" \
    || no "ط-٥" "إعادةُ طلبِ غيره" "**مرّت — ويحرّر رحلةَ غيره**"
}

# ══════════════════════════════════════════════════════════════════════
# **هـ · المال — يُقرأ ولا يُكتب**
# ══════════════════════════════════════════════════════════════════════
stage_money(){
  hdr "هـ · المال"
  local h="Authorization: Bearer $TOKEN"
  code "$A/driver/cash" -H "$h" >/dev/null
  grep -q '"held"\|"limit"\|"balance"' /tmp/dt.json \
    && ok "ي-٤" "الصندوقُ يردّ ما بذمّته وسقفَه" \
    || no "ي-٤" "الصندوق" "لا حقلَ فيه — $(head -c 120 /tmp/dt.json)"

  code "$A/me/wallet" -H "$h" >/dev/null
  grep -q '"balance"' /tmp/dt.json && ok "ي-٧" "المحفظةُ تُقرأ"

  # **ي-٧ · ولا يرى مالَ غيره** — والمعرّفُ يُخمَّن.
  local c; c=$(code "$A/driver/$Z/cash" -H "$h")
  [ "${c:-0}" -ge 400 ] 2>/dev/null && ok "ي-٧" "صندوقُ غيره يُردّ ($c)" \
    || no "ي-٧" "صندوقُ غيره" "**مرّ — ردّ $c**"
}

# ══════════════════════════════════════════════════════════════════════
# **و · ما لا يُفحص بلا طلبٍ حقيقيّ**
# ══════════════════════════════════════════════════════════════════════
stage_human(){
  hdr "و · ما يحتاج عرضاً أو رحلةً حيّة"
  sk "ج-١" "بطاقةُ العرض: الأجرُ والمسافةُ والمتجر" "لا عرضَ يُصنَع"
  sk "ج-٣" "القبولُ ينقل إلى الرحلة" "كذلك"
  sk "ج-٤" "الاعتذارُ لا يُعاد عرضُه" "كذلك"
  sk "ج-٥" "سائقان على طلبٍ واحد" "**رجلان**"
  sk "د-٢" "شريطُ المراحل السبع" "رحلةٌ حيّة"
  sk "د-٥" "«لك من الزبون» أو «مدفوع مسبقاً»" "كذلك"
  sk "و-١" "الكاميرا تفتح عند التسليم" "كذلك"
  sk "و-٤" "التسليمُ يزيد المحفظةَ والصندوق" "تسليمٌ حقيقيّ"
  sk "ز-١" "«إعادة للطابور» تحرّر ولا تُغلق" "رحلةٌ حيّة"
  sk "ز-٤" "الطارئُ يصل غرفةَ العمليّات" "كذلك"
  sk "ح-١" "الطلبُ الخاصّ: «المطلوب» بلفظ الزبون" "طلبٌ خاصّ"
  sk "ط-٨" "تقييمُ المتجر بعد الطلب" "طلبٌ مُغلق"
}

main(){
  [ -z "$PHONE" ] && { echo "DRV_PHONE و DRV_PASS مطلوبان"; exit 2; }
  printf '\033[1m══ اختبارُ تطبيق السائق · المرحلةُ الأولى: المحرّك ══\033[0m\n   %s\n' "$A"
  stage_anon
  stage_login || true
  [ -n "$TOKEN" ] && { stage_read; stage_guard; stage_money; }
  stage_human
  printf '\n\033[1m══ الحصيلة ══\033[0m\n  نجح %d · سقط %d · بشريّ %d\n' "$OKN" "$NON" "$SKN"
  [ "$NON" -gt 0 ] && printf '\n\033[31mالساقط:\033[0m%b\n' "$FAILED"
  [ "$NON" -eq 0 ]
}
main "$@"
