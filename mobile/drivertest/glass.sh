#!/usr/bin/env bash
# ══════════════════════════════════════════════════════════════════════
# **اختبارُ تطبيق السائق · المرحلةُ الثانية — الزجاج**
# ══════════════════════════════════════════════════════════════════════
#
# # ثلاثةُ محرَّماتٍ في هذا النصّ
#
# **١ · لا يُضغط «موافق»** — البطاقةُ عرضُ طلبٍ لزبونٍ حقيقيّ،
# **وقبولُها يُسند رحلةً إلى نصٍّ آليّ.**
#
# **٢ · لا تُفتح ورديّةٌ ولا تُغلق** — من فتحها أنزل عليه المحرّكُ
# طلباتِ الناس، **ومن أغلقها قطع سائقاً يعمل.**
#
# **٣ · ولا مفتاحَ رجوعٍ في الشاشة الجذر** — أخرجني في المتجر إلى
# تطبيقٍ آخرَ على جهاز المالك ثمّ نقرتُ فيه. **والعودةُ بتبويبٍ سفليّ.**
#
# **ولا نقرةَ عمياء** — كلُّ ضغطةٍ من حدودِ عنصرٍ عُثر عليه بنصّه.

set -u
cd "$(dirname "$0")"
. ../reptest/lib.sh
P=com.rahalgo.driver

cd_(){ local B X1 Y1 X2 Y2
  B=$(grep -F "content-desc=\"$1\"" /tmp/u.xml | grep -oP 'bounds="\[[0-9,]+\]\[[0-9,]+\]' | head -1)
  [ -z "$B" ] && return 1
  X1=$(echo "$B"|grep -oP '\[\K[0-9]+'|sed -n 1p); Y1=$(echo "$B"|grep -oP ',\K[0-9]+'|sed -n 1p)
  X2=$(echo "$B"|grep -oP '\[\K[0-9]+'|sed -n 2p); Y2=$(echo "$B"|grep -oP ',\K[0-9]+'|sed -n 2p)
  echo "$(( (X1+X2)/2 )) $(( (Y1+Y2)/2 ))"; }
tc(){ local Q; Q=$(cd_ "$1") || return 1; a shell input tap $Q; sleep "${2:-3}"; d; }

# tab **تبويبٌ سفليٌّ** — ويُلتقط الأدنى في الشاشة لا الأوّل.
tab(){ local B
  B=$(grep -F "text=\"$1\"" /tmp/u.xml | grep -oP 'bounds="\[[0-9,]+\]\[[0-9,]+\]' \
      | awk -F'[][,]' '{print $6, $2, $3, $5}' | sort -n | tail -1)
  [ -z "$B" ] && return 1
  set -- $B
  a shell input tap $(( ($2+$4)/2 )) $(( ($3+$1)/2 )); sleep 4; d; }
home(){ tab "لوحتي"; }

boot(){ a shell am force-stop $P; a shell am start -n $P/.MainActivity >/dev/null
        sleep 8; d; }

# ══════════════════════════════════════════════════════════════════════
# **أ · الإقلاعُ والتبويبات**
# ══════════════════════════════════════════════════════════════════════
stage_boot(){
  printf '\nأ · الإقلاع\n'
  boot
  has "تسجيل الدخول" && { no "أ-١" "الجلسة" "خرج — الجلسةُ انتهت"; return 1; }
  ok "أ-١" "الجلسةُ المحفوظةُ تدخل مباشرةً"
  local s
  for s in الرحلة الطلبات لوحتي حسابي; do
    has "$s" && ok "أ-١" "تبويبُ «$s» معروض" || no "أ-١" "التبويبات" "لا «$s»"
  done
  for s in القائمة الإشعارات محفظتك تقييمك; do
    cd_ "$s" >/dev/null && ok "أ-١" "زرُّ «$s» في الشريط" || no "أ-١" "الشريط" "لا زرَّ «$s»"
  done
}

# ══════════════════════════════════════════════════════════════════════
# **ب · بطاقةُ العرض — تُقرأ ولا تُمسّ**
# ══════════════════════════════════════════════════════════════════════
stage_offer(){
  printf '\nب · بطاقةُ العرض\n'
  has "طلب جديد" || { sk "ج-١" "بطاقةُ العرض" "لا عرضَ الآن"; return; }
  ok "ج-١" "«طلب جديد» معروضة"
  has "أجرة التوصيل" && ok "ج-١" "الأجرُ مكتوب" || no "ج-١" "الأجر" "غيرُ مكتوب"
  has "المسافة إلى" && ok "ج-١" "المسافةُ مكتوبة" || no "ج-١" "المسافة" "غيرُ مكتوبة"
  has "إجمالي الفاتورة" && ok "ج-١" "إجماليُّ الفاتورة مكتوب"

  # **ج-٢ · نقداً أو محفظة — ولا يُخلطان.**
  local cash=0 wal=0
  has "عند التسليم" && cash=1
  has "مدفوع" && wal=1
  [ $((cash+wal)) = 1 ] && ok "ج-٢" "طريقةُ دفعٍ واحدةٌ لا اثنتان" \
    || no "ج-٢" "طريقةُ الدفع" "**نقدٌ=$cash ومحفظةٌ=$wal — والخلطُ يُفقد السائقَ مالَه**"

  # **ج-٤ · لا زرَّ رفضٍ — قرارٌ لا نقص.**
  has "موافق" && ok "ج-٤" "«موافق» معروض — ولم يُضغط"
  local bad=0 s
  for s in "رفض" "اعتذر" "تجاهل"; do has "$s" && bad=1; done
  [ "$bad" = 0 ] && ok "ج-٤" "**لا زرَّ رفضٍ — والعدّادُ يفعل ما كان يفعله**" \
                 || no "ج-٤" "زرُّ الرفض" "ظهر — والقرارُ أن يُحذف"
}

# ══════════════════════════════════════════════════════════════════════
# **ج · لوحتي — الورديّةُ والصندوقُ والهدف**
# ══════════════════════════════════════════════════════════════════════
#
# **ولا يُقلب مفتاحُ الورديّة** — يُقرأ حالُه وشرحُه.
stage_board(){
  printf '\nج · لوحتي — والورديّةُ لا تُقلب\n'
  tab "لوحتي" || { no "ب-١" "لوحتي" "لم تُفتح"; return; }

  has "بالعمل" || has "خارج العمل" \
    && ok "ب-١" "مفتاحُ الورديّة معروض" || no "ب-١" "الورديّة" "لا مفتاح"
  has "الآن تستقبل الطلبات" && ok "ب-٢" "«الآن تستقبل الطلبات»"
  has "لا يمكنك استقبال الطلبات" && ok "ب-٢" "«لا يمكنك استقبال الطلبات — أنت خارج العمل»"

  has "مدين للمكتب" && ok "ي-٥" "«مدين للمكتب بـ» في اللوحة"
  has "يبقى" && ok "ي-٦" "الهدفُ: «يبقى … طلبا»"
  has "نلت المكافأة" && ok "ي-٦" "«نلت المكافأة»"
  up 2
  has "مدين للمكتب" && ok "ي-٥" "«مدين للمكتب» بعد التمرير"
}

# ══════════════════════════════════════════════════════════════════════
# **د · الطلبات — وخمسةُ أسبابٍ لفراغ الطابور**
# ══════════════════════════════════════════════════════════════════════
#
# **ومن رأى شاشةً فارغةً بلا سبب ظنّ التطبيقَ عطبان وأغلقه.**
stage_queue(){
  printf '\nد · الطابورُ وسببُ فراغه\n'
  tab "الطلبات" || { no "ب-٣" "الطلبات" "لم تُفتح"; return; }
  if ! has "لا يوجد طلب معروض عليك الآن"; then
    sk "ب-٣" "فراغُ الطابور" "الطابورُ غيرُ فارغٍ الآن"
    return
  fi
  ok "ب-٣" "«لا يوجد طلب معروض عليك الآن»"
  local n=0 s
  for s in "وردیتك مغلقة" "ورديتك مغلقة" "الموقع مطفأ" \
           "النقد الذي بذمتك بلغ السقف" "معك طلبات بعدد حدك" "كل شيء جاهز"; do
    has "$s" && { ok "ب-٣" "وسببُه: $s"; n=$((n+1)); }
  done
  [ "$n" = 0 ] && no "ب-٣" "سببُ الفراغ" "**فراغٌ صامت — ومن رآه ظنّ التطبيقَ عطبان**"
}

# ══════════════════════════════════════════════════════════════════════
# **هـ · الرحلة**
# ══════════════════════════════════════════════════════════════════════
stage_trip(){
  printf '\nهـ · الرحلة\n'
  tab "الرحلة" || { no "د-١" "الرحلة" "لم تُفتح"; return; }
  if has "لا رحلة الآن"; then
    ok "د-١" "«لا رحلة الآن»"
    has "خذ طلبا" && ok "د-١" "**ومعها «خذ طلبا… وتبدأ رحلتك»**" \
                  || no "د-١" "فراغُ الرحلة" "فراغٌ بلا إرشاد"
    sk "د-٢" "شريطُ المراحل السبع" "لا رحلةَ حيّة"
    return
  fi
  ok "د-٢" "رحلةٌ حيّةٌ معروضة"
  local s
  for s in "قبلت الطلب" "إلى المتجر" "عند المتجر" "استلمت" "إلى الزبون" \
           "عند الزبون" "سلّمت"; do
    has "$s" && ok "د-٢" "مرحلة: $s"
  done
  has "لك من الزبون" && ok "د-٥" "«لك من الزبون» — نقداً"
  has "مدفوع مسبقا" && ok "د-٥" "«مدفوع مسبقاً» — محفظة"
  has "إعادة للطابور" && ok "ز-١" "«إعادة للطابور» معروض — ولم يُضغط"
}

# ══════════════════════════════════════════════════════════════════════
# **و · القائمةُ — الصندوقُ والشكاوى والتقييم**
# ══════════════════════════════════════════════════════════════════════
stage_drawer(){
  printf '
و · القائمة
'
  # **وتبويبُ الرحلة خريطةٌ ملءَ الشاشة بلا شريطٍ علويّ** — فمن جاء
  # منه لم يجد «القائمة». (وقع في أوّل تشغيل.)
  home
  tc "القائمة" 4 || { no "ي-١" "القائمة" "لم تُفتح"; return; }
  local s
  # **وأسماؤها كما هي في القائمة لا كما ظننتُها** — «صندوقي» لا
  # «النقد»، **و«الشكاوى والبلاغات» لا «الشكاوى».** (وقع في أوّل تشغيل:
  # نقرةٌ لم تقع، **فقُرئت القائمةُ نفسُها وحُسبت الشكاوى ساقطة.**)
  for s in "سجل الطلبات" "صندوقي" "أهدافي والمكافآت" "الشكاوى والبلاغات"; do
    has "$s" && ok "ي-١" "القائمةُ فيها «$s»" || no "ي-١" "القائمة" "لا «$s»"
  done

  t "صندوقي" 5 >/dev/null && {
    has "النقد الذي قبضته ولم تسلمه بعد"       && ok "ي-١" "**«النقد الذي قبضته ولم تسلمه بعد»**"       || no "ي-١" "شرحُ الصندوق" "غائب — ورقمٌ بلا شرحٍ يُساء فهمُه"
    has "اقتربت من السقف" && ok "ي-٢" "«اقتربت من السقف — سلم النقد قبل أن يتوقف الطابور عنك»"
    has "بلغت السقف" && ok "ي-٣" "«بلغت السقف — لا تقبل طلبات نقدية حتى تسلم»"
    home; }

  tc "القائمة" 4 && t "الشكاوى والبلاغات" 5 >/dev/null && {
    has "ما رفع عليك" && has "ما رفعته أنت"       && ok "ط-٢" "**تبويبان: «ما رفع عليك» و«ما رفعته أنت»**"       || no "ط-٢" "الشكاوى" "**ليسا تبويبين — والخلطُ يقلب المعنى**"
    home; }

  tc "القائمة" 4 && t "أهدافي والمكافآت" 5 >/dev/null && {
    ok "ي-٦" "شاشةُ الأهداف تُفتح"; home; }

  tc "القائمة" 4 && t "سجل الطلبات" 5 >/dev/null && {
    ok "ط-١" "السجلُّ يُفتح"
    has "لا طلبات" || has "بحث" && ok "ط-١" "السجلُّ فيه بحثٌ أو فراغٌ منطوق"
    home; }

  # **ط-٦ · وتقييمُه زرٌّ في الشريط لا بندٌ في القائمة.**
  tc "تقييمك" 5 && {
    ok "ط-٦" "شاشةُ التقييم تُفتح"
    has "لا مراجعات" && ok "ط-٧" "«لا مراجعات بعد» — لا فراغٌ صامت"
    home; }
}

# ══════════════════════════════════════════════════════════════════════
# **ز · الضغطُ المكرَّرُ والتنقّلُ السريع**
# ══════════════════════════════════════════════════════════════════════
stage_stress(){
  printf '\nز · الضغطُ المكرَّرُ\n'
  local i
  for i in 1 2 3; do tf "لوحتي"; tf "الطلبات"; tf "الرحلة"; tf "حسابي"; done
  sleep 5; d
  a shell "pidof $P" | grep -q . \
    && ok "ز-٧" "اثنتا عشرةَ نقلةً سريعةً — والتطبيقُ حيّ" \
    || { no "ز-٧" "التنقّلُ السريع" "**التطبيقُ مات**"; return; }
  tc "القائمة" 2 >/dev/null; tf "القائمة"; sleep 3; d
  a shell "pidof $P" | grep -q . \
    && ok "ز-٧" "القائمةُ بلا انهيار" || no "ز-٧" "القائمة" "**انهارت**"
  home
}

main(){
  [ -z "${S:-}" ] && { echo "لا جهاز"; exit 2; }
  printf '══ اختبارُ تطبيق السائق · المرحلةُ الثانية: الزجاج ══\n  %s\n' "$S"
  stage_boot || { printf '\nنجح %d · سقط %d\n' "$OKN" "$NON"; exit 1; }
  stage_offer; stage_board; stage_queue; stage_trip; stage_drawer; stage_stress
  printf '\n══ الحصيلة ══\n  نجح %d · سقط %d\n' "$OKN" "$NON"
  [ "$NON" -eq 0 ]
}
main "$@"
