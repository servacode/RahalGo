#!/usr/bin/env bash
# ══════════════════════════════════════════════════════════════════════
# **المرحلةُ الثانية — الزجاج: بصريّاً ووظيفيّاً**
# ══════════════════════════════════════════════════════════════════════
#
# (طلبُ المالك ٢٠٢٦-٠٨-٣٠: «لا نريد فقط اختباراً وظيفيّاً أو برمجيّاً —
#  بل بصريّاً ووظيفيّاً وبرمجيّاً، وكلّ النواحي بالخلفيّة والتطبيق،
#  وماذا يحدث بكلّ حالةٍ من الحالات المذكورة».)
#
# # وثلاثُ عيونٍ في كلّ خطوة
#
#     🖥  ما يُعرض  — نصُّ الشاشة من `uiautomator`
#     📷  ما يُرى   — لقطةٌ تُحفظ ليراها إنسان
#     ⚙  ما يجري  — `logcat` والمحرّك
#
# **ونصُّ الشاشة يُقرأ ولا يُفترض**: من فحص «أفُتحت الشاشة؟» بلا قراءةِ
# نصِّها **يمرّ على شاشةٍ فارغةٍ ويقول نجحت.**
#
# # ولا نقرةَ عمياء
#
# **كلُّ ضغطةٍ تُحسب من حدودِ عنصرٍ يُعثر عليه بنصّه** — لا بإحداثيّاتٍ
# مكتوبةٍ في السكربت. **وإحداثيّةٌ ثابتةٌ تشيخ بأوّل تبديلِ تخطيط**،
# ثمّ تضغط ما لم تقصده — **وقع فعلاً ٢٠٢٦-٠٨-٣٠.**
#
# # وما لا تفعله
#
# **لا تحكم على الجمال** — التناسقَ والمسافات. **تحفظ اللقطاتِ ليحكم
# إنسان**، وتؤكّد على ما يُقرأ نصّاً.

set -u
PKG=com.rahalgo.rep
SHOT="${SHOT_DIR:-/tmp/reptest-shots}"
mkdir -p "$SHOT"

PASS_N=0; FAIL_N=0; SKIP_N=0; STEP=0
FAILED=""

ok() { PASS_N=$((PASS_N+1)); printf '  \033[32m✔\033[0m %-8s %s\n' "$1" "$2"; }
no() { FAIL_N=$((FAIL_N+1)); FAILED="$FAILED\n  $1  $2 — $3"
       printf '  \033[31m✗\033[0m %-8s %s\n      \033[31m%s\033[0m\n' "$1" "$2" "$3"; }
sk() { SKIP_N=$((SKIP_N+1)); printf '  \033[33m؟\033[0m %-8s %s — %s\n' "$1" "$2" "$3"; }
hdr() { printf '\n\033[1m%s\033[0m\n' "$1"; }

adb_() { timeout 60 adb "$@" 2>/dev/null; }

# dump **يقرأ شجرةَ الشاشة.** — وتُحفظ لتُستعمل مرّاتٍ بلا إعادة قراءة.
dump() { adb_ exec-out uiautomator dump /dev/tty | tr '<' '\n<' > /tmp/rt-ui.xml; }

# txt **نصوصُ الشاشة سطراً سطراً.**
txt() { grep -oP 'text="\K[^"]+' /tmp/rt-ui.xml | grep -v '^$'; }

# has **أفي الشاشة هذا النصّ؟**
has() { txt | grep -qF "$1"; }

# shot **لقطةٌ مرقَّمةٌ باسم الخطوة** — ليقرأها إنسانٌ بعد التشغيل.
shot() { STEP=$((STEP+1)); adb_ exec-out screencap -p > "$SHOT/$(printf '%02d' $STEP)-$1.png"; }

# bounds **حدودُ عنصرٍ بنصّه** — ويردّ «س ص» مركزَه.
#
# **ويُعثر عليه بنصّه لا بموضعه** — فلا يشيخ الفحصُ بتبديل تخطيط.
center() {
  local b
  b=$(grep -F "text=\"$1\"" /tmp/rt-ui.xml | grep -oP 'bounds="\[[0-9,]+\]\[[0-9,]+\]' | head -1)
  [ -z "$b" ] && return 1
  local x1 y1 x2 y2
  x1=$(echo "$b" | grep -oP '\[\K[0-9]+' | sed -n 1p)
  y1=$(echo "$b" | grep -oP ',\K[0-9]+' | sed -n 1p)
  x2=$(echo "$b" | grep -oP '\[\K[0-9]+' | sed -n 2p)
  y2=$(echo "$b" | grep -oP ',\K[0-9]+' | sed -n 2p)
  echo "$(( (x1+x2)/2 )) $(( (y1+y2)/2 ))"
}

# tap_ **يضغط عنصراً بنصّه** — ويقول أين ضغط.
tap_() {
  local c; c=$(center "$1") || { echo "      لا عنصرَ نصُّه «$1»"; return 1; }
  adb_ shell input tap $c
  sleep "${2:-2}"
  dump
}

# type_ **يكتب في حقلٍ عنوانُه كذا.**
type_() {
  local c; c=$(center "$1") || return 1
  adb_ shell input tap $c
  adb_ shell input text "$2"
  adb_ shell input keyevent 4
  sleep 1
  dump
}

# crashed **أوقع انهيارٌ منذ آخر مسح؟**
crashed() {
  adb_ logcat -d 2>/dev/null | grep -E "FATAL EXCEPTION|ANR in $PKG" | grep -c "$PKG"
}

# ══════════════════════════════════════════════════════════════════════
# **أ · الإقلاع**
# ══════════════════════════════════════════════════════════════════════
stage_boot() {
  hdr "أ · الإقلاعُ والدخول"
  adb_ logcat -c
  adb_ shell am force-stop $PKG
  local t0 t1
  t0=$(date +%s%N)
  adb_ shell am start -n $PKG/.MainActivity >/dev/null
  sleep 5
  t1=$(date +%s%N)
  dump; shot boot

  local ms=$(( (t1-t0)/1000000 ))
  [ "$ms" -lt 6000 ] && ok "أ-١" "يُقلع في $ms ملّي" \
                     || no "أ-١" "الإقلاع" "$ms ملّي — بطيء"

  # **وشاشتان مقبولتان**: الدخولُ إن لم تكن جلسة، أو لوحتُه إن كانت.
  if has "تسجيل الدخول"; then
    ok "ب-١" "شاشةُ الدخول: «تسجيل الدخول» بلا ذكر الدور"
    has "إنشاء حساب" && no "ب-٢" "بابُ إنشاء حساب" "ظاهرٌ وهو ممنوعٌ للمندوب" \
                     || ok "ب-٢" "لا بابَ لإنشاء حساب"
    LOGGED=0
  elif has "لوحتي"; then
    ok "ب-٣" "الجلسةُ محفوظةٌ — دخل مباشرةً"
    LOGGED=1
  else
    no "أ-١" "أوّلُ شاشة" "ليست دخولاً ولا لوحة: $(txt | head -3 | tr '\n' '/')"
    LOGGED=-1
  fi
}

stage_login() {
  [ "${LOGGED:-0}" != 0 ] && return 0
  hdr "ب · تسجيلُ الدخول"
  type_ "رقم الهاتف" "${REP_PHONE_LOCAL:-0997518432}"
  type_ "كلمة المرور" "${REP_PASS:-}"
  shot login-filled
  tap_ "تسجيل الدخول" 6
  shot after-login
  has "لوحتي" && ok "ب-٣" "الدخولُ نجح" || no "ب-٣" "الدخول" "لم تظهر لوحتي"
}

# ══════════════════════════════════════════════════════════════════════
# **ب · لوحتي — وأرقامُها تُقرأ لا تُفترض**
# ══════════════════════════════════════════════════════════════════════
stage_board() {
  hdr "ج · لوحتي"
  dump; shot board

  has "هدف الشهر" && ok "ج-١" "بطاقةُ الهدف تُعرض" \
                  || no "ج-١" "بطاقةُ الهدف" "غائبة"

  # ════════════════════════════════════════════════════════════════
  # **والوحدةُ «طلب» لا «عميل»**
  # ════════════════════════════════════════════════════════════════
  #
  # **كان النصُّ يقول «بقي ٧ عميلاً» والمحرّكُ يعدّ الطلبات** — فيوجّه
  # المندوبَ إلى فتح متاجرَ بدل إنجاح ما فتح. **وهذا الفحصُ يمنع
  # عودتَه.**
  if txt | grep -qP 'بقي .* عميل'; then
    no "ج-٥" "وحدةُ الهدف" "يقول «عميلاً» والمحرّكُ يعدّ الطلبات"
  elif txt | grep -qP 'بقي .* طلب' || has "تحقق الهدف"; then
    ok "ج-٥" "الهدفُ بالطلبات لا بالعملاء"
  else
    sk "ج-٥" "وحدةُ الهدف" "لا شريطَ ظاهر — الهدفُ صفرٌ ربّما"
  fi

  local k
  for k in "هذا الشهر:ج-١" "منذ بدأت:ج-٢" "رصيد المحفظة:ج-٢"; do
    has "${k%%:*}" && ok "${k##*:}" "«${k%%:*}» تُعرض" \
                   || no "${k##*:}" "«${k%%:*}»" "غائبة"
  done

  # **ورمزُ الدعوة: إمّا رمزٌ وإمّا سببُ قفله** — ولا فراغَ صامت.
  adb_ shell input swipe 540 1800 540 700 400; sleep 2; dump; shot board-bottom
  if has "رمزك للمتاجر"; then
    if txt | grep -q "وثق حسابك"; then
      ok "ج-٤" "الرمزُ مقفلٌ ويقول لماذا"
      txt | grep -q "واتساب" \
        && no "ب-١٥" "نصُّ التوثيق" "ما زال يسمّي القناة" \
        || ok "ب-١٥" "لا تُسمّى قناةُ التوثيق"
    else
      ok "ج-٣" "الرمزُ يُعرض"
    fi
  else
    no "ج-٣" "بطاقةُ الرمز" "غائبة"
  fi
}

# ══════════════════════════════════════════════════════════════════════
# **ج · إضافةُ عميل — وأخطرُ فحصٍ فيها بقاءُ ما كُتب**
# ══════════════════════════════════════════════════════════════════════
stage_add() {
  hdr "د · إضافةُ عميل"
  tap_ "إضافة عميل" 4; shot add-empty

  has "المحافظة" && ok "د-١٤" "حقلُ المحافظة موجود" \
                 || no "د-١٤" "المحافظة" "غائبةٌ عن النموذج"

  # **ولا يُرسم لوحُ المناطق قبل اختيار محافظة.**
  local before after
  before=$(txt | grep -c "مركز")
  has "المنطقة" && [ "$before" = 0 ] \
    && ok "د-١٤" "لوحُ المناطق فارغٌ قبل اختيار محافظة" \
    || sk "د-١٤" "لوحُ المناطق" "حالٌ لم تُقرأ بوضوح"

  # **ثلاثةُ حقولٍ تُكتب ثمّ تُفتح الخريطةُ ويُرجع** — عطبُ ٢٠٢٦-٠٨-٣٠.
  type_ "اسم المتجر" "QAstore"
  type_ "اسم صاحبه" "QAowner"
  type_ "رقم الهاتف" "0900000101"
  shot add-filled

  if has "QAstore" && has "QAowner"; then
    ok "د-١" "الحقولُ الثلاثةُ تُكتب"
  else
    no "د-١" "الكتابة" "لم تظهر القيمُ في الحقول"
    return
  fi

  # ════════════════════════════════════════════════════════════════
  # **وهذا هو الفحص**
  # ════════════════════════════════════════════════════════════════
  #
  # **`when` كان يُخرج الشاشةَ من التركيب فتضيع حالتُها** — والمندوبُ
  # يعود من الخريطة فيجد ما كتبه ممحوّاً. **ولا رسالةَ ولا انهيار.**
  adb_ shell input swipe 540 1800 540 900 400; sleep 2; dump
  if tap_ "حدد نقطة المتجر على الخريطة" 6 || tap_ "بدل النقطة" 6; then
    shot map
    has "تأكيد الموقع" && ok "د-٤" "الخريطةُ تُفتح" \
                       || no "د-٤" "الخريطة" "لم تُفتح: $(txt | head -2 | tr '\n' '/')"
    adb_ shell input keyevent 4; sleep 4; dump; shot back-from-map
    if has "QAstore" && has "QAowner"; then
      ok "د-١٢" "ما كُتب يبقى بعد الخريطة والرجوع"
    else
      no "د-١٢" "بقاءُ الحقول" "**مُحيت بفتح الخريطة** — والمندوبُ يكتبها ثانيةً أو يترك"
    fi
  else
    no "د-٤" "زرُّ الخريطة" "لم يُعثر عليه"
  fi

  # **وتبديلُ المحافظة يمسح المنطقة.**
  adb_ shell input swipe 540 900 540 1800 400; sleep 2; dump
  local g1 g2
  g1=$(txt | grep -m1 -P '^(الرقة|حلب|دمشق)$')
  if [ -n "$g1" ] && tap_ "$g1" 4; then
    if txt | grep -qP '^(مركز|تل|الثورة|أعزاز)'; then
      ok "د-١٤" "اختيارُ محافظةٍ يُظهر مناطقَها"
    else
      no "د-١٤" "مناطقُ المحافظة" "لم تظهر بعد اختيارها"
    fi
  else
    sk "د-١٤" "اختيارُ محافظة" "لم يُعثر على رقاقة"
  fi
}

# ══════════════════════════════════════════════════════════════════════
# **د · عملائي والأصناف**
# ══════════════════════════════════════════════════════════════════════
stage_clients() {
  hdr "هـ · عملائي والأصناف"
  tap_ "عملائي" 5; shot clients
  has "عملائي" && ok "هـ-١" "شاشةُ عملائي تُفتح" \
               || no "هـ-١" "عملائي" "لم تُفتح"

  txt | grep -qP 'يعملون|ينتظرون البت|لم تسجل عميلا' \
    && ok "هـ-٢" "القائمةُ تعرض حالاً أو فراغاً مفهوماً" \
    || no "هـ-٢" "قائمةُ العملاء" "لا قسمَ ولا رسالةَ فراغ"

  # **وتفصيلُ عميلٍ إن وُجد.**
  local first
  first=$(txt | grep -A1 "يعملون" | tail -1)
  if [ -n "$first" ] && tap_ "$first" 5; then
    shot client-detail
    has "الأصناف" && ok "هـ-٨" "بابُ الأصناف موجود" \
                  || no "هـ-٨" "بابُ الأصناف" "غائب"
    has "صافي عمولتي" && ok "هـ-٥" "مجاميعُ العميل تُعرض" \
                      || no "هـ-٥" "مجاميعُ العميل" "غائبة"
    if tap_ "الأصناف" 5; then
      shot menu
      has "صنف جديد" && ok "و-٥" "زرُّ «صنف جديد» موجود" \
                     || no "و-٥" "صنف جديد" "غائب"
      if tap_ "صنف جديد" 4; then
        shot new-item
        has "سعر المتجر" && ok "و-٦" "«سعر المتجر» — اللفظُ الموحَّد" \
                         || no "و-٦" "لفظُ السعر" "ليس «سعر المتجر»"
        has "قسم المنصة" && ok "و-٦" "«قسم المنصة» — اللفظُ الموحَّد" \
                         || no "و-٦" "لفظُ القسم" "ليس «قسم المنصة»"
        # **وحفظٌ بلا اسمٍ يقول لماذا** — كان صمتاً تامّاً.
        adb_ shell input swipe 540 1800 540 500 300; sleep 1
        adb_ shell input swipe 540 1800 540 500 300; sleep 1
        adb_ shell input swipe 540 1800 540 500 300; sleep 2; dump
        # ══════════════════════════════════════════════════════════
        # **ورسالةُ `Flash` تعيش أربعَ ثوانٍ**
        # ══════════════════════════════════════════════════════════
        #
        # **فتُقرأ من أوّل شجرةٍ بعد الضغط لا من ثانية** — وقراءةُ
        # الشجرة نفسُها تستغرق ثانيتين، **فقراءتان تستهلكان عمرَ
        # الرسالة فتُقرأ الشاشةُ صامتةً ويُتّهم التطبيق.**
        #
        # (وقع في أوّل تشغيلٍ لهذا الفحص ٢٠٢٦-٠٨-٣٠ — **والعطبُ كان
        #  في الفحص لا في التطبيق.**)
        if tap_ "حفظ" 0; then
          has "اكتب اسم الصنف" \
            && ok "و-١٥" "حفظٌ باسمٍ فارغٍ يقول «اكتب اسم الصنف»" \
            || no "و-١٥" "رسالةُ الحفظ" "صمتٌ — والزرُّ يبدو معطوباً"
          shot save-empty
        fi
      fi
    fi
  else
    sk "هـ-٥" "تفصيلُ العميل" "لا عميلَ فعّالٌ ليُفتح"
  fi
}

# ══════════════════════════════════════════════════════════════════════
# **هـ · حسابي والقائمة الجانبيّة**
# ══════════════════════════════════════════════════════════════════════
stage_account() {
  hdr "و · حسابي والقائمة"
  adb_ shell input keyevent 4; sleep 2
  adb_ shell input keyevent 4; sleep 2
  tap_ "حسابي" 5; shot account
  has "الاسم الكامل" && ok "ب-٧" "شاشةُ حسابي تُفتح" \
                     || no "ب-٧" "حسابي" "لم تُفتح"

  # **ونصُّ التوثيق بلا شرحٍ ولا قناة** — تصحيحُ ٢٠٢٦-٠٨-٣٠.
  if has "حسابك غير موثق" || has "حسابك موثق"; then
    ok "ب-١٥" "حالُ التوثيق تُعرض"
    txt | grep -q "لا تفتح دوامك" \
      && no "ب-١٥" "نصُّ التوثيق" "ما زال «لا تفتح دوامك قبل التوثيق»" \
      || ok "ب-١٥" "لا نهيَ عن فتح الدوام"
    txt | grep -q "سيفتح واتساب" \
      && no "ب-١٥" "شرحُ التوثيق" "ما زال معروضاً" \
      || ok "ب-١٥" "لا شرحَ للتوثيق"
  else
    no "ب-١٥" "حالُ التوثيق" "لا تُعرض"
  fi
}

# ══════════════════════════════════════════════════════════════════════
# **و · الانهيارات — طوالَ المشي**
# ══════════════════════════════════════════════════════════════════════
stage_crash() {
  hdr "ز · الانهيارات"
  local n; n=$(crashed)
  [ "$n" = 0 ] && ok "ط-٥" "صفرُ انهيارٍ في الجولة كلِّها" \
               || no "ط-٥" "انهيار" "$n سطرَ FATAL/ANR — انظر logcat"
}

main() {
  adb devices | grep -q "device$" || { echo "لا جهازَ موصول"; exit 2; }
  printf '\033[1m══ اختبارُ تطبيق المندوب · المرحلةُ الثانية: الزجاج ══\033[0m\n'
  printf '   اللقطات: %s\n' "$SHOT"
  stage_boot
  stage_login
  stage_board
  stage_add
  stage_clients
  stage_account
  stage_crash
  printf '\n\033[1m══ الحصيلة ══\033[0m\n'
  printf '  نجح %d · سقط %d · لم يُقرَّر %d · لقطات %d\n' \
         "$PASS_N" "$FAIL_N" "$SKIP_N" "$STEP"
  [ "$FAIL_N" -gt 0 ] && printf '\n\033[31mالساقط:\033[0m%b\n' "$FAILED"
  [ "$FAIL_N" -eq 0 ]
}
main "$@"
