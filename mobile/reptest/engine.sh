#!/usr/bin/env bash
# ══════════════════════════════════════════════════════════════════════
# **المرحلةُ الأولى — طبقةُ المحرّك**
# ══════════════════════════════════════════════════════════════════════
#
# (طلبُ المالك ٢٠٢٦-٠٨-٣٠: «أنشئ اختباراً عبر مراحل ونفّذها بشكل كامل…
#  كأنّك مندوبٌ تريد استخراج العيوب».)
#
# # ولماذا لا تُشبه المنظومةَ السابقة
#
# **تلك كانت تقرأ الشيفرةَ ولا تستعمل التطبيق** — اثنا عشرَ حارساً عن
# شكلِ الكود، وفحصُ جهازٍ يسأل «أحيٌّ؟ كم ذاكرة؟». **فمرّت خضراءَ
# والتطبيقُ مكسور** (حكمُ المالك: «فاشلة بصراحة»).
#
# **وهذه تنادي ما يناديه التطبيقُ حرفاً** — بالنقاط نفسِها والرؤوس
# نفسِها — **وتؤكّد على ما يردّه المحرّكُ لا على ما في الملفّ.**
#
# # ومصدرُها العقدُ لا رأيي
#
# **كلُّ فحصٍ هنا بندٌ مرقَّمٌ في `docs/تطبيق-المندوب.md`** — ولا يُفحص
# ما لم نتّفق أنّه صواب، **ولا يبقى بندٌ بلا فحصٍ إلّا معلَّماً `؟`.**
#
# # وما لا تفعله
#
# **لا تلمس الزجاج** — تلك المرحلةُ الثانية (`glass.sh`). **ولا تحكم
# على جمالٍ ولا سرعةِ تمرير.**

set -u
A="${API:-https://api.rahalgo.com/api/v1}"
PHONE="${REP_PHONE:-}"
PASS="${REP_PASS:-}"

PASS_N=0; FAIL_N=0; SKIP_N=0
FAILED=""

# ok **يسجّل نتيجةَ بندٍ من العقد.**
#
# **والرقمُ أوّلاً** — فمن قرأ سطراً في المخرَج وجد بندَه في الوثيقة
# **بلا بحث**، ومن أراد إصلاحَه عرف ما اتّفقنا عليه.
ok() { PASS_N=$((PASS_N+1)); printf '  \033[32m✔\033[0m %-8s %s\n' "$1" "$2"; }
no() { FAIL_N=$((FAIL_N+1)); FAILED="$FAILED\n  $1  $2 — $3"
       printf '  \033[31m✗\033[0m %-8s %s\n      \033[31m%s\033[0m\n' "$1" "$2" "$3"; }
sk() { SKIP_N=$((SKIP_N+1)); printf '  \033[33m؟\033[0m %-8s %s — %s\n' "$1" "$2" "$3"; }

# code **رمزُ الرَّدّ لنداءٍ.** — والزمنُ معه: بطءٌ عطبٌ أيضاً.
code() { curl -s -o /tmp/rt.json -w '%{http_code}' --max-time 30 "$@"; }
body() { cat /tmp/rt.json; }
errcode() { grep -oP '"code":"\K[^"]+' /tmp/rt.json 2>/dev/null | head -1; }

hdr() { printf '\n\033[1m%s\033[0m\n' "$1"; }

# ══════════════════════════════════════════════════════════════════════
# **أ · ما يُقرأ بلا حساب**
# ══════════════════════════════════════════════════════════════════════
#
# **ونموذجُ التسجيل يقرؤها قبل أن يسجّل أحد** — فلو طُلب توكنٌ لَوقف
# من جاء يفتح متجرَه عند أوّل حقل.
stage_public() {
  hdr "أ · القراءةُ العامّة"

  # **والعدُّ يُقرأ بعد النداء لا داخلَ شرطه** — **و`[ ]` المتسلسلةُ
  # تُشغّل `code` في صدفةٍ فرعيّةٍ فتكتب ملفّاً لا يراه ما بعدها.**
  # ════════════════════════════════════════════════════════════════
  # **والمعروضُ هو الفعّالُ لا المبذور**
  # ════════════════════════════════════════════════════════════════
  #
  # **وتوقُّعُ «أربعَ عشرةَ» كان خطأً في الفحص لا في المنصّة** (٢٠٢٦-٠٨-٣٠):
  # بُذرت أربعَ عشرةَ، **وأطفأ المالكُ إحدى عشرةَ من اللوحة** وأبقى
  # الرقّةَ وحلبَ ودمشق — **وهو الغرضُ من الإطفاء بعينه.**
  #
  # **فيُفحص أنّ فيها واحدةً على الأقلّ** — وأنّ العددَ يُقرأ بـ`wc`
  # لا بـ`grep -c`: **الأخيرُ يعدّ الأسطرَ لا المطابقات**، والردُّ
  # سطرٌ واحد.
  local c n
  c=$(code "$A/public/governorates"); n=$(grep -o '"name"' /tmp/rt.json | wc -l)
  if [ "$c" = 200 ] && [ "$n" -ge 1 ]; then
    ok "د-١٤" "المحافظاتُ الفعّالةُ تُقرأ ($n)"
  else
    no "د-١٤" "المحافظات" "ردّ $c وعددُها $n"
  fi

  local g
  g=$(grep -oP '"id":"\K[^"]+' /tmp/rt.json | head -1)
  [ "$(code "$A/public/districts?governorate_id=$g")" = 200 ] \
    && [ "$(body | grep -oc '"name"')" -ge 1 ] \
    && ok "د-١٤" "مناطقُ محافظةٍ تُقرأ" \
    || no "د-١٤" "المناطق" "لم تُقرأ"

  # **والحالُ السالبةُ أهمُّ من الموجبة** — المستخدمُ يعيش فيها.
  [ "$(code "$A/public/districts")" = 400 ] \
    && ok "د-١٤" "مناطقُ بلا محافظةٍ تُردّ" \
    || no "د-١٤" "مناطقُ بلا وسيط" "قُبلت — والمتوقّع ٤٠٠"

  [ "$(code "$A/public/districts?governorate_id=abc")" = 400 ] \
    && ok "د-١٤" "نصٌّ حرٌّ في حقل المحافظة يُردّ" \
    || no "د-١٤" "نصٌّ حرّ" "قُبل — والقائمةُ لا تحرس من يرسل بيده"
}

# ══════════════════════════════════════════════════════════════════════
# **ب · الأبوابُ مقفلةٌ بلا توكن**
# ══════════════════════════════════════════════════════════════════════
stage_guards_anon() {
  hdr "ب · الأبوابُ بلا توكن"
  local p
  for p in me leads merchants categories wallet incentives; do
    [ "$(code "$A/rep/$p")" = 401 ] \
      && ok "ي-٤" "/rep/$p يردّ ٤٠١" \
      || no "ي-٤" "/rep/$p" "مفتوحٌ بلا توكن — رمزُه $(cat /tmp/rt.json >/dev/null; code "$A/rep/$p")"
  done
}

# ══════════════════════════════════════════════════════════════════════
# **ج · الدخولُ وشاشاتُ القراءة**
# ══════════════════════════════════════════════════════════════════════
TOKEN=""
stage_login() {
  hdr "ج · الدخولُ ولوحتي"

  # **وعميلٌ باسمه** — `android-rep`: **دخولٌ جديدٌ يُبطل ما سبق من
  # نوعه**، فلا يُقطع من يجرّب على الجهاز إن اختلف النوع.
  local c
  c=$(code -X POST "$A/auth/login" -H 'Content-Type: application/json' \
        -H 'X-RahalGo-Client: reptest' \
        -d "{\"phone\":\"$PHONE\",\"password\":\"$PASS\"}")
  if [ "$c" != 200 ]; then
    no "ب-٣" "الدخول" "ردّ $c"
    return 1
  fi
  TOKEN=$(grep -oP '"access_token":"\K[^"]+' /tmp/rt.json)
  ok "ب-٣" "الدخولُ بكلمة المرور"

  # **وكلمةٌ خاطئةٌ تُردّ برسالةٍ لا تكشف أيَّ الحقلين أخطأ.**
  [ "$(code -X POST "$A/auth/login" -H 'Content-Type: application/json' \
        -H 'X-RahalGo-Client: reptest' \
        -d "{\"phone\":\"$PHONE\",\"password\":\"XXwrongXX99\"}")" = 401 ] \
    && ok "ب-٣" "كلمةٌ خاطئةٌ تُردّ" \
    || no "ب-٣" "كلمةٌ خاطئة" "قُبلت"

  local h="Authorization: Bearer $TOKEN"

  [ "$(code "$A/rep/me" -H "$h")" = 200 ] \
    && ok "ج-١" "لوحتي تُقرأ" || no "ج-١" "لوحتي" "لم تُقرأ"

  # ════════════════════════════════════════════════════════════════
  # **وشريطُ الهدف يقيس ما يُكافأ عليه**
  # ════════════════════════════════════════════════════════════════
  #
  # **كان يعرض `month_merchants` والمحرّكُ يعدّ الطلبات** — فيرى
  # المندوبُ رقماً لا يقود إلى المكافأة. **فيُفحص أنّ الحقلين
  # موجودان وأنّ الشاشةَ تقرأ الصحيح** (تفحصه المرحلةُ الثانية على
  # الزجاج).
  body | grep -q '"month_delivered"' \
    && ok "ج-٥" "`month_delivered` يصل الشاشة" \
    || no "ج-٥" "حقلُ الهدف" "غائبٌ عن ردّ /rep/me"

  # **ورمزُ الدعوة مقفلٌ ما لم يوثَّق** — والقفلُ من المحرّك لا الشاشة.
  local ver inv
  ver=$(grep -oP '"whatsapp_verified":\K(true|false)' /tmp/rt.json)
  inv=$(grep -oP '"invite_code":\K("[^"]*"|null)' /tmp/rt.json)
  if [ "$ver" = false ] && [ "$inv" = null ]; then
    ok "ج-٤" "الرمزُ مقفلٌ لغير الموثَّق"
  elif [ "$ver" = true ] && [ "$inv" != null ]; then
    ok "ج-٤" "الرمزُ يظهر للموثَّق"
  else
    no "ج-٤" "قفلُ الرمز" "توثيق=$ver ورمز=$inv — لا يتّفقان"
  fi

  local row ep id name
  for row in "merchants|هـ-١|عملائي" "leads|هـ-٣|الطلباتُ المعلّقة" "categories|د-٢|التصنيفات" "wallet|ز-٧|المحفظة" "incentives|ج-٦|الحوافز" "platform-sections|و-١|أقسامُ السوق"; do
    ep=${row%%|*}; id=$(echo "$row" | cut -d"|" -f2); name=$(echo "$row" | cut -d"|" -f3)
    [ "$(code "$A/rep/$ep" -H "$h")" = 200 ] \
      && ok "$id" "$name تُقرأ" || no "$id" "$name" "لم تُقرأ"
  done

  # **والحوافزُ تُقرأ بحقولها** — هدفٌ ومكافأةٌ وبلوغ.
  code "$A/rep/incentives" -H "$h" >/dev/null
  body | grep -q '"target_reward"' && body | grep -q '"reached"' \
    && ok "ج-٦" "الحوافزُ تحمل الهدفَ والمكافأة" \
    || no "ج-٦" "الحوافز" "ينقصها target_reward أو reached"
}

# ══════════════════════════════════════════════════════════════════════
# **د · الحارس — أخطرُ ما في التطبيق**
# ══════════════════════════════════════════════════════════════════════
#
# **والمعرّفاتُ تُخمَّن أو تُقرأ من ردٍّ سابق** — فلا يكفي أن تُخفى
# الأزرارُ في الشاشة.
stage_guard() {
  hdr "د · حارسُ الملكيّة"
  local h="Authorization: Bearer $TOKEN"
  local Z=00000000-0000-0000-0000-000000000000

  [ "$(code "$A/rep/stores/$Z/menu" -H "$h")" = 403 ] \
    && ok "هـ-١٠" "قائمةُ متجرٍ ليس عميلَه تُردّ" \
    || no "هـ-١٠" "قائمةُ متجرِ غيره" "مرّت"

  [ "$(code -X PATCH "$A/rep/menu/items/$Z" -H "$h" \
        -H 'Content-Type: application/json' -d '{"price":9}')" = 403 ] \
    && ok "هـ-١٠" "تعديلُ صنفٍ ليس له يُردّ" \
    || no "هـ-١٠" "تعديلُ صنفِ غيره" "مرّ — **ويبدّل أسعارَ سوقٍ لا يعرفه صاحبُه**"

  [ "$(code -X DELETE "$A/rep/menu/items/$Z" -H "$h")" = 403 ] \
    && ok "هـ-١٠" "حذفُ صنفٍ ليس له يُردّ" \
    || no "هـ-١٠" "حذفُ صنفِ غيره" "مرّ"

  [ "$(code -X POST "$A/rep/stores/$Z/menu/items" -H "$h" \
        -H 'Content-Type: application/json' -d '{"name":"x","price":1}')" = 403 ] \
    && ok "هـ-١٠" "إنشاءُ صنفٍ في متجرٍ ليس عميلَه يُردّ" \
    || no "هـ-١٠" "إنشاءٌ في متجرِ غيره" "مرّ"

  [ "$(code "$A/rep/merchants/$Z" -H "$h")" = 404 ] \
    && ok "هـ-١٠" "تفصيلُ متجرٍ ليس عميلَه يُردّ" \
    || no "هـ-١٠" "تفصيلُ متجرِ غيره" "مرّ"
}

# ══════════════════════════════════════════════════════════════════════
# **هـ · نموذجُ إضافة العميل — كلُّ فروعه**
# ══════════════════════════════════════════════════════════════════════
#
# **ولا يُنشأ طلبٌ ناجحٌ هنا** — يكتب في الإنتاج. **الفروعُ السالبةُ
# وحدَها**، والموجبةُ تُمشى على الزجاج في المرحلة الثانية.
stage_lead() {
  hdr "هـ · نموذجُ إضافة العميل — الفروعُ السالبة"
  local h="Authorization: Bearer $TOKEN"
  local g d c
  code "$A/public/governorates" >/dev/null
  g=$(grep -oP '"id":"\K[^"]+' /tmp/rt.json | head -1)
  code "$A/public/districts?governorate_id=$g" >/dev/null
  d=$(grep -oP '"id":"\K[^"]+' /tmp/rt.json | head -1)
  code "$A/rep/categories" -H "$h" >/dev/null
  c=$(grep -oP '"id":"\K[^"]+' /tmp/rt.json | head -1)

  local base="\"store_name\":\"QA\",\"owner_name\":\"QA\",\"phone\":\"0900000101\",\"password\":\"QaPass202699\""

  post() { code -X POST "$A/rep/leads" -H "$h" -H 'Content-Type: application/json' -d "$1"; }

  [ "$(post "{$base,\"category_id\":\"$c\",\"area\":\"وسط المدينة\"}")" = 400 ] \
    && ok "د-١" "بلا منطقةٍ يُردّ" \
    || no "د-١" "بلا منطقة" "قُبل — **وعاد النصُّ الحرُّ صفّاً بلا انتماء**"

  [ "$(post "{$base,\"category_id\":\"$c\",\"district_id\":\"وسط\"}")" = 400 ] \
    && ok "د-١" "نصٌّ حرٌّ مكانَ المنطقة يُردّ" \
    || no "د-١" "نصٌّ حرّ" "قُبل"

  [ "$(post "{\"store_name\":\"QA\",\"owner_name\":\"QA\",\"phone\":\"0900000101\",\"password\":\"12\",\"category_id\":\"$c\",\"district_id\":\"$d\"}")" = 400 ] \
    && [ "$(errcode)" = weak_password ] \
    && ok "د-٥" "كلمةٌ قصيرةٌ تُردّ باسمها" \
    || no "د-٥" "كلمةٌ قصيرة" "الرمزُ $(errcode)"

  [ "$(post "{\"store_name\":\"QA\",\"owner_name\":\"QA\",\"phone\":\"abc\",\"password\":\"QaPass202699\",\"category_id\":\"$c\",\"district_id\":\"$d\"}")" = 400 ] \
    && [ "$(errcode)" = invalid_phone ] \
    && ok "د-٦" "رقمٌ خاطئٌ يُردّ باسمه" \
    || no "د-٦" "رقمٌ خاطئ" "الرمزُ $(errcode)"

  [ "$(post "{\"store_name\":\"\",\"owner_name\":\"QA\",\"phone\":\"0900000101\",\"password\":\"QaPass202699\",\"category_id\":\"$c\",\"district_id\":\"$d\"}")" = 400 ] \
    && ok "د-١" "بلا اسمِ متجرٍ يُردّ" \
    || no "د-١" "اسمٌ فارغ" "قُبل"

  # **وتصنيفٌ حُذف من اللوحة قبل الإرسال** — كان يردّ ٥٠٠ خاماً.
  local cc
  cc=$(post "{$base,\"category_id\":\"00000000-0000-0000-0000-000000000000\",\"district_id\":\"$d\"}")
  if [ "$cc" = 400 ] && [ "$(errcode)" = invalid_category ]; then
    ok "د-١٣" "تصنيفٌ محذوفٌ يُقال باسمه"
  else
    no "د-١٣" "تصنيفٌ محذوف" "ردّ $cc/$(errcode) — والمندوبُ يقرأ «خطأ غير متوقّع»"
  fi
}

# ══════════════════════════════════════════════════════════════════════
# **و · ما لا يُؤتمت — يُقال ولا يُدّعى**
# ══════════════════════════════════════════════════════════════════════
stage_human() {
  hdr "و · ما يحتاج إنساناً"
  sk "ح-١" "إشعارُ عميلٍ جديدٍ يوقظ الجهاز" "لا يُرسَل إلّا بموافقة إدارةٍ حقيقيّة"
  sk "ح-٢" "إشعارُ عمولةٍ لا يوقظ" "يحتاج طلباً يُسلَّم"
  sk "ح-٣" "ضغطُ الإشعار يفتح موضعَه" "يحتاج إشعاراً واصلاً"
  sk "أ-٥" "شاشةُ التحديث لا تُغلق بالرجوع" "تحتاج رفعَ `app.min_version.rep`"
}

main() {
  [ -z "$PHONE" ] && { echo "REP_PHONE و REP_PASS مطلوبان"; exit 2; }
  printf '\033[1m══ اختبارُ تطبيق المندوب · المرحلةُ الأولى: المحرّك ══\033[0m\n'
  printf '   %s\n' "$A"
  stage_public
  stage_guards_anon
  stage_login || true
  [ -n "$TOKEN" ] && { stage_guard; stage_lead; }
  stage_human
  printf '\n\033[1m══ الحصيلة ══\033[0m\n'
  printf '  نجح %d · سقط %d · بشريّ %d\n' "$PASS_N" "$FAIL_N" "$SKIP_N"
  [ "$FAIL_N" -gt 0 ] && printf '\n\033[31mالساقط:\033[0m%b\n' "$FAILED"
  [ "$FAIL_N" -eq 0 ]
}
main "$@"
