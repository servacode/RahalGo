package com.rahalgo.customer.orders

/**
 * ══════════════════════════════════════════════════════════════════════
 * **مهلةُ الإلغاء بكلامٍ مفهوم** (قرارُ المالك ٢٠٢٦-١٠-٣٠)
 * ══════════════════════════════════════════════════════════════════════
 *
 * كان الزرُّ «إلغاء الطلب (متبقٍ 0:58)» **فلم يُفهم العدّاد.** فصار الزرُّ «إلغاء الطلب»
 * بلا عدّاد، وجنبَ الحال في رأس البطاقة «يمكنك إلغاء الطلب خلال 46 ثانية».
 *
 * **والأرقامُ غربيّة** (قاعدةُ المشروع)، والتمييزُ بالعربيّ الصحيح: ثانية/ثانيتين/ثوانٍ،
 * دقيقة/دقيقتين/دقائق. ومرآتُه في الويب `cancelWithin` (`orderParts.tsx`).
 */
object CancelCountdown {
    /** **«46 ثانية» · «دقيقة و10 ثوانٍ» · «دقيقتين»** — وصفرٌ أو أقلُّ نصٌّ فارغ. */
    fun within(secs: Int): String {
        if (secs <= 0) return ""
        val m = secs / 60
        val s = secs % 60
        val min = when {
            m == 0 -> ""
            m == 1 -> "دقيقة"
            m == 2 -> "دقيقتين"
            m in 3..10 -> "$m دقائق"
            else -> "$m دقيقة"
        }
        val sec = when {
            s == 0 -> ""
            s == 1 -> "ثانية"
            s == 2 -> "ثانيتين"
            s in 3..10 -> "$s ثوانٍ"
            else -> "$s ثانية"
        }
        return when {
            min.isEmpty() -> sec
            sec.isEmpty() -> min
            else -> "$min و$sec"
        }
    }
}
