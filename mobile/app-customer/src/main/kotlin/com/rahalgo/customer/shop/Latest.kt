package com.rahalgo.customer.shop

/**
 * ══════════════════════════════════════════════════════════════════════
 * **آخرُ من طُلب هو وحدَه من يكتب** (٢٠٢٦-٠٩-١٧)
 * ══════════════════════════════════════════════════════════════════════
 *
 * # العطبُ الذي وُلدت منه
 *
 * **شاشةُ السوق لها كاتبٌ واحدٌ — `items` — وله ثلاثةُ أبوابٍ**: **فتحُ
 * قسمٍ، وبحثٌ، وسحبةُ إنعاش.** **وكلُّها نداءاتُ شبكةٍ تُطلق ولا تنتظر
 * بعضَها.**
 *
 * **فمن نقر «شاورما» ثمّ «حلويات» قبل أن يردّ الأوّل أطلق نداءين
 * يتسابقان** — **والرابحُ أسرعُهما لا آخرُهما.** **فيقف الشريطُ على
 * «حلويات» وتحتَه شاورما**: **يطلبها الزبونُ وهو يظنّ أنّه في قسمٍ
 * آخر.** **ولا خطأَ يُرى ولا سطرَ في سجلّ.**
 *
 * **وشبكةُ الرقّة تجعل هذا هو الحالَ الغالبَ لا النادر**: **ردٌّ بطيءٌ
 * لقسمٍ صغيرٍ يسبقه ردٌّ أبطأُ لقسمٍ كبير.**
 *
 * # ولمَ لا يكفي الإلغاء
 *
 * **`Job.cancel()` لا يوقف نداءً تمّ ولم يُستأنَف بعد** — **يعود إلى
 * السطر التالي فيكتب وهو ملغى.** **والإلغاءُ رجاءٌ لا حكم.**
 *
 * **والرقمُ يحكم**: **من أخذ تذكرةً ثمّ سبقته تذكرةٌ أحدثُ لا يكتب
 * حرفا** — **ولو نُقرت الرقاقةُ نفسُها مرّتين.**
 *
 * **ولا تُستعمل من خيطين** — كلُّ نداءاتها من الخيط الرئيس كغيرِها في
 * نموذج العرض.
 */
class Latest {

    private var seq = 0

    /** **يأخذ تذكرةً لنداءٍ جديد** — **ويُبطل ما قبله.** */
    fun begin(): Int = ++seq

    /** **أهذه التذكرةُ هي الأحدثُ؟** — **ومن دونها لا يُكتب شيء.** */
    fun isCurrent(ticket: Int): Boolean = ticket == seq
}
