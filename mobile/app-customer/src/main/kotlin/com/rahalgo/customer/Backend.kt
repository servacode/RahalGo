package com.rahalgo.customer

import android.content.Context
import com.rahalgo.ui.AppCore
import com.rahalgo.ui.Core

/**
 * ══════════════════════════════════════════════════════════════════════
 * **وصلةُ تطبيق الزبون بالمحرّك**
 * ══════════════════════════════════════════════════════════════════════
 *
 * **وكلُّ ما فيها اليوم في `ui.Core`** — الجلسةُ والدخولُ و`me`
 * والحسابُ والبثُّ الحيّ. **وما سيُضاف يخصّ الزبونَ وحدَه**: المتاجرُ
 * والسلّةُ وطلباتُه.
 */
object Backend {

    /**
     * **عنوان المحرّك — يضعه البناءُ لا ثابتٌ مشترك** (`P-8`، ٢٠٢٦-٠٩-١٤).
     *
     * (قرار المالك ٢٠٢٦-٠٨-١١: «بحسابي الحقيقي، ما بدنا نرجع للمحلّي».)
     *
     * **والإصدارُ مقفلٌ على الإنتاج**: `release` يكتبه حرفاً ولا يقرأ
     * خاصّيّةً — **فلا تُبنى قطعةُ إصدارٍ تشير إلى تجهيزٍ أبداً.**
     *
     * **والتجريبيُّ وحدَه يقبل `-Prahalgo.apiBaseUrl`** — **لأجل `P-8`:
     * أربعةُ تطبيقاتٍ على جهازٍ واحدٍ تمشي الدورةَ على التجهيز بلا أن
     * تكتب حرفاً في بيانات الناس.**
     *
     * **ولا تبديلَ في وقت التشغيل**: لا إعدادٌ ولا شاشةٌ ولا متغيّرُ
     * بيئة — **وخادمٌ يختاره المستخدم بابٌ لا يُغلق.**
     *
     * **ويحرسه `ProductionEndpointGuardTest`.**
     */
    val BASE_URL: String = BuildConfig.API_BASE_URL

    /**
     * **أصلُ آثار الخرائط** — من البناء كذلك، بالقاعدة نفسِها.
     *
     * **ولا يُكتب مضيفٌ في منطق واجهة** — منه وحدَه تُشتقّ عناوينُ
     * الفهرس والأرشيف والموارد.
     */
    val MAPS_BASE_URL: String = BuildConfig.MAPS_BASE_URL

    /**
     * **نوعُ العميل — كما تعرفه قائمةُ المحرّك المغلقة.**
     *
     * (`identity/client_kind.go`: `{android|ios}-{customer|driver|merchant|rep}`.)
     *
     * **ونصٌّ لا يطابقها يُقرأ متصفّحا** فيُخرج صاحبَه من الويب كلّما فتح
     * التطبيق — **وهو عطبٌ صامتٌ لا يظهر إلّا بشكوى.**
     *
     * **وجلسةٌ لكلّ نوعِ عميل**: فمن دخل التطبيقَ لا يُخرج نفسَه من
     * المتصفّح، **وهو ما يفعله السائقُ والزبونُ على جهازٍ واحد.**
     */
    const val CLIENT = "android-customer"

    // **ورقمُ النسخة يُقرأ من البناء لا يُكتب** — انظر بوّابةَ التحديث.
    fun of(context: Context): Core =
        AppCore.install(context, BASE_URL, CLIENT, BuildConfig.VERSION_CODE)
}
