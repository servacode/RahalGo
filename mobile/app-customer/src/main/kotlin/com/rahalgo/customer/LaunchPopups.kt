package com.rahalgo.customer

/**
 * ══════════════════════════════════════════════════════════════════════
 * **نافذةٌ منبثقةٌ واحدةٌ فقط في كلّ فتحةٍ للتطبيق** (قرارُ المالك ٢٠٢٦-١١-١١، البند ١٣)
 * ══════════════════════════════════════════════════════════════════════
 *
 * **كان يفتح التطبيقَ فيجد «كيف كانت الخدمة؟» ثمّ، بعد أن يغلقها، «هل هذا عنوانك الصحيح؟»**
 * — نافذتان متتاليتان قبل أن يرى السوق. **فالأولى تحجز الفتحة** والثانية تنتظر الفتحةَ
 * التالية (حالتُها باقيةٌ في المحرّك فلا تضيع)، **ولا تُلغى.**
 *
 * **الفتحة**: تبدأ بإنشاء الشاشة وبعودة التطبيق من الخلفيّة (`reset`). **والترتيبُ حين يتزاحم
 * اثنان هو ترتيبُ التركيب** — «تصحيح العنوان» قبل «التقييم» لأنّه يوقف توصيلاً جارياً.
 *
 * (نافذتا «عرض السعر» و«مشاركة الموقع» لا تُحجَبان: فيهما قرارٌ على طلبٍ جارٍ، وتتقدّمان
 * أصلاً على الاثنتين في `MainActivity`.)
 */
object LaunchPopups {
    private var holder: String? = null

    /** **أيُرسَم هذا الآن؟** — نعم إن كانت الفتحةُ فارغةً أو في يده هو. */
    fun claim(key: String): Boolean {
        val h = holder
        if (h == null) {
            holder = key
            return true
        }
        return h == key
    }

    /** **فتحةٌ جديدة** — يُنادى عند إنشاء الشاشة وعند عودتها من الخلفيّة. */
    fun reset() {
        holder = null
    }

    internal fun holderForTest(): String? = holder
}
