#!/bin/sh
# ══════════════════════════════════════════════════════════════════════
# **موارِدُ الخريطة — مرّةً واحدةً لكلّ المناطق**
# ══════════════════════════════════════════════════════════════════════
#
# (المرحلة ٦أ، قرارُ المالك ٢٠٢٦-٠٨-٢١، البند ٧.)
#
#   الموارد (نمطٌ · حروفٌ · أيقونات)  ←  نسخةٌ واحدة  ←  كلُّ المناطق
#   حزمةُ المنطقة (بلاطاتٌ وحدَها)     ←  نسخةُ بياناتها
#
# **ودمشقُ وحلبُ والرقّةُ تتشارك `resourcesVersion` نفسَها** — أمرُ
# المالك: «لا أريد تكرار style/glyphs/sprites داخل كلّ حزمة مدينة».
#
# **والحروفُ ثقيلةٌ نسبيّاً**: نطاقاتُ العربيّة وأشكالِ عرضها لخطّين
# (عاديٍّ وعريض). **وتكرارُها في كلّ مدينةٍ يضاعف بلا فائدة.**
#
# # والخطّ
#
# (قرارُ المالك، البند ١٣: «إذا ترخيص «تجوال» ليس مثبتاً، اعتمد Noto
#  المناسب بترخيص OFL».)
#
# **ولا يُوزَّع ملفُّ خطٍّ في المستودع** — يُنزَّل عند البناء من مصدره
# الرسميّ، **وترخيصُه يُحفظ بجانبه.**
set -eu

MAPS=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
WORK=${WORK:-/srv/maps}
OUT="$WORK/out/map-resources"
. "$MAPS/config/resources.env"

mkdir -p "$OUT/glyphs" "$OUT/fonts"

# ── ١ · الخطّ ───────────────────────────────────────────────────────
# **بترخيص OFL** — مباحُ التضمين والتوزيع دونَ اتّصال.
#
# **والبصمةُ تُتحقَّق** — فلو بُدّل ملفٌّ في المنبع عُرف قبل أن تُبنى
# حروفٌ مختلفة.
#
# **والقراءةُ بالسطر لا بالمسافة** — لأنّ اسمَ الرصّة فيه مسافة
# (`RahalGo Regular`). **و`for spec in $FONTS` كان يقطعه نصفين.**
#
# **والحلقةُ بإعادةِ توجيهٍ لا بأنبوب** — فالأنبوبُ يفتح صدفةً فرعيّةً
# **فلا يُخرج `exit 5` منها من البناء**، فتمرّ بصمةٌ مخالفةٌ صامتة.
echo "▸ الخطّ"
while IFS='|' read -r stack url want; do
  [ -n "$stack" ] || continue
  file="$OUT/fonts/$stack.ttf"
  if [ ! -f "$file" ]; then
    echo "  · تنزيلُ $stack"
    curl -sL --fail -o "$file" "$url"
  fi
  got=$(sha256sum "$file" | cut -d' ' -f1)
  if [ "$got" != "$want" ]; then
    echo "  ✗ $stack: بصمةٌ مخالفة" >&2
    echo "    المنتظَر $want" >&2
    echo "    المقروء  $got" >&2
    exit 5
  fi
  echo "  ✓ $stack — بصمةٌ مطابقة"
done <<FONTLIST
$FONTS
FONTLIST

# **والترخيصُ يُرفَق ويُتحقَّق** — شرطُ OFL أن يُوزَّع النصُّ مع الخطّ.
# **ولا `|| true`** — فالتخطّي الصامتُ يُنتج توزيعاً مخالفاً للرخصة
# **ولا يظهر في سجلّ.**
LIC="$OUT/fonts/LICENSE.txt"
[ -f "$LIC" ] || curl -sL --fail -o "$LIC" "$FONT_LICENSE_URL"
got=$(sha256sum "$LIC" | cut -d' ' -f1)
if [ "$got" != "$FONT_LICENSE_SHA256" ]; then
  echo "  ✗ نصُّ الرخصة: بصمةٌ مخالفة" >&2
  echo "    المنتظَر $FONT_LICENSE_SHA256" >&2
  echo "    المقروء  $got" >&2
  exit 5
fi
echo "  ✓ $FONT_LICENSE — نصٌّ مرفَقٌ ببصمةٍ مطابقة"

# ── ٢ · الحروف ─────────────────────────────────────────────────────
# **والنطاقاتُ مقيسةٌ لا مفترضة** — انظر `glyph-ranges.mjs`:
# العربيّةُ الأساسيّةُ **وأشكالُ عرضها**، وإلّا ظهرت مربّعاتٍ والخطُّ
# سليم.
echo "▸ بناءُ الحروف"
node "$MAPS/scripts/glyph-ranges.mjs" > "$OUT/glyphs/RANGES.txt"
sh "$MAPS/scripts/build-glyphs.sh" "$OUT"

# **وبوّابةُ الأسماء** — البند ١١: عقدُ العنوان
# `{fontstack}/{range}.pbf`. **فإن لم يكن اسمُ المجلّد هو نفسَه الذي
# يطلبه `text-font` فالعنوانُ يردّ ٤٠٤ والخريطةُ بلا أسماء.**
echo "▸ مطابقةُ أسماء الرصّات"
node "$MAPS/scripts/check-fontstacks.mjs" "$OUT" "$MAPS/style/rahalgo.style.json"

# **وتغطيةُ المتن** — البند ٥: لا يُكتشف على الجهاز أنّ الأسماء
# مربّعات. **يُفتح كلُّ نطاقٍ وتُقرأ مُعرِّفاتُ حروفه.**
echo "▸ تغطيةُ العربيّة"
node "$MAPS/scripts/check-glyph-coverage.mjs" "$OUT"

# ── ٣ · الأيقونات ──────────────────────────────────────────────────
# **أربعُ أيقوناتٍ لا أربعون** — سياسةُ المعالم الأدنى (البند ٢٠).
echo "▸ بناءُ الأيقونات"
sh "$MAPS/scripts/build-sprite.sh" "$OUT"

# ── ٤ · النمطُ بارتباطاته ──────────────────────────────────────────
# **نمطٌ دلاليٌّ واحدٌ وثلاثةُ ارتباطات** (البند ٨).
echo "▸ ربطُ النمط"
node "$MAPS/scripts/bind-style.mjs" online \
  --tiles="$BASE_URL/base/latest/syria.pmtiles" \
  --resources="$BASE_URL/map-resources/$RESOURCES_VERSION" \
  --out="$OUT/style.online.json"
node "$MAPS/scripts/bind-style.mjs" offline \
  --tiles="tiles.pmtiles" --resources="." \
  --out="$OUT/style.offline.json"

# ── ٥ · عقدُ الموارد ───────────────────────────────────────────────
# **فلا يقع: نمطٌ جديدٌ مع حروفٍ قديمة** (البند ١٢).
#
# **ويُقاس من الناتج لا يُكتب باليد** (البند ١٠) — نسخةُ الخطّ
# وترخيصُه وبصمتُه، والنطاقاتُ المبنيّة، والأيقوناتُ الموجودة.
echo "▸ عقدُ الموارد"
node "$MAPS/scripts/resources-manifest.mjs" "$OUT" > "$OUT/resources.json"

echo "✓ الموارد في $OUT"
