-- **تصفيرُ الإعدادات** — تُمحى القيمُ المخزَّنة، ويعمل النظامُ بافتراضات الفهرس.
--
-- # لماذا يُمحى الجدولُ كلُّه ولا يُعطَّل شيء
--
-- **افتراضُ كلّ مفتاحٍ في `settings.Catalog` لا في القاعدة.** والصفُّ في
-- `app_settings` ليس تعريفَ المفتاح — **هو قرارُ المالك أن يخالف الافتراض.**
-- فمحوُه يعني «عُد إلى ما كتبه المهندس»، لا «لا إعدادَ لهذا».
--
-- **وهذا ما يجعل المحوَ آمناً**: لا مفتاحَ يصير مجهولاً، ولا قراءةَ تنهار.
--
-- (قرارُ المالك ٢٠٢٦-٠٨-٠٤: «احذف جميع الإعدادات بشكلٍ كاملٍ نهائيّ وسنعود
-- لنعمل الإعداداتِ بشكلٍ صحيحٍ ونهائيّ، بحيث الأرقامُ تصدر من مكانٍ مركزيٍّ
-- واحدٍ وليس من أماكنَ متفرّقة».)
--
-- # وثلاثةٌ تُقال قبل أن تُمحى
--
--	platform.treasury_user_id  ←  **حسابُ الخزينة** — وافتراضُه فارغ
--	platform.support_phone     ←  رقمُ الدعم الظاهر للزبون — وافتراضُه فارغ
--	whatsapp.otp_template      ←  نصُّ رسالة الرمز — وله افتراضٌ في الفهرس
--
-- **والخزينةُ وحدَها لها أثرٌ صامت**: بلا حسابٍ مختارٍ لا يُكتب قيدُ خزينة،
-- **ولا يُعطَّل تسليم** — يمضي الطلبُ ويبقى الدفترُ ناقصَ طرف. فتُختار من
-- «الإعدادات ← المنصة» قبل أوّل طلبٍ يُسلَّم.
--
-- # ولا يُمحى تعريفٌ ولا يُفقد مفتاح
--
-- **الفهرسُ في الشيفرة**، فيعود كلُّ مفتاحٍ ظاهراً في اللوحة بقيمته الافتراضية
-- **ومكتوباً عليه أنّه لم يُغيَّر منذ التنصيب** — وهو صادق.

BEGIN;

-- **يُقرأ ما سيُمحى قبل محوِه** — رقمٌ يُقال بعد الحذف لا يُراجَع.
SELECT count(*) AS "قيمٌ مخزّنةٌ ستُمحى" FROM app_settings;

DELETE FROM app_settings;

COMMIT;

SELECT count(*) AS "الباقي" FROM app_settings;
