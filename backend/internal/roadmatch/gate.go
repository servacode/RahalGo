package roadmatch

import "context"

// ══════════════════════════════════════════════════════════════════════
// **بوّابة التتبّع — نداء `trace_attributes` واحد بالمرّة للخادم كله**
// ══════════════════════════════════════════════════════════════════════
//
// Valhalla عنا بخيط شغل **واحد** وبلا مهلة من جهته: كل نداء بيستنّى ع نفس الخيط، والنداء بيضل
// ماسكه حتى لو عميلنا تركه. فالمطابق وتعلّم الطرق (عمّاله الأربعة) **بيمرقوا من هون** ⇒ نداء تتبّع
// واحد بالطريق بأي لحظة، والملاحة واللوحة ما بيستنّوا ورا أكتر من نداء.

var traceGate = make(chan struct{}, 1)

// Acquire **بيمسك البوّابة** (أو بيرجع لما يخلص `ctx`). `release` لازم تنطلب مرّة.
func Acquire(ctx context.Context) (release func(), err error) {
	select {
	case traceGate <- struct{}{}:
		return func() { <-traceGate }, nil
	case <-ctx.Done():
		return nil, ctx.Err()
	}
}
