// GapDecl فجوةٌ معلَنةٌ بشدّتها.
type GapDecl struct {
	ID       string
	Title    string
	Severity string
	// Fixed **دليلُ الإصلاح** — فارغٌ يعني «ما زالت قائمة».
	//
	// # ولماذا نصٌّ لا علَمٌ منطقيّ
	//
	// **`true` لا تقول من أصلحها ولا بأيّ دليل** — **وفجوةٌ تُغلَق
	// بعلَمٍ تُفتح بعلَمٍ**، ولا يبقى ما يُراجَع.
	//
	// **والنصُّ يُقرأ في البوّابة والتقرير** — فمن سأل «لماذا لم تعد
	// مانعة؟» وجد الجواب في مكانٍ واحد.
	//
	// **ولا تُملأ إلّا وحارسُ انحدارٍ دائمٌ يؤكّد العقدَ ويمرّ.**
	Fixed string
	// WokenBy **الإعدادُ الذي يوقظ النائمة** — و`LATENT` وحدَها تملؤه.
	WokenBy string

	// PartOf **فجوةٌ جذرُها جذرُ أخرى** — **فتُقرأ ولا تُعَدّ مانعاً
	// ثانياً.** (`XG-37` كشفت أنّ العدَّ يجب أن يكون واحداً.)
	//
	// # ولمَ لا تُحذَف
	//
	// **حذفُ سجلٍّ سُجّل يمحو ما قيس** — **ومن قرأ التقريرَ غداً لم
	// يجد نطاقاً مقيساً ولا سببَ اختفائه.**
	//
	// **والاستتباعُ يُبقي النطاقَ مقروءاً ويُوحّد المانع** — وهو نفسُ
	// عقدِ `SupersededBy` في البوّابة: **سببٌ واحدٌ لا مانعان
	// مصطنعان.**
	PartOf string
}

