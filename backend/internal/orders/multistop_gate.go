package orders

// ══════════════════════════════════════════════════════════════════════
// **بوّابةُ الطلب من عدّة متاجر — نسخةُ السائق أوّلاً** (٢٠٢٦-١١-٠٥)
// ══════════════════════════════════════════════════════════════════════
//
// (قرارُ المالك ٢٠٢٦-١١-٠٥: «١ موافق» — طلبٌ واحدٌ بعدّة محطّات.)
//
// **الطلبُ من متجرين يحتاج سائقاً يعرف المحطّات**: يستلم من كلّ متجرٍ
// بضغطته هو، **وتطبيقُ السائق المنشورُ اليومَ لا يعرف إلّا محطّةً واحدة.**
//
// # القاعدة
//
//	orders.max_sources = 1                 ⇒ ١ — كما اليوم
//	orders.max_sources > 1 والبوّابةُ مغلقة ⇒ ١ — **والسلّةُ تقول «متجرٌ واحد»**
//	orders.max_sources > 1 والبوّابةُ مفتوحة ⇒ الرقمُ المضبوط
//
// **والبوّابةُ مفتوحةٌ حين تُفرض على كلّ السائقين نسخةٌ تعرف المحطّات**:
// أدنى نسخةٍ يُسمَح لها (`app.min_version.driver` أو رقمُ الملفّ المرفوع
// مع الفرض التلقائيّ) ≥ `orders.multistop_driver_build`. **وصفرُ هذا
// المفتاح — وهو الافتراض — يعني أنّ النسخةَ لم تصدر بعد**: البوّابةُ مغلقة.
//
// # ولماذا في وقت التشغيل لا عند الحفظ وحدَه
//
// **إنزالُ أدنى نسخةٍ للسائق يومَ رجوعٍ يُغلق السلّةَ في اللحظة** — **أيّاً
// كان ترتيبُ ما بُدّل من إعدادات.** **والتسعيرةُ والإنشاءُ يسألان
// القارئَ نفسَه** (`maxSources`)، **فلا تقول السلّةُ «متجران» ويردّ
// الإنشاء.**
//
// # ومن يحقنها
//
// **الخادم** — هو الذي يعرف أدنى نسخةٍ نافذة (`effectiveMinVersion`).
// **وبلا حقنٍ مغلقة**: اختبارٌ يبني المحرّكَ وحدَه يعمل بمتجرٍ واحدٍ في
// الطلب، **وهو الحالُ الآمن.**

import (
	"context"

	"github.com/servacode/rahalgo/backend/internal/dbtx"
)

// MultiStopGate **أيُفتح الطلبُ من أكثرَ من متجرٍ الآن؟**
//
// **ويقرأ بالمنفّذ المُمرَّر** — `XG-46`: **الإنشاءُ يسأله وهو داخلَ
// معاملته**، **ووصلةٌ ثانيةٌ من المَسبَح هنا تُجمّد الطلبَ حين يمتلئ.**
type MultiStopGate func(ctx context.Context, q dbtx.Querier) bool

// SetMultiStopGate يحقن البوّابةَ — **يُنادى مرّةً عند الإقلاع.**
func (s *Service) SetMultiStopGate(g MultiStopGate) { s.multiStop = g }

// MultiStopReady **أنسخةُ السائق التي تعرف المحطّات مفروضةٌ على الجميع؟**
//
// **وبلا بوّابةٍ أو بلا منفّذٍ: لا** — **والإغلاقُ هو الافتراضُ الآمن.**
func (s *Service) MultiStopReady(ctx context.Context, q dbtx.Querier) bool {
	return s.multiStop != nil && q != nil && s.multiStop(ctx, q)
}

// poolQ **المَسبَحُ منفّذاً — وفراغٌ حقيقيٌّ إن غاب.**
//
// **ومؤشّرٌ فارغٌ داخلَ واجهةٍ ليس واجهةً فارغة** (انظر `settings.Get`) —
// **فشرطُ `q != nil` يمرّ ثمّ ينهار النداء.**
func (s *Service) poolQ() dbtx.Querier {
	if s.db == nil {
		return nil
	}
	return s.db
}
