package orders

// ══════════════════════════════════════════════════════════════════════
// **التوصيلةُ تُرسَل ما دامت المنصّةُ بالدوام** — قرارُ المالك ٢٠٢٦-١٠-٢٩
// ══════════════════════════════════════════════════════════════════════
//
// (نصُّه: «مادام المنصة بالدوام معناها في سائقين، إذا كانت خارج الدوام ما
//  يقدر يرسل».)
//
// # وما ألغاه هذا القرار
//
// **كان الشرطُ منذ ٢٠٢٦-١٠-٠١ «سائقٌ واحدٌ فاعلٌ بالدوام»** — فإن لم يكن
// سائقٌ بالدوام رُدّت التوصيلةُ بـ`no_drivers_on_shift` والمنصّةُ في دوامها.
// **وأُلغي**: دوامُ المنصّة هو الحُجّة، **والتوزيعُ يتولّى الانتظارَ والبحثَ
// والتوسّعَ** كما يتولّاه في كلّ طلب.
//
// # وأين يُحرَس الدوامُ الآن
//
// **في البوّابة نفسِها التي تحرس طلبَ الزبون** — `requireOrdering` في
// `server/platform_gate.go`، **تُنادى في عرض السعر وفي الإنشاء قبل قراءة
// الجسم.** فخارجَ الدوام يُردّ `platform_closed_now` **ومعه موعدُ الفتح**
// (`next_available_at`)، **والإيقافُ المؤقّتُ** `temporarily_unavailable`.
// **ولا حارسَ ثانٍ هنا** — بابٌ واحدٌ لمعنًى واحد.

import (
	"net/http"

	"github.com/servacode/rahalgo/backend/internal/httpx"
)

// ErrNoDriversOnShift **لا سائقَ بالدوام الآن.**
//
// **لم يعُد «لدي توصيلة» يردّه** (قرارُ المالك ٢٠٢٦-١٠-٢٩) — **ويبقى الرمزُ
// معروفاً** لتطبيقٍ قديمٍ ولمراقبة الأخطاء (`monitoring_errors.go`).
var ErrNoDriversOnShift = httpx.NewError(http.StatusServiceUnavailable,
	"no_drivers_on_shift", "errors.no_drivers_on_shift")
