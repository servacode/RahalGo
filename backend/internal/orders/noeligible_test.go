// **رسالةُ «لن يلتقطه أحد» تحمل الرقمين.**
//
// (جردُ لوحة السائق ٢٠٢٦-٠٨-٠٩ · قرارُ المالك: «نفّذها كلَّها».)
//
// # ما كان
//
// **التعليقُ فوق السطر يَعِد بالرقمين** — «٢٬٠٦١٬٠٠٠ والسقفُ ٥٠٠٬٠٠٠ تقول أين
// المخرج» — **والشيفرةُ تردّ الحكمَ وحدَه**: «فوق سقف السائقين».
//
// **وتعليقٌ يَعِد بما لا تفعله شيفرتُه أسوأُ من لا تعليق**: من قرأه صدّقه ولم
// يفتح السطر. **وبقي ستّةَ أيّام.**
//
// # ولماذا الرقمان
//
// «فوق السقف» تُغلق الباب، **والرقمان يقولان أين المخرج**: يُرفع السقفُ أو
// يُقسَّم الطلب. **والعملياتُ تقرأ الرسالةَ لتقرّر، لا لتعرف أنّ ثمّةَ مشكلة.**

import (
	"strings"
	"testing"
)

func TestGroupDigitsIsReadable(t *testing.T) {
	// **أرقامٌ أجنبيّةٌ وفاصلُ الآلاف «,»** (قرارُ المالك ٢٠٢٦-١٠-٠٣) — كان «٬» العربيّ.
	cases := map[int64]string{
		0:       "0",
		7:       "7",
		999:     "999",
		1000:    "1,000",
		500000:  "500,000",
		2061000: "2,061,000",
		-1500:   "-1,500",
	}
	for in, want := range cases {
		if got := groupDigits(in); got != want {
			t.Errorf("%d → %q، والمنتظَر %q", in, got, want)
		}
	}
}

// TestNoEligibleMessageCarriesBothNumbers **الرقمان في الرسالة نفسِها.**
//
// **ويُنادى الأصلُ لا نسخةٌ منه**: أوّلُ صياغةٍ لهذا الاختبار ركّبت الرسالةَ
// بيدها، **فكانت تفحص سطرَها لا الشيفرة** — ولو حُذف رقمٌ من `NoEligibleReason`
// لَمرّت ناجحة. (وهو الخطأُ نفسُه الذي وقع في `coerceNum` قبل ساعة.)
//
// **فمُيّزت الرسالةُ في `cashOverLimitMessage`** وتُنادى كما هي — ولا قاعدةَ
// تُفتح.
func TestNoEligibleMessageCarriesBothNumbers(t *testing.T) {
	msg := cashOverLimitMessage(2061000, 500000)

	for _, want := range []string{groupDigits(2061000), groupDigits(500000)} {
		if !strings.Contains(msg, want) {
			t.Errorf("الرسالةُ %q لا تحمل %q — فتُغلق البابَ ولا تدلّ عليه", msg, want)
		}
	}
}
