package orders

// وضعا التشغيل — من يدير الطلبات ومن يراقب.
//
// # لماذا وضعان
//
// **ليس كلُّ متجرٍ يجلس إلى شاشة.** مطعمٌ صغير في الرقة لا يملك جهازاً في
// المطبخ ولا من يراقبه. وإلزامُه ببوابةٍ يفتحها يعني طلباتٍ تتأخّر حتى يتذكّر
// أحدُهم أن ينظر. **ومتجرٌ آخر يديرها بنفسه ولا يريد وسيطاً.**
//
// فصار للمنصة وضعان يحكمهما مفتاحٌ واحد (`merchants.self_manage_orders`):
//
//	┌──────────────────┬─────────────────────┬──────────────────────┐
//	│                  │ المنصة تدير          │ المتجر يدير           │
//	├──────────────────┼─────────────────────┼──────────────────────┤
//	│ القبول والرفض     │ **العمليات**        │ **المتجر**           │
//	│ المتجر في النظام  │ يشاهد لا غير        │ يدير طلباته          │
//	│ دورُ المنصة        │ ينتهي عند التحويل   │ مراقبةٌ لا يد          │
//	└──────────────────┴─────────────────────┴──────────────────────┘
//
// # ولماذا هنا لا في الشاشة
//
// كانت بوابةُ المتجر تُخفي أزرارَ القبول في وضع «المنصة تدير» — **والمحرّكُ لا
// يعرف الوضعَ أصلاً**. فمتجرٌ يستدعي الواجهةَ البرمجية مباشرةً يقبل طلبَه رغم
// أن السياسة تمنعه.
//
// **وحجبٌ في الواجهة وحدها ليس حجباً، هو وعدٌ بحجب** — وهو الدرسُ نفسه الذي
// أخرجَ ردَّ خصوصية الزبون من الشاشة إلى الخادم.
//
// # وحدُّ الإلغاء
//
// في وضع «المنصة تدير» ينتهي دورُ المنصة عند تحويل الطلب إلى المتجر: **لا
// تقول «وصل» لأنها لا تعلم، ولا تُلغي لأنها ليست هناك.**
//
// **لكنّ «ليست هناك» هي العلّة، فهي أيضاً الحدّ.** فما دام الطلبُ في الطابور لم
// يمسكه سائق، فلا أحدَ هناك أصلاً — والعملياتُ آخرُ من يملك إنهاءه، وبلا ذلك
// يبقى طلبٌ لم يلتقطه أحدٌ معلّقاً إلى الأبد ومالُ الزبون محجوزٌ فيه.
//
// **فإذا أمسكه سائق، صار هو العين** — وهو وحده من يقول «استلمتُ» أو «المطعم
// مغلق».
//
// # والأدمن يبقى
//
// الوضعُ **فصلُ مسؤولياتٍ لا حاجزُ أمانٍ ضدّ خصم**. ونظامٌ بلا تجاوزٍ في أيّ
// موضع هو نظامٌ يُصلَح بجراحةٍ في قاعدة البيانات حين يقع ما لم يُحسب.
//
// فالأدمن — وهو المالك — يبقى قادراً، **وكلُّ فعلٍ له مُسجَّل**.

import "slices"

// rolesUnderMode يُنقّي أدوارَ الفاعل ممّا يمنعه الوضعُ الحاليّ.
//
// **تنقيةٌ لا رفض**: تُحذَف الأدوارُ الممنوعة ثم تُسأل الخريطة. فمن يحمل دوراً
// آخر يخوّله يمرّ به — **ولا يُحرَم أحدٌ من حقٍّ يملكه بسببٍ يخصّ حقّاً آخر**.
//
// selfManage: أالمتجرُ يدير طلباته؟ · driverHolds: أفي يد سائقٍ الآن؟
func rolesUnderMode(selfManage bool, from, to string, roles []string, driverHolds bool) []string {
	// **والأدمنُ فوق السلطة لا فوق العِلم.**
	//
	// كان يتخطّى كلَّ الحُرّاس — **فسقط أهمُّها عمّن أحدث المشكلةَ أصلاً**:
	// شكوى المالك الحيّة قالت حرفياً «ضُغطت **بيد الأدمن** بعد ثانيةٍ من
	// القبول». **فالشخصُ الذي وقعت منه بقي الوحيدَ الذي يملكها.**
	//
	// # وفرقٌ خلطتُه فتَبِع
	//
	//	سلطة  ←  يملك ما لا تملكه العمليات: إلغاءٌ بعد التحويل، تدخّلٌ مسجَّل
	//	عِلم   ←  **لا أحدَ في المنصة يعلم أنّ المطبخ بدأ** — ولا المالكُ يعلم
	//
	// **و«بدء التحضير» ليست مسألةَ صلاحية، هي مسألةُ معرفة.** وكونُك المالكَ
	// لا يمنحك عِلماً بما يجري في مطبخِ غيرك، **وزرٌّ يكتب في السجلّ حدثاً لم
	// يقع يكذب سواءٌ ضغطه مالكٌ أو موظّف.**
	//
	// # ولماذا استُثني ما استُثني
	//
	// مراحلُ السائق تبقى بيده: **هاتفٌ نفدت بطاريتُه حاجةٌ تشغيليةٌ حقيقية**،
	// والمالكُ يُكملها عنه وتُسجَّل باسمه. **أمّا التحضيرُ فلا حاجةَ له أصلاً**
	// — الإنزالُ إلى الطابور تلقائيّ، فالزرُّ لا يخدم إلّا الكذب.
	isAdmin := slices.Contains(roles, "admin")

	drop := func(role string) []string {
		out := make([]string, 0, len(roles))
		for _, r := range roles {
			if r != role {
				out = append(out, r)
			}
		}
		return out
	}

	if selfManage {
		// **المتجر يدير — والمنصةُ عينٌ لا يد.**
		//
		// القبولُ والرفضُ اختصاصُ المتجر وحده. وقبولُ العمليات نيابةً عنه
		// يعني طلباً يُقبل ولا مطبخَ يعلم به. **والمالكُ يتجاوز** — تدخّلٌ
		// مسجَّل، وهو صاحبُ المنصة.
		if from == StPending && (to == StAccepted || to == StRejected) && !isAdmin {
			return drop("ops")
		}
		return roles
	}

	// **المنصة تدير — والمتجرُ يشاهد.**
	//
	// لا قبولَ ولا رفضَ ولا «بدء تحضير» ولا إلغاء: هو خارج النظام يُبلَّغ
	// برسالة. **وزرٌّ لا يملكه ليس زرّاً مخفياً، هو حقٌّ غيرُ ممنوح.**
	if slices.Contains(roles, "merchant") {
		roles = drop("merchant")
	}

	// **ولا تُعلن العملياتُ بدءَ تحضيرٍ لم تبدأه.**
	//
	// التحضيرُ فعلٌ في مطبخٍ خارج النظام — **والمنصةُ لا تراه**. وهي القاعدةُ
	// نفسُها التي منعتها من قول «وصل للمتجر»: **لا تُعلن ما لا تعلم.**
	//
	// وقد وقع فعلاً في تجربةٍ حيّة: ضُغطت بعد ثانيةٍ من القبول **والمتجرُ لم
	// يُبلَّغ بعد** — فمضى الطلبُ إلى «قيد التحضير» ولا مطبخَ يعلم به.
	// **ولا يستثنى المالك.** شكواه الحيّة قالت «ضُغطت **بيد الأدمن** بعد
	// ثانيةٍ من القبول» — **فاستثناؤه يُبقي الخللَ عند من أحدثه.**
	if to == StPreparing {
		roles = drop("ops")
		roles = drop("admin")
	}

	// **ومراحلُ الطريق للسائق وحده.**
	//
	// المنصةُ لا تعلم أنه وصل المتجرَ ولا أنه استلم ولا أنه سلّم — **ربّما كان
	// في طلبٍ آخر وهو عائدٌ إليه**. وزرٌّ بيدها هنا **يكتب في السجلّ حدثاً لم
	// يقع**، ثم يُبنى عليه حسابُ تأخّرٍ أو تعويض.
	// **«مقروءةٌ لها فقط»** — نصُّ قرار المالك. ولا استثناءَ للمالك نفسِه:
	// **لا هو ولا موظّفُه يعلم أنّ السائق وصل**، وزرٌّ بيد أحدهما يكتب في
	// السجلّ حدثاً لم يقع ثمّ يُبنى عليه حسابُ تأخّرٍ أو تعويض.
	// **ولا يملكها المالكُ إلّا بتوقيعٍ صريح.**
	//
	// وسؤالُ المالك كشف الحاجة (٢٠٢٦-٠٨-٠٢): **«ربما لن يكون هناك موظفين
	// وفقط مدير المنصة سوف يدير العمل»** — وهاتفُ سائقٍ نفدت بطاريتُه يترك
	// الطلبَ عالقاً بلا من يُكمله.
	//
	// **والمشكلةُ لم تكن يوماً «من ضغط»، كانت «ماذا يقول السجلّ».** فحين
	// يُوقَّع الفعلُ تدخّلاً يدوياً **يصدق السجلّ**: يقول «أعلنتها المنصةُ»
	// لا «قالها السائق». وبلا التوقيع يبقى ممنوعاً — **فلا يُضغط سهواً كما
	// وقع في `#1004`.**
	if driverOnly[to] {
		roles = drop("ops")
		if !slices.Contains(roles, RoleManualOverride) {
			roles = drop("admin")
		}
	}

	// **وبعد أن تصير البضاعةُ بيده — مراقبةٌ لا تحكّم.**
	//
	// **ولا يفتحه التوقيعُ هنا.** التوقيعُ يُصدّق السجلَّ («أعلنتها المنصة»)
	// **ولا يُصدّق الواقع**: من يقول «تمّ التسليم» وهو في المكتب يقول ما لا
	// يعلمه — **ربّما كان السائقُ عالقاً في الطريق أو الزبونُ لم يفتح.**
	//
	// **والمالُ يتحرّك على قوله**: يُقيَّد للمتجر ولنا وللمندوب، **ويُحمَّل
	// السائقُ نقداً لم يقبضه** فيُطالَب بتسليمه للصندوق. **وتصحيحُ قيدٍ وقع
	// أصعبُ من انتظار من يعرف.**
	//
	// **وقبل الاستلام يبقى التوقيعُ يعمل**: طلبٌ أُسند ولم يتحرّك، أو سائقٌ
	// عند باب المتجر وهاتفُه صامت — **المنصةُ تعلم بالمكالمة وتُنقذ الطلب،
	// ولا بضاعةَ خرجت بعد.**
	//
	// **وبابُ الطارئ بعدها الاستغاثةُ لا زرُّ التسليم**: تُفتح على الطلب فتُقرأ
	// وتُعالَج، **ولا يُكتب في الدفتر تسليمٌ لم يشهده أحد.**
	//
	// (قرارُ المالك ٢٠٢٦-٠٨-٠٤: «لا يجوز تدخّلُ المنصة — بمجرّد أن السائق
	// استلم الطلب هي تراقب فقط عمليةَ التسليم، لم يعد بإمكانها التحكّم بشيء».)
	if goodsWithDriver[from] {
		roles = drop("ops")
		roles = drop("admin")
	}

	// **وبعد التحويل لا تُلغي العملياتُ طلباً.**
	//
	// قامت بدورها — قبلت وحوّلت — وانتهى عملُها. **وكلُّ زرٍّ يبقى بيدها بعد
	// ذلك بابُ تلاعبٍ أو ضغطةِ خطأ، والخطأُ هنا يُلغي طلباً طُبخ.**
	//
	// ويبقى ما قبل التحويل بيدها: طلبٌ لم يُقبل بعد أو قُبل ولم يُحوَّل **لم
	// يعلم به مطبخٌ ولا تحرّك له سائق.**
	// **وهذه سلطةٌ لا عِلم — فالمالكُ يبقى عليها.**
	//
	// إلغاءُ طلبٍ بعد التحويل قرارٌ يملكه صاحبُ المنصة: **يعلم ما يفعل ويتحمّل
	// أثرَه**، ويُسجَّل باسمه. **والعملياتُ لا تملكه** — قامت بدورها وانتهى.
	if to == StCancelled && afterHandoff[from] && !isAdmin {
		roles = drop("ops")
	}
	return roles
}

// driverOnly مراحلُ الطريق — لا يملكها إلّا من يسير فيها.
var driverOnly = map[string]bool{
	StAtPickup: true, StPickedUp: true, StOnTheWay: true,
	StAtDropoff: true, StDelivered: true, StFailed: true,
}

// goodsWithDriver البضاعةُ خرجت من المتجر وهي بيد السائق.
//
// **وهي الحدُّ الذي تصير عنده المنصةُ مراقبةً**: ما قبله بيدها، وما بعده
// **بيد من يحملها وحدَه.**
//
// **و`StAtPickup` ليست منها**: السائقُ عند الباب ولم يستلم بعد — **والمنصةُ
// تعلم بالمكالمة أنّه هناك.**
var goodsWithDriver = map[string]bool{
	StPickedUp: true, StOnTheWay: true, StAtDropoff: true,
}

// afterHandoff الحالاتُ التي بلغها الطلبُ بعد تحويله إلى المتجر.
var afterHandoff = map[string]bool{
	StDispatching: true, StAssigned: true, StAtPickup: true,
	StPickedUp: true, StOnTheWay: true, StAtDropoff: true,
}

// RoleManualOverride دورٌ اصطناعيّ **لا يُمنح لأحد** — يُضاف في المعالِج حين
// يؤكّد المالكُ أنّ ما يفعله **تدخّلٌ يدويّ**.
//
// **ولماذا دورٌ لا معامل**: `rolesUnderMode` تقرأ الأدوارَ وحدَها، **ومعاملٌ
// جديدٌ يمرّ عبر خمس دوالّ ليصل** — والدورُ يصل حيث تصل الأدوار.
//
// **ولا يُقبل من غير الأدمن**: المعالِجُ يفحص ذلك قبل أن يضيفه.
const RoleManualOverride = "manual_override"
