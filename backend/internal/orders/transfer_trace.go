package orders

// ══════════════════════════════════════════════════════════════════════
// **أثرٌ يُقرأ لفشلٍ وقع بعد قبولٍ ثابت** — `R24`
// ══════════════════════════════════════════════════════════════════════
//
// # المسألة
//
// **التحويلُ التلقائيُّ ثلاثةُ أفعالٍ لا واحد**: قبولٌ · وإبلاغُ
// المتجر · وإنزالٌ إلى السائقين. **والقبولُ يثبت في القاعدة قبل أن
// يُعلَم أوصلت الرسالةُ أم لا** — **وبين الفحص والإرسال ثوانٍ تكفي
// لتنقطع شبكةُ هاتفٍ حقيقيّ.**
//
// **فإن تعذّر الإبلاغُ بقي الطلبُ `accepted` بلا أن يعلم به المتجر** —
// **حالٌ صحيحةُ الشكل خاطئةُ المعنى**: الزبونُ يقرأ «قيد التحضير»
// ولا أحدَ خلف الباب.
//
// # ولماذا لا يكفي السجلّ
//
// **كان الأثرُ الوحيدُ سطراً في `logger`** — **والسجلُّ ليس حقيقةً
// تشغيليّة**: لا يُقرأ في لوحةٍ، ولا يُنسَب إلى طلبٍ يُفتَح، ولا
// يبقى بعد دورةِ حفظٍ، **ولا يُستدرَك منه.**
//
// **ومن أراد أن يعرف كان عليه أن يقرأ عموداً `NULL` في جدول** —
// **وذاك ليس أثراً يُقرأ، هو أثرٌ يُستنتَج.**
//
// # ولماذا `order_events` لا جدولٌ جديد
//
// **سجلُّ الطلب هو مكانُ ما جرى للطلب** — **يُقرأ في اللوحة سطراً
// سطراً**، ويحمل الفاعلَ والوقتَ والنصّ. **وجدولٌ جديدٌ لحالِ فشلٍ
// واحدةٍ حقيقةٌ ثانيةٌ تشيخ.**
//
// **والحدثُ بحالٍ ثابتة** (`from = to`) — **فهو يصف ولا ينقل**،
// وسابقتُه في `merchant_blocked.go`.

import "context"

// TransferFailureNote **نصُّ الأثر** — يُقرأ في سجلّ الطلب.
//
// **ويبدأ بوسمٍ ثابتٍ يُبحَث به** — فمن أراد جردَ ما لم يُبلَّغ وجده.
const TransferFailureNote = "تعذّر إبلاغُ المتجر — قُبل الطلبُ ولم تصل الرسالة"

// NoteTransferFailure يكتب أثرَ فشلِ الإبلاغ في سجلّ الطلب.
//
// **ولا يُبدّل حالاً** — الطلبُ `accepted` كما هو، **والحدثُ يقول
// لماذا لم يُوسَم مُرسَلاً.**
//
// **ويردّ خطأً ليُسجَّل** — **وسقوطُه لا يُبطل شيئاً**: الفعلُ الذي
// يصفه وقع أصلاً.
func (s *Service) NoteTransferFailure(ctx context.Context, orderID, actorID, reason string) error {
	note := TransferFailureNote
	if reason != "" {
		note += " — " + reason
	}
	var status string
	if err := s.db.QueryRow(ctx,
		`SELECT status FROM orders WHERE id = $1`, orderID).Scan(&status); err != nil {
		return err
	}
	// **والفاعلُ قد يكون فارغاً** — التحويلُ يقع باسم من أنشأ الطلب،
	// **وعمودُ الفاعل `uuid` لا يقبل نصّاً خاوياً.**
	var actor any
	if actorID != "" {
		actor = actorID
	}
	_, err := s.db.Exec(ctx, `
		INSERT INTO order_events (order_id, from_status, to_status, actor_id, note)
		VALUES ($1, $2, $2, $3, $4)`, orderID, status, actor, note)
	return err
}
