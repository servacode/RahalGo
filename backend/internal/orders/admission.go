package orders

// قبولُ الطلب في يد سائق — **مقطعٌ حرجٌ واحدٌ لكلّ سائق.**
//
// # لماذا وُجد
//
// **حارسان يسألان السؤالَ نفسَه في اللحظة نفسِها**:
//
//	سقفُ النقد          ←  `D7` — أيحتمل مالَ هذا الطلب؟
//	وسقفُ الطلبات النشطة ←  `D24` — أيحتمل طلباً آخر؟
//
// **وكلاهما عن السائق نفسِه وفي لحظةِ القبول نفسِها.**
//
// **وقفلان لحارسَين على مَوردٍ واحدٍ وهمُ حماية**: **من أخذ
// `driver-cash:` وحدَه سابقَ من أخذ `driver-active:`** — **فيمرّ
// الاثنان وكلٌّ منهما يظنّ نفسَه محروساً.**
//
// **فالقفلُ واحدٌ ومالكُه واحد** — **يُؤخَذ هنا مرّةً ثمّ يُسأل
// الحارسان تحته.**
//
// # وما كان يقع
//
// **إسنادُ المكتب لم يكن يسأل عن السقف أصلاً** — **ثلاثةُ طلباتٍ
// والسقفُ واحد، وكلُّها مرّت.**
//
// **وانتزاعُ السائق كان يقرأ العددَ قبل المعاملة ثمّ يكتب** —
// **فمئةُ جولةٍ من مئةٍ تجاوزت السقف**، **والبابان معاً كذلك.**
//
// # والقفلُ على السائق لا على النظام
//
// **سائقان لا ينتظر أحدُهما الآخر** — **وحارسٌ يُسلسِل الإسنادَ
// كلَّه يشلّ المنصّةَ في ساعة الذروة.**
//
// **ويسقط بانتهاء المعاملة** (`xact`) — **فلا يُنسى مفتوحاً.**
//
// # ولا خروجَ إلى الشبكة تحته
//
// **القفلُ يحرس قبولاً في القاعدة** — **لا بثّاً ولا إشعاراً ولا
// تحويلاً**: تلك كلُّها بعد التثبيت كما كانت (`R24`/`XG-44`).

import (
	"context"
	"net/http"

	"github.com/servacode/rahalgo/backend/internal/dbtx"
	"github.com/servacode/rahalgo/backend/internal/httpx"
)

// ErrTooManyActive **بلغ السائقُ سقفَ ما بيده.**
//
// **والرمزُ هو القائمُ في بابِ الانتزاع** (`too_many_active_orders`)
// — **ولا يُخترَع رمزٌ ثانٍ لحكمٍ واحد**، وله نصُّه العربيُّ في
// خريطة أندرويد.
var ErrTooManyActive = httpx.NewError(http.StatusConflict,
	"too_many_active_orders", "errors.too_many_active_orders")

// Admission **ما يلزم للحكم** — يُقرأ كلُّه قبل فتح المعاملة.
//
// **والسقوفُ تُمرَّر ولا تُقرأ هنا**: **قراءةُ إعدادٍ داخلَ معاملةٍ
// تطلب اتّصالاً ثانياً والأوّلُ في اليد** (`XG-48`).
type Admission struct {
	// CashDue نقدُ الطلب الداخل — صفرٌ لما لا نقدَ فيه.
	CashDue int64
	// CashLimit سقفُ التعرّض النقديّ.
	CashLimit int64
	// ActiveMax سقفُ الطلبات النشطة — **وسالبٌ يعني «لا سقفَ هنا».**
	//
	// **وهو استثناءٌ قائمٌ لا ثغرة**: **ما عُرض على السائق بعينه
	// يُقبَل ولو بلغ سقفَه** (قرارُ المالك ٢٠٢٦-٠٨-١٣) — **والعرضُ
	// لا يقع إلّا بعد فحص شروطه، فما عبره مسموحٌ بالتعريف.**
	ActiveMax int64
}

// AdmitDriverTx **أيجوز أن يصير هذا الطلبُ مسؤوليّةَ هذا السائق؟**
//
// **ويُنادى داخلَ معاملة الإسناد** — **قبل الكتابة وبعد فتحها.**
//
// **ويسقط بأوّل مانع**: **ولا يُكتب إسنادٌ نجح فيه حارسٌ وسقط فيه
// أخوه.**
func (s *Service) AdmitDriverTx(ctx context.Context, q dbtx.Querier,
	driverID string, in Admission) error {

	// **والقفلُ باسمٍ مفصولٍ عن سواه** — **ورقمٌ يُشتقّ من نصٍّ قد
	// يصادف رقمَ قفلٍ آخرَ في المنصّة**، فيُسبَق بمجالٍ يخصّه.
	if _, err := q.Exec(ctx,
		`SELECT pg_advisory_xact_lock(hashtext('driver-admit:' || $1::text))`,
		driverID); err != nil {
		return err
	}

	// ── سقفُ الطلبات النشطة ───────────────────────────────────────
	//
	// **والنشطُ ما بيده ولم يُغلَق** — **تعريفٌ واحدٌ يقرؤه المرشَّحُ
	// وبابُ الانتزاع وهذا الحارس.**
	//
	// **ويُقرأ داخلَ القفل لا قبله**: **عددٌ قُرئ قبله يشيخ قبل أن
	// يُستعمَل**، **وهو `D24` بعينه.**
	if in.ActiveMax > 0 {
		var active int64
		if err := q.QueryRow(ctx, `
			SELECT count(*) FROM orders
			WHERE driver_id = $1::uuid AND closed_at IS NULL`,
			driverID).Scan(&active); err != nil {
			return err
		}
		// **والحدُّ يُبلَغ ولا يُتجاوَز**: **من بيده اثنان والسقفُ
		// ثلاثةٌ يأخذ ثالثاً** — **ومن بيده ثلاثةٌ يُردّ.**
		if active+1 > in.ActiveMax {
			return ErrTooManyActive
		}
	}

	// ── وسقفُ النقد ───────────────────────────────────────────────
	//
	// **تحت القفل نفسِه** — **ولا قفلَ ثانٍ ولا ترتيبَ يُحفَظ.**
	if s.cashbox == nil {
		return nil
	}
	return s.cashbox.GuardTx(ctx, q, driverID, in.CashDue, in.CashLimit)
}
