// ══════════════════════════════════════════════════════════════════════
//
//	**من رفض الاستلامَ يدفع مقدَّماً مدّةً**
//
// ══════════════════════════════════════════════════════════════════════
//
// (قرارُ المالك ٢٠٢٦-٠٨-٢٣: «الزبونُ الذي يرفض الاستلام مرّةً واحدةً لا
//
//	تصبح طلباتُه إلّا عن طريق المحفظة حصراً… تُقفل لديه لمدّةٍ يحدّدها
//	الأدمن».)
//
// # ما يحميه
//
// **الطلبُ المرفوضُ خسارةٌ كاملةٌ على المنصّة** — مقيسةٌ على طلبٍ حقيقيّ
// (٢٠٢٦-٠٨-٢٣): بضاعةٌ بـ٢٣٤ دُفعت للمتجر لحظةَ الاستلام، وتعويضٌ ٥٠
// للسائق، **والزبونُ لم يدفع شيئاً والطعامُ بيدنا.**
//
// **والمقابلُ موجودٌ للمتجر منذ زمن** (`merchants.cancel_ban_*`) —
// **وبابٌ مبنيٌّ لطرفٍ ومفتوحٌ للآخر ليس عدلاً بل سهو.**
//
// # ولماذا دفعٌ مقدَّمٌ لا حظرُ حساب
//
// **من رفض مرّةً قد يكون معذوراً**: عنوانٌ خاطئٌ أو ظرفٌ طارئ. **وحظرُ
// حسابه عقوبةٌ تفقده زبوناً، والدفعُ المقدَّمُ يحمي المالَ ويُبقيه.**
// **ومن دفع سلفاً لا يخسر أحدٌ إن لم يستلم** — يُردّ إليه ما دفع
// (`refundOnEnter`) ولا تدفع المنصّةُ من جيبها.
//
// # وذنبُه هو لا كلُّ إخفاق
//
// **`fault` يُكتب لحظةَ الفشل** (`failreasons.go`) — وأربعةُ أسبابٍ
// ذنبُها على الزبون: غيابُه، ورفضُه، وتعذّرُ الوصول إليه، وعنوانٌ خاطئ.
// **وطلبٌ فشل بذنب المتجر أو السائق لا يُحسب عليه** — ولو حُسب لَعوقب
// على ما لا يملك من أمره شيئاً.

// ErrCashBlocked **الدفعُ نقداً موقوفٌ مؤقّتاً** — والمحفظةُ مفتوحة.
//
// **والرسالةُ تقول البديلَ لا المنعَ وحدَه**: من قرأ «مرفوض» أغلق
// التطبيق، **ومن قرأ «ادفع من محفظتك» أكمل طلبَه.**
var ErrCashBlocked = httpx.NewError(http.StatusConflict,
	"cash_blocked", "errors.cash_blocked")

// cashBlocked **أعلى هذا الزبونُ إخفاقاتٌ بذنبه في المدّة؟**
//
// # ولماذا يُعدُّ في نافذةٍ لا مطلقاً
//
// **إخفاقٌ قبل سنةٍ ليس حاضراً** — ومن عوقب على ما مضى لا يعود.
// **والنافذةُ تُنسي ما قدُم** فيعود الزبونُ إلى النقد بعد أن يمضي أجلُه.
//
// # والصفرُ يُطفئ الحارسَ
//
// **فمن لم يُرده لم يُفرض عليه** — ولا يُكتب مفتاحٌ لا سبيلَ لإطفائه.
func (s *Service) cashBlocked(ctx context.Context, customerID string) (bool, error) {
	if s.settings == nil {
		return false, nil
	}
	limit := s.settings.GetInt(ctx, "customers.cash_ban_failures")
	if limit <= 0 {
		return false, nil
	}
	days := s.settings.GetInt(ctx, "customers.cash_ban_days")
	if days <= 0 {
		return false, nil
	}

	// **ويُعدُّ من `order_events` لا من `orders.status`** — الطلبُ قد
	// يُعالَج بعدها (استرجاعٌ أو تسويةُ بضاعة) **فيتبدّل حالُه ويضيع
	// أثرُ الإخفاق.** والحدثُ لا يتبدّل: **وقع فقُيّد.**
	var failures int64
	err := s.db.QueryRow(ctx, `
		SELECT count(*)
		FROM order_events e
		JOIN orders o ON o.id = e.order_id
		WHERE o.customer_id = $1
		  AND e.to_status = 'failed'
		  AND o.fault = 'customer'
		  -- **والمدّةُ تُضرَب لا تُلصَق نصّاً** — لصقُ رقمٍ في تعبيرٍ
		  -- نصّيٍّ يجعل pgx يعجز عن ترميزه فيسقط النداءُ كلُّه
		  -- (cannot find encode plan). **وكشفه أوّلُ اختبارٍ ناداه.**
		  AND e.created_at > now() - ($2::int * interval '1 day')`,
		customerID, days).Scan(&failures)
	if err != nil {
		return false, err
	}
	return failures >= limit, nil
}
