package orders

/*
**الحديثُ يبدأ بنفسه لحظةَ يأخذ السائقُ الطلبَ الخاصّ.**

(قرارُ المالك ٢٠٢٦-٠٨-١٠: «مجرّد ما السائق ياخذ الطلب يجب أن تُفتح دردشة عند
 الطرفين، ورسالةٌ تلقائيّةٌ للسائق بالطلب المطلوب، وردٌّ للمستخدم: لقد استلمتُ
 طلبك سوف تصلك تفاصيل السعر بعد قليل».)

# ولماذا لا تكفي قناةٌ مفتوحةٌ فارغة

**القناةُ كانت تُفتح ولا يقول فيها أحدٌ شيئاً.** والفقّاعةُ لا تظهر إلّا بحديثٍ
يُنبّه، **فيبقى الطرفان ينتظر كلٌّ منهما الآخر**: السائقُ لا يعرف أنّ عليه أن
يبدأ، والزبونُ لا يعرف أنّ أحداً أخذ طلبَه.

**والطلبُ الخاصُّ لا يمشي بلا كلام**: لا سعرَ فيه ولا أجرةَ حتّى يتّفقا. **فصمتُ
الدقائق الأولى هو العطبُ نفسُه** — لا واجهةٌ ناقصة.

# ورسالتان لا واحدة

**الأولى نصُّ الطلب كما كتبه صاحبُه** — تُنسَب إليه لأنّها كلامُه حرفاً بحرف.
**وبها يفتح السائقُ الحديثَ وهو يعرف ما المطلوب**، لا «افتح واسأل».

**والثانية جوابٌ باسم السائق**: «استلمتُ طلبك». **وهي واقعٌ لا وعد** — أخذ
الطلبَ فعلاً، وهذا ما تقوله. **والزبونُ ينتظر خبراً** ولو بعد دقيقة.

# وتُكتب مرّةً لا مرّتين

**الإسنادُ يقع أكثرَ من مرّة**: يُسحب الطلبُ من سائقٍ فيُعاد إلى الطابور فيأخذه
ثانٍ. **فنصُّ الطلب يُكتب إن كان الحديثُ فارغاً**، **وتحيّةُ السائق تُكتب لمن
لم يقل في هذا الحديث شيئاً بعد** — فالسائقُ الثاني يُحيّي والنصُّ لا يُكرَّر.

# وبعد الإيداع لا داخلَه

**رسالةٌ تعذّرت كتابتُها لا تُبطل إسناداً وقع** — الطلبُ في يد السائق فعلاً،
**ومعاملةٌ تسقط لأجل سطرِ حديثٍ تترك الطلبَ بلا صاحب.**
*/

import (
	"context"
)

// customGreeting **جوابُ السائق الأوّل — باسمه لأنّه واقعُه.**
const customGreeting = "استلمتُ طلبك — سوف تصلك تفاصيل السعر وأجرة التوصيل بعد قليل."

// openCustomChat **يكتب أوّلَ سطرين في حديث الطلب الخاصّ.**
//
// **ولا يردّ خطأً يوقف شيئاً** — يُسجَّل ويمضي.
func (s *Service) openCustomChat(ctx context.Context, orderID, customerID, driverID string) {
	if driverID == "" {
		return
	}

	// **نصُّ الطلب من الصفّ لا من الذاكرة** — قد يكون عُدّل بعد الإنشاء.
	var request string
	if err := s.db.QueryRow(ctx,
		`SELECT COALESCE(custom_request, '') FROM orders WHERE id = $1`,
		orderID).Scan(&request); err != nil {
		s.logger.Error("الطلب الخاصّ: تعذّرت قراءةُ نصّ الطلب", "order", orderID, "error", err)
		return
	}
	if request == "" {
		return
	}

	// **الأولى: كلامُ الزبون — إن كان الحديثُ فارغاً.**
	//
	// **والشرطُ في الاستعلام لا في نداءين** — بين السؤال والكتابة تقع كتابةٌ
	// أخرى، **فيُكتب النصُّ مرّتين** لسائقين أخذا الطلبَ في ثانيةٍ واحدة.
	if _, err := s.db.Exec(ctx, `
		INSERT INTO order_messages (order_id, sender_id, sender_role, body)
		SELECT $1, $2, 'customer', $3
		WHERE NOT EXISTS (SELECT 1 FROM order_messages WHERE order_id = $1)`,
		orderID, customerID, request); err != nil {
		s.logger.Error("الطلب الخاصّ: تعذّرت كتابةُ نصّ الطلب في الحديث",
			"order", orderID, "error", err)
	}

	// **والثانية: جوابُ هذا السائق — إن لم يكن قال شيئاً بعد.**
	if _, err := s.db.Exec(ctx, `
		INSERT INTO order_messages (order_id, sender_id, sender_role, body)
		SELECT $1, $2, 'driver', $3
		WHERE NOT EXISTS (SELECT 1 FROM order_messages
		                  WHERE order_id = $1 AND sender_id = $2)`,
		orderID, driverID, customGreeting); err != nil {
		s.logger.Error("الطلب الخاصّ: تعذّرت كتابةُ جواب السائق",
			"order", orderID, "error", err)
	}
}
