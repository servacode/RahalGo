package orders

/*
**الحديثُ يبدأ بنفسه لحظةَ يأخذ السائقُ الطلبَ الخاصّ.**

(قرارُ المالك ٢٠٢٦-٠٨-١٠: «مجرّد ما السائق ياخذ الطلب يجب أن تُفتح دردشة عند
 الطرفين، ورسالةٌ تلقائيّةٌ للسائق بالطلب المطلوب، وردٌّ للمستخدم: لقد استلمتُ
 طلبك سوف تصلك تفاصيل السعر بعد قليل».)

# ولماذا لا تكفي قناةٌ مفتوحةٌ فارغة

**القناةُ كانت تُفتح ولا يقول فيها أحدٌ شيئاً.** والفقّاعةُ لا تظهر إلّا بحديثٍ
يُنبّه، **فيبقى الطرفان ينتظر كلٌّ منهما الآخر**: السائقُ لا يعرف أنّ عليه أن
يبدأ، والزبونُ لا يعرف أنّ أحداً أخذ طلبَه.

**والطلبُ الخاصُّ لا يمشي بلا كلام**: لا سعرَ فيه ولا أجرةَ حتّى يتّفقا. **فصمتُ
الدقائق الأولى هو العطبُ نفسُه** — لا واجهةٌ ناقصة.

# ورسالتان لا واحدة

**الأولى نصُّ الطلب كما كتبه صاحبُه** — تُنسَب إليه لأنّها كلامُه حرفاً بحرف.
**وبها يفتح السائقُ الحديثَ وهو يعرف ما المطلوب**، لا «افتح واسأل».

**والثانية جوابٌ باسم السائق**: «استلمتُ طلبك». **وهي واقعٌ لا وعد** — أخذ
الطلبَ فعلاً، وهذا ما تقوله. **والزبونُ ينتظر خبراً** ولو بعد دقيقة.

# وتُكتب مرّةً لا مرّتين

**الإسنادُ يقع أكثرَ من مرّة**: يُسحب الطلبُ من سائقٍ فيُعاد إلى الطابور فيأخذه
ثانٍ. **فنصُّ الطلب يُكتب إن كان الحديثُ فارغاً**، **وتحيّةُ السائق تُكتب لمن
لم يقل في هذا الحديث شيئاً بعد** — فالسائقُ الثاني يُحيّي والنصُّ لا يُكرَّر.

# وبعد الإيداع لا داخلَه

**رسالةٌ تعذّرت كتابتُها لا تُبطل إسناداً وقع** — الطلبُ في يد السائق فعلاً،
**ومعاملةٌ تسقط لأجل سطرِ حديثٍ تترك الطلبَ بلا صاحب.**
*/

import (
	"context"
)

// customGreeting **جوابُ السائق الأوّل — باسمه لأنّه واقعُه.**
const customGreeting = "استلمتُ طلبك — سوف تصلك تفاصيل السعر وأجرة التوصيل بعد قليل."

// plainGreeting **وأوّلُ كلمةٍ في طلبٍ عاديّ.**
//
// ══════════════════════════════════════════════════════════════════════
// **والحديثُ يُفتح في العاديّ كما في الخاصّ**
// ══════════════════════════════════════════════════════════════════════
//
// (قرارُ المالك ٢٠٢٦-٠٨-١١: «هل نسمح للدردشة أيضاً إذا كان الطلبُ عاديّاً
//
//	ولیس خاصّاً — تفتح دردشةٌ عند الطرفين فيعلم الزبونُ بحال طلبه».)
//
// **والقناةُ كانت مفتوحةً أصلاً بعد تعيين السائق** — لكنّها صامتة. **وقناةٌ
// فارغةٌ لا يعرف أحدٌ أنّها موجودة**: الزبونُ لا يرى فقّاعةً تدعوه، والسائقُ
// لا يعلم أنّ له باباً إلى صاحب الطلب.
//
// **فيقع ما تقع فيه كلُّ منصّة**: يتأخّر السائقُ أو يضلّ العنوانَ، **فيتّصل
// الزبونُ بالمنصّة أو يُلغي** — والحلُّ كان في يده ولم يُعرَض عليه.
//
// **ولا نصَّ طلبٍ هنا يُنقل**: الطلبُ العاديُّ أصنافٌ يراها الطرفان في
// الكرت، **ونسخُها في الحديث تكرارٌ يزاحم ما يُكتب بعده.** فسطرٌ واحدٌ
// يفتح الباب.
const plainGreeting = "أنا سائقُ طلبك — تواصل معي هنا إن احتجتَ شيئاً."

// openCustomChat **يكتب أوّلَ سطرين في حديث الطلب الخاصّ.**
//
// **ولا يردّ خطأً يوقف شيئاً** — يُسجَّل ويمضي.
func (s *Service) openCustomChat(ctx context.Context, orderID, customerID, driverID string) {
	if driverID == "" {
		return
	}

	// **نصُّ الطلب من الصفّ لا من الذاكرة** — قد يكون عُدّل بعد الإنشاء.
	var request string
	if err := s.db.QueryRow(ctx,
		`SELECT COALESCE(custom_request, '') FROM orders WHERE id = $1`,
		orderID).Scan(&request); err != nil {
		s.logger.Error("الطلب الخاصّ: تعذّرت قراءةُ نصّ الطلب", "order", orderID, "error", err)
		return
	}
	if request == "" {
		return
	}

	// **الأولى: كلامُ الزبون — إن كان الحديثُ فارغاً.**
	//
	// **والشرطُ في الاستعلام لا في نداءين** — بين السؤال والكتابة تقع كتابةٌ
	// أخرى، **فيُكتب النصُّ مرّتين** لسائقين أخذا الطلبَ في ثانيةٍ واحدة.
	if _, err := s.db.Exec(ctx, `
		INSERT INTO order_messages (order_id, sender_id, sender_role, body)
		SELECT $1, $2, 'customer', $3
		WHERE NOT EXISTS (SELECT 1 FROM order_messages WHERE order_id = $1)`,
		orderID, customerID, request); err != nil {
		s.logger.Error("الطلب الخاصّ: تعذّرت كتابةُ نصّ الطلب في الحديث",
			"order", orderID, "error", err)
	}

	// **والثانية: جوابُ هذا السائق — إن لم يكن قال شيئاً بعد.**
	if _, err := s.db.Exec(ctx, `
		INSERT INTO order_messages (order_id, sender_id, sender_role, body)
		SELECT $1, $2, 'driver', $3
		WHERE NOT EXISTS (SELECT 1 FROM order_messages
		                  WHERE order_id = $1 AND sender_id = $2)`,
		orderID, driverID, customGreeting); err != nil {
		s.logger.Error("الطلب الخاصّ: تعذّرت كتابةُ جواب السائق",
			"order", orderID, "error", err)
	}
}

// openPlainChat **يفتح حديثَ الطلب العاديّ بسطرٍ من سائقه.**
//
// **والشرطُ في الاستعلام لا في نداءين** — كما في الخاصّ: بين السؤال والكتابة
// تقع كتابةٌ أخرى، **فيُكتب السطرُ مرّتين** لسائقين أخذا الطلبَ في ثانية.
func (s *Service) openPlainChat(ctx context.Context, orderID, driverID string) {
	if driverID == "" {
		return
	}
	if _, err := s.db.Exec(ctx, `
		INSERT INTO order_messages (order_id, sender_id, sender_role, body)
		SELECT $1, $2, 'driver', $3
		WHERE NOT EXISTS (SELECT 1 FROM order_messages
		                  WHERE order_id = $1 AND sender_id = $2)`,
		orderID, driverID, plainGreeting); err != nil {
		s.logger.Error("تعذّر فتحُ حديث الطلب", "order", orderID, "error", err)
	}
}

// ══════════════════════════════════════════════════════════════════════
// **وسطرٌ في الحديث عند كلّ خطوة**
// ══════════════════════════════════════════════════════════════════════
//
// (البندُ الثاني عشر في قائمة المالك ٢٠٢٦-٠٨-١٢: «رسائل تلقائية للزبون
//
//	بكلّ خطوة: في طريقي للمتجر · استلمت طلبك · وصلتك».)
//
// # لماذا في الحديث لا في الإشعار وحدَه
//
// **الإشعارُ يمرّ ويُمحى** — والزبونُ الذي فتح تطبيقَه بعد ربع ساعةٍ لا
// يجد شيئاً. **والحديثُ يبقى**: يقرأ فيه أين صار طلبُه بلا أن يسأل.
//
// **وهي باسم السائق** لأنّها فعلُه — **لا إشعارَ نظامٍ بلا وجه.**
//
// # ولا سطرَ لكلّ حال
//
// **`at_pickup` ليست خبراً للزبون**: وقوفُ السائق عند المتجر شأنُ
// السائق. **وأربعةٌ تكفي**: مشى · استلم · وصل · سلّم. **ومن كتب سطراً
// لكلّ انتقالٍ** حوّل الحديثَ إلى سجلٍّ لا يُقرأ.
var stepLines = map[string]string{
	StAssigned:  "استلمتُ طلبك — في طريقي إلى المتجر.",
	StPickedUp:  "استلمتُ طلبك من المتجر — في طريقي إليك.",
	StAtDropoff: "وصلتُ إليك.",
	StDelivered: "سُلّم الطلب — شكراً لك.",
}

// ══════════════════════════════════════════════════════════════════════
// **وسطورُ الطلب الخاصّ لا تذكر متجرا**
// ══════════════════════════════════════════════════════════════════════
//
// (شكوى المالك ٢٠٢٦-٠٨-١٣ على البطاقة، **وهذه العائلةُ نفسُها في
//
//	الحديث** — وأمسكها اختبارُ القاعدة.)
//
// **«في طريقي إلى المتجر» تصل زبونَ طلبٍ خاصٍّ ولا متجرَ فيه** —
// السائقُ يشتريه بنفسه من حيث وجده. **وخبرٌ كاذبٌ يصل الزبونَ في حديثه
// أسوأُ من صمت**: يسأل «أيّ متجر؟» فلا جواب.
//
// **والإسنادُ بلا سطرٍ هنا**: `openCustomChat` تكتب تحيّتَها لحظتَه
// («سوف تصلك تفاصيل السعر وأجرة التوصيل») — **وسطرٌ ثانٍ في اللحظة
// نفسِها يقول الشيءَ مرّتين.**
var customStepLines = map[string]string{
	StPickedUp:  "اشتريتُ طلبك — في طريقي إليك.",
	StAtDropoff: "وصلتُ إليك.",
	StDelivered: "سُلّم الطلب — شكراً لك.",
}

// stepLine يكتب سطرَ الخطوة في حديث الطلب — **مرّةً واحدةً لكلّ خطوة.**
//
// **ولا يُفشل الانتقال**: الطلبُ تحرّك فعلاً، **ومعاملةٌ تسقط لأجل سطرِ
// حديثٍ** تترك الطلبَ بين حالين.
func (s *Service) stepLine(ctx context.Context, orderID, driverID, kind, to string) {
	table := stepLines
	if kind == KindCustom {
		table = customStepLines
	}
	line, ok := table[to]
	if !ok || driverID == "" {
		return
	}
	if _, err := s.db.Exec(ctx, `
		INSERT INTO order_messages (order_id, sender_id, sender_role, body)
		SELECT $1, $2, 'driver', $3
		WHERE NOT EXISTS (SELECT 1 FROM order_messages
		                  WHERE order_id = $1 AND body = $3)`,
		orderID, driverID, line); err != nil {
		s.logger.Error("تعذّر كتبُ سطر الخطوة", "order", orderID, "error", err)
	}
}
