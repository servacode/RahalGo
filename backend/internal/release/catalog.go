// Package release **سجلُّ التوزيع — مصدرُ حقيقةٍ واحدٌ لتطبيقات المنصّة.**
//
// ══════════════════════════════════════════════════════════════════════
// **مركزُ التنزيل الرسميّ** (`DLC`، ٢٠٢٦-٠٩-١٣)
// ══════════════════════════════════════════════════════════════════════
//
// # ما كان قائماً قبل هذه الحزمة (جُرد لا افتُرض)
//
// **آليّةُ توزيعٍ واحدةٌ لتطبيقٍ واحد**:
//
//	platform.app_url    رابطٌ (متجرُ جوجل عادةً)
//	platform.app_file   ملفٌّ يُرفع من اللوحة
//	GET /api/v1/public/app   يخدم الملفَّ باسم rahalgo.apk
//	appHref()           قاعدةُ الأولويّة: الرابطُ ثمّ الملفّ
//
// **وهي صحيحةٌ لِما بُنيت له** — **يومَ كان «التطبيق» واحداً.** **وصارت
// أربعة**: زبونٌ وسائقٌ ومتجرٌ ومندوب. **ومفتاحٌ واحدٌ لأربعةِ ملفّاتٍ
// يعني أنّ رفعَ تطبيقِ السائق يمحو تطبيقَ الزبون.**
//
// # وما وُجد كذباً صريحاً
//
// **صفحةُ `/app` تعرض زرَّ متجرِ جوجل برابطٍ مكتوبٍ في شيفرتها** —
// **و`platform.app_url` فارغٌ في الإنتاج والتجهيز معاً** (قِيس
// ٢٠٢٦-٠٩-١٣). **فالمنصّةُ تَعِد بمتجرٍ لا يُعرَف أنّه فُتح.**
//
// # والقاعدةُ التي يحرسها هذا السجلّ
//
// **لا أثرَ معتمَدٌ = لا زرَّ تنزيل.** **والغيابُ يُغلق ولا يُخمّن**:
// **إعدادٌ ناقصٌ يعطي «غيرُ متوفّر»، لا ملفّاً قديماً ولا رابطاً
// مُختَرعاً.**
//
// # ولمَ حزمةٌ بذاتها
//
// **أربعُ صفحاتٍ في الويب وخمسُ بوّاباتٍ تقرأ الحالَ نفسَه** — **وقاعدةُ
// أولويّةٍ تُكتب في كلٍّ منها تفترق في الرابعة.** (وهي عِلّةُ `appHref`
// نفسِها المكتوبةُ في تعليقها: «خمسُ بوّاباتٍ تعرض الزرّ».)
package release

// Channel **قناةُ التوزيع المقصودةُ للتطبيق** — لا حالُه الآن.
//
// **والقصدُ في الشيفرة والحالُ في الإعدادات**: **قناةُ الزبون متجرٌ
// بقرار المالك**، **وحالُه «متوفّرٌ أو لا» يقولها الإعدادُ لا الكود.**
type Channel string

const (
	// ChannelPlay **متجرُ جوجل قناةٌ أولى** — يُحدِّث نفسَه ويُطمئن من ينزّل.
	ChannelPlay Channel = "play"
	// ChannelDirect **ملفٌّ رسميٌّ مباشرٌ** — لتطبيقات الفريق.
	ChannelDirect Channel = "direct"
)

// Status **حالُ التوزيع المعلَنة — أحوالٌ صريحةٌ لا استنتاجٌ من وجود نصّ.**
//
// **ومن فحص «هل النصُّ غيرُ فارغ؟» ليقرّر، خلط الغيابَ بالعطب** —
// **والحالُ المُسمّاةُ تُقرأ في الشاشة وفي الفحص وفي التقرير.**
type Status string

const (
	// StatusUnavailable **لا أثرَ معتمَدٌ بعد** — ولا زرَّ يُعرض.
	StatusUnavailable Status = "unavailable"
	// StatusPlay **متجرُ جوجل وحدَه.**
	StatusPlay Status = "play"
	// StatusDirect **ملفٌّ رسميٌّ مباشرٌ وحدَه.**
	StatusDirect Status = "direct"
	// StatusPlayAndDirect **الاثنان** — متجرٌ وملفٌّ رسميّ.
	StatusPlayAndDirect Status = "play_and_direct"
)

// App **تطبيقٌ من الأربعة — هويّتُه ثابتةٌ في الشيفرة.**
//
// **والمعرّفُ يُقرأ من `build.gradle.kts` ولا يُخترَع** — **ويحرسه
// `TestDLC_PackageIdsMatchGradle`**: **من بدّل المعرّفَ في أندرويد ولم
// يبدّله هنا أسقط الفحصَ**، **ولا يُكتشَف بعد النشر أنّ صفحةَ التنزيل
// تقول معرّفاً غيرَ الذي في الجهاز.**
type App struct {
	// Key مفتاحٌ قصيرٌ يظهر في المسار العامّ: `‎/download/<key>`.
	Key string
	// PackageID معرّفُ الحزمة في أندرويد — **كما في الغرادل حرفاً.**
	PackageID string
	// Channel القناةُ المقصودة.
	Channel Channel
	// GradlePath موضعُ الهويّة في المستودع — **للحارس لا للعرض.**
	GradlePath string
}

// Apps **الأربعةُ بترتيبها في مركز التنزيل.**
//
// **والزبونُ أوّلاً**: **هو من يفتح الصفحةَ في الغالب.**
var Apps = []App{
	{Key: "customer", PackageID: "com.rahalgo.customer", Channel: ChannelPlay,
		GradlePath: "mobile/app-customer/build.gradle.kts"},
	{Key: "driver", PackageID: "com.rahalgo.driver", Channel: ChannelDirect,
		GradlePath: "mobile/app-driver/build.gradle.kts"},
	{Key: "merchant", PackageID: "com.rahalgo.merchant", Channel: ChannelDirect,
		GradlePath: "mobile/app-merchant/build.gradle.kts"},
	{Key: "rep", PackageID: "com.rahalgo.rep", Channel: ChannelDirect,
		GradlePath: "mobile/app-rep/build.gradle.kts"},
}

// Find **تطبيقٌ بمفتاحه — أو لا شيء.**
//
// **ومفتاحٌ مجهولٌ لا يُحلّ إلى ملفٍّ** — **وهو حدُّ الأمان في مسار
// التنزيل**: `‎/public/app/{key}` لا يقبل إلّا هذه الأربعة.
func Find(key string) (App, bool) {
	for _, a := range Apps {
		if a.Key == key {
			return a, true
		}
	}
	return App{}, false
}

// ══════════════════════════════════════════════════════════════════════
// **مفاتيحُ الإعدادات — والقيمةُ في اللوحة لا في الشيفرة**
// ══════════════════════════════════════════════════════════════════════
//
// **ورابطٌ يُكتب في شيفرةٍ لا يُبدَّل إلّا بنشر** — وهو نصُّ تعليقِ
// `platform.app_url` القائم، **وهو ما خرقته صفحةُ `/app`.**

// PlayURLKey مفتاحُ رابط متجرِ جوجل لهذا التطبيق.
func PlayURLKey(key string) string { return "release." + key + ".play_url" }

// ApkKey مفتاحُ اسمِ ملفِّ الأثر المخزَّن — **يكتبه الخادمُ عند الرفع.**
func ApkKey(key string) string { return "release." + key + ".apk" }

// **ولا مفتاحَ للبصمة** — **تُحسب من الملفّ نفسِه** (`public.go`):
// **إعدادٌ تكتبه يدٌ يكذب**، **والمحسوبُ من القرص لا يكذب.**

// VersionKey **اسمُ النسخة المعروض** — نصٌّ يكتبه المالك.
//
// **ولا يُقرأ من الملفّ**: **قراءةُ `versionName` من `APK` تحتاج أدواتِ
// أندرويد على الخادم**، **ولا تُنصَّب لأجل سطرٍ يُعرض.** **فيبقى
// اختياريّاً**: **يُعرض إن كُتب ويُسكَت عنه إن لم يُكتب** — **ولا
// يُخترَع رقمٌ.**
func VersionKey(key string) string { return "release." + key + ".version" }

