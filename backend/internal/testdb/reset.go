// ══════════════════════════════════════════════════════════════════════
// **قاعدةُ الاختبار تبدأ نظيفةً — لا حيث انتهى تشغيلُ أمس**
// ══════════════════════════════════════════════════════════════════════
//
// (بأمر المالك ٢٠٢٦-٠٨-٢٠: «الاختبارات تصبح Deterministic · معزولة ·
//  قابلة للتكرار · **لا تعتمد على بيانات تراكمت من تشغيلات سابقة**».)
//
// # ما وقع فعلاً
//
// **كان في هذه الحزمة تنظيفٌ يكذب.** `NewUser` تسجّل `t.Cleanup` يحذف
// المستخدمَ في آخر الاختبار — **والحذفُ يفشل دائماً** بقيدٍ أجنبيٍّ من
// `audit_log`، **وخطؤه مُهمَلٌ بـ`_, _ =`** فلا يراه أحد.
//
// **فبقي كلُّ مستخدمٍ وُلد في شهر.** والقياسُ يوم كُتب هذا:
//
//	notifications  ٥٬٥٨٨٬٥٢٢ صفّاً  ·  ١٨٢٨ ميغابايت
//	users             ٦٧٬٨٩٩       ·   ٨٢ ميغابايت
//	القاعدةُ كلُّها                  ·  ٢٠٠٩ ميغابايت
//
// **وثمنُه سقوطٌ يبدو عشوائيّاً**: `NOTIF-001` يقيس ٣٫٥ ثانيةٍ مرّةً
// و٢٦٫٥ مرّةً أخرى بالشيفرة نفسِها — **ليس عيباً في المنتج بل ركاماً في
// القاعدة.**
//
// **وأثرُه أعمقُ من البطء**: في `NewUser` خمسون محاولةً تقفز فوق أرقام
// هواتفَ مشغولة — **آليّةٌ وُلدت لتحتمل الركام لا لتصلحه.**
//
// # ولماذا لم يُصلَح الحذفُ بدل هذا
//
// **ثلاثون قيداً أجنبيّاً تشير إلى `users`** (قِيست). وحذفٌ يدويٌّ
// يرتّبها **يشيخ مع أوّل جدولٍ جديد** — بالصمت نفسِه الذي أخفى العيبَ
// شهراً.
//
// **وإسقاطُ المخطّطِ ثمّ الهجراتُ لا يشيخ**: حالةُ البداية هي حالةُ
// خادمٍ يُقلع أوّلَ مرّة، **مهما تبدّلت الجداول.**
//
// **والامتداداتُ تعود معها** — `postgis` و`citext` و`pg_trgm` تُنشئها
// الهجرتان `0001` و`0039` بـ`IF NOT EXISTS`.
//
// **وكلفتُه ٥٫٦ ثوانٍ مقيسةً** لـ١١٧ هجرةً على قاعدةٍ فارغة — **مرّةً
// واحدةً في العمليّة لا في كلّ اختبار.**

const (
	// **مفتاحُ القفل** — رقمٌ ثابتٌ لا معنى له إلّا أنّه لنا.
	lockKey = 8_140_921_356_711_042

	// **وكم يُنتظر قبل الاستسلام** — بناءٌ كاملٌ لا يتجاوزها.
	lockWait = 10 * time.Minute
)

var prepareOnce sync.Once

// **الاتّصالُ حاملُ القفل** — يعيش عمرَ العمليّة كلَّه.
//
// **ولا يُغلق عمداً**: بوستغرس يحرّر قفلَ الجلسة عند انقطاعها، **فخروجُ
// العمليّة — ولو انهياراً — يحرّره.**
var lockConn *pgx.Conn

// prepare يمسك القاعدةَ لهذه العمليّة ثمّ يعيدها إلى الصفر — مرّةً واحدة.
func prepare(t *testing.T, rawURL string, pool *pgxpool.Pool) {
	t.Helper()
	var failure error
	prepareOnce.Do(func() {
		failure = lockAndReset(rawURL, pool)
	})
	if failure != nil {
		t.Fatalf("تعذّرت تهيئةُ قاعدة الاختبار: %v", failure)
	}
}

func lockAndReset(rawURL string, pool *pgxpool.Pool) error {
	// **والحارسُ يُعاد هنا** — هذه الدالّةُ تُسقط مخطّطاً، **فلا تُصدَّق
	// نيّةُ من ناداها.**
	if !isTestDatabase(rawURL) {
		return fmt.Errorf("رُفض المسح: %s ليست قاعدةَ اختبار", redactURL(rawURL))
	}

	ctx := context.Background()
	if err := acquire(ctx, rawURL); err != nil {
		return err
	}

	// **وقد يُراد فحصُ القاعدة بعد سقوط** — فيُسكت المسحُ صراحةً.
	if os.Getenv("TEST_DB_KEEP") != "" {
		return nil
	}

	// **الإسقاطُ والهجراتُ بعده في `Pool`.**
	if _, err := pool.Exec(ctx,
		`DROP SCHEMA IF EXISTS public CASCADE; CREATE SCHEMA public`); err != nil {
		return fmt.Errorf("تعذّر إسقاطُ المخطّط: %w", err)
	}
	return nil
}

// ══════════════════════════════════════════════════════════════════════
// **وقاعدةٌ واحدةٌ لا يقتسمها تشغيلان**
// ══════════════════════════════════════════════════════════════════════
//
// **إحدى عشرة حزمةً تتقاسم `rahalgo_test`** (قِيست). ومن شغّلها متوازيةً
// **مسحت إحداها ما تحت الأخرى.**
//
// **وقفلُ الجلسة يجعل التسلسلَ شرطَ القاعدة لا عادةَ من يكتب الأمر** —
// فالثانيةُ تنتظر الأولى، **ولا يعود `-p 1` رجاءً في مستند.**
func acquire(ctx context.Context, rawURL string) error {
	conn, err := pgx.Connect(ctx, rawURL)
	if err != nil {
		return fmt.Errorf("تعذّر فتحُ اتّصال القفل: %w", err)
	}
	waitCtx, cancel := context.WithTimeout(ctx, lockWait)
	defer cancel()
	if _, err := conn.Exec(waitCtx, `SELECT pg_advisory_lock($1)`, int64(lockKey)); err != nil {
		_ = conn.Close(ctx)
		return fmt.Errorf("قاعدةُ الاختبار مشغولةٌ بتشغيلٍ آخرَ منذ %v: %w", lockWait, err)
	}
	lockConn = conn
	return nil
}
