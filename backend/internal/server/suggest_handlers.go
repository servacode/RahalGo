package server

import (
	"net/http"
	"strconv"
)

// handleSuggestWith **«يُطلب معه»** — ما يُشترى مع ما في السلّة.
//
// (طلبُ المالك ٢٠٢٦-٠٨-٢٢: «نقطةٌ يجب أن تُضاف — مع الأكل مثلاً كولا،
//
//	عيران، والأحجام. هي حركةٌ ذكيّةٌ بالأكل تعرض عليه كولا أو عيران، هي
//	أكثرُ شيءٍ تنطلب».)
//
// # لماذا لا تكفي المجموعاتُ الاختياريّة
//
// **«يُضاف» يلصق الكولا بالساندويش** — سطرٌ واحدٌ بسعرٍ واحد. **والزبونُ
// الذي طلب ثلاثةَ ساندويشات وكولتين** لا يستطيع قولَها بالخيارات: إمّا
// كولا لكلٍّ أو لا شيء. **والاقتراحُ يضيف صنفاً مستقلّاً** يزيد عدَّه
// ويُنقصه كما يشاء.
//
// # وما يُقترح
//
// **مشروبٌ ومقبّلاتٌ وحلوى** — الأقسامُ الثلاثةُ التي تُطلب مع الطعام،
// **ولا تُقترح شاورما على شاورما.** ويُستثنى ما في السلّة أصلاً:
// **اقتراحُ ما اشتراه يقول له إنّنا لا نقرأ سلّته.**
//
// # ولماذا يُرشَّح بالمدينة
//
// **الاقتراحُ يدخل السلّة بضغطةٍ واحدة** — فلو اقترحنا صنفاً من مدينةٍ
// أخرى **لَرفضه المحرّكُ عند الإرسال** ولا يفهم الزبونُ لماذا سقط طلبُه
// كلُّه بسبب كولا.
func (s *Server) handleSuggestWith(w http.ResponseWriter, r *http.Request) {
	q := r.URL.Query()

	limit := 8
	if n, err := strconv.Atoi(q.Get("limit")); err == nil && n > 0 && n <= 20 {
		limit = n
	}
	// **وما في السلّة يُستثنى** — ولا يُترك فارغاً: `= ANY(NULL)` تُسقط
	// كلَّ صفّ. **والقائمةُ الفارغةُ في pgx تُرسَل مصفوفةً فارغةً** فتردّ
	// الشرطَ صادقاً لكلّ صنفٍ كما يُراد.
	exclude := q["exclude"]
	if exclude == nil {
		exclude = []string{}
	}

	// **ومدينتُه وحدَها** — انظر `city_filter.go`. **ولو اقتُرح صنفٌ من
	// مدينةٍ أخرى لَرفض المحرّكُ الطلبَ كلَّه عند الإرسال**، ولا يفهم
	// الزبونُ لماذا سقط طلبُه بسبب كولا أضافها باقتراحنا.
	where, geo := s.cityWhere(r.Context(), scopeFrom(r), 3)
	args := append([]any{suggestSections, exclude}, geo...)

	// **والترتيبُ بالأرخص** — الاقتراحُ إضافةٌ على طلبٍ قُرِّر، **وصنفٌ
	// يقارب ثمنَ الوجبة يُقرأ بيعاً لا خدمة.**
	s.scanItems(w, r, itemSelect+`
		  AND ps.name = ANY($1)
		  AND i.available
		  AND NOT (i.id = ANY($2::uuid[]))`+where+`
		ORDER BY i.merchant_price ASC
		LIMIT `+strconv.Itoa(limit), args...)
}

// suggestSections **الأقسامُ التي تُطلب مع الطعام** — ولا رابعَ لها اليوم.
//
// **وأسماءٌ لا معرّفات**: المعرّفاتُ تتبدّل بين قاعدةٍ وقاعدة، **والاسمُ
// هو ما يراه المالكُ في اللوحة** فيعرف ما يجري.
var suggestSections = []string{"مشروبات باردة", "مقبّلات", "حلويّات"}
