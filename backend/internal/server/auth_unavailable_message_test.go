package server

// ══════════════════════════════════════════════════════════════════════
// **«تعذّر التحقّق» رسالةٌ خاصّةٌ بها، لا «عطبٌ غيرُ متوقّع»** — `XG-41B`
// ══════════════════════════════════════════════════════════════════════
//
// # ما كان يقع
//
// **`errors.auth_unavailable` بلا مدخلٍ في المعجم** — **فتسقط
// `errorText` إلى `errors.internal`**: «حدث خطأ غير متوقع، حاول مجددا».
//
// **وذاك كذبٌ في اتّجاهين**: **يقول للمستخدم إنّ في المنصّة عطباً**
// **ولا يقول له أنّ جلستَه سليمةٌ وأنّ الانتظارَ يكفي.**
//
// # ولماذا المعنى دقيقٌ هنا
//
// **الحالُ ثلاثٌ لا اثنتان** (`R16`): سليمة · مُبطَلة · **«لا أعرف».**
// **والثالثةُ ٥٠٣ لا ٤٠١** — **لأنّ «رمزُك مُبطَل» كذبٌ يُخرج صاحبَ
// جلسةٍ سليمةٍ ويطلب منه دخولاً جديداً لن ينفعه.**
//
// **فالرسالةُ يجب أن تقول ذلك بعينه**: **مؤقّتٌ · وليس ذنبَ كلمة
// المرور · ولا يلزمه دخولٌ جديد.**
//
// # وما لا يُقال
//
// **ولا اسمَ بنيةٍ داخليّة**: من قرأ «قاعدة البيانات» أو `Redis` في
// رسالةِ خطأٍ عرف عن المنصّة ما لا يلزمه — **والمهاجمُ يقرأ ما يقرؤه
// الزبون.**

import (
	"encoding/json"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestXG41B_AuthUnavailableHasItsOwnMessage(t *testing.T) {
	raw, err := os.ReadFile(filepath.Join("..", "..", "..",
		"web", "packages", "i18n", "src", "locales", "ar.json"))
	if err != nil {
		t.Skipf("المعجمُ غيرُ متاح: %v", err)
	}
	var dict struct {
		Errors map[string]string `json:"errors"`
	}
	if err := json.Unmarshal(raw, &dict); err != nil {
		t.Fatalf("المعجمُ لا يُقرأ: %v", err)
	}

	msg := dict.Errors["auth_unavailable"]
	if strings.TrimSpace(msg) == "" {
		t.Fatal("**`errors.auth_unavailable` بلا رسالة** — " +
			"**فتُقرأ «حدث خطأ غير متوقع» وهي ليست عطباً** (`XG-41B`)")
	}
	t.Logf("XG-41B: %q", msg)

	// **ولا تسقط إلى العامّة** — **وهذا هو العطبُ بعينه لا عرَضُه.**
	if msg == dict.Errors["internal"] {
		t.Error("**الرسالةُ هي العامّةُ نفسُها** — **فلم يتبدّل شيء**")
	}

	// **ولا تُلقي اللومَ على كلمة المرور ولا تُعلن الجلسةَ باطلة.**
	for _, bad := range []string{"كلمة المرور", "غير صحيحة", "منتهية", "سجل الدخول من جديد", "سجّل الدخول من جديد"} {
		if strings.Contains(msg, bad) {
			t.Errorf("**الرسالةُ تدّعي ما لم يُثبَت** (%q) — "+
				"**والخادمُ قال «لا أعرف» لا «أنت مخطئ»**", bad)
		}
	}

	// **ولا تكشف بنيةً داخليّة.**
	for _, leak := range []string{"قاعدة البيانات", "Redis", "redis", "Postgres", "postgres", "SQL", "خادم قاعدة"} {
		if strings.Contains(msg, leak) {
			t.Errorf("**الرسالةُ تكشف بنيةً داخليّة**: %q", leak)
		}
	}

	// **وتقول إنّه مؤقّت** — فمن قرأها عرف أنّ الانتظارَ يكفي.
	temporary := false
	for _, sign := range []string{"بعد قليل", "لاحقا", "لاحقاً", "الآن", "مؤقت"} {
		if strings.Contains(msg, sign) {
			temporary = true
		}
	}
	if !temporary {
		t.Error("**لا تقول إنّ الحالَ مؤقّتة** — **فيظنّها القارئُ نهائيّة**")
	}
}
