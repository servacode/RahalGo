package server

// هويّةُ المنصة — **من يتعاقد، وإلى من يُشتكى، وأين يقع.**
//
// # لماذا من الإعدادات لا من الشيفرة
//
// الشروطُ والخصوصيةُ وثيقتان قانونيّتان تذكران اسماً ورقماً وعنواناً، **وهذه
// تتغيّر**: يُسجَّل الاسمُ التجاريّ، ويُبدَّل رقمُ الدعم، **وينتقل المكتب.**
//
// **وما كُتب في شيفرةٍ لا يُبدَّل إلّا بنشر** — فيبقى الرقمُ القديمُ معروضاً
// شهراً، **ومن اتّصل به لم يجد أحداً**، ويقرؤها زبونٌ فيظنّ المنصةَ مهجورة.
//
// # وعامّةٌ لا محميّة
//
// **من يُسأل أن يوافق على الشروط يقرؤها قبل أن يدخل** — ووثيقةٌ لا تُقرأ إلّا
// بعد التسجيل وثيقةٌ يُوافَق عليها بلا قراءة.

import (
	"net/http"

	"github.com/servacode/rahalgo/backend/internal/httpx"
)

// handlePublicContact ما تعرضه الصفحاتُ القانونية — **وفارغُه يُحذف لا يُعرض.**
//
// **وسطرٌ يقول «الهاتف: —» أسوأُ من غيابه**: يُقرأ عطباً في المنصة لا حقلاً لم
// يُملأ بعد. فتُعاد الحقولُ كما هي، **والشاشةُ تُسقط الفارغَ منها.**
func (s *Server) handlePublicContact(w http.ResponseWriter, r *http.Request) {
	ctx := r.Context()
	httpx.JSON(w, http.StatusOK, map[string]any{
		// **والاسمُ واحدٌ لا اثنان.**
		//
		// (سأل المالك 2026-08-09: «لا أفهم الفرق بين الاثنين أصلاً».)
		//
		// **كان «الاسمُ القانونيّ» حقلاً ثانياً** يُحقن في الوثيقتين — وقيمتُه
		// عنده اسمُ المنصة نفسُه. **وحقلان بقيمةٍ واحدةٍ يفترقان يوماً** فتقول
		// الشروطُ اسماً ويقول الشريطُ غيرَه.
		//
		// **ويعود إن سُجّلت شركةٌ باسمٍ آخر** — سطرٌ واحدٌ يومَها.
		"legal_name": s.settings.GetString(ctx, "platform.name"),
		// ══════════════════════════════════════════════════════════════
		// **ونصوصُ الصفحات — كاملةً لا فارغةً**
		// ══════════════════════════════════════════════════════════════
		//
		// (طلبُ المالك 2026-08-09: صفحاتٌ ديناميّةٌ تُحرَّر من اللوحة ·
		//  وقرارُه 2026-08-13: «التطبيقُ والويبُ نفسُ النموذج».)
		//
		// **كانت تُردّ فارغةً ما لم تُحرَّر، والويبُ يعوّضها من معجمه.**
		// **وذلك تعويضٌ لا يصل إلى التطبيق** — فيقرأ سائقٌ شروطاً بيضاء.
		//
		// **والافتراضُ صار في المحرّك** (`settings/pagetext.go`)، فيردّ
		// **النصَّ النافذ**: المحرَّرَ إن حُرِّر، **وإلّا الأصل.**
		"help_text":    s.settings.GetString(ctx, "page.help_text"),
		"terms_text":   s.settings.GetString(ctx, "page.terms_text"),
		"privacy_text": s.settings.GetString(ctx, "page.privacy_text"),
		// **ومن نحن** — لا صفحةَ لها في الويب بعد، **ولها بابٌ في
		// التطبيق** (شرطُ غوغل بلاي: من يقف خلف التطبيق يُعرَف).
		"about_text": s.settings.GetString(ctx, "page.about_text"),
		// **وتعليماتُ السائق** — غيرُ تعليمات الزبون: تلك «كيف أطلب؟»،
		// **وهذه «كيف أبدأ ورديّتي؟».**
		"driver_help_text": s.settings.GetString(ctx, "page.driver_help_text"),
		// **وتعليماتُ المندوب** — **ونداءٌ ثالثٌ لسطرٍ تأخيرٌ يُرى**،
		// فتصل الثلاثةُ معاً ويقرأ كلُّ تطبيقٍ ما يخصّه.
		"rep_help_text": s.settings.GetString(ctx, "page.rep_help_text"),
		// **وتعليماتُ المتجر رابعة** — تصل مع أخواتها في النداء نفسِه.
		"merchant_help_text": s.settings.GetString(ctx, "page.merchant_help_text"),
		"support_phone":      s.settings.GetString(ctx, "platform.support_phone"),
		"address":            s.settings.GetString(ctx, "platform.address"),
	})
}
