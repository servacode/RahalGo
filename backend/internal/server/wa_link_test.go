package server

import (
	"net/url"
	"strings"
	"testing"
)

// TestWALink الرابطُ يفتح المحادثةَ الصحيحة بالنصّ الصحيح.
//
// **الرقمُ سوريٌّ والنصُّ عربيٌّ متعدّدُ الأسطر** — وكلاهما يكسر رابطاً بُني
// بالتسلسل. و`wa.me` تريده دولياً بلا `+` ولا صفرٍ بادئ: صفرٌ باقٍ يفتح
// محادثةً لرقمٍ لا وجود له، **ويظنّ الموظّفُ أنه حوّل الطلب وقد فتح صفحةَ
// خطأ**.
func TestWALink(t *testing.T) {
	const text = "طلب جديد #1002\n——————————————\n• سلطة خضراء ×2"

	// ══════════════════════════════════════════════════════════════════
	// **والمُعامَلُ محمولٌ لا أرضيّ** (٢٠٢٦-٠٩-١٣)
	// ══════════════════════════════════════════════════════════════════
	//
	// **وكان `0223344556`** — أرضيُّ حلب. **وواتسابُ لا يعمل على
	// أرضيّ**، **فالرابطُ كان يُبنى لرقمٍ لا حسابَ له عليه** — وهو
	// عينُ العطب الذي يحذّر منه تعليقُ هذا الاختبار.
	//
	// **وهويّةُ الرقم صارت سوريّةً محمولةً وحدَها**، فيردّ التطبيعُ
	// الأرضيَّ ويُرجع `waLink` فراغاً — **فيقرأ الموظّفُ «لا واتساب»
	// بدل أن يفتح محادثةً ميّتة.**
	got := waLink("0932123456", text)
	const wantPrefix = "https://wa.me/963932123456?text="
	if !strings.HasPrefix(got, wantPrefix) {
		t.Fatalf("الرابط = %q، والمتوقّع أن يبدأ بـ%q", got, wantPrefix)
	}

	// **النصُّ يعود كما دخل** — لا سطرٌ ضاع ولا حرفٌ تشوّه.
	decoded, err := url.QueryUnescape(strings.TrimPrefix(got, wantPrefix))
	if err != nil {
		t.Fatalf("فكُّ الترميز تعذّر: %v", err)
	}
	if decoded != text {
		t.Errorf("النصُّ بعد الترميز اختلف:\nوصل: %q\nأُريد: %q", decoded, text)
	}

	// **رقمٌ لا يُفهم يعطي رابطاً فارغاً لا رابطاً مكسوراً.** والواجهة تُخفي
	// الزرَّ عند الفراغ — فلا يُعرض زرٌّ يفتح صفحةَ خطأ.
	for _, bad := range []string{"", "123", "لا رقم"} {
		if got := waLink(bad, text); got != "" {
			t.Errorf("waLink(%q) = %q، والمتوقّع فراغ", bad, got)
		}
	}
}

// TestWALinkRejectsNonMobile **ولا رابطَ واتسابٍ لما لا يستقبله.**
//
// **وفراغٌ صريحٌ أصدقُ من رابطٍ يفتح صفحةَ خطأ** — والمعالِجُ يقرؤه
// «لا واتساب» فيُخبر الموظّف.
func TestWALinkRejectsNonMobile(t *testing.T) {
	for _, in := range []string{
		"0223344556",    // أرضيُّ حلب
		"0112345678",    // أرضيُّ دمشق
		"+905321234567", // تركيّ
		"+14155552671",  // أمريكيّ
		"093212345",     // ناقصٌ رقماً
		"",              // فارغ
	} {
		if got := waLink(in, "نصّ"); got != "" {
			t.Errorf("**رابطٌ بُني لرقمٍ لا يستقبل واتساب**: %q ⇒ %q", in, got)
		}
	}
}
