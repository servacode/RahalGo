//
// # وتصحيحُ العقد
//
// **وما فوق يقول «والمالُ يُحجب كذلك»** — **وهو حقٌّ في مال الزبون
// لا في تسوية المتجر.** **فبقرارِ المالك ٢٠٢٦-٠٨-٢٦ ثمّ ٢٠٢٦-٠٩-٠٩
// يرى صاحبُ المتجر ثلاثةً**: **ما بِيع من عنده · ما اقتُطع منه · بأيّ
// نسبة** — «المجموع» و«خصم المنصة» و«المستحق لك».
//
// **وما عداها يبقى محجوباً**: أجرُ التوصيل وما دفعه الزبونُ جملةً
// وطريقةُ دفعه وحسمُه ومحفظتُه.
//
// **وبقي هذا الملفُّ لأنّ فيه سببَ الحكم لا تنفيذَه.**
