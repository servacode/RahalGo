package server

// خصوصيةُ الزبون عند المتجر.
//
// **الخصوصيةُ لا تكون بإخفاءٍ في الشاشة.** كان الخادم يُرسل إلى بوابة المتجر
// كلَّ ما في الطلب — اسمَ الزبون وهاتفه وعنوانه ودبّوسه — وتُخفيه الواجهةُ أو
// تعرضه. ومن يفتح أدوات المتصفّح يقرؤه كلَّه. **وحجبٌ في الواجهة وحدها ليس
// حجباً، هو وعدٌ بحجب.**
//
// ## ولماذا يُحجب أصلاً
//
// **المتجر لا يحتاجه**: السائقُ يأتي إليه ويأخذ، ولا يذهب المتجرُ إلى أحد.
// وهاتفُ الزبون وعنوانُه في يد مطعمٍ يعني أنه يستطيع أن يتّصل به مباشرةً في
// الطلب القادم — **فتصير المنصةُ دليلَ زبائنَ يُبنى على ظهرها ثم يُستغنى عنها**.
// وهذا أوّلُ ما يُحرَس في كل منصّة توصيل.
//
// ## والمال يُحجب كذلك
//
// بطاقةُ الطلب عند المتجر **ورقةُ مطبخ لا فاتورة**: تقول ماذا يُطبخ وما يُراعى
// فيه. وما يستحقّه المتجر يراه في **محفظته وتقاريره وكشف حسابه** — وهي أدقّ
// لأنها تعرض مستحقّه هو، لا ما دفعه الزبون (وفيه رسمُ توصيلٍ ليس له، وقد
// يُضاف عليه غداً هامشُ منصّة).
//
// ## وما يبقى
//
// رقمُ الطلب · وقتُه · حالتُه · **الأصنافُ بخياراتها** · **وملاحظةُ الزبون** —
// وهي ما يُطبخ به. ووقتُ التحضير والجاهزية، فهما شأنُ مطبخه.

import "github.com/servacode/rahalgo/backend/internal/orders"

// redactForMerchant يمسح ما لا يخصّ المتجر من الطلب.
//
// **بالمسح لا بالاختيار**: لو بُني كائنٌ جديد بالحقول المسموحة لَنُسي حقلٌ
// جديد يُضاف غداً فيُسرَّب صامتاً. والمسحُ يُبقي الإضافةَ ظاهرةً حتى يُنظر فيها.
func redactForMerchant(o *orders.Order) {
	o.CustomerID = ""
	o.CustomerName = ""
	o.CustomerPhone = ""
	o.AddressText = ""
	o.Lat, o.Lng = 0, 0
	o.ZoneID, o.ZoneName = nil, nil

	// السائق كذلك: المتجر يسلّم لمن يأتي، ولا شأن له بمن هو ولا بأجره
	o.DriverID, o.DriverPhone, o.DriverName = nil, nil, nil
	// **ومن عُرض عليه كذلك** — شأنُ توزيعٍ داخليّ لا يخصّ المطبخ.
	o.OfferedDriverName = nil
	// **وصورةُ التسليم تُظهر بابَ الزبون** — والمتجرُ لا يرى عنوانَه أصلاً.
	o.ProofURL, o.ProofTakenAt = nil, nil
	o.ProofMeters, o.ProofSkipReason = 0, ""

	// المال — يراه في محفظته وتقاريره
	o.Subtotal, o.DeliveryFee, o.Discount, o.Total = 0, 0, 0, 0
	o.WalletPaid, o.CashDue = 0, 0
	o.PaymentMethod = ""
	o.PromoCode = nil
}
