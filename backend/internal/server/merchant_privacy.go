//
// **كانت هنا `redactForMerchant` تمحو ستّةَ عشرَ حقلاً ويخرج الباقي**
// — **وقيس عليها ١٤ خرقاً في تفصيل المتجر و١٦ في قائمته** (دورةُ ٤٥).
//
// **وكانت تُصفّر `subtotal` ثمّ يُعيد `fillMerchantMoney` ملأه بعد
// مئتَي سطر** — **فالتنقيةُ التي يجري بعدها قلمٌ ليست تنقية.**
//
