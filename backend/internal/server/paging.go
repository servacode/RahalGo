package server

/*
**الترقيم — حدٌّ يُقال لا سقفٌ يُصمت عنه.**

(قرارُ المالك ٢٠٢٦-٠٨-١٠: «لا تنسَ إضافة الباجينيشن في الأماكن التي تلزم».)

# ولماذا السقفُ الصامتُ عطب

**`LIMIT 200` بلا عدٍّ ولا صفحةٍ ثانيةٍ يقطع القائمةَ بلا كلمة** — **فتُقرأ
«هذا كلُّ ما هناك».** ومن راجع نزاعاتِ الشهر فرأى مئتين ظنّها مئتين، **وبنى
على النقص قراراً.**

**والعدُّ وحدَه لا يكفي**: «٤٠٠ نزاع» ولا سبيلَ إلى الثاني منها مئتين
**يقول لصاحبه إنّ نصفَها محجوبٌ عنه** — فيبحث عن باب.

# ولماذا في ملفٍّ واحد

**كان يُكتب بيدٍ في كلّ معالِج**: قراءةُ الرقم، وحدُّه الأدنى، وحدُّه
الأعلى، وحسابُ الإزاحة. **وأربعةُ أسطرٍ تُنسخ عشرين مرّةً تفترق**: يُنسى
الحدُّ الأعلى في واحدٍ **فيطلب من ينادي الواجهةَ مئةَ ألفِ صفٍّ دفعةً**،
ويُنسى الأدنى في آخرَ فتصير الإزاحةُ سالبة.
*/

import (
	"net/http"
	"strconv"
)

// Paging **صفحةٌ مطلوبةٌ محدودة.**
type Paging struct {
	Page    int
	PerPage int
	Offset  int
}

// maxPerPage **سقفُ ما يُطلب في نداءٍ واحد.**
//
// **ولا يُترك للعميل**: من كتب `per_page=100000` يسحب الجدولَ كلَّه في
// نداءٍ واحد — **وهو بابُ إسقاطِ خادمٍ بسطرٍ في شريط العنوان.**
const maxPerPage = 100

// pagingOf **يقرأ الصفحةَ من النداء بحدودها.**
//
// **والافتراضُ يُمرَّر لا يُكتب هنا**: قائمةُ نزاعاتٍ وقائمةُ نشاطٍ ليستا
// بحجمٍ واحد.
func pagingOf(r *http.Request, def int) Paging {
	q := r.URL.Query()
	page, _ := strconv.Atoi(q.Get("page"))
	perPage, _ := strconv.Atoi(q.Get("per_page"))
	if page < 1 {
		page = 1
	}
	if perPage < 1 {
		perPage = def
	}
	if perPage > maxPerPage {
		perPage = maxPerPage
	}
	return Paging{Page: page, PerPage: perPage, Offset: (page - 1) * perPage}
}

// paged **يغلّف القائمةَ بعددها وصفحتها.**
//
// **والشكلُ نفسُه في كلّ قائمةٍ مرقَّمة** (`{items, total, page, per_page}`)
// — **ومكوّنُ الترقيم في الواجهة يقرأ هذه الحقولَ وحدَها.** فلو سمّاها
// معالِجٌ بغيرها لَعُرضت صفحةٌ واحدةٌ أبداً بلا خطأ.
func paged(key string, items any, total int, p Paging) map[string]any {
	return map[string]any{
		key:        items,
		"total":    total,
		"page":     p.Page,
		"per_page": p.PerPage,
	}
}
