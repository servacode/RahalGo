package server

import "net/http"

/*
**ترويساتُ الأمان — طبقةٌ ثانيةٌ حين تسقط الأولى.**

(كشفه فحصُ المشروع ٢٠٢٦-٠٨-٠٧، وأُصلح بقرار المالك: «أكمل».)

كان المشروعُ بصفرِ ترويساتِ أمان.

# لماذا تُهمّ هنا بعينه

**رمزُ الجلسة في `localStorage`** — فأيُّ ثغرةِ نصٍّ في الواجهة تسرقه، ولا
تنتهي الجلسةُ بإغلاق التبويب.

**ولم أجد في المشروع كلِّه `dangerouslySetInnerHTML` ولا `eval`** — فالخطرُ
اليومَ نظريّ. **والترويساتُ هي ما يبقى حين يُكتب سطرٌ جديدٌ غداً** ولا يمرّ
على من يعرف.

# ولماذا هذه الأربع

  - `nosniff`     — **الوسائطُ عندنا يرفعها الناس.** والمتصفّحُ الذي يخمّن
    نوعَ الملفّ ينفّذ HTML مدسوساً في صورة.
  - `DENY`        — لا تُوضع لوحةُ الإدارة في إطارٍ داخل موقعٍ آخر: يُعرض
    زرٌّ شفّافٌ فوق زرِّ الحذف فيضغطه صاحبُه وهو يظنّ غيرَه.
  - `no-referrer` — مسارٌ فيه رقمُ طلبٍ أو معرّفُ حسابٍ لا يُسرَّب إلى موقعٍ
    خارجيٍّ في `Referer`.
  - `Permissions` — لا كاميرا ولا ميكروفون. **والموقعُ يحتاج الموضعَ وحدَه.**

# ولا CSP هنا

**سياسةُ محتوىً ضيّقةٌ تكسر Next** (نصوصٌ ومسارُ تطويرٍ داخليّان)، **وواسعةٌ
لا تمنع شيئاً فتُقرأ حمايةً وهي ليست بها.** موضعُها الوسيطُ العكسيُّ عند
النشر، حيث تُكتب مرّةً لِما يُخدَم فعلاً.

# ولا HSTS

**تُضاف عند النشر خلف TLS.** وترويسةٌ تفرض HTTPS على `localhost` تكسر
التطويرَ كلَّه ولا تحمي شيئاً — **وما يُكسَر في التطوير يُطفَأ في الإنتاج.**
*/
func securityHeaders(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		h := w.Header()
		h.Set("X-Content-Type-Options", "nosniff")
		h.Set("X-Frame-Options", "DENY")
		h.Set("Referrer-Policy", "no-referrer")
		h.Set("Permissions-Policy", "camera=(), microphone=(), payment=()")
		next.ServeHTTP(w, r)
	})
}
