package server

// **عنوانُ العميل بلا منفذ.**
//
// (كشفه قياسٌ حيٌّ ٢٠٢٦-٠٨-٠٧: أُرسل أربعةٌ وثلاثون رمزاً من مضيفٍ واحدٍ
//  والحدُّ ثلاثون — **ولم يُمنع أحدُها.**)
//
// # المرض
//
// `clientIP` كان يردّ `r.RemoteAddr` كما هو: **`127.0.0.1:54321`** — والمنفذُ
// عابرٌ يتبدّل مع كلّ اتّصال. **فمفتاحُ الحدّ يتبدّل معه**، ولا يتراكم عدٌّ
// أبداً.
//
// **ولا يخصّ الرموزَ وحدَها**: `loginMaxPerIP` مبنيٌّ على الدالّة نفسِها —
// **فحدُّ محاولات الدخول للعنوان كان مكسوراً منذ كُتب.**
//
// **ولم يره اختبارُ وحدةٍ قطّ**: الاختباراتُ تمرّر عنواناً نظيفاً نصّاً،
// فتُصدّق ما لا يقع في الحياة. **وحدَه النداءُ الحيُّ كشفه.**
//
// # ولماذا لم يظهر في الإنتاج
//
// `middleware.RealIP` يعيد كتابة `RemoteAddr` من `X-Forwarded-For` **حين
// تكون الترويسةُ موجودة** — أي خلف وسيطٍ عكسيّ. **فالحدُّ يعمل خلف الوسيط
// ويسقط في النداء المباشر**، وهو ما لا يُلاحَظ حتّى يُنادى مباشرةً.

import (
	"net/http"
	"net/http/httptest"
	"testing"
)

func TestClientIPHasNoPort(t *testing.T) {
	cases := []struct{ remote, want string }{
		{"127.0.0.1:54321", "127.0.0.1"},
		{"203.0.113.9:1", "203.0.113.9"},
		// **وIPv6 بين قوسين** — وقسمةٌ ساذجةٌ على النقطتين تمزّقه.
		{"[2001:db8::1]:44300", "2001:db8::1"},
		// **وما لا منفذَ له يبقى كما هو** — `RealIP` تكتبه هكذا خلف الوسيط.
		{"198.51.100.7", "198.51.100.7"},
		{"", ""},
	}
	for _, c := range cases {
		r := httptest.NewRequest(http.MethodGet, "/", nil)
		r.RemoteAddr = c.remote
		if got := clientIP(r); got != c.want {
			t.Fatalf("clientIP(%q) = %q — والمنتظَر %q.\n"+
				"**والمنفذُ عابرٌ**: مفتاحُ الحدّ يتبدّل مع كلّ اتّصالٍ فلا يتراكم عدّ.",
				c.remote, got, c.want)
		}
	}
}
