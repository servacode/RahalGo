package server

// **بابُ رفع الصورة عند المندوب ليس تحت حارس القائمة.**
//
// (قِيس على الجهاز ٢٠٢٦-٠٨-١٨: المندوبُ يفتح صنفاً ويختار صورةً
//  **فتردّ الشاشةُ «هذا الحسابُ ليس حساب سائق»** — وهي ترجمةُ ٤٠٣.)
//
// # ولماذا وقع
//
// **`repMenuGuard` يقرأ معرّفاً من المسار** — `id` أو `itemID` أو
// `sectionID` — **و`/rep/media` لا معرّفَ فيه.** فيقع في «الافتراضُ
// منعٌ لا سماح» **فيُردّ كلُّ رفع.**
//
// # ولماذا يُقرأ المصدرُ ولا يُنادى الموجّه
//
// **جُرّب أوّلاً بنداءٍ حقيقيٍّ على `Router()`** — فردّ ٥٠٠ لا ٤٠٣:
// **جهازُ الاختبار المشترك يبني خادماً ناقصَ التبعيات**، فينهار وسيطٌ
// قبل أن يُبلَغ الحارسُ أصلاً.
//
// **واختبارٌ يردّ ٥٠٠ حيث يُنتظر ٤٠٣ لا يقيس شيئاً** — يمرّ والعطبُ
// قائم. **وأخضرُ لا يقيس أسوأُ من لا اختبار**: يُطمئن ولا يحرس.
//
// **والعطبُ في موضع تسجيل الباب لا في جسمه** — **فيُقرأ الموضعُ نفسُه.**
// (وهذا ما يفعله `TestTruthDocIsCurrent` مع الوثيقة.)

import (
	"os"
	"strings"
	"testing"
)

func TestRepMediaRoute_NotBehindMenuGuard(t *testing.T) {
	src, err := os.ReadFile("server.go")
	if err != nil {
		t.Fatalf("تعذّرت قراءةُ الموجّه: %v", err)
	}
	text := string(src)

	const marker = "r.Use(s.repMenuGuard)"
	at := strings.Index(text, marker)
	if at < 0 {
		t.Fatal("لم يُعثر على حارس قائمة المندوب — **تبدّل اسمُه فبطل هذا الحارس**")
	}

	// ══════════════════════════════════════════════════════════════════
	// **وتُقرأ مجموعةُ الحارس إلى قوسها المغلق**
	// ══════════════════════════════════════════════════════════════════
	//
	// **تُعدّ الأقواسُ من أوّل `{` قبل الحارس** — وهو قوسُ `r.Group`،
	// **فما بينه وبين مقابله هو ما يحرسه.**
	open := strings.LastIndex(text[:at], "{")
	if open < 0 {
		t.Fatal("لا قوسَ يفتح مجموعةَ الحارس")
	}
	depth, end := 0, -1
	for i := open; i < len(text); i++ {
		switch text[i] {
		case '{':
			depth++
		case '}':
			depth--
			if depth == 0 {
				end = i
			}
		}
		if end >= 0 {
			break
		}
	}
	if end < 0 {
		t.Fatal("مجموعةُ الحارس بلا قوسٍ يُغلقها")
	}

	guarded := text[open:end]
	if strings.Contains(guarded, `"/media"`) {
		t.Fatal(
			"رفعُ الصورة مسجَّلٌ داخل `repMenuGuard` — **والحارسُ يطلب معرّفاً " +
				"في المسار ولا معرّفَ في هذا الباب**، فيردّ ٤٠٣ كلَّ مرّة " +
				"فلا يرفع المندوبُ صورةَ صنفٍ أبدا.",
		)
	}

	// **ولا يكفي ألّا يكون داخلَه — يجب أن يكون مسجَّلاً أصلا.**
	//
	// **ونقلُه خارجاً بحذفه يُرضي الشرطَ الأوّل ويكسر الرفعَ كلَّه** —
	// فيُسأل عن وجوده في شجرة المندوب.
	repAt := strings.Index(text, `r.Route("/rep"`)
	if repAt < 0 || !strings.Contains(text[repAt:repAt+6000], `r.Post("/media", s.handleUploadMedia)`) {
		t.Fatal("لا بابَ لرفع الصورة عند المندوب — **فلا صورةَ لصنفٍ يبنيه**")
	}
}
