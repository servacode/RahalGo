package server

// **كلُّ بابٍ يُنشئ طلباً محروسٌ من الإعادة.**
//
// (تدقيقُ الإطلاق ٢٠٢٦-٠٨-١٩ — BUG-002.)
//
// # ما وُجد
//
// **`/orders` ملفوفةٌ منذ بُنيت و`/orders/custom` لا** — وبابان لفعلٍ
// واحدٍ أحدُهما محروسٌ والآخرُ مكشوف. **وهي عائلةُ الخلل التي تكرّرت
// في هذا المستودع**: قاعدةٌ تُطبَّق في موضعٍ وتُنسى في مثله.
//
// **وضغطتان على شبكةٍ سيّئةٍ تُنشئان طلبين** — يذهب فيهما سائقان إلى
// بابٍ واحد، ويُخصم مرّتان.
//
// # ولماذا يُقرأ المصدرُ ولا يُنادى الموجّه
//
// **تركيبُ خادمٍ كاملٍ هنا يحتاج قاعدةً ومحرّكاً** فينهار قبل أن
// يُبلَغ الوسيط — **واختبارٌ يردّ ٥٠٠ حيث يُنتظر حارسٌ لا يقيس شيئا.**
// (وهو الدرسُ نفسُه من `rep_media_route_test.go`.)
//
// **والعطبُ في موضع تسجيل الباب لا في جسمه** — فيُقرأ الموضعُ نفسُه.

import (
	"os"
	"regexp"
	"strings"
	"testing"
)

// createRoutes **أبوابٌ تُنشئ شيئاً يُحاسَب عليه.**
//
// **والقائمةُ صريحةٌ لا مُخمَّنة**: ليس كلُّ `POST` يحتاج حراسةً —
// **وحارسٌ يُنذر على الصواب يُطفَأ.** تُزاد كلَّما فُتح بابُ إنشاءٍ
// جديد.
var createRoutes = []string{
	`r.Post("/orders"`,
	`r.Post("/orders/custom"`,
}

func TestCreateRoutes_AreIdempotent(t *testing.T) {
	raw, err := os.ReadFile("server.go")
	if err != nil {
		t.Fatalf("تعذّرت قراءةُ الموجّه: %v", err)
	}
	src := string(raw)

	for _, route := range createRoutes {
		at := strings.Index(src, route)
		if at < 0 {
			t.Errorf("لم يُوجد البابُ %s — تغيّر مسارُه فأصلحْ الحارس", route)
			continue
		}
		// **ويُقرأ السطرُ نفسُه** — الوسيطُ يلفّ المعالجَ في موضع التسجيل.
		end := strings.IndexByte(src[at:], '\n')
		if end < 0 {
			end = len(src) - at
		}
		line := src[at : at+end]
		if !strings.Contains(line, "s.idempotent(") {
			t.Errorf("%s بلا حمايةٍ من الإعادة — **ضغطتان على شبكةٍ سيّئةٍ "+
				"تُنشئان طلبين**\n    السطر: %s", route, strings.TrimSpace(line))
		}
	}
}

// TestIdempotencySkipsWithoutKey **وحمايةٌ لا يُرسَل مفتاحُها لا تحرس.**
//
// **وهذا نصفُ العطب الثاني** (BUG-001): الخادمُ يلفّ البابَ،
// **والتطبيقُ لا يرسل `Idempotency-Key`** — فيمرّ النداءُ بلا حراسة.
//
// **ويُوثَّق هنا صراحةً** لأنّ قراءةَ `server.go` وحدَها تُوهم أنّ
// البابَ محميّ: **الحمايةُ عقدٌ بين طرفين**، ونصفُه في التطبيق.
func TestIdempotencySkipsWithoutKey(t *testing.T) {
	raw, err := os.ReadFile("idempotency.go")
	if err != nil {
		t.Fatalf("تعذّرت القراءة: %v", err)
	}
	// **والشرطُ مقصودٌ ولا يُغيَّر**: بابٌ يرفض بلا مفتاحٍ يكسر كلَّ
	// عميلٍ قديم. **إنّما يُوثَّق أنّ العبءَ على المنادي.**
	if !regexp.MustCompile(`if key == "" \|\| uid == "" \{`).Match(raw) {
		t.Error("تغيّر شرطُ التخطّي — راجعْ أثرَه على العملاء")
	}
}
