package server

// **مصدرُ البضاعة محجوبٌ عن الزبون.**
//
// # لماذا
//
// في مدينةٍ يعرف أهلُها بعضهم، **زبونٌ رأى اسمَ المطعم يتّصل به مباشرةً في
// المرّة القادمة** — فيوفّر رسمَ التوصيل، والمطعمُ يوفّر عمولتنا. **وكلُّ
// منصةِ توصيلٍ تموت من هذا الباب**، لا من عطبٍ تقنيّ.
//
// # والحجبُ كان في التصفّح وحدَه
//
// `TestBrowse_HidesSource` يحرس `/public` منذ المرحلة الثانية. **وطلباتُ
// الزبون لم تُحرَس قطّ**: `/my/orders` و`/my/orders/{id}` تعيدان `orders.Order`
// كاملاً — وفيه `merchant_name` و`merchant_id`. **فما حُجب عند التصفّح ظهر عند
// الطلب**، وهو الموضعُ الذي يفتحه الزبونُ أكثر.
//
// **وشهده المالكُ على شاشته** (٢٠٢٦-٠٨-٠٣): «مازال اسم المتجر يظهر للزبون».
//
// # والمعرّفُ كالاسم، والشعارُ كالاثنين
//
// `merchant_id` وحدَه يُفتح به `/public/merchants/{id}` فيُقرأ الاسمُ كاملاً.
// **وشعارٌ لمطعمٍ يعرفه أهلُ الحيّ يُغني عن الاسم** — الصورةُ تُعرف قبل أن
// تُقرأ الكلمة.
//
// # والمسحُ لا الاختيار
//
// لو بُني كائنٌ جديدٌ بالحقول المسموحة **لنُسي حقلٌ جديدٌ يُضاف غداً فيُسرَّب
// صامتاً.** والمسحُ يُبقي الإضافةَ ظاهرةً حتى يُنظر فيها.

import "github.com/servacode/rahalgo/backend/internal/orders"

// redactForCustomer يمسح ما يدلّ على مصدر البضاعة.
//
// **وما عداه يبقى**: الأصنافُ وأسعارُها وحالةُ الطلب والسائقُ واسمُه ورقمُه —
// **فالسائقُ يقرع بابَه، والزبونُ يحتاج أن يعرف من يفتح له.**
func redactForCustomer(o *orders.Order) {
	o.MerchantID = ""
	o.MerchantName = ""
	o.MerchantLogoThumb = nil
	// **واسمُ من عُرض عليه الطلبُ ولم يقبل** — شأنُ توزيعٍ داخليّ، **والزبونُ
	// يعرف سائقَه حين يصير سائقَه لا قبله.**
	o.OfferedDriverName = nil
}

// redactAllForCustomer لقائمة الطلبات.
func redactAllForCustomer(list []orders.Order) {
	for i := range list {
		redactForCustomer(&list[i])
	}
}
