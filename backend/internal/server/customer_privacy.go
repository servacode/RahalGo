package server

// **مصدرُ البضاعة محجوبٌ عن الزبون — في الطلبات وحدَها اليوم.**
//
// # والعكسُ — **قرارُ المالك ٢٠٢٦-١٠-١٥**
//
// **ما يلي سببُ الحجب الأوّل، ويبقى للتاريخ.** والمالكُ عكسه صراحةً في
// **التصفّح والعروض**: كلُّ صنفٍ يحمل اسمَ متجره ومعرّفَه
// (`TestBrowse_ShowsStoreName`)، **والعروضُ لا يُمسح منها الاسم.** **وطلباتُ
// الزبون باقيةٌ على حكم عقد `P-1`** — لم يشملها القرار.
//
// # لماذا
//
// في مدينةٍ يعرف أهلُها بعضهم، **زبونٌ رأى اسمَ المطعم يتّصل به مباشرةً في
// المرّة القادمة** — فيوفّر رسمَ التوصيل، والمطعمُ يوفّر عمولتنا. **وكلُّ
// منصةِ توصيلٍ تموت من هذا الباب**، لا من عطبٍ تقنيّ.
//
// # والحجبُ كان في التصفّح وحدَه
//
// `TestBrowse_HidesSource` كان يحرس `/public` منذ المرحلة الثانية. **وطلباتُ
// الزبون لم تُحرَس قطّ**: `/my/orders` و`/my/orders/{id}` تعيدان `orders.Order`
// كاملاً — وفيه `merchant_name` و`merchant_id`. **فما حُجب عند التصفّح ظهر عند
// الطلب**، وهو الموضعُ الذي يفتحه الزبونُ أكثر.
//
// **وشهده المالكُ على شاشته** (٢٠٢٦-٠٨-٠٣): «مازال اسم المتجر يظهر للزبون».
//
// # والمعرّفُ كالاسم، والشعارُ كالاثنين
//
// `merchant_id` وحدَه يُفتح به `/public/merchants/{id}` فيُقرأ الاسمُ كاملاً.
// **وشعارٌ لمطعمٍ يعرفه أهلُ الحيّ يُغني عن الاسم** — الصورةُ تُعرف قبل أن
// تُقرأ الكلمة.
//
// # والمسحُ لا الاختيار
//
// لو بُني كائنٌ جديدٌ بالحقول المسموحة **لنُسي حقلٌ جديدٌ يُضاف غداً فيُسرَّب
// صامتاً.** والمسحُ يُبقي الإضافةَ ظاهرةً حتى يُنظر فيها.

import (
	"github.com/servacode/rahalgo/backend/internal/offers"
)

// ══════════════════════════════════════════════════════════════════════
// **والتنفيذُ انتقل** — دورةُ ٤٦
// ══════════════════════════════════════════════════════════════════════
//
// **كانت هنا `redactForCustomer` تمحو أربعةَ حقولٍ ويخرج الباقي** —
// **وقيس عليها ١٦ خرقاً في تفصيل الزبون و١٤ في قائمته** (دورةُ ٤٥).
//
// **فصار الحكمُ واحداً للقنوات كلِّها**: `orders.ViewFor` مولَّدةٌ من
// عقد `P-1`، **تُبنى بالسماح** — انظر `order_view.go`.
//
// **وبقي هذا الملفُّ لأنّ فيه سببَ الحكم لا تنفيذَه**: **ولولا السببُ
// لعاد أوّلُ من رأى الحقلَ ناقصاً فأضافه.**
//
// **والعروضُ نوعٌ آخرُ لا طلب** (`offers.Offer`) — **ولها تنقيتُها
// حتّى يُبنى لها عقدُها.**

// redactOffersForCustomer يمسح من العروض **ما يخصّ الإدارة وحدَها.**
//
// # واسمُ المتجر لم يعد يُمسح — **قرارُ المالك ٢٠٢٦-١٠-١٥**
//
// **كانت ثالثةَ أبواب الحجب** بعد التصفّح والطلبات، تمسح `merchant_name`
// و`merchant_id`. **وعكس المالكُ القرارَ صراحةً للتصفّح والعروض**: الزبونُ
// يرى اسمَ المتجر على الصنف في الشبكة وتحت اسم الصنف في العروض. **فصار
// الاسمُ والمعرّفُ يخرجان كما في التصفّح** — بابان بحكمٍ واحد.
//
// **وطلباتُ الزبون لم يشملها العكس** — حكمُها في عقد `P-1` (`orders.ViewFor`)
// ولم يُمسّ.
func redactOffersForCustomer(rows []offers.Offer) {
	for i := range rows {
		// **ومن عمل العرضَ وحالُ موافقته شأنُ الإدارة** (٢٠٢٦-١٠-٠٤).
		rows[i].CreatedByName = ""
		rows[i].CreatedByKind = ""
		rows[i].ApprovalState = ""
	}
}
