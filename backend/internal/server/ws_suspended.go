package server

// ما يصل الحسابَ المعلَّق في البثّ — **`D14`.**
//
// # لماذا لم تكفِ الغرفة
//
// **دورةُ ٥٣ حصرت المعلَّقَ في غرفته** — **ومنعت طابورَ العمل
// الجديد.** **وظُنّ أنّ غرفةَ السائق عملُه القائمُ وحدَه.**
//
// **وليست كذلك**: **`rotation.go` تبثّ العرضَ في غرفة السائق نفسِها**
// — **«عُرض عليك طلبٌ» تصل `driver:<id>` كما تصل `drivers:queue`.**
// **فالمعلَّقُ يُمنَع من الطابور ويُنادى من بابه الخاصّ.**
//
// # فالحكمُ على الحمولة لا على اسم الغرفة
//
// **وحمولةُ الطلب تحمل صاحبَه** (`driver_id` في مرشَّح السائق) —
// **فتُقرأ منها**: **ما يحمله السائقُ الآنَ يصله**، **وما عُرض عليه
// ولم يقبله لا يصله.**
//
// # ولا استعلامَ لكلّ إطار
//
// **والسلطةُ في الحمولة نفسِها** — **وهي مكتوبةٌ من الطلب المثبَّت**:
// **فلا نداءَ قاعدةٍ لكلّ حدث**، **ولا ذاكرةٌ تشيخ فتمنح عملاً
// جديداً.**
//
// # والإشارةُ الصمّاءُ تُمنَع
//
// **وبثُّ العرض `{"type":"order"}` بلا حمولة** — **إشارةُ «أعِد
// الجلب» لا تقول عن أيّ طلب.** **ومن لا يستطيع أن يُثبت أنّها عن
// طلبٍ يحمله لا تصله**: **المنعُ هو الأصلُ عند الجهل.**
//
// # وحسابُه يصله
//
// **`user:<id>` إشعاراتُه ومحفظتُه** — **وليست عملاً جديداً**:
// **مالُه ورسائلُه شأنُه**، **ومنعُها عقوبةٌ على مالٍ لا على فعل.**

import "encoding/json"

// suspendedFilter **يقرّر ما يصل وصلةَ معلَّقٍ من غرفةِ عمله.**
//
// **ولا يُنادى إلّا للمعلَّق** — **والنشطُ لا يمرّ به إطلاقاً.**
type suspendedFilter struct {
	// UserID صاحبُ الوصلة.
	UserID string
}

// allow **أتصل هذه الحمولةُ صاحبَ الوصلة؟** — **لغرفة العمل وحدَها.**
//
// **والحكمُ على الحمولة**: **حمولةُ طلبٍ يحمله ⇒ تصل** · **وما سواها
// ⇒ لا تصل.**
//
// **والغرفُ الأخرى لا تمرّ بهذا الحارس أصلاً** — **تُشترَك على حدة**
// (`user:` إشعاراتُه ومحفظتُه).
func (f suspendedFilter) allow(payload []byte) bool {
	// **وما لا يُقرأ لا يُصدَّق** — **وحمولةٌ عاجزةٌ عن إثبات نفسها
	// تُمنَع.**
	var frame struct {
		Order *struct {
			DriverID *string `json:"driver_id"`
		} `json:"order"`
	}
	if err := json.Unmarshal(payload, &frame); err != nil {
		return false
	}
	if frame.Order == nil || frame.Order.DriverID == nil {
		// **إشارةُ العرض الصمّاء** — `{"type":"order"}` بلا طلب.
		return false
	}
	return *frame.Order.DriverID == f.UserID
}

// workRoomOf غرفةُ عمل هذا الدور — **وفارغٌ يعني لا غرفةَ عملٍ له.**
//
// **والسائقُ وحدَه اليومَ يُعرَض عليه عملٌ في غرفته الخاصّة**
// (`rotation.go`). **والزبونُ والمتجرُ يُبَثُّ إليهما ما يخصّ طلباً
// قائماً لا عرضَ عملٍ جديد** — **فلا يُخترَع لهما قيدٌ لا يقتضيه
// عقدُهما.**
func workRoomOf(roles []string, userID string) string {
	for _, r := range roles {
		if r == "driver" {
			return "driver:" + userID
		}
	}
	return ""
}
