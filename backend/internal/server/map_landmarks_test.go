// TestLandmarkLabel **تسميةُ المعلم عربيّةٌ وحدَها** — بأسماء الهجرة 0467 نفسِها (Overture)، وكانت
// تُرسم كما هي في `name:ar`: «مستشفى الرازّي - Alrazzi hospital» على خريطة الزبون.
func TestLandmarkLabel(t *testing.T) {
	cases := []struct{ in, want string }{
		// **المخلوطُ من الهجرة** — يبقى عربيُّه.
		{"مستشفى الرازّي - Alrazzi hospital", "مستشفى الرازّي"},
		{"نورهان Norhan Shop", "نورهان"},
		{"Vitamen فيتامين", "فيتامين"},
		{"Stirk complex / مجمع سترك", "مجمع سترك"},
		{"إيسال - Isal", "إيسال"},
		{"قطن - Coton", "قطن"},
		{"دول دول - Doll Doll", "دول دول"},
		{"أحذية وحقائب حبايبنا-Hbaebna", "أحذية وحقائب حبايبنا"},
		{"فادي Haji", "فادي"},
		{"chfمؤسسة الاسكان التعاوني", "مؤسسة الاسكان التعاوني"},
		{"مشفى البكور - Al-Bakkor hospital", "مشفى البكور"},
		{"معهد الحمادين -AL Hamadeen institute", "معهد الحمادين"},
		{"روضة براعم السلام Bra3em Alslaam Kindergarten -منبج", "روضة براعم السلام -منبج"},
		{"Tel Abyad border crossing معبر تل أبيض الحدودي الرسمية", "معبر تل أبيض الحدودي الرسمية"},
		{"PARIS Kozmetik.basmacioglu مبيع مكياجات سورية وتركية  جملة ومفرق", "مبيع مكياجات سورية وتركية جملة ومفرق"},
		{"كافتريا المدينة El Ruha Cafe Akçakale", "كافتريا المدينة"},
		// **واللاتينيُّ وحدَه بلا تسمية.**
		{"Norhan Shop", ""},
		{"amenity=place_of_worship", ""},
		{"Shop 24", ""},
		{"   ", ""},
		// **والعربيُّ الخالصُ كما هو** — بفواصله وأرقامه ومسافاته.
		{"الجيل الجديد 2", "الجيل الجديد 2"},
		{"شركة الاسطورة/جمعة الصالح", "شركة الاسطورة/جمعة الصالح"},
		{"منظمة وفاق - مركز براعم", "منظمة وفاق - مركز براعم"},
		{"عبايات ابويوسف / بالقبو/", "عبايات ابويوسف / بالقبو/"},
		{"جمعيه رفع  المستوى الصحي / مسكنة.", "جمعيه رفع  المستوى الصحي / مسكنة."},
		{"  جامع النور  ", "جامع النور"},
		// **والأقواسُ والفواصلُ التي تيتّمت.**
		{"مطعم (Pizza House)", "مطعم"},
		{"Al Buder (قطن حلو الشعيب)", "قطن حلو الشعيب"},
		{"مدرسة (الأمل) School", "مدرسة (الأمل)"},
		{"قطن - Coton - دول", "قطن - دول"},
		{"Doll | دول دول", "دول دول"},
	}
	for _, c := range cases {
		got := landmarkLabel(c.in)
		if got != c.want {
			t.Errorf("landmarkLabel(%q) = %q — يُنتظر %q", c.in, got, c.want)
		}
		for _, r := range got {
			if unicode.Is(unicode.Latin, r) {
				t.Errorf("حرفٌ لاتينيٌّ في تسمية %q: %q", c.in, got)
				break
			}
		}
	}
}
