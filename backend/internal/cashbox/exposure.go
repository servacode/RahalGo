package cashbox

// تعرُّضُ السائق النقديّ — **`D7`.**
//
// # ما كان
//
// **`OverLimit` تقارن `held >= limit`** — **و`held` لا يرتفع إلّا عند
// التحصيل** (`CollectTx` لحظةَ التسليم).
//
// **فبابان مفتوحان**:
//
//	١ **نقدُ الطلب الداخل لا يُحسَب** — فسائقٌ محتجَزُه صفرٌ يقبل
//	  طلباً نقدُه ضعفُ السقف (قيس: ٢٧٠٬٠٠٠ والسقفُ ١٠٠٬٠٠٠)
//	٢ **والمُسنَدُ الذي لم يُسلَّم لا يُرى** — **ثلاثةُ طلباتٍ بأربعين
//	  ألفاً تمرّ كلُّها والسقفُ مئة**، `held` صفرٌ في الثلاث
//
// # والسقفُ سقفُ تعرّضٍ لا سقفُ ما في الجيب
//
// **وما بيده اليومَ نصفُ المسألة**: **من حمل طلباتٍ لم يسلّمها بعدُ
// يحمل مالَها** — **والخطرُ وقع ساعةَ أُسنِدت إليه لا ساعةَ قبضها.**
//
// # ومصدرٌ واحدٌ لا صيغتان
//
// **وكانت الصيغةُ الصحيحةُ موجودةً في مرشَّح الطابور** (`rotation.go`:
// `held + cash_due <= limit`) **وفي بابِ القبول** — **وغائبةً عن
// الإسناد اليدويّ.** **وثلاثُ نسخٍ لقاعدةٍ واحدةٍ تنحرف إحداها.**
//
// **فصارت هنا وحدَها**، **ويناديها كلُّ من يضع طلباً نقديّاً في يد
// سائق.**
//
// # ولاحقاً — عهدةُ المكتب
//
// **وتعديلاتُ الإطلاق ستُدخل سلفةً يموّلها المكتب** يحملها السائقُ
// قبل أن يقبض شيئاً. **وهي بندٌ ثالثٌ في هذه الصيغة لا بنيةٌ أخرى** —
// **ولذلك سُمّيت «تعرّضاً» لا «محصَّلاً».**

import (
	"context"
	"fmt"
)

// Exposure **ما على السائق من نقدٍ اليوم** — محصَّلاً ومُسنَداً.
//
//	المحصَّلُ   ←  `driver_cash_boxes.held` — قبضه ولم يسلّمه
//	والمُسنَدُ  ←  نقدُ طلباتٍ بيده لم تُغلَق بعد
//
// **والطلبُ المغلَقُ خارجٌ من الحساب**: **سُلّم فصار محصَّلاً**
// (`CollectTx` تنقله إلى `held`)، **أو أُلغي فلا شيءَ فيه** —
// **وعدُّه في الحالين ازدواجٌ أو ظلم.**
//
// **ويُقرأ من المُنفِّذ المُمرَّر** — **فمن ناداه داخلَ معاملةٍ قرأ ما
// تراه هي.**
func (s *Service) Exposure(ctx context.Context, q Querier, driverID string) (int64, error) {
	var held, inflight int64
	err := q.QueryRow(ctx, `
		SELECT COALESCE((SELECT b.held FROM driver_cash_boxes b
		                  WHERE b.driver_id = $1::uuid), 0),
		       COALESCE((SELECT sum(o.cash_due) FROM orders o
		                  WHERE o.driver_id = $1::uuid
		                    AND o.closed_at IS NULL), 0)`,
		driverID).Scan(&held, &inflight)
	if err != nil {
		return 0, err
	}
	return held + inflight, nil
}

// GuardTx **يمنع طلباً نقديّاً يتجاوز بالسائق سقفَه** — **ذرّيّاً.**
//
// # ولماذا قفلٌ
//
// **قراءةٌ ثمّ مقارنةٌ ثمّ كتابةٌ تمرّ مرّتين**: **إسنادان متزامنان
// بستّين ألفاً والسقفُ مئة** — **كلٌّ منهما يقرأ صفراً فيجيز نفسَه**،
// فيصير التعرّضُ مئةً وعشرين. (قيس قبل الإصلاح.)
//
// **والصفُّ وحدَه لا يكفي**: **الطلبان صفّان مختلفان** — **فقفلُ
// الصفِّ يحرس الطلبَ ولا يحرس السائق.**
//
// **فالقفلُ على السائق** — **وهو أصغرُ ما يكفي**: **سائقان لا
// ينتظر أحدُهما الآخر**، **ولا يُسلسَل النظامُ كلُّه.**
//
// **ويسقط بانتهاء المعاملة** (`xact`) — **فلا يُنسى مفتوحاً.**
//
// # وما لا نقدَ فيه لا يُحبَس
//
// **طلبُ المحفظةِ لا يزيد تعرّضاً** — **ومن منعه بسقف النقد منع
// جائزاً**، **وحارسٌ يمنع الجائزَ يُطفأ في أوّل شكوى.**
//
// # وعند السقف تماماً
//
// **يُقبَل** — **وهو ما تفعله بابُ القبول ومرشَّحُ الطابور اليوم**
// (`held + cash_due <= limit`)، **ولا يُبدَّل عقدٌ قائمٌ في إصلاح
// عيب.**
// # والسقفُ يُمرَّر ولا يُقرأ هنا
//
// **وكان يُقرأ داخلَ المعاملة** (`s.Limit(ctx)`) — **وهي تقرأ من
// المَسبَح لا من المُنفِّذ المُمرَّر**: **فيطلب النداءُ اتّصالاً
// ثانياً وهو ممسكٌ بالأوّل.**
//
// **وتحت التزاحم يجفّ المَسبَح**: كلُّ نداءٍ يمسك واحداً وينتظر
// ثانياً لا يأتي — **وتوقّف `TestAccept_DriversRace` عشرَ دقائقَ
// حتّى انفجرت مهلتُه.** (وهي عائلةُ `XG-46` نفسُها.)
//
// **فيُقرأ السقفُ قبل فتح المعاملة ويُمرَّر** — **ولا اتّصالَ ثانٍ.**
func (s *Service) GuardTx(ctx context.Context, q Querier, driverID string, incoming, limit int64) error {
	if incoming <= 0 {
		return nil
	}
	// **والقفلُ باسمٍ مفصولٍ عن سواه** — **ورقمٌ يُشتقّ من نصٍّ قد
	// يصادف رقمَ قفلٍ آخرَ في المنصّة**، فيُسبَق بمجالٍ يخصّه.
	if _, err := q.Exec(ctx,
		`SELECT pg_advisory_xact_lock(hashtext('driver-cash:' || $1::text))`,
		driverID); err != nil {
		return err
	}

	current, err := s.Exposure(ctx, q, driverID)
	if err != nil {
		return err
	}
	if current+incoming > limit {
		return ErrLimitExceed
	}
	return nil
}

// ExposureNote **سطرٌ يُقرأ في سجلٍّ عند الرفض** — ولا يخرج إلى طرف.
//
// **ولا يُرسَل إلى زبونٍ ولا متجر** (`P-1`): **دَينُ السائق شأنُه
// وشأنُ المكتب.**
func ExposureNote(current, incoming, limit int64) string {
	return fmt.Sprintf("تعرّضٌ=%d + وارد=%d > سقف=%d", current, incoming, limit)
}
