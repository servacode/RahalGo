// ══════════════════════════════════════════════════════════════════════
// **٤٠٤ موتُ رمز — و٤٠٣ بابٌ مغلقٌ في المشروع**
// ══════════════════════════════════════════════════════════════════════
//
// (قِيس ٢٠٢٦-٠٨-١٤ على جهازٍ حقيقيّ: **جهازٌ واحدٌ مسجَّل، وصفرٌ قُبل** —
//
//	ولا رنّةَ ولا اهتزازَ ولا إشعار.)
//
// # لماذا يُحرَس
//
// **كانت الحالتان سواءً** — كلتاهما «رمزٌ ميّت» فيُحذف. **والفرقُ بينهما
// كلُّ شيء:**
//
//	٤٠٤  الرمزُ لا يعرفه المشروع   ← جهازٌ حُذف منه التطبيق · يُحذف بحقّ
//	٤٠٣  واجهةٌ لم تُفعَّل أو حسابُ خدمةٍ بلا صلاحيّة · **يُصلَح لا يُحذف**
//
// **وحذفُ الرمز على ٤٠٣ يُخفي العطبَ ويضاعفه**: يُمحى رمزُ كلّ سائقٍ في
// المنصّة واحداً بعد واحد — **ثمّ لا يبقى ما يُرسَل إليه**، فيبدو أنّ لا
// أجهزةَ أصلاً **والسببُ سطرٌ في إعدادات غوغل.**
//
// **وهو عطبٌ يشفي نفسَه ظاهريّاً**: كلُّ تسجيلٍ جديدٍ يُحذف بعد أوّل
// إرسال، **فلا يبقى أثرٌ يُقرأ.**

func TestForbiddenIsNotADeadToken(t *testing.T) {
	src, err := os.ReadFile("fcm.go")
	if err != nil {
		t.Fatalf("تعذّرت القراءة: %v", err)
	}
	s := string(src)

	// **كتلةُ القرار** — من أوّل `switch` على الحال إلى آخرها.
	i := strings.Index(s, "case res.StatusCode < 300:")
	j := strings.Index(s[i:], "\n\t}")
	if i < 0 || j < 0 {
		t.Fatal("لم أجد كتلةَ قراءة الحال — تبدّل شكلُها والحارسُ صار أعمى")
	}
	block := s[i : i+j]

	// **الموتُ لـ٤٠٤ وحدَها** (ومعها ٤٠٠ برمزٍ مشوَّه).
	death := regexp.MustCompile(`case res\.StatusCode == http\.StatusNotFound[^:]*:`)
	if !death.MatchString(block) {
		t.Error("٤٠٤ لم تعد تعني موتَ رمز — فيبقى رمزٌ ميّتٌ يُنادى عليه إلى الأبد")
	}
	// **و٤٠٣ لا تُعدّ موتاً.**
	if regexp.MustCompile(`StatusNotFound \|\| .*StatusForbidden`).MatchString(block) ||
		regexp.MustCompile(`StatusForbidden.*\n\s*return true`).MatchString(block) {
		t.Error("٤٠٣ تُعدّ موتَ رمزٍ — فيُمحى رمزُ كلّ سائقٍ والسببُ إعدادُ مشروع")
	}
}

// TestDiagnoseTellsWhenNoneAccepted **و«صفرٌ قُبل» لا تُقرأ نجاحا.**
//
// **وجوابٌ يقول «وصلت» وهي لم تصل أسوأُ من صمت** — يُغلق البابَ على
// البحث. (وقع فعلاً: ظهرت «وصلت — أُرسلت إلى ٠ من ١».)
func TestDiagnoseTellsWhenNoneAccepted(t *testing.T) {
	src, err := os.ReadFile("diagnose.go")
	if err != nil {
		t.Fatalf("تعذّرت القراءة: %v", err)
	}
	if !strings.Contains(string(src), "len(dead) > 0 && out.Error == \"\"") {
		t.Error("رمزٌ رُفض لا يُقال — فيُقرأ الفحصُ ناجحاً وهو فاشل")
	}
}
