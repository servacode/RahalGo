package support

// **كلُّ سببِ شكوى يعرف مَن يعنيه — أو يقول صراحةً إنّه لا يعني أحداً.**
//
// (شكوى المالك ٢٠٢٦-٠٨-٠٩: «مين ضد مين وكلّ شخص ياخذ حقّه».)
//
// # المرضُ الذي يمنعه
//
// **سببٌ جديدٌ يُضاف بلا `Against`** يُقرأ «على المنصّة» بالسكوت — **فلا يُنذَر
// أحدٌ ولا يُخبَر أحد**، وتذهب الشكوى إلى العمليات وحدَها.
//
// **ولا يظهر ذلك في خطأ**: الشكوى تُفتح وتُقرأ ويُردّ عليها، **والمشتكى عليه
// لا يعلم.** وهو بعينه ما شكا منه المالك.
//
// **فيُلزَم كلُّ سببٍ بقرارٍ صريح** — إمّا اسمُ طرفٍ وإمّا ذِكرُه في قائمة
// «لا طرفَ له». **والسكوتُ ليس قراراً.**

import "testing"

// platformReasons **ما لا يُنسَب إلى شخصٍ عمداً.**
//
// **«مال» و«أخرى» شكاوى على المنصّة نفسِها** — تأخّرٌ في التوزيع أو خطأٌ في
// تسعير، ولا شخصَ فيها يُنذَر.
//
// **و«تأخّر» لا يُنسب لأحدٍ بعينه**: مطبخٌ تأخّر أو سائقٌ تأخّر أو توزيعٌ
// تأخّر، **ولا يُعرف أيُّها من شكوى الزبون** — فتذهب إلى العمليات وهي تقرأ
// الأوقاتَ وتنسب.
var platformReasons = map[string]bool{
	"money": true, "other": true, "late": true,
}

func TestEveryComplaintReasonDeclaresItsTarget(t *testing.T) {
	if len(ComplaintReasons) < 5 {
		t.Fatalf("الأسبابُ %d فقط — أحُذفت القائمة؟", len(ComplaintReasons))
	}
	for _, r := range ComplaintReasons {
		switch r.Against {
		case "driver", "merchant":
			if platformReasons[r.Code] {
				t.Errorf("%q معدودٌ على المنصّة ويحمل طرفاً %q — قراران متناقضان",
					r.Code, r.Against)
			}
		case "":
			if !platformReasons[r.Code] {
				t.Errorf("%q بلا طرفٍ ولا هو في قائمة «لا طرفَ له» — "+
					"**فيُقرأ «على المنصّة» بالسكوت**، ولا يُخبَر من هي عليه.",
					r.Code)
			}
		default:
			t.Errorf("%q يحمل طرفاً مجهولاً %q — والطرفان `driver` و`merchant` لا ثالثَ لهما",
				r.Code, r.Against)
		}
	}
}
