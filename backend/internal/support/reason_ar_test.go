package support_test

// **كلُّ سببِ شكوى له اسمٌ عربيّ.**
//
// (كشفه فحصٌ شاملٌ ٢٠٢٦-٠٨-٠٨: إشعارُ الإدارة يقول «شكوى على طلب — late».)
//
// # المرض
//
// الرمزُ لغةُ الآلة: يُخزَّن ويُقارن ويُفهرس. **واسمُه لغةُ الناس.** ومن
// قرأ الإشعارَ في لوحته قرأ كلمةً إنكليزيّةً وسطَ جملةٍ عربيّة.
//
// **ولا يُترجَم في الواجهة**: الإشعارُ يُخزَّن نصّاً في القاعدة ويُقرأ كما
// خُزّن — **فترجمتُه هناك تأتي بعد فوات الأوان.**
//
// # ولماذا حارسٌ لا انتباه
//
// **من زاد سبباً في القائمة لن يتذكّر اسمَه العربيّ** — ولا شيءَ يذكّره:
// الشيفرةُ تُبنى، والنداءُ يعمل، **والرمزُ يظهر في إشعارٍ يقرؤه إنسان.**
//
// وهو الدرسُ نفسُه من حارسِ أسماء الحالات وأفعالِ التدقيق.

import (
	"testing"

	"github.com/servacode/rahalgo/backend/internal/support"
)

func TestEveryComplaintReasonHasArabicName(t *testing.T) {
	for _, r := range support.ComplaintReasons {
		ar := support.ReasonAr(r.Code)
		if ar == r.Code {
			t.Errorf("السببُ %q بلا اسمٍ عربيّ — **يُعرض خامّاً في الإشعار**", r.Code)
			continue
		}
		for _, ch := range ar {
			if (ch >= 'a' && ch <= 'z') || (ch >= 'A' && ch <= 'Z') {
				t.Errorf("اسمُ %q يحوي حرفاً لاتينيّاً: %q", r.Code, ar)
				break
			}
		}
	}
}
