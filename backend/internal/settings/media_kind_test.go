package settings

// **نوعُ الصورة يُفحص لا يُقبل نصّاً حرّاً.**
//
// # لماذا وُجد
//
// `Validate` تنتهي بـ«نوعٌ غير معروف» لكلّ نوعٍ لم يُذكر في `switch`. **فنوعٌ
// يُضاف إلى الكتالوج ولا تُضاف حالتُه هنا يُرفض حفظُه أبداً** — واللوحةُ تعرض
// الحقلَ ويكتب فيه المالكُ ولا يُحفظ شيء، **ولا خطأَ يفسّر السبب.**
//
// **ومعرّفُ الوسيط يُفحص أنّه معرّف**: بلاه يُكتب في الإعداد أيُّ نصّ، **ولا
// يظهر الخطأُ إلّا في شريطٍ علويٍّ برابطٍ مكسور** — بعد النشر.

import "testing"

func TestMediaSetting_AcceptsIDAndEmptyOnly(t *testing.T) {
	const key = "platform.logo"

	// **والفراغُ مقبولٌ عمداً** — هو ما يعني «لا شعارَ، أبقِ الحرف».
	if got, err := Validate(key, ""); err != nil || got != "" {
		t.Fatalf("الفراغُ رُفض: %v (%v) — **ومنصّةٌ بلا شعارٍ يجب أن تعمل**", got, err)
	}

	const id = "3f2b1c4d-5e6f-4a7b-8c9d-0e1f2a3b4c5d"
	if got, err := Validate(key, id); err != nil || got != id {
		t.Fatalf("المعرّفُ الصالحُ رُفض: %v (%v)", got, err)
	}

	// **ونصٌّ حرٌّ يُرفض** — وهو ما كان يمرّ لولا الفحص.
	for _, bad := range []string{"logo.png", "/media/2026/08/x.png", "نعم"} {
		if _, err := Validate(key, bad); err == nil {
			t.Errorf("قُبل %q معرّفَ صورةٍ — **ورابطٌ مكسورٌ في الشريط العلويّ**", bad)
		}
	}

	// **ورقمٌ ليس معرّفاً** — الحقلُ يأتي من JSON فقد يصل رقماً.
	if _, err := Validate(key, 42); err == nil {
		t.Error("قُبل رقمٌ معرّفَ صورة")
	}
}
