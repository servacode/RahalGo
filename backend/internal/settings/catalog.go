// byKey فهرسٌ يُبنى مرّة — البحث الخطّي في كل كتابة إعداد ترفٌ لا داعي له.
var byKey = func() map[string]Def {
	return indexCatalog()
}()

// indexCatalog يبني فهرسَ البحث من `Catalog`.
//
// **ويُنادى عند التحميل وحين يُبدَّل الفهرس** — والاختباراتُ تُبدّله لتفحص
// آلةَ التحقّق بمفاتيحها هي. **وخريطةٌ تُبنى مرّةً ولا تُعاد تجعل التبديلَ
// بلا أثر**، فتُقرأ نتيجةُ الاختبار من فهرسٍ لم يعد قائماً.
func indexCatalog() map[string]Def {
	m := make(map[string]Def, len(Catalog))
	for _, d := range Catalog {
		m[d.Key] = d
	}
	return m
}

// ReindexCatalog يُعيد بناءَ الفهرس بعد تبديل `Catalog` — **للاختبارات.**
func ReindexCatalog() { byKey = indexCatalog() }

// Lookup تعريف المفتاح، أو false إن كان مجهولاً.
func Lookup(key string) (Def, bool) {
	d, ok := byKey[key]
	return d, ok
}

// ErrUnknownKey مفتاحٌ ليس في الكتالوج — يُرفض ولا يُنشأ.
type ErrUnknownKey struct{ Key string }

func (e ErrUnknownKey) Error() string { return "settings: مفتاح مجهول: " + e.Key }

// ErrInvalidValue قيمةٌ لا تطابق تعريف مفتاحها.
type ErrInvalidValue struct {
	Key    string
	Reason string
}

func (e ErrInvalidValue) Error() string {
	return fmt.Sprintf("settings: قيمة غير صالحة لـ%s: %s", e.Key, e.Reason)
}

// Validate يتحقق أن القيمة تطابق تعريف المفتاح، ويعيدها **مطبَّعة**.
//
// والتطبيع مقصود: JSON لا يفرّق بين ٧٠ و٧٠٫٠، والقاعدة تقرأ `::float8` فتقبل
// الاثنين — لكنّ اللوحة تعرض `70.0` فيظنّ القارئ أن ثمّة كسراً. فيُعاد الصحيح
// صحيحاً.
func Validate(key string, v any) (any, error) {
	d, ok := Lookup(key)
	if !ok {
		return nil, ErrUnknownKey{Key: key}
	}
	switch d.Kind {
	case KindInt, KindMoney:
		n, ok := toNumber(v)
		if !ok {
			return nil, ErrInvalidValue{Key: key, Reason: "ليست رقماً"}
		}
		if n != float64(int64(n)) {
			return nil, ErrInvalidValue{Key: key, Reason: "ليست عدداً صحيحاً"}
		}
		if n < d.Min || n > d.Max {
			return nil, ErrInvalidValue{Key: key,
				Reason: fmt.Sprintf("خارج المدى [%v..%v]", d.Min, d.Max)}
		}
		return int64(n), nil

	case KindBool:
		b, ok := v.(bool)
		if !ok {
			return nil, ErrInvalidValue{Key: key, Reason: "ليست نعم/لا"}
		}
		return b, nil

	case KindChoice:
		s, ok := v.(string)
		if !ok {
			return nil, ErrInvalidValue{Key: key, Reason: "ليست نصاً"}
		}
		for _, o := range d.Options {
			if o == s {
				return s, nil
			}
		}
		return nil, ErrInvalidValue{Key: key, Reason: "ليست من الخيارات المتاحة"}

	case KindText:
		s, ok := v.(string)
		if !ok {
			return nil, ErrInvalidValue{Key: key, Reason: "ليست نصاً"}
		}
		// الطول بالمحارف لا بالبايتات: الحرف العربي بايتان، فقياسُه بالبايت
		// يقصّ نصّاً عربياً عند نصف ما يقصّ عنده نصّاً لاتينياً.
		if d.Max > 0 && float64(len([]rune(s))) > d.Max {
			return nil, ErrInvalidValue{Key: key,
				Reason: fmt.Sprintf("أطول من %v محرفاً", d.Max)}
		}
		return s, nil

	case KindPercent:
		// **ونوعٌ بلا فحصٍ يُرفض دائماً** — آخرُ السلسلة «نوعٌ غير معروف».
		// (وهو ما وقع عند إضافة `media`، فكُتب هذا التذكير.)
		//
		// **والمدى ٠..١٠٠ ضمناً** — لا يُكتب في كلّ مفتاح.
		n, ok := toNumber(v)
		if !ok {
			return nil, ErrInvalidValue{Key: key, Reason: "ليست رقماً"}
		}
		if n != float64(int64(n)) {
			return nil, ErrInvalidValue{Key: key, Reason: "ليست عدداً صحيحاً"}
		}
		if n < 0 || n > 100 {
			return nil, ErrInvalidValue{Key: key, Reason: "خارج المدى [0..100]"}
		}
		return int64(n), nil

	case KindLongText:
		// **ولا حدَّ محارفَ إلّا سقفاً يمنع الإغراق** — سياسةُ خصوصيّةٍ كاملةٌ
		// تبلغ آلافاً، **وحقلٌ يُرفض عند خمسمئةٍ لا يصلح لها.**
		t, ok := v.(string)
		if !ok {
			return nil, ErrInvalidValue{Key: key, Reason: "ليست نصاً"}
		}
		if len([]rune(t)) > 20000 {
			return nil, ErrInvalidValue{Key: key, Reason: "أطول من ٢٠٠٠٠ محرف"}
		}
		return t, nil

	case KindGeo:
		// **ويُفحص أنّه نقطةٌ على الأرض لا نصٌّ فيه فاصلة.**
		//
		// **والمدى يُفحص**: خطُّ عرضٍ فوق ٩٠ لا وجودَ له، **ومن كتب `90,200`
		// وقع مكتبُه خارج الكوكب** فلا تُظهره الخريطةُ ولا يُقال له لماذا.
		g, ok := v.(string)
		if !ok {
			return nil, ErrInvalidValue{Key: key, Reason: "ليست موقعاً"}
		}
		if g == "" {
			return "", nil
		}
		parts := strings.Split(g, ",")
		if len(parts) != 2 {
			return nil, ErrInvalidValue{Key: key, Reason: "الموقع يُكتب «عرض,طول»"}
		}
		lat, err1 := strconv.ParseFloat(strings.TrimSpace(parts[0]), 64)
		lng, err2 := strconv.ParseFloat(strings.TrimSpace(parts[1]), 64)
		if err1 != nil || err2 != nil {
			return nil, ErrInvalidValue{Key: key, Reason: "الموقع ليس رقمين"}
		}
		if lat < -90 || lat > 90 || lng < -180 || lng > 180 {
			return nil, ErrInvalidValue{Key: key, Reason: "الموقع خارج حدود الأرض"}
		}
		return fmt.Sprintf("%.6f,%.6f", lat, lng), nil

	case KindMedia:
		// **ومعرّفُ الوسيط يُفحص أنّه معرّفٌ لا نصٌّ حرّ.**
		//
		// **وبلا فحصٍ يُقبل أيُّ نصّ** — فيُكتب في الإعداد ما ليس صورةً،
		// **ولا يظهر الخطأُ إلّا في شريطٍ علويٍّ برابطٍ مكسور.**
		//
		// **والفراغُ مقبولٌ عمداً**: هو ما يعني «لا شعارَ — أبقِ الحرف».
		s, ok := v.(string)
		if !ok {
			return nil, ErrInvalidValue{Key: key, Reason: "ليست معرّفَ صورة"}
		}
		if s == "" {
			return "", nil
		}
		if _, err := uuid.Parse(s); err != nil {
			return nil, ErrInvalidValue{Key: key, Reason: "ليست معرّفَ صورةٍ صالحاً"}
		}
		return s, nil

	case KindFile:
		// **والاسمُ يكتبه الخادمُ عند الرفع** — ولا يُقبل هنا إلّا الإفراغ.
		// فمن أراد إزالةَ الملفّ أرسل نصّاً فارغاً، ومن أراد وضعَه رفعه.
		s, ok := v.(string)
		if !ok || s != "" {
			return nil, ErrInvalidValue{Key: key, Reason: "الملفُّ يُرفع ولا يُكتب"}
		}
		return "", nil
	}
	return nil, ErrInvalidValue{Key: key, Reason: "نوعٌ غير معروف"}
}

// toNumber يقبل ما يصل من JSON رقماً — وهو `float64` دائماً بعد فكّ الترميز.
func toNumber(v any) (float64, bool) {
	switch n := v.(type) {
	case float64:
		return n, true
	case json.Number:
		f, err := n.Float64()
		return f, err == nil
	case int:
		return float64(n), true
	case int64:
		return float64(n), true
	}
	return 0, false
}
