//
// **وما فُعل يُكتب في `docs/WORKLOG.md` خطوةً خطوة** — لا في وثيقةٍ تُراجَع
// لاحقاً. (وجردُ ما كان قبل التفريغ في `docs/archive/2026-08-04/`.)
