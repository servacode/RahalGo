// Groups **ترتيبُ الأقسام في اللوحة — ومصدرُه الواحد.**
//
// كان يُشتقّ من ترتيب `Catalog`: أوّلُ ظهورٍ للمجموعة هو موضعُها. **فقسمٌ بلا
// مفاتيحَ لا يظهر أصلاً** — ولا يُبنى قسمٌ يُملأ على مراحل، إذ لا سبيل إلى
// رؤيته قبل أن يمتلئ.
//
// **والاشتقاقُ يُخفي قراراً أيضاً**: موضعُ القسم صار أثراً جانبيّاً لترتيب
// المفاتيح — **فنقلُ مفتاحٍ ينقل قسماً معه** بلا أن يقصد أحد.
// **ولا مجموعةَ اليوم.**
//
// كان «قسم جديد» موضعَ البناء التدريجيّ، **ثمّ قرّر المالكُ ألّا يبقى شيء**
// (٢٠٢٦-٠٨-٠٤: «قسم العمولات احذفه، وقسم جديد أيضاً — فقط البوت والمناطق
// اتركها»). **ومجموعةٌ فارغةٌ تبقى تبويباً ينتظر** — وشريطٌ فيه تبويبٌ لا
// شيءَ فيه يُفتح مرّةً ويُتعلَّم تجاهلُه.
//
// **وتُكتب المجموعةُ حين يُكتب أوّلُ مفتاحٍ فيها** — لا قبله.
