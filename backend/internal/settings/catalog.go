//
// **المفتاحُ الذي ليس هنا لا يُقرأ ولا يُكتب**: `Validate` ترفض كتابتَه،
// و`GetInt` تعيد صفراً، و`GetString` فراغاً. **والقراءةُ لا تنهار** — تعيد
