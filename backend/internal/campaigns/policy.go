package campaigns

// ══════════════════════════════════════════════════════════════════════
// **سياسةُ الإزعاج — قرارٌ خالصٌ يُقاس بلا قاعدة** (`NT`، ٢٠٢٦-٠٩-١٥)
// ══════════════════════════════════════════════════════════════════════
//
// **وحارسٌ يبني صفَّ بياناتٍ بيده ويقرؤه لا يقيس قراراً** — **درسُ
// الدفعة السادسة.** **فما يُقرَّر هنا دوالُّ خالصةٌ يُمرَّر إليها
// الزمنُ والحال.**
//
// # ولا سياسةٌ ثانيةٌ في أندرويد
//
// **ومن كتب ساعةَ الهدوء في التطبيق أيضاً جعل لها حقيقتين** —
// **تُبدَّل في اللوحة وتبقى في جيوب الناس حتّى يُحدّثوا.**

import (
	"strings"
	"time"
)

// ══════════════════════════════════════════════════════════════════════
// **الصنفُ يفصل — ولا يُخلط معاملةٌ بتسويق** (البند ٢)
// ══════════════════════════════════════════════════════════════════════
const (
	// CategoryEngagement **تفاعلٌ: عرضٌ وخبرُ وصولِ خدمة.**
	//
	// **ويخضع لساعة الهدوء وللسقف** — **ويُؤجَّل ولا يضيع.**
	CategoryEngagement = "engagement"

	// CategoryTransactional **معاملةٌ: خبرُ طلبٍ ومالٍ وأمن.**
	//
	// **ولا يُؤجَّل ولا يُعدّ في سقف** — **ومن أخّر «وصل سائقُك» إلى
	// الصباح أفسد التوصيل**، **ومن أسقطها لأنّ صاحبَها طلب كثيراً
	// أفسده أكثر.**
	//
	// **ولا تُنشَأ حملةٌ بهذا الصنف** — **القيدُ في القاعدة يمنعه**:
	// **فلا يتقمّص الأدمنُ خبرَ طلب.**
	CategoryTransactional = "transactional"
)

// Engagement **أيخضع هذا الصنفُ لسياسة الإزعاج؟**
//
// **وما ليس تفاعلاً معاملةٌ** — **والافتراضُ أن يُسلَّم لا أن يُؤجَّل**:
// **ومن جهل صنفَ خبرٍ فأخّره أخّر خبرَ طلبٍ يوماً.**
func Engagement(category string) bool { return category == CategoryEngagement }

// ══════════════════════════════════════════════════════════════════════
// **ساعةُ الهدوء — بتوقيت الخدمة لا بساعة الجهاز** (البند ١١)
// ══════════════════════════════════════════════════════════════════════
//
// **ولا توقيتَ لكلّ مستخدمٍ في المنصّة** — **قِيس: لا عمودَ منطقةٍ
// زمنيّةٍ في `users`.** **واختراعُ حقلٍ فارغٍ لا يملؤه أحدٌ سياسةٌ
// كاذبة.**
//
// **فيُؤخذ توقيتُ الخدمة** — **`Asia/Damascus`**، **وهو المستعمَل في
// المنصّة أصلاً** (`incentives/target.go`): **ومنطقةٌ ثانيةٌ تفترق.**
var damascus = time.FixedZone("Asia/Damascus", 3*60*60)

// Quiet **حدّا ساعة الهدوء بالساعات المحلّيّة.**
//
// **ومن الثانية والعشرين إلى الثامنة** — **وهي مبدئيّةٌ تُضبط من
// اللوحة** (`notify.quiet_from` و`notify.quiet_to`).
type Quiet struct{ From, To int }

// DefaultQuiet **ما يُعمل به قبل أن يُضبط شيء.**
var DefaultQuiet = Quiet{From: 22, To: 8}

// InQuiet **أواقعةٌ هذه اللحظةُ في ساعة الهدوء؟**
//
// **والمدّةُ تعبر منتصفَ الليل** — **فـ٢٢→٨ ليست مجالاً تصاعديّاً**:
// **ومن قارن بـ`>=from && <to` وحدَه أسكت النهارَ كلَّه.**
//
// **وحدّان متساويان يعني لا هدوء** — **ولا يُسكَت اليومُ كلُّه بخطإِ
// ضبط.**
func (q Quiet) InQuiet(at time.Time) bool {
	if q.From == q.To {
		return false
	}
	h := at.In(damascus).Hour()
	if q.From < q.To {
		return h >= q.From && h < q.To
	}
	return h >= q.From || h < q.To
}

// NextAllowed **متى يجوز التسليمُ بعد هذه اللحظة؟**
//
// **ولا يُسقَط الخبرُ لأنّه جاء ليلاً** — **يُؤجَّل إلى الثامنة**:
// **والإسقاطُ يجعل الحملةَ تختفي بلا أثرٍ يُقرأ.**
func (q Quiet) NextAllowed(at time.Time) time.Time {
	if !q.InQuiet(at) {
		return at
	}
	local := at.In(damascus)
	next := time.Date(local.Year(), local.Month(), local.Day(), q.To, 0, 0, 0, damascus)
	if !next.After(local) {
		next = next.AddDate(0, 0, 1)
	}
	return next
}

// ══════════════════════════════════════════════════════════════════════
// **سقفُ الإزعاج — كم مرّةً في اليوم** (البند ١٢)
// ══════════════════════════════════════════════════════════════════════
//
// **وعشرةُ إشعاراتٍ من متجرٍ يرفع عشرةَ أصنافٍ تُفقد المنصّةَ صوتَها**
// — **ومن كفّ عن قراءة إشعاراتنا لا يقرأ ما يهمّه.**
//
// **والسقفُ على التفاعل وحدَه** — **ولا يُعدّ خبرُ طلبٍ فيه.**
const DefaultDailyCap = 2

// UnderCap **أله متّسعٌ اليوم؟**
//
// **والسقفُ صفراً يعني منعاً تامّاً للتفاعل** — **وهو ضبطٌ مشروعٌ
// في أيّام الأزمات.**
func UnderCap(sentToday, cap int) bool { return sentToday < cap }

// ══════════════════════════════════════════════════════════════════════
// **حالُ الحملة — محفوظةٌ لا مشتقّة**
// ══════════════════════════════════════════════════════════════════════
const (
	StatusDraft     = "draft"
	StatusScheduled = "scheduled"
	StatusSending   = "sending"
	StatusSent      = "sent"
	StatusCancelled = "cancelled"
	StatusFailed    = "failed"
)

// Cancellable **أيُلغى بعدُ؟** — **وما بدأ إرسالُه لا يُسحَب.**
//
// **ومن ألغى حملةً وصلت نصفَ الناس أعطى وعداً لا يملكه** — **والرسالةُ
// في جيوبهم.**
func Cancellable(status string) bool {
	return status == StatusDraft || status == StatusScheduled
}

// ══════════════════════════════════════════════════════════════════════
// **الوجهةُ نوعٌ ومعرّف — لا رابطٌ حرّ** (البند ٨)
// ══════════════════════════════════════════════════════════════════════
//
// **ورابطٌ حرٌّ في إشعارٍ بابُ تصيّدٍ في جيب الزبون.**
const (
	DestHome  = "home"
	DestOffer = "offer"
)

// ══════════════════════════════════════════════════════════════════════
// **و«المتجر» لم تعد وجهةً** (قرارُ المالك ٢٠٢٦-٠٩-١٥)
// ══════════════════════════════════════════════════════════════════════
//
// **ولا شاشةَ متجرٍ عند الزبون** — **قرارُه ٢٠٢٦-٠٨-٠٥**: «المتاجرُ
// مخفيّةٌ عن الزبون بالكامل»، **والمحرّكُ يحجبها في الردّ نفسِه**
// (`customer_privacy.go`). **وقِيس ٢٠٢٦-٠٩-١٥ على التجهيز**: **ثلاثةُ
// أبوابٍ عامّةٍ للمتاجر ⇒ ٤٠٤ ثلاثتُها.**
//
// **فوجهةٌ لا يملك التطبيقُ أن يفتحها ليست عقداً** — **هي وعدٌ يُرسَل
// في جيب الزبون ثمّ لا يُوفى**: **يُنقَر فيُفتَح البيتُ، فيُقرأ
// «الإشعارُ لا يعمل».**
//
// **والمنعُ في المحرّك لا في اللوحة** — **ولوحةٌ تُنقَّى وحدَها يتخطّاها
// نداءٌ مصنوعٌ بيد**، **ونسخةٌ قديمةٌ من اللوحة تبقى ترسلها.**
//
// **والصفوفُ القديمةُ تبقى تاريخاً** — **ولا يُعاد كتابةُ سجلٍّ ليُجمَّل**:
// **لكنّها لا تصير سالكةً من جديد.**

// ValidDest **أوجهةٌ نعرفها؟**
//
// **وما لا نعرفه يُردّ عند الإنشاء** — **ولا يُخزَّن ليُفتَح غداً**:
// **ومن قبله اليومَ سلّم للتطبيق ما لا يعرف كيف يفتحه.**
//
// **و`offer` يلزمه معرّف** — **و`home` لا يقبله.**
func ValidDest(destType, destID string) bool {
	switch destType {
	case "", DestHome:
		return strings.TrimSpace(destID) == ""
	case DestOffer:
		return strings.TrimSpace(destID) != ""
	default:
		return false
	}
}

// ══════════════════════════════════════════════════════════════════════
// **الجمهورُ نوعٌ ومرجع** (البند ٥)
// ══════════════════════════════════════════════════════════════════════
const (
	AudienceRole     = "role"
	AudienceInterest = "service_interest"
)

// Roles **من يجوز مخاطبتُه بالدور** — **مرآةُ `broadcastRoles` القائمة.**
var Roles = map[string]bool{
	"customer": true, "driver": true, "merchant": true, "sales": true,
}

// ValidAudience **أجمهورٌ مفهوم؟**
//
// **ومرجعُ «أخبرني» مفتاحُ هدفٍ من الدفعة الرابعة حرفاً** —
// `city:<uuid>` أو `cell:<y>,<x>`: **ولا صيغةَ ثانيةٌ لشيءٍ واحد.**
func ValidAudience(kind, ref string) bool {
	ref = strings.TrimSpace(ref)
	switch kind {
	case AudienceRole:
		return Roles[ref]
	case AudienceInterest:
		return strings.HasPrefix(ref, "city:") || strings.HasPrefix(ref, "cell:")
	default:
		return false
	}
}
