package routing

import (
	"context"
	"errors"
	"strconv"
)

// ══════════════════════════════════════════════════════════════════════
// **عقدُ محرّك المسارات — المرحلة ٨أ**
// ══════════════════════════════════════════════════════════════════════
//
// (قرارُ المالك ٢٠٢٦-٠٨-٢١ بعد قياس المرحلة ٨.)
//
// **لا اسمَ محرّكٍ في هذا العقد.** من أراد محرّكاً آخرَ يوماً كتب
// محوّلاً يحقّق `Backend` — **ولا يعلم به `driver-navigation` ولا
// أندرويد ولا `TripViewModel`.**
//
// **والقرارُ المقيس** (١٨٩ استعلاماً على سوريا، ٢٠٢٦-٠٨-٢١): يبقى
// OSRM `routability` محرّكَ الإنتاج. **وهذا العقدُ ليس تمهيداً
// لتبديله** — هو ما يجعل التبديلَ ممكناً لو قِيست حاجةٌ إليه.

// Backend **ما يُطلب من أيّ محرّك مسارات** — وسطحُه ثلاثُ دوالّ.
type Backend interface {
	// Enabled **أثمّة محرّكٌ مضبوط؟** — وفارغٌ يعني الخطَّ المستقيم.
	Enabled() bool

	// Route **مسارٌ واحدٌ موصًى به.**
	Route(ctx context.Context, from, to Point) (*Route, error)

	// RouteSet **الموصى به وبدائلُه** — بترتيب المحرّك، والأوّلُ هو
	// الموصى به. **والترشيحُ ليس هنا**: `FilterAlternatives` تقرّر.
	RouteSet(ctx context.Context, from, to Point) ([]*Route, error)
}

// **وهذا يُسقط البناءَ إن انحرف `Client` عن العقد.**
var _ Backend = (*Client)(nil)

// ══════════════════════════════════════════════════════════════════════
// **حدُّ الالتقاط — TD-SNAP-RADIUS**
// ══════════════════════════════════════════════════════════════════════
//
// **العيبُ الذي أُغلق** (قِيس ٢٠٢٦-٠٨-٢١): OSRM بلا حدٍّ افتراضيٍّ
// لنصف قطر الالتقاط. **فإحداثيّةُ باريس تلتقط على طريقٍ سوريٍّ بعد
// ٣١١١ كم ويردّ المحرّكُ مساراً بلا أيّ خطأ** — والقاهرةُ ٥٢٣ كم،
// والبحرُ المتوسّط ١٧٠ كم.
//
// **وذلك في تطبيق توصيلٍ عيبٌ صامت**: تثبيتُ GPS فاسدٌ لا يُظهر
// عطلاً — **يُظهر مساراً واثقاً خاطئاً**، فيسوق السائقَ إلى لا شيء.
//
// # ولماذا رقمان لا رقم
//
// **الأصلُ والوجهةُ ليسا من طبيعةٍ واحدة**:
//
//   - **الأصلُ موضعُ سائقٍ على الطريق** — انحرافُه خطأُ GPS، ومداه
//     عشراتُ الأمتار.
//   - **والوجهةُ متجرٌ أو زبونٌ داخلَ بناء** — يبعد عن أقرب طريقٍ
//     بعمق البناء وفناءِ الحيّ، **وهو انحرافٌ حقيقيٌّ لا خطأ.**
//
// **فحدٌّ واحدٌ يظلم أحدَهما**: ضيّقٌ يرفض متجراً حقيقيّاً، وواسعٌ
// يقبل تثبيتاً فاسداً.

// SnapPolicy **حدُّ ما يُقبل بُعده عن أقرب طريق.**
type SnapPolicy struct {
	// OriginM **الأصل** — موضعُ السائق.
	OriginM float64
	// DestinationM **الوجهة** — متجرٌ أو عنوانُ زبون.
	DestinationM float64
}

// ══════════════════════════════════════════════════════════════════════
// **الأرقامُ مُعايَرة لا مُختارة**
// ══════════════════════════════════════════════════════════════════════
//
// **قِيست على ١٨٩ أصلاً بخمسِ إزاحاتِ GPS (٠·١٠·٢٥·٥٠·٧٥م)**
// و**٩٠٠ متجرٍ حقيقيٍّ مستخرَجٍ من `syria.osm.pbf`** (تسلسل ٤٦٣٥):
//
//	الأصل   ١٥٠م → حضريّ ٩٨٫٥٪ · ريفيّ ١٠٠٪  (١٠٠م تعطي ٩٧٫١٪)
//	الوجهة  ٢٥٠م → متجرٌ حضريّ ١٠٠٪ · خارجَ المدن ٩٦٫٠٪
//	               (١٥٠م تعطي ٩٩٫٨٪ و٩٤٫٣٪)
//
// **والوجهةُ أوسع عمداً**: رفضُ وجهةٍ يعني «لا يمكن التوصيل» لزبونٍ
// حقيقيّ — **وذلك أسوأُ من مسارٍ يبدأ من زاويةِ الشارع.**
//
// # والهامشُ إلى الخطأ ضخم
//
// **أقربُ نقطةٍ خاطئةٍ قِيست تبعد ٢٣٠٣٦م** (البادية السوريّة) —
// **اثنان وتسعون ضعفَ حدِّ الوجهة.** فالحدُّ لا يمرّ منه شيءٌ من
// باريس ولا القاهرة ولا بغداد ولا أنقرة ولا البحر.
const (
	defaultOriginRadiusM      = 150.0
	defaultDestinationRadiusM = 250.0
)

// DefaultSnapPolicy **سياسةُ الخادم** — البند ٤: الهاتفُ لا يحدّدها.
func DefaultSnapPolicy() SnapPolicy {
	return SnapPolicy{OriginM: defaultOriginRadiusM, DestinationM: defaultDestinationRadiusM}
}

// radiuses **حدٌّ لكلّ إحداثيّة، مفصولاتٌ بـ`%3B`.**
//
// **وصفرٌ أو سالبٌ يعني بلا حدّ** — ولا يُستعمل في الإنتاج، **لكن
// الاختبارات تحتاج أن تقيس الفرق.**
//
// ══════════════════════════════════════════════════════════════════════
// **ولماذا `%3B` لا `;`**
// ══════════════════════════════════════════════════════════════════════
//
// **OSRM يقبل الاثنتين** — قُستا حيّاً (v26.8.0): باريس
// `NoSegment` والرقّة `Ok` في كلتا الصيغتين.
//
// **لكنّ `net/url` في Go تُسقط كلّ المعاملات إن وجدت فاصلةً
// منقوطةً خاماً في الاستعلام** — ولا تقول لماذا. **وأوّلُ من
// وقع فيها اختباري أنا**: قرأ الخادمُ المزيّف `radiuses=""`
// فظننتُ أنّ الشيفرةَ لا ترسلها.
//
// **فالترميزُ يمرّ من أيّ محلّل** — من وسيطٍ أو سجلٍّ أو
// اختبارٍ يقرأ الطلب.
func (p SnapPolicy) radiuses() string {
	return radiusValue(p.OriginM) + "%3B" + radiusValue(p.DestinationM)
}

func radiusValue(m float64) string {
	if m <= 0 {
		return "unlimited"
	}
	return strconv.FormatFloat(m, 'f', 0, 64)
}

// bounded **أيُطبَّق حدٌّ أصلاً؟**
func (p SnapPolicy) bounded() bool { return p.OriginM > 0 || p.DestinationM > 0 }

// ══════════════════════════════════════════════════════════════════════
// **والفشلُ يُسمّى — البند ٧**
// ══════════════════════════════════════════════════════════════════════
//
// **ولا إعادةَ محاولةٍ بلا حدّ**: من ردّ عليه المحرّكُ `NoSegment`
// ثمّ أعاد السؤالَ بلا نصفِ قطر **أعاد العيبَ الصامتَ بعينه.**

// ErrNoSegment **لا طريقَ ضمنَ الحدّ** — إحداثيّةٌ بعيدةٌ أو فاسدة.
var ErrNoSegment = errors.New("routing: لا طريقَ قريبةً من الإحداثيّة")

// ErrNoRoute **الطرفان على الشبكة ولا سبيلَ بينهما.**
var ErrNoRoute = errors.New("routing: لا سبيلَ بين النقطتين")
