--
-- # العقد
--
--	تغييرُ المرء لكلمته  ⇒ **تبقى جلستُه الحاليّة**، وتُقطَع البواقي
--	إعادةُ الإدارة        ⇒ تُقطَع كلُّها ولا استثناء
--
-- # ولماذا عمودٌ ثانٍ
--
-- **حِقبةُ `R13` تقتل كلَّ عائلةٍ بدأت قبلها** — **وجلسةُ من غيّر
-- كلمتَه بدأت قبلها أيضاً.** **فبلا استثناءٍ يُخرج نفسَه من الصفحة
-- التي يقف عليها**، **وهو عكسُ ما طُلب.**
--
-- **والاستثناءُ عائلةٌ واحدةٌ بعينها** — **لا «آخرُ جلسة» ولا
-- «جلساتُ هذا الجهاز»**: **العائلةُ التي نفّذت التغييرَ موثَّقةً**،
-- تُقرأ من رمز الوصول الذي حمل الطلب.
--
-- # وأقوى الإبطالين يغلب
--
-- **إعادةُ الإدارة والحظرُ والإخراجُ الشاملُ تصفّره** — **فلا يبقى
-- استثناءٌ من جولةٍ سابقةٍ يُنجي جلسةً وجب قطعُها.**
--
-- **وفارغٌ يعني لا استثناء** — وهو حالُ كلّ حسابٍ قائم.
