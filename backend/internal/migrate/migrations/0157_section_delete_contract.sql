-- ٠١٥٧ · عقدُ حذفِ القسم — **مفتاحٌ بقي على عقدٍ نُسخ قبل عام**
--
-- # عقدان لا يجتمعان
--
-- **`0057` أنشأت العمودَ يقبل الفراغَ ومفتاحُه `ON DELETE SET NULL`**،
-- **ونصُّها يقول لماذا**: «وفراغُه مشروع: صنفٌ لم يُصنَّف بعد… ولا يُعرض
-- في التصفّح، ويبقى قابلاً للطلب من صفحة متجره». **وكان ذلك صحيحاً
-- يومَه.**
--
-- **ثمّ نقلت `0084` القائمةَ إلى قسم السوق**، **وجاءت `0118` بقرار
-- المالك (٢٠٢٦-٠٨-٢٢): «إضافة الصنف القسم إلزامي، لا يجب أن يكون
-- اختياري فيضيف صنف بدون قسم»** — **فصار العمودُ `NOT NULL`.**
--
-- **وبقي المفتاحُ على عقده القديم.**
--
-- # وما كان يقع
--
-- **حذفُ قسمٍ فيه صنفٌ لا يُفرِّغ الحقلَ ولا يمنع نفسَه**: **يحاول
-- الكتابةَ فراغاً فيصطدم بـ`NOT NULL`** (`23502`) — **ورمزٌ لا يعرفه
-- `respondErr` يردّ خمسَمئة.** **فالأدمن يقرأ «عطبٌ في الخادم» عن
-- قاعدةٍ تعمل تماماً، ولا يُقال له إنّ القسمَ مشغول.**
--
-- # والعقدُ المقصود مستخرَجٌ لا مُخترَع
--
--	`SET NULL`  ⇐  **ميّت** — قرارُ ٠١١٨ يمنع صنفاً بلا قسم
--	`CASCADE`   ⇐  **مرفوضٌ نصّاً** في تعليق معالِج الحذف: «ولو حُذف
--	                معه لَضاعت أسعارٌ وخياراتٌ بُنيت على مدى شهور
--	                بضغطةٍ واحدةٍ لا تُردّ»
--	الإطفاء     ⇐  **قائمٌ يعمل** — `PATCH active=false`، وهو وحدَه ما
--	                تناديه لوحةُ الأدمن (لا زرَّ حذفٍ فيها)، **وهو ما
--	                فعلته `0156` بالأقسام الستّة المتقاعدة**
--
-- **فلم يبقَ للحذف إلّا `RESTRICT`**: **القسمُ المشغولُ يُمنع حذفُه،
-- والفارغُ يُحذف كما كان.**
--
-- # ولا بياناتٍ تتبدّل
--
-- **وهذا تبديلُ عقدٍ لا تبديلُ صفّ**: **لا `menu_items` تُمَسّ ولا
-- `platform_sections`** — **والأقسامُ الثمانيةُ والثلاثون كما تركتها
-- `0156`.**
--
-- **و`store_sections` على `CASCADE` وتبقى**: **صلةُ متجرٍ بقسم، وذهابُها
-- مع القسم صوابٌ** — **وليست بضاعةً تضيع.**

ALTER TABLE menu_items
    DROP CONSTRAINT IF EXISTS menu_items_platform_section_id_fkey;

ALTER TABLE menu_items
    ADD CONSTRAINT menu_items_platform_section_id_fkey
    FOREIGN KEY (platform_section_id) REFERENCES platform_sections(id)
    ON DELETE RESTRICT;

COMMENT ON CONSTRAINT menu_items_platform_section_id_fkey ON menu_items IS
	'قسمٌ مشغولٌ لا يُحذف — والتقاعدُ إطفاءٌ لا حذف (قرارُ ٢٠٢٦-٠٨-٢٢: القسم إلزاميّ)';
