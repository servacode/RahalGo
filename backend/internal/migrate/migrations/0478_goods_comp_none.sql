-- ══════════════════════════════════════════════════════════════════════
--
-- طابورُ «تعويض البضاعة» (`GET /admin/losses/goods-compensations`) يعرض كلَّ طلبٍ حُسمت
-- بضاعتُه «إلى المتجر» ولم يُعوَّض. **وبعضُها لا تعويضَ له أصلاً** — رجعت البضاعةُ سليمةً
-- أو اتّفق المتجرُ مع المكتب — **فيبقى في الطابور للأبد.**
--
-- فالماليّةُ تقول «ما في تعويض» مرّةً واحدة: **يُوسَم الطلبُ ويخرج من الطابور نهائياً،
-- ولا يتحرّك قرش.** ومن قالها ومتى ولماذا محفوظٌ هنا وفي سجلّ التدقيق.

