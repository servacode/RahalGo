-- **وماذا جرى — يُكتب حين يُغلق البلاغ.**
--
-- (قرارُ المالك ٢٠٢٦-٠٨-١٦ بعد فحصٍ طلبه.)
--
-- # المسألة
--
-- **الجدولُ كان يحفظ من أغلق ومتى — ولا يحفظ ماذا فعل.**
--
-- **وصفحةُ الطوارئ تسأل صراحةً**: «أوصل الطلبَ غيرُه؟ أطمأنّ السائق؟ أدُفع له
-- شيء؟» — **ولا حقلَ يحمل الجواب.**
--
-- **فبعد يومين تجد «أُغلقت بيد فلان» ولا تجد ماذا جرى** — وهو بعينه ما كُتبت
-- الشاشةُ لمنعه: «طارئٌ يُقرأ ولا يُغلق طارئٌ نُسي».
--
-- # وفارغٌ مسموح
--
-- **ولا تُفرض على القديم**: بلاغاتٌ أُغلقت قبل هذا العمود لا نصَّ لها، **وقيمةٌ
-- مخترَعةٌ تُقرأ شهادةً لم يقلها أحد.**
ALTER TABLE driver_emergencies
    ADD COLUMN IF NOT EXISTS resolution text NOT NULL DEFAULT '';

-- **والمُعالَجُ يُقرأ بالأحدث** — سؤالُه «ماذا جرى مؤخّراً؟»،
-- **والمفتوحُ بالأقدم** لأنّ سؤاله «من ينتظر منذ متى؟».
CREATE INDEX IF NOT EXISTS driver_emergencies_resolved_idx
    ON driver_emergencies (resolved_at DESC) WHERE status = 'resolved';
