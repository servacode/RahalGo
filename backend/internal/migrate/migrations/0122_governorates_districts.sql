--
-- **ويُبذَر مرّةً ثمّ يُملك من اللوحة**: `ON CONFLICT DO NOTHING` يجعل
-- إعادةَ الهجرة بلا أثر، **ولا يُعيد ما أطفأه المالكُ أو عدّل اسمَه.**
--
-- **والتقسيمُ رسميٌّ لا مخترَع** — ومن وجد فيه خطأً صحّحه من اللوحة،
-- **لا من هجرةٍ ثانية.** وهذا هو الغرضُ كلُّه.
--
