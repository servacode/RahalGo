-- ══════════════════════════════════════════════════════════════════════
-- **المحافظاتُ ومناطقُها — تقسيمُ سوريا يُبذَر مرّةً ولا يُعاد**
-- ══════════════════════════════════════════════════════════════════════
--
-- (قرارُ المالك ٢٠٢٦-٠٨-٣٠: «سنوسّع العمل لباقي محافظات سوريا ومناطقها،
--  لذلك يجب أن نجهّز المحافظات والمناطق من الآن كي لا نعود لاحقاً ونعدّل
--  الكود… وطبعاً يجب أن يكون بلوحة الأدمن خيارٌ لإضافة المحافظات
--  والمناطق وتعديلها وإيقافها وتفعيلها».)
--
-- # الحالُ الذي يُصلَح
--
-- **«المنطقة» في نموذجَي تسجيل المتجر نصٌّ حرٌّ يكتبه صاحبُه بيده** —
-- في الويب وفي تطبيق المندوب. يُخزَّن في `merchant_leads.area`،
-- **وعند الموافقة يصير عنوانَ المتجر النصّيّ**، ثمّ لا يُصنَّف ولا
-- يُبحث به ولا يُصفّى.
--
-- **وكلُّ يومٍ يمرّ يضيف صفّاً لا يُصنَّف** — وترحيلُ نصوصٍ كتبها الناسُ
-- بأهوائهم («وسط المدينة» و«وسط البلد» و«المركز») يستحيل حين تكثر.
-- **واليومَ صفٌّ واحد** (قِيس ٢٠٢٦-٠٨-٣٠).
--
-- # ولماذا جدولان لا واحد — و«منطقة» كلمتان لشيئين
--
--     المنطقةُ الإداريّة   ←  تقسيمُ الدولة، ثابتٌ لا نخترعه
--     منطقةُ التوصيل       ←  مضلَّعٌ نرسمه ونسعّره (`delivery_zones`)
--
-- **وخلطُهما يُضيع الاثنين**: تُضاف منطقةٌ إداريّةٌ فتُطالَب بأجرةِ
-- توصيل، أو تُعدَّل أجرةٌ فيتبدّل تقسيمُ الدولة.
--
-- # والمحافظةُ طبقةُ عنوانٍ لا طبقةُ تشغيل
--
-- **والهجرةُ ٠١١٦ رفضتها عمداً وهي محقّة:**
--
--     «المحافظةُ تكذب على الأرض: الطبقةُ والرقّةُ في محافظةٍ واحدةٍ
--      وبينهما خمسةٌ وخمسون كيلومترا — ولا متجرَ في الرقّة يوصّل إليها.»
--
-- **فلا تقرّر المحافظةُ من يرى ماذا** — تبقى المدينةُ تقرّرها، وتبقى
-- منطقةُ التوصيل تسعّرها. **والهرمُ:**
--
--     محافظة ← منطقة إداريّة ← مدينة ← منطقة توصيل
--     └──── عنوانٌ وتنظيمٌ وتقرير ────┘ └─── تشغيلٌ وتسعير ───┘
--
-- **فلا يُمسّ ما يعمل، وتُضاف فوقه طبقتان تُنظّمان التوسّع.**
--
-- # وطبقتان لا ثلاث
--
-- **والناحيةُ تُركت عمداً** (قرارُ المالك ٢٠٢٦-٠٨-٣٠): تفصيلٌ لا يحتاجه
-- بيعُ وجبةٍ ولا توصيلُها، **وطبقةٌ لا تُملأ تبقى فارغةً تُربك من يملأ
-- النموذج.**
--
-- # وهذه الهجرةُ لا تغيّر سلوكاً
--
-- **جدولان جديدان وعمودٌ يقبل الفراغ** — لا شاشةَ تقرؤها بعدُ ولا مسارَ
-- يشترطها. **والدفعةُ الأولى تُبذَر وتنام**، ثمّ تأتي اللوحةُ ثمّ
-- النموذجان.

-- ══════════════════════════════════════════════════════════════════════
-- **المحافظات**
-- ══════════════════════════════════════════════════════════════════════
--
-- **و`active` لا حذف**: محافظةٌ فيها متاجرُ لا تُمحى — تُطفأ فتختفي من
-- النموذج **ويبقى ما نُسب إليها مقروءاً.** (وهي قاعدةُ `cities` نفسُها.)
CREATE TABLE IF NOT EXISTS governorates (
    id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name       text NOT NULL CHECK (btrim(name) <> ''),
    active     boolean NOT NULL DEFAULT true,
    -- **والترتيبُ يدويٌّ لا أبجديّ**: المالكُ يرفع ما يعمل فيه إلى الأعلى،
    -- **ومن بحث عن محافظته في أربعَ عشرةَ مرتّبةً هجائيّاً يمرّ عليها كلِّها.**
    sort_order integer NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS governorates_name_key ON governorates (name);

-- ══════════════════════════════════════════════════════════════════════
-- **المناطقُ الإداريّة**
-- ══════════════════════════════════════════════════════════════════════
--
-- **و`RESTRICT` لا `CASCADE`**: حذفُ محافظةٍ يمحو مناطقَها ومعها انتماءُ
-- كلّ متجرٍ فيها — **صمتاً.** فيُمنع الحذفُ ما دام تحتها شيء، **ويبقى
-- الإطفاءُ هو البابَ الوحيد.**
CREATE TABLE IF NOT EXISTS districts (
    id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    governorate_id uuid NOT NULL REFERENCES governorates(id) ON DELETE RESTRICT,
    name           text NOT NULL CHECK (btrim(name) <> ''),
    active         boolean NOT NULL DEFAULT true,
    sort_order     integer NOT NULL DEFAULT 0,
    created_at     timestamptz NOT NULL DEFAULT now()
);
-- **والاسمُ فريدٌ داخلَ محافظته لا في سوريا كلِّها** — «مركز» تتكرّر في
-- كلّ محافظة، **وفريدٌ عامٌّ يمنع بذرَ الثانية.**
CREATE UNIQUE INDEX IF NOT EXISTS districts_gov_name_key
    ON districts (governorate_id, name);
CREATE INDEX IF NOT EXISTS districts_gov_idx ON districts (governorate_id);

-- ══════════════════════════════════════════════════════════════════════
-- **والمدينةُ تنتمي إلى منطقة**
-- ══════════════════════════════════════════════════════════════════════
--
-- **ويقبل الفراغ**: مدنٌ قائمةٌ لم تُنسب بعد، **ولا يُشترط في مسارٍ
-- اليوم.** والنسبةُ تُملأ من اللوحة أو في الدفعة الرابعة.
ALTER TABLE cities ADD COLUMN IF NOT EXISTS district_id uuid REFERENCES districts(id);
CREATE INDEX IF NOT EXISTS cities_district_idx ON cities (district_id);

