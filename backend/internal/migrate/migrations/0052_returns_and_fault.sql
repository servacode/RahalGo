-- **الذنبُ والاسترداد** — بقرار المالك (٢٠٢٦-٠٨-٠٢).
--
-- ## ١ · الذنبُ يُسجَّل لأنه يقرّر مالاً
--
-- طلبٌ تعذّر تسليمُه له سببان مختلفان في الحكم لا في اللفظ:
--
--   * **الحقُّ على الزبون** (عنوانٌ وهميّ · لا يردّ · رفض بلا سبب)
--     → **السائقُ يُعوَّض تلقائياً** بنسبةٍ من رسم التوصيل.
--   * **الحقُّ على السائق** (ادّعى التسليم · تأخّر فبرد الطعام)
--     → **لا تعويض** + إنذار.
--
-- **ونصٌّ حرٌّ لا يُعدّ ولا يُقاس**: كُتب في تجربتنا الحيّة «الزبون لا يقبل
-- الاستلام او رفض او لم اجد احد او العنوان وهمي» — **أربعةُ أحكامٍ في سطر**،
-- وأحدُها يستوجب مراجعةَ زبونٍ والآخر لا يستوجب شيئاً.
--
-- **والذنبُ لا يُستنتَج من `ended_by`**: ذاك يقول **من ضغط**، وهذا يقول **من
-- تسبّب** — وهما شيئان مختلفان حين تعمل المنصةُ نيابةً عن غيرها.
ALTER TABLE orders ADD COLUMN fault text
    CHECK (fault IN ('customer', 'driver', 'merchant', 'platform'));
ALTER TABLE orders ADD COLUMN fail_reason text;

COMMENT ON COLUMN orders.fault IS
    'من تسبّب في فشل الطلب — يقرّر التعويض. غير ended_by الذي يقول من ضغط';

-- ## ٢ · الاسترداد سياسةُ متجرٍ لا قاعدةَ منصة
--
-- منهم من يستردّ بضاعتَه ومنهم من يرفض. **وعلَمٌ لكلِّ متجر** يقرّر ما يظهر
-- للسائق حين يتعذّر التسليم.
ALTER TABLE merchants ADD COLUMN accepts_returns boolean NOT NULL DEFAULT false;

-- **ومتى أُعيدت** — فيُخصم مستحقُّها منه.
--
-- **وهذا ما يحلّ عقدةَ الدفع عند الاستلام**: المتجرُ قبض حين خرجت البضاعة،
-- فإن عادت إليه **عاد معها مالُها**. ولو تُرك له المالُ والبضاعةُ معاً **لربح
-- من الفشل أكثرَ ممّا يربح من النجاح** — وهو حافزٌ مقلوب.
ALTER TABLE orders ADD COLUMN returned_at timestamptz;

-- ## ٣ · والعمودُ القديم لم يعد له معنى
--
-- `goods_settled_to` وُضع حين كان المتجرُ يقبض عند التسليم، فكان يُسأل: «أنعوّضه
-- أم لا؟». **وبعد أن صار يقبض عند الاستلام صار السؤالُ عكسَه: أنستردّ منه أم
-- لا؟** — وهو ما يجيبه `returned_at`.
--
-- **ولا يُحذف العمود**: فيه بياناتٌ لطلباتٍ حُسمت بالقاعدة القديمة، **ومحوُ
-- تاريخٍ لتنظيف جدولٍ محوُ جوابٍ عن سؤالٍ يُطرح يوماً.**
COMMENT ON COLUMN orders.goods_settled_to IS
    'مهجور — كان يُستعمل حين يقبض المتجر عند التسليم. البديل: returned_at';

-- ## ٤ · نسبةُ التعويض — مفتاحٌ لا رقمٌ في الشيفرة
--
-- **ونسبةٌ لا مبلغٌ ثابت**: الثابتُ يظلم طرفاً حتماً — خمسةُ آلافٍ كثيرةٌ على
-- مشوارٍ في الحيّ وقليلةٌ على مشوارٍ عبر المدينة. **والنسبةُ تتبع المسافةَ لأن
-- رسم التوصيل يتبعها أصلاً.**
INSERT INTO app_settings (key, value) VALUES
    ('drivers.failed_compensation_percent', '50'::jsonb)
ON CONFLICT (key) DO NOTHING;
