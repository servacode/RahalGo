-- ══════════════════════════════════════════════════════════════════════
-- **فهرسُ التحقّق الموثوق من الجلسة**
-- ══════════════════════════════════════════════════════════════════════
--
-- (`R16` — دورةُ إصلاحٍ ١٦، ٢٠٢٦-٠٩-٠٧.)
--
-- # لماذا لا يكفي القائم
--
-- **`refresh_tokens_session_idx` جزئيٌّ**:
--
--	(user_id, session_id) WHERE revoked_at IS NULL
--
-- **وعيبان فيه للسؤال الجديد**:
--
--	١ **عمودُه الأوّلُ `user_id`** — والسؤالُ يأتي بمعرّف جلسةٍ
--	  وحدَه، **فلا يُستعمل الفهرسُ في بحثٍ بالثاني.**
--	٢ **يستثني المُبطَلَ** — **والسؤالُ عينُه «أمُبطَلةٌ هي؟»**،
--	  فالصفوفُ التي نبحث عنها خارجَه أصلاً.
--
-- **وفهرسٌ لا يخدم السؤالَ مسحٌ كاملٌ في كلّ طلبِ توثيق.**
--
-- # وأصغرُ ما يكفي
--
-- **عمودٌ واحد** — **ولا `INCLUDE` ولا شرطَ جزئيّ**: الصفوفُ لعائلةِ
-- جلسةٍ واحدةٍ قليلةٌ (تدويرُ التجديد يُضيف صفّاً لا جدولاً)،
-- **فالانتقالُ إلى الصفّ لقراءة `revoked_at` و`expires_at` رخيص.**
CREATE INDEX IF NOT EXISTS refresh_tokens_session_lookup_idx
    ON refresh_tokens (session_id);
