--
-- # المشكلة
--
-- **الزبونُ يضغط «اطلب» فينقطع الردُّ في الطريق.** التطبيقُ لا يعلم أوصل
-- الطلبُ أم لا، **فيعيد الإرسال** — وينشأ طلبان وخصمان.
--
-- **وانتقالاتُ الحالة محميّةٌ أصلاً**: `مُسلَّم` لا ينتقل إلى `مُسلَّم`،
-- والصفُّ مقفولٌ بـ`FOR UPDATE`. **لكنّ الإنشاءَ لا حارسَ له** — ولا
-- إضافةَ الرصيد اليدويّة، ولا تسويةَ نقد السائق، ولا منحَ المكافأة.
--
-- # والحلّ مفتاحٌ يرسله العميل
--
-- **رقمٌ يولّده التطبيقُ مرّةً لكلّ فعلٍ يقصده** — ويبقى نفسَه في كلّ
-- إعادة. **فأوّلُ نداءٍ ينفّذ ويُحفظ ردُّه، والإعادةُ تُرجع المحفوظَ ولا
-- تنفّذ شيئاً.**
--
-- **والمفتاحُ من العميل لا من الخادم**: الخادمُ لا يستطيع أن يفرّق بين
-- «إعادةِ محاولة» و«طلبٍ ثانٍ مقصود» — **والزبونُ قد يطلب مرّتين بنفس
-- المحتوى في دقيقة، وهذا حقُّه.** والتطبيقُ وحدَه يعرف أنّها المحاولةُ
-- نفسُها.
--
-- # ولماذا يُحفظ الردُّ لا المفتاحُ فقط
--
-- **التطبيقُ ينتظر رقمَ الطلب ليعرضه.** ولو رُدّ على الإعادة بـ«مكرّر»
-- بلا بيانات **لَبقي صاحبُه لا يعرف أنجح طلبُه أم لا** — وهو أسوأُ من
-- الطلب المكرّر نفسِه.
CREATE TABLE IF NOT EXISTS idempotency_keys (
    -- **المفتاحُ مع صاحبه ومع النقطة** — لا وحدَه.
    --
    -- **ولو كان وحدَه لَاستطاع أحدٌ أن يُعطّل فعلَ غيره**: يرسل مفتاحاً
    -- يخمّنه فيحجزه، **فيصير فعلُ صاحبِه الحقيقيِّ «مكرّراً» ويُردّ عليه
    -- ردٌّ ليس له.**
    user_id     uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    endpoint    text NOT NULL,
    key         text NOT NULL,

    -- **الحالةُ تفرّق بين «قيد التنفيذ» و«انتهى»** — ونداءان متزامنان
    -- بالمفتاح نفسِه يقع أحدُهما على صفٍّ لم يكتمل بعد، **فيُردّ عليه
    -- «أعد المحاولة» لا ردٌّ فارغ.**
    done        boolean NOT NULL DEFAULT false,
    status_code int     NOT NULL DEFAULT 0,
    -- **نصٌّ لا `jsonb`** — **و`jsonb` تُعيد تنسيقَ ما يُخزَّن فيها**
    -- (مسافاتٌ وترتيبُ مفاتيح)، **فيعود الردُّ المُعادُ مختلفَ البايتات عن
    -- الأصل.** والمقصودُ أن يتلقّى التطبيقُ الردَّ نفسَه حرفاً بحرف.
    response    text,

    created_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, endpoint, key)
);

-- **ويُقلَّم بالزمن** — **وجدولٌ يحفظ مفتاحاً لكلّ فعلٍ إلى الأبد يبلغ
-- الملايين**، ولا يُسأل منه إلّا ما كان قبل دقائق. **والتقليمُ مع الكتابة
-- لا في مهمّةٍ ليليّة**: مهمّةٌ تُنسى أو تتعطّل فينتفخ الجدولُ بصمت.
CREATE INDEX IF NOT EXISTS idempotency_keys_age_idx ON idempotency_keys (created_at);
