-- **وسمُ الرسالة المسيئة — تُحفظ ولا تُمحى**
-- ══════════════════════════════════════════════════════════════════════
--
-- (قرارُ المالك ٢٠٢٦-٠٨-١٢: «ولا تنسَ تعمل أرشفة للكلمات المحظورة —
--  مسبّات أو شتائم».)
--
-- # ولماذا تُوسَم ولا تُمنع
--
-- **المنعُ يُخفي ولا يمنع**: من أراد أن يشتم كتبها بحرفٍ مبدَّلٍ أو بمسافةٍ
-- بين حروفها، **فتمرّ ولا تُعرف.** ومن مُنع مرّةً تعلّم كيف يمرّ في الثانية.
--
-- **والوسمُ يُبقيها ويقولها**: تصل إلى صاحبها كما كُتبت — **والشكوى تُحسم
-- بنصٍّ مكتوبٍ لا بكلمةٍ ضدّ كلمة** — ويقرؤها المكتبُ فيحكم.
--
-- **وهي شهادةٌ في نزاع**: سائقٌ يقول «شتمني» وزبونٌ ينكر — **ومحادثةٌ
-- مُنقّاةٌ لا تشهد لأحد.**
--
-- # وعمودان لا واحد
--
-- **`flagged` للفرز و`flag_word` للسبب**: الأوّلُ يُفهرَس ويُعدّ، **والثاني
-- يقول أيُّ لفظٍ أوقعه** — فيُراجَع الحارسُ نفسُه حين يُخطئ.
ALTER TABLE order_messages
	ADD COLUMN IF NOT EXISTS flagged   boolean NOT NULL DEFAULT false,
	ADD COLUMN IF NOT EXISTS flag_word text;

-- **والسؤالُ دائماً «ما الموسوم»** — وهي قلّةٌ في كثرة، فيُفهرَس الموسومُ
-- وحدَه (`partial index`): **فهرسٌ على عمودٍ كلُّه `false` حملٌ بلا فائدة.**
CREATE INDEX IF NOT EXISTS order_messages_flagged_idx
	ON order_messages (created_at DESC) WHERE flagged;
