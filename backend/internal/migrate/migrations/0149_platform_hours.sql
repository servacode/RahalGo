-- ══════════════════════════════════════════════════════════════════════
-- **دوامُ المنصّة وإيقافُها المؤقّت** (`PH`، ٢٠٢٦-٠٩-١٤)
-- ══════════════════════════════════════════════════════════════════════
--
-- # ولمَ جدولان لا مفاتيحُ إعدادات
--
-- **و`app_settings` مفتاحٌ وقيمةٌ** — **وجدولُ أسبوعٍ بفتراتٍ متعدّدةٍ
-- في اليوم ليس قيمةً واحدة.** **ومن حشره نصّاً واحداً بنى بنيةً داخل
-- نصٍّ**: لا تحقُّقَ في القاعدة، ولا ترتيبَ، ولا فحصَ تداخلٍ —
-- **والمالكُ نهى عن ذلك نصّاً**: «do not force schedules into an
-- unreadable giant JSON/config string».
--
-- **والسابقةُ في المستودع `merchant_hours`** (هجرة ٠٠٠٦): **جدولُ دوامٍ
-- صفوفٌ لا نصّ.** **وهذا امتدادُها إلى المنصّة نفسِها**، **بفارقٍ
-- واحدٍ مقصود**: **فتراتٌ متعدّدةٌ في اليوم** — ولذلك لا مفتاحَ مركّبٌ
-- على `(day, …)` ولا رايةُ «مغلق».
--
-- # واليومُ المغلقُ لا رايةَ له
--
-- **ويومٌ بلا صفوفٍ مغلقٌ بذاته** — **ورايةُ `closed` مع صفٍّ بفترةٍ
-- تصنع حالين يقولان الشيءَ نفسَه** (`closed=true` وفترةٌ صفريّة)
-- **فيفترقان يوماً ويُجيب الجدولُ إجابتين.**
--
-- # وعبورُ منتصف الليل بلا عمودٍ ثالث
--
-- **و`ends_at <= starts_at` تعني العبور** — ١٧:٠٠ ← ٠١:٠٠. **وهو
-- الاصطلاحُ القائمُ في `orders/hours.go` لدوام المتاجر**، **ولا
-- يُخترَع له اصطلاحٌ ثانٍ في المستودع نفسِه.**

CREATE TABLE platform_hours (
    id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    -- ٠=الأحد … ٦=السبت — كما يعدّها بوستغرس (`EXTRACT(dow)`) وGo.
    day_of_week int  NOT NULL CHECK (day_of_week BETWEEN 0 AND 6),
    starts_at   time NOT NULL,
    ends_at     time NOT NULL,
    -- **وبدءٌ يساوي انتهاءً غامضٌ** — أصفرٌ هو أم يومٌ كامل؟
    -- **والغموضُ يُردّ في القاعدة أيضاً، لا في الخادم وحدَه.**
    CONSTRAINT platform_hours_not_empty CHECK (starts_at <> ends_at),
    -- **ولا فترتان تبدآن في اللحظة نفسِها من اليوم نفسِه** — وهو أوّلُ
    -- التداخل وأبسطُه. **وما تبقّى منه يُقاس في الخادم** (`Validate`):
    -- **تقاطعُ المدى على مدارِ الأسبوع لا تُعبّر عنه قيودُ صفٍّ واحد.**
    CONSTRAINT platform_hours_unique_start UNIQUE (day_of_week, starts_at)
);

CREATE INDEX platform_hours_day_idx ON platform_hours (day_of_week);

-- ══════════════════════════════════════════════════════════════════════
-- **الإيقافُ المؤقّت — صفٌّ واحدٌ لا أكثر**
-- ══════════════════════════════════════════════════════════════════════
--
-- **وهو ليس وضعَ إطلاق** (`launch.*`): **ذاك يقول أيُّ عملٍ فُتح للناس
-- أصلاً**، **وهذا يقول «مفتوحٌ ولكن ليس الآن».** **ومن خلط بينهما قال
-- للناس «نعود الرابعة» عن بابٍ لا موعدَ لفتحه** — **والمالكُ نهى عن
-- التحميل على وضع الإطلاق نصّاً.**
--
-- # ولمَ جدولٌ لا مفاتيح
--
-- **وفيه موعدُ عودةٍ لحظيٌّ** (`timestamptz`) — **و`app_settings` نصٌّ
-- أو رقمٌ أو رايةٌ، ولا نوعَ لحظةٍ فيها.** **ولو حُشر نصّاً لَقُرئ
-- بالتخمين في كلّ موضعٍ يقرؤه**، **وفرقُ التوقيت يضيع.**
--
-- **وسطرُ التدقيق فيه كما في `app_settings`** — `updated_at`
-- و`updated_by` — **فلا بنيةَ تدقيقٍ جديدةٌ تُخترَع.**
CREATE TABLE service_closure (
    -- **مفتاحٌ منطقيٌّ مقيَّدٌ بـ`true`** — **فالصفُّ واحدٌ بحكم
    -- القاعدة لا بحكم أدبِ من يكتب.**
    id         boolean PRIMARY KEY DEFAULT true CHECK (id),
    active     boolean NOT NULL DEFAULT false,
    message    text NOT NULL DEFAULT '',
    -- **موعدُ العودة إن كان معلوماً** — **والفارغُ يعني «لا موعد»،
    -- ولا يُخترَع له واحد.**
    ends_at    timestamptz,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by uuid REFERENCES users (id)
);

-- **ويُبذَر الصفُّ مطفأً** — **فالقراءةُ تجد صفّاً دائماً ولا تفرّق
-- بين «لا صفّ» و«مطفأ».**
INSERT INTO service_closure (id) VALUES (true) ON CONFLICT DO NOTHING;

-- ══════════════════════════════════════════════════════════════════════
-- **ولا يُغلَق شيءٌ بهذه الهجرة**
-- ══════════════════════════════════════════════════════════════════════
--
-- **والجدولُ يُنشأ فارغاً** — **ولو كان «الفارغُ مغلقاً» لَأوقفت هذه
-- الهجرةُ استقبالَ الطلبات في لحظةِ نشرها.** **وذاك عطبٌ لا ميزة**
-- (وهو الدرسُ المكتوبُ في هجرة ٠١٤٨ نفسِها).
--
-- **فسريانُ الجدول رايةٌ صريحةٌ** — `hours.platform_enforced` —
-- **افتراضُها `false`**، **فيُبنى الجدولُ ويُراجَع ثمّ يُفعَّل في
-- لحظةٍ يختارها المالك.** **ولا تُبذَر هنا**: **غيابُ المفتاح يقع على
-- الافتراض، وهو المطلوب.**
