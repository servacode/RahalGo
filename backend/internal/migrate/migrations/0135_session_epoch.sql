--
-- (`R13` — دورةُ إصلاحٍ ١٨، ٢٠٢٦-٠٩-٠٧.)
--
-- # العلّة
--
-- **إعادةُ الإدارة لكلمةِ حسابٍ فعلُ استرداد** — جهازٌ ضاع أو حسابٌ
-- اختُرق. **وكانت تكتب البصمةَ ولا تُبطل جلسة**: **رمزُ الوصول القديمُ
-- يعمل، ورمزُ التجديد يدور إلى الأبد.**
--
-- # ولماذا لا يكفي إبطالُ الصفوف
--
-- **`Refresh` تُبطل الرمزَ المعروضَ أوّلاً ثمّ تُصدر بديلَه** — **وبين
-- الاثنين تقع الإعادة**:
--
--	١ التجديدُ يُبطل الرمزَ القديم
--	٢ الإعادةُ تُبطل ما تجده — **ولا شيءَ حيٌّ لتجده**
--	٣ التجديدُ يُدرج صفّاً جديداً — **فيُفلت من الاسترداد**
--
-- **وقفلُ صفٍّ لا يُغلقها**: **من انتظر القفلَ أدرج بعد تحريره**،
-- **والإبطالُ مضى.**
--
-- # فحِقبةٌ لا مطاردة
--
-- **`sessions_revoked_at` خطٌّ زمنيٌّ على الحساب.** **وعائلةُ جلسةٍ
-- كلُّ صفوفها قبله ماتت** — **مهما أُدرج بعدها.**
--
-- **ودخولٌ جديدٌ يُنشئ عائلةً جديدةً بعد الخطّ** فيمرّ. **والاستردادُ
-- ليس إغلاقاً.**
--
-- # وفارغةٌ تعني «لم يقع استرداد»
--
-- **فلا حسابَ قائمٌ يُمسّ بهذه الهجرة** — والتاريخُ يبقى تاريخاً.
ALTER TABLE users
    ADD COLUMN IF NOT EXISTS sessions_revoked_at timestamptz;

COMMENT ON COLUMN users.sessions_revoked_at IS
    'R13: كلُّ عائلةِ جلسةٍ بدأت قبل هذا الوقت ميّتةٌ ولا تُجدَّد';
