-- **مكافأةُ الهدف تُدفع آليّاً — ومرّةً واحدةً في الشهر.**
--
-- (قرارُ المالك ٢٠٢٦-٠٨-٠٩: «يجب أن تكون واضحة وتُدفع بشكل آليّ عند إتمام
--  الهدف، مع تأثير للشاشة عند وصول الهدف احتفاليّ للسائق».)
--
-- # وهو تراجعٌ عن قرارٍ سابقٍ بوعي
--
-- **كان (٢٠٢٦-٠٨-٠٥): «بيدك، والشاشةُ تقول من بلغ»** — لأنّ من بلغ الهدفَ
-- بثلاثين طلباً صغيراً ليس كمن بلغه في ليالي المطر، **والفرقُ يراه إنسانٌ ولا
-- تراه معادلة.**
--
-- **والمالكُ اختار الوضوحَ على التقدير**: من يركض خلف هدفٍ يجب أن يعرف الجائزة.
-- **والتقديرُ يبقى بابُه مفتوحاً** — المكافأةُ اليدويّةُ لم تُلغَ، وهذه تُضاف.
--
-- # والتكرارُ هو الخطر
--
-- **رقمٌ يدفع آليّاً يدفع مرّتين إن سُئل مرّتين**: يُسلَّم طلبان في ثانيةٍ
-- واحدة، **فيقرأ كلاهما «لم يُكافأ بعد» ويكتب كلاهما مكافأة.**
--
-- **والفحصُ قبل الكتابة لا يمنعه**: بينهما ثغرةٌ يمرّ فيها الاثنان.
-- **والقاعدةُ تحكم حيث لا يحكم الترتيب** — وهو ما تعلّمناه في تذاكر الشكاوى
-- (`tickets_one_open_per_order`).
ALTER TABLE incentives
  -- period **شهرُ الحافز — «2026-08».**
  --
  -- **ونصٌّ لا تاريخ**: الفهرسُ الفريدُ يحتاج تعبيراً ثابتاً، **و`date_trunc`
  -- بمنطقةٍ زمنيّةٍ ليست ثابتة** فلا تدخل فهرساً. والنصُّ يُحسب مرّةً عند
  -- الكتابة بتوقيت دمشق.
  ADD COLUMN IF NOT EXISTS period text;

-- **مكافأةُ هدفٍ واحدةٌ لكلّ شخصٍ في كلّ شهر.**
--
-- **وجزئيٌّ على `for_target`**: المكافآتُ اليدويّةُ تتكرّر بلا حدّ — **يُكافَأ
-- من أحسن مرّتين في شهر**، وهذا حقُّ المالك لا خلل.
CREATE UNIQUE INDEX IF NOT EXISTS incentives_one_target_per_month
  ON incentives (user_id, period) WHERE for_target AND period IS NOT NULL;
