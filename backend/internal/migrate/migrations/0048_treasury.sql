-- **خزينةُ المنصة** — بقرار المالك (٢٠٢٦-٠٨-٠١).
--
-- # المسألة
--
-- لم يكن للمنصة دفترٌ إطلاقاً. ما يراه المالك `sum(platform_commission)` —
-- **جمعُ عمودٍ في تقرير لا رصيدٌ في دفتر.** فلا يظهر فيه ما خرج: أجورُ
-- السائقين ولا عمولاتُ المندوبين ولا التعويضاتُ ولا الاسترجاعات.
--
-- **وربحٌ يُعرَض بلا مصاريفه ليس ربحاً، هو إيراد** — والفرقُ بينهما هو الفرقُ
-- بين منصةٍ تكسب ومنصةٍ تظنّ أنها تكسب.
--
-- # وماذا يقول رصيدُها
--
-- **ما كسبَته المنصةُ وما أنفقَته** — لا النقدَ في المكتب (ذاك يقيسه صندوقُ
-- السائق). فطلبٌ ببضاعة ١٠٠ ألف وتوصيل ١٠:
--
--	  الزبون يدفع        ١١٠٬٠٠٠
--	  − المتجر            ٩٠٬٠٠٠   (البضاعة ناقصَ العمولة)
--	  − السائق             ٧٬٠٠٠
--	  − المندوب            ١٬٠٠٠
--	  ────────────────────────────
--	  = الخزينة          ١٢٬٠٠٠
--
-- **ومالُ المتجر ليس مصروفاً على المنصة، هو مالٌ يعبر** لا يخصّها.
--
-- # ولماذا تُستثنى من قيد «لا سالب»
--
-- طلبٌ نقديّ: الزبونُ يدفع ١١٠ ألفاً **في جيب السائق**، والمنصةُ تقيّد ٩٨
-- لأطرافها — **فتدفع قبل أن تقبض.** والقيدُ يرفض القيدَ الأوّل من يومها الأوّل.
--
-- **والسالبُ ليس خطأً، هو الواقع**: مقدارُه النقدُ الذي لم يصل المكتبَ بعد.
--
-- والاستثناءُ **للخزينة وحدها**: محافظُ الناس تبقى محروسةً بالقيد نفسه، فلا
-- يُسحب من زبونٍ ما لا يملك ولا يُخصم من سائقٍ إلى ما دون الصفر.
ALTER TABLE wallets ADD COLUMN is_treasury boolean NOT NULL DEFAULT false;

ALTER TABLE wallets DROP CONSTRAINT IF EXISTS wallets_balance_check;
ALTER TABLE wallets ADD CONSTRAINT wallets_balance_check
    CHECK (balance >= 0 OR is_treasury);

-- **خزينةٌ واحدة لا خزينتان**: لو تعدّدت لصار السؤال «كم ربحنا؟» جمعاً يدوياً
-- يُنسى أحدُ طرفيه.
CREATE UNIQUE INDEX wallets_single_treasury_idx ON wallets (is_treasury)
    WHERE is_treasury;

-- # نوعُ القيد
--
-- **`platform_profit` لا `adjustment`**: التسويةُ فعلُ إنسانٍ يُصحّح، وهذا قيدٌ
-- يصدره المحرّك عن كل طلب. **ولفظٌ واحدٌ لهما يجعل تقريرَ الأرباح يحوي أخطاءَ
-- الموظّفين** — ولا يُفرَّق بينهما بعد شهر.
ALTER TABLE wallet_transactions DROP CONSTRAINT IF EXISTS wallet_transactions_kind_check;
ALTER TABLE wallet_transactions ADD CONSTRAINT wallet_transactions_kind_check
    CHECK (kind = ANY (ARRAY[
        'topup', 'order_payment', 'refund', 'compensation', 'commission',
        'merchant_earning', 'driver_earning', 'payout', 'adjustment',
        'platform_profit'   -- نصيبُ الخزينة من طلبٍ مُسلَّم (سالبٌ عند العكس)
    ]));

-- # ومن يحملها
--
-- **حسابُ مستخدمٍ يحدّده المالك** — الأدمن أو المدير المالي. ولم يُختر بالدور
-- بل بالحساب: **الأدوارُ يحملها أكثرُ من واحد، والخزينةُ واحدة.**
--
-- وفارغٌ يعني **لم تُختَر بعد**: عندها لا يُكتب قيدُ خزينةٍ ولا يُعطَّل تسليم.
-- **وطلبٌ يُرفض لأن المالك لم يفتح صفحةَ الإعدادات خسارةٌ لا تُحتمَل.**
INSERT INTO app_settings (key, value) VALUES ('platform.treasury_user_id', '""'::jsonb)
    ON CONFLICT (key) DO NOTHING;
