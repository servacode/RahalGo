-- حلقة المطبخ — ما كان ينقص الدورة التشغيلية للمتجر.
--
-- كان الطلب ينتقل من «قيد التحضير» إلى «جارٍ إسناد سائق» بقرار عمليات أو
-- **بمؤقّتٍ زمني**: فيُستدعى السائق بالساعة لا بالجاهزية — يصل مبكراً فينتظر،
-- أو متأخراً فيبرد الطعام. والوحيد الذي يعرف متى يجهز هو المطبخ.

-- وقت التحضير: افتراضٌ للمتجر، ورقمٌ فعلي لكل طلب يُثبَّت عند القبول.
-- (يبقى الافتراض على المتجر كي لا يُسأل عنه في كل طلب.)
ALTER TABLE merchants ADD COLUMN default_prep_minutes integer NOT NULL DEFAULT 20
    CHECK (default_prep_minutes BETWEEN 1 AND 240);
ALTER TABLE orders ADD COLUMN prep_minutes integer;

-- **الجاهزية علامة لا حالة** عن قصد.
--
-- جعلُها حالةً في السلسلة يفرض تسلسلاً كاذباً: التحضير وإسناد السائق مساران
-- **متوازيان** لا متتاليان — قد يصل السائق ويقف عند الباب والطعام لم يجهز، وقد
-- يجهز الطعام ولمّا يُسنَد سائق. فلو كانت حالةً لتعذّر أن يقول المتجر «جهز»
-- بينما الطلب في «تم إسناد سائق».
--
-- فهي وسمٌ زمني يُرفع في أي لحظة قبل الاستلام، ويقرؤه السائق والعمليات كحقيقة
-- لا كمرحلة.
ALTER TABLE orders ADD COLUMN ready_at timestamptz;

-- الحدّ الأدنى للطلب على المتجر لا على المنطقة وحدها.
-- مطعمٌ حدّه خمسون ألفاً وبقاليةٌ حدّها عشرة آلاف لا يتعايشان تحت رقمٍ واحد
-- للمنطقة. والأعلى بينهما هو الملزِم — لا يُلغي أحدهما الآخر.
ALTER TABLE merchants ADD COLUMN min_order bigint NOT NULL DEFAULT 0
    CHECK (min_order >= 0);

-- بحث سريع عمّا جهز ولمّا يُستلَم — شاشة العمليات تسأله كل ثانية
CREATE INDEX orders_ready_pending_pickup_idx ON orders (ready_at)
    WHERE ready_at IS NOT NULL AND status IN ('preparing', 'dispatching', 'assigned', 'at_pickup');
