-- إشعارٌ للزبون حين ينال التوصيلةَ المجانيّة أوّلَ مرّة. **والإعفاءُ يقع في أكثر من باب**
-- (الطلبُ العاديّ عند الإنشاء، والمشترياتُ والأمانةُ عند تثبيت الأجرة) — **فيُرسَل من نبضةٍ
-- دوريّةٍ بعد التثبيت** لا من داخل معاملةٍ قد تُرجَع، و`notified_at` يمنع التكرار.
ALTER TABLE free_delivery_claims ADD COLUMN IF NOT EXISTS notified_at timestamptz;

-- **وما نيل قبل اليوم لا يُبشَّر به متأخّراً.**
UPDATE free_delivery_claims SET notified_at = created_at WHERE created_at < now() - interval '1 day';
