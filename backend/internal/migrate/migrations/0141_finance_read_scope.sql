-- ══════════════════════════════════════════════════════════════════════
-- **والماليّةُ دورٌ كانونيٌّ لا دورٌ قديم**
-- ══════════════════════════════════════════════════════════════════════
--
-- (`ADG-2` · `AQ-1` — دورةُ إصلاحٍ ٢٦ · جولةٌ ثانية.)
--
-- # المسألة
--
-- **`finance` اسمٌ واحدٌ لدورين في ذهني**: **قديمٌ يُحفَظ وصولُه**،
-- **وكانونيٌّ يخضع لأقلِّ صلاحيّة.** **وهو دورٌ واحدٌ في القاعدة.**
--
-- **فطُبّقت عليه قاعدةُ الحفظ مرّتين** — دورةُ ٢٥ أعطته `support.manage`
-- و`audit.read` لأنّ حارسَه القديم كان `admin,finance`، **وهجرةُ ٠١٤٠
-- أعطته المحادثاتِ والعناوينَ لأنّها كانت بلا حارس.**
--
-- **والعقدُ يقول عكسَ ذلك**: **الماليّةُ دورٌ من التسعة**، **ولا قدرةَ
-- تبقى له لأنّها كانت تعمل.**
--
-- # وما يُنزَع
--
-- **`support.manage`** — **وهي القدرةُ التي أُنشئت أصلاً لأنّ إغلاقَ
-- التذكرة بحارس `admin,finance` كان عكسَ التخصّص.** **فإبقاؤها للماليّة
-- إبقاءٌ للعلّة التي أُنشئت لرفعها.**
--
-- **`audit.read`** — **وُصفت يومَ أُنشئت بأنّها «قراءةُ أمنٍ لا مال».**
--
-- **`orders.communications.read`** — **من يسوّي حساباً لا يقرأ كلامَ
-- الناس.**
--
-- **`users.sensitive.read`** — **قيدُ محفظةٍ لا يحتاج دفترَ بيوت.**
--
-- **ويبقى لها كشفُها**: `finance.export` **عملٌ مكتوبٌ في المصدر.**
--
-- **وهذا تبديلُ وصولٍ لحساباتٍ قائمة** — وبندُ ترحيل الحسابات مسجَّلٌ
-- من دورةِ ٢٥.
DELETE FROM role_capabilities
 WHERE role_code = 'finance'
   AND capability_code IN (
        'support.manage',
        'audit.read',
        'orders.communications.read',
        'users.sensitive.read');
