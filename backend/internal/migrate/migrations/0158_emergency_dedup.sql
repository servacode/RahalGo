-- ══════════════════════════════════════════════════════════════════════
-- **بلاغُ الطوارئ مرّةً واحدةً لكلّ طلبٍ مفتوح** (`DRV-DEF-001`)
-- ══════════════════════════════════════════════════════════════════════
--
-- **كان زرُّ الطوارئ يُدرج صفّاً بلا حارس** — فإن سقطت الشبكةُ بعد أن وصل
-- النداءُ الخادمَ وضاع الردُّ، **أعاد السائقُ الضغطَ فوُلِّد بلاغٌ ثانٍ**
-- لطارئٍ واحد. **والعملياتُ تقرأ بلاغَين لحادثةٍ واحدةٍ فتُربَك.**
--
-- **والصوابُ**: بلاغٌ مفتوحٌ واحدٌ لكلّ طلب. فإعادةُ الضغطِ بعد فشلٍ ترتدّ
-- إلى الصفِّ القائمِ لا تُنشئ ثانياً — **تسجيلٌ مرّةً واحدةً، وإخطارٌ مرّةً
-- على الأقلّ** (وهو العقدُ الصحيحُ لإنذارِ سلامة).
--
-- **وقبل الحارس يُنظَّف ما مضى بلا أذى**: إن وُجدت بلاغاتٌ مفتوحةٌ مكرّرةٌ
-- لطلبٍ واحد (من العطبِ نفسِه) **يُبقى الأقدمُ — وهو الإنذارُ الحقيقيُّ
-- الأوّل — ويُغلَق ما بعده** (نسخُ الإعادةِ لا الحادثةُ). **فلا يُمسّ
-- إنذارٌ حقيقيّ.**

UPDATE driver_emergencies e
   SET status      = 'resolved',
       resolved_at = now(),
       resolution  = 'auto: deduped by 0158 (kept earliest open per order)'
 WHERE e.status = 'open'
   AND e.order_id IS NOT NULL
   AND EXISTS (
       SELECT 1 FROM driver_emergencies o
        WHERE o.order_id = e.order_id
          AND o.status   = 'open'
          AND o.created_at < e.created_at
   );

-- **الحارسُ**: بلاغٌ مفتوحٌ واحدٌ لكلّ طلب (الطلبُ غيرُ الفارغ).
CREATE UNIQUE INDEX IF NOT EXISTS driver_emergencies_one_open
    ON driver_emergencies (order_id) WHERE status = 'open';
