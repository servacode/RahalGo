-- # 1 · حصّةُ المنصّة من الأجرة صارت مفتاحاً واحداً لكلّ الأنواع (البند 1)
--
-- **والقديمُ (`delivery.merchant_delivery_platform_percent`) يُمحى ولا تُنقل
-- قيمتُه**: كان لـ«لدي توصيلة» والخاصّ وحدهما، **ونقلُ 10% إلى المفتاح الجديد
-- يُنقص أجرَ كلّ سائقٍ في الطلب العاديّ فجأة.** والجديدُ (`delivery.platform_percent`)
-- يبدأ صفراً بقرار المالك، **والطلباتُ القائمةُ تحمل لقطتَها** فلا يتبدّل منها شيء.
--
-- # 2 · مفاتيحُ ميّتةٌ أو أُلغي قرارُها (البندان 4 و6)
--
--	sales.commission_source   المصدرُ ثابت: ربحُ المنصّة كلُّه
--	sales.activation_orders   العمولةُ من أوّل طلبٍ ناجح
--	platform.invite_code      لا قارئَ له في المحرّك
--	platform.app_url          الزرُّ العلويُّ يقرأ مركزَ التنزيل
--	platform.app_file         والملفُّ القديمُ لا يُخدَم بعد اليوم (الرابطُ يُحوَّل)
--
-- **ويُمحى ملفُّ التطبيق القديم من الإعداد لا من القرص** — والقرصُ يُنظَّف بيدٍ
-- بعد التأكّد أنّ مركزَ التنزيل يحمل النسخَ الأربع.
DELETE FROM app_settings
 WHERE key IN (
    'delivery.merchant_delivery_platform_percent',
    'sales.commission_source',
    'sales.activation_orders',
    'platform.invite_code',
    'platform.app_url',
    'platform.app_file'
 );

-- # 3 · سقفُ نقد السائق لا يكون صفراً (البند 5)
--
-- **الصفرُ كان يُقرأ «خمسمئة ألف» في الصندوق و«صفراً» في التوزيع** — وأقلُّه
-- الآن عشرةُ آلاف. **وقيمةٌ مخزَّنةٌ تحت الحدّ تُمحى فيعمل الافتراض** (500000)
-- — لا تُرفع إلى عشرة آلاف فيُحبس كلُّ سائقٍ عن النقد.
DELETE FROM app_settings
 WHERE key = 'drivers.cash_limit'
   AND jsonb_typeof(value) = 'number'
   AND (value #>> '{}')::numeric < 10000;
