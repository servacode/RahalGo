-- المفضّلةُ على الصنف لا على المتجر.
--
-- # القرار
--
-- قرّر المالك (٢٠٢٦-٠٨-٠٥): «بالنسبة للمفضّلة لازم تكون ع صنف وليس ع متجر».
--
-- # ولماذا هو الصواب
--
-- **الزبونُ لا يشتهي متجراً، يشتهي صحناً.** ومن أحبّ شاورما مطعمٍ بعينه لا
-- يريد قائمتَه كلَّها — يريد ذلك الصحن، وبينه وبينه ثلاثُ ضغطاتٍ في كلّ مرّة:
-- المتجرُ ثمّ القسمُ ثمّ الصنف.
--
-- **ومفضّلةُ المتاجر تختصر واحدةً من ثلاث.**
--
-- # ولا تُنقَل البيانات
--
-- **لأنّها لا تُنقَل**: «أحبّ هذا المتجر» لا يُترجَم إلى صنفٍ بعينه — **وأيَّ
-- صنفٍ نختار له؟** فاختيارٌ نضعه نحن عنه أسوأُ من لا شيء.
--
-- **والجدولُ فارغٌ أصلاً** (صفرُ صفٍّ يومَ الترحيل)، فالمسألةُ نظريّة.

DROP TABLE IF EXISTS user_favorites;

CREATE TABLE user_favorites (
	user_id      uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	menu_item_id uuid NOT NULL REFERENCES menu_items(id) ON DELETE CASCADE,
	created_at   timestamptz NOT NULL DEFAULT now(),
	PRIMARY KEY (user_id, menu_item_id)
);

-- **الأحدثُ أوّلاً** — وآخرُ ما أحبَّه أقربُ إلى ما يطلبه اليوم.
CREATE INDEX user_favorites_user_idx ON user_favorites (user_id, created_at DESC);

-- **ومن حُذف صنفُه حُذف صفُّه** (`ON DELETE CASCADE` أعلاه): مفضّلةٌ تشير إلى
-- صنفٍ رفعه المتجرُ من قائمته **تُعرض بطاقةً فارغةً لا اسمَ لها ولا سعر**.
