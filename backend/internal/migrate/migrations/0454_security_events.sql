-- ══════════════════════════════════════════════════════════════════════
-- **أحداثُ الأمان مجمَّعةً باليوم** (مراقبةُ المنصّة — الدفعةُ الثانية ٢٠٢٦-١٠-١٧)
-- ══════════════════════════════════════════════════════════════════════
--
-- صفٌّ واحدٌ لكلّ نوعٍ في كلّ يوم — **فألفُ محاولةِ دخولٍ غلطٍ صفٌّ واحدٌ عدُّه
-- ألف**، لا ألفُ صفّ.
--
--   day         يومُ دمشق (`platform.Location`) — **فـ«مبارح» في التقرير الصباحيّ
--               هو مبارح المالك لا مبارح غرينتش.**
--   kind        login_failed · login_locked · otp_limited · code_wrong ·
--               code_locked · gps_mocked · forbidden
--   count       كم مرّةً في هذا اليوم
--   updated_at  آخرُ كتابة
--
-- **ولا رقمَ هاتفٍ ولا معرّفَ ولا رمزَ ولا كود** — عددٌ لا غير. **ويُكتب من
-- الذاكرة دفعةً كلَّ دقيقة** كعدّاد الأخطاء (`server_errors`)، **فالتقريرُ يقرأ
-- مبارح ولو أُعيد تشغيلُ الخادم في الليل.** ويُحذف ما جاوز تسعين يوماً.
CREATE TABLE IF NOT EXISTS security_events_daily (
    day        date        NOT NULL,
    kind       text        NOT NULL,
    count      bigint      NOT NULL DEFAULT 0,
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (day, kind)
);
