-- الخزينةُ صفةٌ في المحفظة — **لا مفتاحاً في الإعدادات.**
--
-- # المسألة: مصدرانِ لحقيقةٍ واحدة
--
-- كان للخزينة موضعان: مفتاحُ `platform.treasury_user_id` يقول من هي، وعمودُ
-- `wallets.is_treasury` يقول من هي. **وإن افترقا فأيُّهما يُصدَّق؟**
--
-- **والعمودُ أصدق**: عليه الفهرسُ الفريد الذي يمنع خزينتين، وعليه شرطُ
-- `balance >= 0 OR is_treasury` الذي يسمح لها وحدَها بالسالب — **فالقاعدةُ
-- تحرسه ولا تحرس المفتاح.** وكان الحلُّ القديم أن يُصحَّح العمودُ من المفتاح
-- عند كلّ قيد، **وهو علاجُ عرَضٍ لا سبب.**
--
-- **وقد ذهب المفتاحُ مع الإعدادات كلِّها** (٢٠٢٦-٠٨-٠٤)، فبقي العمودُ وحدَه
-- — وهو ما كان يجب من البداية.
--
-- # وصفةٌ في حسابٍ ليست إعداداً
--
-- هي كالدور: تُمنح لحسابٍ بعينه، **ولا تُضبط برقمٍ في شاشة.** فلا تعود
-- الإعداداتُ من بابٍ خلفيّ.
--
-- (قرارُ المالك ٢٠٢٦-٠٨-٠٤: «كلُّ المبالغ تُضاف وتُخصم من محفظة الأدمن فقط»
-- — واختار حساب «مدير المنصة».)
--
-- # وما تعنيه «محفظةُ الأدمن»
--
-- **ليست أنّ محافظَ الآخرين لا تتحرّك**: المتجرُ يقبض مستحقَّه والسائقُ أجرَه
-- والمندوبُ عمولتَه، **وكلٌّ في محفظته.** بل أنّ **الطرفَ المقابلَ في كلّ قيدٍ
-- هو المنصة** — فما دفعته دخل منها وما قبضته دخل إليها، **ولا مالَ يظهر أو
-- يختفي بلا طرفين.**

-- **والوسمُ لصاحب الدور الذي اختاره المالك.**
--
-- **ولا يُوسَم بالدور وحدَه**: الأدوارُ يحملها أكثرُ من واحد (حسابا أدمنٍ في
-- هذه القاعدة)، **والخزينةُ واحدة** — فيُقصد الحسابُ بهاتفه.
UPDATE wallets SET is_treasury = false WHERE is_treasury;

UPDATE wallets SET is_treasury = true
 WHERE user_id = (SELECT id FROM users WHERE phone = '+963999000001');

COMMENT ON COLUMN wallets.is_treasury IS
	'خزينةُ المنصة — واحدةٌ لا غير (فهرسٌ فريد)، وهي وحدَها تقبل رصيداً سالباً';
