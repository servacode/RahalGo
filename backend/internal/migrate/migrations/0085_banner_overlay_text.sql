-- **نصُّ اللافتة وزرُّها — فوق الصورة لا مطبوعان فيها.**
--
-- (طلبُ المالك ٢٠٢٦-٠٨-٠٩: «الصفحة الرئيسيّة لازم نقدر نرفع صورة تكون هي
--  عرض الصفحة… وراح يكون فوق الصورة على اليمين نصّ نقدر نبدّله، والنصّ اللي
--  بالصورة مع زرّ حمّله الآن».)
--
-- # ولماذا لا يُطبع النصُّ في الصورة
--
-- **صورةٌ فيها كلامٌ تُصمَّم مرّةً وتُبدَّل بمصمّم**: تبديلُ كلمةٍ يعني ملفّاً
-- جديداً. **والنصُّ حقلٌ يُكتب في ثانية.**
--
-- **وحرفٌ مطبوعٌ في صورةٍ يخفت** حين تُصغَّر للجوّال، **وحرفٌ حقيقيٌّ يبقى
-- حادّاً في كلّ مقاس** — ويقرؤه القارئُ الصوتيُّ ومحرّكُ البحث.
--
-- # وثلاثةُ حقولٍ لا واحد
--
-- `subtitle` سطرٌ تحت العنوان · `cta_label` كلمةُ الزرّ · و`target` القائمُ
-- أصلاً هو وجهتُه. **وزرٌّ بلا كلمةٍ لا يُعرض**: لافتةٌ إخباريّةٌ لا تحتاج
-- زرّاً، **وزرٌّ اسمُه «اضغط» أسوأُ من لا زرّ.**
--
-- **وكلُّها فارغةٌ افتراضاً** — فاللافتاتُ القائمةُ تبقى كما هي بلا لمسة.
ALTER TABLE banners
  ADD COLUMN IF NOT EXISTS subtitle  text NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS cta_label text NOT NULL DEFAULT '';

-- # وأينَ تظهر اللافتة
--
-- (شكوى المالك ٢٠٢٦-٠٨-٠٩: «الموجود بالبانرات يظهر بصفحة التسوّق وليس
--  بالصفحة الرئيسيّة كما طلبي».)
--
-- **الصفحةُ الرئيسيّةُ فارغةٌ بقرارٍ سابق** (٢٠٢٦-٠٨-٠٦)، **واللافتاتُ كلُّها
-- في التسوّق.** وما يريده الآن عرضٌ في الرئيسيّة — **وهو غيرُ لافتات العروض**:
-- ذاك يقول «ما الجديد» وهذا يقول «ما هذه المنصّة».
--
-- **ولا جدولٌ ثانٍ لهما**: بنيةٌ واحدةٌ بصورةٍ ونصٍّ وزرّ، **ونسختان منها
-- تفترقان في الميزة الثالثة.** فيُضاف عمودُ موضعٍ يقول أين تُعرض.
--
-- **والقائمُ يبقى حيث هو** — `shop` افتراضاً، فلا تنتقل لافتةٌ منشورةٌ إلى
-- صفحةٍ لم تُقصد.
ALTER TABLE banners
  ADD COLUMN IF NOT EXISTS placement text NOT NULL DEFAULT 'shop'
    CHECK (placement IN ('home', 'shop'));

