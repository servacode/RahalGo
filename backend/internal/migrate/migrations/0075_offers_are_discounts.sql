-- العروضُ صارت خصوماً وحدَها — **واللافتاتُ في جدولها.**
--
-- # الازدواج
--
-- كان في المنصة **لافتتان**: جدولُ `banners` (قائمٌ منذ البداية، له ترتيبٌ
-- وشاشةٌ في «الأكواد» وموضعٌ في صفحة الزبون)، **ونوعُ `banner` في `offers`
-- الذي أُضيف بالأمس.**
--
-- **وشيءٌ واحدٌ في مكانين يفترق**: تُضاف لافتةٌ في أحدهما فلا تظهر في عرض
-- الآخر، **ويُسأل «لماذا لا تظهر لافتتي؟» ولا جوابَ يُقنع.**
--
-- (شهده المالك ٢٠٢٦-٠٨-٠٥: «لاحظت وجود العروضات والخصومات وأيضاً العروض
-- والأكواد وهي بنفس الهدف — ادمج جميع الميزات بصفحة واحدة».)
--
-- # وأيُّهما يبقى
--
-- **الأقدمُ الأكملُ يبقى**: `banners` له ترتيبُ عرضٍ (`sort_order`) وشاشةٌ
-- مبنيّةٌ وموضعٌ في الصفحة الأولى. **ونوعُ `banner` في `offers` وُلد بالأمس
-- ولم يُستعمل** — فيُطوى.
--
-- **و`offers` تبقى لما لا يفعله غيرُها**: خصمٌ على صنفٍ بعينه يمرّ في لقطة
-- البند فيغيّر ما يُقيَّد في الدفتر.

-- **ولا تُحذف اللافتاتُ المنشأة — تُنزَل.**
--
-- **صفٌّ يُحذف لا يُقرأ في تقريرٍ لاحق**، ومن سأل «ماذا نشرنا في رمضان؟» لم
-- يجد ما يقرؤه. (وهي القاعدةُ نفسُها التي منعت حذفَ العروض.)
UPDATE offers SET active = false WHERE kind = 'banner';

-- **والحقولُ تُترك ولا تُسقَط.**
--
-- إسقاطُ عمودٍ يمحو ما فيه بلا رجعة، **وحقلٌ فارغٌ لا يُقرأ لا يضرّ** — بينما
-- عمودٌ مفقودٌ يُسقط استعلاماً قديماً لم يُحدَّث بعد. **والاحتياطُ هنا أرخصُ
-- من نظافةٍ لا تُرى.**
--
-- **والقيدُ وحدَه يُشدّ**: لا نوعَ جديدٌ بعد اليوم إلّا الخصم.
ALTER TABLE offers DROP CONSTRAINT IF EXISTS offers_kind_check;
ALTER TABLE offers ADD CONSTRAINT offers_kind_check CHECK (kind = 'discount');

-- **وشرطُ الاكتمال يصير مطلقاً** — لم يعد ثمّة نوعٌ يُعفى منه.
ALTER TABLE offers DROP CONSTRAINT IF EXISTS offers_discount_complete;
ALTER TABLE offers ADD CONSTRAINT offers_discount_complete CHECK (
	menu_item_id IS NOT NULL AND
	discount_percent IS NOT NULL AND
	borne_by IS NOT NULL
);
