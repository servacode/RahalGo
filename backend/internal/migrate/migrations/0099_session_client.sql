-- **جلسةٌ لكلّ نوعِ عميل — لا جلسةٌ واحدةٌ للحساب**
-- ══════════════════════════════════════════════════════════════════════
--
-- (قرارُ المالك ٢٠٢٦-٠٨-١١، ضمن خطّة تطبيق أندرويد: «لازم نسمح للحساب
--  بجلستين: متصفّح وتطبيق».)
--
-- # ما كان
--
-- **دخولٌ جديدٌ يُبطل كلَّ الجلسات** (هجرة `0026`). وكان صحيحاً حين كانت
-- المنصّةُ متصفّحاً وحدَه: `session_id` يجمع توكناتِ الدخول الواحد،
-- والتسليمُ بين اللوحات يبقى داخل العائلة، **وأيُّ دخولٍ آخرَ يقتلها.**
--
-- # ولماذا ينكسر مع الهاتف
--
-- **السائقُ يفتح التطبيقَ فيخرج من الويب، ويفتح الويبَ فيخرج من التطبيق.**
-- وهي حلقةٌ لا مخرجَ منها: كلاهما «دخولٌ جديد».
--
-- # ولا يُلغى القيدُ بل يُضيَّق
--
-- **القيدُ ليس شكليّاً — هو ما يمنع مشاركةَ الحسابات**: سائقٌ يعطي رقمَه
-- ورمزَه لآخرَ فيعملان معاً على حسابٍ واحد، **فيقبضان أجرةً على اسمٍ
-- واحدٍ ولا تعرف المنصّةُ من سلّم.**
--
-- **فيصير القيدُ: جلسةٌ واحدةٌ لكلّ نوعِ عميل.** متصفّحٌ واحدٌ وهاتفُ
-- أندرويد واحدٌ وآيفونُ واحد. **وسائقٌ بهاتفين لا يزال ممنوعاً** — وهو
-- ما كان يُحرَس فعلاً.
--
-- **والسقفُ مغلق**: القيمةُ تُقيَّد في الشيفرة بثلاثِ قيمٍ معروفة، **فلا
-- يفتح أحدٌ جلساتٍ بلا حدٍّ بترويسةٍ يخترعها.**
--
-- # والقديمُ كلُّه `web`
--
-- **وهو صحيحٌ تاريخيّاً**: لم يكن ثمّة عميلٌ آخرُ حين كُتبت تلك الصفوف.
ALTER TABLE refresh_tokens
    ADD COLUMN IF NOT EXISTS client text NOT NULL DEFAULT 'web';

-- **والفهرسُ يتبع الاستعلامَ الجديد**: «أبطِل جلساتِ هذا الحساب من هذا
-- النوع» — وبلاه مسحٌ كاملٌ لكلّ توكناتِ الحساب عند كلّ دخول.
CREATE INDEX IF NOT EXISTS refresh_tokens_client_idx
    ON refresh_tokens (user_id, client) WHERE revoked_at IS NULL;
