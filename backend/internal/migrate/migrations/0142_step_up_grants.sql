-- ══════════════════════════════════════════════════════════════════════
--
-- (دورةُ إصلاحٍ ٢٨، ٢٠٢٦-٠٩-٠٨ · بعقد مالكٍ صريح.)
--
-- # ولماذا صفٌّ في القاعدة لا رمزٌ موقَّع
--
-- **العقدُ يقول «مرّةً واحدة»** — **ورمزٌ موقَّعٌ لا يعرف أنّه
-- استُعمل.** **والاستعمالُ حقيقةٌ لا توقيع**، فمكانُها القاعدة.
--
-- # وما لا يُخزَّن
--
-- **لا كلمةٌ ولا بصمتُها ولا رمزُ جلسةٍ ولا حمولةُ طلب** — **وما
-- يُخزَّن بصمةُ ما نوى الفاعلُ فعلَه**، فلا تُقرأ ولا تُعكَس.
--
-- # والحياةُ قصيرة
--
-- **خمسُ دقائقَ حدّاً** — **ولا «وضعُ مالكٍ مرفوع» يدوم.** **إثباتٌ
-- واحدٌ لفعلٍ واحد.**

CREATE TABLE step_up_grants (
    id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),

    -- **مربوطٌ بالفاعل وبجلسته** — ولا يُنقَل.
    user_id     uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    session_id  uuid NOT NULL,

    -- **الفعلُ الكانونيّ** — من معجم الأفعال الحسّاسة.
    action      text NOT NULL,

    -- **الهدفُ للقراءة في التدقيق** — والحدُّ الفعليُّ في `scope_hash`.
    target_type text NOT NULL DEFAULT '',
    target_id   text NOT NULL DEFAULT '',

    -- ══════════════════════════════════════════════════════════════
    -- **بصمةُ ما نوى الفاعلُ فعلَه**
    -- ══════════════════════════════════════════════════════════════
    --
    -- **«الفعلُ والهدف» لا يكفيان** — **من أكّد قيدَ خمسين ألفاً لا
    -- يكون قد أكّد خمسَ مئةِ ألفٍ لنفس الحساب.**
    --
    -- **فتدخل البصمةَ**: الفعلُ (الطريقةُ والمسارُ كاملاً) **وحقولُ
    -- التبديل الجوهريّة** — المبلغُ · الدورُ · القدرةُ · قيمةُ
    -- الإعداد.
    scope_hash  text NOT NULL,

    -- ══════════════════════════════════════════════════════════════
    -- **وحقبةُ الاعتماد** — `sessions_revoked_at` وقتَ الإصدار
    -- ══════════════════════════════════════════════════════════════
    --
    -- **وهي الثابتُ القائمُ من دورتَي ١٨ و١٩** — **ولا يُخترَع نظامُ
    -- إصداراتِ اعتمادٍ ثانٍ.**
    --
    -- **فتبديلُ الكلمة (بالنفس أو بالإدارة) يدمغ الحقبة** — **وإثباتٌ
    -- وُلد قبلها يموت وإن لم يُستعمَل**، **ولو صدر في سباقٍ مع
    -- التبديل**: **المقارنةُ لحظةَ الاستعمال هي الحكم.**
    --
    -- **و`NULL` حالٌ مشروعة** — حسابٌ لم تُبطَل جلساتُه قطّ.
    epoch       timestamptz,

    created_at  timestamptz NOT NULL DEFAULT now(),
    expires_at  timestamptz NOT NULL,
    consumed_at timestamptz
);

-- **والقراءةُ دائماً بالفاعل** — ولا تُقرأ الجدولُ كلُّها.
CREATE INDEX step_up_grants_user_idx ON step_up_grants (user_id, action);

-- **والمنتهيةُ تُكنَس** — ولا يبقى إثباتٌ ميّتٌ إلى الأبد.
CREATE INDEX step_up_grants_expiry_idx ON step_up_grants (expires_at)
    WHERE consumed_at IS NULL;
