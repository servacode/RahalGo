-- دعوةُ الزبون لزبون — **ومن جلب يُكافأ، والمنصةُ تدفع.**
--
-- # المسألة
--
-- المنصةُ تُعرَف بالكلام: يذكرها زبونٌ لجاره فيُنزّلها. **ولا شيءَ يقيس ذلك
-- ولا يكافئه** — فيبقى الترويجُ صدفةً، والإعلانُ المدفوعُ وحدَه ما يُشترى.
--
-- **ومن جلب ثلاثةَ زبائنَ أنفعُ من لافتةٍ في الشارع** — ولم يكن له عندنا شيء.
--
-- (قرارُ المالك ٢٠٢٦-٠٨-٠٥: «رابطُ دعوة... أوّلُ دعوةٍ يربح مبلغاً، والثانية
-- والثالثة، وبعدها مبلغٌ ثابت... والمنصةُ تتحمّل التكاليف من حساب الأدمن».)
--
-- # ولماذا سُلَّمٌ ثمّ ثابت
--
-- **الأولى أصعبُها**: من لم يجرّب لا يعرف أنّها تنفع. **ثمّ تسهل** — فيُدفع
-- للأولى أكثر، ويقلّ حتى يستقرّ. **وثابتٌ من أوّلها يُغري القليلين، ومرتفعٌ
-- دائماً يستنزف.**
--
-- # ومتى يُصرف
--
-- **لا عند التسجيل — عند أوّل طلبٍ يُسلَّم.**
--
-- **ورقمُ هاتفٍ يُسجَّل لا يساوي شيئاً**: تُفتح مئةُ حسابٍ في ساعةٍ بأرقامٍ
-- تُشترى، **فتُدفع مئةُ مكافأةٍ على مئة حسابٍ لن تطلب شيئاً أبداً.** والطلبُ
-- المُسلَّم زبونٌ حقيقيّ.

CREATE TABLE IF NOT EXISTS referrals (
	-- invitee المدعوُّ — **مفتاحٌ لأنّه يُدعى مرّةً واحدة.**
	--
	-- **ولا يُدعى من دُعي**: من فتح حساباً بدعوةِ فلانٍ لا يُنسب لغيره،
	-- **وحسابان يتبادلان الدعوةَ يطبعان مالاً من العدم.**
	invitee_id uuid PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
	inviter_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	-- rank ترتيبُ هذه الدعوة عند الداعي — **يُثبَّت لحظةَ النسب لا لحظةَ
	-- الصرف**: من دعا ثلاثةً في يومٍ ثمّ طلبوا بترتيبٍ مقلوبٍ لا تنقلب
	-- مكافآتُه. **والسُّلَّمُ يُقرأ من ترتيب الدعوة لا من ترتيب الطلب.**
	rank int NOT NULL CHECK (rank > 0),
	created_at timestamptz NOT NULL DEFAULT now(),
	-- rewarded_at متى صُرفت — **وفارغُها «لم يطلب بعد».**
	rewarded_at timestamptz,
	reward_amount bigint NOT NULL DEFAULT 0 CHECK (reward_amount >= 0)
);

CREATE INDEX IF NOT EXISTS referrals_inviter_idx
	ON referrals (inviter_id, created_at);

-- **ورمزُ الدعوة عمودٌ قائمٌ في `users`** (`invite_code`) — كان للمندوبين.
--
-- **ولا يُنشأ عمودٌ ثانٍ لمعنًى واحد**: «رمزٌ يُعرَف به صاحبُه» هو هو، سواءٌ
-- جلب متجراً أم زبوناً. **وعمودان يعنيان توليدين وتحقّقين وفهرسين** — ويُسأل
-- يوماً أيُّهما يُقرأ.
--
-- **ويُولَّد عند الطلب لا للجميع مسبقاً**: أكثرُ الزبائن لا يدعو أحداً،
-- **ورمزٌ لكلّ حسابٍ ملءُ جدولٍ بما لا يُستعمل.**
CREATE UNIQUE INDEX IF NOT EXISTS users_invite_code_uniq
	ON users (invite_code) WHERE invite_code IS NOT NULL AND invite_code <> '';
