-- **ولا هويّةَ فارغة** (`SI`، ٢٠٢٦-٠٩-١٤)
-- ══════════════════════════════════════════════════════════════════════
--
-- **و`0153` منعت العدم ولم تمنع الفراغ** — **و`NOT NULL` تقبل النصَّ الفارغ.**
--
-- **وصفٌّ هويّتُه فارغةٌ أسوأُ من صفٍّ لا وجودَ له**: **لا يُدمَج فيه
-- جديدٌ فيتكاثر**، **ولا يُلغى فيُحبَس صاحبُه في تسويقٍ لا يخرج منه**،
-- **ولا يُطابقه سؤالُ «من يُخبَر يومَ تُطلَق هذه المدينة؟»** — **فيبقى
-- يُعَدّ في الكثافة وصاحبُه لا يُخبَر أبداً.**
--
-- **والبناءُ في الشيفرة لا يُخرج فارغاً اليوم** — **وهذا الحدُّ لمن
-- يعدّله غداً**، **ولمن يكتب بالسطر مباشرةً.** **وطبقتان لا واحدة.**
--
-- **والبياضُ فراغٌ أيضاً** — **ومسافةٌ وحدَها هويّةٌ لا تُقرأ ولا تُطابَق.**
--
-- # ولمَ لا `btrim`
--
-- **و`btrim` تقلّم الفراغاتِ وحدَها لا الجدولةَ ولا السطرَ الجديد** —
-- **فمرّت جدولةٌ وسطرٌ جديدٌ من تحتها.** (قِيس: `SI-15` سقط.)
--
-- **والشرطُ يُقلَب**: **لا «ليست فارغةً بعد التقليم»** — **بل «فيها
-- محرفٌ واحدٌ ليس بياضاً».** **وصنفُ `[:space:]` يعمّ البياضَ كلَّه.**

ALTER TABLE coverage_requests
    ADD CONSTRAINT coverage_requests_target_key_not_blank
    CHECK (target_key ~ '[^[:space:]]');
