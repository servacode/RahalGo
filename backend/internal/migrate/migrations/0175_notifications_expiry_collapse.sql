--
-- **فصار صفّاً بنوعٍ لا يُعرض في الصندوق** (`order_offer`)، **وله أجلٌ**: عرضٌ
-- انقضت مهلتُه لا يُسلَّم بعدها (`expires_at`)، **ومفتاحُ طيٍّ** (`collapse_key`)
-- فلا يتراكم عرضان لطلبٍ واحدٍ في شريط الهاتف.
ALTER TABLE notifications ADD COLUMN IF NOT EXISTS expires_at timestamptz;
ALTER TABLE notifications ADD COLUMN IF NOT EXISTS collapse_key text NOT NULL DEFAULT '';
