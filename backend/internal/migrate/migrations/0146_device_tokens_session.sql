-- **ومِلكيّةُ وجهةِ الدفع عائلةُ جلسةٍ لا رمزٌ يُقرأ من الجهاز** — `D12`
-- ══════════════════════════════════════════════════════════════════════
--
-- (دورةُ إصلاحٍ ٦٠ · بقرار المالك.)
--
-- # الثغرةُ التي بقيت من دورةِ ٥٩
--
-- **الخروجُ صار يحذف وجهةَ الدفع** — **لكنّه كان يحذفها بالرمز الذي
-- يرسله الجهاز.** **ورمزُ `FCM` قد لا يُقرأ ساعةَ الخروج**: خدماتُ
-- جوجل معطّلة، أو الشبكةُ منقطعة، أو المهلةُ انتهت.
--
-- **فيمضي الخروجُ ناجحاً وتبقى الوجهةُ حيّة** — **ولا يُنهيها إلّا
-- مرشّحُ القِدَم بعد شهرين.**
--
-- **وخروجٌ نجح لا يحتمل «سيُنظَّف لاحقاً»**: **صاحبُ الهاتف يظنّ أنّه
-- خرج، وإشعاراتُ حسابه تصل بعد خروجه.**
--
-- # ولماذا عائلةُ الجلسة
--
-- **الخادمُ يعرف العائلةَ في الموضعين بلا أن يسأل الجهاز**:
--
--     التسجيل: رمزُ الوصول يحمل `sid`
--     الخروج:  رمزُ التجديد يردّ `session_id`
--
-- **فالسلطةُ عنده أصلاً** — **وكانت مُهمَلة.**
--
-- **وليست هويّةَ جهازٍ دائمة**: **لا اسمَ جهازٍ ولا سجلَّ أجهزةٍ ولا
-- «أجهزةٌ موثوقة»** — **إنّما مِلكيّةٌ في الخادم تكفي لتنظيف ما يخصّ
-- هذه الجلسة.**
--
-- # والرمزُ يبقى هو العنوان
--
-- **`token` ما زال المفتاحَ الفريد** — **وهو عنوانُ التسليم عند
-- `FCM`.** **و`session_id` مِلكيّةٌ لا عنوان.**
--
-- # ولا يُختلَق مالكٌ لصفٍّ قديم
--
-- **الصفوفُ القائمةُ تبقى `NULL`** — **ولا تُحذف ولا يُنسَب إليها
-- عائلةٌ لم تُسجّلها.** **ويحكمها ما كان يحكمها**: مرشّحُ القِدَم،
-- **ورمزُ الجهاز حين يرسله عميلٌ قديم.**
--
-- **وأوّلُ تسجيلٍ موثَّقٍ يكتب مالكَها** — فتنتقل إلى العقد الجديد
-- بلا هجرةِ بيانات.
--
-- # ولا مفتاحَ أجنبيّ
--
-- **`refresh_tokens.session_id` ليس فريداً** — **العائلةُ صفوفٌ لا
-- صفّ**، فلا يصلح مرجعاً. **والتنظيفُ يقع في معاملة الخروج نفسِها،
-- فلا يُترك صفٌّ يتيمٌ لجلسةٍ ماتت.**
ALTER TABLE device_tokens
    ADD COLUMN IF NOT EXISTS session_id uuid;

-- **وحذفُ الخروج يمرّ به** — `DELETE ... WHERE session_id = $1`:
-- **بلا فهرسٍ مسحٌ كاملٌ للجدول عند كلّ خروج.**
CREATE INDEX IF NOT EXISTS device_tokens_session_idx
    ON device_tokens (session_id);
