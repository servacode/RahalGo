-- توثيق رقم واتساب — إثبات أن للحساب قناةَ تواصل حيّة يملكها صاحبه فعلاً.
--
-- رقم الدخول قد لا يكون رقم واتساب: المندوب قد يدخل بكلمة مرور أنشأتها الإدارة
-- فلا يثبت شيئاً عن رقمه، وقد يكون رقمه بلا واتساب أصلاً. والمندوب يعمل عبر
-- واتساب حصراً: يرسل رابطه وباركوده للمتاجر، ويصله المتجر ليسأل. فرقمٌ غير
-- موثّق يعني عمولةً منسوبة لمن لا يُوصل إليه.
--
-- التوثيق = رمزٌ يُرسل عبر واتساب إلى الرقم ويُدخله صاحبه: يثبت أن الرقم
-- يملك واتساب، وأن صاحب الحساب يملك الرقم.
ALTER TABLE users ADD COLUMN whatsapp_phone citext;
ALTER TABLE users ADD COLUMN whatsapp_verified_at timestamptz;

-- بحثٌ سريع عن الموثَّقين (تقارير الإدارة ولوحة المناديب)
CREATE INDEX users_whatsapp_verified_idx ON users (whatsapp_verified_at)
    WHERE whatsapp_verified_at IS NOT NULL;
