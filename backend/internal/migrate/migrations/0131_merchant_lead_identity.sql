-- ══════════════════════════════════════════════════════════════════════
-- **مرشَّحٌ واحدٌ لا يصير متجرين**
-- ══════════════════════════════════════════════════════════════════════
--
-- (`XG-18` · `D25` · `C-03` — دورةُ إصلاحٍ ٥، ٢٠٢٦-٠٩-٠٦.)
--
-- # ما أُثبت
--
-- **نداءان متوازيان على المرشَّح نفسِه ⇒ متجران، كلاهما منسوبٌ
-- للمندوب** — **ستُّ جولاتٍ من ست.**
--
-- **وكانت الحمايةُ عرَضيّةً لا مقصودة**: النداءان يُنشئان حسابَ صاحبِ
-- المتجر فيصطدمان بتفرّد `users.phone` فيسقط أحدُهما. **ومن كان له
-- حسابٌ من قبلُ لا اصطدامَ فيه** — **وهي الحالُ الشائعة**: صاحبُ
-- المتجر زبونٌ عندنا أصلاً.
--
-- # والهويّةُ الكانونيّةُ مقيسةٌ لا مُخترَعة
--
-- **ليست الهاتفَ ولا المالك**: **متجرٌ ثانٍ لصاحبٍ واحدٍ مسموحٌ عمداً**
-- — «فالمتجر قد يكون فرعاً جديداً بحقّ» (`handlePublicJoin`)، **وإنّما
-- يسقط عنه إسنادُ المندوب.** **فقيدٌ على الهاتف يمنع فرعاً مشروعاً.**
--
-- **وإنّما هي المرشَّح**: **طلبُ انضمامٍ واحدٌ يُنتج متجراً واحداً على
-- الأكثر** — وهو ما يقوله حارسُ `convertLead` نفسُه، **وما يوجبه
-- `C-03`**:
--
--     ONE REAL MERCHANT IDENTITY MUST NOT BECOME
--     TWO PAYABLE MERCHANT/REP RELATIONSHIPS
--
-- # ولماذا عمودٌ في `merchants` لا في `merchant_leads`
--
-- **`merchant_leads.merchant_id` قائمٌ ولا يمنع شيئاً**: النداءان
-- يُنشئان متجرَين ثمّ يكتب كلٌّ منهما معرّفَه في المرشَّح، **فآخرُهما
-- يغلب والأوّلُ يبقى يتيماً منسوباً للمندوب.**
--
-- **والاتّجاهُ المعكوسُ هو الذي يُقيَّد**: **المتجرُ يقول من أيّ مرشَّحٍ
-- جاء**، وفريدٌ عليه — **فالثاني يُرفض في لحظة إدخاله لا بعدها.**

ALTER TABLE merchants
    ADD COLUMN IF NOT EXISTS lead_id uuid
        REFERENCES merchant_leads (id) ON DELETE SET NULL;

-- ══════════════════════════════════════════════════════════════════════
-- **والتركةُ تُفحَص قبل أن تُقيَّد**
-- ══════════════════════════════════════════════════════════════════════
--
-- **ولا يُدمَج ولا يُحذَف شيءٌ تلقائيّاً**: **متجران حقيقيّان لمرشَّحٍ
-- واحدٍ حالٌ تخصّ مالاً وإسناداً** — **ومن دمجها بيد آلةٍ محا نصفَ
-- الحقيقة.** **فتتوقّف الهجرةُ وتُسمّي الصفوف.**
DO $$
DECLARE
    مكرَّر int;
BEGIN
    SELECT count(*) INTO مكرَّر FROM (
        SELECT merchant_id FROM merchant_leads
         WHERE merchant_id IS NOT NULL
         GROUP BY merchant_id HAVING count(*) > 1) x;
    IF مكرَّر > 0 THEN
        RAISE EXCEPTION
            'XG-18: % متجراً يشير إليه أكثرُ من مرشَّح — تُراجَع يدوياً قبل القيد',
            مكرَّر;
    END IF;
END $$;

-- **والنسبُ يُملأ ممّا هو قائم** — `merchant_leads.merchant_id` هو
-- السجلُّ الوحيدُ لِما تحوّل، **ولا يُختلق نسبٌ لمتجرٍ أُنشئ من لوحة
-- الإدارة مباشرةً**: يبقى `lead_id` فارغاً وهو الصواب.
UPDATE merchants m
   SET lead_id = l.id
  FROM merchant_leads l
 WHERE l.merchant_id = m.id
   AND m.lead_id IS NULL;

-- ══════════════════════════════════════════════════════════════════════
-- **والقيدُ في المخطَّط لا في الشيفرة**
-- ══════════════════════════════════════════════════════════════════════
--
-- **فحصٌ ثمّ إدخالٌ يترك بينهما فجوة** — **وهي الفجوةُ التي أنتجت
-- متجرَين في ستّ جولاتٍ من ست.** **والفهرسُ الفريدُ لا فجوةَ فيه**:
-- **الثاني يُرفض ولو سقط كلُّ حارسٍ في الشيفرة.**
--
-- **وجزئيٌّ**: **متاجرُ لوحة الإدارة بلا مرشَّحٍ وهي كثيرة**، ولا
-- يجمعها `NULL` في قيدٍ واحد.
CREATE UNIQUE INDEX IF NOT EXISTS merchants_lead_uq
    ON merchants (lead_id) WHERE lead_id IS NOT NULL;
