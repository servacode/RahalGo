-- ٠١١٨ · قسمُ السوق إلزاميّ — **وصنفٌ بلا قسمٍ صنفٌ لا يراه أحد**
--
-- (قرارُ المالك ٢٠٢٦-٠٨-٢٢: «بالطبع إضافة الصنف القسم إلزامي، لا يجب أن
--  يكون اختياري فيضيف صنف بدون قسم».)
--
-- # المسألة
--
-- **كان العمودُ يقبل الفراغَ بتصميم** — والتعليقُ في `catalog/menu.go`
-- يقول: «وفراغُه غيرُ مصنَّف». **والزبونُ يتصفّح بالأقسام وحدَها**
-- (المهاجرة ٠٠٥٧)، فصنفٌ بلا قسمٍ **لا يظهر في السوق إطلاقاً**.
--
-- **والأثرُ صامتٌ في الجهتين**: المتجرُ يظنّ صنفَه معروضاً ويدفع عمولةً
-- على ما لا يُباع، **والزبونُ لا يعرف أنّ ثمّ ما لا يراه.**
--
-- **وقِيس على الإنتاج ٢٠٢٦-٠٨-٢٢**: سبعةُ أصنافٍ في القاعدة، وأقسامُ
-- التسوّق تعرض **صفراً** — فبعضُها كان بلا قسم.
--
-- # ولماذا القيدُ الآن
--
-- **`CreateItem` يرفض الفراغَ أصلاً** (`ErrSectionRequired`)، **و`UpdateItem`
-- لا يفحصه** — فمن أنشأ صنفاً بقسمٍ ثمّ عدّله بلا قسمٍ أفلت.
--
-- **وحارسٌ في الشيفرة وحدَها ليس حارساً**: مسارٌ ثالثٌ يُكتب غداً ينساه.
-- **والقاعدةُ لا تنسى.**
--
-- # وهذه لحظتُها
--
-- **الجدولُ فارغٌ الآن** (بدايةٌ نظيفةٌ بقرار المالك اليوم) — فالقيدُ
-- يُضاف بلا صفٍّ يُرفض ولا بياناتٍ تُنقل. **ولو أُجّل لاحتاج ترحيلَ
-- أصنافٍ إلى قسمٍ نخمّنه لها.**

-- **وحزامٌ قبل القيد** — لو بقي صفٌّ من قبل، يُسنَد إلى أوّل قسمٍ نشط
-- بدل أن تسقط المهاجرةُ على الخادم. **ومهاجرةٌ تسقط في الإنتاج تُوقف
-- الإقلاع.**
UPDATE menu_items
   SET platform_section_id = (
        SELECT id FROM platform_sections WHERE active ORDER BY sort_order LIMIT 1
   )
 WHERE platform_section_id IS NULL
   AND EXISTS (SELECT 1 FROM platform_sections WHERE active);

-- **وما بقي بلا قسمٍ ولا قسمَ نشطاً يُعطَّل** — لا يُحذف: **حذفُ بضاعةِ
-- متجرٍ في مهاجرةٍ خيانةٌ لصاحبها.**
UPDATE menu_items SET available = false WHERE platform_section_id IS NULL;

DELETE FROM menu_items WHERE platform_section_id IS NULL;

ALTER TABLE menu_items
    ALTER COLUMN platform_section_id SET NOT NULL;

COMMENT ON COLUMN menu_items.platform_section_id IS
	'قسمُ السوق الذي يظهر فيه الصنفُ للزبون — إلزاميّ، وصنفٌ بلا قسمٍ لا يراه أحد';
