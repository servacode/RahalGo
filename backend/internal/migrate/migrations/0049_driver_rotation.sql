-- **نظاما توزيع الطلبات على السائقين** — بقرار المالك (٢٠٢٦-٠٨-٠١).
--
-- # النظامان
--
--   * **الأسرع التقاطاً** (القائم): الطلبُ معروضٌ للجميع ومن سبق أخذ. سريعٌ
--     في ساعات الذروة، **ويُجوّع البطيء**: سائقٌ بهاتفٍ قديم أو حيٍّ ضعيف
--     الشبكة لا يصل قبل غيره أبداً.
--
--   * **بالترتيب**: يُعرض على سائقٍ واحدٍ في دوره، فإن لم يأخذه في مهلته
--     انتقل الدورُ إلى التالي. **عدلٌ في التوزيع وثمنُه ثوانٍ.**
--
-- # ودورٌ يُقاس بالانتظار لا بقائمةٍ ثابتة
--
-- قائمةٌ ثابتة تعني أن من في أوّلها يُعرض عليه كلُّ شيء، ومن دخل الدوام متأخراً
-- ينتظر دورةً كاملة. **والأعدلُ: من طال انتظارُه منذ آخر طلبٍ أُسند إليه.**
--
-- وهو يُصحّح نفسه: من أخذ طلباً هبط إلى آخر الصفّ، ومن رُفض عرضُه ثلاثاً بقي
-- في أوّله. **ولا يحتاج أحدٌ أن يمسك دفتراً.**
ALTER TABLE users ADD COLUMN last_assigned_at timestamptz;

-- # والعرضُ على الطلب لا في جدولٍ ثانٍ
--
-- **عرضٌ واحدٌ حيٌّ لكل طلب** — لا تاريخَ عروضٍ يُحفظ. وجدولٌ ثانٍ يعني صفّاً
-- يتيماً كلَّما أُلغي طلبٌ في لحظة انتقال الدور، **وسؤالاً ثانياً عن أيُّ
-- العروض هو الحيّ الآن.**
--
-- والتاريخُ حين يُطلب يُقرأ من `order_events` — وهو مكانُه.
ALTER TABLE orders ADD COLUMN offered_driver_id uuid REFERENCES users (id);
ALTER TABLE orders ADD COLUMN offer_expires_at  timestamptz;
-- **ومن مرّ عليه الدورُ لا يُعاد إليه في هذا الطلب** — وإلّا دار العرضُ على
-- الأوّل أبداً: هو أطولُ انتظاراً وسيبقى كذلك ما دام لم يأخذ، **فيدور العرضُ
-- بين اثنين حتى ينتهي الطعام.**
ALTER TABLE orders ADD COLUMN offer_passed uuid[] NOT NULL DEFAULT '{}';

COMMENT ON COLUMN orders.offered_driver_id IS
    'صاحبُ الدور الآن في نمط «بالترتيب» — فارغٌ يعني معروضٌ للجميع';

-- الراصدُ يمرّ على العروض المنتهية كلَّ دورة: فهرسٌ جزئيّ على ما لم ينتهِ بعد.
CREATE INDEX orders_offer_expiry_idx ON orders (offer_expires_at)
    WHERE offer_expires_at IS NOT NULL;

-- # المفاتيح
--
-- **والافتراضيّ `queue`**: هو ما تعمل به المنصةُ اليوم، **وتبديلُ نظامِ توزيعٍ
-- بترحيلٍ صامت يفاجئ سائقين في منتصف نوبتهم.**
INSERT INTO app_settings (key, value) VALUES
    ('drivers.assignment_mode',  '"queue"'::jsonb),
    ('drivers.offer_timeout_sec', '45'::jsonb)
ON CONFLICT (key) DO NOTHING;
