-- ══════════════════════════════════════════════════════════════════════
--
-- قائمةُ مشروبات المتجر كانت تُنسخ إلى كلّ الأصناف بلا استثناء (هجرة ٠٤٥٨).
-- **صار لكلّ صنفٍ مفتاح**: مطفأٌ ⇒ لا تُنسخ إليه ولا يراها الزبونُ فيه.
--
--   menu_items.drinks_off   true: الصنفُ بلا مشروبات المتجر
--
-- **والافتراضُ `false`** — فكلُّ صنفٍ قائمٍ يبقى كما هو، والنسخةُ القديمة من
-- التطبيق لا ترسل الحقلَ فلا يتغيّر شيء.
ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS drinks_off boolean NOT NULL DEFAULT false;
