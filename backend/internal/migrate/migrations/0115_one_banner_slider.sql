-- **سلايدرٌ واحدٌ للمنصّة — والتطبيقُ يقرأ لافتاتِ الرئيسيّة**
-- ══════════════════════════════════════════════════════════════════════
--
-- (قرارُ المالك ٢٠٢٦-٠٨-١٨: «نعم كان قراري أن نفصلهنّ، والآن أريد حذفَ
--  سلايدر التسوّق وربطَ التطبيق بسلايدر الرئيسيّة».)
--
-- # ولماذا رجع عن قراره
--
-- **فصلَهما ٢٠٢٦-٠٨-١٧** («بانرات صفحة التسوّق مختلفة عن الرئيسيّة»).
-- **ثمّ قاسه بالعمل**: يرفع الصورةَ مرّتين ويحذفها مرّتين، **ولافتةٌ
-- تُحدَّث في موضعٍ وتُنسى في آخرَ تُقرأ عرضاً منتهياً في نصف المنصّة.**
--
-- # ولا تُحذف صورُه
--
-- **الموضعُ يُلغى ولا يُلغى ما رُفع**: لافتتاه في «التسوّق» تنتقلان إلى
-- «الرئيسيّة» فتظهران معها. **ومن أراد حذفَهما حذفهما من اللوحة بضغطة**
-- — **وصورةٌ تُمحى في هجرةٍ لا تُستردّ.**
--
-- # والقيدُ يُضيَّق فلا يعود
--
-- **بابٌ يُغلق في الشاشة ويبقى مفتوحاً في القاعدة يُفتح غدا** — بنداءٍ
-- مباشرٍ أو بشيفرةٍ تُكتب وقد نُسي السبب. **والقيدُ يقول لا.**

UPDATE banners SET placement = 'home' WHERE placement = 'shop';

ALTER TABLE banners DROP CONSTRAINT IF EXISTS banners_placement_check;

ALTER TABLE banners
    ADD CONSTRAINT banners_placement_check CHECK (placement IN ('home'));

ALTER TABLE banners ALTER COLUMN placement SET DEFAULT 'home';

-- **ومفتاحا دورانِ لافتة التسوّق يُمحيان** — لا أحدَ يقرؤهما بعد اليوم،
-- **ومفتاحٌ في اللوحة لا أثرَ له يُضبط ويُنتظر أثرُه.**
DELETE FROM app_settings WHERE key IN ('shop.banner_auto', 'shop.banner_seconds');
