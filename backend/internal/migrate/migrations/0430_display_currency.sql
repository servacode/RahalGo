-- «الزبون يشوف السعر بدولار والسوري ويدفع بالسوري قيمة الدولار».
--   SYP  الأسعارُ بالليرة كما كانت
--   USD  يُعرض كلُّ صنفٍ بالدولار (محسوباً من الليرة بسعر صرف المتجر) **وتحته
--        الليرة** — والسلّةُ والدفعُ والدفترُ بالليرة لا يمسّها شيء.
ALTER TABLE merchants ADD COLUMN IF NOT EXISTS display_currency text NOT NULL DEFAULT 'SYP'
    CHECK (display_currency IN ('SYP', 'USD'));
