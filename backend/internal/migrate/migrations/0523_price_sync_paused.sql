-- ٠٥٢٣ · «إيقاف» المزامنة صار إيقاف مؤقّت (قرار المالك ٢٠٢٦-١١-٠٧)
--
-- «إذا أعطى إيقاف ما في داعي لإعادة التحميل — بينزل مرّة وحدة بس».
-- كان «إيقاف البرنامج» يشيل البرنامج من الكمبيوتر (price_sync_stop) ولازم ينحمّل من جديد.
-- هلّق: price_sync_paused = البرنامج باقي على الكمبيوتر وبيسأل كل دقيقة،
-- بس ما بيقرأ الأمين ولا بيرفع شي، و«شغّل المزامنة» بترجّعو بالسؤال الجاي.
-- والحذف من الكمبيوتر ضلّ زرّ لحالو (price_sync_stop) متل قبل.

ALTER TABLE merchants ADD COLUMN IF NOT EXISTS price_sync_paused boolean NOT NULL DEFAULT false;
