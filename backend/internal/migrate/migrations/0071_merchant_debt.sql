-- دَينُ المتجر — ما استُرجع منه ولم يجده في محفظته.
--
-- # المسألة
--
-- المتجرُ يقبض عند خروج البضاعة من يده، لا عند وصولها. فإن تعذّر التسليمُ
-- ورُدّت إليه بضاعتُه، **يُسترجع ما قبض** — أخذ بضاعتَه فلا يأخذ ثمنَها معها.
--
-- **وقد يكون سحب المالَ قبل ذلك.** ومحفظتُه لا تنزل تحت الصفر:
--
--     CHECK (balance >= 0 OR is_treasury)
--
-- **فيُرفض الاسترجاعُ برمّته** — لا جزئياً، بل كلّه — وتبقى البضاعةُ محسومةً
-- في يده وثمنُها في جيبه، **بلا أثرٍ في أيّ دفتر.**
--
-- # وقرارُ المالك (٢٠٢٦-٠٨-٠٤)
--
-- «يُخصم ما وُجد، والباقي يُقيَّد ديناً على المتجر يُستوفى من أوّل مستحقٍّ
-- قادم». **فلا زرٌّ يُرفض، ولا مالَ يضيع.**
--
-- # ولماذا عمودٌ على المتجر لا على المحفظة
--
-- المحفظةُ لصاحب الحساب، **وقد يملك متجرين**: دَينُ أحدهما ليس دَينَ الآخر،
-- ولا يُقاصّ من مستحقّ غيره. **والبضاعةُ رُدّت إلى متجرٍ بعينه.**

ALTER TABLE merchants
	ADD COLUMN IF NOT EXISTS debt bigint NOT NULL DEFAULT 0;

-- **ولا دَينَ سالب**: سالبُه يعني أنّ المنصةَ مدينةٌ له، وذاك موضعُه المحفظةُ
-- لا هذا العمود — **وعمودٌ يحمل معنيين يُقرأ خطأً يوماً.**
ALTER TABLE merchants
	DROP CONSTRAINT IF EXISTS merchants_debt_not_negative;
ALTER TABLE merchants
	ADD CONSTRAINT merchants_debt_not_negative CHECK (debt >= 0);
