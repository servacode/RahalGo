-- ══════════════════════════════════════════════════════════════════════
-- **مصالحةُ أقلِّ صلاحيّة**
-- ══════════════════════════════════════════════════════════════════════
--
-- (`ADG-2` · `AQ-1` — دورةُ إصلاحٍ ٢٦، ٢٠٢٦-٠٩-٠٨ · بطلب المالك.)
--
-- **«يقرأ فقط» ليست «أقلَّ صلاحيّة».** **ودورةُ ٢٥ منحت أدواراً قراءاتٍ
-- عريضةً لأنّها قراءات** — **وقياسُ ما تكشفه أظهر خلافَ ذلك.**

-- ── التحليلات — تقاريرُ لا سجلّاتٌ خام ──────────────────────────────
--
-- **`orders.read`** تفتح محادثاتِ الطلبات ورسائلَها · **`users.read`**
-- تفتح دليلَ الحسابات وتصديرَه وعناوينَ الناس · **`finance.read`**
-- تفتح محافظَ الأفراد وتصديرَ الدفتر.
--
-- **ولا واحدةَ منها تقريرٌ** — **والتقاريرُ في `analytics.read`
-- وحدَها** (`/stats` · `/reports`).
DELETE FROM role_capabilities
 WHERE role_code = 'analytics'
   AND capability_code IN ('orders.read', 'users.read', 'finance.read');

-- ── مراجعُ السائقين — يقرأ ولا يُنهي وردية ──────────────────────────
--
-- **`drivers.manage` تجمع القراءةَ والتشغيل** — **فمن وُظّف للتوثيق
-- ملك `POST /drivers/{id}/end-shift`**، **وإخراجُ سائقٍ من عمله ليس
-- توثيقاً.**
--
-- **ولا `drivers.verify`**: **لا مسارَ توثيقٍ للسائق في الخادم اليوم**
-- — **وقدرةٌ بلا فعلٍ تُقرأ عقداً وهي أمنية.** **والانقسامُ المقيس هو
-- قراءةٌ/تشغيل**، وبند الترحيل قائم.
DELETE FROM role_capabilities
 WHERE role_code = 'driver_verification' AND capability_code = 'drivers.manage';

-- ── مراجعُ المتاجر — لا طلباتٍ ولا دليلَ حسابات ─────────────────────
--
-- **مساراتُه أربعةٌ**: حالةُ مرشَّحٍ · مراجعةُ صنف · المعلَّقُ · القائمة.
-- **ولا واحدٌ منها يقرأ طلباً.**
--
-- **و`GET /leads` تُخرج اسمَ المندوب وكودَه في صفّها** — **فلا يحتاج
-- دليلَ الحسابات ليعرف من رشّح.**
DELETE FROM role_capabilities
 WHERE role_code = 'merchant_verification'
   AND capability_code IN ('orders.read', 'users.read');

-- ── التسويق — محتوىً لا جغرافيا ─────────────────────────────────────
--
-- **`settings.general.manage` تحكم المناطقَ والمحافظاتِ والنواحي
-- ومضلَّعاتِ التغطية والفروع** — **ومن بدّل مضلَّعاً بدّل من تصله
-- المنصّةُ أصلاً.** **وذاك قرارُ عملٍ لا حملةٌ إعلانيّة.**
DELETE FROM role_capabilities
 WHERE role_code = 'marketing_content'
   AND capability_code = 'settings.general.manage';

-- ══════════════════════════════════════════════════════════════════════
-- **و`drivers.read` تُسنَد لمن كان يبلغ سجلَّ السائقين**
-- ══════════════════════════════════════════════════════════════════════
--
-- **وإلّا كسر الانقسامُ عملاً قائماً** — `GET /drivers` و
-- `GET /ops-map/drivers` انتقلا إليها.
INSERT INTO role_capabilities (role_code, capability_code)
SELECT r, 'drivers.read' FROM unnest(ARRAY[
    'owner_super_admin', 'operations', 'driver_verification',
    'admin', 'ops'
]) AS r ON CONFLICT DO NOTHING;
