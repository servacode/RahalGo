-- **مستلمو «لدي توصيلة» المحفوظون — وما أخفاه المتجرُ منهم** (قرارُ المالك ٢٠٢٦-١١-٠٥)
-- ══════════════════════════════════════════════════════════════════════
--
-- «بنقطة المتجر وقت يبعث طلب لزبون لازم يصير في مثل التخزين لمعلوماتهم بحيث اذا رجع
-- بعث مره ثانية بمجرد ما يكتب اسم الزبون يتعبى باقي المعلومات بشكل تلقائي»
--
-- **والقائمةُ لا جدولَ لها** — تُقرأ من توصيلات المتجر نفسِها (`orders` من نوع
-- `merchant_delivery`): الاسمُ والرقمُ والعنوانُ والنقطةُ من آخر توصيلةٍ لكلّ رقم.
-- **فلا نسخةَ ثانيةً تشيخ عن الطلبات.**
--
-- **وهذا الجدولُ لزرّ «شيلو من القائمة» وحدَه** — مستلِمٌ كُتب غلط. **ويرجع وحدَه** إن
-- بعث له المتجرُ توصيلةً بعد إخفائه (`hidden_at` أقدمُ من آخر توصيلة).
-- والرقمُ بصيغته المخزَّنة (`+9639XXXXXXXX`) — من `identity.NormalizePhone`.
CREATE TABLE IF NOT EXISTS merchant_recipients_hidden (
    merchant_id uuid        NOT NULL REFERENCES merchants (id) ON DELETE CASCADE,
    phone_norm  text        NOT NULL,
    hidden_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (merchant_id, phone_norm)
);
