-- ══════════════════════════════════════════════════════════════════════
--  خصمٌ بمبلغٍ ثابت — إلى جانب النسبة، وواحدٌ منهما لا اثنان
-- ══════════════════════════════════════════════════════════════════════
--
-- (قرارُ المالك ٢٠٢٦-٠٩-٣٠: «ابنِ ميزة إنشاء عرض بمبلغ ثابت أيضاً».
--  وهو **قرارٌ صريحٌ يمسّ المال** — واتّفاقُ العمل يشترطه: «ولا يُمسّ
--  دفترُ المال إلّا بقرارٍ صريحٍ من المالك».)
--
-- # لماذا عمودٌ ثانٍ لا إعادةُ تفسيرٍ للأوّل
--
-- **`discount_percent` عمودٌ قائمٌ تقرؤه خمسةُ مواضعَ في المحرّك** ولقطةُ
-- اقتصاد الطلب. **ومن أعاد تفسيرَ قيمته بعلَمٍ ثالثٍ كسر كلَّ قارئٍ قديم
-- صامتاً**: صفٌّ قيمتُه ٥ يُقرأ «خمسةٌ بالمئة» في موضعٍ و«خمسُ ليراتٍ» في
-- آخر. **فيُزاد عمودٌ صريح، والقديمُ كما هو حرفاً.**
--
-- # وواحدٌ منهما لا اثنان — بقيدٍ في القاعدة لا بأدبٍ في الشيفرة
--
-- **صفٌّ يحمل الاثنين لا جوابَ له**: أيُّهما يُحسب؟ **وحسبةٌ بلا جوابٍ
-- واحدٍ تُنتج سعرَين** — يرى الزبونُ واحداً ويُحاسَب بالآخر.
--
-- **والقيدُ في القاعدة لأنّ الكاتبين أكثرُ من واحد**: مسلكُ المتجر،
-- ومسلكُ المندوب، ولوحةُ الإدارة، وبذّارُ الاختبار. **وحارسٌ في دالّةٍ
-- واحدةٍ يحرسها وحدَها.**
--
-- # والصفوفُ القائمةُ لا تُمَسّ
--
-- **كلُّها بالنسبة**، **والعمودُ الجديد `NULL` فيها** — فالقيدُ يمرّ
-- عليها بلا تعديلِ صفٍّ واحد. **ولا هجرةَ بياناتٍ ولا نافذةَ خطر.**

ALTER TABLE offers ADD COLUMN IF NOT EXISTS discount_amount bigint;

COMMENT ON COLUMN offers.discount_amount IS
	'خصمٌ بمبلغٍ ثابت بالليرة — بديلُ discount_percent لا رفيقُه';

-- **ومبلغٌ غيرُ موجبٍ ليس خصماً** — صفرٌ لا يخصم، وسالبٌ يرفع السعر.
ALTER TABLE offers DROP CONSTRAINT IF EXISTS offers_amount_positive;
ALTER TABLE offers ADD CONSTRAINT offers_amount_positive
	CHECK (discount_amount IS NULL OR discount_amount > 0);

-- ══════════════════════════════════════════════════════════════════════
--  **وعرضُ الخصم له طريقةٌ واحدةٌ بالضبط**
-- ══════════════════════════════════════════════════════════════════════
--
-- **ويُقيَّد نوعُ الخصم وحدَه** (`kind = 'discount'`): الجدولُ يحمل أنواعاً
-- أخرى في عقده — **ومن قيّد الكلَّ منع ما لم يُقصد منعُه.**
ALTER TABLE offers DROP CONSTRAINT IF EXISTS offers_one_discount_kind;
ALTER TABLE offers ADD CONSTRAINT offers_one_discount_kind
	CHECK (
		kind <> 'discount'
		OR (discount_percent IS NOT NULL AND discount_amount IS NULL)
		OR (discount_percent IS NULL AND discount_amount IS NOT NULL)
	);
