-- ٠٠٥٣ · النجمةُ للمنصة، والشكوى تُصنَّف
--
-- # ١ · لماذا `merchant_stars` صارت `platform_stars`
--
-- الزبونُ لا يرى اسمَ المتجر ولا يختاره — يطلب من «رحّال غو» ونحن نختار من
-- أين نشتري. **فنجمةٌ تُنسب إلى متجرٍ لم يعرفه الزبون نجمةٌ بلا معنى**: هو
-- يحكم على ما وصله — طعامٍ ووقتٍ ومعاملة — **وثلاثتُها من عندنا لا من عنده.**
--
-- وأسوأُ من انعدام المعنى أثرُه: **متجرٌ يُحاسَب على تأخيرٍ سببُه سائقُنا**،
-- وآخرُ يُمدح على سرعةٍ سببُها قربُ العنوان.
--
-- **والاسمُ يُغيَّر لا يُترك على حاله**: عمودٌ اسمُه `merchant_stars` يُقرأ
-- على أنّه تقييمُ المتجر بعد سنة، **مهما كُتب في التوثيق أنّه صار للمنصة.**
ALTER TABLE order_ratings RENAME COLUMN merchant_stars TO platform_stars;

-- # ٢ · سببُ الشكوى مصنَّفٌ لا نصٌّ حرّ
--
-- **للعلّةِ نفسِها التي صُنّف بها سببُ تعذّر التسليم**: نصٌّ حرٌّ لا يُعدّ ولا
-- يُقاس. ولا يُعرف كم شكوى «لم يصلني طلبي» وقعت هذا الشهر، ولا أيُّ سائقٍ
-- يتكرّر معه ذلك — **والتكرارُ هو الخبر، لا الحادثةُ الواحدة.**
ALTER TABLE tickets ADD COLUMN IF NOT EXISTS reason text;

-- **الشكوى تُنسب إلى من فتحها.**
--
-- كانت `created_by` تعني «من أنشأ التذكرة» — وهو موظّفُ الدعم دائماً، لأنّ
-- الزبون لم يكن يملك بابَ فتحٍ أصلاً. **وبعد أن صار يملكه، صار الحقلُ يخلط
-- شكوى الزبون بشكوى فُتحت عنه.**
ALTER TABLE tickets ADD COLUMN IF NOT EXISTS opened_by_customer boolean NOT NULL DEFAULT false;

-- **وطلبٌ لا يُشتكى منه مرّتين وشكواه الأولى مفتوحة.**
--
-- بلا هذا يفتح الزبونُ عشراً بضغطاتٍ متتالية حين لا يأتيه ردٌّ فوريّ —
-- **فيُغرق مكتبَ الدعم بشكوًى واحدةٍ مكرّرة**، ويضيع بينها ما يستحقّ النظر.
CREATE UNIQUE INDEX IF NOT EXISTS tickets_one_open_per_order
    ON tickets (order_id) WHERE status <> 'resolved' AND order_id IS NOT NULL;

-- مهلةُ الشكوى — قرارُ المالك ٢٠٢٦-٠٨-٠١، ويملك تغييرَها من اللوحة.
INSERT INTO app_settings (key, value) VALUES ('support.complaint_window_hours', '24'::jsonb)
ON CONFLICT (key) DO NOTHING;
