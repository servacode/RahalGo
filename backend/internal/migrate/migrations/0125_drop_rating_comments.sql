-- **(قرارُ المالك ٢٠٢٦-٠٨-٣١:** «اتّفقنا سابقاً أنّه تقييمٌ بدون أيّ
-- تعليقٍ بأيّ تطبيق — يعني فقط تقييم» · ثمّ «احذف العامود».)
--
-- # وحقلٌ يُطلب ولا يُقرأ حيث يُكتب
--
-- **الزبونُ كان يكتب «كلمة إن أردت»** — **ولا تطبيقَ في المنصّة يعرضها.**
-- تقرؤها لوحةُ الإدارة وحدَها.
--
-- **فيكتب فيها شكواه ظانّاً أنّ أحداً سيردّ** — **وبابُ الشكوى غيرُه**،
-- فيضيع بلاغُه في حقلٍ لا جوابَ له.
--
-- # وعمودان لا واحد
--
-- **`order_ratings`** — الزبونُ يقيّم الخدمةَ والسائق.
-- **`merchant_ratings`** — السائقُ يقيّم المتجر. **وشاشتُه لا حقلَ فيها
-- أصلاً**، **والنداءُ كان يحمل نصّاً فارغاً** — عمودٌ يُملأ بالفراغ منذ
-- بُني.
--
-- # ولا شيءَ يُفقَد
--
-- **الجدولان فارغان**: مُسحت الطلباتُ كلُّها بقرار المالك في اليوم نفسِه،
-- **و`ON DELETE CASCADE` أسقطت تقييماتها معها.** فليس في العمودين حرفٌ
-- يُمحى.

ALTER TABLE order_ratings DROP COLUMN IF EXISTS comment;
ALTER TABLE merchant_ratings DROP COLUMN IF EXISTS comment;
