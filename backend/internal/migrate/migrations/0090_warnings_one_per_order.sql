-- **إنذارٌ واحدٌ لكلّ طلب — في الجدول الموحَّد.**
--
-- (وُحِّدت الإنذاراتُ ٢٠٢٦-٠٨-٠٩ بقرار المالك: «اجعله لكلّ الأدوار».)
--
-- # ولماذا لزم فوراً
--
-- **الشيفرةُ تكتب بـ`ON CONFLICT (order_id)`** في موضعين: الإنذارُ الآليُّ
-- عند خطأ المتجر، والمطالبةُ عند التعويض. **و`ON CONFLICT` بلا فهرسٍ فريدٍ
-- يطابقه ليس شرطاً — إنّه خطأٌ وقتَ التنفيذ**: «no unique or exclusion
-- constraint matching the ON CONFLICT specification».
--
-- **فينكسر إقفالُ طلبٍ تعذّر تسليمُه** — لا في البناء ولا في اختبار، **بل عند
-- أوّل متجرٍ يرفض التسليم.** وكان الفهرسُ على الجدول القديم وحدَه، **ونُقلت
-- الكتابةُ ولم يُنقل الشرط.**
--
-- # ومعناه
--
-- **واقعةٌ واحدةٌ تُنذَر مرّةً.** طلبٌ تعذّر ثمّ عُوّض عنه لا يُنذَر مرّتين:
-- **الإنذارُ عن السلوك لا عن عدد المرّات التي مررنا فيها على الصفّ.**
--
-- **والإنذارُ اليدويُّ بلا طلبٍ لا يُحدّه شيء** (`WHERE order_id IS NOT NULL`)
-- — من أساء مرّتين يُنذَر مرّتين.
CREATE UNIQUE INDEX IF NOT EXISTS warnings_one_per_order
  ON warnings (order_id) WHERE order_id IS NOT NULL;
