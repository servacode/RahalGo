-- **زمنُ الجهاز بجانب زمن الخادم — للنقاط التي تصل متأخّرة**
-- ══════════════════════════════════════════════════════════════════════
--
-- (خطّةُ تطبيق أندرويد، البند الثالث — `docs/RAHALGO_MOBILE_TECH_DECISION.md`.)
--
-- # ما كان
--
-- **`created_at` وحدَه، وافتراضُه `now()`** — أي لحظةُ وصول النقطة إلى
-- المحرّك. **وهو صحيحٌ تماماً في المتصفّح**: التبويبُ مفتوحٌ والنبضةُ تصل
-- في ثانيتها، **فزمنُ التسجيل هو زمنُ الوصول.**
--
-- # ولماذا ينكسر مع الهاتف
--
-- **السائقُ يدخل قبواً فتنقطع الشبكةُ عشرين دقيقة.** ويجمع الجهازُ في تلك
-- المدّة عشراتِ النقاط، **فترسل كلُّها دفعةً حين تعود الشبكة.**
--
-- **فتُسجَّل كلُّها في ثانيةٍ واحدة** — أي أنّ سائقاً وقف عشرين دقيقةً
-- يبدو كأنّه قطع المدينةَ في لحظة. **ويقرأ `ApproachTo` أنّه اقترب وابتعد
-- في اللحظة نفسِها، فيُخطئ الإسنادُ ولا يُخطئ أحدٌ في الشيفرة.**
--
-- # فعمودان لا عمود
--
-- **`recorded_at` متى قال الجهازُ إنّه كان هناك، و`created_at` متى وصلنا.**
-- **والفرقُ بينهما ليس ضجيجاً** — هو مقدارُ ما كان السائقُ خارجَ التغطية،
-- ويُقرأ حين يُسأل «لماذا اختفى؟».
--
-- **والقراءةُ كلُّها تتبدّل إلى `recorded_at`** (`orders/track.go`): ترتيبُ
-- النقاط هو ما يقول اتّجاهاً، **وترتيبٌ بزمن الوصول يكذب على كلّ دفعة.**
ALTER TABLE driver_track
    ADD COLUMN IF NOT EXISTS recorded_at timestamptz;

-- **والقديمُ زمنُ وصوله هو زمنُ تسجيله** — كلُّه من المتصفّح، ولا دفعاتِ
-- فيه. **فالنسخُ صحيحٌ تاريخيّاً لا تقريبٌ مقبول.**
UPDATE driver_track SET recorded_at = created_at WHERE recorded_at IS NULL;

ALTER TABLE driver_track
    ALTER COLUMN recorded_at SET NOT NULL,
    ALTER COLUMN recorded_at SET DEFAULT now();

-- ══════════════════════════════════════════════════════════════════════
-- **ونقطةٌ واحدةٌ لكلّ سائقٍ في كلّ لحظة**
-- ══════════════════════════════════════════════════════════════════════
--
-- **وهذه هي مفاتيحُ التكرار للموقع** — بلا حقلٍ إضافيّ.
--
-- **والدفعةُ تُعاد**: الهاتفُ يُرسل عشرين نقطة، ينقطع الردُّ في الطريق،
-- **فيُعيد الإرسالَ لأنّه لا يعلم أنّها وصلت.** ولولا هذا القيدُ لَتضاعف
-- الأثرُ — **ولا يظهر ذلك في شيء**: النقاطُ صحيحةٌ ومكرّرة، فيبدو السائقُ
-- أكثفَ حركةً ممّا كان.
--
-- **والقديمُ قد يحمل مكرّراً** فيُنظَّف قبل القيد — **وحذفُ نقطةٍ مكرّرةٍ
-- لا يفقد شيئاً**، هي النقطةُ نفسُها بالزمن نفسِه.
DELETE FROM driver_track a USING driver_track b
WHERE a.driver_id = b.driver_id
  AND a.recorded_at = b.recorded_at
  AND a.id > b.id;

CREATE UNIQUE INDEX IF NOT EXISTS driver_track_point_uniq
    ON driver_track (driver_id, recorded_at);

-- **والفهرسُ يتبع القراءةَ الجديدة** — القديمُ على `created_at` لم يعد
-- يُستعمَل، **وفهرسٌ لا يُقرأ يُبطئ كلَّ كتابةٍ ولا يُسرّع شيئاً.**
CREATE INDEX IF NOT EXISTS driver_track_recorded_idx
    ON driver_track (driver_id, recorded_at DESC);
DROP INDEX IF EXISTS driver_track_recent_idx;
