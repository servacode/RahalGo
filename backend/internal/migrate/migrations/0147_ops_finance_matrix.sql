-- **مصفوفةُ العمليّات والماليّة** — أقلُّ صلاحيّةٍ لكلٍّ
-- ══════════════════════════════════════════════════════════════════════
--
-- # المسألة المقيسة
--
-- **قراءةٌ مدموجةٌ في كتابة.** `GET /merchants` كانت بـ
-- `merchants.manage` و`GET /settings` بـ`settings.general.manage` —
-- **وشاشةُ الطلبات تنادي الاثنتين.** فموظّفُ العمليّات كان يملك
-- **إنشاءَ المتاجر وتحريرَ قوائم غيره وحذفَ أصنافها** من أجل سطرٍ
-- يقرؤه في قائمة التحويل، **وكان محجوباً عن مفتاحٍ تشغيليٍّ يقرؤه.**
--
-- # وقاعدةُ هذه الهجرة
--
-- **لا أحدَ يفقد ما كان يراه.** من ملك `merchants.manage` يُمنَح
-- `merchants.read`، ومن ملك أيَّ درجةِ كتابةٍ في الإعدادات يُمنَح
-- `settings.read`. **والمبدَّلُ أنّ من كان يقرأ لم يعد يكتب.**

-- ── ١ · ولا أحدَ يفقد قراءةً كان يملكها ──────────────────────────────
INSERT INTO role_capabilities (role_code, capability_code)
SELECT DISTINCT role_code, 'merchants.read'
  FROM role_capabilities
 WHERE capability_code = 'merchants.manage'
ON CONFLICT DO NOTHING;

INSERT INTO role_capabilities (role_code, capability_code)
SELECT DISTINCT role_code, 'settings.read'
  FROM role_capabilities
 WHERE capability_code IN ('settings.general.manage',
                           'settings.financial.manage',
                           'settings.security.manage')
ON CONFLICT DO NOTHING;

-- ── ٢ · العمليّات: تنفيذُ الطلب واستمرارُ الخدمة ─────────────────────
--
-- **وتُمنَح القراءتين** — وهما بابا ما كانت تفعله أصلاً:
--
--	`merchants.read`   سياقُ المتجر وقائمةُ التحويل في شاشة الطلبات
--	`settings.read`    المفتاحُ التشغيليُّ في الشاشة نفسِها
--
-- **وتُنزَع واحدة**: `merchants.manage` — **إنشاءُ متجرٍ وتحريرُ
-- قائمةِ غيره وحذفُ أصنافها وساعاتُه ونشاطُ المندوبين ليست تشغيلاً**،
-- **وإنّما مُنحت لأنّ القراءةَ كانت خلفها.** **وقد صار للقراءة بابُها.**
INSERT INTO role_capabilities (role_code, capability_code)
SELECT 'operations', c
  FROM (VALUES ('merchants.read'), ('settings.read')) v(c)
 WHERE EXISTS (SELECT 1 FROM roles WHERE code = 'operations')
ON CONFLICT DO NOTHING;

DELETE FROM role_capabilities
 WHERE role_code = 'operations'
   AND capability_code = 'merchants.manage';

-- ── ٣ · والماليّةُ لا تُمنَح شيئاً ──────────────────────────────────
--
-- **وثلاثةُ أبوابٍ كانت تُعرَض لها في اللوحة والمحرّكُ يردّها ٤٠٣**:
-- سجلُّ التدقيق · وزرُّ إغلاق التذكرة · وقراءةُ لوح الإعدادات.
--
-- **وبابٌ مرئيٌّ لا يُفتح عطبُ واجهةٍ لا نقصُ صلاحيّة** — **وعلاجُه
-- أن يُخفى لا أن يُفتح.** **ولو فُتح لَصارت الماليّةُ تقرأ سجلَّ
-- الأمن وتُغلق تذاكرَ الدعم**، **وذاك عكسُ ما تطلبه أقلُّ صلاحيّة.**
--
-- **والاستثناءُ `settings.read` وحدَها** — **وهي تملك كتابةَ المفتاح
-- الماليّ**، فقراءةُ اللوح دونَها. وقد نالتها في البند ١ تلقائيّاً.

-- ── ٤ · والإرثُ لا يُمَسّ في هذه الهجرة ──────────────────────────────
--
-- **و`ops` صفرُ حاملين في الإنتاج** (قِيس ٢٠٢٦-٠٩-١٣)، **وقدراتُه
-- مجموعةٌ عليا من `operations` تماماً.** **ودمجُه قرارُ مالكٍ لا
-- قرارُ هجرة** — فيبقى كما هو، **ويأخذ القراءتين كغيره** (البند ١
-- أعلاه) **فلا يفقد حاملٌ محتملٌ شيئاً.**
