-- ══════════════════════════════════════════════════════════════════════
-- **منطقةُ المتجر تُختار ولا تُكتب**
-- ══════════════════════════════════════════════════════════════════════
--
-- (قرارُ المالك ٢٠٢٦-٠٨-٣٠: «اختيارُ المحافظة والمنطقة بفورم تسجيل متجر
--  جديد… وبهذا سينعكس أيضاً على المندوب».)
--
-- # وكان نصّاً حرّاً
--
-- **يكتبه صاحبُه بيده في الويب وفي تطبيق المندوب** — «وسط المدينة»
-- و«وسط البلد» و«المركز» ثلاثةُ نصوصٍ لموضعٍ واحد. **ولا يُصنَّف ولا
-- يُبحث به ولا يُصفّى**، ثمّ يصير عنوانَ المتجر النصّيّ.
--
-- # ويبقى العمودُ القديم
--
-- **و`area` لا يُحذف**: هو ما كُتب في الصفوف الماضية، **وحذفُه يمحو
-- ما لا نملك بديلَه.** ويبقى بعدَه **عنواناً تفصيليّاً اختياريّاً**
-- يكتبه صاحبُه — «مقابل الجامع» — **وهو ما لا يقوله معرّفُ منطقة.**
--
-- **فالمنطقةُ تقول أين، والنصُّ يقول كيف تصل.**
--
-- # و`NULL` مسموحٌ اليوم
--
-- **الإلزامُ يأتي في الدفعة الرابعة** بعد أن يُرحَّل القائم. **وعمودٌ
-- إلزاميٌّ يُضاف على صفوفٍ لا تملؤه يُسقط الهجرةَ على قاعدة الإنتاج.**

ALTER TABLE merchant_leads
    ADD COLUMN IF NOT EXISTS district_id uuid REFERENCES districts(id);

CREATE INDEX IF NOT EXISTS merchant_leads_district_idx
    ON merchant_leads (district_id);

-- ══════════════════════════════════════════════════════════════════════
-- **والمتجرُ يحملها بعد الموافقة**
-- ══════════════════════════════════════════════════════════════════════
--
-- **ولا تُشتقّ من المدينة**: المدينةُ تُشتقّ من الإحداثيّات (نصفُ قطر)،
-- **والمنطقةُ اختارها صاحبُها.** ومن اشتقّ الثانيةَ من الأولى ضيّع ما
-- قيل له صراحةً.
--
-- **وهي طبقةُ عنوانٍ لا طبقةُ تشغيل** — لا يُصفّى بها سوقٌ ولا تُسعَّر
-- بها أجرة. (انظر الهجرة ٠١٢٢.)
ALTER TABLE merchants
    ADD COLUMN IF NOT EXISTS district_id uuid REFERENCES districts(id);

CREATE INDEX IF NOT EXISTS merchants_district_idx
    ON merchants (district_id);
