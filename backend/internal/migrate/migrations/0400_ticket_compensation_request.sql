-- **كان حلُّ التذكرة يُودِع في محفظة الزبون فوراً** — بلا موافقةٍ ولا سقف،
-- ومن غير الخزينة (مالٌ يُخلق من عدم)، **وللزبون دائماً** ولو كان صاحبُ
-- الشكوى سائقاً أو متجراً.
--
-- **والآن**: الحلُّ يكتب طلبَ تعويضٍ معلَّقاً لصاحب الشكوى، والماليّةُ
-- توافق فيُدفع من الخزينة أو ترفض. **وهذا العمودُ يربط التذكرةَ بطلبها**
-- — بلا مفتاحٍ أجنبيّ، فجدولُ الطلبات قد يتبدّل حين يُنشر بابُ التعويضات
-- الموحّد، والربطُ يبقى.
--
-- **والقديمُ يبقى كما هو**: تذكرةٌ بلا طلب تقرأ عمودَ `compensation` الذي
-- دُفع قبل اليوم.
