-- 0521 · قسمان جديدان لاستيراد أصناف «الأمين» — قرارُ المالك ٢٠٢٦-١١-٠٧
--
-- **مستلزمات الحيوانات الأليفة**: طعامُ القطط والكلاب والطيور والأسماك،
-- الرمل، شامبو الحيوانات، الأطواق، الأقفاص.
-- **حقائب وإكسسوارات وساعات**: الحقائب والمحافظ والإكسسوار والمجوهرات
-- والخواتم والأساور وإكسسوار الشعر والساعات والنظارات الشمسية.
--
-- **يُضافان بعد ثمانيةٍ وثلاثين ولا يُمَسّ ترتيبُ غيرهما.**
-- **ولا يُدرَج اسمٌ له صفّ** — بالمفتاح المنطقيّ `section_name_key`
-- (نفس حارس 0200) فلا يتكرّر ولو اختلف التشكيل، وإعادةُ التشغيل آمنة.
INSERT INTO platform_sections (name, icon, sort_order)
SELECT c.name, c.icon, c.sort_order
  FROM (VALUES
    ('حقائب وإكسسوارات وساعات', 'clothes', 39),
    ('مستلزمات الحيوانات الأليفة', 'other', 40)
  ) AS c(name, icon, sort_order)
 WHERE NOT EXISTS (
       SELECT 1 FROM platform_sections p
        WHERE section_name_key(p.name) = section_name_key(c.name));
