-- # العطب
--
-- **موضعان يكتبان بهما**:
--
--   `referrals`  — مكافأةُ من دعا، وقيدُها المقابلُ على الخزينة
--   `incentives` — مكافأةُ الهدف وعقوبتُه، وقيدُهما المقابل
--
-- **وقيدُ `kind` لا يعرفهما** — فكلُّ نداءٍ منهما يُردّ بمخالفة قيد.
--
-- **ولم يظهر بعد**: لم يُسلَّم طلبٌ لمدعوٍّ برمز، ولم تُمنح مكافأةُ هدفٍ
-- بعد. **وسيظهر أوّلَ مرّة.**
--
-- # ولماذا أخطرُ من رسالةِ خطأ
--
-- **قيدُ الدعوة داخلَ معاملةِ تسليم الطلب** — **فإرجاعُها يعني أن يفشل
-- تسليمُ طلبٍ لأنّ صاحبَه جاء بدعوة.**
--
-- # ولماذا نوعان لا «تسويةٌ إداريّة»
--
-- **من السبب يُشتقّ التقرير**: «كم صُرف على المكافآت هذا الشهر» و«كم
-- استُقطع عقوبةً» سؤالان لهما جواب. **ولو كُتبا `adjustment` لَاختلطا
-- بالتسويات اليدويّة** — وهي شيءٌ ثالث.
--
-- **والعقوبةُ تدخل الخزينةَ لا تخرج منها** — وهي الوحيدةُ في هذا الملفّ
-- التي تزيد رصيدَها.
ALTER TABLE wallet_transactions DROP CONSTRAINT IF EXISTS wallet_transactions_kind_check;
ALTER TABLE wallet_transactions ADD CONSTRAINT wallet_transactions_kind_check
    CHECK (kind = ANY (ARRAY[
        'topup', 'order_payment', 'refund', 'compensation', 'commission',
        'merchant_earning', 'driver_earning', 'payout', 'adjustment',
        'platform_profit',
        'platform_expense',
        'operating_expense',
        'reward',   -- مكافأةُ دعوةٍ أو هدف — تخرج من الخزينة
        'penalty'   -- عقوبةٌ على سائقٍ أو مندوب — تدخل الخزينة
    ]));
