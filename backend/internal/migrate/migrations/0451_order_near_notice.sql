-- **«الكابتن قريب منك» — مرّةً واحدةً لكلّ طلب** (قرارُ المالك ٢٠٢٦-١٠-١٦)
-- ══════════════════════════════════════════════════════════════════════
--
-- **حين يدخل الكابتنُ ثلاثمئة مترٍ من الباب يُنبَّه الزبونُ** أن يطلع إلى
-- الباب أو الشبّاك فيلتقيا أسرع. **ونبضةُ الموقع تصل كلَّ ثوانٍ** — فلولا
-- علامةٌ تقول «قيل» لَرنّ هاتفُه مع كلّ نبضة.
--
-- # ولماذا عمودٌ لا مفتاحٌ في Redis
--
-- **Redis يُسقطه الحِملُ على التجهيز** (هشاشةٌ مقيسة) — **ومفتاحٌ يضيع بسقوطه
-- يعيد الرنّةَ مع النبضة التالية.** **والعمودُ يُكتب بشرطه في جملةٍ واحدة**
-- (`near_notice_at IS NULL`)، **فنبضتان معاً لا تُرنّان مرّتين.**
--
-- **وعمرُه عمرُ الطلب** — لا مهلةَ تُضبط ولا تنظيف.

ALTER TABLE orders ADD COLUMN IF NOT EXISTS near_notice_at timestamptz;
