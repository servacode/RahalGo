--
-- # المسألة
--
-- **وسبعةُ أبوابٍ افتراضُها مغلق** — **وهو الصحيحُ**: قراءةٌ تعذّرت
-- تسقط على الافتراض، **فعطبٌ في القاعدة لا يفتح عملاً مُغلقاً.**
--
-- **لكنّ المنصّةَ تعمل اليومَ**: الطلباتُ تُستقبَل والتصفّحُ مفتوحٌ
-- والتسجيلُ قائم. **فلو نُشر الأثرُ بلا بذرٍ لَتوقّف كلُّ ذلك في
-- لحظةِ الإقلاع** — **وذاك عطبٌ لا إطلاق.**
--
-- # فتُبذَر مفتوحةً
--
-- **وما يعمل اليومَ يُكتب صفّاً صريحاً `true`** — **فالأثرُ يقرأ
-- الصفَّ لا الافتراض، ولا يتبدّل عند المنصّة العاملة شيء.**
--
-- **ومنصّةٌ تُنصَّب من الصفر غداً تبدأ مغلقةً** — **لا صفَّ لها،
-- فتقرأ الافتراض.** وهو المطلوب: تُنزَّل قبل أن تُفتح.
--
-- # ولا مخطَّطَ يُمَسّ
--
-- **والمفاتيحُ في فهرس الشيفرة** (`settings/catalog.go`)، **والقيمُ
-- صفوفٌ في `app_settings` القائم** — فلا جدولَ يُنشأ ولا عمود.

INSERT INTO app_settings (key, value)
SELECT k, 'true'::jsonb
  FROM (VALUES ('launch.customer_signup'),
               ('launch.customer_browse'),
               ('launch.customer_orders'),
               ('launch.customer_custom_orders'),
               ('launch.driver_work'),
               ('launch.merchant_orders'),
               ('launch.rep_acquisition')) v(k)
ON CONFLICT (key) DO NOTHING;

-- **ونصُّ الحال يبقى فارغاً** — **ولا يُعرَض ما لم يُضبَط**، فتقع
-- رسالةُ المعجم المركزيّة بدلاً منه.
--
-- **ولا يُبذَر بنصٍّ مكتوبٍ هنا**: **وثيقةُ هجرةٍ ليست مكانَ كلامٍ
-- يقرؤه زبون** — يُضبط من اللوحة يومَ يُحتاج.
