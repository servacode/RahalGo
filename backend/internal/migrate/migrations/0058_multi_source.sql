-- ٠٠٥٨ · طلبٌ من مصدرين — **متجرٌ واحدٌ اسمُه رحّال غو**
--
-- # المسألة
--
--	في ذهن الزبون   :  متجرٌ واحد · سلّةٌ واحدة · فاتورةٌ واحدة
--	في دفتر المنصة  :  مطابخُ متعدّدة · مستحقّاتٌ متعدّدة · رحلةُ جمعٍ واحدة
--
-- **ولا إفراغَ للسلّة ولا سؤال** — السببُ الذي كان يستدعيه قد زال بإخفاء
-- المصدر. **ورسمُ التوصيل هو الجسر**: يعرف النظامُ عددَ الأماكن فيحسب،
-- والزبونُ يرى رقماً واحداً.
--
-- # ولماذا العمودُ في البند لا جدولٌ ثالث
--
-- **البندُ يعرف مصدرَه بالفعل** — `menu_items.merchant_id`. لكنّ قراءتَه منه
-- **تقرأ المصدرَ اليوم لا مصدرَ يومِ الطلب**: يُنقل صنفٌ إلى متجرٍ آخر، أو
-- يُحذف، **فتُعاد قراءةُ طلبات الأمس بمصدرٍ لم يحضّرها.**
--
-- **ولقطةٌ في البند تحسم**: من حضّره حينها هو من يُقيَّد له، ولو أُغلق متجرُه
-- بعدها.
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS merchant_id uuid REFERENCES merchants(id);

-- **والقائمُ يُملأ بمصدر الطلب** — كان مصدراً واحداً فلا لبس.
UPDATE order_items oi SET merchant_id = o.merchant_id
FROM orders o WHERE o.id = oi.order_id AND oi.merchant_id IS NULL;

CREATE INDEX IF NOT EXISTS order_items_by_merchant ON order_items (merchant_id);

-- # و`orders.merchant_id` يبقى — **مصدراً أوّلَ لا مصدراً وحيداً**
--
-- **ولا يُلغى**: عشراتُ الاستعلامات تقرؤه — لوحةُ المتجر، وتقاريرُه،
-- ومخالفاتُه، وبوّابتُه. **وحقلٌ يُنزع من تحت قارئيه يكسرهم جميعاً في لحظة.**
--
-- ومعناه صار **أوّلَ محطّةٍ في رحلة السائق**: من هناك يبدأ، ثمّ يمرّ بالثاني.
COMMENT ON COLUMN orders.merchant_id IS
    'المصدرُ الأوّل — أوّلُ محطّةٍ للسائق. وبقيّةُ المصادر في order_items.merchant_id';

-- **مفاتيحُ القرار — والسقفُ في الإعدادات لا في الشيفرة** (قرار المالك).
--
-- **ولا سقفَ للأصناف**: عائلةٌ تطلب شاورما وبطاطا وسلطة وعصيراً وحلواً من
-- **مطبخٍ واحد** — خمسةُ أصنافٍ ووقفةٌ واحدة، **فيُعاقَب الطلبُ الطبيعيّ لمنع
-- النادر.** والقيدُ على عدد المصادر لا على ما في السلّة.
INSERT INTO app_settings (key, value) VALUES
    ('orders.max_sources', '2'::jsonb),
    -- **مجّانيٌّ حين لا يكلّف، محسوبٌ حين يكلّف.**
    --
    -- والعملاقان يبتلعان الرسمَ لأنهما يشتريان زبائنَ بأموال مستثمرين،
    -- **ورحّال لا يستطيع ولا يجب أن يحاول.**
    ('orders.extra_source_fee', '0'::jsonb),
    -- **والقيدُ الحقيقيُّ «قريب» لا «كم»** — التكلفةُ في المسافة بين المطبخين
    -- لا في عددهما. وألفٌ وخمسمئة متر مشوارُ دقائق في مدينةٍ كالرقّة.
    ('orders.source_proximity_m', '1500'::jsonb)
ON CONFLICT (key) DO NOTHING;
