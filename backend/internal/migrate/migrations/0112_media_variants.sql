-- **لمحةٌ فوريّةٌ ومقاساتٌ للصورة الواحدة.**
--
-- (طلبُ المالك ٢٠٢٦-٠٨-١٧: «نريد حلَّ مشكلة الصور بحيث لا يلاحظ المستخدمُ
--  أنّ الصور تتحمّل مهما كان الإنترنت بطيئاً… الحلُّ برمجيّ».)
--
-- # اللمحة
--
-- **صورةٌ بعرض ٢٤ بكسلاً تُخزَّن نصّاً في الصفّ نفسِه** (`data:` بنحو
-- ستّمئة بايت) — **تُرسل مع الورقة فتُرى في أوّل رسمة**، ثمّ تحلّ الكاملةُ
-- محلَّها حين تصل.
--
-- **ولا نداءَ لها**: لو كانت ملفّاً لَاحتاجت رحلةً ثانيةً، **وهي التي جاءت
-- لتُلغي الانتظار.**
--
-- # والمقاسات
--
-- **صورةٌ بعرض ١٦٠٠ تُرسل إلى هاتفٍ عرضُه ٣٩٠** — **فيُحمَّل أربعةُ أضعافِ
-- ما يُرى.** فتُولَّد نسختان أصغرُ ويختار المتصفّحُ بنفسه (`srcset`).
--
-- **والمسارُ يُشتقّ ولا يُخزَّن**: `<id>_960.jpg` و`<id>_480.jpg` بجانب
-- الأصل — **وأعمدةٌ لكلّ مقاسٍ تعني هجرةً كلَّما أُضيف مقاس.**
ALTER TABLE media ADD COLUMN blur text NOT NULL DEFAULT '';

-- **وعلمٌ يقول إنّ المقاسات وُلّدت** — الصفوفُ القديمةُ بلا نسخٍ صغيرة،
-- **ومن طلب مقاساً لم يُولَّد يأخذ ٤٠٤ في وسط الصفحة.**
ALTER TABLE media ADD COLUMN sizes boolean NOT NULL DEFAULT false;
