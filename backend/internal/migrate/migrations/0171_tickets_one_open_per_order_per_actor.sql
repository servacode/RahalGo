-- **بلاغٌ مفتوحٌ واحدٌ لكلّ طلبٍ — لكلّ فاعل** (قرارُ المالك ٢٠٢٦-١٠-٠١)
-- ══════════════════════════════════════════════════════════════════════
--
-- **قِيس على التجهيز**: المتجرُ بلّغ عن تأخّر السائق على طلب، **فلمّا اشتكى
-- الزبونُ من جودة الطعام على الطلب نفسِه رُدّ بـ«لك شكوى مفتوحة» — ولم يفتح
-- شيئاً.** الفهرسُ كان واحداً للأطراف كلِّها (٠٠٥٣): **أوّلُ من بلّغ يُسكت
-- الباقين.**
--
-- **والغرضُ الأصليُّ باقٍ**: الزبونُ لا يفتح عشرَ شكاوى على طلبٍ واحد بضغطاتٍ
-- متتالية — **ولا المتجرُ ولا السائقُ.** فالقيدُ على (الطلب، من فتح).
--
-- **والاسمُ يحمل الاسمَ القديم** — الشيفرةُ تعرف التعارضَ به
-- (`ErrComplaintOpen`)، فلا تتغيّر رسالةُ من كرّر نفسَه.

DROP INDEX IF EXISTS tickets_one_open_per_order;

CREATE UNIQUE INDEX IF NOT EXISTS tickets_one_open_per_order_actor
    ON tickets (order_id, created_by) WHERE status <> 'resolved' AND order_id IS NOT NULL;
