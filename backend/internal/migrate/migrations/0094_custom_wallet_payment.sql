-- **الدفعُ من المحفظة في الطلب الخاصّ — نقلٌ لا كسب.**
--
-- (قرارُ المالك ٢٠٢٦-٠٨-٠٩: «نعم، إذا تمّ الدفع من المحفظة يُحوَّل المبلغ
--  بشكلٍ تلقائيٍّ إلى السائق من محفظة المنصّة».)
--
-- # وهو متّسقٌ مع قراره الأوّل
--
-- **«خدمةٌ للسائق، والمنصّةُ توثّق ولا تحاسب»** — وهذا يبقى: **لا عمولةَ ولا
-- ربح.** المنصّةُ تنقل ما اتّفقا عليه من محفظةٍ إلى محفظة، **وتخرج منه بلا
-- شيء.**
--
-- **والمبلغُ يُعرَف عند التوثيق لا عند الطلب** — فالخصمُ عند التسليم.
--
-- # ولا نوعَ قيدٍ جديد
--
-- **`order_payment` للخصم من الزبون و`driver_earning` للإيداع عند السائق** —
-- وهما قائمان. **ونوعٌ جديدٌ يعني قائمةً تُحدَّث في الدفتر والتقارير وشاشة
-- المحفظة**، ولا يقول أكثرَ ممّا يقولانه.

-- **وعلامةُ الدفع تمنع التكرار.**
--
-- **وقد يُنادى التسليمُ مرّتين** — شبكةٌ تُعيد الطلب، أو موظّفٌ يضغط ثانيةً —
-- **فيُخصم من الزبون مرّتين ويُودَع للسائق مرّتين**، ولا يظهر إلّا في شكوى.
--
-- **وعلامةٌ في صفّ الطلب لا فهرسٌ على الدفتر**: الفهرسُ على
-- `wallet_transactions` يشمل كلَّ الطلبات — **وقيدٌ عامٌّ لأجل حالةٍ خاصّةٍ
-- قد يكسر ما يعمل منذ شهور.** والعلامةُ تخصّ ما تخصّ.
