-- ══════════════════════════════════════════════════════════════════════
-- **طبقاتُ الرصيد — والمحجوزُ ليس متاحاً** — `XG-12` · `AQ-3`
-- ══════════════════════════════════════════════════════════════════════
--
-- (دورةُ إصلاحٍ ٣٠، ٢٠٢٦-٠٩-٠٨ · بعقد مالكٍ صريح.)
--
-- # ما قيس قبل
--
-- **رصيدٌ مئةُ ألفٍ · طلبُ سحبٍ بمئةِ ألف ⇒ `201` والرصيدُ لم يُحجَز** ·
-- **ثمّ أُنفق كلُّه ⇒ `200`** · **ثمّ قرارُ الدفع ⇒ `409`.**
--
-- **ولا مالَ ضاع ولا رصيدَ سالب** — **لكنّ الماليّةَ توافق على سحبٍ
-- يرتدّ**، والطلبُ يبقى معلَّقاً بلا شرح، **والمالُ الذي قرّرت عليه
-- ذهب.**
--
-- # والطبقاتُ أربعٌ ومصدرُ الحقيقة واحد
--
--	POSTED       `wallets.balance`   — ما في المحفظة فعلاً
--	RESERVED     `wallets.reserved`  — محجوزٌ لعمليّةٍ جارية
--	AVAILABLE    مشتقٌّ = `balance - reserved` — **لا عمودَ له**
--	OUTSTANDING  `financial_obligations` — **قائمٌ من `XG-31`**
--
-- **والمتاحُ لا يُخزَّن** — **ورقمٌ ثالثٌ يُكتب يشيخ حين يُنسى تحديثه.**
--
-- # ولماذا القيدُ هو الحارس
--
-- **`reserved <= balance` قيدٌ في الجدول** — **فكلُّ خصمٍ يمرّ بـ
-- `applyTx` يُفحَص به**: خصمُ `س` يترك `balance - س`، والقيدُ يوجب
-- `reserved <= balance - س` **وهو بعينه `س <= available`.**
--
-- **فلا يُفتَّش عن ثلاثين موضعاً يقرأ رصيداً** — **الحدُّ عند الكتابة
-- لا عند القراءة.** **والقراءاتُ تُصحَّح ليكون الردُّ مفهوماً، لا
-- ليكون آمناً.**

ALTER TABLE wallets
    ADD COLUMN reserved bigint NOT NULL DEFAULT 0;

-- **ولا محجوزٌ سالبٌ ولا محجوزٌ يتجاوز الموجود.**
--
-- # والخزينةُ مستثناةٌ كما هي مستثناةٌ من القيد الأوّل
--
-- **`wallets_balance_check` يقول `balance >= 0 OR is_treasury`** —
-- **فالخزينةُ تسبق دخلَها بمصروفها عمداً** (`0048_treasury.sql`).
--
-- **ولو أُغفل ذلك لَصار `reserved(0) <= balance(سالب)` كاذباً** —
-- **فتسقط كلُّ عمليّةٍ تدفع من الخزينة**، وهي التسليمُ والتعويضُ
-- والاسترداد. **وقيس: تسعةٌ وسبعون فحصاً سقطت بـ`insufficient_balance`.**
--
-- **ولا حجزَ للخزينة أصلاً**: لا طلبَ سحبٍ لها، **ويحرسه ثابتُ
-- المصالحة** (`FI-11.e`).
ALTER TABLE wallets
    ADD CONSTRAINT wallets_reserved_check
    CHECK (reserved >= 0 AND (reserved <= balance OR is_treasury));

-- ══════════════════════════════════════════════════════════════════════
-- **وحالاتُ طلب السحب ستٌّ لا ثلاث**
-- ══════════════════════════════════════════════════════════════════════
--
--	pending     أُنشئ ولم يبدأ صرفُه            — محجوز
--	processing  بدأ الصرفُ ولم يثبت نجاحُه      — **محجوزٌ كما هو**
--	paid        ثبت النجاح                      — يُخصَم ويُفكّ الحجز
--	rejected    رُفض قبل الصرف                  — يُفكّ بلا خصم
--	failed      **فشلٌ مُثبَتٌ ولا صرفَ وقع**    — يُفكّ بلا خصم
--	reversed    دُفع ثمّ ارتدّ من المزوّد        — قيدٌ مقابلٌ يُعيده
--
-- **و`failed` لا تُستعمَل لمجهول النتيجة** — **ومجهولُ النتيجة يبقى
-- `processing` حتّى تُثبت المصالحةُ حقيقتَه.** **ولا يُخلَق مالٌ من
-- شكّ.**
--
-- **ولا تكاملَ مزوّدٍ هنا** — **يُبنى النموذجُ ليستعمله الآليُّ غداً
-- بأمان**، ولا يُعاد تصميمُه حينئذٍ.
ALTER TABLE payout_requests DROP CONSTRAINT payout_requests_status_check;
ALTER TABLE payout_requests
    ADD CONSTRAINT payout_requests_status_check
    CHECK (status IN ('pending', 'processing', 'paid', 'rejected', 'failed', 'reversed'));

-- **والحجزُ يُنسَب إلى طلباتٍ قائمة** — فهرسٌ يخدم مصالحةَ الثابت.
CREATE INDEX payout_requests_active_idx
    ON payout_requests (user_id)
    WHERE status IN ('pending', 'processing');

-- ══════════════════════════════════════════════════════════════════════
-- **ومطالبُ اليومِ تُحجَز أثراً رجعيّاً**
-- ══════════════════════════════════════════════════════════════════════
--
-- **وإلّا خرق الثابتُ أوّلَ تشغيل**: طلبٌ معلَّقٌ أُنشئ قبل الهجرة
-- **لا حجزَ له**، **ومصالحةُ `wallets.reserved` مع الطلبات القائمة
-- تسقط.**
--
-- **ويُحجَز ما تحتمله المحفظةُ لا أكثر** — **فمن أنفق رصيدَه بعد
-- طلبه لا يُختلَق له مال**، **ويبقى طلبُه معلَّقاً بحجزٍ ناقصٍ يراه
-- المكتب.**
UPDATE wallets w
   SET reserved = LEAST(
           w.balance,
           COALESCE((SELECT sum(p.amount) FROM payout_requests p
                      WHERE p.user_id = w.user_id AND p.status = 'pending'), 0))
 WHERE EXISTS (SELECT 1 FROM payout_requests p
                WHERE p.user_id = w.user_id AND p.status = 'pending');
