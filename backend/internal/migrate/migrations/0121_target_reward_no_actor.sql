-- **مكافأةُ الهدف بلا فاعلٍ بشريّ — والعمودُ كان يمنعها**
-- ══════════════════════════════════════════════════════════════════════
--
-- `incentives.created_by` وُضع `NOT NULL` في `0073` **وهو صحيحٌ يومَها**:
-- كلُّ حافزٍ كان قرارَ إنسانٍ يُكتب باسمه، **ومالٌ يخرج بلا اسمٍ لا يُراجَع.**
--
-- ثمّ جاءت `0089` بمكافأةِ الهدف الآليّة: يبلغ السائقُ أو المندوبُ هدفَه
-- **فتُصرف بلا أن يقرّر أحد.** وكُتب في `grantTarget` نصّاً:
--
--     «ولا يُعاد بناءُ ما في `Grant`: هي تأخذ فاعلاً بشريّاً، **وهذه بلا
--      فاعل** — ومن كتب `actor` وهميّاً جعل السجلَّ يقول إنّ إنساناً قرّر.»
--
-- **فصار الإدراجُ يكتب `NULL` في عمودٍ يرفضه.** و`0089` أضافت `period`
-- والفهرسَ الفريدَ **ولم تمسّ القيدَ الذي يمنع ما جاءت لتُمكِّنه.**
--
-- # ولماذا لم يظهر
--
-- **`grantTarget` تُنادى بعد إيداع معاملة التسليم** — فخطؤها لا يُبطل
-- تسليماً وقع، وهو صواب. **وتُسجَّل بـ`s.logf`، و`s.logger` لم يُحقَن قطّ**
-- (`incentives.New` لم تكن تأخذ مسجّلاً).
--
-- **فالإدراجُ يسقط في كلّ تسليمٍ منذ `0089` ولا أثرَ لسقوطه**: لا خطأٌ في
-- ردٍّ، ولا سطرٌ في سجلّ، **ولا مالٌ في محفظة.** والشريطُ في التطبيق يمتلئ
-- ويصير أخضرَ ويُكتب «تحقق الهدف — أحسنت».
--
-- **وعطبٌ صامتٌ في المال أطولُ عمراً من عطبٍ يُسقط الطلب**: هذا يُرى في
-- دقيقة، وذاك ينتظر أن يسأل من لم يقبض.
--
-- (كشفه جردُ تطبيق المندوب ٢٠٢٦-٠٨-٣٠ — والسائقُ كان يخسرها معه.)
--
-- # وما يبقى محروساً
--
-- **الإرخاءُ لا يفتح باباً**: `reason` ما زال إلزاميّاً وغيرَ فارغ، **فكلُّ
-- قيدٍ يقول عن ماذا** ولو لم يقل عن يد من. **والفهرسُ الفريدُ في `0089`
-- يمنع صرفَها مرّتين في الشهر.**
--
-- **والفارغُ يُقرأ «آليّة» لا «مجهولة»**: لا سبيلَ إلى قيدٍ يدويٍّ بلا اسم —
-- `Grant` تُلزم فاعلاً في الشيفرة.

ALTER TABLE incentives ALTER COLUMN created_by DROP NOT NULL;
