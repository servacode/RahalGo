-- ══════════════════════════════════════════════════════════════════════
--  حملاتُ الإشعار — **جدولةٌ تنجو من إعادة التشغيل** (`NT`، ٢٠٢٦-٠٩-١٥)
-- ══════════════════════════════════════════════════════════════════════
--
-- # ولماذا جدولٌ جديدٌ هنا وقد مُنع في الدفعة السابعة
--
-- **وبابُ الإعلان قائمٌ منذ زمن** (`POST /admin/broadcast`): **يُعدّ
-- الجمهورَ ثمّ يُرسل في الحال.** **ولا يحفظ شيئاً.**
--
-- **وثلاثةُ أشياءَ لا تقوم بلا صفٍّ دائم:**
--
--   ١ · **الجدولة** — «أرسلها الجمعةَ عند العاشرة». **والذاكرةُ تموت
--       مع العمليّة**: **من جدول ثمّ أُعيد تشغيلُ الخادم فقد جدولتَه
--       بلا أثرٍ يُقرأ.**
--
--   ٢ · **منعُ الازدواج** — **ضغطتان على «أرسل» في شبكةٍ بطيئةٍ
--       إرسالان.** **ولا يُمنَع ذلك إلّا بهويّةٍ محفوظةٍ تُقارَن.**
--
--   ٣ · **الأثرُ بعد الحدث** — **«ماذا أرسلنا في رمضان ولمن؟»**
--       **وسجلُّ الأحداث يقول «أُرسل إعلان» ولا يقول ما صار به.**
--
-- **ولا يصلح لها جدولُ `notifications`**: **ذاك صفٌّ لكلّ إنسان**،
-- **والحملةُ واحدةٌ لآلاف.** **ومن خلطهما جعل إلغاءَ حملةٍ محوَ
-- إشعاراتِ الناس.**
--
-- # وما لا يُحفظ هنا
--
-- **ولا أرقامَ هواتفَ ولا قوائمَ متلقّين** — **والحملةُ تصف الجمهورَ
-- لا تعدّه أسماءً.** **وقائمةٌ محفوظةٌ تشيخ في دقيقة، وتُسرَّب في
-- تصديرٍ لا يُنتبَه له.** (وهو عقدُ خصوصيّة الهاتف القائم.)

CREATE TABLE IF NOT EXISTS campaigns (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),

    -- ══════════════════════════════════════════════════════════════════
    -- **الصنفُ يفصل المعاملةَ عن التسويق** — **ولا يُخلطان أبداً**
    -- ══════════════════════════════════════════════════════════════════
    --
    -- **وخبرُ طلبٍ لا يُؤجَّل لساعةِ هدوءٍ ولا يُعدّ في سقفِ إزعاج** —
    -- **ومن أخّر «وصل سائقُك» إلى الصباح أفسد التوصيل.**
    --
    -- **ولا تملك هذه الحملاتُ أن تتقمّص خبرَ طلب**: **القيدُ هنا لا
    -- يقبل غيرَ التفاعل.** **فلا يُرسل الأدمنُ «طلبك في الطريق».**
    category text NOT NULL DEFAULT 'engagement'
        CHECK (category = 'engagement'),

    title text NOT NULL CHECK (btrim(title) <> ''),
    body  text NOT NULL DEFAULT '',

    -- ══════════════════════════════════════════════════════════════════
    -- **الجمهورُ نوعٌ ومرجعٌ — لا شرطُ استعلامٍ حرّ**
    -- ══════════════════════════════════════════════════════════════════
    --
    -- **ونصُّ استعلامٍ يُكتب في لوحةٍ يصير بابَ حقنٍ في القاعدة** —
    -- **ومن كتب شرطاً خاطئاً أرسل إلى كلّ الناس وهو يظنّ أنّه يخاطب
    -- عشرة.**
    --
    --	role:<code>        ⇒ كلُّ من له هذا الدور
    --	city:<uuid>        ⇒ مشتركو «أخبرني» في مدينةٍ بعينها
    --	cell:<y>,<x>       ⇒ مشتركوها في مربّعٍ خارجَ المدن
    --
    -- **والمرجعُ نصٌّ واحدٌ بصيغة `target_key` نفسِها** (الدفعة الرابعة)
    -- — **ولا صيغتان لشيءٍ واحد.**
    audience_type text NOT NULL
        CHECK (audience_type IN ('role', 'service_interest')),
    audience_ref text NOT NULL CHECK (btrim(audience_ref) <> ''),

    -- ══════════════════════════════════════════════════════════════════
    -- **والوجهةُ نوعٌ ومعرّف — لا رابطٌ حرّ**
    -- ══════════════════════════════════════════════════════════════════
    --
    -- **ورابطٌ حرٌّ في إشعارٍ بابُ تصيّدٍ في جيب الزبون** — **ومن نقر
    -- «عرض» فوجد صفحةَ دفعٍ غريبةً لا يلوم إلّا المنصّة.**
    --
    -- **وفارغُهما «يفتح التطبيقَ وحدَه»** — وهو الحالُ الافتراضيّ.
    dest_type text CHECK (dest_type IN ('offer', 'merchant', 'home')),
    dest_id   uuid,

    -- ══════════════════════════════════════════════════════════════════
    -- **والحالُ محفوظةٌ لا مشتقّةٌ — بخلاف العروض**
    -- ══════════════════════════════════════════════════════════════════
    --
    -- **والعرضُ حالُه دالّةٌ من زمنه** (الدفعة السابعة) — **والحملةُ
    -- فعلٌ وقع أو لم يقع**: **«أُرسلت» ليست دالّةَ ساعةٍ بل أثرَ عمل.**
    --
    -- **ولا يُستنتج «أُرسلت» من مضيّ الموعد** — **فموعدٌ مضى وعاملٌ
    -- كان ميّتاً يعني حملةً لم تُرسَل**، **ومن قرأها «أُرسلت» كذب
    -- عليه.**
    status text NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft', 'scheduled', 'sending', 'sent',
                          'cancelled', 'failed')),

    -- **والموعدُ بوقت الخادم** — **ولا سلطانَ لساعة المتصفّح.**
    scheduled_at timestamptz,

    created_by uuid NOT NULL REFERENCES users(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    sent_at      timestamptz,
    cancelled_at timestamptz,

    -- ══════════════════════════════════════════════════════════════════
    -- **والحجزُ بأجلٍ لا بعلَم** — **كحجز صفوف الدفع** (`PF-09`)
    -- ══════════════════════════════════════════════════════════════════
    --
    -- **ومنفّذٌ مات وعلَمُه مرفوعٌ يحبس الحملةَ أبداً** — **والأجلُ
    -- يُطلقها من تلقائه، فيلتقطها غيرُه.**
    claimed_at timestamptz,

    -- ══════════════════════════════════════════════════════════════════
    -- **والعدُّ يقول ما يُعرَف ويسكت عمّا لا يُعرَف** (البند ١٤)
    -- ══════════════════════════════════════════════════════════════════
    --
    --	targeted       ⇒ كم حساباً وقع عليه الاختيار
    --	inbox_created  ⇒ كم صفّاً كُتب في الصناديق فعلاً
    --	deferred       ⇒ كم أُجّل لساعة الهدوء أو للسقف
    --
    -- **ولا عمودَ «وصل» ولا «قُرئ»** — **ولا تُقاس القراءةُ عندنا**:
    -- **وقبولُ غوغل للرسالة ليس قراءةَ إنسان**، **ومن كتب «وصلت»
    -- بناءً عليه كذب برقم.**
    targeted      integer NOT NULL DEFAULT 0,
    inbox_created integer NOT NULL DEFAULT 0,
    deferred      integer NOT NULL DEFAULT 0,

    -- **وسببُ السقوط يُحفَظ** — **و«فشلت» بلا سببٍ لا تُصلَح.**
    error text NOT NULL DEFAULT '',

    -- ══════════════════════════════════════════════════════════════════
    -- **وهويّةُ المحاولة تمنع الازدواج** (`NT-06`)
    -- ══════════════════════════════════════════════════════════════════
    --
    -- **وضغطتان في شبكةٍ بطيئةٍ نداءان** — **والثاني يجد الأولى
    -- محفوظةً فيردّها كما هي.** **وهو عقدُ `Idempotency-Key` القائم في
    -- المنصّة، محفوظاً في الصفّ نفسِه.**
    idem_key text NOT NULL CHECK (btrim(idem_key) <> ''),

    -- **والموعدُ شرطٌ للمجدولة** — **ومجدولةٌ بلا موعدٍ لا تُستحقّ أبداً.**
    CONSTRAINT campaigns_scheduled_needs_time CHECK (
        status <> 'scheduled' OR scheduled_at IS NOT NULL)
);

-- **وهويّةُ المحاولة فريدةٌ لصاحبها** — **ومفتاحٌ من أدمنٍ لا يصادر
-- مفتاحَ غيره.**
CREATE UNIQUE INDEX IF NOT EXISTS campaigns_idem_idx
    ON campaigns (created_by, idem_key);

-- **والسؤالُ الغالبُ: ما المستحقُّ الآن؟**
CREATE INDEX IF NOT EXISTS campaigns_due_idx
    ON campaigns (scheduled_at)
    WHERE status = 'scheduled';

CREATE INDEX IF NOT EXISTS campaigns_recent_idx
    ON campaigns (created_at DESC);

-- ══════════════════════════════════════════════════════════════════════
-- **وما وصل هذا الحسابَ من تفاعلٍ — لسقفِ الإزعاج ومنعِ التكرار**
-- ══════════════════════════════════════════════════════════════════════
--
-- # ولماذا صفٌّ ثانٍ ولا يُقرأ `notifications`
--
-- **وجدولُ الإشعارات يحمل المعاملاتِ والتفاعلَ معاً** — **وعدُّ
-- «كم أزعجناه هذا اليوم؟» فيه يعدّ أخبارَ طلباته**، **فيُسكَت عنه
-- لأنّه طلب كثيراً.**
--
-- **وهذا يعدّ التفاعلَ وحدَه** — **ويقول أيضاً: أوصلته هذه الحملةُ
-- بعينها من قبل؟** **فإعادةُ محاولةٍ بعد سقوطٍ لا تُرسل مرّتين.**
CREATE TABLE IF NOT EXISTS campaign_recipients (
    campaign_id uuid NOT NULL REFERENCES campaigns(id) ON DELETE CASCADE,
    user_id     uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    sent_at     timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (campaign_id, user_id)
);

-- **وسقفُ اليوم يُقرأ بالحساب والزمن.**
CREATE INDEX IF NOT EXISTS campaign_recipients_user_idx
    ON campaign_recipients (user_id, sent_at DESC);
