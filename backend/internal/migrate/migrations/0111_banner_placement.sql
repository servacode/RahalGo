-- # وافتراضُه التسوّق
--
-- **ما رُفع قبل اليوم رُفع للتسوّق** — وهو المكانُ الوحيد الذي كان يعرضها.
-- **فافتراضٌ غيرُه ينقل لافتاتِ صاحبها إلى صفحةٍ لم يقصدها.**
ALTER TABLE banners
    ADD COLUMN placement text NOT NULL DEFAULT 'shop'
        CHECK (placement IN ('shop', 'home'));

-- **والقراءةُ دائماً بموضعٍ وترتيب** — فالفهرسُ عليهما معاً.
CREATE INDEX banners_placement_idx ON banners (placement, sort_order);
