--
-- (قِيس ٢٠٢٦-٠٩-٠٢: **لا سطرَ واحدٌ في التطبيق ولا في المحرّك يفحص
--  أنّ الموقع مزيَّف** — لا `isFromMockProvider` ولا ما يقوم مقامها.)
--
-- ## وما كان يقع
--
-- **يُنزّل السائقُ تطبيقَ تزييفٍ من المتجر — مجّانيٌّ ومتاحٌ للجميع —
-- ويضع موضعَه عند بيت الزبون وهو في بيته.** ثمّ يضغط «تمّ التسليم».
--
-- **وإثباتُ التسليم يكتب «على بعد خمسةِ أمتارٍ من العنوان»** — وهو
-- محسوبٌ من الموضع المزيَّف نفسِه. **فالحارسُ الذي بُني للحماية صار
-- شاهدَ زورٍ يشهد لمن يخدعه.**
--
-- ## ولماذا حقلٌ لا منع
--
-- **والمنعُ وحدَه يُعمي**: من مُنع لم يُسجَّل، ولا يُعرف كم مرّةً جرّب.
-- **فيُسجَّل أوّلاً** — في كلّ نقطةٍ وفي إثبات التسليم — ثمّ يُمنع ما
-- يمسّ المال.
--
-- **والقديمُ `false`** — لا لأنّه صحيحٌ بل لأنّه غيرُ معلوم، **ولا
-- يُتَّهم أحدٌ بأثرٍ لم يُقَس يومَه.**

ALTER TABLE driver_track
  ADD COLUMN IF NOT EXISTS mocked boolean NOT NULL DEFAULT false;

-- **وإثباتُ التسليم يحمل وسمَه معه** — فيُقرأ في اللوحة بعد شهر.
ALTER TABLE orders
  ADD COLUMN IF NOT EXISTS pod_mocked boolean NOT NULL DEFAULT false;

-- **وفهرسٌ على المزيَّف وحدَه** — فالأكثريّةُ صادقةٌ ولا تُفهرس.
CREATE INDEX IF NOT EXISTS driver_track_mocked_idx
  ON driver_track (driver_id, recorded_at DESC)
  WHERE mocked;
