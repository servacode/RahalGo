-- **الشكوى تعرف ضدّ مَن هي — والإنذارُ يبلغ كلَّ دور.**
--
-- (شكوى المالك ٢٠٢٦-٠٨-٠٩: «قدّمت شكوى على السائق من حساب الزبون، وجّه إنذار
--  للسائق… بس ما وصل الإنذار… لازم يكون في تنبيه بخصوص الشكوى بشكل مباشر
--  مين ضد مين وكلّ شخص ياخذ حقّه».)
--
-- # المرضُ الأوّل: شكوى بلا مشتكًى عليه
--
-- **`tickets` تحمل صاحبَ الشكوى والطلبَ ولا تحمل ضدّ مَن هي.**
--
-- وأثرُه أخطرُ ممّا يبدو: صفحةُ السمعة تعرض **للسائق كلَّ شكوى على طلبٍ قاده**،
-- **ولصاحب المتجر كلَّ شكوى على طلبٍ من متجره.** فشكوى على السائق يقرؤها
-- صاحبُ المتجر وكأنّها عليه، **والعكس** — ويعدّ نفسَه متّهماً بما لا شأنَ له به.
--
-- **و`NULL` تعني «على المنصّة»** — شكوى لا تخصّ شخصاً بعينه: تأخّرٌ في
-- التوزيع، أو خطأٌ في التسعير. **وهي حالةٌ حقيقيّةٌ لا نقصُ بيانات.**
ALTER TABLE tickets
  ADD COLUMN IF NOT EXISTS against_user_id uuid REFERENCES users(id) ON DELETE SET NULL;

-- **ولا يُعرض على أحدٍ ما ليس عليه** — فهرسٌ لسؤالٍ يُسأل في كلّ فتحةِ شاشة.
CREATE INDEX IF NOT EXISTS tickets_against_idx
  ON tickets (against_user_id) WHERE against_user_id IS NOT NULL;

-- # المرضُ الثاني: إنذارٌ للمتاجر وحدَها
--
-- **`merchant_warnings` هو الجدولُ الوحيد** — فحين وجّه المالكُ إنذاراً لسائق
-- **لم يُسجَّل شيء**: كانت ملاحظةً نصّيّةً في سجلّ المتابعة تصل الزبونَ لا
-- السائق.
--
-- **والإنذارُ الذي لا يُسجَّل لا يُعدّ ولا يُحتجّ به يومَ الحظر** — ولا يعرف
-- صاحبُه أنّه أُنذر أصلاً.
--
-- # ولماذا جدولٌ واحدٌ لكلّ الأدوار
--
-- (قرارُ المالك: «اجعله لكلّ الأدوار حتّى الزبون — ممكن يكون تعامل بسوء مع
--  السائق، بالنهاية كمان السائق بشر ويقدّم خدمة».)
--
-- **وأربعةُ جداولَ لأربعة أدوارٍ أربعُ نسخٍ من قاعدةٍ واحدة**: يُضاف حقلٌ في
-- إحداها ويُنسى في الثلاث. **والإنذارُ إنذارٌ مهما كان دورُ صاحبه.**
--
-- **ويُنسب إلى مستخدمٍ لا إلى متجر**: المتجرُ كيانٌ وصاحبُه شخص، **ومن أُنذر
-- هو من يقرأ** — والحسابُ هو ما يُحظَر لا اللافتة.
CREATE TABLE IF NOT EXISTS warnings (
  id        uuid PRIMARY KEY DEFAULT gen_random_uuid(),

  -- **المُنذَر** — أيُّ دورٍ كان.
  user_id   uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,

  -- **ودورُه وقتَ الإنذار يُثبَّت** — لا يُشتقّ عند القراءة.
  --
  -- **فمن كان سائقاً ثمّ صار مندوباً** تُقرأ إنذاراتُه القديمةُ باسم دوره
  -- الجديد، **ويبدو المندوبُ سيّئَ السجلّ في عملٍ لم يعمله.**
  role_code text NOT NULL,

  -- **وسببٌ إلزاميّ** — إنذارٌ بلا سببٍ لا يُصحَّح ولا يُحتجّ به.
  reason    text NOT NULL CHECK (btrim(reason) <> ''),
  note      text NOT NULL DEFAULT '',

  -- **والطلبُ الذي وقع فيه إن وُجد** — وقد يقع خارجَ طلب.
  order_id  uuid REFERENCES orders(id) ON DELETE SET NULL,
  -- **والشكوى التي وُلد منها إن وُجدت** — فيُعرف الإنذارُ بسببه لا بكلمته.
  ticket_id uuid REFERENCES tickets(id) ON DELETE SET NULL,

  issued_by uuid REFERENCES users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS warnings_user_idx ON warnings (user_id, created_at DESC);

-- **والقديمُ يُهاجَر ولا يُترك.**
--
-- **إنذاراتُ المتاجر قائمةٌ ولها أصحاب** — ومن حُذف جدولُه فقد سجلَّه،
-- **فيبدو نظيفاً وهو ليس كذلك.** فتُنقل إلى أصحاب المتاجر بأسمائهم.
INSERT INTO warnings (user_id, role_code, reason, note, issued_by, created_at)
SELECT m.owner_user_id, 'merchant', w.reason, COALESCE(w.note, ''),
       w.issued_by, w.created_at
FROM merchant_warnings w
JOIN merchants m ON m.id = w.merchant_id
WHERE m.owner_user_id IS NOT NULL
ON CONFLICT DO NOTHING;

-- **ولا يُحذف `merchant_warnings` في هذه الهجرة.**
--
-- **الحذفُ بعد أن يُقرأ الجديدُ في الإنتاج لا معه** — وهجرةٌ تنقل وتحذف في
-- خطوةٍ واحدةٍ لا تُراجَع: **إن أخطأ النقلُ ذهب الأصل.**
