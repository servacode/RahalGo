--
-- # المسألة
--
-- **ومنطقةٌ قد تكون مُغطّاةً جغرافيّاً ولا يُوصَّل إليها الآن**: حيٌّ
-- يُخدَم من الثامنة إلى السادسة. **والساعةُ التاسعةُ ليلاً تُردّ اليومَ
-- بـ`out_of_zone`** — **وهو كذبٌ**: **عنوانُه داخلَ التغطية، والوقتُ هو
-- المانع.**
--
-- **ومن قرأ «عنوانُك خارجَ منطقة التوصيل» ظنّ أنّ المنصّةَ لا تصله
-- أبداً فحذف التطبيق** — **ومن قرأ «يعود التوصيل الثامنةَ صباحاً» عاد.**
--
-- # ولمَ جدولٌ لكلّ منطقةٍ لا جدولٌ واحد
--
-- **ومنطقةٌ تعمل ليلَ نهارٍ وأخرى تُغلق السادسةَ وثالثةٌ بفترتين** —
-- **وجدولٌ عامٌّ واحدٌ لا يصفها.** **ودوامُ المنصّة** (`0149`) **يبقى
-- عامّاً ومنفصلاً**: **ذاك يقول أنستقبل أصلاً، وهذا يقول أنُوصّل إلى
-- هنا.**
--
-- # والاصطلاحُ اصطلاحُ دفعةِ الدوام حرفاً
--
-- **يومٌ بلا فتراتٍ مغلقٌ بذاته** · **و`ends_at <= starts_at` عبورٌ
-- لمنتصف الليل** · **والبدءُ داخلٌ والانتهاءُ خارج.** **ولا يُخترَع
-- اصطلاحٌ ثانٍ في المستودع نفسِه** — **واثنان يفترقان يوماً فيقول
-- الجدولان في اللحظة نفسِها قولين.**

CREATE TABLE delivery_zone_hours (
    id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    -- **ومحوُ المنطقة يمحو جدولَها** — **وجدولٌ يتيمٌ يبقى في القاعدة
    -- بلا منطقةٍ يصفها**، **ولا أحدَ يعرف لماذا هو هناك.**
    zone_id    uuid NOT NULL REFERENCES delivery_zones (id) ON DELETE CASCADE,
    day_of_week int  NOT NULL CHECK (day_of_week BETWEEN 0 AND 6),
    starts_at   time NOT NULL,
    ends_at     time NOT NULL,
    -- **وبدءٌ يساوي انتهاءً غامضٌ** — أصفرٌ هو أم يومٌ كامل؟
    CONSTRAINT delivery_zone_hours_not_empty CHECK (starts_at <> ends_at),
    -- **ولا فترتان تبدآن في اللحظة نفسِها من اليوم نفسِه للمنطقة
    -- نفسِها** — **وما تبقّى من التداخل يُقاس في الخادم** (`Validate`):
    -- **تقاطعُ المدى على مدارِ الأسبوع لا تُعبّر عنه قيودُ صفٍّ واحد.**
    CONSTRAINT delivery_zone_hours_unique_start UNIQUE (zone_id, day_of_week, starts_at)
);

CREATE INDEX delivery_zone_hours_zone_idx ON delivery_zone_hours (zone_id);

-- ══════════════════════════════════════════════════════════════════════
-- **وسريانُ الجدول رايةٌ في المنطقة نفسِها**
-- ══════════════════════════════════════════════════════════════════════
--
-- **ولا يُقرأ السريانُ من «أللمنطقة صفوفٌ؟»** — **فمن أدخل الأحدَ وحدَه
-- ثمّ ذهب لينام أغلق منطقتَه ستّةَ أيّامٍ بلا أن يقصد.**
--
-- **وافتراضُها `false`** — **فكلُّ منطقةٍ قائمةٍ تبقى كما هي اليوم:
-- متاحةً زمنيّاً على مدار الساعة**، **خاضعةً لما كانت تخضع له من
-- تغطيةٍ جغرافيّةٍ ووضعِ إطلاقٍ ودوامِ منصّة.** **ونشرُ هذه الهجرة لا
-- يُغلق منطقةً واحدة.**
--
-- **وهو الدرسُ عينُه المكتوبُ في ٠١٤٨ و٠١٤٩.**
ALTER TABLE delivery_zones
    ADD COLUMN hours_enforced boolean NOT NULL DEFAULT false;
