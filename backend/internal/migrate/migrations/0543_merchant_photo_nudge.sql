--
-- صفٌّ لكلّ صاحبِ متجرٍ وصله التذكير: **آخرُ يومٍ (بتوقيت دمشق) أُرسل له فيه**.
-- يُحجز اليومُ قبل الإرسال بشرطٍ (`last_day <> اليوم`) فلا يصله إشعاران في يومٍ واحد
-- ولو تداخلت نبضتان.
CREATE TABLE IF NOT EXISTS merchant_photo_nudge (
    user_id    uuid PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    last_day   date        NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now()
);
