-- ٠١٥٦ · فهرسُ أقسام الإطلاق — **بنيةٌ تُبنى من المصدر لا من لوحةٍ بيد**
--
-- # المسألة
--
-- **و`0057` بذر تسعةَ أقسامٍ ابتدائيّة** — ونصُّه يقولها صراحةً: «قابلةٌ
-- للتعديل والحذف من اللوحة». **ثمّ نُسجت بنيةُ الإطلاق الحقيقيّةُ في
-- اللوحة**: ثمانيةٌ وثلاثون قسماً بأسمائها وترتيبها وأيقوناتها.
--
-- **فصارت البنيةُ حالةَ قاعدةٍ لا شيفرة.** **وقاعدةٌ تُبنى من الصفر
-- تعود إلى التسعة** — **ولا أحدَ يعلم أنّ ما رآه ذهب** حتّى يفتح
-- الزبونُ سوقاً بتسعة أبوابٍ بدل ثمانيةٍ وثلاثين.
--
-- **و`ON CONFLICT DO NOTHING` في `0057` لم يكن يحرس شيئاً**: **لا فهرسَ
-- فريداً على الاسم يصطدم به** — فالحارسُ اسمٌ بلا أثر.
--
-- # وما تفعله هذه الهجرة
--
-- **تُثبّت الفهرسَ في المصدر** — **ولا تلمس ما ليس فيه.**
--
--	قاعدةٌ نظيفة  ⇐  تسعةٌ من `0057` ثمّ تُكمَّل إلى ثمانيةٍ وثلاثين
--	قاعدةٌ قائمة  ⇐  الموجودُ يبقى بمعرّفه، والناقصُ يُضاف
--	الإنتاج       ⇐  الثمانيةُ والثلاثون موجودةٌ ومطابقة — لا تبدّل
--
-- **والمعرّفاتُ لا تُمَسّ**: **الاسمُ هو المفتاحُ المنطقيّ لا الرقم** —
-- **ولكلّ بيئةٍ معرّفاتُها** (الإنتاجُ والتجهيزُ مختلفان اليومَ فعلاً)،
-- **و`menu_items` و`store_sections` تشيران بالمعرّف**: **فتبديلُه يقطع
-- كلَّ صنفٍ عن قسمه.**
--
-- # ولا يُحذَف تاريخ
--
-- **والأقسامُ المتقاعدةُ تبقى صفوفاً معطَّلة** — **ولا تُحذَف.**
--
-- **وحذفُها متعذّرٌ أصلاً متى أشار إليها صنف**: **مفتاحُ
-- `menu_items.platform_section_id` موصوفٌ `ON DELETE SET NULL`
-- والعمودُ نفسُه `NOT NULL`** — **وهما لا يجتمعان**: **فالحذفُ يسقط
-- بخرقِ `NOT NULL` ولا يُفرِّغ الحقل.** (قِيس ٢٠٢٦-٠٩-١٨.)

