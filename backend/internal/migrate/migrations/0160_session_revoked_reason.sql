-- **Redis سريعٌ لكنّه يزول**: مفتاحُ `sess:revoked:<sid>` مهلتُه عمرُ رمز
-- الوصول. **وجهازٌ قديمٌ كان مطفأً حين دخل الجديد** قد يعود بعد انقضائها،
-- **فيجب أن يعرف السببَ الدقيق** — «سُجّل الدخول من جهازٍ آخر» لا رسالةً
-- عامّة. **فالسببُ يُخزَّن هنا مع الإبطال، فيبقى ما بقي الصفّ.**
--
-- **وصفوفُ `refresh_tokens` تُبطَل بتحديثٍ لا بحذف** (`revoked_at`)، فالسببُ
-- يدوم مع العائلة.
--
--   ''           = إبطالٌ عامّ (خروج · حظر · حذف · إعادةُ كلمة) — تبقى مميَّزة
--   'superseded' = دخولٌ جديدٌ من نوعِ العميل نفسِه أزاح هذه العائلة
--
-- **إضافةٌ آمنةٌ وعكوسة**: عمودٌ بقيمةٍ افتراضيّةٍ فارغة، لا يمسّ صفّاً قائماً.
-- (التراجع: ALTER TABLE refresh_tokens DROP COLUMN IF EXISTS revoked_reason;)
ALTER TABLE refresh_tokens
    ADD COLUMN IF NOT EXISTS revoked_reason text NOT NULL DEFAULT '';
