--
-- «الطلبُ الخاصّ يظهر أمانة أو مشتريات… إذا أمانة النظامُ يفهم أنّه ما في حقُّ بضاعة،
-- وإذا مشتريات في حقُّ بضاعة.» — **يختاره الزبونُ عند الطلب.**
--
-- «أوّلَ شي لازم يوثّق أجرةَ التوصيل… لأنّ السائقَ أوّلَ شي ما يعرف شقد سعرُ البضاعة»
-- — **فالأجرةُ أوّلاً، وثمنُ البضاعة بعد الشراء.** و`custom_goods_pending` يقول إنّ الأجرةَ
-- وُثّقت والبضاعةَ لم تُوثَّق بعد — **ولا يُضغط «تم شراء المطلوب» قبلها** (المحرّك).
ALTER TABLE orders ADD COLUMN IF NOT EXISTS custom_mode text NOT NULL DEFAULT 'purchase'
    CHECK (custom_mode IN ('purchase', 'amanah'));
ALTER TABLE orders ADD COLUMN IF NOT EXISTS custom_goods_pending boolean NOT NULL DEFAULT false;
