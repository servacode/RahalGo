-- **كلُّ من في المنصّة زبونٌ أيضاً — ولو أُنشئ قبل القرار.**
--
-- (قرارُ المالك ٢٠٢٦-٠٨-١٠: «أيُّ دورٍ لا يمكن أن يظهر له إلّا كزبون…
--  والسائقُ يمكن أن يكون زبوناً، وكذلك المتجرُ والمندوبُ وصاحبُ المنصّة
--  والموظّفون… طبعاً الدورُ يتم تفعيله بشكلٍ تلقائيٍّ كزبون، لا يحتاج
--  تدخّلاً يدويّاً».)
--
-- # ولماذا ترحيلٌ لا شيفرةٌ تعمل عند الدخول
--
-- **الشيفرةُ أُصلحت** (`grantsCustomer` صارت تشمل كلَّ دور) — **لكنّها تعمل
-- عند المنح**، ومن مُنح دورَه أمسِ لا يمرّ بها ثانيةً.
--
-- **فكلُّ حسابٍ قائمٍ يبقى بلا دور الزبون إلى الأبد**: يفتح الموقعَ فيتصفّح
-- ولا يستطيع أن يطلب، **وزرُّ «تسوّق» في لوحته يقود إلى بابٍ لا يُفتح.**
--
-- **وإصلاحٌ يسري على الجديد وحدَه ليس إصلاحاً** — هو تأجيلٌ للعطب إلى أن
-- يُنسى سببُه.
--
-- # ولا يُلمس دورٌ قائم
--
-- **إضافةٌ لا استبدال**: من كان سائقاً يبقى سائقاً ومعه الزبون. **وقاعدةُ
-- «دورٌ أساسيٌّ واحد» لا يخرقها هذا** — الزبونُ ليس دوراً أساسيّاً، هو بابُ
-- التصفّح والطلب والمحفظة.
--
-- **و`ON CONFLICT DO NOTHING` تجعلها تُعاد بلا أثر** — والترحيلُ يُطبَّق
-- مرّةً، **لكنّ استعلاماً لا يُؤذي إن أُعيد خيرٌ من واحدٍ يعتمد على أن يُطبَّق
-- مرّةً.**
INSERT INTO user_roles (user_id, role_code)
SELECT u.id, 'customer'
FROM users u
WHERE NOT EXISTS (
  SELECT 1 FROM user_roles ur
  WHERE ur.user_id = u.id AND ur.role_code = 'customer'
)
ON CONFLICT DO NOTHING;
