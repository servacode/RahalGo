-- **قناةُ تواصلٍ بين الزبون والسائق — بلا رقمٍ يعرفه أحدُهما عن الآخر.**
--
-- (قرارُ المالك ٢٠٢٦-٠٨-٠٩: «حتّى إذا اتّصل ما يظهر رقم الزبون عند السائق
--  ولا رقم السائق عند الزبون، لازم الاثنين ما يقدروا يوصلوا لبعض إلّا عن
--  طريق المنصّة فقط».)
--
-- # ولماذا الرسائلُ أوّلاً والصوتُ بعدها
--
-- **الصوتُ يحتاج تطبيقاً** — لا مكالمةَ واردةٌ في متصفّحٍ مغلق. **والرسالةُ
-- تعمل اليوم**، وتصل على شبكةٍ ضعيفةٍ وتنتظر حتّى يعود الإرسال. **والمكالمةُ
-- لا تنتظر.**
--
-- **وهي البديلُ حين يسقط الصوتُ لا منافسُه**: سائقٌ على درّاجةٍ يتنقّل بين
-- أبراج الشبكة تنقطع مكالمتُه في منتصف الجملة — **وهذا ما سيقع لا ما قد يقع.**
--
-- # ولا جدولَ للصلاحيات
--
-- **الصلاحيةُ تُشتقّ من الطلب ولا تُخزَّن.**
--
-- الوثيقةُ اقترحت `order_call_permissions` بصفوفٍ تُكتب وتُحدَّث وتنتهي.
-- **وصفٌّ يَنسخ حالةً ينحرف عنها**: يُلغى الطلبُ ولا يُحدَّث الصفّ، **فتبقى
-- الصلاحيةُ مفتوحةً على طلبٍ ميّت** — ولا يظهر ذلك في أيّ خطأ. ويحتاج كنّاساً
-- دوريّاً، **وكنّاسٌ يتوقّف يترك أبواباً مفتوحة.**
--
-- **والاشتقاقُ لا ينحرف**: مَن طرفا الطلب، وما حالتُه، ومتى سُلّم — كلُّها
-- في `orders` أصلاً. **والسؤالُ يُسأل لحظةَ الاستعمال فيُجاب بالحقيقة.**
--
-- # وهذا الجدولُ للرسائل وحدَها
--
-- **ولا يحمل رقماً ولا معرّفَ طرفٍ مختار**: المرسِلُ يُكتب من الجلسة،
-- **والمستقبِلُ يُشتقّ من الطلب** — فلا يستطيع أحدٌ أن يراسل من يشاء.
CREATE TABLE IF NOT EXISTS order_messages (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id   uuid NOT NULL REFERENCES orders(id) ON DELETE CASCADE,

  -- **المرسِلُ من الجلسة لا من الجسد** — ولا يُقبل معرّفٌ يرسله العميل.
  sender_id  uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,

  -- **ودورُه يُثبَّت وقتَ الكتابة** — `customer` أو `driver`.
  --
  -- **ولا يُشتقّ عند القراءة**: السائقُ قد يتبدّل بعد تحويل، **فرسالةٌ كتبها
  -- الأوّلُ تُقرأ باسم الثاني** لو اشتُقّ الدورُ من `orders.driver_id` اليوم.
  sender_role text NOT NULL CHECK (sender_role IN ('customer', 'driver')),

  body       text NOT NULL CHECK (btrim(body) <> ''),

  -- **وقتُ قراءة الطرف الآخر** — لِيُعرَف ما وصل ممّا انتظر.
  read_at    timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- **الترتيبُ زمنيٌّ داخل الطلب** — وهو كلُّ ما يُستعلَم.
CREATE INDEX IF NOT EXISTS order_messages_order_idx
  ON order_messages (order_id, created_at);

-- **وغيرُ المقروء يُعدّ بسرعة** — شارةٌ في كلّ فتحةِ شاشة.
CREATE INDEX IF NOT EXISTS order_messages_unread_idx
  ON order_messages (order_id, sender_role) WHERE read_at IS NULL;
