-- **أجرُ السائقِ المستحقّ — مستقلٌّ عمّا يدفعه الزبون** — قرارٌ ٢٠٢٦-٠٩-٢٧
-- ══════════════════════════════════════════════════════════════════════
--
-- # العلّة
--
-- **عرضُ «توصيلٌ مجّانيّ» كان يُصفّر `delivery_fee`** (ما يدفعه الزبون)، **وأجرُ
-- السائق هو `delivery_fee` نفسُه** — **فيقود السائقُ مشوارَه ويأخذ صفراً** لأنّ
-- المنصّةَ وعدت الزبونَ بالمجّان. **والوعدُ على المنصّة لا على السائق.**
--
-- # الحلّ
--
-- **حقلٌ ثانٍ `driver_fee`**: أجرُ السائقِ المعتمَد = أجرةُ التوصيلِ الأساسُ
-- (قبل خصمِ العرض). **يُثبَّت لحظةَ الإنشاء** كسائرِ لقطات الاقتصاد. ما يدفعه
-- الزبونُ يبقى في `delivery_fee` (قد يكون صفراً بالعرض)، **وما يأخذه السائقُ في
-- `driver_fee`** — **والفرقَ تموّله الخزينةُ** (عرضٌ مموَّلٌ من المنصّة، بالحساب
-- الفرقيّ في `creditTreasury` تلقائيّاً). ولا سلوكَ ممولٍ من المتجرِ يُخترَع.
--
-- # ولا يُعاد كتابةُ الماضي
--
-- **الطلباتُ القائمةُ: `driver_fee = delivery_fee`** — فما أُخذ فعلاً هو
-- `delivery_fee` (لم يكن للحقلين فرقٌ قبل اليوم)، **وطلبُ توصيلٍ مجّانيٍّ قديمٌ
-- أخذ سائقُه صفراً ويبقى صفراً** (لا استرجاعَ رجعيّ، لا إعادةَ دفع).

ALTER TABLE orders
    ADD COLUMN IF NOT EXISTS driver_fee bigint NOT NULL DEFAULT 0;

-- **تعبئةُ القائم**: أجرُ السائقِ كان = أجرةَ التوصيل المدفوعة، فيُنسخ كما هو.
UPDATE orders SET driver_fee = delivery_fee;
