-- **اتّجاهُ السائق يُحفظ مع أثره**
-- ══════════════════════════════════════════════════════════════════════
--
-- (المرحلة ١ من الملاحة، بأمر المالك ٢٠٢٦-٠٨-٢٠: «من المرحلة ١ تبدأ
--  البيانات الجديدة اللازمة مستقبلاً لـRahalGo Traffic… **قبل أيّ
--  Migration افحص الموجود أوّلاً**».)
--
-- # وما وُجد قبل أن يُكتب هذا
--
-- `driver_track` يحفظ اليوم: الموضعَ و`speed_mps` و`accuracy_m`
-- و`recorded_at`. **ثلاثةٌ من أربعةٍ موجودة** — **وينقص الاتّجاهُ
-- وحدَه.**
--
-- **فهذا أقلُّ تغييرٍ ممكن**: عمودٌ واحدٌ يقبل الفراغ.
--
-- # ولماذا يلزم الاتّجاه لاحقاً
--
-- **سرعةُ مقطعِ شارعٍ لا تُحسب بلا اتّجاه**: نقطتان على شارعٍ ذي
-- اتّجاهين **تقولان سرعةً واحدةً لطريقين مختلفين** — وأحدُهما مزدحمٌ
-- والآخرُ خالٍ.
--
-- **ولا يُبنى شيءٌ من هذا في المرحلة ١** — يُحفظ الرقمُ وحدَه.
--
-- # والتوافقُ الخلفيُّ محفوظ
--
-- **يقبل الفراغَ ولا افتراضَ له**: نسخةُ السائق المنشورةُ اليوم لا
-- ترسله، **فتُكتب صفوفُها بلا اتّجاهٍ كما كانت.** ولا يُكسر شيء.
--
-- **ولا قيدَ على المدى** — `NULL` مسموحة، **وقيدٌ يرفض الفراغَ يجعل
-- كلَّ نسخةٍ قديمةٍ تفشل في الكتابة.**
ALTER TABLE driver_track ADD COLUMN IF NOT EXISTS bearing_deg double precision
    CHECK (bearing_deg IS NULL OR (bearing_deg >= 0 AND bearing_deg < 360));
