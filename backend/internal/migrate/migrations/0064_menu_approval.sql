-- ٠٠٦٤ · مراجعةُ القائمة قبل النشر — **إعدادٌ كان يَعِد ولا يفعل**
--
-- # الحادثة
--
-- `merchants.menu_requires_approval` **مفتاحٌ مُعرَّفٌ ومحفوظٌ في القاعدة منذ
-- الهجرة ٠٠٠٩، ولا يقرؤه سطرٌ واحدٌ في المشروع.** فُحصت الأربعون مفتاحاً
-- واحداً واحداً (٢٠٢٦-٠٨-٠٤) — **وهو الوحيدُ الميّت.**
--
-- **وإعدادٌ يكذب أخطرُ من إعدادٍ غائب**: من شغّله ظنّ أنّ قوائمَ المتاجر صارت
-- تُراجَع قبل النشر، **وهي تُنشر كما هي.** والغائبُ يُسأل عنه، **والكاذبُ
-- يُبنى عليه.**
--
-- # ولماذا يستحقّ أن يُبنى لا أن يُحذف
--
-- المتجرُ يملك أن يضيف صنفاً ويعدّل سعرَه (`POST /merchant/stores/{id}/menu/items`)،
-- **وما يضيفه يظهر للزبون في اللحظة نفسِها.** فسعرٌ كُتب بخطأ صفرٍ زائد يُباع
-- به، **وصنفٌ لا تريده المنصةُ في سوقها يُعرض فيه.**
--
-- # وما يُراجَع وما لا يُراجَع
--
-- **المحتوى يُراجَع** — الاسمُ والوصفُ والسعرُ والصورة: هي ما يراه الزبون.
-- **والإتاحةُ لا تُراجَع** — «نفد الصنف» قرارُ مطبخٍ في لحظته، **ومراجعتُه
-- تجعل المتجرَ يبيع ما نفد حتى نستيقظ.**
--
-- # والقائمُ يبقى منشوراً
--
-- `DEFAULT true` **وما وُجد قبل اليوم يُقرّ**: تشغيلُ المفتاح لا يُخفي قائمةَ
-- متجرٍ يعمل منذ شهر. **ومراجعةٌ بأثرٍ رجعيّ تُطفئ السوقَ في لحظةٍ واحدة.**

ALTER TABLE menu_items
	ADD COLUMN IF NOT EXISTS approved boolean NOT NULL DEFAULT true;

-- **وسببُ الردّ يُقال لصاحبه** — «رُفض» بلا كلمةٍ يُعاد إرسالُه كما هو.
ALTER TABLE menu_items
	ADD COLUMN IF NOT EXISTS review_note text NOT NULL DEFAULT '';

-- **والطابورُ يُقرأ بالأقدم أوّلاً** — من انتظر أطولَ أَولى.
CREATE INDEX IF NOT EXISTS menu_items_pending_idx
	ON menu_items (created_at) WHERE NOT approved;
