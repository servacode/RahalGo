-- # ٤ · «استلمتها» على الطلب الجديد (القرار ٥)
--
-- **رنينٌ متكرّرٌ للطلب الجديد حتّى يضغط موظّفٌ «استلمتها»** — والضغطةُ تُسكت
-- الرنينَ عند المكتب كلِّه لا عند صاحبها وحدَه، **فتُحفظ في الطلب لا في متصفّح.**
ALTER TABLE orders ADD COLUMN IF NOT EXISTS office_seen_at timestamptz;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS office_seen_by uuid REFERENCES users(id) ON DELETE SET NULL;
