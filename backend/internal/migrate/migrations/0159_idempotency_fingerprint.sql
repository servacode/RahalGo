--
-- (`CAF-02` · `13-029` — قرارُ المالك ٢٠٢٦-٠٩-٢١.)
--
-- # العلّة
--
-- **المفتاحُ يحمي من الإعادةِ نفسِها**: نداءٌ انقطع رُدُّه يُعاد بالمفتاح
-- نفسِه فيُرجَع المحفوظُ ولا يُنفَّذ ثانيةً. **لكنّه لا يحرس المحتوى**:
-- **لو أُعيد المفتاحُ نفسُه مع جسمٍ مختلف** — سلّةٌ عُدّلت، عنوانٌ تبدّل —
-- **رُدَّ عليه ردُّ الطلب الأوّل** كأنّه هو، **فيظنّ الزبونُ أنّ تعديلَه
-- وقع وهو لم يقع.** أو — أخطرُ — **لو غيّر العميلُ الجسمَ ونسي أن يُدوّر
-- المفتاح، نُفِّذ طلبٌ لا يقصده على ردّ طلبٍ يقصده.**
--
-- # والحلّ بصمةٌ دلاليّةٌ للجسم
--
-- **بصمةُ `SHA-256` تُحسَب من حقول الطلب ذاتِ المعنى** (الأصناف والكمّيّات
-- والخيارات والدفع والعنوان والإحداثيّات والملاحظات) **دون العابر منها**
-- (المفتاحُ نفسُه، الطوابعُ الزمنيّة، ترتيبُ الأصناف في السلّة).
--
-- **فمفتاحٌ عاد ببصمةٍ مطابقة** ⇒ إعادةٌ حقيقيّة، يُرجَع المحفوظ.
-- **ومفتاحٌ عاد ببصمةٍ مختلفة** ⇒ `409 idempotency_key_reused`، **ولا
-- تنفيذَ ثانٍ.**
--
-- # ولا حشوَ للتركة
--
-- **العمودُ يقبل `NULL`** — **وصفوفُ ما قبل هذه الهجرة تبقى بلا بصمة**:
-- لا بصمةَ عندها فلا حكمَ عليها، **فتُعامَل كما كانت** (إعادةٌ أو ردٌّ
-- محفوظ) حتّى يُقلّمها الاحتفاظُ خلال أربعٍ وعشرين ساعة. **ولا حسابَ بأثرٍ
-- رجعيّ**: لا يُملأ العمودُ لصفٍّ قائم — **جسمُه الأصليُّ لم يُحفَظ، فأيُّ
-- بصمةٍ تُحسَب له اليوم كذبةٌ لا حقيقة.**
--
-- **ولا مساسَ بالدفتر ولا بحساب المحفظة ولا بخزينةٍ** — هذا حرسُ محتوى
-- الطلب لا غير.

ALTER TABLE idempotency_keys
    -- **بصمةُ جسم الطلب** — `bytea` لأنّها بايتاتُ `SHA-256` خام (٣٢ بايت)،
    -- **و`NULL` تعني «صفٌّ بلا بصمة»**: من قبل الهجرة، أو نقطةٌ لا تُبصَم.
    ADD COLUMN IF NOT EXISTS request_fingerprint bytea;
