-- **رمزُ الأدمن — طبقةٌ ثانيةٌ فوق كلمة المرور.**
--
-- (قرارُ المالك ٢٠٢٦-٠٨-١٠: «يجب أن يكون هناك للأدمن رمزُ دخولٍ ثانٍ من
--  ٤ أرقام… مثل تحقّقٍ ثنائيٍّ فقط للأدمن، لأنّه بنفس اللوحة تحسّباً
--  للاختراق».)
--
-- # ولماذا صار لازماً الآن
--
-- **بابُ الدخول صار واحداً للجميع** — وهو الصواب، **لكنّه يعني أنّ من سرق
-- كلمةَ مرور المالك يصل لوحتَه من العنوان نفسِه الذي يفتحه كلُّ زبون.**
-- ولا عنوانَ خفيٌّ يحميها بعد اليوم.
--
-- # ويُخزَّن مُعمًّى لا نصّاً
--
-- **أربعةُ أرقامٍ نصّاً في القاعدة تُقرأ بنظرة** — ومن بلغ القاعدة بلغ
-- الرمزَ والكلمةَ معاً، **فسقطت الطبقتان بضربةٍ واحدة.** والتعميةُ نفسُها
-- التي لكلمة المرور (argon2id)، **ولا دالّةَ ثانيةٌ تُختار لها**.
--
-- # ولا يُفرض على الجميع
--
-- **العملياتُ والماليةُ خارجَه** بقرار المالك — والعمودُ فارغٌ لهم، **ولا
-- يُطلب ممّن لا رمزَ له.** وفراغُ العمود عند الأدمن يعني «لم يُضبط بعد»،
-- **فيُطلب ضبطُه عند أوّل دخولٍ ولا يُترك اختياريّاً فيُنسى.**
ALTER TABLE users ADD COLUMN IF NOT EXISTS admin_pin_hash text;

-- **ووقتُ آخر تبديلٍ يُقرأ في «حسابي»** — ومن لا يعرف متى بدّله آخرَ مرّة
-- لا يعرف أيبدّله الآن.
ALTER TABLE users ADD COLUMN IF NOT EXISTS admin_pin_set_at timestamptz;
