-- **«المنصة أغلقت، يجب عليك إغلاق دوامك»** — قرار المالك ٢٠٢٦-١١-٠٦
-- ══════════════════════════════════════════════════════════════════════
--
-- دوامٌ بقي مفتوحاً طول الليل **يضلّ دواماً واحداً**: لا يُقسم الصبح ولا يُسكَّر آليّاً.
-- لكن لما تسكّر المنصّة (جدولُ الدوام، أو زرّ «مسكّرين») **كلُّ سائقٍ لسّا بدوامه يوصله
-- إشعارٌ واحد**، **وإذا ما سكّره لليوم التالي** يوصله لما تفتح المنصّة **تذكيرٌ واحد** إنّ
-- دوامه من أمس لسّا مفتوح. ولا تسكير آليّ ولا إلحاح ولا تصعيد للعمليّات.
--
-- **ومرّةً لكلّ سائقٍ وإغلاق** — الختمُ مفتاحه (سائق · يوم المنصّة · نوع)، فإعادةُ تشغيل
-- الخادم أو جولتان لا تكرّران شيئاً (كختم تذكير المعالم `landmark_quota_reminders`).
--
--   platform_closed  أُرسل «المنصة أغلقت» — `day` يومُ المنصّة لحظةَ الإغلاق
--   next_day         أُرسل «دوامك من أمس لسّا مفتوح» — `day` يومُ الإغلاق نفسه
CREATE TABLE IF NOT EXISTS driver_shift_reminders (
    driver_id uuid        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    day       date        NOT NULL,
    kind      text        NOT NULL CHECK (kind IN ('platform_closed', 'next_day')),
    -- **الدوامُ الذي ذُكِّر به** — تذكيرُ اليوم التالي له وحدَه: سكّره وفتح غيره ⇒ لا تذكير.
    shift_id  uuid        REFERENCES driver_shifts (id) ON DELETE CASCADE,
    sent_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (driver_id, day, kind)
);
