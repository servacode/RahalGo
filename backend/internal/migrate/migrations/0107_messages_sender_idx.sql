-- **فهرسُ من كتب — لسجلّ محادثاته.**
--
-- (شكوى المالك ٢٠٢٦-٠٨-١٥: «الدردشاتُ السابقةُ تتأخّر كثيراً لتفتح».)
--
-- **وسجلُّ المحادثات يسأل سؤالين**: ما الطلباتُ التي أنا طرفٌ فيها،
-- **وما الطلباتُ التي كتبتُ فيها بيدي وإن سُحبت منّي.**
--
-- **والثاني كان يُجاب بمسحِ الجدول كلِّه**: فهارسُ `order_messages` كانت
-- على `order_id` وحدَه — **تُجيب «ماذا في هذا الطلب؟» ولا تجيب «أين
-- كتب هذا الرجل؟».**
--
-- **وهو السؤالُ الذي يُسأل مرّةً واحدةً لكلّ فتحةِ سجلّ** — ويكبر
-- جوابُه بكلّ رسالةٍ تُكتب في المنصّة، **لا برسائله هو.**
CREATE INDEX IF NOT EXISTS order_messages_sender_idx
  ON order_messages (sender_id, order_id);
