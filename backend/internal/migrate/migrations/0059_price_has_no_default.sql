-- ٠٠٥٩ · **سعرُ الشراء بلا افتراض** — والنسيانُ يُصرخ لا يُنتج مجّاناً
--
-- # ما كشفته التجربةُ الحيّة (٢٠٢٦-٠٨-٠٢)
--
-- أُضيف `merchant_price` في `0056` بـ`DEFAULT 0`. **والقائمُ رُحّل بالسعر
-- نفسِه فلا خلل فيه** — لكنّ كلَّ إدراجٍ جديدٍ ينسى العمودَ يضع **صفراً**.
--
-- **وسعرُ البيع يُحسب من سعر الشراء**، فصفرُ الشراء **صفرُ البيع**: قائمةٌ
-- كاملةٌ تُعرض مجّاناً.
--
-- ووقع فعلاً: **الزراعةُ تُدرج `price` ولا تُدرج `merchant_price`** — فظهرت
-- أصنافُ المتجرين كلُّها بصفر. **ولم يشتكِ شيء**: لا خطأ في السجلّ، ولا
-- اختبارٌ يسقط، **والقائمةُ تُعرض كاملةً وكلُّ سعرٍ فيها صفر.**
--
-- # ولماذا الافتراضُ نفسُه هو الخلل
--
-- **افتراضٌ صالحٌ يُخفي النسيان.** لو لم يكن للعمود افتراضٌ لَسقط الإدراجُ في
-- أوّل تجربة، **ولَقيل لنا أين الخطأ في السطر الذي فيه.**
--
-- **وصفرٌ في عمود سعرٍ ليس قيمةً محايدة** — هو «مجّاناً». والقاعدةُ لا تعرف
-- الفرقَ بين «لم يُذكر» و«بلا ثمن»، **فتكتب الثانيةَ ونحن نعني الأولى.**
ALTER TABLE menu_items ALTER COLUMN merchant_price DROP DEFAULT;

-- **ولقطةُ البند كذلك.** بندُ طلبٍ بلا سعر شراءٍ يعني مستحقَّ متجرٍ صفراً —
-- **بضاعةٌ خرجت من مطبخه ولا يُقيَّد له شيء.**
ALTER TABLE order_items ALTER COLUMN merchant_price DROP DEFAULT;

-- **وما وقع يُصلَح لا يُترك.** أصنافٌ أُدرجت بصفرٍ بين ٠٠٥٦ واليوم تُعاد إلى
-- سعرها المعروض — **وهو ما كان يقبضه المتجرُ قبل نموذج السعرين.**
UPDATE menu_items SET merchant_price = price
WHERE merchant_price = 0 AND price > 0;

UPDATE order_items SET merchant_price = unit_price
WHERE merchant_price = 0 AND unit_price > 0;
