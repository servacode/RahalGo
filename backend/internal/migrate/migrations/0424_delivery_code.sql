-- يصل الكودُ الزبونَ بأيّ قناة، أو أعفته العمليّات.
--
-- **والمحاولاتُ تُعدّ**: خمسٌ خاطئةٌ تُقفل الطلبَ حتّى تتدخّل العمليّات.
