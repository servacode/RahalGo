-- **حجزُ الدعوة بالرقم — قرارُ المالك 2026-10-05**
-- ══════════════════════════════════════════════════════════════════════
--
-- كانت صفحةُ الدعوة تطلب من الصديق أن **ينسخ الرمزَ بيده** ثمّ يلصقه في
-- التطبيق — **ومن نزّل ملفّاً مباشراً لا `referrer` له يضيع رمزُه.**
--
-- فصار الصديقُ يكتب رقمَه في الصفحة (`POST /public/invite/claim`)، **ويُحفظ
-- هنا رقمُه مع رمز من دعاه**، **وعند تأكيد التسجيل بلا `ref`** يُقرأ الحجزُ
-- بالرقم فيُنسب الحسابُ ثمّ يُحذف الحجز.
--
-- # حجزٌ واحدٌ للرقم — والأحدثُ يغلب
--
-- **من فتح رابطَين فآخرُ ما ضغطه هو ما قصده** — فالإدراجُ يكتب فوق القديم
-- (`ON CONFLICT (phone) DO UPDATE`) ويجدّد موعده.
--
-- # ويسقط بعد ثلاثين يوماً
--
-- **والقراءةُ تشترط `created_at` خلال ثلاثين يوماً** — فالقديمُ لا يُنسب
-- ولو بقي صفُّه، **ويُكنَس عند كلّ حجزٍ جديد.**
CREATE TABLE IF NOT EXISTS invite_claims (
    phone       TEXT PRIMARY KEY,           -- مطبَّعٌ كـ users.phone: +9639XXXXXXXX
    invite_code TEXT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS invite_claims_created_idx ON invite_claims (created_at);
