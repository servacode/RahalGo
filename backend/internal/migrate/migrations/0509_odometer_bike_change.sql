--
-- الرقمُ الأقلّ من آخر رقمٍ مرفوض (هجرة ٠٥٠١) — فسائقٌ بدّل درّاجته (أو انبدّل عدّادها)
-- كان يعلق ولا يفتح دوامَه ولا يسكّره لحتى تصحّح العمليّات آخرَ رقم.
--
-- **فصار يقدر يقول «بدّلت الدرّاجة»** ويصوّر العدّادَ الجديد ويكتب رقمَه: المحرّكُ يقبل
-- الرقمَ (أقلّ أو أكثر) **بهالعلامة الصريحة وحدها**، ويعلّم القراءة هون، ويبلّغ المراقبة.
--
-- **ولا مسافةَ تُحسب عبر التبديل**: كلُّ فرقٍ طرفُه الثاني قراءةُ تبديل (حسب العدّاد ·
-- التقريبي · مشى خارج الدوام) يُترك فارغاً — الرقمان من عدّادين مختلفين.
--
-- **وتبديلٌ واحدٌ لكلّ سائق باليوم** (يوم الحساب) — وما زاد يُرفض كالعادة وتصحّحه العمليّات.
ALTER TABLE driver_odometer_readings
    ADD COLUMN IF NOT EXISTS bike_change boolean NOT NULL DEFAULT false;

CREATE INDEX IF NOT EXISTS driver_odometer_bike_change_idx
    ON driver_odometer_readings (driver_id, created_at DESC) WHERE bike_change;
