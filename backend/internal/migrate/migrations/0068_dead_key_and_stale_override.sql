-- مفتاحٌ ميّتٌ ولقطةٌ متأخّرة — أثران كشفهما الترحيلُ ٠٠٦٧.
--
-- # ١) مفتاحٌ باسمٍ مقلوب لا يقرؤه أحد
--
-- الترحيلُ ٠٠٥٦ بذر `merchants.commission_percent_default` بقيمة ٢، **والذي
-- تقرؤه الشيفرةُ كان `merchants.default_commission_percent`** — كلمتان
-- مقلوبتان. فبقي في القاعدة منذ ٢٠٢٦-٠٨-٠٢ **رقمٌ يبدو عمولةً ولا أثرَ له**،
-- وليس في الكتالوج فلا يظهر في اللوحة أصلاً.
--
-- **وهو الخطرُ الذي وصفه الترحيلُ السابق بلفظه**: مفتاحٌ مهجورٌ يُضبط يوماً
-- ظنّاً أنّه الفاعل، **فيُغيَّر رقمٌ لا يقرؤه أحد ويبقى الأثرُ غائباً** —
-- ويُبحث عن العطب في كلّ مكانٍ إلّا في الاسم.

DELETE FROM app_settings WHERE key = 'merchants.commission_percent_default';

-- # ٢) لقطةٌ بقيت تحكم متجراً بعد أن تغيّر العامّ
--
-- الترحيلُ ٠٠٦٧ أبقى كلَّ متجرٍ رقمُه غيرُ العامّ **لأنّ اختلافَه يُقرأ
-- اتفاقاً**. وكان العامُّ يومَها ٣، ومتجرُ التجربة على ١٠ — **فقُرئ اتفاقاً
-- وهو لقطةُ يومِ إنشائه**: وُلد حين كان العامُّ عشرة، ثمّ نزل العامُّ ولم
-- ينزل معه.
--
-- **ولا سبيل إلى التفريق بينهما في القاعدة**: اتفاقٌ حقيقيٌّ ولقطةٌ متأخّرة
-- رقمان متطابقان. فالتفريقُ قرارُ صاحبِ المنصة لا استنتاجُ ترحيل.
--
-- **وقرارُه قيل صراحةً** (٢٠٢٦-٠٨-٠٤): «لازم كلُّ المشروع يأخذ الإعداداتِ
-- هذه بحيث تُطبَّق بشكلٍ حقيقيٍّ فوريٍّ عند أيّ تغيّر».
--
-- فتُفرَّغ التجاوزاتُ كلُّها **مرّةً واحدةً عند هذا الحدّ**: تبدأ المنصةُ من
-- «الكلُّ يتبع العامّ»، **ومن يُتّفق معه على غيره يُوضع له رقمُه من صفحته
-- بعد اليوم** — فيصير التجاوزُ قراراً مؤرّخاً لا إرثاً مجهولاً.

UPDATE merchants SET commission_percent = NULL WHERE commission_percent IS NOT NULL;
