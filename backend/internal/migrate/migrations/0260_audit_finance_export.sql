-- # 1 · الماليّةُ تقرأ السجلّ
--
-- **نُزعت منها `audit.read` في الهجرة 0141** لأنّها وُصفت «قراءةَ أمنٍ لا
-- مال». **وقرّر المالكُ أن تعود** — والمبالغُ في السجلّ تبقى ظاهرةً لها
-- لأنّها تملك `finance.read` (`canSeeAuditMoney`).
INSERT INTO role_capabilities (role_code, capability_code) VALUES
    ('finance', 'audit.read')
ON CONFLICT DO NOTHING;

-- # 2 · التصديرُ قدرةٌ لحالها
--
-- **كان التصديرُ لكلّ من يقرأ** — وصار قدرةً تُمنح للأدمن وللمالك الأعلى
-- وحدَهما (`audit.export`). **والعرضُ يبقى لكلّ من ملك `audit.read`.**
-- ومن أراد غداً أن يمنحها لدورٍ آخر منحها من اللوحة بلا سطرِ شيفرة.
INSERT INTO role_capabilities (role_code, capability_code) VALUES
    ('admin',             'audit.export'),
    ('owner_super_admin', 'audit.export')
ON CONFLICT DO NOTHING;
