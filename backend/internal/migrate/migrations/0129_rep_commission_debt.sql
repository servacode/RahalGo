-- ══════════════════════════════════════════════════════════════════════
-- **التزامُ المندوب — عمولةٌ سُحبت عن طلبٍ استُرِدّ**
-- ══════════════════════════════════════════════════════════════════════
--
-- (`XG-10` · `PG-6` — دورةُ إصلاحٍ ٢، ٢٠٢٦-٠٩-٠٦.)
--
-- # ما يوجبه العقد
--
-- **`RQ-5 = APPROVED` (قرارُ المالك النهائيّ ٢٠٢٦-٠٩-٠٥):**
--
--     ORDER REVENUE REVERSED → RELATED REP COMMISSION REVERSED
--
-- **«وإن كانت العمولةُ قد سُحبت فعلاً، تُعالَج التزاماً أو رصيداً سالباً
-- وفق النظام المالي — ولا يُمحى التاريخ.»**
--
-- # ولماذا عمودٌ لا رصيدٌ سالب
--
-- **`CHECK (balance >= 0 OR is_treasury)` قيدٌ قائمٌ يحرس المحافظ** —
-- **وفتحُه لمندوبٍ يفتحه للجميع.** **والالتزامُ خارجَ المحفظة يُبقي
-- القيدَ كما هو.**
--
-- **وهي آليّةُ `merchants.debt` نفسُها** — قائمةٌ منذ مسار ردّ البضاعة،
-- **ومُثبَتةٌ ومقروءةٌ في التحصيل.** **ولا آليّةَ ثالثةٌ تُخترَع.**
--
-- # واسمٌ يقول ما هو
--
-- **`commission_debt` لا `debt`** — **وعمودٌ عامٌّ على `users` يُقرأ
-- ديناً في كلّ شيء**، فيُستعمل يوماً لما لم يُقصَد به.
--
-- # وأماميّةٌ لا تمسّ صفّاً
--
-- **افتراضُها صفرٌ** — **فكلُّ حسابٍ قائمٍ يصير بلا التزامٍ بلا كتابة**،
-- ولا سلوكَ يتبدّل لمن لم يُستردَّ طلبُ متجرِه.
ALTER TABLE users
    ADD COLUMN IF NOT EXISTS commission_debt bigint NOT NULL DEFAULT 0;

-- **ولا التزامَ سالب** — **والسالبُ يعني أنّ المنصّة تدين للمندوب**،
-- وذلك مالٌ يُقيَّد في محفظته لا في عمود دَين.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                    WHERE conname = 'users_commission_debt_ck') THEN
        ALTER TABLE users ADD CONSTRAINT users_commission_debt_ck
            CHECK (commission_debt >= 0);
    END IF;
END $$;

-- **ومن عليه التزامٌ قِلّة** — فيُفهرَس جزئيّاً.
CREATE INDEX IF NOT EXISTS users_commission_debt_idx
    ON users (id) WHERE commission_debt > 0;
