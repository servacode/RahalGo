--
-- كانت الأمانة باتجاه واحد: «استلم من شخص ونوصلها لبابك». والزبون اللي بدّو يبعت أمانة لحدا
-- ما كان عندو خيار — فكان الكابتن يروح للمستلم ويرجع بالأمانة لبيت الزبون، بالعكس.
--
--   receive  (الافتراض — كل الأمانات القديمة والتطبيقات القديمة)  الاستلام من الشخص، التسليم لعنوان الزبون.
--   send     الاستلام من عنوان الزبون (pickup_override)، التسليم لموقع المستلم (dropoff) — وموقعه
--            بيوصل بالواتساب، فلحد ما يوصل `dropoff_known = false` والكابتن ما بيتوجّه لنقطة كاذبة.
--            والاسم والرقم بـ amanah_holder_* هنّي المستلم. والأجرة بيدفعها المرسل عند الاستلام،
--            والدفتر ما بيتغيّر (بيتسجّل عند التسليم متل اليوم). والكود بيوصل للمستلم بالواتساب.

ALTER TABLE orders ADD COLUMN IF NOT EXISTS amanah_direction text NOT NULL DEFAULT 'receive'
    CHECK (amanah_direction IN ('receive', 'send'));
