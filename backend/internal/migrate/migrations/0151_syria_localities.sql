-- ══════════════════════════════════════════════════════════════════════
-- **مراكزُ المحافظات السوريّة — بذرٌ لا مخطَّط** (`AG`، ٢٠٢٦-٠٩-١٤)
-- ══════════════════════════════════════════════════════════════════════
--
-- # المسألة
--
-- **وإحداثيّةٌ في دمشقَ كانت تُصنَّف `area_not_supported`** — **صحيحةً
-- في حكمها، عاجزةً عن تسمية مكانها.** **والمطلوبُ «رحّال غو لم يصل إلى
-- دمشق بعد» لا «لم يصل إلى منطقتك».**
--
-- **وأربعَ عشرةَ محافظةً مبذورةٌ بأسمائها** (هجرة ٠١٢٢) **بلا هندسةٍ
-- واحدة** — **ومدينةٌ واحدةٌ مبذورةٌ بمركزها ونصفِ قطرها: الرقّة.**
--
-- # ولمَ لا تُرسَم حدودُ المحافظات
--
-- **ولا حدودَ إداريّةً في المستودع** — **لا ملفَّ `geojson` ولا
-- `shapefile`**، **وأساسُ الخرائط على الخادم مقصوصٌ بمستطيلاتٍ لاستخراج
-- البلاطات لا بحدودٍ إداريّة.** **ومُرمِّزُ العناوين نداءٌ إلى طرفٍ
-- ثالثٍ حيّ** — **ونهى المالكُ أن تعتمد الإتاحةُ عليه.**
--
-- **فلا تُخترَع مضلَّعاتٌ تقريبيّة** — **وحدٌّ مرسومٌ بالحدس يُقرأ حقيقةً
-- بعد شهر**، **ويُبنى عليه ما لا يحتمله.**
--
-- # والمدنُ مركزٌ ونصفُ قطرٍ — وهو النموذجُ المقصود
--
-- **ومكتوبٌ في هجرة ٠١١٦ نصّاً**: «**ومركزٌ ونصفُ قطرٍ يقولان أين هي** —
-- تُعرف مدينةُ الزبون من عنوانه بلا أن يختار». **ويقرؤه `city_filter`
-- اليومَ ليعرف سوقَ الزبون.**
--
-- **فهذا امتدادُ نموذجٍ قائمٍ لا نموذجٌ ثانٍ** — **وإحداثيّاتُ مراكز
-- المحافظات وقائعُ لا تُخترَع**، **ونصفُ القطر هو افتراضُ المشروع نفسُه
-- (٢٥ كم)**، **ويُعدَّل من اللوحة لكلّ مدينةٍ على حدة.**
--
-- **وهو تصنيفُ موضعٍ لا حدُّ خدمة** — **والتوصيلُ يبقى لـ`delivery_zones`
-- و`ZoneAt` وحدَها.**
--
-- # وكلُّها مُطفأةٌ إلّا ما كان مُطلَقاً
--
-- **و`cities.active` هي رايةُ «أُطلقت الخدمةُ هنا»** — يقرؤها
-- `city_filter` فيحجب سوقَ من لا مدينةَ فعّالةً له. **فتُبذَر الثلاثَ
-- عشرةَ مُطفأةً**: **تُسمّى ولا تُخدَم**، **والرقّةُ وحدَها تبقى كما
-- هي.**
--
-- **ولا يتبدّل تصفّحٌ ولا طلبٌ ولا تغطية** — **`city_filter` يشترط
-- `c.active`**، **فالمُطفأةُ لا تدخل حسبتَه أصلاً.**
--
-- # وما يبقى مجهولاً يبقى مجهولاً
--
-- **وقريةٌ في البادية لا يحويها نصفُ قطرِ مركز** — **فتقع على
-- `area_not_supported` كما كانت.** **ولا يُسمّى ما لا يُعرَف.**
--
-- **وريفُ دمشقَ لا يُبذَر مدينةً** — **وهو محافظةٌ تحيط بدمشقَ ولا
-- مركزَ لها يُميَّز عنها بنصف قطر**، **ومركزان متداخلان يجعلان التسميةَ
-- قرعةً.**

INSERT INTO cities (name, center, radius_m, active, sort_order, district_id)
SELECT v.name,
       ST_SetSRID(ST_MakePoint(v.lng, v.lat), 4326)::geography,
       25000,
       false,
       v.ord,
       d.id
FROM (VALUES
    -- الاسم        · العرض   · الطول   · الترتيب · منطقةُ المركز
    ('دمشق',        33.5138, 36.2765, 20, 'مركز دمشق'),
    ('حلب',         36.2021, 37.1343, 21, 'مركز حلب'),
    ('حمص',         34.7308, 36.7090, 22, 'مركز حمص'),
    ('حماة',        35.1318, 36.7578, 23, 'مركز حماة'),
    ('اللاذقية',    35.5196, 35.7915, 24, 'مركز اللاذقية'),
    ('طرطوس',       34.8890, 35.8866, 25, 'مركز طرطوس'),
    ('إدلب',        35.9306, 36.6339, 26, 'مركز إدلب'),
    ('الحسكة',      36.5024, 40.7477, 27, 'مركز الحسكة'),
    ('دير الزور',   35.3359, 40.1408, 28, 'مركز دير الزور'),
    ('درعا',        32.6189, 36.1021, 29, 'مركز درعا'),
    ('السويداء',    32.7094, 36.5694, 30, 'مركز السويداء'),
    ('القنيطرة',    33.1256, 35.8244, 31, 'مركز القنيطرة')
) AS v(name, lat, lng, ord, district)
JOIN districts d ON d.name = v.district
-- **ومنطقةٌ لم تُبذَر لا تُوقف الهجرة** — الانضمامُ يُسقط صفَّها وحدَه.
ON CONFLICT (name) DO NOTHING;

-- ══════════════════════════════════════════════════════════════════════
-- **والرقّةُ تُنسَب إلى منطقتها إن لم تكن** — فتُعرَف محافظتُها.
-- ══════════════════════════════════════════════════════════════════════
--
-- **وهجرةُ ٠١١٦ بذرتها قبل أن تُوجد المناطق** (٠١٢٢) — **فقد تبقى بلا
-- نسبة.** **ومدينةٌ بلا منطقةٍ لا تُعرَف محافظتُها.**
UPDATE cities
   SET district_id = (SELECT id FROM districts WHERE name = 'مركز الرقة')
 WHERE name = 'الرقة' AND district_id IS NULL;

-- **ودليلٌ على النسبة** — تُقرأ في كلّ تصنيفِ موضع.
CREATE INDEX IF NOT EXISTS cities_district_idx ON cities (district_id);
