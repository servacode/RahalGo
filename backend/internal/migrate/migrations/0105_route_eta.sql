-- **زمنُ الطريق كما تقوله الخريطة — يُلتقط في لحظته ويُجمَّد**
-- ══════════════════════════════════════════════════════════════════════
--
-- (قرارُ المالك ٢٠٢٦-٠٨-١٢: «يجب أن يكون لدينا زمنٌ افتراضيٌّ تقريبيّ،
--  وعلامةُ الإكس يعني أكيد ما رح نعدم السائق أو المتجر، ولكن حركةٌ ذكيّةٌ
--  للمنصّة فقط».)
--
-- # ولماذا عمودان لا حسابٌ عند العرض
--
-- **المسافةُ المحفوظة خطُّ طائرٍ لا طريقُ شوارع** (`ST_Distance`)، وقِيس
-- الفرقُ على خمسة أزواجٍ حقيقيّةٍ في الرقّة: **الشارعُ أطولُ بـ٤٩٪
-- وسطيّاً، وبلغ ٦٤٪ في واحدة.** فمهلةٌ محسوبةٌ منه تضع علامةً حمراءَ على
-- سائقٍ سار الطريق الصحيح.
--
-- **والفرقُ ليس ثابتاً حتّى يُضرب في معامل**: من ٢٣٪ إلى ٦٤٪ في خمس
-- عيّنات — **ومعاملٌ واحدٌ يظلم بعضها ويسامح بعضها.**
--
-- # ولماذا يُجمَّد في لحظته
--
-- **موضعُ السائق يتحرّك.** فلو سُئلت الخريطةُ اليومَ عن طلب أمس **لَقِيست
-- من بيته لا من حيث كان** — والقياسُ يجب أن يُلتقط حين وقع.
--
-- # وفارغٌ يعني «لا يُعرف» لا «صفر»
--
-- **الخريطةُ تتعطّل، والعنوانُ قد يكون بلا إحداثيّ.** فيبقى العمودُ
-- فارغاً **ويبقى الخطُّ بلا علامةٍ كما هو اليوم** — ولا يُوسَم أحدٌ
-- بتأخيرٍ لم يُقَس.

