-- ٠٠٦١ · إثباتُ التسليم — **صورةٌ وإحداثياتٌ ووقت**
--
-- # لماذا
--
-- قاعدتُنا: **«الزبونُ يُصدَّق أوّلَ مرّة»** — والمنصةُ تتحمّل. **وقاعدةٌ بلا
-- دليلٍ تكلفةٌ بلا سقف**: من عرف أنّ كلمتَه تكفي قالها مرّةً بعد مرّة، **ولا
-- يبقى للسائق الصادق ما يدفع به عن نفسه.**
--
-- **والمشكلةُ ليست في تصديق الزبون، هي في أنّ لا شيءَ يُقاس عليه.** فيُقال
-- «كلمةٌ ضدّ كلمة» — **وهي ليست كلمةً ضدّ كلمة إن كان أحدُهما يحمل صورةً
-- بموقعٍ ووقت.**
--
-- # والمعيارُ العالميّ ثلاثةٌ لا واحد
--
--	الصورة       ←  تُظهر **موضعَ التسليم** لا الطردَ وحدَه: بابٌ، رقمٌ، معلَم
--	الإحداثيات   ←  **تُلتقط آلياً** فتثبت أنّه كان هناك
--	الوقت        ←  آليٌّ كذلك — لا يُكتب بيد
--
-- **وأهمُّها الإحداثيات**: صورةُ بابٍ قد تكون لأيّ باب، **وصورةٌ بإحداثياتٍ
-- على بُعد خمسة أمتارٍ من عنوان الزبون بيّنة.**
--
-- # والمسافةُ تُحسب لا تُخزَّن
--
-- **تُقاس ساعةَ السؤال من نقطتين محفوظتين** — موضعِ التسليم وعنوانِ الزبون.
-- ورقمٌ محسوبٌ ومخزَّنٌ يفترق عن مصدريه يوماً، **ويُحتجّ به وهو خطأ.**
ALTER TABLE orders ADD COLUMN IF NOT EXISTS pod_media_id uuid REFERENCES media(id) ON DELETE SET NULL;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS pod_at geography(Point, 4326);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS pod_taken_at timestamptz;

-- pod_skip_reason لماذا لم تُلتقط — **وفارغٌ حين التُقطت.**
--
-- **ولا يُترك التسليمُ رهينةَ كاميرا.** هاتفٌ لا يعمل، أو إذنٌ مرفوض، أو ليلٌ
-- لا يُرى فيه شيء — **وسائقٌ لا يستطيع إنهاء طلبٍ سلّمه فعلاً يقف في الشارع.**
--
-- **لكنّ التخطّي يُقال لا يمرّ صامتاً**: كلمةٌ تُكتب وتُقرأ يومَ النزاع.
-- **ومن تخطّى عشر مرّاتٍ يُقرأ ذلك في صفّه**، ومن تخطّى مرّةً لا يُلام.
ALTER TABLE orders ADD COLUMN IF NOT EXISTS pod_skip_reason text NOT NULL DEFAULT '';

