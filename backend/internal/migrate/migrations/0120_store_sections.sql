-- **أقسامُ المتجر — ما يبيعه هو لا ما تبيعه المنصّة**
-- ══════════════════════════════════════════════════════════════════════
--
-- (بلاغُ المالك 2026-08-26: «قسم السوق يجب أن يكون مخصّصاً — مو معقول
--  كل الأقسام تطلع عند كل المتاجر. مطعم تطلع المأكولات فقط، شو علاقته
--  بالأحذية؟»)
--
-- # ولماذا وقع
--
-- **و`platform-sections` تردّ كلَّ أقسام المنصّة النشطة** — بلا نظرٍ إلى
-- من يسأل. **فصاحبُ مطعم شاورما يفتح «أضف صنفاً» فيرى قائمةً فيها
-- أحذيةٌ وأدويةٌ وهدايا.**
--
-- **وقائمةٌ طويلةٌ أكثرُها لا يعنيه تُختار منها بالخطأ** — وصنفٌ في قسمٍ
-- غلط يظهر للزبون في المكان الخطأ، **أو لا يظهر أصلا.**
--
-- # ولماذا جدولٌ لا عمودٌ في المتجر
--
-- **والمتجرُ الواحدُ قد يبيع من قسمين وثلاثة**: كافتيريا تبيع شاورما
-- وحلويات ومشروبات. **وعمودٌ واحدٌ يحصره في قسم.**
--
-- # ولماذا لا يُشتقّ من الأصناف
--
-- **وكان يمكن أن نقول: أقسامُه ما وُجد فيها صنف** — لكنّ الأوّلَ يبقى
-- بلا قسم. **والمتجرُ الجديدُ يفتح «أضف صنفاً» فلا يجد شيئا.**
--
-- **فيُعلن هو ما يبيع، ثمّ يُقيَّد به.**
--
-- # وفارغٌ يعني الكلّ
--
-- **ومتجرٌ لم يختر بعدُ يرى القائمةَ كاملةً كما اليوم** — فلا يُكسر
-- متجرٌ قائمٌ يومَ يُطبَّق هذا الترحيل.
CREATE TABLE IF NOT EXISTS store_sections (
    store_id   uuid NOT NULL REFERENCES merchants (id) ON DELETE CASCADE,
    section_id uuid NOT NULL REFERENCES platform_sections (id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (store_id, section_id)
);

-- **والاستعلامُ الساخن: «أقسامُ هذا المتجر»** — يقع مع كلّ فتحةٍ
-- لنموذج الصنف.
CREATE INDEX IF NOT EXISTS store_sections_store_idx ON store_sections (store_id);
