-- **متى نزل الطلبُ إلى الطابور** — وقتٌ قائمٌ بذاته لا يُستنتَج.
--
-- ## العطبُ الذي كشفه
--
-- كان الراصدُ يقيس «طلبٌ بلا سائق» بـ`updated_at`:
--
--     WHERE status IN ('preparing','dispatching')
--       AND updated_at < now() - driver_timeout
--
-- **و`updated_at` يتغيّر مع أيّ تعديل** — لا مع النزول إلى الطابور وحده.
-- فتحويلُ الطلب إلى المتجر يمسّه، وعرضُ الترتيب على سائقٍ يمسّه، **وكلُّ
-- مسٍّ يُصفّر المؤقّت**.
--
-- **فطلبٌ يُعرض على خمسة سائقين بالتناوب لا يُنبَّه عنه أبداً** — لأن كلَّ
-- عرضٍ يُجدّد عمرَه. **وهو أسوأُ ما يقع براصد: يعمل ولا يرصد.**
--
-- ## ولماذا عمودٌ لا استنتاج
--
-- **الحقيقةُ تُسجَّل لحظةَ وقوعها.** واستنتاجُها لاحقاً من أثر الأحداث ممكنٌ
-- لكنّه يقرأ جدولاً كاملاً لكلِّ طلبٍ في كلِّ دورةِ رصد — **وسؤالٌ يُطرح كلَّ
-- دقيقةٍ يستحقّ جواباً جاهزاً**.
ALTER TABLE orders ADD COLUMN dispatched_at timestamptz;

COMMENT ON COLUMN orders.dispatched_at IS
    'متى نزل الطلب إلى طابور السائقين — يُقاس منه انتظارُ الإسناد';

-- الراصدُ يمرّ على غير المُسنَد كلَّ دورة
CREATE INDEX orders_dispatched_waiting_idx ON orders (dispatched_at)
    WHERE dispatched_at IS NOT NULL AND driver_id IS NULL;

-- **مهلةُ ظهور زرّ الإسناد اليدويّ** — مفتاحٌ مستقلٌّ بقرار المالك.
--
-- **والإسنادُ اليدويّ احتياطٌ لا أصل**: زرٌّ متاحٌ دائماً يُستعمل دائماً،
-- **فيصير هو الطريقَ ويصير الترتيبُ زينة**. فلا يظهر إلّا حين يعجز الطابور.
--
-- ومستقلٌّ عن مهلة التنبيه عمداً: **قد يريد المالكُ أن يعلم قبل أن يتدخّل.**
INSERT INTO app_settings (key, value) VALUES ('orders.manual_assign_after_min', '10'::jsonb)
    ON CONFLICT (key) DO NOTHING;
