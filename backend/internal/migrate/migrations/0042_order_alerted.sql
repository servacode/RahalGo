-- أثر الإنذار.
--
-- كانت الإنذارات تُحسب عند فتح الصفحة وتُعرض حمراء، ثم لا شيء: طلبٌ عالقٌ منذ
-- ساعة لا يوقظ أحداً. **من فتح الصفحة رآه، ومن انشغل لم يرَ** — وغرفةُ عمليات
-- تُدار بمن يتذكّر أن ينظر ليست غرفة عمليات.
--
-- والعلامة في القاعدة لا في ذاكرة الخادم: ذاكرةٌ تُفقد بإعادة تشغيل، فيُعاد
-- إنذار كل طلبٍ عالق دفعةً واحدة عند كل نشر. والإشعار المكرَّر يُدرَّب على
-- تجاهله فيصير كالصمت.
ALTER TABLE orders ADD COLUMN alerted_at timestamptz;

-- الحارس يسأل «من عَلِق ولم يُنذَر بعد؟» كل دقيقة
CREATE INDEX orders_pending_alert_idx ON orders (created_at)
    WHERE closed_at IS NULL AND alerted_at IS NULL;
