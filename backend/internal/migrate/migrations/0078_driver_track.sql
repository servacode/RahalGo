-- أثرُ السائق — **أين كان لا أين هو فقط.**
--
-- # لماذا لا يكفي آخرُ موضع
--
-- عمودُ `users.last_location` يجيب «أين هو الآن». **ولا يجيب سؤالين يحتاجهما
-- الإسنادُ الذكيّ:**
--
--	أواقفٌ عند المتجر أم عابرٌ بجانبه؟   ←  يلزم موضعان في وقتين
--	وإلى أين يتّجه؟                     ←  يلزم موضعان في وقتين
--
-- **ونقطةٌ واحدةٌ لا تقول اتّجاهاً**: من هو على بُعد أربعمئة مترٍ من المتجر
-- قد يكون قادماً إليه أو خارجاً منه، **والفرقُ بينهما هو الفرقُ بين إسنادٍ
-- صائبٍ وطلبٍ يضيع.**
--
-- (قرارُ المالك ٢٠٢٦-٠٨-٠٥: «يجب أن يكون هناك تعقّبٌ حقيقيٌّ لموقع السائق
-- بحيث نحدّد بشكلٍ صحيحٍ أنّه متوقّفٌ عند المتجر الأوّل ولم يتجاوز الثاني أو
-- يبتعد عنه».)
--
-- # وأثرٌ قصيرٌ لا سجلٌّ أبديّ
--
-- **السؤالُ عن الدقائق الأخيرة لا عن الشهر الماضي.** وجدولٌ يحفظ نبضةً كلَّ
-- دقيقةٍ لكلّ سائقٍ إلى الأبد **يبلغ الملايين في شهر** ولا يُسأل منه إلّا
-- الذيل. **فيُقلَّم مع كلّ كتابة** — انظر `driver_track.go`.

CREATE TABLE IF NOT EXISTS driver_track (
	id         bigserial PRIMARY KEY,
	driver_id  uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	at         geography(Point, 4326) NOT NULL,
	-- speed_mps سرعتُه لحظتَها إن قالها الجهاز — **وفارغُها لا تُخمَّن**:
	-- سرعةٌ محسوبةٌ من نقطتين تكذب عند أوّل قفزةٍ في دقّة الـGPS.
	speed_mps  double precision,
	-- accuracy_m دقّةُ القراءة — **ونقطةٌ بدقّةِ خمسِمئة مترٍ ليست نقطة**:
	-- تقول «هو في الحيّ» لا «هو عند الباب»، **والوقوفُ يُقاس بالأمتار.**
	accuracy_m double precision,
	created_at timestamptz NOT NULL DEFAULT now()
);

-- **والسؤالُ دائماً «آخرُ ما عند هذا السائق»** — فيُفهرَس به وبالوقت نازلاً.
CREATE INDEX IF NOT EXISTS driver_track_recent_idx
	ON driver_track (driver_id, created_at DESC);
