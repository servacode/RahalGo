-- ══════════════════════════════════════════════════════════════════════
-- **العنوانُ يُكتب أجزاءً لا سطراً**
-- ══════════════════════════════════════════════════════════════════════
--
-- (قرارُ المالك ٢٠٢٦-٠٨-١٨ بصورِ مرجعٍ: «المنطقة والمبنى · الشارع ·
--  الطابق · نوع العنوان» — واختار الأعمدةَ الحقيقيّةَ على التركيب في
--  سطرٍ واحد: «هكذا يكون العملُ احترافيّاً أكثر… ويمكن تعديلها أو
--  حذفها».)
--
-- # ولماذا الأعمدةُ لا السطر
--
-- **سطرٌ واحدٌ يُكتب ولا يُفكّ** — ومن أراد أن يعدّل طابقَه وجد نصّاً
-- عليه أن يُعيد كتابتَه كلَّه. **والتعديلُ هو ما طلبه المالك.**
--
-- # و`address_text` يبقى — مشتقّاً لا مكتوبا
--
-- **الطلباتُ تحفظ لقطةً منه** (`orders.address_text`) — **والسائقُ يقرأ
-- سطراً لا ثلاثةَ حقول.** فيبقى العمودُ ويُركَّب في المحرّك من الأجزاء:
-- **مصدرٌ واحدٌ للحقيقة، ونسخةٌ مشتقّةٌ تُكتب في موضعٍ واحد.**
--
-- # والقديمُ لا يُكسَر
--
-- **عناوينُ اليومَ سطرٌ بلا أجزاء** — تُنقل كلُّها إلى «المنطقة
-- والمبنى»: **أقربُ الحقول إلى ما كُتب**، ويبقى العنوانُ مقروءاً
-- ويُصحّحه صاحبُه حين يعدّله.

ALTER TABLE user_addresses
    -- **المنطقةُ والمبنى** — أوّلُ ما يقوله من يصف بيته، وهو الإلزاميّ.
    ADD COLUMN area_building text NOT NULL DEFAULT '',
    ADD COLUMN street        text NOT NULL DEFAULT '',
    -- **والطابقُ اختياريّ** — بيتٌ أرضيٌّ لا طابقَ له، **وحقلٌ إلزاميٌّ
    -- لا يخصّ الجميعَ يُملأ بأيّ شيءٍ ليمرّ.**
    ADD COLUMN floor         text NOT NULL DEFAULT '',
    -- **ونوعُ العنوان رمزٌ لا كلمة** — **ولفظٌ يُخزَّن يشيخ يومَ تُبدَّل
    -- الكلمةُ في الشاشة**، فتبقى صفوفُ الأمس بلفظ الأمس.
    ADD COLUMN kind          text NOT NULL DEFAULT 'other'
        CHECK (kind IN ('home', 'work', 'other'));

-- **ونقلُ القديم**: ما كُتب سطراً يصير «المنطقة والمبنى».
UPDATE user_addresses SET area_building = address_text WHERE area_building = '';

-- **ولا يُقبل عنوانٌ بلا منطقةٍ ومبنى** — كما لا يُقبل بلا نصٍّ اليوم.
ALTER TABLE user_addresses
    ADD CONSTRAINT user_addresses_area_not_empty CHECK (area_building <> '');
