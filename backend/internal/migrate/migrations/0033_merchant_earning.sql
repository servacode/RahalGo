-- مستحقّات المتجر — الطرف الوحيد في الدورة المالية بلا دفتر.
--
-- الزبون له محفظة، والمندوب له محفظة، والسائق له صندوق نقد — والمتجر لا شيء.
-- بينما المال يقع فعلاً: الزبون يدفع نقداً للسائق، والسائق يسوّيه **للمنصة**،
-- فتصير المنصة ممسكةً بمال المتجر بلا قيدٍ يقول كم لها وكم عليها. ولو سأل صاحب
-- المتجر «كم لي عندكم؟» لما كان في النظام جواب — والتسوية تصير ذاكرةً وأوراقاً،
-- وهو أول ما ينهار عند الخلاف.
--
-- **المستحقّ = subtotal − عمولة المنصة**، لا `total`: رسم التوصيل أجرُ خدمةٍ
-- تؤدّيها المنصة بسائقها، فليس من نصيب المتجر. والعمولة نفسها محسوبة على
-- `subtotal` في المحرّك، فالأساسان متسقان.
--
-- ولا جدول جديد: الدفتر العام (wallets + wallet_transactions) يفي — بقيوده
-- الذرّية ومنعِه الرصيد السالب وكشف حسابه المطبوع. الناقص كان **نوع الحركة**.
ALTER TABLE wallet_transactions DROP CONSTRAINT wallet_transactions_kind_check;
ALTER TABLE wallet_transactions ADD CONSTRAINT wallet_transactions_kind_check
    CHECK (kind IN (
        'topup',            -- شحن رصيد
        'order_payment',    -- دفع طلب من المحفظة
        'refund',           -- استرجاع طلب
        'compensation',     -- تعويض من المنصة
        'commission',       -- عمولة مندوب
        'merchant_earning', -- مستحقّ متجر عن طلب مُسلَّم
        'payout',           -- صرف رصيد
        'adjustment'        -- تسوية إدارية
    ));
