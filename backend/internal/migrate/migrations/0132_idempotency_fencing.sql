-- ══════════════════════════════════════════════════════════════════════
-- **منعُ التكرار: علامةُ تثبيتٍ داخلَ معاملة العمل**
-- ══════════════════════════════════════════════════════════════════════
--
-- (`XG-33` · `R8` · `C-06` — دورةُ إصلاحٍ ٩، ٢٠٢٦-٠٩-٠٦.)
--
-- # العلّة
--
-- **المطالبةُ تُكتب على المَسبَح خارجَ معاملة العمل**: حجزٌ ثمّ عملٌ ثمّ
-- ختمٌ في ثلاثِ عمليّات. **فحين تبقى غيرَ منتهيةٍ لا يُعرَف من الصفّ
-- وحدَه**: أمات المنفّذُ قبل أن يقع العمل فالإعادةُ آمنة، **أم وقع ومات
-- قبل حفظ النتيجة فالإعادةُ تكرّره؟** **والفرقُ مالٌ.**
--
-- **ومقيسٌ**: مطالبةٌ يتيمةٌ ⇒ `409` وصفرُ تنفيذ **إلى أن يُقلَّم بعد
-- أربعٍ وعشرين ساعة.**
--
-- # والحلُّ المعتمد
--
--     IDEMPOTENCY DURABLE COMMIT STATE MUST BE ATOMIC WITH BUSINESS COMMIT
--
-- **فالعلامةُ والنتيجةُ تُكتبان في معاملة العمل نفسِها، وتثبيتٌ واحد.**

ALTER TABLE idempotency_keys
    -- **متى ثبت العملُ** — **تُكتب داخلَ معاملته، فوجودُها يقين.**
    ADD COLUMN IF NOT EXISTS committed_at timestamptz,

    -- **حتّى متى يملك صاحبُها الحقَّ في التنفيذ.**
    --
    -- **والمهلةُ ليست الحماية**: قفلُ الصفّ ورمزُ الملكيّة هما الحارسان.
    -- **وهي تمنع البقاءَ إلى الأبد لا أكثر.**
    ADD COLUMN IF NOT EXISTS lease_until timestamptz,

    -- ══════════════════════════════════════════════════════════════════
    -- **رمزُ الملكيّة — سياجٌ لا معرِّف**
    -- ══════════════════════════════════════════════════════════════════
    --
    -- **كلُّ حيازةٍ تولّد رمزاً جديداً.** **ومن استُرِدّت منه المطالبةُ
    -- ثمّ استيقظ يجد رمزَه لا يطابق** — **فلا يكتب حرفاً.**
    --
    -- **والمهلةُ وحدَها لا تكفي**: ساعةٌ تسبق ساعةً، **وعمليّةٌ بطيئةٌ
    -- ليست عمليّةً ميّتة.**
    --
    -- **و`NULL` تعني صفّاً من قبلِ هذه الهجرة** — **لا يُستردّ أبداً**،
    -- انظر أدناه.
    ADD COLUMN IF NOT EXISTS owner_token uuid;

-- ══════════════════════════════════════════════════════════════════════
-- **والتركةُ تُعامَل بأشدّ ما يُؤمَن**
-- ══════════════════════════════════════════════════════════════════════
--
-- **مقيسٌ قبل الهجرة** (٢٠٢٦-٠٩-٠٦): اختبارٌ 0 · تجهيزٌ 0 ·
-- **إنتاجٌ ٣ صفوفٍ كلُّها `done` ولا معلَّقَ واحد** (أقدمُها ٦ أيّام).
--
-- **`done` يعني أنّ العملَ ثبت والردُّ حُفظ** — **فيُترجَم تثبيتاً.**
-- **ولا يُختلَق وقتٌ لم يُحفَظ**: `created_at` هو أقربُ ما نملك، **وهو
-- يقولُ متى بدأت لا متى ثبتت** — والفرقُ ثوانٍ، **والغرضُ أن تُقرأ
-- «ثبتت» لا أن يُؤرَّخ بها.**
UPDATE idempotency_keys
   SET committed_at = created_at
 WHERE done AND committed_at IS NULL;

-- **والمعلَّقُ من قبلُ لا يُستردّ ولا يُعاد تنفيذُه.**
--
-- **ولا يُفترَض أنّه لم ينفّذ**: **ليس في الصفّ ما يقول.** **ورمزُ
-- ملكيّتِه يبقى `NULL`** — **فالاستردادُ يشترط رمزاً قائماً** ولا
-- يمسّها. **فتبقى محجوبةً كما هي اليوم حتّى يُقلّمها الاحتفاظُ نفسُه** —
-- **وحبسٌ يوماً أهونُ من تكرارِ دفعة.**
--
-- (ولا صفَّ كهذا في أيّ بيئةٍ الآن — والقاعدةُ مكتوبةٌ لِما يأتي.)

CREATE INDEX IF NOT EXISTS idempotency_reclaimable_idx
    ON idempotency_keys (lease_until)
    WHERE committed_at IS NULL;
