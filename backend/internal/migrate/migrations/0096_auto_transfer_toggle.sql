-- (قرارُ المالك ٢٠٢٦-٠٨-١٠: «الطلبات يوجد خيارٌ تلقائيٌّ وخيارٌ يدويّ».)
--
-- # ولماذا تُحذف صفوفُها
--
-- **المفتاحان لم يعودا في الفهرس** (`settings/catalog.go`) — **وصفٌّ لمفتاحٍ
-- مجهولٍ يبقى في الجدول لا يقرؤه أحد**، ثمّ يراه من يفتح القاعدةَ بعد سنةٍ
-- فيظنّ أنّ للمنصّة عتبةَ تحويلٍ مضبوطة.
--
-- **والإعداداتُ سجلُّ قراراتٍ لا مخزنَ قيم**: ما لم يعد قراراً لا يبقى فيه.
--
-- # ولا يُترجَم القديمُ إلى الجديد
--
-- **عتبةٌ مضبوطةٌ لا تعني «فعِّل التحويلَ للكلّ»** — من وضع «حوّل ما فوق
-- مئتَي ألف» لم يقل «حوّل كلَّ شيء». **وترجمةٌ تخمّن نيّةَ صاحبها تُفعّل ما
-- لم يُطلب**، فتُبلَّغ المتاجرُ كلُّها فجأةً.
--
-- **فيبدأ المفتاحُ مُطفأً** — ويُشعله المالكُ حين يجهز البوت.
DELETE FROM app_settings
WHERE key IN ('orders.auto_transfer_min_total', 'orders.auto_transfer_min_items');
