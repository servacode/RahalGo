-- ٠٠٦٥ · سببُ ردّ الفرصة — **يُقال للمندوب لا يُكتم عنه**
--
-- # المسألة
--
-- ترفض الإدارةُ فرصةَ انضمامٍ فيصل المندوبَ إشعارٌ: **«رُدّ طلبُ الانضمام» —
-- واسمُ المتجر وحدَه.** ولا يعرف:
--
--   - أمكرّرٌ هو؟ (المتجرُ مسجَّلٌ باسمٍ آخر)
--   - أم خارج التغطية؟
--   - أم الرقمُ خطأ؟ أم التصنيفُ لا نعمل به؟
--
-- **فيلاحق عميلاً ميتاً، أو يعيد إرسال الفرصة نفسِها** — فتُردّ ثانيةً، ويدور
-- هو والمكتبُ في حلقة.
--
-- # وهي القاعدةُ التي فرضناها في كلّ مكانٍ سواه
--
-- الرفضُ والإلغاءُ والفشلُ والاسترجاعُ **كلُّها تلزمها كلمة** (`requiresReason`)،
-- وحسمُ النزاع كذلك، وردُّ صنفٍ في مراجعة القائمة كذلك. **والفرصةُ وحدَها
-- كانت تُردّ صامتة.**
--
-- # و`note` ليست هذه
--
-- عمودُ `note` القائمُ **يكتبه المندوبُ حين يُرسل** — «صاحبُه يفتح بعد
-- العصر». وخلطُ قرارِ الإدارة به **يمحو ما كتبه صاحبُ الفرصة**، ويجعل حقلاً
-- واحداً يحمل صوتين.

ALTER TABLE merchant_leads
	ADD COLUMN IF NOT EXISTS decision_note text NOT NULL DEFAULT '';
