-- ٠٠٨٤ · قائمةُ المتجر تُجمَّع بقسم السوق — **طبقةٌ واحدةٌ لا اثنتان**
--
-- # الخطأ الذي شهده المالك
--
-- (٢٠٢٦-٠٨-٠٧: «الأدمنُ هو من يجب عليه أن يزرع الأقسام، والمتجرُ يجد أقساماً
--  جاهزة… لأنّ بكرا كلّ متجرٍ رح ينزّل اسمَ قسمٍ مختلفٍ وصورةً مختلفة».)
--
-- **طبقتان كانتا تقولان الشيءَ نفسَه بكلماتٍ مختلفة**:
--
--     أقسامُ المنصة (٢٦):  شاورما · مشاوي · برغر · حلويات · مشروبات · بقالة
--     أقسامُ المتاجر (٦):  المشاوي على الفحم · المشروبات · الحلويات · المقبلات
--
-- **و«المشاوي على الفحم» و«مشاوي» شيءٌ واحد.** ومتجرٌ ثانٍ يكتب «مشويّات»،
-- وثالثٌ «على الفحم» — **فيصير للسوق عشرون اسماً لقسمٍ واحد.**
--
-- # والسوقُ يعمل بأقسام المنصة أصلاً
--
-- **قِيس قبل التبديل**: ١٩٤ صنفاً مصنَّفةٌ في `platform_section_id`، **وصفرٌ
-- بلا تصنيف.** فطبقةُ المتجر **زائدةٌ ولا يقرؤها الزبون** — إنّما تُصان.
--
-- # ولا يُحذف عمودٌ فيه بيانات
--
-- **`section_id` يبقى** ويصير يحتمل الفراغ. **والحذفُ هجرةٌ لاحقةٌ بعد أن
-- يهدأ** — ونحن لا نعدّل هجرةً بعد دمجها، **ولا نمحو عموداً في يومه.**
--
-- **والقديمُ يبقى مقروءاً**: كلُّ صنفٍ اليومَ له `section_id`، فلا شيءَ ينكسر
-- إن قُرئ. **والجديدُ لا يكتبه.**

ALTER TABLE menu_items ALTER COLUMN section_id DROP NOT NULL;

-- **وقسمُ السوق يصير هو المفتاح** — والفهرسُ موجودٌ (`menu_items_by_platform_section`)،
-- ويُضاف مركَّبٌ بالمتجر لأنّ الشاشةَ تسأل: **أقسامُ هذا المتجر وحدَه.**
CREATE INDEX IF NOT EXISTS menu_items_merchant_platform_idx
	ON menu_items (merchant_id, platform_section_id);
