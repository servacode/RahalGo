-- # الخلل
--
-- الهجرةُ ٠٠٦١ أضافت `delivery_proof` إلى الأنواع المقبولة **في Go**، وتركت
-- قيدَ القاعدة على ما كان عليه منذ ٠٠١٨. **فقبِلت الشيفرةُ ما ترفضه القاعدة**:
-- تُفحص الصورةُ وتُصغَّر وتُكتب على القرص، ثمّ يسقط الإدراجُ على القيد —
-- **خمسمئة، وملفٌّ يتيمٌ في مجلد الرفع.**
--
-- **ولم يظهر في أيّ اختبار**: الاختباراتُ لا ترفع صوراً، والشاشةُ لم تُجرَّب
-- بيد. ظهر في أوّل رفعةٍ حقيقية.
--
-- # والدرس
--
-- **قائمةُ الأنواع مكتوبةٌ في موضعين** — والموضعان يفترقان بلا صوت. من زاد
-- نوعاً في أحدهما زاده في الآخر، **وإلّا فقد كتب قاعدةً لا تُطبَّق.**
ALTER TABLE media DROP CONSTRAINT media_kind_check;
