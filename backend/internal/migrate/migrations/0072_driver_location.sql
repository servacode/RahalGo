-- أين السائقُ الآن — **ولا شيءَ في المنصة كان يعرف.**
--
-- # المسألة
--
-- الترتيبُ يوزّع بالدور: من طال انتظارُه يأخذ. **وهو عدلٌ في الوقت وأعمى في
-- المكان** — فيُسنَد طلبٌ من مطعمٍ في المنصور إلى سائقٍ واقفٍ في الرميلة،
-- **وآخرُ يقف أمام المطعم نفسِه لا يُعرَض عليه شيء.**
--
-- **والمسافةُ لا تُقاس بلا نقطة.** ولم يكن للسائق موضعٌ في القاعدة أصلاً:
-- لا عمود، ولا نقطةٌ يُرسل إليها.
--
-- (قرارُ المالك ٢٠٢٦-٠٨-٠٥: «المسافة بين السائق والمتجر وبين المتجر والزبون
-- يجب أن نعرفها... لتكون ميزةً ذكيةً لمعرفة لمن سيُسنَد الطلبُ ولماذا».)
--
-- # ولماذا في `users` لا في جدولٍ للأثر
--
-- **السؤالُ «أين هو الآن» لا «أين كان»**: صفٌّ واحدٌ يُحدَّث، لا سطرٌ يُضاف
-- كلَّ دقيقةٍ لكلّ سائق. وجدولُ أثرٍ يُنتج ملايينَ الصفوف في شهر **ولا يُسأل
-- منه إلّا الأخير.**
--
-- ومن أراد الأثرَ لاحقاً بناه بقصدٍ لا بأثرٍ جانبيّ.
--
-- # ووقتُ القراءة معه
--
-- **نقطةٌ بلا وقتٍ كذبةٌ تشيخ**: سائقٌ أغلق التطبيقَ قبل ساعةٍ يبقى موضعُه
-- مكتوباً، **فيُحسب أقربَ الجميع وهو في بيته.** فيُقرأ العمودان معاً أو
-- لا يُقرأ أحدُهما.

ALTER TABLE users
	ADD COLUMN IF NOT EXISTS last_location geography(Point, 4326);

ALTER TABLE users
	ADD COLUMN IF NOT EXISTS last_location_at timestamptz;

-- **وفهرسٌ مكانيّ** — بلاه يُمسح كلُّ سائقٍ في المنصة لاختيار أقربَ واحد.
CREATE INDEX IF NOT EXISTS users_last_location_idx
	ON users USING gist (last_location)
	WHERE last_location IS NOT NULL;
