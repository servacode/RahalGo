-- (طلبُ المالك 2026-08-25: «أضف بلوحة التحكم خيار لمعرفة عدد الزوار».)
--
-- # ولماذا صفٌّ واحدٌ في اليوم لا صفٌّ لكلّ فتحة
--
-- **وصفٌّ لكلّ فتحةٍ يحمل وقتَها ومن فتحها هو «نشاط المستخدم»** — وقد
-- أقررنا لغوغل أنّنا لا نجمعه (أمان البيانات، 2026-08-25). **وإقرارٌ
-- يكذب سببُ إيقافٍ لا تأخير.**
--
-- **فيُحفظ عددٌ لا حدث**: يومٌ، ونوعُ عميل، وكم مرّة. **ولا اسمَ ولا
-- رقمَ هاتفٍ ولا عنوانَ شبكةٍ ولا معرّفَ جهاز.**
--
-- # ولا يُسأل هذا الجدولُ عن شخص
--
-- **ومن أراد معرفةَ «كم شخصاً فتح اليوم» يسأل `device_tokens`** —
-- وفيه `last_seen_at` يُحدَّث عند كلّ إقلاع، **وأجهزتُه معلَنةٌ لغوغل
-- سلفا.**
--
-- # والزيادةُ ذرّيّةٌ بلا قفل
--
-- **و`ON CONFLICT DO UPDATE` تزيد في نداءٍ واحد** — ولو فتح ألفٌ معاً
-- لم يضِع عدّ.
CREATE TABLE IF NOT EXISTS app_opens_daily (
    -- **بتوقيت دمشق لا UTC** — «كم فُتح اليوم؟» سؤالُ صاحب المنصّة،
    -- **ويومُه يبدأ عنده لا في غرينتش.**
    day    date   NOT NULL,
    -- android-customer · android-driver · web — كما في `X-RahalGo-Client`.
    client text   NOT NULL,
    opens  bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (day, client)
);

-- **والقراءةُ دائماً بمدى أيّام** — «آخر سبعة» و«آخر ثلاثين».
CREATE INDEX IF NOT EXISTS app_opens_daily_day_idx ON app_opens_daily (day DESC);
