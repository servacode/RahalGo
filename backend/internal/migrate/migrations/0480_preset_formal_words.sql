-- خيارات الصنف الجاهزة بالفصحى (قرار المالك ٢٠٢٦-١٠-٢٨: لا كلمات عامية بالتطبيقات).
-- «نص كيلو» صارت «نصف كيلو». الأصناف المحفوظة قبل هذا تبقى كما هي —
-- اسم الخيار فيها ملك المتجر، وقد يكون غيّره بنفسه.
UPDATE option_presets
   SET options = replace(options::text, '"نص كيلو"', '"نصف كيلو"')::jsonb
 WHERE options::text LIKE '%"نص كيلو"%';
