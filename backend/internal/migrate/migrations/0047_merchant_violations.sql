-- **حظرُ المتجر كثيرِ الإلغاء** — بقرار المالك (٢٠٢٦-٠٨-٠١).
--
-- # ١ · حالةٌ ثالثة لا حالتان
--
-- كانت `inactive` تعني «المتجرُ أغلق نفسه» — إجازةٌ أو ترميمٌ أو موسم.
-- **ولو حُظر بها لَرفع الحظرَ عن نفسه** بضغطةٍ من بوابته: يُعيدها `active`
-- ويعود يستقبل الطلبات، **وحظرٌ يرفعه المحظور ليس حظراً.**
--
-- فـ`suspended` حالةٌ **لا يملكها المتجر** — تضعها المنصةُ وترفعها وحدها.
-- والفرقُ ليس تسميةً: قراءةُ التقارير تختلف بين متجرٍ مرتاحٍ ومتجرٍ مُعاقَب،
-- **ولفظٌ واحدٌ لحالتين يُعمي القارئ عن أيّهما أمامه.**
ALTER TABLE merchants DROP CONSTRAINT IF EXISTS merchants_status_check;
ALTER TABLE merchants ADD CONSTRAINT merchants_status_check
    CHECK (status IN ('active', 'inactive', 'suspended'));

-- # ٢ · مسحُ المخالفات — عفوٌ لا حذف
--
-- «نستطيع رفع الحظر وإزالة المخالفات إذا أردنا» — والمخالفاتُ ليست جدولاً
-- يُحذف منه: هي **طلباتٌ وقعت فعلاً** ولا يجوز محوُ وقوعها من السجلّ.
--
-- **فالعفوُ خطٌّ زمنيّ لا ممحاة**: يُعدّ ما بعده وحده. فيبقى الماضي مقروءاً
-- لمن يسأل «كم مرّةً سامحناه؟» — وهو سؤالٌ يُطرح حين يُطلب العفوُ رابعةً.
ALTER TABLE merchants ADD COLUMN violations_cleared_at timestamptz;

COMMENT ON COLUMN merchants.violations_cleared_at IS
    'عفوٌ عن المخالفات: لا يُعدّ إلا ما أُغلق بعد هذا الوقت. NULL = لا عفو';

-- # ٣ · من أنهى الطلب
--
-- عدُّ المخالفات يحتاج جواباً دقيقاً: **من ألغى؟** ولا يُستنتج من الحالة:
-- `cancelled` يصل إليها الزبونُ والمتجرُ والعملياتُ والأدمن، **وحسبانُها كلَّها
-- على المتجر يحظر بريئاً**. و`rejected` في وضع «المنصة تدير» ترفضها العملياتُ
-- عن المنصة لا عن المتجر.
--
-- **فيُسجَّل الدورُ الذي خوّل الانتقال** لحظةَ وقوعه — لا يُخمَّن لاحقاً من
-- جدول الأدوار، فالأدوارُ تتغيّر والماضي لا يتغيّر.
ALTER TABLE orders ADD COLUMN ended_by text;

COMMENT ON COLUMN orders.ended_by IS
    'الدور الذي خوّل الانتقال النهائي: merchant | customer | driver | ops | admin';

-- # ٤ · المفاتيح
--
-- **والوضعُ اختيارٌ لا حتم**: مالكٌ يريدها آليةً يضبطها `auto`، ومن يريد أن
-- يرى قبل أن يبطش يضبطها `manual` فتصله الإشارةُ ويقرّر. **وحظرٌ يقع ليلاً
-- بلا من يراه يُفقد المنصةَ متجراً ويُفقد المتجرَ رزقاً** — والاثنان خسارة.
INSERT INTO app_settings (key, value) VALUES
    ('merchants.cancel_ban_mode',  '"manual"'::jsonb),
    ('merchants.cancel_ban_count', '5'::jsonb),
    ('merchants.cancel_ban_days',  '30'::jsonb)
ON CONFLICT (key) DO NOTHING;
