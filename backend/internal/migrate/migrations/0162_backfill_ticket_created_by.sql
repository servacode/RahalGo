-- 0162 · نسبُ الشكوى القديمة إلى صاحبها — تمهيدٌ لفرزِ «شكاواي» (Batch 4، C1)
-- ══════════════════════════════════════════════════════════════════════
--
-- **صارت شاشةُ «شكاوى قدّمتها» تُرشَّح بـ created_by = المستخدم** لا بـ
-- customer_id (الذي يحمل صاحبَ الطلب حتى في بلاغِ سائقٍ عليه — تسريب).
--
-- **والشكاوى القديمةُ فتحها الزبونُ قبل أن يُملأ عمودُ created_by** قد يكون
-- created_by فيها فارغاً — فتختفي من قائمته بعد الترشيح الجديد. **فتُنسب
-- إلى صاحبها**: كلُّ تذكرةٍ فتحها زبونٌ بنفسه (opened_by_customer) وبلا كاتبٍ
-- مسجَّل، كاتبُها هو صاحبُ الطلب (customer_id).
--
-- **آمنةٌ ومحصورة**: لا تمسّ إلّا ما فتحه الزبونُ بنفسه وبلا كاتب — لا بلاغَ
-- سائقٍ ولا متجرٍ ولا تذكرةَ موظّف. **عكوسة**: إعادةُ العمود إلى NULL لتلك
-- الصفوف لو لزم (لا قيمةَ سابقةً تُفقد — كانت فارغة).
UPDATE tickets
   SET created_by = customer_id
 WHERE opened_by_customer = true
   AND created_by IS NULL
   AND customer_id IS NOT NULL;
