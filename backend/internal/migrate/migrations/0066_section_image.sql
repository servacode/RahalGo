-- ٠٠٦٦ · صورةُ القسم — **وجهُ السوق للزبون**
--
-- # المسألة
--
-- القسمُ اليومَ **أيقونةٌ من قائمةٍ ثابتة** (`icon`): رمزٌ رماديٌّ يشبه ما
-- سواه. **وسوقٌ يُتصفَّح بالصور لا بالرموز** — الزبونُ يعرف الشاورما من صورتها
-- قبل أن يقرأ اسمَها، **ورمزٌ واحدٌ لعشرة أقسامٍ يجعلها كلَّها شيئاً واحداً.**
--
-- (قرارُ المالك ٢٠٢٦-٠٨-٠٤: «لازم يكون كرت لكلّ قسم فيه اسمُ القسم وصورةُ
-- القسم».)
--
-- # والأيقونةُ تبقى
--
-- **لا تُحذف**: هي ما يُعرض قبل أن تُرفع صورة، **وفي المواضع الضيّقة** — شريطُ
-- تصفّحٍ أو قائمةٌ مختصرة. **وصورةٌ لم تُرفع بعد لا تترك القسمَ فارغاً.**

ALTER TABLE platform_sections
	ADD COLUMN IF NOT EXISTS image_media_id uuid REFERENCES media(id) ON DELETE SET NULL;
