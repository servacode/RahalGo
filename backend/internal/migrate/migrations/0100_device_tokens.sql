-- # ولماذا لم تكن موجودة
--
-- **الإشعارُ يُحفظ في صندوق الوارد ويُبثّ عبر WebSocket** — وهو يكفي
-- المتصفّح: التبويبُ مفتوحٌ فيصل، ومغلقٌ فيُقرأ عند العودة.
--
-- **والهاتفُ غيرُ ذلك**: التطبيقُ مقفلٌ أكثرَ ممّا هو مفتوح، **والسائقُ
-- الذي يعلم بطلبٍ بعد دقيقتين طلبٌ ضائع.**
--
-- # والصفُّ رمزٌ لا جهاز
--
-- **رمزُ FCM يتبدّل**: عند إعادة التثبيت، وعند مسح البيانات، وأحياناً من
-- تلقاء نفسه. **فلا يُعامَل معرّفاً ثابتاً للجهاز** — إنّما عنوانَ بريدٍ
-- يُجدَّد، والتطبيقُ يُسجّله في كلّ إقلاع.
--
-- # ورمزٌ واحدٌ لحسابٍ واحدٍ في كلّ لحظة
--
-- **`token` مفتاحٌ فريد، لا `(user_id, token)`.** وهاتفٌ يُسلَّم لسائقٍ
-- آخرَ يُسجّل الرمزَ نفسَه باسمٍ جديد، **فينتقل الصفُّ إليه** — ولو كان
-- الفريدُ مركّباً لَبقي الصفّان معاً **فوصل إشعارُ السائق الأوّل إلى
-- هاتفٍ صار عند غيره.**
CREATE TABLE IF NOT EXISTS device_tokens (
    token        text PRIMARY KEY,
    user_id      uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    -- android · ios — **والقائمةُ مغلقةٌ في الشيفرة** كما نوعُ الجلسة.
    platform     text NOT NULL,
    -- **إصدارُ التطبيق يُحفظ** — فمن شكا من عطبٍ عُرف من أيّ نسخةٍ يشكو،
    -- **ومن أراد أن يُلزم بالتحديث عرف كم جهازاً سيمنع.**
    app_version  text NOT NULL DEFAULT '',
    created_at   timestamptz NOT NULL DEFAULT now(),
    -- **ويُحدَّث في كلّ إقلاع** — **ورمزٌ لم يُرَ منذ شهرين ميّتٌ عمليّاً**،
    -- والإرسالُ إليه إنفاقٌ بلا مستقبِل.
    last_seen_at timestamptz NOT NULL DEFAULT now()
);

-- **الاستعلامُ الوحيدُ الساخن**: «أعطني أجهزةَ هذا الحساب» — يقع مع كلّ
-- إشعار، **وبلا فهرسٍ مسحٌ كاملٌ للجدول في كلّ حدث.**
CREATE INDEX IF NOT EXISTS device_tokens_user_idx ON device_tokens (user_id);
