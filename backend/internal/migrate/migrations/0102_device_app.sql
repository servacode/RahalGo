-- (قرارُ المالك ٢٠٢٦-٠٨-١١: «لازم يكون هناك فصلٌ بين العمليات والإشعارات».)
--
-- # المشكلة
--
-- **صاحبُ المتجر يحمل تطبيقين**: تطبيقَ متجرِه وتطبيقَ الزبون ليطلب عشاءه.
-- **وجدولُ الأجهزة يعرف أنّ الجهازَ أندرويد ولا يعرف أيَّ تطبيق.**
--
-- **فإشعارُ «طلبٌ جديد» يرنّ في التطبيقين معاً.** والسائقُ كذلك، والمندوب.
--
-- # والقيمةُ تأتي من ترويسة العميل نفسِها
--
-- **التطبيقُ يرسل `X-RahalGo-Client: android-merchant` مع كلّ نداء** — وهي
-- الترويسةُ التي تفصل الجلسات (هجرة `0099`). **فيُشتقّ منها التطبيقُ ولا
-- يُطلب حقلٌ جديدٌ في الطلب** — حقلٌ يُنسى، وترويسةٌ لا تُنسى لأنّ الجلسةَ
-- تعتمد عليها.
--
-- # وفارغٌ يعني «يستقبل كلَّ شيء»
--
-- **لا صفوفَ في الإنتاج اليوم** (الجدولُ عمرُه يوم، ولا تطبيقَ بعد).
-- **لكنّ الفارغَ يبقى مسموحاً**: جهازٌ سُجّل من متصفّحٍ أو من نسخةٍ قديمة
-- **يجب أن يستقبل لا أن يصمت** — إشعارٌ زائدٌ أهونُ من إشعارٍ مفقود.
ALTER TABLE device_tokens
    ADD COLUMN IF NOT EXISTS app text NOT NULL DEFAULT '';

-- **الاستعلامُ الساخن صار «أجهزةُ هذا الحساب لهذا التطبيق»** — يقع مع كلّ
-- إشعار.
CREATE INDEX IF NOT EXISTS device_tokens_user_app_idx ON device_tokens (user_id, app);
