-- ══════════════════════════════════════════════════════════════════════
-- **وما وُجد قبل اليوم يُنسب — ولا يُترك معلَّقاً**
-- ══════════════════════════════════════════════════════════════════════
--
-- **والنموذجان صارا يُلزمان المنطقة** (٠١٢٣)، **والقائمُ لا منطقةَ له**:
-- ثلاثةُ متاجرَ وطلبٌ واحدٌ كُتب فيه «وسط المدينة» — قِيس ٢٠٢٦-٠٨-٣٠.
--
-- **وصفٌّ قديمٌ بلا انتماءٍ لا يشتكي**: يُقرأ في اللوحة بحقلٍ فارغٍ
-- **فيُظنّ عطباً في العرض**، ويبقى خارجَ كلّ تصفيةٍ تُبنى عليه غداً.
--
-- # والنسبةُ تُشتقّ من المدينة لا تُخمَّن
--
-- **`cities.district_id` مُلئ في `0122`** — والمتجرُ يعرف مدينتَه
-- (تُشتقّ من إحداثيّاته منذ ٢٠٢٦-٠٨-٢٢). **فالسلسلةُ قائمةٌ ولا تحتاج
-- ظنّاً**: متجر ← مدينة ← منطقة.
--
-- **وما لا مدينةَ له يبقى فارغاً** — **وتخمينُ منطقةٍ لمتجرٍ لا نعرف
-- أين هو أسوأُ من فراغٍ يُرى في اللوحة فيُصحَّح بيد.**

UPDATE merchants m
   SET district_id = c.district_id
  FROM cities c
 WHERE m.city_id = c.id
   AND m.district_id IS NULL
   AND c.district_id IS NOT NULL;

-- ══════════════════════════════════════════════════════════════════════
-- **والطلباتُ المعلّقةُ تُنسب بمتجرها أو بمدينة نقطتها**
-- ══════════════════════════════════════════════════════════════════════
--
-- **والمحوَّلُ منها يأخذ منطقةَ متجره** — هو هو.
UPDATE merchant_leads l
   SET district_id = m.district_id
  FROM merchants m
 WHERE l.merchant_id = m.id
   AND l.district_id IS NULL
   AND m.district_id IS NOT NULL;

-- **وما لم يُحوَّل بعدُ تُقرأ مدينتُه من نقطته** — **بنصف قطر المدينة
-- نفسِه الذي يُصنَّف به المتجر** (`0116`)، فلا قاعدتان لشيءٍ واحد.
UPDATE merchant_leads l
   SET district_id = c.district_id
  FROM cities c
 WHERE l.district_id IS NULL
   AND l.lat IS NOT NULL AND l.lng IS NOT NULL
   AND c.district_id IS NOT NULL
   AND ST_DWithin(
         ST_SetSRID(ST_MakePoint(l.lng, l.lat), 4326)::geography,
         c.center, c.radius_m);
