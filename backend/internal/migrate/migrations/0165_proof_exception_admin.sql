-- ══════════════════════════════════════════════════════════════════════
--
-- # العلّة
--
-- **كان السائقُ يتخطّى الصورةَ بكلمةٍ يكتبها بنفسه** (`pod_skip_reason`)،
-- **فيأذن لنفسه.** قرارُ المالك: **لا سائقَ يتخطّى بكلمة** — الاستثناءُ يحتاج
-- إذنَ أدمن/عمليّاتٍ موثَّقاً، والسائقُ العاديُّ لا يملكه.
--
-- # الحلّ
--
-- **عمودان يقولان مَن أذن ومتى**: `pod_skip_by` (الأدمن/العمليّات المُخوَّل)
-- و`pod_skip_at`. **والبوّابةُ لم تعد تقبل `pod_skip_reason` وحدَه** — تقبل
-- صورةً أو **إذناً مُخوَّلاً** (`pod_skip_by IS NOT NULL`). و`pod_skip_reason`
-- يبقى للسبب الإلزاميّ الذي يكتبه المُخوِّل.
--
-- **ولا يُعاد كتابةُ الماضي**: طلباتٌ تخطّاها سائقٌ قديماً و سُلّمت بالفعل مرّت
-- البوّابةَ يومَها؛ وما لم يُسلَّم بعدُ يُمنع حتّى يأذن مُخوَّل — وهو المقصود.

ALTER TABLE orders
    ADD COLUMN IF NOT EXISTS pod_skip_by uuid REFERENCES users (id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS pod_skip_at timestamptz;
