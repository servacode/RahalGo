-- **ما بعد الفشل** — الطلبُ يسقط، والخسارةُ تبقى بلا حامل.
--
-- كان `failed` نهايةً محاسبيةً ناقصة: يُردّ للزبون ما دفع، **ثم لا شيء**.
-- والطعامُ مطبوخٌ بيد السائق، والسائقُ قاد رحلةً أو رحلتين، **ولا قيدَ يقول
-- من يحمل الثمن.**
--
-- فقرّر المالك (٢٠٢٦-٠٨-٠١):
--
--   * **السائقُ يُعوَّض دائماً من المنصة يدوياً** — لا تلقائياً. أجرُ التوصيل
--     مقابل تسليمٍ تمّ، وما وقع رحلةٌ لا تسليم. **وتقديرُ الرحلة يختلف**:
--     مشوارٌ إلى الحيّ المجاور ليس كمشوارٍ عبر المدينة، ورقمٌ آليّ واحد يظلم
--     أحدهما. فيُقدَّرها إنسانٌ ويوقّع عليها.
--
--   * **البضاعةُ تعود إلى مكتب المنصة**، ثم أحدُ أمرين:
--       - **المتجرُ يستردّها** — فلا قيد: أخذ بضاعته.
--       - **المتجرُ يرفض** — **فالمنصةُ تتحمّل كاملاً** وتدفع له ما كان
--         سيقبضه لو نجح الطلب.
--
-- **وحقلٌ واحدٌ لا حقلان**: «إلى أين ذهبت البضاعة» يجيب السؤالين — أَحُسم
-- المصير؟ ومن حمله؟ وحقلٌ منفصل لـ«أَحُسم» يفتح بابَ تناقضٍ بين الاثنين.
--
-- و**NULL يعني معلَّقاً**: طلبٌ فشل ولم يُحسم مصيرُ بضاعته بعد — وهو سؤالٌ
-- تُجيبه العملياتُ حين تصل البضاعةُ للمكتب، لا لحظةَ الفشل.
ALTER TABLE orders ADD COLUMN goods_settled_to text
    CHECK (goods_settled_to IN ('merchant', 'platform'));

COMMENT ON COLUMN orders.goods_settled_to IS
    'مصير بضاعة طلبٍ فشل: merchant = المتجر استردّها · platform = رفض فتحمّلتها المنصة ودفعت له · NULL = لم يُحسم بعد';
