--
-- # المسألة
--
-- **قسمةُ القدرات كانت تحرس البابَ لا الحمولة.** فمن ملك users.read
-- ليجد حساباً لقيدٍ ماليٍّ نال هاتفَه أيضاً — **ولا يتّصل بأحد.**
--
-- # ومن يُمنَح
--
-- **من يتّصل بالناس في عمله**: العمليّاتُ والمكتبُ والدعمُ والتحقيقُ
-- وتوثيقُ السائقين والمتاجر — **ومالكُ المنصّة والإداريّ.**
--
-- **ولا تُمنَح الماليّةَ ولا التحليل**: **الماليّةُ تجد الحسابَ بمعرّفه
-- واسمه وحاله لتقيّد له** — ولا تكلّمه. **والتحليلُ يقرأ مجاميعَ لا
-- أشخاصاً.**
--
-- # ولا تُنزَع قدرةٌ قائمة
--
-- **هذه إضافةٌ لا إعادةُ توزيع**: من كان يرى الهاتفَ ويحتاجه بقي يراه،
-- **والمبدَّلُ أنّ من لا يحتاجه لم يعد يراه.**

-- **والمعجمُ في الشيفرة لا في جدول** (`authz/catalog.go`) — **ولا
-- جدولَ قدراتٍ في القاعدة**، فتُسجَّل المنحُ وحدَها.

INSERT INTO role_capabilities (role_code, capability_code)
SELECT r.code, 'users.contact.read'
  FROM roles r
 WHERE r.code IN (
        'owner_super_admin', 'admin', 'ops', 'operations',
        'customer_support', 'trust_safety',
        'driver_verification', 'merchant_verification')
ON CONFLICT DO NOTHING;
