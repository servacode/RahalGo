package catalog

// **قائمةُ متجرٍ بُنيت بالشيفرة الحاليّة تُقرأ.**
//
// (كشفه فحصٌ يدويٌّ ٢٠٢٦-٠٨-٠٨ على متجرٍ جديدٍ في قاعدةٍ نظيفة: أُضيف أوّلُ
//
//	صنفٍ من الشاشة، **فصارت صفحةُ الأصناف تردّ ٥٠٠ إلى الأبد.**)
//
// # المرض
//
// هجرةُ ٠٠٨٤ رفعت طبقةَ أقسام المتجر، **و`CreateItem` لم تعد تكتب
// `section_id`** — العمودُ يبقى للصفوف القديمة ويُترك فارغاً للجديدة.
//
// **و`GetMenu` بقيت تقرؤه في حقلٍ لا يقبل الفراغ** (`SectionID string`):
//
//	can't scan into dest[1] (col: section_id): cannot scan NULL into *string
//
// **فأوّلُ صنفٍ يُنشئه متجرٌ يكسر قائمتَه كلَّها** — لصاحبه وللإدارة معاً،
// **ولا يُصلحها إلّا حذفُ الصنف.**
//
// # ولماذا لم يظهر قطّ
//
// **الصفوفُ القديمةُ كلُّها لها `section_id`** — ١٩٤ صنفاً كتبها الرمزُ
// السابق. فالقراءةُ تنجح على كلّ ما في القاعدة، **ولا تسقط إلّا على صنفٍ
// وُلد بعد الهجرة.**
//
// **وقاعدةُ التطوير لم تكن نظيفةً قطّ**: كلُّ فحصٍ سابقٍ جرى على بذرةٍ
// كتبها الرمزُ القديم. **والقاعدةُ الفارغةُ وحدَها كشفته.**
//
// # ولماذا حارسٌ لا انتباه
//
// **الكاتبُ والقارئُ في دالّتين متجاورتين في الملفّ نفسِه** — ومع ذلك
// افترقا بلا صوت. **وهي عائلةُ الخلل نفسُها**: قاعدةٌ مكتوبةٌ في موضعين.
//
// **والاختبارُ يبني كما تبني الشيفرةُ اليوم** — لا بإدراجٍ مباشرٍ في الجدول:
// فإدراجٌ بيدِ الاختبار يملأ `section_id` **فيشهد بما لا يقع.**

import (
	"context"
	"testing"
)

// TestGetMenu_ReadsItemsCreatedToday **ما تكتبه الشيفرةُ تقرؤه.**
func TestGetMenu_ReadsItemsCreatedToday(t *testing.T) {
	f := newMenuFixture(t)
	ctx := context.Background()

	// **يُنشأ بالخدمة لا بجملةِ إدراج** — فيُترك `section_id` فارغاً كما يقع.
	if _, err := f.svc.CreateItem(ctx, f.actorID, f.merchantID, MenuItemInput{
		Name:              ptr("صنفٌ وُلد بعد الهجرة"),
		Price:             ptr(int64(25000)),
		PlatformSectionID: ptr(f.platformID),
	}, "127.0.0.1"); err != nil {
		t.Fatalf("تعذّر إنشاء الصنف: %v", err)
	}

	sections, err := f.svc.GetMenu(ctx, f.merchantID)
	if err != nil {
		t.Fatalf("**القائمةُ لا تُقرأ بعد أوّل صنف** — وهذا ٥٠٠ في وجه صاحب المتجر: %v", err)
	}
	if len(sections) != 1 {
		t.Fatalf("أقسامٌ %d والمنتظَر واحد — القسمُ يظهر لأنّ فيه صنفاً", len(sections))
	}
	if len(sections[0].Items) != 1 {
		t.Fatalf("أصنافٌ %d في القسم والمنتظَر واحد", len(sections[0].Items))
	}
	if sections[0].Items[0].Name != "صنفٌ وُلد بعد الهجرة" {
		t.Fatalf("الاسمُ %q", sections[0].Items[0].Name)
	}
}
