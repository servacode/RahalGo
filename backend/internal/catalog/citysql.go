package catalog

import "strconv"

// ══════════════════════════════════════════════════════════════════════
//  **اشتقاقُ مدينةِ المتجر من نقطتِه — تعبيرٌ واحدٌ لا أربعة**
// ══════════════════════════════════════════════════════════════════════
//
// # المسألة
//
// **ومدينةُ المتجر تُشتقّ من موقعه ولا تُسأل** — **صاحبُ المتجر يضع
// نقطتَه على الخريطة، والمدينةُ تُعرف منها.**
//
// **وترشيحُ السوق يشترط أن تساوي مدينةُ المتجر مدينةَ الزبون**
// (`city_filter.go`) — **فمتجرٌ بلا مدينةٍ لا يظهر لأحدٍ أبداً**:
// **و`NULL = x` ليست صحيحةً في SQL، ولا تكون.**
//
// # ولماذا صار التعبيرُ هنا
//
// **وكان مكتوباً مرّتين في `catalog.go`** — **وغائباً عن ثلاثة مواضع
// تكتب جغرافيا المتجر**:
//
//	`Update`      تبدّل الموقعَ ولا تُعيد حسابَ المدينة
//	`cmd/seed`    موضعان يُنشئان متاجرَ بلا مدينةٍ ألبتّة
//
// **ونسخةٌ تُصلَح وثلاثٌ تبقى** — **وهو ما وقع**: **أُصلح الإنشاءُ في
// ٢٠٢٦-٠٨-٢٢ بعد شكوى المالك «الأصنافُ لم تظهر بالتطبيق أبداً»،
// **وبقيت المواضعُ الأخرى** — **فعاد العطبُ نفسُه على جهازٍ حقيقيٍّ في
// ٢٠٢٦-٠٩-١٦**: **ستّةٌ وثلاثون صنفاً في قاعدة التجهيز، وصفرٌ لمن يقف
// داخلَ المطعم.**
//
// # ولا نموذجَ جغرافيا ثانٍ
//
// **وهذا هو استعلامُ `cityWhere` عينُه** — **المدينةُ أقربُ مدينةٍ
// مُفعَّلةٍ تحوي النقطةَ في نصف قطرها.** **ومن كتب اشتقاقاً ثانياً
// بمعنىً ثانٍ جعل المتجرَ في مدينةٍ والزبونَ في أخرى وهما في مكانٍ واحد.**

// CityOfPointSQL **يردّ تعبيرَ «مدينةُ هذه النقطة»** — يُدرَج في
// `INSERT` أو `UPDATE` كما هو.
//
// **و`latArg` و`lngArg` رقما المُعاملَين** (`$8` ⇒ 8) — **والترقيمُ
// يختلف بين الجُمَل، فيُمرَّر ولا يُفترَض.**
//
// **ويردّ `NULL` حين لا نقطةَ** — **ولا يُخمَّن**: **مدينةٌ مُخمَّنةٌ
// أسوأُ من لا مدينة، لأنّها تُخفي المتجرَ عن أهله وتُظهره لغيرهم.**
func CityOfPointSQL(latArg, lngArg int) string {
	lat := "$" + strconv.Itoa(latArg) + "::float8"
	lng := "$" + strconv.Itoa(lngArg) + "::float8"
	pt := "ST_SetSRID(ST_MakePoint(" + lng + ", " + lat + "), 4326)::geography"
	return `(SELECT c.id FROM cities c
	          WHERE c.active
	            AND ` + lat + ` IS NOT NULL AND ` + lng + ` IS NOT NULL
	            AND ST_DWithin(c.center, ` + pt + `, c.radius_m)
	          ORDER BY ST_Distance(c.center, ` + pt + `)
	          LIMIT 1)`
}
