package catalog

// ══════════════════════════════════════════════════════════════════════
// **«الصنف بلا صورة يبقى مخفياً، وبس تنزل صورة يصير متوفر»** (قرار المالك ٢٠٢٦-١١-٠٧)
// ══════════════════════════════════════════════════════════════════════
//
// المزامنة كانت تخلّي كلّ صنف كميته فوق الصفر «متوفر» — فيطلع للزبون صنف بلا صورة.
// هلّق، **للأصناف اللي عملتها مزامنة الأمين بس** (`ameen_created`):
//
//   - الكمية فوق الصفر والصنف بلا صورة ⇒ **بيضلّ مخفي** وبينعلّم `photo_hold`،
//     وبينعدّ بالتقرير (`kept_hidden_no_photo`).
//   - الكمية صفر ⇒ مخفي متل قبل، والعلامة بتنشال.
//   - **أوّل صورة بتنزل للصنف** (أيّ طريق: تطبيق المتجر، الموقع، اللوحة، المندوب —
//     كلّهم من `UpdateItem`) والعلامة عليه ⇒ **بيصير متوفر**، إلّا إذا آخر كمية من الأمين
//     صفر (`ameen_qty`).
//   - **وصاحب المتجر إذا غيّر التوفّر بإيده** العلامة بتنشال — فما منقلب شي اختاره.
//   - **وصنف متوفر أصلاً ما بينخفى** لأنو بلا صورة — القاعدة بتمنع الإظهار بس.
//
// والأصناف اللي عملها المتجر بإيده (ولو انربطت برقم الأمين) سلوكها ما تغيّر: الكمية بتحكم.

// photoRule **قاعدة الصورة لصفّ مطابَق** — بتاخد التوفّر اللي بدّها ياه الكمية وبتردّ
// التوفّر والعلامة بعد القاعدة.
func photoRule(it *syncItem, wantAvail, hold bool) (avail, newHold bool) {
	if !wantAvail {
		return false, false
	}
	if it.ameenCreated && it.noImage && !it.available {
		return false, true
	}
	return true, hold
}
