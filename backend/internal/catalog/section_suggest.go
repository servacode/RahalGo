// SuggestSection returns the platform section name an item most likely belongs to, from its name alone.
// ok=false when no rule is confident. The returned name is EXACTLY one of the launch section names.
func SuggestSection(name string) (section string, ok bool) {
	toks := tokenize(name)
	if len(toks) == 0 {
		return "", false
	}
	rs := rulesOnce()
	// 1) قواعد قاطعة في أي موضع
	if s, hit := rs.strong.match(toks, false); hit {
		return s, s != secAbstain
	}
	// 2) الرأس: الكلمة الأولى، ثم بعد تخطّي كلمات التعبئة العامّة
	if s, hit := rs.head.match(toks, true); hit {
		return s, s != secAbstain
	}
	if k := skipGeneric(toks); k > 0 && k < len(toks) {
		if s, hit := rs.head.match(toks[k:], true); hit {
			return s, s != secAbstain
		}
	}
	// 3) قواعد ضعيفة في أي موضع
	if s, hit := rs.weak.match(toks, false); hit {
		return s, s != secAbstain
	}
	return "", false
}

// ───────────────────────── التطبيع والتقطيع ─────────────────────────

func normalize(s string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(s) {
		switch {
		case r >= 0x064B && r <= 0x065F, r == 0x0670, r == 0x0640:
			continue // تشكيل وتطويل
		case r == 'أ' || r == 'إ' || r == 'آ' || r == 'ٱ':
			r = 'ا'
		case r == 'ة':
			r = 'ه'
		case r == 'ى':
			r = 'ي'
		case r == 'ؤ':
			r = 'و'
		case r == 'ئ':
			r = 'ي'
		case r >= '٠' && r <= '٩':
			r = '0' + (r - '٠')
		case r >= '۰' && r <= '۹':
			r = '0' + (r - '۰')
		}
		if unicode.IsLetter(r) || unicode.IsDigit(r) {
			b.WriteRune(r)
		} else {
			b.WriteByte(' ')
		}
	}
	return b.String()
}

func isNumeric(t string) bool {
	for _, r := range t {
		if !unicode.IsDigit(r) {
			return false
		}
	}
	return t != ""
}

// tokenize يطبّع ويقطّع، ويحذف رقم المادة البادئ والأرقام المجرّدة،
// ويشيل «ال» التعريف من الكلمات الطويلة.
func tokenize(name string) []string {
	raw := strings.Fields(normalize(name))
	out := make([]string, 0, len(raw))
	for _, t := range raw {
		if isNumeric(t) {
			continue
		}
		out = append(out, stripAl(t))
	}
	return out
}

func stripAl(t string) string {
	if strings.HasPrefix(t, "ال") && len([]rune(t)) > 4 {
		return strings.TrimPrefix(t, "ال")
	}
	return t
}

// كلماتُ تعبئةٍ تُتخطّى عند البحث عن الرأس («مجموعة عطر …»، «علبة بسكويت …»).
var genericLead = map[string]bool{
	"مجموعه": true, "علبه": true, "بكج": true, "عرض": true, "عبوه": true,
	"كرتون": true, "كيس": true, "بوكس": true, "حبات": true, "قطع": true,
	"قطعه": true, "جديد": true, "مشكل": true, "كرات": true, "اكياس": true, "حبه": true,
}

func skipGeneric(toks []string) int {
	k := 0
	for k < len(toks) && genericLead[toks[k]] {
		k++
	}
	return k
}

// ───────────────────────── محرّك القواعد ─────────────────────────

type pattern []string // كلماتٌ متتالية، وآخرُ حرفٍ «*» يعني بادئة

type rule struct {
	section string
	pats    []pattern
	ctx     []pattern // اختياري: يجب أن يظهر أحدها في مكانٍ ما
}

type ruleList []rule

type ruleSet struct{ strong, head, weak ruleList }

func compilePats(spec string) []pattern {
	var out []pattern
	for _, alt := range strings.Split(spec, patSeparator) {
		var p pattern
		for _, w := range strings.Fields(normalize(alt + "")) {
			p = append(p, stripAl(w))
		}
		// «*» تُحذف في normalize، فنقرأها من النصّ الأصلي
		fields := strings.Fields(alt)
		for i, f := range fields {
			if strings.HasSuffix(f, "*") && i < len(p) {
				p[i] += "*"
			}
		}
		if len(p) > 0 {
			out = append(out, p)
		}
	}
	return out
}

func r(section, spec string, ctx ...string) rule {
	rl := rule{section: section, pats: compilePats(spec)}
	if len(ctx) > 0 {
		rl.ctx = compilePats(ctx[0])
	}
	return rl
}

func tokMatch(p, t string) bool {
	if strings.HasSuffix(p, "*") {
		return strings.HasPrefix(t, strings.TrimSuffix(p, "*"))
	}
	return p == t
}

func (p pattern) at(toks []string, i int) bool {
	if i+len(p) > len(toks) {
		return false
	}
	for j, w := range p {
		if !tokMatch(w, toks[i+j]) {
			return false
		}
	}
	return true
}

func anyPat(ps []pattern, toks []string, headOnly bool) bool {
	for _, p := range ps {
		if headOnly {
			if p.at(toks, 0) {
				return true
			}
			continue
		}
		for i := range toks {
			if p.at(toks, i) {
				return true
			}
		}
	}
	return false
}

func (l ruleList) match(toks []string, headOnly bool) (string, bool) {
	for _, rl := range l {
		if !anyPat(rl.pats, toks, headOnly) {
			continue
		}
		if len(rl.ctx) > 0 && !anyPat(rl.ctx, toks, false) {
			continue
		}
		return rl.section, true
	}
	return "", false
}

