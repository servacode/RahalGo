package textguard

import "testing"

// **السائقُ يرى الاسمَ الأوّل وحده** (قرارُ المالك ٢٠٢٦-١١-٠٥) — والاسمُ
// المركّبُ يبقى كلمتين، والرقمُ لا يمرّ ولو كُتب مكانَ الاسم.
func TestFirstName(t *testing.T) {
	cases := map[string]string{
		"أحمد محمد العلي":  "أحمد",
		"عبد الله الأحمد":  "عبد الله",
		"أبو محمد":         "أبو محمد",
		"ابو خالد الحسن":   "ابو خالد",
		"عبدالرحمن خالد":   "عبدالرحمن",
		"أم علي حسن":       "أم علي",
		"الحاج محمود سعيد": "الحاج محمود",
		"Ahmad Ali":        "Ahmad",
		"0991234567":       "",
		"أحمد 0991234567":  "أحمد",
		"٠٩٩١٢٣٤٥٦٧ سامر":  "سامر",
		"   ":              "",
		"":                 "",
		"عبد":              "عبد",
		"  سليمان  ":       "سليمان",
	}
	for in, want := range cases {
		if got := FirstName(in); got != want {
			t.Errorf("FirstName(%q) = %q، والمتوقّع %q", in, got, want)
		}
	}
}
