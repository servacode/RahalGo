package comms

import (
	"strings"
	"unicode"
)

// ══════════════════════════════════════════════════════════════════════
// **تنقيةُ ما يُكتب — قبل أن يُخزَّن**
// ══════════════════════════════════════════════════════════════════════
//
// (قرارُ المالك ٢٠٢٦-٠٨-١٢: «وتحميه الشات من الأكواد والفايروسات
//  للأمان».)
//
// # وأمّا «الأكواد» فبابُها مغلقٌ ببنيةِ العرض لا بفلتر
//
// **الشاشاتُ تعرض النصَّ نصّا**: React يهرب كلَّ رمزٍ في `{body}` بنفسه،
// **وCompose يرسم `Text` لا صفحة.** ولا موضعَ واحدَ في المنصّة يبني HTML
// من كلام مستخدم (`dangerouslySetInnerHTML` غيرُ موجودةٍ في الويب كلِّه —
// قيس ٢٠٢٦-٠٨-١٢).
//
// **وفلترُ «<script>» يعطي أماناً كاذبا**: من اعتمد عليه فتح البابَ يومَ
// يُضاف عرضٌ يبني HTML، **لأنّ الحارسَ في المكان الخطأ.**
//
// # وما يُنقّى فعلاً: محارفُ تخدع العين
//
// **علامةُ قلب الاتّجاه** (`U+202E`) تجعل النصَّ يُعرض معكوسا: يُكتب سطرٌ
// يقول شيئاً **ويُقرأ شيئاً آخرَ في الشاشتين** — وهي حيلةٌ قديمةٌ في
// أسماء الملفّات، وتعمل في أيّ نصٍّ يُعرض.
//
// **ومحارفُ الصفرِ عرضاً** (`U+200B` وأخواتها) تفصل حروفَ الكلمة فتمرّ من
// كلّ حارس: «س‌ب‌ة» تُقرأ كما تُقرأ **ولا يمسكها فحصُ نصّ.**
//
// **ومحارفُ التحكّم** (ما دون المسافة) تكسر السجلّاتِ والتصديرَ إلى CSV.

// sanitize يزيل ما يخدع العين ويُبقي ما يُقرأ.
func sanitize(body string) string {
	var b strings.Builder
	b.Grow(len(body))
	for _, r := range body {
		switch {
		// **والسطرُ الجديد يبقى** — وحدَه من محارف التحكّم.
		case r == '\n':
			b.WriteRune(r)
		case r == '\r' || r == '\t':
			b.WriteRune(' ')
		case unicode.IsControl(r):
			// يُسقط
		case isDeceptive(r):
			// يُسقط
		default:
			b.WriteRune(r)
		}
	}
	// **وعشرون سطراً فارغاً ليست رسالة** — تُطوى إلى سطرين.
	out := b.String()
	for strings.Contains(out, "\n\n\n") {
		out = strings.ReplaceAll(out, "\n\n\n", "\n\n")
	}
	return strings.TrimSpace(out)
}

// isDeceptive **محرفٌ لا يُرى ويغيّر ما يُرى.**
//
// **وتُكتب بأرقامها لا بأشكالها**: محرفٌ لا يُرى مكتوبٌ في الشيفرة
// **لا يراه من يقرؤها**، وبعضُها يرفضه المترجمُ أصلا (`U+FEFF`).
func isDeceptive(r rune) bool {
	switch r {
	// **قلبُ الاتّجاه وتجاوزُه وتضمينُه** — تعرض النصَّ بغير ترتيبه:
	// يُكتب سطرٌ ويُقرأ آخر.
	case 0x202A, 0x202B, 0x202C, 0x202D, 0x202E,
		0x2066, 0x2067, 0x2068, 0x2069,
		// **عرضٌ صفريٌّ ووصلٌ وفصل** — تقطّع الكلمة فتمرّ من كلّ فحص:
		// «س‌ب‌ة» تُقرأ كما تُقرأ ولا يمسكها فحصُ نصّ.
		0x200B, 0x200C, 0x200D, 0x200E, 0x200F, 0xFEFF,
		// **مسافاتٌ لا تُكتب** — تُقلّد الفراغ في أسماءٍ مزوّرة.
		0x2060, 0x180E:
		return true
	}
	return false
}
