package comms

import (
	"strings"
	"unicode"
)

// ══════════════════════════════════════════════════════════════════════
// **حارسُ الشتائم — يَسِم ولا يمنع**
// ══════════════════════════════════════════════════════════════════════
//
// (قرارُ المالك ٢٠٢٦-٠٨-١٢: «ولا تنسَ تعمل أرشفة للكلمات المحظورة —
//  مسبّات أو شتائم».)
//
// # ولماذا وسمٌ لا منع
//
// **المنعُ يُخفي ولا يمنع**: من أراد أن يشتم كتبها بحرفٍ مبدَّلٍ أو بمسافةٍ
// بين حروفها، **فتمرّ ولا تُعرف** — ومن مُنع مرّةً تعلّم كيف يمرّ ثانية.
//
// **والوسمُ يُبقيها ويقولها**: الشكوى تُحسم بنصٍّ مكتوبٍ لا بكلمةٍ ضدّ كلمة،
// **ومحادثةٌ منقّاةٌ لا تشهد لأحد.**
//
// # والعربيّةُ تُكتب بعشرة أشكال
//
// **«إ» و«أ» و«آ» و«ا» حرفٌ واحدٌ في الكتابة السريعة**، و«ة» تُكتب «ه»،
// و«ى» تُكتب «ي». **وحارسٌ يقارن الحرفَ بالحرف** يمسك شكلاً واحداً من عشرة.
//
// **والتشكيلُ والتطويلُ يُحشران للتمويه**: «كــلـب» — **ثلاثةُ محارفٍ زائدة
// تُسقط كلَّ فحصٍ نصّيّ.**
//
// **وتكرارُ الحرف كذلك**: «كلللب» — فيُطوى إلى حرفٍ واحد.

// normalize يردّ الكلمةَ إلى شكلٍ واحدٍ يُقارَن به.
func normalize(s string) string {
	var b strings.Builder
	b.Grow(len(s))
	var last rune
	for _, r := range s {
		switch r {
		case 'أ', 'إ', 'آ', 'ٱ':
			r = 'ا'
		case 'ة':
			r = 'ه'
		case 'ى':
			r = 'ي'
		case 'ؤ':
			r = 'و'
		case 'ئ':
			r = 'ي'
		case 'ـ': // تطويل
			continue
		}
		// **والتشكيلُ يُسقط** — حركاتٌ لا تُغيّر الكلمة وتُسقط المقارنة.
		if unicode.In(r, unicode.Mn) {
			continue
		}
		// **والتكرارُ يُطوى إلى حرفٍ واحد** — «كلللب» تصير «كلب».
		//
		// **وطيُّه إلى حرفين لا يكفي**: من كرّر ثلاثاً مرّ من الحارس،
		// **وهو أوّلُ ما يجرّبه من يريد أن يمرّ.** (كشفه اختبارٌ
		// ٢٠٢٦-٠٨-١٢: «كلللب» مرّت.)
		//
		// **وثمنُه مقبول**: الحرفُ المكرَّرُ في العربيّة يُكتب شدّةً لا
		// حرفين، **وما يُكتب مكرّراً نادر** — ولا لفظَ في القائمة يقع
		// عليه.
		if r == last {
			continue
		}
		last = r
		b.WriteRune(unicode.ToLower(r))
	}
	return b.String()
}

// banned **ألفاظٌ لا تُقال بين سائقٍ وزبون.**
//
// **وهي مكتوبةٌ بشكلها المُطبَّع** — تُقارَن بعد التطبيع لا قبله.
//
// **والقائمةُ قصيرةٌ عمدا**: كلُّ لفظٍ يُضاف يزيد احتمالَ وسمِ بريء
// («كلبش» ليست «كلب»)، **ووسمٌ كاذبٌ يُتعب من يراجع** حتّى يكفّ عن
// المراجعة. **فما شاع وحدَه** — ويُزاد بما يظهر في المراجعة.
var banned = []string{
	"كلب", "حمار", "حيوان", "غبي", "احمق", "قذر", "وسخ",
	"خنزير", "لعنه", "يلعن", "تفو", "زباله", "حقير", "نذل",
	"شرموط", "عرص", "منيك", "كس", "طيز", "خرا", "زق",
	"fuck", "shit", "bitch", "asshole", "idiot", "stupid",
}

// Offense يفحص النصَّ — **ويردّ اللفظَ الذي أوقعه** أو فراغا.
//
// **والفحصُ على الكلمات لا على النصّ كلِّه**: «كسر» تحوي «كس»، **ومن فحص
// بالاحتواء وسم كلَّ من كتب «كسرت الزجاج».**
//
// **والفصلُ بغير الحرف**: مسافةٌ أو نقطةٌ أو رقم — **فمن كتب «يا_كلب»
// يُمسك**، ومن كتب «كلبش» لا يُمسك.
func Offense(body string) string {
	clean := normalize(body)
	words := strings.FieldsFunc(clean, func(r rune) bool {
		return !unicode.IsLetter(r) && !unicode.IsDigit(r)
	})
	for _, w := range words {
		for _, bad := range banned {
			if w == bad {
				return bad
			}
		}
	}
	return ""
}
