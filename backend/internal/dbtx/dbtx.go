// Package dbtx عقدٌ واحدٌ لِما تحتاجه الطبقاتُ من معاملة.
//
// ══════════════════════════════════════════════════════════════════════
// **ولماذا حزمةٌ لا تعريفٌ في كلّ حزمة**
// ══════════════════════════════════════════════════════════════════════
//
// **العمليّةُ الواحدةُ تعبر أربعَ طبقات**: الخادمُ يبدأ المعاملة،
// **والمعجمُ ينشئ المتجر، والهويّةُ تنشئ صاحبَه، والحوافزُ تدفع
// مكافأتَه.** **ولا تقع كلُّها أو لا تقع إلّا إن حملت المعاملةَ نفسَها.**
//
// **وواجهةٌ في كلّ حزمةٍ تُوَلِّد أربعَ نسخٍ متطابقة** — **ومن بدّل
// واحدةً وحدَها كسر ثلاثاً.**
package dbtx

import (
	"context"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgconn"
)

// Querier ما تفعله المعاملةُ والمَسبَحُ معاً.
//
// **و`*pgxpool.Pool` و`pgx.Tx` كلاهما يحقّقه** — **فمن ناداه بالمَسبَح
// كتب بلا معاملةٍ ومن ناداه بالمعاملة انضمّ إليها**، والشيفرةُ واحدة.
type Querier interface {
	Exec(context.Context, string, ...any) (pgconn.CommandTag, error)
	QueryRow(context.Context, string, ...any) pgx.Row
	Query(context.Context, string, ...any) (pgx.Rows, error)
}
