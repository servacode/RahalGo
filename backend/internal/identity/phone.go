package identity

import (
	"strings"
)

// ══════════════════════════════════════════════════════════════════════
// **هويّةُ الرقم — سوريّةٌ وحدَها** (٢٠٢٦-٠٩-١٣)
// ══════════════════════════════════════════════════════════════════════
//
// # ما كان (مقيسٌ قبل التبديل)
//
// **كان العقدُ `^\+[1-9][0-9]{7,14}$`** — **أيُّ رقمٍ في العالم.**
// **واختبارُه يقول ذلك نصّاً**: `{"+905321234567", …, true} // رقم تركي
// صالح`. **فرقمٌ تركيٌّ يُسجَّل حساباً، ويُرسَل إليه رمزُ تحقّق.**
//
// # وقرارُ المنتَج (٢٠٢٦-٠٩-١٣)
//
//	ما يكتبه الناسُ   09XXXXXXXX        — عشرةُ أرقامٍ تبدأ بـ09
//	ما يُقبَل نداءً    وأربعُ صيغٍ تؤولُ إليه
//	ما يُخزَّن         +9639XXXXXXXX     — واحدةٌ لا غير
//
// **والرقمُ السوريُّ المحمول**: `+963` ثمّ **تسعةُ أرقامٍ تبدأ بـ9**.
// **والأرضيُّ ليس هويّةَ حساب** — لا رسائلَ إليه ولا واتساب.
//
// # ولماذا هنا لا في الشاشات
//
// **وثلاثةَ عشرَ مسلكاً في `Service` تنادي هذه الدالّة** — التسجيلُ
// والدخولُ والرمزُ وتبديلُ الرقم واستعادةُ الكلمة وإنشاءُ الموظّفين.
// **فالمنعُ هنا يبلغها كلَّها**، **ومنعٌ في شاشةٍ يُلتَفّ عليه بنداءٍ
// مباشر.**
//
// **والرفضُ قبلَ الإرسال**: `RequestOTP` و`RequestSignup` و
// `RequestPasswordReset` تُطبّع أوّلاً — **فلا يُرسَل رمزٌ إلى رقمٍ
// يُردّ بعده.**

// syrianLocalLen طولُ الرقم المحلّيِّ بعد رمز الدولة — تسعةٌ.
const syrianLocalLen = 9

// NormalizePhone **يوحّد الرقمَ السوريَّ إلى `+9639XXXXXXXX`** — أو يردّ.
//
// # الصيغُ المقبولة
//
//	09XXXXXXXX        صيغةُ الناس
//	+9639XXXXXXXX     الصيغةُ المخزَّنة — يرسلها عميلٌ قائم
//	009639XXXXXXXX    صيغةُ الاتّصال الدوليّ
//	9639XXXXXXXX      بلا بادئة
//	9XXXXXXXX         المحلّيُّ بلا صفر
//
// **وما سواها يُردّ** — **ولا يُعاد تفسيرُ رقمٍ أجنبيٍّ سوريّاً**:
// `+905321234567` يُردّ ولا يُقلَب إلى `+96305321234567`.
func NormalizePhone(raw string) (string, bool) {
	// **والفواصلُ تُطرح**: مسافةٌ وشرطةٌ وقوسان — يكتبها الناسُ عادةً.
	p := strings.Map(func(r rune) rune {
		if r >= '0' && r <= '9' || r == '+' {
			return r
		}
		return -1
	}, raw)

	// **و`+` لا تُقبل إلّا في أوّله** — `9+63…` ليس رقماً.
	if i := strings.IndexByte(p, '+'); i > 0 {
		return "", false
	}

	// ── ردُّ كلِّ صيغةٍ إلى المحلّيِّ التسعيّ ─────────────────────────
	var local string
	switch {
	case strings.HasPrefix(p, "+963"):
		local = p[4:]
	case strings.HasPrefix(p, "00963"):
		local = p[5:]
	case strings.HasPrefix(p, "963"):
		local = p[3:]
	case strings.HasPrefix(p, "+"):
		// **بادئةُ دولةٍ أخرى** — تُردّ صراحةً ولا تُؤوَّل.
		return "", false
	case strings.HasPrefix(p, "0"):
		local = p[1:]
	default:
		local = p
	}

	// ── وشرطُ المحمول السوريّ ────────────────────────────────────────
	//
	// **تسعةُ أرقامٍ تبدأ بـ9** — **ولا أرضيَّ ولا خدميّ**، فهما لا
	// يستقبلان رمزاً ولا واتساب.
	if len(local) != syrianLocalLen || local[0] != '9' {
		return "", false
	}
	for i := 0; i < len(local); i++ {
		if local[i] < '0' || local[i] > '9' {
			return "", false
		}
	}
	return "+963" + local, true
}

// IsSyrianMobile **أهذا رقمٌ سوريٌّ محمول؟** — للحرّاس والتقارير.
//
// **ويُقاس بالتطبيع لا بتعبيرٍ ثانٍ** — **وقاعدتان تفترقان يومَ
// تُبدَّل إحداهما.**
func IsSyrianMobile(raw string) bool {
	_, ok := NormalizePhone(raw)
	return ok
}
