package identity

import (
	"context"
	"strings"
)

// ══════════════════════════════════════════════════════════════════════
//  **نوعُ العميل — أيُّ بابٍ دخل منه؟**
// ══════════════════════════════════════════════════════════════════════
//
// (قرارُ المالك ٢٠٢٦-٠٨-١١، في خطّة تطبيق أندرويد: «لازم نسمح للحساب
//  بجلستين: متصفّح وتطبيق».)
//
// # ولماذا في السياق لا في التوقيع
//
// **ثمانيةُ مداخلَ عامّةٍ تُصدر جلسة** — دخولٌ بكلمة، ورمزٌ لمرّة، وتسجيلٌ
// جديد، واستعادةُ كلمة، ورمزُ أدمن (بابان)، وتسليمٌ بين اللوحات، وتدويرُ
// توكن. **وكلُّها تحمل `userAgent, ip string` متجاورين.**
//
// **ونصٌّ خامسٌ بجانبهما بابُ خطأٍ صامت**: من بدّل موضعَ اثنين لم يُخبره
// المترجم، **فيُسجَّل عنوانُ الإنترنت مكانَ نوع العميل** ويصير لكلّ عنوانٍ
// جلسةٌ مستقلّة — أي إلغاءُ القيد كلِّه بلا أن يظهر.
//
// **والسياقُ يحمله كما يحمل معرّفَ المستخدم في الوسيط** — طريقةٌ يعرفها
// المشروع، **ولا موضعَ فيها يُخطَأ.**

// ClientWeb **المتصفّح — وهو الافتراضُ ومَن لم يُصرّح.**
//
// **ولا يُقسَّم بالدور**: من يفتح لوحتَه وسوقَه في تبويبين هو جلسةٌ واحدة،
// **وقد كان كذلك منذ البداية**، ولا سببَ يبدّله.
const ClientWeb = "web"

// ══════════════════════════════════════════════════════════════════════
// **والتطبيقُ يُقسَّم بتطبيقه لا بمنصّته**
// ══════════════════════════════════════════════════════════════════════
//
// (قرارُ المالك ٢٠٢٦-٠٨-١١: «تطبيقاتٌ منفصلةٌ لكلّ واحدٍ على حدة».)
//
// **كانت `android` نوعاً واحداً** — وهو صحيحٌ لتطبيقٍ واحد. **ومع أربعةِ
// تطبيقاتٍ ينكسر:**
//
// **`FieldRolesAreCustomers` تجعل كلَّ سائقٍ ومتجرٍ ومندوبٍ زبوناً أيضاً**
// (قرارُ المالك ٢٠٢٦-٠٨-١٠). **فالمتجرُ يحمل تطبيقَ متجرِه وتطبيقَ الزبون
// ليطلب عشاءه** — وهما نوعٌ واحد، **فيفتح أحدَهما فيخرج من الآخر.**
//
// **وهي الحلقةُ المقفلةُ نفسُها التي أُصلحت بين الويب والتطبيق** — تعود من
// بابٍ ثانٍ.
//
// **والتقسيمُ بمنصّةٍ وتطبيقٍ لا بقائمةٍ مسطّحةٍ من تسعةِ نصوص**: من أضاف
// تطبيقاً خامساً يضيف كلمةً في مكانٍ واحد، **ولا يكتب أربعَ قيمٍ ينسى
// إحداها.**
var clientPlatforms = map[string]bool{
	"android": true,
	"ios":     true,
}

var clientApps = map[string]bool{
	"customer": true,
	"driver":   true,
	"merchant": true,
	// **والمندوبُ في القائمة وإن أُجّل تطبيقُه**: كلمةٌ لا تُكلّف شيئاً،
	// **وغيابُها يوم يُبنى يجعل التطبيقَ يُقرأ متصفّحاً فيُخرج صاحبَه من
	// لوحته على الويب** — وهو عطبٌ صامتٌ يُبحث عنه طويلاً.
	"rep": true,
}

type clientCtxKey struct{}

// WithClient يضع نوعَ العميل في السياق — **يُنادى من وسيط الخادم وحدَه.**
func WithClient(ctx context.Context, client string) context.Context {
	return context.WithValue(ctx, clientCtxKey{}, normalizeClient(client))
}

// ClientFrom نوعُ العميل من السياق — **و`web` لمن لم يُصرّح.**
//
// **والافتراضُ متصفّحٌ لا خطأ**: كلُّ ما كُتب قبل اليوم متصفّح، **وكلُّ
// نداءٍ من الويب لا يحمل الترويسةَ ولن يحملها.**
func ClientFrom(ctx context.Context) string {
	if v, ok := ctx.Value(clientCtxKey{}).(string); ok {
		return v
	}
	return ClientWeb
}

// normalizeClient يردّ المجهولَ إلى `web` — **لا يرفضه.**
//
// **ورفضُ النداء بسبب ترويسةٍ غريبةٍ يقفل الباب في وجه من لا ذنبَ له**:
// وسيطٌ يعيد كتابة الترويسات، أو نسخةٌ قديمةٌ من التطبيق تكتب اسماً
// تبدّل. **والأسوأُ أن يُمنع الدخولُ لا أن تُشارَك جلسةٌ مع المتصفّح.**
//
// **والقائمةُ مغلقةٌ عمداً**: القيدُ «جلسةٌ لكلّ نوع» لا يعني شيئاً إن
// استطاع أحدٌ أن يخترع نوعاً بترويسةٍ من عنده — **فيفتح مئةَ جلسةٍ بمئة
// كلمة**، وتسقط الحمايةُ من مشاركة الحسابات وهي تبدو قائمة.
func normalizeClient(client string) string {
	platform, app, ok := strings.Cut(client, "-")
	if !ok || !clientPlatforms[platform] || !clientApps[app] {
		return ClientWeb
	}
	return platform + "-" + app
}
