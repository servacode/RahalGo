package identity

import "testing"

// TestNormalizePhone **هويّةُ الرقم سوريّةٌ وحدَها** (٢٠٢٦-٠٩-١٣).
//
// **وكان العقدُ يقبل أيَّ رقمٍ في العالم** — وسطرُه القديم يقول نصّاً
// `{"+905321234567", "+905321234567", true} // رقم تركي صالح`.
// **فرقمٌ تركيٌّ يُسجَّل حساباً ويُرسَل إليه رمز.**
func TestNormalizePhone(t *testing.T) {
	cases := []struct {
		in   string
		want string
		ok   bool
		why  string
	}{
		// ── صيغةُ الناس ───────────────────────────────────────────
		{"0932123456", "+963932123456", true, "صيغةُ الناس"},
		{"0999999999", "+963999999999", true, "أعلى محمول"},
		{"0900000000", "+963900000000", true, "أدنى محمول"},

		// ── والصيغُ الأربعُ المقبولةُ نداءً ───────────────────────
		{"+963932123456", "+963932123456", true, "المخزَّنةُ — عميلٌ قائم"},
		{"00963932123456", "+963932123456", true, "اتّصالٌ دوليّ"},
		{"963932123456", "+963932123456", true, "بلا بادئة"},
		{"932123456", "+963932123456", true, "محلّيٌّ بلا صفر"},

		// ── والفواصلُ تُطرح ──────────────────────────────────────
		{"0932 123 456", "+963932123456", true, "مسافات"},
		{"0932-123-456", "+963932123456", true, "شُرَط"},
		{"(0932) 123-456", "+963932123456", true, "أقواس"},

		// ══════════════════════════════════════════════════════════
		// **والأجنبيُّ يُردّ ولا يُؤوَّل** — وهذا ما كان مفتوحاً
		// ══════════════════════════════════════════════════════════
		{"+905321234567", "", false, "تركيّ"},
		{"+14155552671", "", false, "أمريكيّ"},
		{"+9715012345678", "", false, "إماراتيّ"},
		{"+4915112345678", "", false, "ألمانيّ"},
		{"+96650123456", "", false, "سعوديّ — وبادئتُه تشبه سوريا"},
		{"0090532123456", "", false, "دوليٌّ تركيٌّ بصفرين"},

		// ── وبادئاتٌ سوريّةٌ ليست محمولاً ─────────────────────────
		{"0112345678", "", false, "أرضيُّ دمشق — لا رمزَ إليه"},
		{"0212345678", "", false, "أرضيُّ حلب"},
		{"+963112345678", "", false, "أرضيٌّ بالصيغة المخزَّنة"},

		// ── وطولٌ خاطئ ───────────────────────────────────────────
		{"093212345", "", false, "تسعةٌ — ناقصٌ رقماً"},
		{"09321234567", "", false, "أحدَ عشرَ — زائدٌ رقماً"},
		{"+96393212345", "", false, "ناقصٌ بالصيغة المخزَّنة"},
		{"+9639321234567", "", false, "زائدٌ بالصيغة المخزَّنة"},

		// ── ومشوَّهٌ ──────────────────────────────────────────────
		{"12345", "", false, "قصير"},
		{"abc", "", false, "حروف"},
		{"", "", false, "فارغ"},
		{"+", "", false, "بادئةٌ وحدَها"},
		{"0932abc456", "", false, "حروفٌ في وسطه"},
		{"9+63932123456", "", false, "بادئةٌ في وسطه"},
		{"0000000000", "", false, "أصفارٌ — لا يبدأ بـ9"},
		{"0812345678", "", false, "يبدأ بـ08"},
	}
	for _, c := range cases {
		got, ok := NormalizePhone(c.in)
		if ok != c.ok || got != c.want {
			t.Errorf("NormalizePhone(%q) = (%q, %v) · المنتظَر (%q, %v) — %s",
				c.in, got, ok, c.want, c.ok, c.why)
		}
	}
}

// TestPhoneIdentityIsOne **وصيغتان تؤولان إلى حسابٍ واحد.**
//
// **وشرطُ المالك**: `09XXXXXXXX` و`+9639XXXXXXXX` **هويّةٌ واحدة** —
// **ولا حسابٌ مكرَّرٌ لفرقٍ في الكتابة وحدَه.**
func TestPhoneIdentityIsOne(t *testing.T) {
	groups := [][]string{
		{"0932123456", "+963932123456", "00963932123456", "963932123456",
			"932123456", "0932 123 456", "0932-123-456"},
		{"0988776655", "+963988776655", "00963988776655", "988776655"},
	}
	for _, g := range groups {
		first, ok := NormalizePhone(g[0])
		if !ok {
			t.Fatalf("الصيغةُ الأولى %q رُدّت", g[0])
		}
		for _, in := range g[1:] {
			got, ok := NormalizePhone(in)
			if !ok || got != first {
				t.Errorf("**هويّتان لرقمٍ واحد**: %q ⇒ %q · و%q ⇒ %q",
					g[0], first, in, got)
			}
		}
	}
}

// TestIsSyrianMobileAgreesWithNormalize **ولا قاعدةَ ثانية.**
func TestIsSyrianMobileAgreesWithNormalize(t *testing.T) {
	for _, in := range []string{
		"0932123456", "+963932123456", "+905321234567", "0112345678", "", "abc",
	} {
		_, ok := NormalizePhone(in)
		if IsSyrianMobile(in) != ok {
			t.Errorf("**قاعدتان تفترقان على %q**", in)
		}
	}
}
