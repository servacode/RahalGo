package identity

// **رمزُ الأدمن — حارسٌ على شكله وعلى من يلزمه.**
//
// # ولماذا حارسٌ لهذين بالذات
//
// **الشكلُ يُقفل صاحبَه**: من قَبِل رمزاً بخمسة أرقامٍ أو بأرقامٍ عربيّةٍ
// **ضبطه بلوحةِ مفاتيحَ ثمّ لم يستطع إدخالَه بأخرى** — ولا أحدَ فوق المالك
// يفتح له لوحته.
//
// **ومن يلزمه قرارُ مالك**: «فقط للأدمن». **وسطرٌ يُضاف بعد شهرٍ يوسّعه إلى
// العمليّات فيقف موظّفٌ أمام رمزٍ لا يملكه**، أو يضيّقه فيسقط الحارسُ عن
// أخطر حساب — **وكلاهما لا يُرى في شاشة.**

import "testing"

func TestPin_FormatIsFourDigitsOnly(t *testing.T) {
	ok := []string{"0000", "1234", "9999"}
	for _, p := range ok {
		if !validPin(p) {
			t.Fatalf("رُفض رمزٌ سليم %q — **فلا يستطيع المالكُ ضبطَ رمزه**", p)
		}
	}
	// **والعربيّةُ مرفوضةٌ عمداً** — تُكتب بلوحةٍ ولا تُقرأ بأخرى.
	bad := []string{"", "1", "123", "12345", "abcd", "12a4", "١٢٣٤", " 123", "12 4"}
	for _, p := range bad {
		if validPin(p) {
			t.Fatalf("قُبل رمزٌ فاسد %q — **ورمزٌ يُضبط بلوحةٍ ولا يُقبل بأخرى يُقفل صاحبَه**", p)
		}
	}
}

func TestPin_RequiredForAdminOnly(t *testing.T) {
	if !NeedsPin([]string{"admin", "customer"}) {
		t.Fatalf("الأدمنُ بلا رمز — **وهو أخطرُ حسابٍ في المنصّة، وبابُه بابُ الجميع**")
	}
	// **وقرارُ المالك: العملياتُ والماليةُ خارجَه.**
	for _, roles := range [][]string{
		{"ops", "customer"}, {"finance", "customer"}, {"merchant"},
		{"driver"}, {"sales"}, {"customer"}, {},
	} {
		if NeedsPin(roles) {
			t.Fatalf("طُلب رمزٌ من %v — **فيقف موظّفٌ أمام رمزٍ لا يملكه ولا سبيلَ له**", roles)
		}
	}
}
