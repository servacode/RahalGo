package identity

import (
	"context"
	"errors"
	"fmt"
)

// ══════════════════════════════════════════════════════════════════════
// **غيابُ خبرٍ ليس خبراً بالسلامة** — `R16`
// ══════════════════════════════════════════════════════════════════════
//
// # ما كان
//
//	n, err := s.rdb.Exists(ctx, sessionRevokedKey(sid)).Result()
//	return err == nil && n > 0
//
// **و`bool` واحدٌ يخلط حالين لا ثالثَ لهما عنده**: «ليست مُبطَلة»
// و«لا أعرف». **فسقوطُ `Redis` يُقرأ سلامةً** — **وجلسةٌ أُبطلت تعود
// تعمل بمجرّد أن تسقط خبيئة.**
//
// **وقيس بذاكرةٍ حقيقيّة**: مُبطَلةٌ و`Redis` قائمة ⇒ `401`؛ ثمّ
// أُوقفت الحاويةُ ⇒ **`200`**.
//
// # وما هو أخطرُ من ذلك — ولا يُصلحه الرجوعُ إلى القاعدة وحدَه
//
// **منتِجو الإبطال يكتبون القاعدةَ أوّلاً ثمّ `Redis`** — **وكتابةُ
// `Redis` تسقط صامتةً أثناء العطل** (`revokeSession` لا يفحص خطأها).
// **فهذا ممكن**:
//
//	١ جلسةٌ قائمة              ٥ كتابةُ Redis تسقط
//	٢ Redis تسقط               ٦ Redis تعود
//	٣ تُبطَل الجلسة            ٧ EXISTS يردّ صفراً
//	٤ القاعدةُ تُسجّل الإبطال   ٨ **الجلسةُ المُبطَلةُ تعود صالحة**
//
// **فغيابُ المفتاح ليس برهانَ سلامة** — **لا حين تسقط `Redis` ولا
// حين تعود.**
//
// # وما صار — أدوارٌ مسمّاة
//
//	PostgreSQL  **الحقيقةُ الموثوقة** — `refresh_tokens`
//	Redis       **مُسرِّعُ رفضٍ موجَبٌ لا غير**
//
//	إصابةٌ في Redis   ⇒ REVOKED فوراً — ولا سؤالَ للقاعدة
//	غيابٌ في Redis    ⇒ **غيرُ حاسم** ⇒ تُسأل القاعدة
//	خطأٌ أو مهلة      ⇒ **غيرُ حاسم** ⇒ تُسأل القاعدة
//	القاعدةُ ساقطة    ⇒ **خطأٌ يُرفَع** ⇒ المنادي يردّ ٥٠٣
//
// **ولا حالَ تُقرأ سلامةً إلّا بصفٍّ حيٍّ في القاعدة يُثبتها.**

// SessionState حالُ الجلسة كما ثبتت — **ولا رابعَ لها.**
type SessionState int

const (
	// SessionValid **صفٌّ حيٌّ في القاعدة يُثبتها** — لا مجرّدُ غيابِ
	// دليلِ إبطال.
	SessionValid SessionState = iota
	// SessionRevoked أُبطلت أو انتهت أو لا تُعرَف.
	SessionRevoked
)

func (st SessionState) String() string {
	if st == SessionRevoked {
		return "REVOKED"
	}
	return "VALID"
}

// ErrSessionCheckUnavailable **تعذّر التحقّق** — لا «سليمة» ولا «مُبطَلة».
//
// **والمنادي يردّ ٥٠٣ لا ٤٠١**: **«لا أستطيع التحقّق» غيرُ «رمزُك
// مُبطَل»** — والثاني كذبٌ يُخرج صاحبَ جلسةٍ سليمة.
var ErrSessionCheckUnavailable = errors.New("identity: تعذّر التحقّق من الجلسة")

// CheckSession **التحقّقُ الموثوق** — `R16`.
//
// **ولا تُرجع `bool`**: **الشكلُ نفسُه هو ما أوقع العيب** — من كتب
// `revoked = false` عند الخطأ لم يخالف نوعاً، **فالنوعُ سمح له.**
//
// # ومعرّفُ جلسةٍ فارغٌ صنفٌ مستثنى — مُعلَنٌ لا مسكوتٌ عنه
//
// **توكنٌ بلا معرّفِ جلسةٍ لا يُبطَل اليوم أصلاً** (`sid == ""` كانت
// تردّ `false` فوراً). **وإصدارُ المنصّة لا يُنتجه**: `issueSession`
// ينادي `StoreRefresh` **قبل** إصدار التوكن ويأخذ منه المعرّف —
// **فلكلّ توكنِ وصولٍ حقيقيٍّ صفٌّ دائم.**
//
// **والصنفُ الوحيدُ بلا معرّفٍ هو ما تصنعه أدواتُ الفحص** —
// **ويحرسه `TestR16_IssuedTokensAlwaysCarrySession`.**
func (s *Service) CheckSession(ctx context.Context, sid string) (SessionState, error) {
	if sid == "" {
		return SessionValid, nil
	}

	// ── مُسرِّعُ الرفض الموجَب ────────────────────────────────────
	//
	// **الإصابةُ وحدَها حاسمة** — **والغيابُ والخطأُ سواءٌ: لا أعرف.**
	if n, err := s.rdb.Exists(ctx, sessionRevokedKey(sid)).Result(); err == nil && n > 0 {
		return SessionRevoked, nil
	}

	return s.sessionStateFromDB(ctx, sid)
}

// sessionStateFromDB **الحقيقةُ الموثوقة.**
//
// # ولماذا عدّان لا وجودٌ واحد
//
// **«لا صفَّ حيّاً» يخلط حالين**: **جلسةٌ أُبطلت** و**جلسةٌ لا تُعرَف**.
// **وكلتاهما تُرفَض** — **لكنّ التمييزَ يظهر في السجلّ**، فمن رأى
// «لا تُعرَف» كثيرةً عرف أنّ ثمّةَ توكناتٍ تُصدَر خارجَ المسار.
//
// # والانتهاءُ رفضٌ أيضاً
//
// **`RevokeSession` تُبطل ما لم ينتهِ فقط** (`expires_at > now()`) —
// **فالمنتهي يبقى `revoked_at IS NULL` إلى الأبد.** **فلو سُئل عن
// الإبطال وحدَه لَقرأ المنتهي سليماً.**
func (s *Service) sessionStateFromDB(ctx context.Context, sid string) (SessionState, error) {
	live, total, err := s.repo.SessionRows(ctx, sid)
	if err != nil {
		return SessionRevoked, fmt.Errorf("%w: %v", ErrSessionCheckUnavailable, err)
	}
	if live > 0 {
		return SessionValid, nil
	}
	if total == 0 && s.logger != nil {
		// **جلسةٌ لا يعرفها الجدول** — **ولا معرّفَ يُطبع**: هو نصفُ
		// مفتاحِ جلسةٍ حيّة. **والعددُ وحدَه يكفي لملاحظة النمط.**
		s.logger.Warn("التوثيق: جلسةٌ لا تُعرَف في الحقيقة الموثوقة",
			"outcome", "unknown_session")
	}
	return SessionRevoked, nil
}
