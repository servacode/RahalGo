package pricing_test

import (
	"testing"

	"github.com/servacode/rahalgo/backend/internal/pricing"
)

// TestSalePrice الهامشُ يُورَث، والتجاوزُ فراغٌ لا صفر، والتقريبُ لأعلى.
//
// **وأخطرُ ما فيه سطرُ الصفر.** التجاوزُ `NULL` يعني «اتبع ما فوقك»، و`0` يعني
// «لا هامشَ على هذا» — **ومن خلط بينهما جعل كلَّ صنفٍ لم يُلمس بلا هامش**،
// فتبيع المنصةُ ألفَ صنفٍ بسعر شرائها ولا يظهر ذلك في أيّ خطأ.
func TestSalePrice(t *testing.T) {
	n := func(v int64) *int64 { return &v }

	cases := []struct {
		name     string
		rule     pricing.MarginRule
		cost     int64
		item     *int64
		category *int64
		want     int64
	}{
		// **رقمٌ ثابتٌ يُضاف** — لا نسبةَ ولا تقريب. (قرارُ المالك ٢٠٢٦-٠٨-٠٤.)
		//
		// **والثابتُ يوافق تكلفتَك**: سائقٌ وعملياتٌ لا يتضاعفان بتضاعف قيمة
		// الطعام — **وصينيةٌ بستّين ألفاً لا تكلّفك عشرةَ أضعاف الشاورما.**
		{"الهامشُ يُضاف كما هو",
			pricing.MarginRule{Value: 3_000}, 10_000, nil, nil, 13_000},
		{"وعلى الغالي لا يتضاعف",
			pricing.MarginRule{Value: 3_000}, 60_000, nil, nil, 63_000},

		// **والوراثةُ ثلاثُ طبقات**: الصنفُ يرث قسمَه، والقسمُ يرث العامّ.
		{"تجاوزُ القسم يسبق العام",
			pricing.MarginRule{Value: 3_000}, 10_000, nil, n(5_000), 15_000},
		{"وتجاوزُ الصنف يسبقهما",
			pricing.MarginRule{Value: 3_000}, 10_000, n(1_000), n(5_000), 11_000},

		// **الصفرُ قرارٌ لا فراغ.**
		//
		// `NULL` تعني «اتبع ما فوقك» و`0` تعني «لا هامشَ على هذا» — **ومن خلط
		// بينهما جعل كلَّ صنفٍ لم يُلمس بلا هامش.**
		{"صفرُ الصنف يعني لا هامش",
			pricing.MarginRule{Value: 3_000}, 10_000, n(0), n(5_000), 10_000},
		{"وصفرُ القسم كذلك",
			pricing.MarginRule{Value: 3_000}, 10_000, nil, n(0), 10_000},

		// **ولا يُباع بأقلّ من ثمنه.**
		//
		// هامشٌ سالبٌ بالخطأ يجعل المنصةَ تدفع من جيبها عن كلّ بيعة —
		// **وخسارةٌ تتكرّر بلا حدث تُكتشف في آخر الشهر.**
		{"الهامشُ السالب لا يُنقص الثمن",
			pricing.MarginRule{Value: -5_000}, 10_000, nil, nil, 10_000},

		// **وصفرُ الهامش هو حالُ الترحيل** — سعرُ البيع = سعرُ الشراء.
		{"بلا هامشٍ سعرُ البيع سعرُ الشراء",
			pricing.MarginRule{}, 10_000, nil, nil, 10_000},
	}

	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := c.rule.SalePrice(c.cost, c.item, c.category); got != c.want {
				t.Errorf("سعرُ البيع = %d، والمتوقّع %d", got, c.want)
			}
		})
	}
}
