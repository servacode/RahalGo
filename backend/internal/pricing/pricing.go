package pricing

// التسعير — **من سعر الشراء إلى سعر البيع.**
//
// # النموذج
//
//	سعرُ الشراء  ←  ما وضعه المتجر — وتُخصم منه العمولة
//	الهامش      ←  ما تضيفه المنصة — وهو ربحُها
//	التقريب     ←  ما يجعل الرقمَ يُقرأ
//	سعرُ البيع   ←  ما يدفعه الزبون
//
// # ولماذا الهامشُ يُورَث
//
// **ولا أحدَ يُسعّر ألفَ صنفٍ بيده.** فالصنفُ يرث تصنيفَه، والتصنيفُ يرث العام
// — **ومن أراد أن يخصّ صنفاً خصّه، ومن لم يُرد لم يفعل شيئاً.**
//
// **والتجاوزُ فراغٌ لا صفر**: الصفرُ قرارٌ («لا هامشَ على هذا») والفراغُ غيابُ
// قرار («اتبع ما فوقك»). **ومن خلط بينهما جعل كلَّ صنفٍ لم يُلمس بلا هامش.**
//
// # ولماذا نمطان
//
// **الثابتُ يوافق تكلفتَك**: سائقٌ وعملياتٌ لا يتضاعفان بتضاعف قيمة الطعام —
// **وصينيةٌ بستّين ألفاً لا تكلّفك عشرةَ أضعاف الشاورما.**
//
// **والنسبةُ تمنع أن يبدو الرخيصُ غالياً**: خمسون بالمئة على الشاورما **يراها
// من يعرف سعرَها.** وطبقةُ التصنيف تحلّهما معاً.
//
// # والتقريبُ ليس تجميلاً
//
// قائمةٌ فيها ٨٬١٢٥ و١١٬٣٧٥ **تقول «هذه آلةٌ تحسب»**، وقائمةٌ فيها ٨٬٠٠٠
// و١١٬٥٠٠ تقول **«هذا سعرُنا»**. وفي سوريا حيث الفئاتُ كبيرة **هو ما يجعل
// الحسابَ ممكناً في الجيب.**

import (
	"context"
	"math"
)

// MarginRule ما يلزم لحساب سعر بيعٍ من سعر شراء.
type MarginRule struct {
	// Value الهامشُ العام بالليرة — **رقمٌ ثابتٌ يُضاف، لا نسبة.**
	//
	// (قرارُ المالك ٢٠٢٦-٠٨-٠٤: «هامشُ ربح المنصة حقلُ رقمٍ ثابتٍ فقط».)
	Value int64
}

// Store ما يلزم لقراءة المفاتيح — واجهةٌ ضيّقة **كي لا تجرّ الحزمةُ إعداداتٍ
// كاملةً خلفها**، ولتُختبَر بلا قاعدة بيانات.
type Store interface {
	// GetString **بلا احتياطيٍّ من المنادي** — الافتراضُ في الفهرس وحدَه.
	//
	// كان يأخذه، **فكتب كلُّ منادٍ افتراضَه بيده** ووُجد الافتراضُ نفسُه في
	// موضعين. **ورقمان لمعنًى واحدٍ يفترقان.**
	GetString(ctx context.Context, key string) string
	GetInt(ctx context.Context, key string) int64

	// GetHundredths **نسبةٌ بمنزلتين بأجزاء المئة** — `1.5` تُقرأ `150`.
	//
	// **و`GetInt` تبتر `1.5` إلى `1`** — فعمولةُ المنصّة لا تُقرأ بها.
	GetHundredths(ctx context.Context, key string) int64

	// GetBool **مفتاحٌ يُشعَل ويُطفأ** — يلزم لأجرة المسافة.
	GetBool(ctx context.Context, key string) bool
}

// RuleFrom يقرأ مفتاحَ الهامش.
//
// **وبلا مخزنٍ لا هامش**: صفرٌ يعني «سعرُ البيع = سعرُ الشراء» — **وهو الحال
// قبل أن يقرّر المالك**، ولا يخترع ربحاً لم يُتّفق عليه.
func RuleFrom(ctx context.Context, st Store) MarginRule {
	if st == nil {
		return MarginRule{}
	}
	return MarginRule{Value: st.GetInt(ctx, "pricing.margin_fixed")}
}

// SalePrice سعرُ البيع من سعر الشراء والتجاوزات.
//
// `itemOverride` و`categoryOverride` فراغُهما يعني «اتبع ما فوقك».
func (r MarginRule) SalePrice(merchantPrice int64, itemOverride, categoryOverride *int64) int64 {
	margin := r.Value
	switch {
	case itemOverride != nil:
		margin = *itemOverride
	case categoryOverride != nil:
		margin = *categoryOverride
	}

	sale := merchantPrice + margin
	// **ولا يُباع بأقلّ من ثمنه.** هامشٌ سالبٌ بالخطأ يجعل المنصةَ تدفع من
	// جيبها عن كلّ بيعة — **وخسارةٌ تتكرّر بلا حدث تُكتشف في آخر الشهر.**
	if sale < merchantPrice {
		return merchantPrice
	}
	return sale
}

// ── نسبةٌ أو مقطوع — والقاعدةُ واحدةٌ لثلاثة أموال ─────────────────────────
//
// عمولةُ المنصة من المتاجر، وعمولةُ المندوب، وهامشُ البيع: **ثلاثةُ أرقامٍ
// يسألها المالكُ السؤالَ نفسَه** — أنسبةٌ هي أم رقمٌ مقطوع؟
//
// **ولكلٍّ منها كانت حسبتُها في موضعها**: عمولةُ المندوب مكتوبةٌ بـSQL في
// ثلاثة ملفّات، وعمولةُ المتجر عمودٌ يُضرب في مئةٍ في خمسة. **وحسبةٌ في خمسة
// مواضع تفترق في الرابع** — فيُدفع للمندوب غيرُ ما يُعرض له.
//
// (قرارُ المالك ٢٠٢٦-٠٨-٠٤: «نسبةُ المندوب أو رقمٌ ثابتٌ مقطوع · عمولةُ المنصة
// نسبةٌ أو مقطوعةٌ من المتاجر · ولازم كلُّ المشروع يأخذ الإعداداتِ هذه بحيث
// تُطبَّق بشكلٍ حقيقيٍّ فوريٍّ عند أيّ تغيّر».)

// Amount مبلغٌ يُشتقّ من أساس — **نسبةً منه أو رقماً مقطوعاً بدلَه.**
type Amount struct {
	// Mode "percent" أو "fixed" أو `ModePercent2`.
	Mode string
	// Value النسبةُ المئوية، أو المبلغُ المقطوع بالليرة — **أو أجزاءُ المئة
	// من الواحد بالمئة في `ModePercent2`** (`150` = ١٫٥٪).
	Value int64
}

// ModePercent2 **نسبةٌ بمنزلتين** — `Value` بأجزاء المئة (قرارُ المالك ٢٠٢٦-١٠-١٨).
//
// **وعمولةُ المنصّة من المتاجر وحدَها بهذا النمط** — وعمولةُ المندوب باقيةٌ
// نسبةً صحيحة.
const ModePercent2 = "percent2"

// Percent **النسبةُ بمنزلتين أيّاً كان النمط** — للعرض.
func (a Amount) Percent() Percent2 {
	if a.Mode == ModePercent2 {
		return Percent2(a.Value)
	}
	return Pct(a.Value)
}

// Of يحسب المبلغ من أساسه.
//
// **ولا يتجاوز الأساسَ ولا ينزل تحت الصفر.** عمولةٌ مقطوعةٌ بعشرين ألفاً على
// طلبٍ بخمسة عشر **تجعل المتجرَ يدفع لنا كي يبيع** — ورقمٌ سالبٌ يخرج من هنا
// يقلب قيداً محاسبيّاً بلا أن يصرخ أحد.
func (a Amount) Of(base int64) int64 {
	if base <= 0 {
		return 0
	}
	var v int64
	switch a.Mode {
	case "fixed":
		v = a.Value
	case ModePercent2:
		// **والبترُ نفسُه** — `ثمن × ١٠٠٠ ÷ ١٠٠٠٠` يساوي `ثمن × ١٠ ÷ ١٠٠` ليرةً بليرة.
		v = base * a.Value / 10000
	default:
		v = base * a.Value / 100
	}
	if v < 0 {
		return 0
	}
	if v > base {
		return base
	}
	return v
}

// MerchantCommission عمولةُ المنصة من المتجر — **تُقتطع من سعر شرائه.**
//
// **والمتجرُ قد يُخصّ بنسبةٍ غير العامّة** (`merchants.commission_percent`
// في صفّه): تجاوزٌ مثلُ تجاوز هامش الصنف — **وفراغُه «اتبع العام» لا «بلا
// عمولة».** ومن خلط بينهما جعل كلَّ متجرٍ لم يُلمس بلا عمولة.
//
// **والنسبةُ بمنزلتين** (`Percent2`، قرارُ المالك ٢٠٢٦-١٠-١٨) — ١٫٥٪ تُحسب
// ١٫٥٪ لا ١٪ ولا ٢٪.
func MerchantCommission(ctx context.Context, st Store, override *Percent2) Amount {
	if override != nil {
		return Amount{Mode: ModePercent2, Value: int64(*override)}
	}
	// **نسبةٌ لا نمط.** كانت نمطاً وقيمةً (نسبةٌ أو مقطوع)، **ومقطوعٌ من متجرٍ
	// صغيرٍ يبيع بعشرة آلافٍ غيرُ مقطوعٍ من متجرٍ يبيع بمئة** — والنسبةُ تتبع
	// حجمَه وحدَها. (قرارُ المالك ٢٠٢٦-٠٨-٠٤: «نسبةُ عمولة المنصة».)
	if st == nil {
		return Amount{Mode: ModePercent2}
	}
	return Amount{Mode: ModePercent2, Value: st.GetHundredths(ctx, "merchants.commission_percent")}
}

// RepCommission نسبةُ المندوب من عمولة المنصة — **حصّةٌ من حصّتنا لا من البيع.**
//
// **ونسبةٌ لا نمط**: ما يأخذه جزءٌ ممّا نكسبه، **ومقطوعٌ منها لا معنى له** —
// قد يتجاوز العمولةَ نفسَها في طلبٍ صغير.
func RepCommission(ctx context.Context, st Store) Amount {
	if st == nil {
		return Amount{Mode: "percent"}
	}
	return Amount{Mode: "percent", Value: st.GetInt(ctx, "sales.commission_percent")}
}

// ── أجرةُ التوصيل — رقمٌ مقطوعٌ واحد ──────────────────────────────────────
//
// # لماذا رقمٌ واحد
//
// كانت ثلاثةَ أنماط: مقطوعةٌ وبالمنطقة وبالمسافة. **وثلاثةُ أنماطٍ تعني أربعةَ
// مفاتيحَ وحقلَ أجرةٍ في كلّ منطقة** — ومن أراد أن يعرف بكم يُوصَّل طلبٌ فتح
// ثلاثة مواضعَ وجمع.
//
// **والأجرةُ الواحدةُ تُقال في جملة**: «التوصيل عندنا كذا». يعرفها الزبونُ
// قبل أن يطلب، ويعرفها السائقُ قبل أن يأخذ، **ولا تُحسب بحسبةٍ يشكّ فيها
// أحدُهما.**
//
// (قرارُ المالك ٢٠٢٦-٠٨-٠٤: «حقلٌ ندخل المبلغ — لا نسبة ولا مسافة ولا شيء،
// رقمٌ مقطوعٌ فقط».)
//
// # والمناطقُ تبقى تغطيةً لا تسعيراً
//
// **حدُّ التغطية غيرُ الأجرة**: الدوائرُ تقول «إلى أين نُوصّل»، والرقمُ يقول
// «بكم». **ومن خلطهما فتح المدينةَ كلَّها بمجرّد أن وحّد الأجرة.**

// DeliveryFee أجرةُ التوصيل — **رقمٌ واحدٌ لكلّ طلب.**
//
// **وبلا مخزنٍ صفر**: لا يُخترع رسمٌ لم يقرّره أحد. **وصفرٌ هنا يعني توصيلاً
// مجّانيّاً** — فيُقال في الشاشة صراحةً لا يُترك يُكتشف في آخر الشهر.
func DeliveryFee(ctx context.Context, st Store) int64 {
	if st == nil {
		return 0
	}
	fee := st.GetInt(ctx, "delivery.fee")
	if fee < 0 {
		return 0
	}
	return fee
}

// DeliveryFeeAt أجرةُ التوصيل على مسافةٍ بالمتر — **والمفتاحُ يقرّر.**
//
// (طلبُ المالك ٢٠٢٦-٠٨-١٨: «إذا شغّال عن طريق المسافة نحن نحدّد الأجرةَ
// حسب المسافة، وإذا موقّف يأخذ الأجورَ الموجودة بلوحة التحكّم».)
//
// # ولماذا دالّةٌ واحدةٌ للحالين
//
// **مطفأً تردّ ما كانت `DeliveryFee` تردّه** — فلا فرعٌ عند كلّ منادٍ.
// **ودالّتان إحداهما للحال وأخرى للأخرى تفترقان يومَ يُصلَح إحداهما**، وهي
// عائلةُ الخلل نفسُها التي وحّدت `DeliveryAt` من أجلها.
//
// # والأساسُ يبقى أساساً في الحالين
//
// `delivery.fee` هو ما يُضاف إليه لا ما يُستبدَل به. **ومن أطفأ المفتاحَ
// رجع إلى رقمه بلا أن يُعيد ضبطَ شيء** — ولا يُترك حقلٌ يذكر رقماً لا
// يُقرأ.
//
// # والسقفُ ليس تجميلاً
//
// **المسافةُ تُقاس بخطٍّ مستقيمٍ لا بالطريق** — وخطٌّ يعبر النهرَ يقول
// كيلومترين والطريقُ سبعة. **والعكسُ أخطر**: طريقٌ ملتوٍ يُحسَب قصيراً.
// فالسقفُ يقصّ الطرفَ الذي لا يقبله زبون، وصفرٌ يعني «بلا سقف».
func DeliveryFeeAt(ctx context.Context, st Store, meters float64) int64 {
	return RuleOf(ctx, st, StandardFeeKeys).At(meters)
}

// ══════════════════════════════════════════════════════════════════════
// **ولكلِّ نوعٍ مفاتيحُ أجرته** (قرارُ المالك ٢٠٢٦-١٠-١٦)
// ══════════════════════════════════════════════════════════════════════
//
// **كانت «لدي توصيلة» تقرأ مفاتيحَ العاديّ نفسَها** — فمن رفع أجرةَ الطلب العاديّ رفع
// أجرةَ توصيلة المتجر بلا أن يدري. **فصار لكلّ نوعٍ أربعةُ مفاتيح** والحسبةُ واحدة
// (`FeeRule.At`) — **فلا تفترق حسبتان يومَ تُصلَح إحداهما.**

// FeeKeys **أسماءُ مفاتيح الأجرة لنوعٍ واحد.**
type FeeKeys struct {
	Base, ByDistance, PerKm, Max string
}

// StandardFeeKeys **مفاتيحُ الطلب العاديّ** — كما كانت.
var StandardFeeKeys = FeeKeys{
	Base: "delivery.fee", ByDistance: "delivery.by_distance",
	PerKm: "delivery.per_km", Max: "delivery.max_fee",
}

// MerchantDeliveryFeeKeys **مفاتيحُ «لدي توصيلة»** — افتراضُها قيمُ العاديّ يومَ نُشرت
// (هجرة `0452` تنسخها)، **فلا يتبدّل رقمٌ حتّى يعدّلها المالك.**
var MerchantDeliveryFeeKeys = FeeKeys{
	Base: "delivery.merchant_base_fee", ByDistance: "delivery.merchant_by_distance",
	PerKm: "delivery.merchant_per_km", Max: "delivery.merchant_max_fee",
}

// FeeRule **قاعدةُ أجرةٍ مقروءة** — أساسٌ، ومسافةٌ تشتعل أو تنطفئ، وثمنُ كيلومتر، وسقف.
type FeeRule struct {
	Base, PerKm, Max int64
	ByDistance       bool
}

// RuleOf **يقرأ قاعدةَ نوعٍ من الإعدادات** — وبلا مخزنٍ صفرٌ كلُّها (لا رسمَ لم يقرّره أحد).
func RuleOf(ctx context.Context, st Store, k FeeKeys) FeeRule {
	if st == nil {
		return FeeRule{}
	}
	r := FeeRule{
		Base: st.GetInt(ctx, k.Base), ByDistance: st.GetBool(ctx, k.ByDistance),
		PerKm: st.GetInt(ctx, k.PerKm), Max: st.GetInt(ctx, k.Max),
	}
	if r.Base < 0 {
		r.Base = 0
	}
	return r
}

// At **الأجرةُ على مسافةٍ بالمتر** — والشرحُ في `DeliveryFeeAt`.
func (r FeeRule) At(meters float64) int64 {
	if !r.ByDistance || r.PerKm <= 0 || meters <= 0 {
		return r.Base
	}
	// **والكيلومترُ يُقرَّب لأعلى** — **وكسرٌ يُهمَل يجعل من يبعد ١٫٩ كم
	// يدفع أجرةَ كيلومترٍ واحد.**
	fee := r.Base + r.PerKm*int64(math.Ceil(meters/1000))
	if r.Max > 0 && fee > r.Max {
		return r.Max
	}
	return fee
}
