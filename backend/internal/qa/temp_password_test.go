// ══════════════════════════════════════════════════════════════════════
// **الكلمةُ المؤقّتةُ لا تفتح المنصّة** (`TMP`، ٢٠٢٦-٠٩-١٣)
// ══════════════════════════════════════════════════════════════════════
//
// # العقد
//
// **و`must_change_password` واقعةٌ لا رأي**: **هذه الكلمةَ وضعها طرفٌ
// ثالث** — إدارةٌ أو مندوبٌ أو إقلاعُ أوّلِ مالك. **فثمّةَ من يعرفها
// غيرُ صاحب الحساب.**
//
// **وبيانٌ يعرفه ثالثٌ لا يُعطي وصولاً كاملاً حتّى يُبدَّل.**
//
// # وما قِيس قبل الإصلاح (٢٠٢٦-٠٩-١٣)
//
// **العلَمُ كان إشارةَ واجهةٍ لا قيداً**: **`applyForcePolicy` تُقنّعه
// إن كان `security.force_password_change` مُطفأً** — **وهو مُطفأٌ
// افتراضاً ولا صفَّ له في الإنتاج.** **فبوّابةُ الويب لا تراه، ولا
// موضعَ في المحرّك يقف عليه.**
//
// **فحسابُ الرصد في الإنتاج — كلمتُه مؤقّتةٌ وحالُه فعّال — كان يفتح
// كلَّ ما يملكه ببيانٍ يعرفه غيرُه.**
//
// # وحدُّ الإصلاح
//
// **القيدُ مركزيٌّ في `RequireAuth`** — **لا في كلّ معالِج.** **وأربعةُ
// أبوابٍ تبقى مفتوحةً وإلّا صار القيدُ حبساً**: قراءةُ نفسِه · تبديلُ
// الكلمة · الخروجُ · التجديد.
//
// **ولا يُبدَّل عقدُ التوثيق**: **الرمزُ صالحٌ والجلسةُ قائمة** —
// **والمنعُ تخويلٌ لا توثيق**، فيُردّ بـ`403` برمزٍ يقول الخطوةَ.

// tmpUser حسابٌ بجلسةٍ قائمةٍ ثمّ تُوضَع له كلمةٌ من ثالث.
//
// **والترتيبُ كما يقع في المنتَج**: **الإدارةُ تُعيد كلمةَ من له جلسةٌ
// أصلاً** — **فالعلَمُ يظهر على حسابٍ له عائلةٌ حيّة.**
//
// **ولا يُستعمل رمزُ المصنع**: **يُصدَر بلا معرّفِ جلسة** — **وصنفُ
// التوكنات بلا جلسةٍ يبقى على ادّعاءاته بعقد `R16`**، **ولا جلسةَ
// تُسأل عنها فتُقرأ واقعتُه.** (**ورمزُ المنتَج يحمل جلسةً دائماً** —
// يحرسه `TestR16_IssuedTokensAlwaysCarrySession`.)
func tmpUser(t *testing.T, h *Harness, role string) (id, token string) {
	t.Helper()
	u := h.NewUser(role)
	if _, err := h.Pool.Exec(ctxBG(),
		`UPDATE users SET must_change_password = true WHERE id = $1::uuid`,
		u.ID); err != nil {
		t.Fatalf("علَمُ الكلمة المؤقّتة: %v", err)
	}
	return u.ID, u.Token
}

// ══════════════════════════════════════════════════════════════════════
// **TMP1 · ولا تفتح أبوابَ التطبيق**
// ══════════════════════════════════════════════════════════════════════
func TestTMP1_TemporaryPasswordCannotUseTheApp(t *testing.T) {
	h := New(t)
	_, tok := tmpUser(t, h, "customer")

	for _, p := range []string{
		"/api/v1/my/orders",
		"/api/v1/me/summary",
		"/api/v1/my/addresses",
	} {
		got := h.GET(p, tok)
		t.Logf("TMP1 %s ⇒ %d", p, got.Code)
		if got.Code == http.StatusOK {
			t.Errorf("TMP1 **%s مفتوحٌ بكلمةٍ يعرفها ثالث**", p)
		}
		if got.Code == http.StatusForbidden && got.Err() != "password_change_required" {
			t.Errorf("TMP1 **الرمزُ لا يقول الخطوةَ**: %s", got)
		}
	}
}

// ══════════════════════════════════════════════════════════════════════
// **TMP2 · والأبوابُ الأربعةُ تبقى — وإلّا صار القيدُ حبساً**
// ══════════════════════════════════════════════════════════════════════
//
// **ومن قيّد بابَ تبديل الكلمة أقفل الحسابَ على صاحبه** — **ولا مخرجَ
// من القيد إلّا به.**
func TestTMP2_TheWayOutStaysOpen(t *testing.T) {
	h := New(t)
	_, tok := tmpUser(t, h, "customer")

	if got := h.GET("/api/v1/auth/me", tok); got.Code != http.StatusOK {
		t.Errorf("TMP2 **قراءةُ نفسِه مقيَّدة**: %s — **فلا تعرف الشاشةُ لماذا مُنع**", got)
	}
	if got := h.POST("/api/v1/auth/password", tok,
		map[string]any{"password": "Qa!Tmp2-2026"}); got.Code >= 400 {
		t.Fatalf("TMP2 **بابُ التبديل مقيَّد** — **والحسابُ صار محبوساً**: %s", got)
	}
	// **وبعد التبديل يُفتَح كلُّ شيء** — **والقيدُ زال بزوال سببه.**
	if got := h.GET("/api/v1/my/orders", tok); got.Code != http.StatusOK {
		t.Errorf("TMP2 **القيدُ باقٍ بعد التبديل**: %s", got)
	}
}

// ══════════════════════════════════════════════════════════════════════
// **TMP3 · والقيدُ لا يتعلّق بإعدادِ واجهة**
// ══════════════════════════════════════════════════════════════════════
//
// **و`security.force_password_change` إعدادُ إلحاحٍ في الواجهة** (قرارُ
// المالك ٢٠٢٦-٠٨-٠٩: «الحالةُ الافتراضيّةُ غيرُ مفعّل»). **وهو لا يحكم
// الأمنَ**: **ومن أطفأه لا يفتح حساباً ببيانٍ يعرفه ثالث.**
//
// **وقِيس أنّ الإنتاجَ بلا صفٍّ لهذا الإعداد** — **فلو كان القيدُ معلَّقاً
// به لكان مُطفأً هناك.**
func TestTMP3_RestrictionIsNotTiedToTheUIToggle(t *testing.T) {
	h := New(t)
	h.Setting("security.force_password_change", "0")
	_, tok := tmpUser(t, h, "driver")

	got := h.GET("/api/v1/my/orders", tok)
	t.Logf("TMP3 والإعدادُ مُطفأٌ ⇒ %d", got.Code)
	if got.Code == http.StatusOK {
		t.Error("TMP3 **إطفاءُ إعدادِ الواجهة فتح الحسابَ** — " +
			"**والقيدُ أمنٌ لا إلحاح.**")
	}
}

// ══════════════════════════════════════════════════════════════════════
// **TMP4 · وحسابٌ عاديٌّ لا يُمَسّ**
// ══════════════════════════════════════════════════════════════════════
//
// **وقيدٌ يُصيب الأصحّاءَ عطبٌ** — **فيُقاس أنّ من بدّل كلمتَه أو سجّل
// بنفسه يمرّ كما كان.**
func TestTMP4_NormalAccountUnaffected(t *testing.T) {
	h := New(t)
	u := h.NewUser("customer")
	if got := h.GET("/api/v1/my/orders", u.Token); got.Code != http.StatusOK {
		t.Errorf("TMP4 **حسابٌ سليمٌ مُنع**: %s", got)
	}
}
