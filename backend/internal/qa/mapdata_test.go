package qa

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
	"time"
)

// ══════════════════════════════════════════════════════════════════════
// **بياناتُ الخريطة تشيخ ولا يصرخ شيء**
// ══════════════════════════════════════════════════════════════════════
//
// (قرارُ المالك 2026-09-04: «برأيي كل ثلاثة أشهر أفضل **مشان ما
//  ننساها**».)
//
// # وما كان يقع
//
// **بياناتُنا من OpenStreetMap تُجلب لحظةَ البناء** — `AREA=syria` في
// `maps/config/build.env`. **ولا شيءَ يجدّدها بعدها.**
//
// **فبعد سنةٍ تكون الخريطةُ قديمةً ولا يعلم أحد**: شارعٌ جديدٌ في الرقّة
// لا يظهر، **وسائقٌ يُرسَل في طريقٍ لم يعد موجوداً.**
//
// # ولماذا فحصٌ لا ملاحظةٌ في مستند
//
// **وملاحظةٌ في مستندٍ تُقرأ مرّةً وتُنسى** — وقد قال المالكُ سببَه
// نصّاً: «مشان ما ننساها». **وفحصٌ يسقط لا يُنسى.**
//
// # ولماذا ملفٌّ لا ترويسةُ الأرشيف
//
// **والأرشيفُ ثلاثُ مئةِ ميغابايتٍ لا تدخل المستودع** — فيُكتب تاريخُ
// بياناته في ملفٍّ صغيرٍ يُلتزَم معه. **ومن جدّد ولم يكتب التاريخَ
// أسقط الفحصَ على نفسه**، وذاك أهونُ من صمتٍ يدوم سنة.
//
// # ولا يُحدَّث الملفُّ إلّا بعد نشرٍ فعليّ
//
// **وكتابةُ تاريخٍ بلا بناءٍ كذبٌ في ملفّ** — يُسكت الفحصَ ولا يجدّد
// شيئاً. **فمن أراد التأجيل يؤجّله بعينه، لا بيدٍ تكتب رقماً.**

// mapDataMaxAge **ثلاثةُ أشهرٍ بقرار المالك** — 2026-09-04.
const mapDataMaxAge = 90 * 24 * time.Hour

// mapDataFile **تاريخُ بيانات آخر بناءٍ منشور.**
const mapDataFile = "../../../maps/config/data-date.txt"

func TestMapDataIsFresh(t *testing.T) {
	raw, err := os.ReadFile(filepath.Clean(mapDataFile))
	if err != nil {
		t.Fatalf("**تعذّر قراءةُ تاريخ بيانات الخريطة**: %v", err)
	}
	at, err := time.Parse("2006-01-02", strings.TrimSpace(string(raw)))
	if err != nil {
		t.Fatalf("**تاريخٌ لا يُقرأ** في %s: %v", mapDataFile, err)
	}

	age := time.Since(at)
	if age <= mapDataMaxAge {
		return
	}
	t.Fatalf(`**بياناتُ الخريطة شاخت** — عمرُها %d يوماً والحدُّ %d.

	وشارعٌ جديدٌ في الرقّة لا يظهر، **وسائقٌ يُرسَل في طريقٍ لم يعد موجوداً.**

	الإصلاح:
	  1. sh maps/scripts/rebuild-all.sh     # يجلب OSM من جديد ويبني
	  2. انشر الأرشيفَ ثمّ الفهرس
	  3. اكتب تاريخَ اليومَ في %s

	**ولا يُكتب التاريخُ قبل النشر** — يُسكت الفحصَ ولا يجدّد شيئاً.`,
		int(age.Hours()/24), int(mapDataMaxAge.Hours()/24), mapDataFile)
}
