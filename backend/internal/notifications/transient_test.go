//
// **وهذا حارسُ القرار لا حارسُ الشيفرة**: من أضاف حالاً عابراً إلى
// الصندوق — أو رفع منه انقطاعاً يُحتجّ به — **يسقط هنا.**
//
// **والقاعدةُ التي تفصل**: أيرجع إليه بعد يومين؟ **«طلبك في الطريق» لا**
// — والبطاقةُ تقول حالَ الطلب أصدقَ من خبرٍ قديم. **و«تعذّر تسليم طلبك»
// نعم** — يُسأل عنه بعد أيّام، وفيه مال.
