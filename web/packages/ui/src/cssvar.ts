"use client";

/**
 * **قراءةُ توكنٍ من الثيم** — لمن يحتاج اللونَ قيمةً لا صنفاً.
 *
 * # المسألة
 *
 * أكثرُ الواجهة تلوّن بأصناف Tailwind (`bg-primary`)، **وبعضُها لا يستطيع**:
 * الخريطةُ ترسم خطوطَها ودوائرَها بجافاسكربت، **وLeaflet يريد `"#6fd8f5"` لا
 * `"bg-primary"`.**
 *
 * # وماذا كان يقع
 *
 * كانت هناك لوحةُ ألوانٍ ثانيةٌ في `tokens.ts` تُقرأ منها القيم — **وقد شاخت**:
 * `primary` فيها `#14708F` (أزرقُ داكن) والثيمُ صار `#6fd8f5` (سماويٌّ فاتح)،
 * و`surface` فيها أبيضُ والثيمُ أزرق.
 *
 * **فكانت الخريطةُ ترسم بألوان منصّةٍ أخرى** — خطُّ المسار بأزرقَ لا يوجد في
 * الشاشة، **ولا يظهر خطأً ولا يشتكي أحد**: تُقرأ «الخريطةُ شكلُها غريب» ولا
 * يُعرف السبب.
 *
 * **ومصدرٌ واحدٌ يُقرأ منه الجميع** يقطع هذا من أصله: يُبدَّل اللونُ في
 * `theme.css` **فتتبعه الخريطةُ في التحديث نفسِه.**
 *
 * # والاحتياطيُّ ليس زينة
 *
 * `getComputedStyle` لا وجودَ له في الخادم — **وصفحةٌ تُرسم هناك أوّلاً**.
 * فيُعاد الاحتياطيُّ حتّى يصل المتصفّح، **ولونٌ فارغٌ يجعل Leaflet يرسم
 * أسودَ** فيبدو المسارُ خطّاً من فحم.
 */

/** cssVar قيمةُ توكنٍ من جذر الوثيقة — **أو احتياطيُّه قبل أن يصل المتصفّح.** */
export function cssVar(name: string, fallback: string): string {
  if (typeof window === "undefined" || typeof document === "undefined") return fallback;
  const v = getComputedStyle(document.documentElement).getPropertyValue(name).trim();
  return v || fallback;
}

/**
 * **آخرُ ملاذٍ لا لوحةٌ احتياطية.**
 *
 * أوّلُ صياغةٍ مرّرت لكلّ نداءٍ احتياطيَّه بالحرف (`themeColor("primary",
 * "#6fd8f5")`) — **وتلك لوحةٌ ثانيةٌ تُولد من جديد**، وهي عينُ ما حُذف من
 * `tokens.ts` قبل قليل: تُبدَّل الألوانُ في الثيم **ويبقى ما في الأقواس.**
 *
 * **ولا احتياجَ له أصلاً**: الخريطةُ وحدَها من يقرأ القيمَ، وهي تُحمَّل
 * `ssr: false` في كلّ مواضعها — **فالمتصفّحُ موجودٌ دائماً حين تُنادى.**
 *
 * **فبقي رمادٌ واحدٌ لِما لا يقع**: لو غاب التوكنُ لَظهر رماديٌّ يُرى ويُسأل
 * عنه، **بدل أسودَ يبدو خطّاً من فحمٍ فيُظنّ تصميماً.**
 */
const LAST_RESORT = "#808080";

/**
 * themeColor لونُ توكنٍ باسمه المختصر — `themeColor("primary")`.
 *
 * **والاسمُ اسمُ التوكن نفسِه** لا اسمٌ ثانٍ يُترجَم: `primary-dark` هنا هي
 * `--color-primary-dark` هناك، **فمن قرأ أحدَهما عرف الآخر.**
 */
export function themeColor(token: string): string {
  return cssVar(`--color-${token}`, LAST_RESORT);
}
