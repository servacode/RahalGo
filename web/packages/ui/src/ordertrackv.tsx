"use client";

/**
 * ══════════════════════════════════════════════════════════════════════
 * **مسارُ الطلب عاموديّاً — عمودٌ في طرف البطاقة**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (قرارُ المالك ٢٠٢٦-٠٨-١٢: «الرحلة نسوّيها بشكلٍ طوليّ — ناخذ جزءاً من
 *  الكرت من الطرف اليسار، وبدل ما يكون شريط الرحلة أفقيّاً يصير
 *  عاموديّاً… البطاقة تُقسم إلى قسمين، والقسمُ الأوّل لا علاقة له
 *  بالقسم الثاني».)
 *
 * # لماذا عاموديٌّ هنا وأفقيٌّ عند الزبون
 *
 * **بطاقةُ الزبون واحدة، وبطاقةُ المكتب في شبكةٍ من أربع.** والأفقيُّ
 * يأكل سطراً بعرض البطاقة كلِّها — **وهو عرضٌ نادرٌ في شبكة.** والطولُ
 * فائضٌ: فاتورةٌ من ستّة أصناف تُطيل البطاقة، **والطولُ يذهب هدراً.**
 *
 * **ومراحلُ المكتب سبعٌ لا ستّ** — يفرّق بين «في المطبخ» و«بانتظار
 * سائق»، وهما تحت اسمٍ واحدٍ عند الزبون. **وسبعةُ أسماءٍ في سطرٍ أفقيّ
 * تُقصّ أو تُصغَّر حتّى لا تُقرأ.** وعاموديّاً لكلِّ اسمٍ سطرُه.
 *
 * # والخطُّ هو الفاصل
 *
 * **لا حدَّ بين القسمين** — خطُّ المراحل نفسُه يفصلهما. **وحدٌّ إلى جانب
 * خطٍّ** يُقرأ خطّين لا واحداً.
 *
 * # وما انتهى قبل أن يصل يبقى رماديّاً
 *
 * (قرارُ المالك: «نخلّيه رماديّاً مشان ما يخرّب شكل الكرت».)
 *
 * **والملغى لا موضعَ له على المسار** — المحرّكُ يعطيه `-1`، **فلا يُعرف
 * أين توقّف.** فيبقى العمودُ رماديّاً كلُّه: **شكلُ البطاقة لا يتغيّر،
 * وسببُ الانتهاء مكتوبٌ في ترويستها.**
 */

export interface RailStage {
  id: string;
  label: string;
}

export function OrderTrackV({
  stages,
  /** رقمُ المرحلة الحالية — و`-1` لما انتهى قبل أن يصل. */
  current,
  className = "",
}: {
  stages: RailStage[];
  current: number;
  className?: string;
}) {
  // **والمنتهي رماديٌّ كلُّه** — لا نقطةَ مضيئةٌ في مسارٍ لم يكتمل.
  const ended = current < 0;
  const last = stages.length - 1;

  return (
    /* **والعمودُ يملأ طولَ ما بجانبه** — `h-full` مع `justify-between`
       يوزّع المراحلَ على الطول كلِّه، **فتطول البطاقةُ فيتباعد ما فيه
       ولا يتكدّس في أعلاه.** */
    <ul
      className={`flex h-full flex-col justify-between text-2xs leading-tight ${className}`}
    >
      {stages.map((s, i) => {
        const done = !ended && i < current;
        const now = !ended && i === current;
        return (
          <li
            key={s.id}
            /* **وكلُّ مرحلةٍ تنمو بالتساوي إلّا الأخيرة** — فتقف نقطتُها
               عند القاع بالضبط، **ولو نمت لَبقي تحتها فراغٌ بقدر سطر.** */
            className={`relative flex items-start gap-1.5 ${i < last ? "flex-1" : ""}`}
          >
            {/* ══════════════════════════════════════════════════════
                **والواصلُ يُرسم تحت النقطة لا خلف العمود**
                ══════════════════════════════════════════════════════

                **خطٌّ واحدٌ بطول العمود** يحتاج أن يعرف أين أوّلُ نقطةٍ
                وأين آخرُها — **وهو ما لا يُعرف قبل الرسم.**

                **فكلُّ مرحلةٍ تحمل واصلَها**: من تحت نقطتها إلى قاع
                صفِّها — **وقاعُ صفِّها هو نقطةُ التي تليها.** */}
            {i < last && (
              <span
                aria-hidden
                className={`absolute bottom-0 top-3 w-px ${done ? "bg-accent" : "bg-line"}`}
                /* **موضعُه مركزُ النقطة** — والنقطةُ عشرةُ بكسلاتٍ، فمركزُها
                   خمسةٌ من طرف العمود. **والطرفُ يمينٌ في واجهةٍ عربيّة.** */
                style={{ insetInlineStart: "4.5px" }}
              />
            )}
            <span
              aria-hidden
              className={`mt-1 h-2.5 w-2.5 shrink-0 rounded-full border-2 transition-colors ${
                done
                  ? "border-accent bg-accent"
                  : now
                    ? "border-accent bg-surface ring-2 ring-accent-fill"
                    : "border-line bg-surface"
              }`}
            />
            <span
              className={
                now
                  ? "font-bold text-accent-text"
                  : done
                    ? "text-ink-muted"
                    : "text-ink-muted opacity-50"
              }
            >
              {s.label}
            </span>
          </li>
        );
      })}
    </ul>
  );
}
