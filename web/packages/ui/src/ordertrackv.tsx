"use client";

import type { ReactNode } from "react";
import { IconCheck, IconClose } from "./icons";

/**
 * ══════════════════════════════════════════════════════════════════════
 * **مسارُ الطلب عاموديّاً — عمودٌ في طرف البطاقة**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (قرارُ المالك ٢٠٢٦-٠٨-١٢: «الرحلة نسوّيها بشكلٍ طوليّ — ناخذ جزءاً من
 *  الكرت من الطرف اليسار، وبدل ما يكون شريط الرحلة أفقيّاً يصير
 *  عاموديّاً… البطاقة تُقسم إلى قسمين، والقسمُ الأوّل لا علاقة له
 *  بالقسم الثاني».)
 *
 * # لماذا عاموديٌّ هنا وأفقيٌّ عند الزبون
 *
 * **بطاقةُ الزبون واحدة، وبطاقةُ المكتب في شبكةٍ من أربع.** والأفقيُّ
 * يأكل سطراً بعرض البطاقة كلِّها — **وهو عرضٌ نادرٌ في شبكة.** والطولُ
 * فائضٌ: فاتورةٌ من ستّة أصناف تُطيل البطاقة، **والطولُ يذهب هدراً.**
 *
 * **ومراحلُ المكتب سبعٌ لا ستّ** — يفرّق بين «في المطبخ» و«بانتظار
 * سائق»، وهما تحت اسمٍ واحدٍ عند الزبون. **وسبعةُ أسماءٍ في سطرٍ أفقيّ
 * تُقصّ أو تُصغَّر حتّى لا تُقرأ.** وعاموديّاً لكلِّ اسمٍ سطرُه.
 *
 * # والخطُّ هو الفاصل
 *
 * **لا حدَّ بين القسمين** — خطُّ المراحل نفسُه يفصلهما. **وحدٌّ إلى جانب
 * خطٍّ** يُقرأ خطّين لا واحداً.
 *
 * # والمدّةُ على الخطّ لا الساعةُ على النقطة
 *
 * (قرارُ المالك ٢٠٢٦-٠٨-١٢: «نكتب الوقت المستهلك وإشارة صحّ أنّ الزمن
 *  طبيعيّ، وإذا كان هناك تأخير نضع علامة إكس حمراء لنعرف أين حصل
 *  التأخير… وخصوصاً إذا أتت شكوى، نظرةٌ واحدة على السجلّ تحلّ كلّ
 *  الخلاف».)
 *
 * **النقطةُ حالٌ والخطُّ انتقال** — فما يُكتب عليه هو ما استُهلك في
 * عبوره. **والساعةُ لا تجيب السؤال**: «١:٠٥ ثمّ ١:٤٩» تحتاج طرحاً في
 * الرأس، **و«٤٤ د» تقول نفسَها.**
 *
 * **والساعةُ الدقيقةُ تبقى في `title`** — تُقرأ عند الحاجة، **ولا
 * تزدحم بها تسعون بكسلاً.**
 *
 * # والعلامةُ تدلّ ولا تحكم
 *
 * **«✗» تعني «تجاوز المهلة» لا «مُذنِب».** والمهلةُ رقمٌ يضبطه إنسان،
 * **ومن خصم من متجرٍ لأنّ مهلتَه كانت ضيّقةً خصم من بريء.**
 *
 * **والرقمُ تحتها هو الحجّة** — العلامةُ تدلّ العينَ على موضع الوقت
 * الضائع في لحظة، **ثمّ يقرّر من يقرأ.**
 *
 * **وخطٌّ بلا مهلةٍ يبقى بلا علامة** — لا «✓» ولا «✗». **وصحٌّ يُكتب بلا
 * معيار** يقول «كلُّ شيءٍ سليم» وهو لا يعرف، **وهو أسوأُ من صمت.**
 *
 * # ولا مدّةَ على خطٍّ لم يُعبَر
 *
 * **الطلبُ يُردّ إلى الطابور** فيحمل وقتَ إسنادٍ سابقٍ وهو واقفٌ اليوم
 * بلا سائق. **وساعةٌ تحت نقطةٍ رماديّة** تقول شيئاً وشكلُها يقول
 * نقيضَه — **فلا تُكتب إلّا إن بلغ الطلبُ ما تحتها.**
 *
 * # وما انتهى قبل أن يصل يبقى رماديّاً
 *
 * (قرارُ المالك: «نخلّيه رماديّاً مشان ما يخرّب شكل الكرت».)
 *
 * **والملغى لا موضعَ له على المسار** — المحرّكُ يعطيه `-1`، **فلا يُعرف
 * أين توقّف.** فيبقى العمودُ رماديّاً كلُّه: **شكلُ البطاقة لا يتغيّر،
 * وسببُ الانتهاء مكتوبٌ في ترويستها.**
 */

export interface RailStage {
  id: string;
  label: string;
  /**
   * **متى وقع الانتقالُ إلى هذه المرحلة** — نصّاً كما يُقرأ.
   *
   * **ولا يُعرض في العمود** بل في `title` الخطّ فوقها: **الساعةُ حجّةٌ
   * تُطلب في شكوى، والمدّةُ خبرٌ يُمسح بالعين.**
   */
  at?: string | null;
  /** **ما استُهلك في عبور الخطّ فوقها** — نصّاً منسّقاً («٤٤ د»). */
  span?: string | null;
  /**
   * **أتجاوز الخطُّ فوقها مهلتَه** — و`null` «لا حكم».
   *
   * **وهو غيرُ `false`**: تلك تقول «قُيس فكان سليما»، **وهذا يقول «لا
   * مهلةَ لهذا الخطّ فلا أحكم».**
   */
  late?: boolean | null;
  /**
   * **كلمةٌ تُقال مع الوقت على الخطّ فوقها.**
   *
   * (قرارُ المالك ٢٠٢٦-٠٨-١٢: «تحت بانتظار سائق نضع اسم السائق الذي أخذ
   *  الطلب».) **وذاك الخطُّ بعينه هو لحظةُ الإسناد**، فالاسمُ عليه يجيب
   * «من أنهى الانتظار».
   */
  note?: string | null;
}

export function OrderTrackV({
  stages,
  /** رقمُ المرحلة الحالية — و`-1` لما انتهى قبل أن يصل. */
  current,
  /**
   * **ما يُقال بجانب المرحلة الحاليّة** — شارةُ السائق في لوحة المكتب
   * (قرارُ المالك ٢٠٢٦-١٠-٠٣): اسمُه واتّصالٌ وآخرُ ظهور. **ولا شيءَ
   * لمسارٍ انتهى** — لا مرحلةَ حاليّةً فيه.
   */
  currentAside,
  className = "",
}: {
  stages: RailStage[];
  current: number;
  currentAside?: ReactNode;
  className?: string;
}) {
  // **والمنتهي رماديٌّ كلُّه** — لا نقطةَ مضيئةٌ في مسارٍ لم يكتمل.
  const ended = current < 0;
  const last = stages.length - 1;

  return (
    /* **والخطُّ في وسط العمود والمرحلةُ سطرٌ واحدٌ عليه** (المالك ٢٠٢٦-١٠-٢٢: «نخلي الخط
       بوسط الكتابة فيصير واضح انه حاليا نحن وين والكتابة تصير بسطر واحد») — كلُّ مرحلةٍ
       شارةٌ على الخطّ، **والحاليّةُ مملوءةٌ بلونها**، وما مضى بإطارٍ ملوّن، وما بقي باهت.
       **و`flex-1` على كلّ مرحلةٍ إلا الأخيرة** يوزّعها على طول البطاقة. */
    <ul className={`flex h-full flex-col items-center text-2xs leading-tight ${className}`}>
      {stages.map((s, i) => {
        const done = !ended && i < current;
        const now = !ended && i === current;
        const next = stages[i + 1];
        const crossed = !ended && i + 1 <= current;
        return (
          <li key={s.id} className={`flex w-full flex-col items-center ${i < last ? "flex-1" : ""}`}>
            <span
              className={`relative z-10 whitespace-nowrap rounded-control border px-1.5 py-0.5 transition-colors ${
                now
                  ? "border-accent bg-accent font-bold text-on-bright"
                  : done
                    ? "border-accent-edge bg-surface text-ink-muted"
                    : "border-line-soft bg-surface text-ink-muted opacity-60"
              }`}
            >
              {s.label}
            </span>
            {now && currentAside && <div className="mt-1 text-center">{currentAside}</div>}

            {/* **وبين مرحلتين خطٌّ في الوسط** يمتدّ بطول ما بينهما، **والمدّةُ شارةٌ عليه** —
                والساعةُ الدقيقةُ في التلميح، حجّةٌ تُطلب في شكوى. */}
            {i < last && (
              <div className="relative flex w-full flex-1 items-center justify-center">
                <span
                  aria-hidden
                  className={`absolute bottom-0 top-0 w-0.5 -translate-x-1/2 ${done ? "bg-accent" : "bg-line"}`}
                  style={{ left: "50%" }}
                />
                {crossed && (next?.span || next?.note) && (
                  <span
                    className="relative z-10 rounded-badge bg-surface px-1 text-center text-ink-dim"
                    title={next.at ?? undefined}
                  >
                    {next.span && (
                      <span className="inline-flex items-center gap-0.5">
                        <span className="tabular-nums">{next.span}</span>
                        {next.late === true && <IconClose size={11} className="text-danger" />}
                        {next.late === false && <IconCheck size={11} className="text-success" />}
                      </span>
                    )}
                    {next.note && <span className="block">{next.note}</span>}
                  </span>
                )}
              </div>
            )}
          </li>
        );
      })}
    </ul>
  );
}
