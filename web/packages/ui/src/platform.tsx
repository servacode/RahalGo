/** **والاسمُ الافتراضيُّ في المعجم** — يُقرأ حين لا تُضبط الإعدادات. */
const m = getMessages(defaultLocale);

export interface Platform {
  /** اسمُ المنصة من الإعدادات — **وفارغٌ يعني «لم يُضبط بعد»، لا اسماً بديلاً.** */
  name: string;
  /** رابطُ الشعار الجاهز — **وفارغٌ يُبقي الحرف.** */
  logo: string | null;
  /**
   * **هل بابُ رمز التحقّق مفتوح؟** (`auth.otp_login` في الإعدادات.)
   *
   * (قرارُ المالك ٢٠٢٦-٠٨-٠٦: «جهّز بالإعدادات بلوحة الادمن خيار لإطفاء أو
   *  تشغيل تسجيل الدخول برمز التحقّق».)
   *
   * **ومكانُه هنا لا في نداءٍ ثانٍ**: شاشةُ الدخول تحتاجه قبل أن يكون هناك
   * حساب، **وهي تنادي الهويّةَ أصلاً** — ونداءان لسطرين رحلةٌ زائدةٌ في أوّل
   * ما يُفتح.
   *
   * **والافتراضُ `true`** — فلو تأخّر الردُّ أو سقط **يُعرض البابان ثمّ يُخفى
   * ما يجب**، ولا يُحرَم أحدٌ باباً بسبب شبكةٍ بطيئة.
   */
  otpLogin: boolean;
  /**
   * **أقلُّ طولٍ مقبولٍ لكلمة المرور** (`security.password_min_length`).
   *
   * (قرارُ المالك ٢٠٢٦-٠٨-٠٩: «طولُ كلمة المرور يجب أن تكون موحّدةً بكلّ
   *  البرنامج» — وكان مكتوباً ستَّ مرّاتٍ في الويب ومرّتين في المحرّك.)
   *
   * **ولا شرطَ تعقيدٍ معه**: لا حرفاً ولا رقماً يُلزَم بهما أحد (قرارُ
   * المالك: «هو حرٌّ في الاختيار») — **والطولُ وحدَه شرط.**
   *
   * **والافتراضُ ثمانية** — فلو تأخّر الردُّ لا تُقبل كلمةٌ يردّها المحرّك.
   */
  passwordMinLength: number;
  /**
   * **رابطُ تطبيق أندرويد** (`platform.app_url` في الإعدادات).
   *
   * (طلبُ المالك ٢٠٢٦-٠٨-٠٧: «زرُّ تحميل التطبيق بجانب تسجيل الدخول،
   *  وحقلُ الرابط بلوحة التحكّم».)
   *
   * **وفارغٌ يُخفي الزرَّ كلَّه** — زرُّ تحميلٍ لا ينزّل شيئاً يُقرأ عطباً
   * في المنصة لا ميزةً ناقصة.
   */
  appUrl: string;
  /**
   * **خلفيّةُ شاشات الدخول** (`auth.background` في الإعدادات) — **وفارغٌ
   * يُبقي اللونَ وحدَه.**
   *
   * (قرارُ المالك ٢٠٢٦-٠٨-٠٦.)
   */
  authBg: string | null;
  /** **نسختُها الطوليّة للجوّال** — وفارغُها يسقط إلى العريضة. */
  authBgMobile: string | null;
  /**
   * **شفافيّةُ الطبقة فوق الخلفيّة** (٠..١٠٠) — **وصفرٌ يعني بلا طبقة.**
   *
   * (قرارُ المالك ٢٠٢٦-٠٨-٠٦: «ضع خياراً للتحكّم بها… شريط من ٠ إلى ١٠٠».)
   */
  authBgDim: number;
  /**
   * **خلفيّةُ الموقع كلِّه** (`platform.background`) — **وفارغةٌ تُبقي التدرّجَ
   * المرسوم.** (قرارُ المالك ٢٠٢٦-٠٨-٠٦.)
   */
  siteBg: string | null;
  /** **نسختُها الطوليّة للجوّال.** */
  siteBgMobile: string | null;
  /** حجابُها (٠..١٠٠) — **وصورةٌ فوتوغرافيّةٌ تحتاج غالباً ٥٠–٧٠.** */
  siteBgDim: number;
  /**
   * **لمحةُ الخلفيّة** — (طلبُ المالك ٢٠٢٦-٠٨-١٧).
   *
   * **تُرسم في أوّل رسمةٍ تحت الصورة** فلا يُرى تدرّجٌ عارٍ ثمّ تقفز
   * الصورةُ فوقه. **وفارغٌ يعني صورةً رُفعت قبل أن تُولَّد اللمحات.**
   */
  siteBgBlur: string;
  /**
   * **رقمُ الدعم** (`platform.support_phone`) — **وفارغٌ يُخفي السطر.**
   *
   * (قرارُ المالك ٢٠٢٦-٠٨-٠٩: «بالفاتورة لازم نضيف رقم هاتف الدعم للشكاوى».)
   *
   * **الورقةُ تُقرأ بعيداً عن التطبيق** — تُطبع وتُسلَّم، ومن وجد فيها خطأً
   * لا يجد أين يشتكي. **ورقمٌ على الورق هو البابُ الوحيد حينَها.**
   */
  supportPhone: string;
  /**
   * **حساباتُ التواصل** — روابطُ من الإعدادات، **وفارغُها لا يُعرض.**
   *
   * (طلبُ المالك ٢٠٢٦-٠٨-٠٩: «تواصل معنا وحسابات السوشيال ميديا».)
   *
   * **وأيقونةٌ تقود إلى لا شيءٍ أسوأُ من غيابها** — فمنصّةٌ لا تلغرامَ لها
   * لا تُظهر أيقونتَه.
   */
  social: { facebook: string; instagram: string; telegram: string; whatsapp: string };
  /**
   * **هل يُعرض زرُّ الدخول في شريط الموقع؟** (`site.show_login`.)
   *
   * (طلبُ المالك ٢٠٢٦-٠٨-١٧: «مفتاحٌ لإخفاء زرّ تسجيل الدخول — بحيث
   *  أستطيع الدخول عن طريق الرابط المباشر».)
   *
   * **والمسارُ يبقى عاملاً**: `‎/login` يُفتح لمن كتبه، **والزرُّ وحدَه
   * يغيب** — فمن أراد إغلاق الباب يُطفئ التسجيل لا يُخفي زرَّه.
   *
   * **والافتراضُ `true`** — فلو تأخّر الردُّ أو سقط **لا يُحرَم زائرٌ من
   * بابه**: زرٌّ ظهر بلا داعٍ أهونُ من بابٍ اختفى بلا سبب.
   */
  showLogin: boolean;
  /**
   * **هل تُعرض أبوابُ التسوّق؟** (`site.show_shop`.)
   *
   * **وثلاثةٌ لا واحد**: زرُّ الشريط، وأيقونةُ الشريط السفليّ على
   * الجوّال، ودعوةُ الرئيسيّة. **ومن أخفى واحداً وترك اثنين لم يُخفِ
   * شيئاً.**
   */
  showShop: boolean;
  /**
   * **هل بابُ الانضمام مفتوح؟** (`site.join_open`.)
   *
   * (قرارُ المالك ٢٠٢٦-٠٨-١٧: «الانضمامُ كمتجرٍ وسائقٍ ومندوبٍ المفروض
   *  ما يفتح أيَّ فورم تسجيل، والزبون لازم نحط قريباً».)
   *
   * **والافتراضُ مغلقٌ بخلاف أخوَيه** — **بابٌ يُفتح قبل أوانه يستقبل
   * طلباتٍ لا أحدَ يراجعها**، وصاحبُها ينتظر جواباً لا يأتي. **فإن سقط
   * النداءُ بقي مغلقاً**، وهو الأسلم.
   */
  joinOpen: boolean;
  /** **عنوانُ المكتب** (`platform.address`) — وفارغٌ لا يُعرض. */
  address: string;
  /** **موقعُه على الخريطة** `"lat,lng"` — وفارغٌ يعني «لا خريطة». */
  location: string;
}

const EMPTY: Platform = { name: "", logo: null, otpLogin: true, passwordMinLength: 8, appUrl: "", authBg: null, authBgMobile: null, authBgDim: 70, siteBg: null, siteBgMobile: null, siteBgDim: 55, siteBgBlur: "", showLogin: true, showShop: true, joinOpen: false, supportPhone: "", social: { facebook: "", instagram: "", telegram: "", whatsapp: "" }, address: "", location: "" };

/**
 * **مسارُ الوسيط يصير رابطاً هنا — لا في كلّ تطبيق.**
 *
 * (عطبٌ شهده المالك ٢٠٢٦-٠٨-٠٦: «لوغو المنصة مكسورٌ بالأربع شاشات لأنّه يأتي
 *  من مكانٍ غيرِ مركزيّ، لأنّه بشاشة الزبون يعمل بشكلٍ طبيعيّ» — **وتشخيصُه
 *  صحيحٌ حرفاً.**)
 *
 * **المحرّكُ يردّ `/media/…` نسبيّاً** — والوسائطُ على منفذه (٨٠٨٠) لا على
 * منفذ الواجهة. **فمن طلبها من منفذه ردّ ٤٠٤** (قِيس: ٣٠٠١ ردّ ٤٠٤ و٨٠٨٠
 * ردّ ٢٠٠).
 *
 * **وموقعُ الزبون كان يحوّلها في غلافه** (`mediaUrl`) — **فعمل عنده وحدَه**،
 * **وبقيت اللوحاتُ الأربعُ تعرض صورةً مكسورة.**
 *
 * **وهذا هو معنى «غيرِ مركزيّ» بالضبط**: قاعدةٌ صحيحةٌ مكتوبةٌ في تطبيقٍ
 * واحدٍ من خمسة.
 *
 * **وهي عديمةُ الأثر على الرابط الكامل** — فمن مرّر مطلقاً بقي كما هو.
 */
const absolute = (path: string | null | undefined, base: string): string | null => {
  if (!path) return null;
  if (/^(https?:)?\/\//.test(path) || path.startsWith("data:")) return path;
  return base.replace(/\/$/, "") + (path.startsWith("/") ? path : "/" + path);
};
const PlatformContext = createContext<Platform>(EMPTY);

export function PlatformProvider({
  children,
  /**
   * **قيمةٌ مبدئيّةٌ من الخادم** — للتطبيقات التي تقرأ الهويّةَ في التصيير
   * الخادميّ (موقعُ الزبون). **فلا تومض العلامةُ فارغةً ثمّ تمتلئ.**
   */
  initial,
  /** أصلُ المحرّك — يختلف بين التطبيقات فيُحقن. */
  apiBase,
}: {
  children: ReactNode;
  initial?: Platform;
  apiBase: string;
}) {
  /* **والتحويلُ يُطبَّق على كلّ ما يدخل — لا على الوارد من الشبكة وحدَه.**

     **وأوّلُ إصلاحٍ كسر الطرفَ الآخر**: حُوِّل الوارد من النداء فعملت اللوحاتُ
     الأربع، **وانكسر الزبون** — لأنّه يقرأ الهويّةَ في الخادم ويمرّرها
     `initial`، **والمزوّدُ يتخطّى النداءَ حينئذٍ فلا يمرّ التحويل.**

     **ولولا أنّي قِستُ الخمسَ لا الأربعَ لَظننتُه مُصلَحاً.**

     **فالتطبيعُ عند المدخل**: من أينما جاءت القيمةُ تخرج رابطاً كاملاً. */
  const norm = useCallback(
    (pl: Platform): Platform => ({
      ...pl,
      logo: absolute(pl.logo, apiBase),
      authBg: absolute(pl.authBg, apiBase),
      authBgMobile: absolute(pl.authBgMobile, apiBase),
      siteBg: absolute(pl.siteBg, apiBase),
      siteBgMobile: absolute(pl.siteBgMobile, apiBase),
    }),
    [apiBase],
  );
  const [platform, setPlatform] = useState<Platform>(() => (initial ? norm(initial) : EMPTY));

  useEffect(() => {
    // **ومن جاءته قيمةٌ مبدئيّةٌ لا يُنادي**: الخادمُ قرأها قبله.
    if (initial?.name || initial?.logo) return;
    let alive = true;
    fetch(`${apiBase}/api/v1/public/platform`)
      .then((r) => (r.ok ? r.json() : null))
      .then((j) => {
        // **وفشلُ النداء يُبقي الفراغَ ولا يخترع اسماً** — علامةٌ ناقصةٌ
        // أهونُ من علامةٍ كاذبة.
        if (alive && j?.data)
          setPlatform(
            norm({
            name: j.data.name ?? "",
            logo: j.data.logo ?? null,
            otpLogin: j.data.otp_login !== false,
            passwordMinLength:
              typeof j.data.password_min_length === "number" && j.data.password_min_length > 0
                ? j.data.password_min_length
                : 8,
            appUrl: typeof j.data.app_url === "string" ? j.data.app_url : "",
            supportPhone: typeof j.data.support_phone === "string" ? j.data.support_phone : "",
            social: readSocial(j.data.social),
            address: typeof j.data.address === "string" ? j.data.address : "",
            location: typeof j.data.location === "string" ? j.data.location : "",
            authBg: j.data.auth_bg ?? null,
            authBgMobile: j.data.auth_bg_mobile ?? null,
            authBgDim: typeof j.data.auth_bg_dim === "number" ? j.data.auth_bg_dim : 70,
            siteBg: j.data.site_bg ?? null,
            siteBgMobile: j.data.site_bg_mobile ?? null,
            siteBgDim: typeof j.data.site_bg_dim === "number" ? j.data.site_bg_dim : 55,
            siteBgBlur: typeof j.data.site_bg_blur === "string" ? j.data.site_bg_blur : "",
            // **والافتراضُ الظهور** — انظر `showLogin`.
            showLogin: j.data.show_login !== false,
            showShop: j.data.show_shop !== false,
            joinOpen: j.data.join_open === true,
            }),
          );
      })
      .catch(() => undefined);
    return () => {
      alive = false;
    };
  }, [apiBase, initial, norm]);

  /* ══════════════════════════════════════════════════════════════════
     **خلفيّةُ الموقع تُحقَن مُتغيّراً في الجذر — لا تُرسم في مكوّن**
     ══════════════════════════════════════════════════════════════════

     (قرارُ المالك ٢٠٢٦-٠٨-٠٦.)

     **الخلفيّةُ على `body` في الثيم** — وهو يعرف الطبقاتِ الخمسَ وترتيبَها.
     **والصورةُ تأتي من الشبكة**، فلا سبيلَ إلى كتابتها في ورقةٍ ساكنة.

     **فيُحقن مُتغيّران في `<html>`** ويقرؤهما الثيم: **الطبقاتُ تبقى في
     مكانٍ واحد**، ولا يُنشأ عنصرٌ ثانٍ يغطّي الصفحة.

     **وفارغةٌ تعني `none`** — طبقةٌ لا تُرسم، فيبقى التدرّجُ وحدَه. */
  useEffect(() => {
    const root = document.documentElement;
    /* ══════════════════════════════════════════════════════════════════
       **ولا حجابَ حتّى تُحمَّل الصورةُ فعلاً**
       ══════════════════════════════════════════════════════════════════

       (خشيه المالك ٢٠٢٦-٠٨-٠٦: «ربّما يحصل عطلٌ ما فتختفي الصورةُ ويصبح
        شكلُ الموقع بشعاً جدّاً» — **وقِيس فوقع.**)

       **الأسطحُ كانت آمنةً في الحالات الثلاث** (بلا صورة · بصورةٍ تعمل ·
       بصورةٍ ساقطة): شفّافةٌ كلَّها والحبرُ عليها فوق العشرة.

       **والعطبُ كان في الحجاب**: يُرفع بمجرّد وجود الإعداد. **فملفٌّ حُذف من
       القرص وبقي معرّفُه في الإعدادات يُطفئ اللوحةَ بستّين بالمئة** —
       **ظلامٌ بلا صورةٍ تُبرّره.**

       **فيُسبَق الرسمُ بتحميلٍ صامت**: إن نجح رُفعت الصورةُ وحجابُها معاً،
       **وإن سقط بقي التدرّجُ كما هو** — لا صورةَ ولا ظلام.

       **والافتراضُ صفرٌ حتّى يثبت النجاح** — لا العكس: **الطُّرقُ تُفتح على
       السلامة لا على الأمل.**

       ══════════════════════════════════════════════════════════════════
       **ولا يُمحى ما رسمه الخادمُ ثمّ يُعاد**
       ══════════════════════════════════════════════════════════════════

       (شكوى المالك ٢٠٢٦-٠٨-١٦: «يجب أن يتمّ تحميلها بسرعة رغم ضعف
        الإنترنت».)

       **صار الغلافُ يكتب الخلفيّةَ في ورقة الصفحة نفسِها** فتبدأ مع أوّل
       بايت. **وكان هذا الأثرُ يُطفئها أوّلَ ما يعمل** ثمّ يعيدها بعد
       التحميل — **فترتدّ الشاشةُ إلى التدرّج ثمّ تعود**، وهي وميضٌ يراه
       صاحبُها عطباً.

       **فصار الإطفاءُ عند الفشل وحدَه**: `onerror` تمحو الصورةَ والحجابَ
       معاً — **وهو ما حَرَس منه أوّلاً: ظلامٌ بلا صورةٍ تُبرّره.** */
    const clear = () => {
      root.style.setProperty("--site-bg", "none");
      /* **وتُرفع لا تُصفَّر**: `none` تمنع الثيمَ من السقوط إلى العريضة —
         **فيبقى الجوّالُ بلا خلفيّةٍ وإن كانت مرفوعة.** */
      root.style.removeProperty("--site-bg-mobile");
      root.style.setProperty("--site-bg-dim", "0");
    };
    if (!platform.siteBg) {
      clear();
      return;
    }
    let alive = true;
    const img = new Image();
    img.onload = () => {
      if (!alive) return;
      root.style.setProperty("--site-bg", `url("${platform.siteBg}")`);
      if (platform.siteBgMobile) {
        root.style.setProperty("--site-bg-mobile", `url("${platform.siteBgMobile}")`);
      }
      root.style.setProperty("--site-bg-dim", String(platform.siteBgDim / 100));
    };
    img.onerror = () => {
      if (alive) clear();
    };
    img.src = platform.siteBg;
    return () => {
      alive = false;
    };
  }, [platform.siteBg, platform.siteBgMobile, platform.siteBgDim]);

  return (
    <PlatformContext.Provider value={platform}>
      {/* **طبقةُ الصورة عنصرٌ لا إعلانٌ في `body`.**

          (المرحلةُ: خلفيّةُ الموقع من الإعدادات ٢٠٢٦-٠٨-٠٦.)

          **وتُرسم دائماً ولو بلا صورة**: `--site-bg` تساوي `none` فلا يُرسم
          شيء، **وعنصرٌ ثابتٌ فارغٌ لا يكلّف** — **بينما إظهارُه وإخفاؤه
          يُعيد ترتيبَ الطبقات في كلّ تبدّل.** */}
      <div className="site-bg-image" aria-hidden />
      {children}
    </PlatformContext.Provider>
  );
}

export function usePlatform(): Platform {
  return useContext(PlatformContext);
}

/** أوّلُ حرفٍ من الاسم — **يُشتقّ ولا يُكتب في معجم.** */
export function brandLetter(name: string): string {
  return name.trim().charAt(0);
}

/**
 * **علامةُ المنصة — صورةٌ إن رُفعت، وإلّا أوّلُ حرفٍ من اسمها.**
 *
 * **ولا تُحذف حين لا شعارَ ولا اسم**: مربّعٌ فارغٌ في الشريط أسوأُ من حرف،
 * **وشريطٌ بلا علامةٍ يُقرأ صفحةً لم تُحمَّل.** فيبقى المربّعُ بلونه ويُملأ
 * حين يُضبط الاسم.
 */

export function BrandMark({
  size = 36,
  rounded = "control",
  heightClass,
  disc = false,
  className = "",
}: {
  size?: number;
  /**
   * ══════════════════════════════════════════════════════════════════
   * **قرصٌ أبيضُ خلفَ الشعار — في الموقع وحدَه**
   * ══════════════════════════════════════════════════════════════════
   *
   * (طلبُ المالك ٢٠٢٦-٠٨-١٧: «أضف لي دائرةً بيضاء حول لوغو المنصّة فقط
   *  في الموقع».)
   *
   * **وقد طلبها قبلَها وألغاها** (٢٠٢٦-٠٨-٠٩، على ثلاث خطوات) —
   * **والفرقُ أنّها كانت حينَها في كلّ مكان**: الشريطُ والسايدبارُ
   * وشاشةُ الدخول والورقةُ المطبوعة. **وقرصٌ أبيضُ في سايدبارٍ داكنٍ
   * لَطخةٌ**، وهو نفسُه فوق خلفيّةِ صورةٍ في الموقع يفصل الشعارَ عمّا
   * تحته.
   *
   * **فصار خياراً يُطلب لا سلوكاً يُفرض** — والافتراضُ بلا قرص، فلا
   * تتبدّل اللوحاتُ الخمسُ بسطرٍ كُتب للموقع.
   */
  disc?: boolean;
  /** `control` للشريط والسايدبار · `card` للطبقات الكبيرة · `none` للأوراق */
  rounded?: "control" | "card" | "badge" | "none";
  /**
   * **ارتفاعٌ بالأصناف بدل الرقم** — لمن يحتاجه يتبدّل بمقاس الشاشة.
   *
   * (كشفه المالك ٢٠٢٦-٠٨-٠٩ بلقطةٍ من الجوّال: شعارُ الشريط يلامس بطاقةَ
   *  الدخول.)
   *
   * **والرقمُ يُكتب في `style` فيغلب كلَّ صنف** — فلا سبيل إلى `sm:` معه.
   * **وشعارٌ يصلح لشاشةٍ عريضةٍ يخنق شريطَ هاتف.**
   *
   * **ويبقى `size` مطلوباً**: منه يُحسب سقفُ العرض.
   */
  heightClass?: string;
  className?: string;
}) {
  const { name, logo } = usePlatform();
  const [broken, setBroken] = useState(false);
  // **ويُعاد الحالُ صفراً متى تبدّل الشعار** — فمن رفع بديلاً بعد كسرٍ
  // **يراه، ولا يبقى مخفيّاً لأنّ سابقَه سقط.**
  useEffect(() => setBroken(false), [logo]);
  /* **و`rounded` تُقبل ولا تُستعمل.**

     كانت تُستدير بها **بطاقةُ الحرف البديل** — وقد ذهبت. **والشعارُ المرفوع
     لا يُستدار**: صورةٌ صمّمها صاحبُها بحدودها، ومن قصَّ زواياها فرض عليها
     شكلاً لم تُرسَم له.

     **وتبقى في الواجهة لأنّ ستّةَ مواضعَ تمرّرها** — ونزعُها يكسرها كلَّها
     لأجل سطرٍ واحد. */
  void rounded;

  /* ══════════════════════════════════════════════════════════════════
     **ولا شيءَ حيث لا شعار**
     ══════════════════════════════════════════════════════════════════

     (قرارُ المالك ٢٠٢٦-٠٨-٠٩: «مربّع اللوغو ألغِه — إذا لم يُرفع لوغو نتركه
      فارغاً، بدون حرف، بدون شي».)

     **وكان مربّعاً يحمل أوّلَ حرفٍ من الاسم**، وحُجّتُه أنّ مكانَ العلامة
     يبقى محجوزاً فلا ينزلق ما بجانبه حين تصل. **وثمنُ الحجز أن يُقرأ المربّعُ
     الفارغُ عطباً** — وهو ما رآه المالك: لوحٌ رماديٌّ لا معنى له.

     **والانزلاقُ يقع مرّةً عند رفع الشعار**، والمربّعُ يُرى في كلّ فتحة.

     **و`brandLetter` تبقى مصدَّرة**: تستعملها شاشاتٌ أخرى لصورةٍ رمزيّةٍ
     لحسابٍ بلا صورة — **وحذفُ دالّةٍ لأنّ مستعمِلاً واحداً استغنى عنها يكسر
     الباقين.** */
  /* **وصورةٌ كُسرت تُخفى كما يُخفى شعارٌ لم يُرفع** — والحالُ يُعاد صفراً
     متى تبدّل الشعار، **وإلّا بقي المكسورُ مخفيّاً بعد أن رُفع بديلُه.** */
  if (!logo || broken) return null;

  /* ══════════════════════════════════════════════════════════════════
     **الشعارُ عارياً — بلا قرصٍ ولا إطار**
     ══════════════════════════════════════════════════════════════════

     (قرارُ المالك ٢٠٢٦-٠٨-٠٩ على ثلاث خطوات: «ضِف دائرةً بخلفيّةٍ بيضاء…»
      ثمّ «صغّر حجم اللوغو والدائرة قليلاً» ثمّ «ألغِ الدائرة البيضاء أيضاً».)

     **فلم يبقَ إلّا المقاس**: أكبرُ ممّا كان بمرّتين وربع، **بلا قرصٍ ولا
     استدارةٍ ولا إطار.**

     **والارتفاعُ هو المقياس** ويُترك العرضُ على نسبة الصورة، **فيظهر الشعارُ
     كما صُمِّم** ولا يُقصّ. وسقفٌ للعرض (أربعةُ أضعاف الارتفاع) يمنع شعاراً
     شريطيّاً من دفع ما بجانبه.

     **ولا ضربَ في المكوّن.**

     (قرارُ المالك ٢٠٢٦-٠٨-٠٩: «كبّر اللوغو فقط بالتوب بار».)

     **كان يُضرب هنا بمرّتين وربع** فكبُر في الشريط والسايدبار وشاشةِ الدخول
     والورقةِ المطبوعة معاً — **وأُريد الشريطُ وحدَه.**

     **فالمقاسُ ما يُمرَّر لا غير**، ومن أراد أكبرَ مرّر أكبر: **قرارُ الحجم
     عند من يعرف شاشتَه.** */
  const h = size;
  const img = (
    /* ══════════════════════════════════════════════════════════════
       **وشعارٌ مكسورٌ لا يُظهر اسمَ المنصّة**
       ══════════════════════════════════════════════════════════════

       (كشفه المالك ٢٠٢٦-٠٨-١١ بحذف الصورة عمداً: «اكتشفتُ أنّ اسمَ
        المنصّة موجودٌ تحت اللوغو، وأنا سابقاً طلبتُ حذفَ اسم المنصّة من
        التوب بار».)

       **و`alt` نصٌّ بديلٌ يعرضه المتصفّحُ حين تُكسر الصورة** — فكان
       الاسمُ يظهر في الشريط رغم أنّه مُنع منه. **ولا يُرى في التطوير**:
       الصورةُ موجودةٌ فلا يُقرأ البديلُ أبداً.

       **ويقع في الإنتاج بلا يدٍ أحد**: مجلّدُ الوسائط زائلٌ في الاستضافة
       المجّانيّة — **فكلُّ صورةٍ تزول ويظهر اسمُها مكانَها.**

       **والقرارُ القائمُ يقول ما يُفعل**: «إذا لم يُرفع لوغو نتركه فارغاً،
       بدون حرف، بدون شي» (٢٠٢٦-٠٨-٠٩). **وشعارٌ كُسر كشعارٍ لم يُرفع** —
       فيُخفى.

       **و`alt` فارغةٌ لا محذوفة**: الفارغةُ تقول «زخرفةٌ فتجاوزها»،
       **والمحذوفةُ تجعل قارئَ الشاشة ينطق اسمَ الملفّ.** */
    // eslint-disable-next-line @next/next/no-img-element
    <img
      src={logo}
      alt=""
      onError={() => setBroken(true)}
      style={disc ? undefined : heightClass ? { maxWidth: h * 4 } : { height: h, maxWidth: h * 4 }}
      className={
        disc
          ? /* ══════════════════════════════════════════════════════
               **وفرجةُ القرص بنسبةٍ من ارتفاعه لا بحشوةٍ مئويّة**
               ══════════════════════════════════════════════════════

               **وكانت `p-[12%]` على القرص — والحشوةُ المئويّةُ تُحسب من
               عرض الأب لا من قطر الدائرة.** فقرصٌ قطرُه ٩٦ في عمودٍ عرضُه
               ٥٤٤ أخذ حشوةً من خمسةٍ وستّين من كلّ جهة، **فصار صندوقُ
               الصورة صفراً واختفى الشعارُ وبقيت دائرةٌ بيضاءُ فارغة.**
               (كشفه المالك بلقطةٍ ٢٠٢٦-٠٨-١٧.)

               **ولم يظهر في الشريط** لأنّ ارتفاعَه يأتي بصنفٍ لا برقم،
               **فبدا سليماً في موضعٍ ومعطوباً في ثلاثة.**

               **والارتفاعُ المئويُّ يُحسب من ارتفاع الأب** — وهو مضبوطٌ
               في الحالين، فيُقرأ رقماً واحداً أينما وُضع. */
            "h-[74%] w-auto max-w-[74%] shrink-0 object-contain"
          : `w-auto shrink-0 object-contain ${heightClass ?? ""} ${className}`
      }
    />
  );

  /* **والقرصُ مربّعٌ ليكون دائرة** — `rounded-full` على صندوقٍ مستطيلٍ
     تعطي بيضةً لا دائرة، **وشعارُ المنصّة أعرضُ من ارتفاعه.**

     **فالمربّعُ من الارتفاع** (`aspect-square`) والشعارُ يُحصر داخلَه
     بحشوةٍ من كلّ جهة، **فيقع في مركزه مهما كانت نسبتُه.** */
  return disc ? (
    <span
      className={`inline-flex aspect-square shrink-0 items-center justify-center overflow-hidden rounded-full bg-paper ${heightClass ?? ""} ${className}`}
      style={heightClass ? undefined : { height: h }}
    >
      {img}
    </span>
  ) : (
    img
  );
}



