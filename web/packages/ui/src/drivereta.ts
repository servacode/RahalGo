/**
 * **وقتُ السائق — حسابٌ واحدٌ لبطاقتيه.**
 *
 * (جردُ لوحة السائق ٢٠٢٦-٠٨-٠٩ · قرارُ المالك: «يكون واضحاً المسافة والوقت
 *  المقدَّر أيضاً، وشقد بدو الطلب يجهز».)
 *
 * # لماذا هنا لا في كلّ شاشة
 *
 * **الحسابُ نفسُه في «طلبات قادمة» و«مهامّي»** — ونسختان منه تفترقان: تقول
 * إحداهما ثمانياً وتقول الأخرى اثنتي عشرة **عن الطلب نفسِه**، والسائقُ يصدّق
 * أيَّهما رأى أوّلاً.
 *
 * **وهي عائلةُ الخلل التي تكرّرت في هذا المشروع مراراً**: سقفُ النقد في العرض
 * وفي القبول · وقائمةُ أنواع الوسائط في Go وفي القاعدة · وطولُ كلمة المرور في
 * تسعة مواضع. **قاعدةٌ مكتوبةٌ مرّتين تفترق بلا صوت.**
 */

/**
 * **دقائقُ القيادة من المسافة.**
 *
 * @param meters   بالمتر — **وسالبٌ يعني «لا تُعرف»** لا صفراً: الجهلُ ليس قرباً.
 * @param speedKmh متوسّطُ السرعة من `drivers.avg_speed_kmh`.
 *
 * **ويردّ `null` لِما لا يُعرف** — فتُعرض شرطةٌ لا رقمٌ كاذب.
 *
 * **ولا يردّ صفراً**: من كان على بعد عشرين متراً يقرأ «دقيقة» لا «٠ دقيقة»
 * — **وصفرٌ يُقرأ «وصلتَ» وهو لم يصل.**
 */
export function driveMinutes(meters: number, speedKmh: number): number | null {
  if (!(meters >= 0) || !(speedKmh > 0)) return null;
  return Math.max(1, Math.round(meters / ((speedKmh * 1000) / 60)));
}

/**
 * **كم بقي على جهوز الطلب — بالدقائق.**
 *
 * `null` إن لم يُعرف، و`0` إن جهز.
 *
 * **ويُقرأ من وقت الجهوز إن كُتب، وإلّا من وقت القبول ومدّة التحضير** —
 * **والأوّلُ أصدق**: المتجرُ يضغط «جهز» فيُكتب، **والثاني تقديرٌ عند القبول.**
 */
export function readyInMinutes(o: {
  ready_at?: string | null;
  accepted_at?: string | null;
  prep_minutes?: number | null;
}): number | null {
  if (o.ready_at) return 0;
  if (!o.accepted_at || !o.prep_minutes) return null;
  const done = new Date(o.accepted_at).getTime() + o.prep_minutes * 60_000;
  return Math.max(0, Math.round((done - Date.now()) / 60_000));
}
