/**
 * **علاماتُ منصّات التواصل — بأشكالها الأصليّة.**
 *
 * (طلبُ المالك ٢٠٢٦-٠٨-٠٩: «الأيقونات الخاصّة بالسوشيال ميديا يجب أن تكون
 *  الأيقونات الحقيقيّة الأصليّة لتكون واضحةً للمستخدم».)
 *
 * # ولماذا لم تكن كذلك
 *
 * **حزمةُ `lucide` نزعت علاماتِ الشركات** — بقي منها `Send` وحدَه. **فرسمتُها
 * أوّلاً بخطوطٍ رفيعةٍ على طرازها**: مربّعٌ لإنستغرام وطائرةٌ لتلغرام و`f`
 * لفيسبوك. **وعلامةٌ مرسومةٌ بالتقريب لا تُعرَف** — والزائرُ يمسح الصفحةَ
 * بلمحةٍ ولا يدقّق في خطوطٍ نحيفة.
 *
 * **فصارت مصمتةً بشكلها المعروف** (`fill`): الشكلُ هو ما يُعرَّف به، **لا
 * لونُ الشركة** — واللونُ يأتي من الصفحة كما تأخذ كلُّ أيقونةٍ فيها لونَها.
 *
 * # ولماذا هنا لا في `icons.ts`
 *
 * **`icons.ts` أسماءٌ مستعارةٌ لا غير**: يُعيد تصدير `lucide-react` بأسماءٍ
 * عربيّةِ المعنى. **وهذه أشكالٌ تُرسم** فتحتاج `.tsx`.
 *
 * **ولا تُكتب في شاشةٍ بعينها**: حارسُ المركزيّة يمنع رسمَ أيقونةٍ خارج
 * المركز — **وعلامةٌ تُنسخ في ثلاث شاشاتٍ تفترق في الرابعة.**
 */

