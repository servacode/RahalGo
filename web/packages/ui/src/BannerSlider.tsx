"use client";

/**
 * **سلايدرُ اللافتات** — لافتةٌ واحدةٌ في المرّة تتبدّل وحدَها.
 *
 * # لماذا لا شريطٌ يُسحب
 *
 * كانت اللافتاتُ شريطاً أفقياً يُسحب باليد. **ومن لا يسحب لا يرى إلّا الأولى**
 * — والثانيةُ والثالثةُ تُنشَران ولا يراهما أحد، **فيُقال «اللافتاتُ لا تنفع»
 * والحقيقةُ أنّها لم تُعرَض.**
 *
 * (قرارُ المالك ٢٠٢٦-٠٨-٠٥: «لا تنسَ بناء سلايدر بالموقع لعرض البانرات».)
 *
 * # وثلاثةُ تفاصيلَ لولاها لصار إزعاجاً
 *
 *  1. **يتوقّف تحت الإصبع**: من مدّ يدَه ليقرأ لا تُسحب اللافتةُ من تحته.
 *  2. **ولا يدور على واحدة**: لافتةٌ وحيدةٌ تُعرض ساكنةً بلا نقاطٍ ولا مؤقّت.
 *  3. **ويحترم من أطفأ الحركة** (`prefers-reduced-motion`) — لمن يدوخه
 *     المتحرّك، **وهو إعدادٌ في نظامه لا رأيٌ نُصدره نحن.**
 *
 * ═══════════════════════════════════════════════════════════════════════
 * # وخمسةُ نواقصَ سُدَّت (٢٠٢٦-٠٨-٠٦، بطلب المالك: «السلايدر الاحترافيّ»)
 * ═══════════════════════════════════════════════════════════════════════
 *
 * **١ · كان يقفز ولا ينتقل.** لافتةٌ تحلّ محلَّ أختها في إطارٍ واحد **بلا
 * انتقالٍ يُرى** — والعينُ تقرأ القفزةَ خطأً في الصفحة لا تبدُّلَ لافتة.
 * **وهذا وحدَه الفرقُ بين سلايدرَ ومصفوفةِ صور.**
 *
 * **٢ · وكان يرسم واحدةً فقط.** فصورةُ التالية تبدأ تحميلَها **لحظةَ ظهورها**
 * — فيقع إطارٌ رماديٌّ ثمّ تظهر. **والآن كلُّها مرسومةٌ فوق بعضها** والظاهرةُ
 * وحدَها معتمة: **المتصفّحُ حمّلها قبل دورها.**
 *
 * **٣ · ولا سهمَين على الحاسب.** السحبُ يعمل بالإصبع، **ومن يجلس أمام شاشةٍ
 * بفأرةٍ لا يسحب** — فلا يملك إلّا انتظارَ الدورة أو ضغطَ نقطةٍ بحجم ستّة
 * بكسلات.
 *
 * **٤ · ولا لوحةَ مفاتيح.** من ينتقل بالتاب يقف على النقاط **ولا يستطيع
 * التنقّلَ بالأسهم** — وهو أوّلُ ما يُجرَّب.
 *
 * **٥ · ولا يُعرَّف لقارئ الشاشة.** كتلةٌ تتبدّل وحدَها بلا `aria-live`
 * **تُقرأ على الأعمى مرّةً واحدةً ثمّ تكذب عليه** بقيّةَ الوقت.
 */

import { useCallback, useEffect, useRef, useState } from "react";
import { getMessages, defaultLocale } from "@rahalgo/i18n";
import { IconNext, IconPrev } from "./icons";

const m = getMessages(defaultLocale);

export interface SlideItem {
  id: string;
  title: string;
  imageUrl: string | null;
  href?: string;
}

/** @param Link رابطُ الإطار — يختلف بين `next/link` وغيره. */
export function BannerSlider({
  items,
  Link,
  everyMs = 5000,
  hero = false,
  className = "",
}: {
  items: SlideItem[];
  /**
   * ══════════════════════════════════════════════════════════════════
   * **هيئةُ الواجهة — لوحٌ بنسبة ٢:١ لا يُقصّ**
   * ══════════════════════════════════════════════════════════════════
   *
   * (مواصفةُ المالك ٢٠٢٦-٠٨-١٧: «نفس الصورة على جميع الأجهزة… تظهر
   *  كاملةً قدرَ الإمكان دون قصّ… بشكل Card وليس صورةً مسطّحةً ملتصقةً
   *  بالصفحة».)
   *
   * **وثلاثةُ فروقٍ عن لافتة التسوّق**: النسبةُ ٢:١ لا ١٦:٥، **والصورةُ
   * تُحتوى لا تُقصّ**، والمهلةُ أطول.
   *
   * # ولماذا نسبةٌ مكتوبةٌ لا ارتفاعٌ تلقائيّ
   *
   * **المواصفةُ تقول `height: auto`** — وهي الصواب لصورةٍ وحيدة.
   * **والسلايدرُ يكدّس صورَه بعضَها فوق بعض** (`absolute`) ليذوب بينها،
   * **والمُطلَقُ لا يرفع أباه** — فلو تُرك الارتفاعُ تلقائيّاً لَانهار
   * الإطارُ إلى صفر.
   *
   * **والنسبةُ المكتوبةُ تعطي ما تعطيه `height: auto`**: الارتفاعُ يتبع
   * العرضَ بنسبةٍ ثابتة. **وتزيد عليها أنّها محجوزةٌ قبل وصول الصورة** —
   * فلا تقفز الصفحةُ حين تصل.
   *
   * # و`contain` لا `cover`
   *
   * **`cover` تملأ الإطارَ بقصّ ما يفيض** — ولافتةٌ نسبتُها غيرُ نسبة
   * الإطار يضيع منها ما ضاع. **و`contain` تُظهرها كاملةً** مهما رُفعت.
   */
  hero?: boolean;
  Link?: React.ComponentType<{ href: string; className?: string; children: React.ReactNode }>;
  everyMs?: number;
  className?: string;
}) {
  const [at, setAt] = useState(0);
  const [paused, setPaused] = useState(false);
  const many = items.length > 1;

  /**
   * **وإطفاءُ الحركة يُقرأ حيّاً لا مرّةً عند الإقلاع.**
   *
   * كان يُفحص داخل المؤقّت **فيُقرأ عند أوّل رسمٍ وحدَه** — ومن غيّر الإعدادَ
   * في نظامه وهو يتصفّح **يبقى السلايدرُ يدور عنده حتّى يُحدِّث الصفحة.**
   */
  const [still, setStill] = useState(false);
  useEffect(() => {
    const mq = window.matchMedia?.("(prefers-reduced-motion: reduce)");
    if (!mq) return;
    const read = () => setStill(mq.matches);
    read();
    mq.addEventListener("change", read);
    return () => mq.removeEventListener("change", read);
  }, []);

  const go = useCallback(
    (step: number) => setAt((i) => (i + step + items.length) % items.length),
    [items.length],
  );

  useEffect(() => {
    if (!many || paused || still) return;
    /* **وصفرٌ يوقف التبديل** — يقوله الإعدادُ حين يُطفئ المالكُ التلقائيّ.
       (٢٠٢٦-٠٨-٠٩.) **ومؤقّتٌ بمهلةِ صفرٍ يدور بلا توقّف** فيحرق الشاشة. */
    if (everyMs <= 0) return;
    const id = setInterval(() => go(1), everyMs);
    return () => clearInterval(id);
  }, [many, paused, still, everyMs, go]);

  // **والفهرسُ يُقلَّم حين تنقص اللافتات** — عرضٌ يُنزَل والسلايدرُ واقفٌ
  // عليه يترك إطاراً فارغاً.
  useEffect(() => {
    if (at >= items.length) setAt(0);
  }, [at, items.length]);

  const touch = useRef(0);
  const onStart = useCallback((x: number) => {
    touch.current = x;
    setPaused(true);
  }, []);
  const onEnd = useCallback(
    (x: number) => {
      const dx = x - touch.current;
      // **وسحبةٌ قصيرةٌ ليست سحبة** — إصبعٌ يرتجف على شاشةٍ ليس أمراً.
      if (Math.abs(dx) > 40 && many) go(dx < 0 ? 1 : -1);
      setPaused(false);
    },
    [many, go],
  );

  // **ولا إطارَ بلا لافتة** — وحارسٌ بعد القراءة يُرضي المدقّق أيضاً.
  if (items.length === 0) return null;
  const cur = Math.min(at, items.length - 1);

  /*
    كان `h-40 sm:h-52` — **رقمان ثابتان بالبكسل**، والإطارُ يتمدّد بعرض
    الشاشة والارتفاعُ لا يتحرّك. **فالصورةُ الواحدةُ تُقصّ قصّاً مختلفاً في
    كلّ شاشة**: على الجوّال إطارٌ نسبتُه ٢:١، وعلى اللابتوب شريطٌ نسبتُه
    ٦:١ **يبتلع أعلى اللافتة وأسفلَها** — فيضيع العنوانُ المرسومُ فيها
    ويبقى وسطُها وحدَه. (شهده المالك ٢٠٢٦-٠٨-٠٥.)

    وتضيق النسبةُ كلّما اتّسعت الشاشة — **لأنّ الملء ليس هدفاً**: لافتةٌ
    بنسبة ١٦:٩ على شاشةٍ عريضة تصير سبعمئة بكسلٍ من الطول **تملأ الشاشة
    وحدَها** ولا يُرى تحتها شيء.

        جوّال   ٣١١ بكسلاً عرضاً · ١٦:٩ ← ١٧٥ طولاً
        لوحيّ   ٥٧٦ ·············· ٥:٢ ← ٢٣٠
        لابتوب  ٩٦٠ ·············· ١٦:٥ ← ٣٠٠
        أعرض    السقفُ يمسك عند ٣٦٠ **فتزداد عرضاً لا طولاً**
  */
  /* ══════════════════════════════════════════════════════════════════
     **ولوحٌ من الموقع لا شريطٌ ملصوقٌ عليه**
     ══════════════════════════════════════════════════════════════════

     (شكوى المالك ٢٠٢٦-٠٨-٠٩: «السلايدر عريضٌ جدّاً ولا يوجد انسجامٌ بينه
      وبين الموقع — يجب أن يكون وكأنّه من أصل الموقع ومن أصل الخلفيّة، وليس
      سلايدر منفصلاً بهذا الشكل البدائيّ. صغّر حجمه أيضاً وارفعه للأعلى
      قليلاً».)

     **وثلاثةُ أسبابٍ جعلته يُقرأ ملصوقاً:**

     **١ · عرضٌ من حافّةٍ إلى حافّة** — وكلُّ ما في الصفحة تحته محصورٌ في
     عمودٍ أضيق. **فيبدو طبقةً أخرى لا عنصراً في الصفحة.** فيُحصر بعرضٍ
     أقصى ويتوسّط.

     **٢ · أرضٌ مصمتةٌ وحدٌّ حادّ.** وأُعطي أوّلاً ما لأخواته من الألواح —
     **فردّه المالك** (٢٠٢٦-٠٨-٠٩: «لا أريد إطاراً، أريد أن يكون وكأنّه من
     عمق الخلفيّة»). **فلا حدَّ ولا ظلَّ ولا أرض.**

     **وجُرّب قناعٌ يُذيب حوافَّه فردّه** («يتعب البصر») — **وهو محقّ**:
     ذوبانٌ فوق ضبابٍ فوق تصميمٍ نيونيٍّ ثلاثُ طبقاتٍ متحرّكةٍ خلف حرفٍ ثابت.
     **والهدوءُ أقلُّ لا أكثر**: استدارةٌ ناعمةٌ وحسب.

     **٣ · ونسبةٌ تتبدّل بالشاشة** (١٦:٩ على الجوّال · ٥:٢ على اللوحيّ ·
     ٢١:٦ على اللابتوب) **بينما اللافتةُ مقاسٌ واحد** — فتُقصّ أو يظهر حولَها
     فراغٌ في كلّ مقاسٍ إلّا واحداً.

     **فنسبةٌ واحدةٌ في كلّ الشاشات** (١٦:٥) — **ويُصمَّم عليها**:
     ١٦٠٠×٥٠٠. (قرارُ المالك ٢٠٢٦-٠٨-٠٩: «نعتمد قياساً واحداً لكلّ
     السلايدرات، لا أحجاماً مختلفة».)

     **ولا سقفَ ارتفاعٍ معها**: السقفُ يكسر النسبةَ فيعود الفراغ. **والنسبةُ
     نفسُها تحدّ الارتفاع** — أقصى عرضٍ ٦٤ريم فأقصى ارتفاعٍ عشرون.

     **والحشوةُ المضبّبةُ تبقى للثانية والثالثة** — الإطارُ يأخذ نسبةَ
     الأولى، **فما خالفها في المقاس يظهر حولَه فراغٌ من ألوانه هو.** وهي
     أهونُ من قفزةِ ارتفاعٍ عند كلّ تبديل.

     **والسقفُ يبقى** (٢٨٠) — لافتةٌ مربّعةٌ تُرفع خطأً لا تأخذ الشاشة. */
  /* ══════════════════════════════════════════════════════════════════
     **وملءُ الشاشة خيارٌ — لا لافتةٌ وسطَ فراغ**
     ══════════════════════════════════════════════════════════════════

     (شكوى المالك ٢٠٢٦-٠٨-١٧: «يجب أن يكون حجمُ الصورة بحجم الصفحة من
      اليمين إلى اليسار… وليس بانراً صغيراً يضيع في الشاشة».)

     **وحدُّ العرض ١٠٢٤ بكسلاً** — وهو نصفُ شاشةٍ عريضة، **فتُقرأ اللافتةُ
     صندوقاً في وسط الصفحة لا واجهةً لها.**

     **وصفحةُ التسوّق تبقى محدودة**: هناك لافتةٌ فوق شبكةِ أصنافٍ محدودةِ
     العرض، **ولافتةٌ تتجاوز ما تحتها تُقرأ غريبةً عنه.** */
  const frame = hero
    ? "banner-frame relative aspect-[2/1] w-full overflow-hidden"
    : "relative mx-auto aspect-[16/5] w-full max-w-5xl overflow-hidden rounded-card";

  const slide = (it: SlideItem, i: number) => {
    const on = i === cur;
    const body = (
      <>
        {/* ══════════════════════════════════════════════════════════════
            **ولا حشوةَ مضبّبةً خلف اللافتة**
            ══════════════════════════════════════════════════════════════

            (شكوى المالك ٢٠٢٦-٠٨-٠٩: «هذا الشكل أبداً مو مناسب، يتعب البصر
             والنظر — يجب أن يكون شيئاً احترافيّاً هادئاً».)

            **كانت نسخةً مضبّبةً من اللافتة تملأ ما يفيض عن نسبتها** — حيلةٌ
            صحيحةٌ يومَ كانت النسبةُ مكتوبةً وتخالف الصورة.

            **وقد صار المقاسُ واحداً** (١٦:٥) — **فلا فائضَ يُملأ**، ولم يبقَ
            من الضباب إلّا هالةٌ ملطّخةٌ حول التصميم: **لونان متحرّكان خلف
            حرفٍ ثابتٍ يُتعبان العين.**

            **والهدوءُ أن يُترك المشهدُ وحدَه** — لا ظلَّ له ولا هالةَ ولا
            قناعَ يذيب حوافَّه. */}
        {it.imageUrl ? (
          // eslint-disable-next-line @next/next/no-img-element
          <img
            src={it.imageUrl}
            alt={it.title}
            draggable={false}
            /* **والأولى تُحمَّل فوراً وما بعدها كسولاً**: الأولى هي ما يُرى في
               أوّل رسمٍ — **وتأجيلُها يترك فراغاً في أهمّ موضعٍ من الصفحة.** */
            loading={i === 0 ? "eager" : "lazy"}
            /* **وتملأ الإطارَ لأنّ نسبتَه نسبتُها.**

               **كانت `contain` وقرارُ المالك ٢٠٢٦-٠٨-٠٦ ألّا تُقصّ** — وهو
               صحيحٌ يومَ كانت نسبةُ الإطار مكتوبةً وتخالف الصورة: **تصميمٌ
               فيه عنوانٌ وشعارٌ يضيع ربعُه.**

               **وقد وُحّد المقاسُ** (١٦:٥) بقرار المالك ٢٠٢٦-٠٨-٠٩ — **فما
               من فائضٍ يُقصّ**، ولا فراغَ يُملأ. **ومن رفع مقاساً آخرَ
               يُقصّ من أطرافه** وهو ما يقوله له التنبيهُ عند الرفع. */
            className={`relative h-full w-full select-none ${
              hero ? "object-contain" : "object-cover"
            }`}
          />
        ) : (
          <div className="h-full w-full bg-gradient-to-l from-primary-tint to-accent-tint" />
        )}
        {/* **ولا عنوانَ على اللافتة.**

            (قرارُ المالك ٢٠٢٦-٠٨-٠٩: «لا يوجد داعٍ لعنوان البانر ولا للزرّ
             أيضاً».)

            **واللافتةُ تصميمٌ كاملٌ فيه كلامُه** — وشريطٌ أسودُ أسفلَها يعيد
            كتابةَ ما هو مكتوبٌ فيها، **ويغطّي ربعَها.**

            **ويبقى العنوانُ في `alt`** — لمن لا يرى. */}
      </>
    );
    return (
      <div
        key={it.id}
        aria-hidden={!on}
        /* **والمخفيّةُ لا تُلتقط بالتاب**: `inert` تمنع تركيزَ ما تحتها،
           **فلا يقف المتنقّلُ بالكيبورد على رابطٍ لا يراه.**

           **وتُمرَّر منطقيّةً لا نصّاً فارغاً**: كتبتُها `inert=""` أوّلَ مرّةٍ
           بحيلةِ نوع، **فأطلقت React تحذيراً في المتصفّح** — «نصٌّ فارغٌ لسمةٍ
           منطقيّة». **وReact ١٩ تقبلها منطقيّةً أصلاً**، والحيلةُ كانت لغير
           حاجة. (شهد المالك «1 Issue» في شاشته ٢٠٢٦-٠٨-٠٦.) */
        inert={!on}
        className={`absolute inset-0 transition-opacity ease-[--ease-out] ${
          still
            ? "duration-0"
            : hero
              ? "duration-[--duration-banner]"
              : "duration-[--duration-slow]"
        } ${on ? "opacity-100" : "pointer-events-none opacity-0"}`}
      >
        {it.href && Link ? (
          <Link href={it.href} className="block h-full w-full">
            {body}
          </Link>
        ) : (
          body
        )}
      </div>
    );
  };

  /**
   * ══════════════════════════════════════════════════════════════════
   * **والسهمُ خارجَ اللوح في الواجهة — داخلَه في التسوّق**
   * ══════════════════════════════════════════════════════════════════
   *
   * (طلبُ المالك ٢٠٢٦-٠٨-١٧: «الأسهم يجب أن تكون خارجَ السلايدر على
   *  اليمين واليسار بشكلٍ أنيقٍ ضمن دائرةٍ شفّافة».)
   *
   * **وقرصان داكنان فوق تصميمٍ يملأ اللوحَ يغطّيان منه** — والخارجُ لا
   * يغطّي شيئاً. **وفراغُه موجود**: اللوحُ متوسّطٌ بسقفِ ألفٍ ومئة،
   * فيبقى على جانبيه ما يزيد على ثلاثمئة في الشاشة العريضة.
   *
   * **ويبقى داخلاً في التسوّق**: لافتتُه تبلغ حدَّ العمود الذي تحتها،
   * **فلا فراغَ خارجَها يسع قرصاً.**
   *
   * **وتُخفى دون اللابتوب في الواجهة** — الفجوةُ هناك اثنا عشرَ بكسلاً،
   * **وقرصٌ خارجَ اللوح يخرج عن الشاشة.** والسحبُ يكفي.
   */
  const arrow = (dir: -1 | 1) => (
    <button
      type="button"
      onClick={() => go(dir)}
      aria-label={dir === 1 ? m.common.next : m.common.back}
      className={
        hero
          ? /* **دائرةٌ شفّافةٌ بحدٍّ رفيع** — تُرى ولا تُثقل، **وتسطع عند
               المرور** وتبقى لمن ينتقل بالكيبورد. */
            `taparea absolute inset-block-0 my-auto hidden h-11 w-11 items-center justify-center rounded-badge border border-line text-ink opacity-60 backdrop-blur-sm transition-opacity hover:opacity-100 focus-visible:opacity-100 lg:flex ${
              dir === 1 ? "start-[-3.25rem]" : "end-[-3.25rem]"
            }`
          : /* **والسهمُ يخفت حتّى يُطلب** — قرصان داكنان دائمان على لافتةٍ
               ملوّنةٍ يُقرآن أداةً غريبةً عنها. */
            `taparea absolute inset-block-0 my-auto hidden h-9 w-9 items-center justify-center rounded-badge scrim text-on-solid opacity-0 backdrop-blur-sm transition-opacity focus-visible:opacity-100 group-hover:opacity-100 sm:flex ${
              dir === 1 ? "start-3" : "end-3"
            }`
      }
    >
      {/* **والأيقونتان من المركز** — تنقلبان مع اتّجاه الصفحة كسائر
          أيقونات المنصة، **فلا يُقلَبان باليد هنا.** */}
      {dir === 1 ? <IconNext size={18} /> : <IconPrev size={18} />}
    </button>
  );

  return (
    <div
      className={className}
      /* **ويُعرَّف كتلةً تتبدّل** — قارئُ الشاشة يقول «لافتة ٢ من ٣» بدل أن
         يقرأ نصّاً يتغيّر تحته بلا خبر. */
      role="region"
      aria-roledescription="carousel"
      aria-label={m.site.home.bannersLabel}
      onMouseEnter={() => setPaused(true)}
      onMouseLeave={() => setPaused(false)}
      onTouchStart={(e) => onStart(e.touches[0]?.clientX ?? 0)}
      onTouchEnd={(e) => onEnd(e.changedTouches[0]?.clientX ?? 0)}
      /* **والأسهمُ تنقل حين يقع التركيزُ داخله** — وهي أوّلُ ما يُجرَّب. */
      onKeyDown={(e) => {
        if (!many) return;
        if (e.key === "ArrowLeft") go(1);
        else if (e.key === "ArrowRight") go(-1);
      }}
    >
      {/* **وصندوقُ القصّ لا يحمل الأسهم في الواجهة** — `overflow:hidden`
          عليه، **وما خرج عن حدّه يُقصّ.** فصارت أخواتٍ له في غلافٍ نسبيّ. */}
      <div className="relative">
        <div
          className={`group ${frame}`}
          aria-live={paused ? "polite" : "off"}
        >
          {items.map(slide)}
          {!hero && many && arrow(1)}
          {!hero && many && arrow(-1)}
        </div>
        {hero && many && arrow(1)}
        {hero && many && arrow(-1)}
      </div>

      {/* **ونقاطٌ تُضغط لا تُرى فقط** — من رأى الثالثةَ وأراد العودةَ إلى
          الأولى لا ينتظر دورةً كاملة. */}
      {many && (
        <div className="mt-2 flex justify-center gap-1.5">
          {items.map((it, i) => (
            <button
              key={it.id}
              type="button"
              aria-label={it.title}
              aria-current={i === cur}
              onClick={() => setAt(i)}
              className={`taparea h-1.5 rounded-badge transition-all duration-[--duration-base] ease-[--ease-out] ${
                i === cur ? "w-5 bg-accent" : "w-1.5 bg-line hover:bg-ink-muted"
              }`}
            />
          ))}
        </div>
      )}
    </div>
  );
}
