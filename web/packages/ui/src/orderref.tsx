import { fmtRef, fmtDateTime } from "@rahalgo/i18n";

/**
 * ══════════════════════════════════════════════════════════════════════
 * **رقمُ الطلب وتاريخُه — شكلٌ واحدٌ في كلّ لوحة**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (قرارُ المالك ٢٠٢٦-٠٨-١٢: «رقم الطلب على اليسار كما اتّفقنا، بنفس
 *  المربّع الصغير وبنفس اللون، وتحته التاريخ والوقت» · «لا تنسَ التعديلات
 *  التي أطلبها كلُّها مركزيّة، لا تعدّل شيئاً في المكان نفسه».)
 *
 * # ولماذا مركّبةٌ لا سطرٌ في كلّ بطاقة
 *
 * **الرقمُ يُكتب في أربع لوحات**: بطاقةُ الزبون، وبطاقةُ الإدارة، وورقةُ
 * المتجر، وسجلُّ السائق. **وأربعُ صياغاتٍ تفترق يوما**: يُبدَّل لونٌ في
 * واحدة ويبقى في ثلاث، **فيقرأ من يعمل على اللوحتين رقمين مختلفَي
 * الشكل لشيءٍ واحد.**
 *
 * # والرقمُ بالنبرة عمدا
 *
 * **هو ما يُقال في الهاتف حين يُسأل عن طلب**: «الألف والتاسع». **فيقع
 * أوّلَ ما تراه العين** لا سطراً رمادياً بين سطور.
 *
 * # والتاريخُ تحته لا تحت العلامة
 *
 * **والعلامةُ لا تاريخَ لها** — هي هي في كلّ بطاقة. **والتاريخُ خبرٌ عن
 * هذا الطلب وحدَه** فيقع تحت ما يخصّه: «الألف والتاسع، أمس الثامنة».
 */
export function OrderRef({
  number,
  /** **متى وقع** — وفارغٌ يعني بطاقةً لا تاريخَ فيها. */
  at,
  className = "",
}: {
  number: number;
  at?: string | null;
  className?: string;
}) {
  return (
    <span className={`flex flex-col items-end gap-1 ${className}`}>
      <span
        dir="ltr"
        className="rounded-control bg-accent px-2.5 py-1 text-sm font-bold tabular-nums text-on-bright"
      >
        #{fmtRef(number)}
      </span>
      {at && (
        <span className="text-2xs tabular-nums text-ink-muted" dir="ltr">
          {fmtDateTime(at)}
        </span>
      )}
    </span>
  );
}
