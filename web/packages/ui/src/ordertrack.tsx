"use client";

/**
 * **مسارُ الطلب أفقياً** — الحالةُ في البطاقة لا في صفحةٍ أخرى.
 *
 * # لماذا أفقيّ ولماذا هنا
 *
 * الخطُّ الزمنيُّ الرأسيّ (`Timeline`) يشرح **ما وقع ومتى** — وهو صفحةُ تفصيل.
 * **والزبونُ في قائمة طلباته يسأل سؤالاً واحداً: أين طلبي الآن؟** وجوابُه لا
 * يستحقّ انتقالاً إلى صفحة.
 *
 * قرارُ المالك (٢٠٢٦-٠٨-٠٣): «حالة الطلب تكون بنفس الكرت، لا يوجد داعي
 * للانتقال إلى صفحة التفاصيل · نكبّر الكرت شوي والحالة تصير بشكل أفقيّ».
 *
 * # والدرّاجةُ تمشي على المراحل
 *
 * «شو رأيك نخليه أيقونة موتسكل هي تتحرك وتمشي المراحل» — **وهي أصدقُ ما يقوله
 * تطبيقُ توصيل**: الشريطُ يقول «كم بقي» والدرّاجةُ تقول «أنا في الطريق».
 *
 * **وتتحرّك في الجاري وحدَه.** طلبٌ سُلّم أو أُلغي **درّاجتُه ساكنة** — وحركةٌ
 * في عشر بطاقاتٍ مغلقةٍ ضجيجٌ يُتعب العين ولا يدلّ على شيء.
 *
 * **وتسكن لمن أطفأ الحركة في نظامه** (`prefers-reduced-motion`) — فمن طلب
 * السكون طلبه لسببٍ يخصّه.
 *
 * # وما ينتهي قبل أن يصل
 *
 * الملغى والمرفوض والمُخفق **لا مسارَ لهم**: شريطٌ يتوقّف في منتصفه يُقرأ
 * «عالق» لا «انتهى». **فيُعرض سطرٌ واحدٌ يقول أين توقّف ولماذا** — والحقيقةُ
 * أوضحُ من رسمٍ جميلٍ يكذب.
 */

import type { ComponentType } from "react";

export interface TrackStage {
  id: string;
  label: string;
  icon?: ComponentType<{ size?: number; className?: string; strokeWidth?: number }>;
}

export function OrderTrack({
  stages,
  /** رقمُ المرحلة الحالية — و`-1` لما لم يبدأ */
  current,
  /** أيقونةُ المركبة التي تمشي على المسار */
  vehicle: Vehicle,
  /** **الحركةُ للجاري وحدَه** — المغلقُ يسكن */
  live = false,
  className = "",
}: {
  stages: TrackStage[];
  current: number;
  vehicle: ComponentType<{ size?: number; className?: string; strokeWidth?: number }>;
  live?: boolean;
  className?: string;
}) {
  const last = Math.max(1, stages.length - 1);
  const at = Math.min(Math.max(current, 0), stages.length - 1);
  // **النسبةُ من الطرف** — والصفحةُ من اليمين إلى اليسار، فالبدايةُ يمين.
  const pct = (at / last) * 100;

  return (
    /* ══════════════════════════════════════════════════════════════════
       **وحشوةٌ جانبيّةٌ تسع نصفَ ما يقف على الطرفين**
       ══════════════════════════════════════════════════════════════════

       (قرارُ المالك ٢٠٢٦-٠٨-٠٧: «النصوصُ تحت الطريق يجب أن تكون مضبوطةً
        بشكلٍ صحيح».)

       **كلُّ ما على المسار يقف على نسبةٍ منه** — الدرّاجةُ والعُقَدُ
       والأسماء. **والواقفُ على ٠٪ أو ١٠٠٪ يتوسّط الطرفَ فيخرج نصفُه.**

       ── وصنفُ الإزاحة يُلغي نمطَها ──

       **تيلويند ٤ يكتب `-translate-x-1/2` في خاصّيّة `translate`** لا في
       `transform`. **وهما خاصّيّتان تُجمعان لا تتغالبان** — فصنفٌ بـ‎−٥٠٪
       ونمطٌ بـ‎+٥٠٪ يُساويان صفراً.

       **وقِيس**: انحرافُ الأسماء عن عُقَدها **ثمانيةٌ وعشرون بكسلاً بالضبط
       للخمسة** — وهو نصفُ عرض الاسم. **ورقمٌ واحدٌ يتكرّر خمساً ليس صدفة.**

       فبقي النمطُ وحدَه.

       **فتُحجز الحشوةُ هنا مرّةً واحدة**: نصفُ أعرضِ ما يقف — واسمُ مرحلةٍ
       بأربعةٍ وستّين. **والمسارُ يقصر بمقدارها ولا يفيض أحد.** */
    <div className={`w-full px-8 ${className}`}>
      {/* الدرّاجةُ فوق الشريط — تنزلق إلى موضع المرحلة */}
      <div className="relative mb-1 h-7">
        <span
          className={`absolute top-0 text-accent-text ${
            live ? "motion-safe:animate-[rahalgo-ride_1.6s_ease-in-out_infinite]" : ""
          }`}
          style={{
            // **`right` لا `left`**: المسارُ يبدأ من اليمين في واجهةٍ عربية،
            // ولو استُعمل `left` لَمشت الدرّاجةُ عكسَ القراءة.
            right: `${pct}%`,
            transform: "translateX(50%)",
            transition: "right 600ms cubic-bezier(0.4, 0, 0.2, 1)",
          }}
          aria-hidden
        >
          {/* **ووجهُها نحو مسيرها.**

              المسارُ يمشي من اليمين إلى اليسار — كاتّجاه القراءة — **وأيقونةُ
              المركبة في المكتبة موجَّهةٌ إلى اليمين**، فتبدو ماشيةً إلى الخلف.
              **وقلبُها أفقياً يجعلها تسير حيث تنظر.** */}
          <Vehicle size={28} className="-scale-x-100" />
        </span>
      </div>

      {/* القضيبُ والعُقَد */}
      <div className="relative h-1.5" aria-hidden>
        <div className="absolute inset-0 rounded-badge bg-field" />
        <div
          className="absolute inset-y-0 right-0 rounded-badge bg-accent transition-[width] duration-700 ease-out"
          style={{ width: `${pct}%` }}
        />
        {stages.map((s, i) => (
          <span
            key={s.id}
            className={`absolute top-1/2 h-3 w-3 -translate-y-1/2 translate-x-1/2 rounded-full border-2 transition-colors ${
              i <= at ? "border-accent bg-accent" : "border-line bg-surface"
            }`}
            style={{ right: `${(i / last) * 100}%` }}
          />
        ))}
      </div>

      {/* ══════════════════════════════════════════════════════════════
          **والاسمُ تحت عُقدته لا في خانةٍ بجوارها**
          ══════════════════════════════════════════════════════════════

          (قرارُ المالك ٢٠٢٦-٠٨-٠٧.)

          **كانت الأسماءُ صفَّ `flex` بخاناتٍ متساوية**: كلُّ اسمٍ يتوسّط
          خُمسَ العرض. **والعُقَدُ تقف على نسبٍ من المسار** — صفرٌ وخمسةٌ
          وعشرون وخمسون… **والخانةُ الأولى مركزُها عند عشرة بالمئة وعُقدتُها
          عند صفر.**

          **فلا يقع اسمٌ تحت عُقدته إلّا في الوسط** — والطرفان أبعدُ ما
          يكونان. **ويُقرأ الشريطُ فيُظنّ أنّ المرحلةَ غيرُ التي هي.**

          **فصار الاسمُ يقف حيث تقف عُقدتُه** بالنسبة نفسِها، ويتوسّط نفسَه.

          **وعرضُه محجوز**: اسمٌ يتّسع بطوله يزحف على جارِه. **وسطران على الأكثر** — و`leading-tight` يُبقي الارتفاعَ مضبوطاً. */}
      <div className="relative mt-1.5 h-8 text-2xs leading-tight">
        {stages.map((s, i) => (
          <span
            key={s.id}
            className={`absolute top-0 line-clamp-2 w-14 text-center ${
              i === at
                ? "font-bold text-accent-text"
                : i < at
                  ? "text-ink-muted"
                  : "text-ink-muted opacity-50"
            }`}
            style={{ right: `${(i / last) * 100}%`, transform: "translateX(50%)" }}
          >
            {s.label}
          </span>
        ))}
      </div>
    </div>
  );
}
