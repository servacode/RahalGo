/**
 * ══════════════════════════════════════════════════════════════════════
 * **أحداثُ التيّار — مواضعُ تُدفَع كلَّ ثوانٍ، لا «شيءٌ تغيّر»** (٢٠٢٦-١١-٠٥)
 * ══════════════════════════════════════════════════════════════════════
 *
 * (طلبُ المالك ٢٠٢٦-١١-٠٥: «بدنا حركة السائق على الخريطة تكون مباشرة ما بدنا نطّات».)
 *
 * **ناقلُ البثّ يحوّل كلَّ حدثٍ خامٍ إلى «نوع»** (`Notifications.tsx`) — و`useLiveData`
 * بلا أنواعٍ يُعيد الجلبَ على **أيّ** نوع. **فكانت نبضةُ سائقٍ واحدٍ في طلب — كلَّ أربع
 * ثوانٍ — تُعيد في كلّ خريطة عمليّاتٍ مفتوحةٍ نحو ثلاثَ عشرةَ قائمةً من الخادم**، وصفحةَ
 * التوسّع، ولوحةَ صحّة الدفتر بكلّ فحوصها. **وجوابٌ قُرئ قبل نبضةٍ أحدثَ يصل بعدها
 * فيُرجع السائقَ إلى الوراء ثمّ يقدّمه: هذه «النطّات».**
 *
 * **وحدثُ التيّار يحمل الموضعَ نفسَه** — فمن يحتاجه يأخذه بـ`useLiveEvent`، **ولا يصير
 * نوعاً يوقظ إعادةَ الجلب أبداً.** والقائمةُ هنا وحدَها، **وخالصةٌ بلا React** فيقيسها
 * حارسُ `check-opsmap-live.mjs` بالنداء.
 *
 * - `driver_location` — موضعُ السائق الحيّ (`driver_live.go`)، كلَّ ٤ ثوانٍ في الطلب.
 * - `customer_location` — موضعُ الزبون الحيّ لخريطة العمليّات (`live_location.go`)،
 *   كلَّ ١٠ ثوانٍ لكلّ طلبٍ يشارك زبونُه موقعَه — **والعلّةُ نفسُها.**
 */
export const STREAM_EVENTS: ReadonlySet<string> = new Set(["driver_location", "customer_location"]);

/** **أحدثُ تيّارٍ هو؟** — فيصل `useLiveEvent` وحدَه، ولا يُعيد جلبَ شيء. */
export function isStreamEvent(type: string): boolean {
  return STREAM_EVENTS.has(type);
}
