/**
 * ══════════════════════════════════════════════════════════════════════
 * **بابُ الويب يُفتح بقدرةٍ لا باسم دور** (`WEBA`، ٢٠٢٦-٠٩-١٣)
 * ══════════════════════════════════════════════════════════════════════
 *
 * # ما وقع
 *
 * **حسابُ الرصد `customer + observability` دخل من `/adminrahalgo`
 * فسيق إلى `/app`** — **وقدرتُه `observability.read` قدرةُ ويبٍ
 * شرعيّة.**
 *
 * # والجذرُ ليس أنّ «الزبون غلب»
 *
 * **بل أنّ القدراتَ لم تُسأل أصلاً.** **وكان القرارُ قائمةَ ثلاثةِ
 * أسماءٍ مُصرَّفةً** في `homeFor`:
 *
 *	admin · ops · finance   ⇒ اللوحة
 *	وكلُّ ما سواها          ⇒ ‎/app
 *
 * **وهي قائمةٌ شاخت مرّتين**: **`ops` دورٌ مُتقاعِدٌ لا يحمله أحد**،
 * **و`operations` و`observability` — وهما القائمان فعلاً — ليسا
 * فيها.** **فمن مُنح قدرةً اليومَ لا يدخل حتّى يُكتب اسمُ دورِه هنا.**
 *
 * **وبابُ اللوحة نفسُه كان قد صُلِّح** (`canAccessPanel`، ٢٠٢٦-٠٩-١٢)
 * **وبقي بابُ التوجيه بعد الدخول على القائمة القديمة** — **فباب
 * يُفتح وطريقٌ لا يؤدّي إليه.**
 *
 * # والقاعدةُ الجامعة
 *
 * **من ملك قدرةً واحدةً ممّا تُمنَح للمكتب دخل قشرةَ اللوحة** —
 * **وما يراه فيها قدراتُه**، **وكلُّ صفحةٍ محروسةٌ في المحرّك على كلّ
 * حال** (`R15`/`ADG-1`). **وهذه عينٌ لا يد.**
 *
 * **ولا تُفتح لأحدٍ جديد**: **قِيس أنّ `customer` و`driver` و`merchant`
 * و`sales` صفرُ قدرات في جدول السياسة** — **والقدرةُ لا تُمنَح إلّا
 * بمسارٍ مخوَّلٍ بتأكيدٍ وقيدِ تدقيق.**
 *
 * # ولمَ ملفٌّ بذاته
 *
 * **دالّةٌ نقيّةٌ بلا استيرادٍ ولا نافذة** — **فيقيسها حارسٌ بالنداء لا
 * بقراءة نصّ.** **وحارسٌ يقرأ سطراً يمرّ وشرطٌ مقلوبٌ يمرّ معه.**
 */

/**
 * PANEL_ROLES **شبكةُ الأمان القديمة — أسماءٌ لا يُعتمَد عليها.**
 *
 * **وتبقى لحالٍ واحدة**: **تعذّرُ قراءةِ القدرات** (انقطاعٌ أو ٥٠٣) —
 * **فلا يُحبَس الأدمنُ خارجَ لوحته لأنّ نداءً سقط.**
 *
 * **ولا تُزاد أسماءٌ إليها** — **من أراد بابَ ويبٍ لدورٍ جديدٍ يمنحه
 * قدرة.**
 */
export const LEGACY_PANEL_ROLES = ["admin", "ops", "finance"] as const;

/**
 * isWebAuthorized **أله بابٌ في الويب؟**
 *
 * **والقدرةُ أوّلاً**: **قدرةٌ واحدةٌ تكفي** — **وما يراه بعدها قدراتُه.**
 *
 * **ثمّ الأسماءُ القديمةُ شبكةَ أمانٍ** — **وتُقرأ فقط حين لم تصل
 * القدراتُ أصلاً** (`capsLoaded === false`). **ولو قُرئت مع قدراتٍ
 * واصلةٍ فارغةٍ لَدخل صاحبُ دورٍ مجرَّدٍ من كلّ قدرة.**
 */
export function isWebAuthorized(
  roles: readonly string[] | undefined,
  capabilities: readonly string[] | undefined,
  capsLoaded = true,
): boolean {
  if (capabilities && capabilities.length > 0) return true;
  if (capsLoaded) return false;
  const r = roles ?? [];
  return LEGACY_PANEL_ROLES.some((name) => r.includes(name));
}
