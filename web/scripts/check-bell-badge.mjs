/**
 * ══════════════════════════════════════════════════════════════════════
 * **عدّادُ الإشعارات فوق الجرس — ولا يخرج من صندوق زرّه**
 * ══════════════════════════════════════════════════════════════════════
 *
 * # ولماذا حارسٌ لهذا وحدَه
 *
 * **شهده المالكُ ثلاثَ مرّاتٍ في يومٍ واحدٍ (٢٠٢٦-٠٨-١١)**: «الجرسُ يبين
 * مقصوص» ثمّ «البوردرُ الأبيضُ لم تُحلّ مشكلتُه» ثمّ صورةٌ يظهر فيها الجرسُ
 * مبتوراً. **وثلاثةُ إصلاحاتٍ لم تُصبه**: كبّرتُ الحشوةَ في الصفّ، ثمّ
 * صغّرتُ الفقّاعة، ثمّ أزحتُها بجانب الجرس — **وهذا الأخيرُ خالف الاصطلاح**
 * فردّه المالك: «بحياتي ما شفت عدّادَ إشعاراتٍ بجانب الجرس».
 *
 * # والعلّةُ هندسيّةٌ لا جماليّة
 *
 * **صفُّ أدوات الشريط فيه `overflow-x: auto`** ليمنع الشريطَ أن يجرّ الصفحةَ
 * على الجوّال. **و`overflow-x` تجرّ `overflow-y: auto` بحكم المواصفة** —
 * فما خرج علوّاً يُقصّ.
 *
 * **والفقّاعةُ تُوضع سالبةً** (`-top-1`) وحلقتُها تخرج بكسلين — **ستّةٌ فوق
 * حافّةِ ما تُعلَّق عليه.**
 *
 * **فالشرطُ أن تُعلَّق على الأيقونة داخلَ زرٍّ حشوتُه أوسعُ من ستّة** —
 * وحينها لا يبلغها مِقصُّ أيِّ سلفٍ مهما تبدّل ما حولَها في الصفّ.
 *
 * # وحارسٌ يفحص النيّةَ لا الهندسة زخرفة
 *
 * **لا يكفي أن يُقال «الفقّاعةُ تطفو»** — كانت تطفو وهي مقصوصة. **فيُقاس
 * الرقمان**: كم تخرج، وكم تحتمل الحشوة.
 */

import fs from "node:fs";

const FILE = "packages/ui/src/Notifications.tsx";
const src = fs.readFileSync(FILE, "utf8");
const fail = [];

// ── ١ · العدّادُ فوق الجرس لا بجانبه ────────────────────────────────────
// **`float` هي ما يجعلها تطفو** — وبلاها تجلس في الصفّ حبّةً بجانبه.
const bellBlock = src.slice(src.indexOf("<IconBell size={19}"));
if (!/<CountBadge count=\{unread\}[^/]*\bfloat\b/.test(bellBlock)) {
  fail.push(
    "عدّادُ الجرس لا يطفو فوقه — **وهو الاصطلاحُ الذي يعرفه كلُّ من حمل هاتفاً**، " +
      "وردّه المالكُ صراحةً حين أُزيح جانباً (٢٠٢٦-٠٨-١١)",
  );
}

// ── ٢ · ويُعلَّق على الأيقونة لا على الزرّ ─────────────────────────────
// **المرجعُ (`relative`) يقرّر من أين تُقاس الإزاحةُ السالبة.**
if (!/<span className="relative flex">\s*\n\s*<IconBell/.test(src)) {
  fail.push(
    "الفقّاعةُ ليست معلَّقةً على الأيقونة نفسِها — **فالسالبُ يُقاس من حافّة الزرّ " +
      "فتخرج منه**، ويقصّها `overflow` في صفّ الأدوات",
  );
}

// ── ٣ · وحشوةُ الزرّ تحتمل ما يخرج ─────────────────────────────────────
// **ستّةٌ تخرج** (أربعةٌ إزاحةً `-top-1` واثنتان حلقةً `ring-2`).
const OVERHANG = 6;
const btn = src.match(/const cls =\s*\n?\s*"([^"]+)"/);
if (!btn) {
  fail.push(`تعذّر العثورُ على قوالب زرّ الجرس في ${FILE}`);
} else {
  const pad = btn[1].match(/(?:^|\s)p-([\d.]+)(?:\s|$)/);
  const px = pad ? parseFloat(pad[1]) * 4 : 0;
  if (px < OVERHANG) {
    fail.push(
      `حشوةُ زرّ الجرس ${px} بكسلاً والفقّاعةُ تخرج ${OVERHANG} — ` +
        "**فتتجاوز صندوقَ الزرّ ويبلغها المِقصّ**",
    );
  }
}

if (fail.length) {
  console.error(`\nعدّادُ الجرس: ${fail.length} مخالفةً\n`);
  for (const f of fail) console.error(`   ${FILE}  ${f}`);
  console.error("");
  process.exit(1);
}
console.log("عدّادُ الجرس سليم — يطفو فوقه، ولا يخرج من صندوق زرّه.");
