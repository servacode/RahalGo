//  تمرير شاشة التسوّق — والمقبولُ دون العشرة.)
//
// # ما يُقاس
//
// **`SubcomposeAsyncImage` تُعيد قياسَ كلّ صورةٍ في تركيبةٍ مستقلّة** —
// وCoil نفسُها توصي بتجنّبها في القوائم. **وشبكةٌ فيها عشراتُ البطاقات
// تدفع الثمنَ عشراتِ المرّات في كلّ تمريرة.**
//
// **ولا تُمنع مطلقاً**: لها موضعُها حيث يلزم قياسُ الصورة قبل رسم ما
// حولها. **إنّما تُمنع في `RemoteImage`** — البابُ الذي تمرّ منه كلُّ
// صورةٍ في التطبيقات الثلاثة.
//
// **وحارسٌ يمنع كلَّ استعمالٍ يُنذر على الصواب فيُطفَأ.**
//
// # ويُقرأ النداءُ لا الكلمة
//
// **أوّلُ تشغيلٍ أنذر على شرحِه نفسِه** (٢٠٢٦-٠٨-١٩): الاسمُ مكتوبٌ في
// التعليق الذي يشرح لماذا لا يُستعمل. **وحارسٌ لا يفرّق النصَّ من
// النداء يُنذر على وثيقةٍ صحيحة** — ثمّ يُطفَأ لأنّه يكذب.
//
// **فيُنزع التعليقُ قبل القراءة، ويُطلَب القوسُ بعد الاسم.**

import { readFileSync } from 'node:fs'
import { join } from 'node:path'

const HERE = new URL('.', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')
const ROOT = join(HERE, '..', '..')
const FILE = 'mobile/ui/src/main/kotlin/com/rahalgo/ui/RemoteImage.kt'

const raw = readFileSync(join(ROOT, FILE), 'utf8')
// **تُنزع التعليقاتُ أوّلا** — السطريّةُ والكتليّة.
const src = raw.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '')
if (/SubcomposeAsyncImage\s*\(/.test(src)) {
  console.error('بابُ الصور يستعمل SubcomposeAsyncImage:')
  console.error('  · ' + FILE)
  console.error('\nوهي تُعيد قياسَ كلّ صورةٍ في تركيبةٍ مستقلّة — **وقِيس أنّها')
  console.error('  رفعت التقطيعَ إلى ربع الإطارات في شبكة التسوّق.**')
  console.error('\nالبديل: AsyncImage مع onState للحرف البديل.')
  process.exit(1)
}
if (!src.includes('AsyncImage')) {
  console.error('بابُ الصور لا يستعمل AsyncImage — تغيّرت البنيةُ فأصلحْ الحارس.')
  process.exit(1)
}
console.log('بابُ الصور بلا تركيبٍ فرعيّ — صورةٌ واحدةٌ لكلّ بطاقة.')
