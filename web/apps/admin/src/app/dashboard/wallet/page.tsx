"use client";

/**
 * **خزينةُ المنصة** — محفظةُ الحساب الذي تمرّ به كلُّ حركة مال.
 *
 * # القاعدة
 *
 * **لا يُدفع لأحدٍ إلّا وخرج من الخزينة، ولا يدخل مالٌ إلّا ودخلها.** فما خرج
 * بلا مصدرٍ لا يُقرأ لاحقاً، **ومنصةٌ تعرف ما دفعت ولا تعرف من أين لا تعرف
 * شيئاً.**
 *
 * (قرارُ المالك ٢٠٢٦-٠٨-٠٤: «كلُّ شيءٍ يُسحب من حساب الأدمن وكلُّ مبلغٍ يدخل
 * إليه، بحيث يكون هو الخزينةَ التي تدير كلَّ حركات المبالغ المالية بالمشروع».)
 *
 * # ولماذا لم تكن هنا
 *
 * كانت في اللوحة قاعدةٌ مكتوبة: **«موظّفو المنصة لا محافظ لهم»** — فلا شارةَ
 * في الشريط ولا بابَ في القائمة. **وكانت صحيحةً يومَها**: المحفظةُ تُنشأ عند
 * أوّل حركة، وحسابُ الأدمن لا يقبض ولا يُخصم منه، **فشارةٌ برصيد صفرٍ تَعِد
 * بما لا يملكه صاحبها.**
 *
 * **وقد بطل سببُها**: صار لكلّ حسابٍ محفظة، وصارت محفظةُ الأدمن هي الخزينة —
 * **فالرقمُ فيها أهمُّ رقمٍ في المنصة**، لا صفراً يُخفى.
 *
 * # وهي محفظتُه هو لا شاشةٌ ثانية
 *
 * **ولا نقطةَ خادمٍ خاصّة**: `/my/wallet` تعيد كشفَ من يسأل. ومن يحمل الخزينة
 * يرى فيها حركاتِ المنصة كلَّها، **ومن لا يحملها يرى رصيدَه هو** — وهو صادقٌ
 * في الحالين.
 *
 * **وشاشةٌ ثانيةٌ تقرأ خزينةَ غيرها كانت ستحتاج نقطةً ثانيةً وحارساً ثانياً**،
 * وتفترق يوماً عن هذه — **وقد طاردنا هذه العائلةَ طويلاً.**
 */

import { getMessages, defaultLocale } from "@rahalgo/i18n";
import { WalletPage } from "@rahalgo/ui";
import { api } from "@/lib/api";
import { useAuth } from "@/lib/auth";

const m = getMessages(defaultLocale);

export default function AdminWalletPage() {
  const { user } = useAuth();
  return (
    <WalletPage
      api={api}
      path="/api/v1/my/wallet"
      balanceLabel={m.admin.nav.treasury}
      holderName={user?.full_name}
      holderPhone={user?.phone}
    />
  );
}
