"use client";

/**
 * **الصفحاتُ الثابتة** — الشروطُ والخصوصيةُ والمساعدة.
 *
 * # ولماذا هيكلٌ واحدٌ لثلاث
 *
 * ثلاثُ صفحاتٍ من عناوينَ وفقرات، **ولو كُتبت كلٌّ منها وحدَها لَافترقت**:
 * تُصلَح مسافةٌ في إحداها وتبقى الأخريان، **فتُقرأ الثلاثُ من ثلاث منصّات.**
 *
 * # والنصُّ في المعجم لا في الشيفرة
 *
 * **ومن أراد تصحيحَ سطرٍ في الشروط لا يفتح ملفَّ واجهة** — والنصوصُ كلُّها في
 * `ar.json` كبقيّة المنصة.
 *
 * # وهويّةُ المنصة من الخادم
 *
 * **الاسمُ والرقمُ والعنوان يتغيّرون**، وما كُتب في الشيفرة لا يُبدَّل إلّا
 * بنشر — **فيبقى الرقمُ القديمُ معروضاً شهراً ومن اتّصل به لم يجد أحداً.**
 *
 * **وفارغُها يُحذف لا يُعرض**: سطرٌ يقول «الهاتف: —» يُقرأ عطباً في المنصة.
 *
 * # وتُقرأ في الخادم لا في المتصفّح
 *
 * كانت تُجلب بـ`useEffect` **فيخرج من الخادم اسمُ العلامة ثمّ يُبدَّل**، و«تواصل
 * معنا» لا يظهر في المصدر أصلاً. **ووثيقةٌ قانونيةٌ تُقرأ من فهارس البحث**:
 * من بحث عن اسم الشركة لم يجد صفحةَ شروطها. (انظر `contact.ts`.)
 *
 * # والأيقونةُ مفتاحٌ لا دالّة
 *
 * **الصفحةُ تُرسم في الخادم والهيكلُ في المتصفّح** — ودالّةٌ لا تعبر بينهما:
 * «Functions cannot be passed directly to Client Components». **فيُمرَّر
 * مفتاحٌ نصيٌّ ويُختار المكوّنُ هنا**، والنصوصُ والهويّةُ بياناتٌ تعبر.
 */

import { PageContainer, PageHeader, IconNote, IconLock, IconSupport, usePlatform } from "@rahalgo/ui";
import { getMessages, defaultLocale } from "@rahalgo/i18n";
import type { Contact } from "./contact";

const m = getMessages(defaultLocale);
const L = m.site.legal;

export interface Block {
  /** عنوانُ الفقرة — **وفارغُه يعني نصّاً بلا عنوان**. */
  h?: string;
  /** فقراتُها — **سطرٌ لكلّ معنًى**، وفقرةٌ من عشرة أسطرٍ لا تُقرأ. */
  p: string[];
}

/**
 * حقولُ الهويّة التي تُملأ في النصّ — `{name}` و`{phone}` و`{address}`.
 *
 * **ولا يُترك قالبٌ ظاهراً أبداً.**
 *
 * كان يعود بالنصّ كما هو حين لا هويّةَ بعد — **فيقرأ الزائرُ «{name} منصّةُ
 * توصيل»** في أوّل رسمٍ قبل أن يصل الردّ، **وإلى الأبد إن تعثّر الطلب.**
 *
 * **ووثيقةٌ قانونيةٌ فيها قوسٌ لم يُملأ تُقرأ منصّةً غيرَ جاهزة** — وهي أوّلُ
 * ما يفتحه من يريد أن يطمئنّ.
 *
 * **واسمُ العلامة يكفي حتّى يصل الاسمُ المسجَّل**: هو صحيحٌ في الحالين، ولا
 * يقول شيئاً كاذباً.
 */
function fill(text: string, c: Contact | null, platform: string): string {
  // **والبديلُ اسمُ المنصة من الإعدادات لا من المعجم** (قرارُ المالك ٢٠٢٦-٠٨-٠٦)
  return text
    .replace(/\{name\}/g, c?.legal_name || platform)
    .replace(/\{phone\}/g, c?.support_phone ?? "")
    .replace(/\{address\}/g, c?.address ?? "");
}

/** أيقونةُ كلّ صفحة — **تُختار هنا لأنّ الدالّة لا تعبر إلى المتصفّح.** */
const ICONS = { terms: IconNote, privacy: IconLock, help: IconSupport } as const;

export function LegalPage({
  kind,
  title,
  subtitle,
  blocks,
  contact,
}: {
  kind: keyof typeof ICONS;
  title: string;
  subtitle?: string;
  blocks: Block[];
  /** **تصل جاهزةً من الخادم** — لا تُجلب هنا. */
  contact: Contact | null;
}) {
  // **واسمُ المنصة بديلٌ للاسم المسجَّل** — من الإعدادات لا من المعجم.
  const { name: platform } = usePlatform();
  const icon = ICONS[kind];

  return (
    <PageContainer width="medium">
      {/* **وسطرٌ يُقرأ في نصف الشاشة** — والنصُّ القانونيُّ بعرض اللابتوب
          كاملاً يُفقد العينَ أوّلَ السطر عند آخره، فتُعاد قراءتُه أو يُترك. */}
      {/* ══════════════════════════════════════════════════════════════
          **والنصُّ الطويلُ داخلَ لوحٍ لا على الخلفيّة**
          ══════════════════════════════════════════════════════════════

          (كشفه جردُ ٢٠٢٦-٠٨-٠٦: خمسٌ وأربعون سقطةَ تباينٍ من تسعٍ وأربعين
           في ثلاث صفحات — الشروطُ والخصوصيّةُ والمساعدة.)

          **كان يقف على الخلفيّة عارياً** — وهي متدرّجةٌ من زمرّديٍّ داكنٍ
          إلى سماويٍّ فاتح. **فسطرٌ يُقرأ في أعلى الصفحة لا يُقرأ في أسفلها**،
          والعناوينُ عند ٢٫١٥ والمتنُ عند ١٫٦٠.

          **وصفحاتُ الشروط أطولُ نصٍّ في المنصة** — من يقرأ ثلاثمئة كلمةٍ على
          تدرّجٍ متبدّلٍ يترك القراءة. **واللوحُ الزجاجيُّ يُثبّت الأرضَ تحت
          السطر** فلا يتبدّل ما تحته وهو ينزل.

          **وهو اللوحُ نفسُه الذي يحمل التواصلَ أسفلَها** — فلا يُخترع سطحٌ
          ثانٍ لِما هو من جنسه. */}
      {/* ══════════════════════════════════════════════════════════════
          **وكرتٌ لكلّ عنصرٍ — لا لوحٌ واحدٌ طويل**
          ══════════════════════════════════════════════════════════════

          (قرارُ المالك ٢٠٢٦-٠٨-٠٩: «صفحة المساعدة غيرُ احترافيّة — يجب أن
           تكون كروتاً مستطيلةً أنيقة، وكلُّ كرتٍ فيه عنصرٌ حسب الصفحة».)

          **كان لوحاً واحداً فيه عشرةُ عناوينَ متتالية** — **ومن بحث عن جوابٍ
          واحدٍ قرأ تسعةً قبله.** والعينُ لا تجد أين ينتهي سؤالٌ ويبدأ آخر.

          **والكرتُ يفصل بحدّه** — يُمسح بلمحةٍ ويُقرأ ما يخصّ.

          **ولا لوحَ يحوي الكروتَ**: سطحٌ فوق سطحٍ يُقرأ حدّين متوازيين
          **ويأكل من عرض النصّ مرّتين.** */}
      <div className="space-y-3">
        <PageHeader icon={icon} title={title} subtitle={subtitle} />

        {blocks.map((b, i) => (
          <section key={i} className="surface p-4 leading-relaxed sm:p-5">
            {b.h && <h2 className="mb-2 font-bold">{fill(b.h, contact, platform)}</h2>}
            {b.p.map((line, j) => (
              <p key={j} className="mb-2 text-sm text-ink-muted last:mb-0">
                {fill(line, contact, platform)}
              </p>
            ))}
          </section>
        ))}

        {/* **ولا تواصلَ في ذيل هذه الصفحات.**

            (قرارُ المالك ٢٠٢٦-٠٨-٠٩: «لا داعي لوجود تواصل معنا بهذه الصفحة
             لأنّه يوجد صفحةٌ خاصّةٌ بالتواصل، وأيضاً شروط الاستخدام وأيضاً
             سياسة الخصوصية».)

            **وكان يُكرَّر في ثلاث صفحات** — رقمٌ وعنوانٌ في ذيل المساعدة وذيل
            الشروط وذيل الخصوصيّة. **وثلاثُ نسخٍ من شيءٍ واحدٍ تفترق يوماً**،
            **ومن أراد التواصلَ له بابُه في التذييل.** */}
      </div>
    </PageContainer>
  );
}
