import type { NextConfig } from "next";

/**
 * **إعدادُ الويب — وعنوانُ المحرّك يُستبدَل وقتَ البناء.**
 *
 * **و`NEXT_PUBLIC_*` تُستبدَل نصّاً وقتَ البناء لا وقتَ التشغيل** — فما
 * يُكتب هنا هو ما يصل متصفّحَ الزائر. **ومن مرّرها بيئةً وقتَ التشغيل
 * وجد المتصفّحَ ينادي `localhost:8080`** وهو على هاتفه.
 *
 * **ويُشترط رابطٌ كاملٌ بمخطّطه** — **وعنوانٌ بلا `https://` يُنادى
 * مساراً في الموقع نفسِه** (`/api.rahalgo.com/api/v1/...`) فيردّ ٤٠٤،
 * ولا يظهر في أيّ سجلّ أنّ العنوانَ هو العطب.
 */
function asURL(raw: string | undefined, fallback: string): string {
  const v = (raw ?? "").trim();
  if (!v) return fallback;
  return /^https?:\/\//i.test(v) ? v.replace(/\/+$/, "") : `https://${v}`;
}

/**
 * **وعنوانُ الموقع من المنصّة نفسِها** — `RENDER_EXTERNAL_URL` تضعه
 * الاستضافةُ في الخدمة، **فلا يُسأل عنه أحدٌ ولا يُكتب بيد.**
 *
 * **ومن رفع على غير Render يضبط `NEXT_PUBLIC_SITE_URL`** — وهي الأسبق.
 */
const SITE = asURL(
  process.env.NEXT_PUBLIC_SITE_URL,
  "http://localhost:3003",
);

/**
 * ══════════════════════════════════════════════════════════════════════
 * **وعنوانٌ فارغٌ يُسقط البناء — لا يُخبَز صامتاً**
 * ══════════════════════════════════════════════════════════════════════
 *
 * **قِيس على النسخة المرفوعة (٢٠٢٦-٠٨-١٠)**: خُبز العنوانُ فارغاً، **فصار
 * كلُّ نداءٍ مساراً نسبيّاً في الويب نفسِه لا في المحرّك.**
 * فيردّ Next صفحةً بدل JSON، **وتقول الشاشةُ «حدث خطأٌ غير متوقّع»** ولا
 * شيءَ يدلّ على السبب.
 *
 * **وسببُه أنّ الاستضافةَ مرّرت قيمةً فارغة** — خاصّيّةٌ لم تعرفها فحلّتها
 * فراغاً بلا شكوى. **والفراغُ يمرّ من `??`**: هي تسقط على `undefined` لا
 * على `""`.
 *
 * **وموقعُ العطب أسوأُ ما فيه**: يقع وقتَ البناء ويظهر وقتَ الاستعمال،
 * **بعد أن يكون كلُّ شيءٍ قد «نجح».**
 *
 * **فيسقط البناءُ بصوتٍ عالٍ** — رسالةٌ في سجلّ النشر خيرٌ من موقعٍ يعمل
 * ولا يعمل. **وفي التطوير يبقى الافتراضُ المحلّيّ**، فلا يُعطَّل جهازُ أحد.
 */
const API = asURL(process.env.NEXT_PUBLIC_API_URL, "http://localhost:8080");

if (process.env.NODE_ENV === "production") {
  const raw = String(process.env.NEXT_PUBLIC_API_URL ?? "").trim();
  if (!raw) {
    throw new Error(
      "NEXT_PUBLIC_API_URL فارغ — الواجهة ستنادي نفسَها بدل المحرّك ولن يعمل شيء. " +
        "اضبطه في الاستضافة (رابط كامل) ثمّ أعد البناء.",
    );
  }
  /**
   * ══════════════════════════════════════════════════════════════════
   * **واسمٌ بلا نقطةٍ ليس عنواناً يعرفه متصفّح**
   * ══════════════════════════════════════════════════════════════════
   *
   * **قِيس على النسخة المرفوعة (٢٠٢٦-٠٨-١١)**: خُبز `https://rahalgo-api`
   * — **الاسمُ الداخليُّ للخدمة** الذي تتنادى به خدماتُ الاستضافة بينها.
   * **ولا يعرفه جهازُ الزبون**، فيسقط كلُّ نداءٍ برسالةٍ عامّة.
   *
   * **ومصدرُه أنّ `property: host` في المخطّطة تعطي الداخليَّ لا العامّ**
   * — وهو فرقٌ لا يظهر إلّا في متصفّحٍ حقيقيّ، **بعد أن يكون البناءُ
   * والنشرُ قد نجحا.**
   *
   * **فيُشترط مضيفٌ فيه نقطة** — وهو أضعفُ ما يميّز عنواناً عامّاً من اسمٍ
   * داخليّ. **و`localhost` يُستثنى** لبناءٍ محلّيٍّ للتجربة.
   */
  let host = "";
  try {
    host = new URL(/^https?:\/\//i.test(raw) ? raw : `https://${raw}`).hostname;
  } catch {
    throw new Error(`NEXT_PUBLIC_API_URL ليس عنواناً صالحاً: ${raw}`);
  }
  if (!host.includes(".") && host !== "localhost") {
    throw new Error(
      `NEXT_PUBLIC_API_URL يشير إلى اسمٍ داخليٍّ لا يعرفه المتصفّح: ${raw} — ` +
        "اكتب العنوانَ العامَّ كاملاً (مثل https://api.rahalgo.com).",
    );
  }
}

const nextConfig: NextConfig = {
  transpilePackages: ["@rahalgo/ui", "@rahalgo/i18n"],
  env: {
    NEXT_PUBLIC_API_URL: API,
    NEXT_PUBLIC_SITE_URL: SITE,
  },
};

export default nextConfig;
