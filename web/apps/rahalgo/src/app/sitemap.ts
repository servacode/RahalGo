import type { MetadataRoute } from "next";
import { readServerConfig, serverApiBase } from "@/lib/config";

const SITE = () => readServerConfig().siteUrl;
// **ويُقرأ عند الطلب لا عند البناء** — دورةُ ٧١و.
// **والجلبُ بالعنوان الداخليّ** — **والعامُّ لا يُبلَغ من داخل
// الحاوية**: **قِيس أنّ الخريطةَ تُولَّد بلا أقسامٍ لهذا السبب.**
const API = () => serverApiBase();

/**
 * **ويُولَّد عند الطلب لا عند البناء** (دورةُ ٧١و-ر٢).
 *
 * **و`sitemap.ts` كسابقِه لا يخضع لـ`force-dynamic` التخطيط** — فكان
 * يُخبَز في الحزمة و`<loc>` فارغةٌ لأنّ `siteUrl` خاليةٌ وقتَ البناء.
 * **وكان `fetch` فيه يُعيد توليدَه بعد ساعة فيُشفى** — **وشفاءٌ بعد
 * ساعةٍ ليس صحّةً**: أوّلُ زائرٍ بعد النشر يقرأ الفارغَ.
 */
export const dynamic = "force-dynamic";

/**
 * **خريطةُ الموقع** — الرئيسيةُ وأقسامُ السوق.
 *
 * # ولماذا لا متاجرَ فيها
 *
 * **كانت تنشر `‎/m/{id}` لكلّ متجرٍ فعّال** — أي أنّها تُسلّم لغوغل قائمةَ
 * مطاعمِنا بأسمائها وصفحاتِها. **والمتاجرُ مخفيّةٌ عن الزبون بالكامل**:
 * المنصةُ سوقٌ يجلب منها، **وهو يشتري «من رحّال» لا «من مطعم فلان».**
 * (قرارُ المالك ٢٠٢٦-٠٨-٠٥.)
 *
 * **وحجبٌ في الشاشة تنقضه خريطةُ الموقع حجبٌ لم يقع**: الصفحاتُ كانت
 * مهجورةً لا يربط إليها شيء، **والخريطةُ وحدَها كانت تفتحها للعالم** —
 * ثمّ تُفهرَس فتُقرأ من البحث مباشرةً.
 *
 * # وما يُنشر بدلاً منها
 *
 * **أقسامُ السوق** (`‎/s/{id}`) — وهي ما يتصفّحه الزبونُ فعلاً في الرئيسية،
 * **فالمنشورُ يطابق المعروض.**
 */
export default async function sitemap(): Promise<MetadataRoute.Sitemap> {
  const entries: MetadataRoute.Sitemap = [
    { url: SITE(), changeFrequency: "daily", priority: 1 },
    // ══════════════════════════════════════════════════════════════════
    // **وصفحاتُ المنصّة الثابتة — تُفهرَس وتُقرأ قبل التسجيل**
    // ══════════════════════════════════════════════════════════════════
    //
    // **ووثيقةٌ قانونيةٌ لا يجدها محرّكُ البحث كأنّها غيرُ منشورة** — ومن
    // بحث عن اسم المنصّة ليطمئنّ لم يجد شروطَها.
    //
    // **وغوغل بلاي يطلب رابطاً عامّاً لسياسة الخصوصيّة** — ورابطٌ لا
    // يُفهرَس يُقبل، **لكنّ المراجعَ البشريَّ يفتحه.**
    // ══════════════════════════════════════════════════════════════════
    // **ومركزُ التنزيل يُفهرَس** (`DLC`، ٢٠٢٦-٠٩-١٣)
    // ══════════════════════════════════════════════════════════════════
    //
    // **وهو بابُ التوزيع الرسميُّ** — **ومن بحث عن «تطبيق رحّال غو»
    // يجب أن يجد صفحتَنا لا نسخةً مرفوعةً في موقعٍ آخر.**
    //
    // **ولا مجلَّدَ آثارٍ في الخريطة**: **الآثارُ تُخدَم من المحرّك
    // بمفاتيحها** — **ولا مجلَّدَ يُعلَن ولا يُستعرَض.**
    ...["shop", "about", "contact", "join", "help", "terms", "privacy", "delete-account",
      "download", "download/customer", "download/driver", "download/merchant",
      "download/rep"].map((path) => ({
      url: `${SITE()}/${path}`,
      changeFrequency: "monthly" as const,
      priority: 0.5,
    })),
  ];
  try {
    // **ولا تخزينَ للجلب** — **وخزنُ ساعةٍ يناقض توليدَ الطلب**: الأثرُ
    // الواحدُ يخدم بيئتين، **فجسمٌ محفوظٌ من بيئةٍ قد يُخدَم في أخرى.**
    // (وزوّارُ هذا المسار زحّافاتٌ لا بشر، فالكلفةُ لا تُذكر.)
    //
    // **وبمهلةٍ صريحة** — **ومهلةُ الاتّصال الافتراضيّةُ عشرُ ثوانٍ**،
    // **فمحرّكٌ لا يُجاب يكلّف عشراً في كلّ طلب.** (قِيس: ١٠٫٥ ثانيةٍ
    // على التجهيز مقابل ٠٫٠١٥ للأثر المخبوز — **فالتوليدُ عند الطلب
    // بلا مهلةٍ يورث كلفةَ المحرّك لكلّ زحّاف.**)
    const res = await fetch(`${API()}/api/v1/public/home`, {
      cache: "no-store",
      signal: AbortSignal.timeout(3000),
    });
    // **ولا يُحلَّل جسمٌ لم يُقَل إنّه جوابٌ** — **ومن جلب ولم يسأل أوصل
    // لا يفرّق بين «لم أصل» و«لا أقسامَ عندي».** وجسمُ خطأٍ ليس JSON.
    if (!res.ok) return entries;
    const json = (await res.json()) as { data?: { sections?: { id: string }[] } };
    for (const s of json.data?.sections ?? []) {
      entries.push({
        url: `${SITE()}/s/${s.id}`,
        changeFrequency: "daily",
        priority: 0.8,
      });
    }
  } catch {
    /* المحرّكُ غيرُ متاحٍ وقتَ الطلب — الرئيسيةُ والصفحاتُ الثابتة تكفي */
  }
  return entries;
}
