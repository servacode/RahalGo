/**
 * ══════════════════════════════════════════════════════════════════════
 * **حذفُ الحساب — صفحةٌ عامّةٌ يفتحها من لا يملك التطبيق**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (قرارُ المالك ٢٠٢٦-٠٨-١٣: «نبدأ بالإغلاق واحدةً تلو الأخرى» —
 *  والخامسة: شرطا غوغل.)
 *
 * # لماذا تلزم
 *
 * **غوغل بلاي تشترط رابطاً عامّاً لحذف الحساب** — يُكتب في بطاقة
 * التطبيق، **ويُفتح بلا تسجيل دخولٍ وبلا تثبيت التطبيق.**
 *
 * **ومن حذف التطبيقَ من هاتفه لم يحذف حسابَه** — وهو أكثرُ ما يظنّه
 * الناس. **فيبقى رقمُه عندنا وهو يحسبه ذهب.**
 *
 * # وتقول ما يُحذف وما يبقى — بلا تجميل
 *
 * **الاسمُ والرقمُ يذهبان، ودفترُ المال يبقى بلا ما يدلّ عليه.** وهذا
 * ما يفعله المحرّكُ فعلاً (`identity/deletion.go`: `AnonymizeUser`) —
 * **ولا تُكتب هنا وعودٌ لا تطابق الشيفرة.**
 *
 * **وحذفُ الدفتر يمحو حقوقَ سائقين ومتاجرَ في مبالغَ تمّت** — فيُقال
 * ذلك صراحةً، **لا يُخفى في سطرٍ صغير.**
 *
 * # وشروطٌ تمنعه — تُقال قبل أن تُفاجئ
 *
 * **من له رصيدٌ أو نقدٌ في ذمّته أو طلبٌ مفتوحٌ لا يُحذف حسابُه** —
 * والمحرّكُ يمنعه. **ومن لم يُقَل له ذلك يظنّ العطبَ في الموقع.**
 */

import { getMessages, defaultLocale } from "@rahalgo/i18n";
import { LegalPage, type Block } from "../legal/LegalPage";
import { getContact } from "../legal/contact";

const m = getMessages(defaultLocale);
const L = m.site.legal;


export default async function Page() {
  const contact = await getContact();
  return (
    <LegalPage
      kind="privacy"
      title={L.deleteTitle}
      subtitle={L.deleteSubtitle}
      blocks={L.deleteAccount as Block[]}
      contact={contact}
    />
  );
}
