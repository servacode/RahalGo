import { fetchPlatform } from "@rahalgo/ui";
import { CartProvider } from "@/lib/cart";
import Header from "@/components/Header";
import Footer from "@/components/Footer";
import { FloatingCart } from "@/components/FloatingCart";
import { CustomerChat } from "@/components/CustomerChat";
import RatingWatcher from "@/components/RatingWatcher";
import { BottomNav, BottomNavSpacer } from "@/components/BottomNav";

const API = process.env.NEXT_PUBLIC_API_URL ?? "http://localhost:8080";

/**
 * ══════════════════════════════════════════════════════════════════════
 * **غلافُ السوق — لمن يتسوّق وحدَه**
 * ══════════════════════════════════════════════════════════════════════
 *
 * **كان هذا كلُّه في الغلاف الجذر** حين كان الزبونُ تطبيقاً وحدَه. **ومع
 * البابِ الواحد صارت اللوحاتُ جيرانَه**، ولوحةُ الإدارة لا تحتاج سلّةً ولا
 * شريطَ سوقٍ ولا فقّاعةَ محادثةٍ مع سائق.
 *
 * **و`(site)` مجموعةُ مسارٍ لا مسار** — القوسان يعنيان أنّها لا تظهر في
 * العنوان: **`/shop` تبقى `/shop`**، ولا يصير `/site/shop`. فلا رابطٌ
 * ينكسر ولا عنوانٌ يتبدّل على من حفظه.
 *
 * **والسلّةُ هنا لا في الجذر**: سائقٌ يفتح لوحتَه لا يحمل سلّةً، **ومزوّدٌ
 * يُركَّب لمن لا يستعمله يُحمَّل في حزمته بلا سبب.**
 */
export default async function SiteLayout({ children }: { children: React.ReactNode }) {
  const brand = await fetchPlatform(API);
  return (
    <CartProvider>
      {/* **ولا حشوةَ يميناً ويساراً** — (قاعدةُ المالك، قالها أربعَ
          مرّات): الصفحةُ تأخذ العرضَ كاملاً. **والعموديُّ في `main`
          وحدَه** لأنّ الشريطَ والفوترَ شريطان يبلغان الحافّة. */}
      <div className="flex min-h-screen flex-col">
        <Header />
        {/* **وفسحةٌ علويّةٌ بمقدار ما يتدلّى من الشعار.**

            (كشفه المالك ٢٠٢٦-٠٨-٠٩ بلقطتين: الشعارُ يلامس بطاقةَ
             الدخول ثمّ لافتةَ التسوّق.)

            **ونصفُ الشعار ينزل تحت الشريط** (٥٦ بكسلاً) — **وما تحته
            يبدأ حيث ينتهي الشريطُ لا حيث ينتهي المتدلّي**، فيقع عليه.

            **والفسحةُ هنا لا في كلّ صفحة**: خمسُ صفحاتٍ تُصلَح واحدةً
            واحدةً تُنسى السادسة.

            **ومقدارُها المتدلّي وحشوةُ الصفحة، ويتبع مقاسَ الشعار**:
            على الجوّال ٣٢+١٦=٤٨، وفوقه ٥٦+١٦=٧٢. **وثلاثةُ أرقامٍ
            مرتبطة** — الشعارُ ونصفُه والفسحة، **ومن بدّل واحداً بدّل
            الثلاثة.** */}
        <main className="flex min-w-0 flex-1 flex-col px-3 pb-4 pt-12 sm:px-4 sm:pt-[4.5rem]">
          {children}
        </main>
        {/* **والشروطُ والمساعدةُ أسفلَ الصفحة** — حيث يُبحث عنها،
            والشريطُ العلويُّ لما يُضغط كلَّ يوم. */}
        <Footer name={brand.name} social={brand.social} />
        {/* السلّة العائمة خارج الكرت: تُرافق التصفّح ولا تختفي بالتمرير */}
        <FloatingCart />
        {/* **وفقّاعةُ المحادثة عند الزبون كما عند السائق** — (قرارُ
            المالك ٢٠٢٦-٠٨-٠٩: «يجب أن تظهر أيقونة المحادثة عند الطرفين
            ليبقى كرت الطلبات نظيفاً عند السائق وعند الزبون»).

            **وهي تُخفي نفسَها إن لم يكن له طلبٌ بسائق.** */}
        <CustomerChat />
        {/* **ونافذةُ التقييم تُسأل حيث كان الزبون** — لا في صفحة
            الطلبات وحدَها. (قرارُ المالك ٢٠٢٦-٠٨-٠٩.) */}
        <RatingWatcher />
        {/* **وفراغٌ بارتفاع الشريط السفليّ** — وبلاه يختفي آخرُ سطرٍ
            خلفه، وهو غالباً زرُّ الحسم. */}
        <BottomNavSpacer />
      </div>
      {/* **أقسامُ الزبون حيث يصل الإبهام** — على الجوّال وحدَه.
          (خارجَ غلاف الحشوة لأنّه يلتصق بحافّة الشاشة.) */}
      <BottomNav />
    </CartProvider>
  );
}
