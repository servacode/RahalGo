const m = getMessages(defaultLocale);

/**
 * ══════════════════════════════════════════════════════════════════════
 * **والعنوانان يُقرآن عند الطلب لا عند البناء** (دورةُ ٧١و)
 * ══════════════════════════════════════════════════════════════════════
 *
 * **وكانا ثابتين على مستوى الملفّ من `NEXT_PUBLIC_*`** — **فيُخبَزان
 * في الحزمة**، **فصورةُ التجهيز لا تعرف عنوانَ الإنتاج أصلاً** وقِيس
 * ذلك: صفرُ ذكرٍ لـ`api.rahalgo.com` في حزمة التجهيز.
 *
 * **فصارا دالّتين تُنادَيان داخلَ ما يُنفَّذ عند الطلب** — والقيمةُ من
 * بيئة الحاوية.
 */

/**
 * **وعنوانُ الصفحة من الإعدادات لا من المعجم.**
 *
 * (قاعدةُ المالك: «لا أريد أن تكتب اسمَ المنصة بأيّ مكانٍ أبداً».)
 *
 * **وكان مكتوباً في المعجم** — فمن بدّل الاسمَ من اللوحة بدّل الشريطَ
 * والشعار، **وبقي عنوانُ التبويب يقول الاسمَ القديم.**
 *
 * **و`generateMetadata` لا ثابتٌ**: الأوّلُ يُنادى لكلّ طلبٍ فيقرأ الإعدادَ
 * الحيّ، **والثابتُ يُحسب مرّةً عند البناء فيتجمّد.**
 */
/**
 * ══════════════════════════════════════════════════════════════════════
 * **ولا توليدَ ساكنٌ لما يقرأ بيئةَ التشغيل** — دورةُ ٧١و
 * ══════════════════════════════════════════════════════════════════════
 *
 * # وهذا ثمنُ «أثرٍ واحدٍ لكلّ بيئة» — يُدفَع صراحةً
 *
 * **والتوليدُ الساكنُ يقع وقتَ البناء** — **فيلزمه أن يعرف البيئةَ
 * حينها**، وهو عينُ ما أُغلق. **وقِيس**: بلا هذا سقط البناءُ على
 * `/sso` لأنّ `metadataBase` و`fetchPlatform` بلا عنوان.
 *
 * **ولا يُحَلُّ بارتدادٍ إلى عنوانٍ افتراضيّ** — **ذاك يُخبز هويّةَ
 * بيئةٍ من جديد، وهو العطبُ بعينه.**
 *
 * # وما ثمنُه بالضبط
 *
 * **صفحاتُ الموقع تُحسَب عند كلّ طلبٍ بدل أن تُخدَم من توليدٍ سابق.**
 * **والحركةُ اليومَ ضئيلةٌ مقيسةً** (٤٫٢ طلبٍ في الدقيقة في أساس ٦٩ب)،
 * **والبوّابةُ تضغط وتخزّن الأصولَ الساكنة** — فالثمنُ محتملٌ اليومَ.
 * **ومن أراد التوليدَ الساكنَ مع أثرٍ واحدٍ نقلَ الوسومَ الوصفيّةَ
 * كلَّها إلى العميل** — وذاك عملٌ آخرُ يُقاس أوّلاً.
 */
export const dynamic = "force-dynamic";

export async function generateMetadata(): Promise<Metadata> {
  const { apiUrl: API, siteUrl: SITE } = readServerConfig();
  const brand = await fetchPlatform(API);
  const name = brand.name || m.common.appName;
  const title = withPlatform(m.site.appTitle, name);
  const description = withPlatform(m.site.appDescription, name);
  return {
    metadataBase: new URL(SITE),
    // ══════════════════════════════════════════════════════════════
    // **وعنوانُ التبويب اسمُ المنصّة في كلّ صفحة**
    // ══════════════════════════════════════════════════════════════
    //
    // (قرارُ المالك ٢٠٢٦-٠٨-١٥: «اتركها فقط رحّال غو بكلّ الصفحات».)
    //
    // **وكان قالباً يُلحق الاسمَ بعنوان الصفحة** (`تواصل معنا | رحّال
    // غو`) — **وعنوانُ التبويب يُقرأ في شريطٍ ضيّقٍ فيه عشرُ تبويبات**:
    // ما يزيد على كلمتين يُقصّ، **فيبقى الجزءُ الذي لا يدلّ.**
    //
    // **والاسمُ وحدَه يُعرف من حرفه الأوّل.**
    title: { default: name, template: `${name}` },
    /* ══════════════════════════════════════════════════════════════
       **وأيقونةُ التبويب شعارُ المنصّة لا مربّعٌ مرسوم**
       ══════════════════════════════════════════════════════════════

       (طلبُ المالك ٢٠٢٦-٠٨-١٧: «اللوغو يجب أن يظهر جانبَ اسم الصفحة
        بالأعلى».)

       **وكانت `icon.svg` مربّعاً بحرف «ر»** كُتب يومَ لم يكن للمنصّة
       شعار — **ومن رفع شعارَه من اللوحة بقي تبويبُه يحمل مربّعاً
       رسمَه غيرُه.**

       **وتُقرأ من الإعدادات في كلّ طلب** كسائر الهويّة: من بدّل الشعارَ
       بدّل أيقونتَه معه بلا نشر.

       **وتسقط إلى المرسومة إن لم يُرفع شعار** — تبويبٌ بلا أيقونةٍ
       يُقرأ صفحةً مجهولة. */
    icons: brand.logo
      ? { icon: API + brand.logo, apple: API + brand.logo }
      : undefined,
    description,
    openGraph: { title, description, siteName: name, locale: "ar_SY", type: "website" },
  };
}

/**
 * ══════════════════════════════════════════════════════════════════════
 * **الغلافُ الجذر — ما يشترك فيه كلُّ من يفتح المنصّة**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (قرارُ المالك ٢٠٢٦-٠٨-١٠: «يجب أن يكون بابٌ واحدٌ للجميع وشاشةُ تسجيلٍ
 *  واحدةٌ للجميع بدون استثناء».)
 *
 * # ولماذا لا يعرف هذا الغلافُ الزبونَ
 *
 * **كان يحمل السلّةَ والشريطَ والفوترَ وفقّاعةَ المحادثة** — لأنّه كان
 * غلافَ تطبيق الزبون وحدَه. **والآن تسكن اللوحاتُ الخمسُ تحته**، وشريطُ
 * سوقٍ فوق لوحة الإدارة **عبثٌ يراه صاحبُه عطباً.**
 *
 * **فما يبقى هنا ثلاثةٌ لا رابعَ لها**:
 *
 *   - **هويّةُ المنصّة** — تُقرأ في الخادم مرّةً لكلّ صفحة، فتصل مع أوّل
 *     بايت ولا تومض العلامةُ فارغةً ثمّ تمتلئ. **وفشلُ جلبها لا يُسقط
 *     الموقع**: الاسمُ يسقط إلى المعجم والشعارُ إلى الحرف.
 *   - **الجلسة** (`AuthProvider`) — يقرؤها كلُّ دور.
 *   - **بوّابةُ الكلمة المؤقّتة** — من أعادت الإدارةُ تعيينَ كلمته يُجبَر
 *     على تبديلها **أيَّ دورٍ كان**. وكانت في أربع لوحاتٍ وتُنسى الخامسة —
 *     **وهنا لا تُنسى واحدة.**
 *
 * **وما عداه ينزل إلى غلاف قسمِه**: `(site)` للسوق، ولكلّ لوحةٍ غلافُها.
 */
/**
 * ══════════════════════════════════════════════════════════════════════
 * **ومسارُ الصورة يُنقّى قبل أن يُكتب في ورقةِ أنماط**
 * ══════════════════════════════════════════════════════════════════════
 *
 * **نصٌّ من الإعدادات يُحقن في `<style>` يخرج من حدّه** بحرفٍ واحدٍ
 * (`")}`) — **ولا يشفع أنّ الذي يرفعه هو المالك**: الإعدادُ يُقرأ من
 * قاعدةٍ تُنسخ وتُستعاد وتُعدَّل بيدٍ خارج الشاشة.
 *
 * **فما ليس مسارَ وسيطٍ لا يُكتب أصلاً.**
 */
function mediaHref(path: string | null | undefined): string | null {
  if (!path || !/^\/media\/[A-Za-z0-9/._-]+$/.test(path)) return null;
  // **والعنوانُ يُقرأ عند النداء** — دورةُ ٧١و.
  return readServerConfig().apiUrl + path;
}

export default async function RootLayout({ children }: { children: React.ReactNode }) {
  const { apiUrl: API } = readServerConfig();
  const brand = await fetchPlatform(API);

  // ══════════════════════════════════════════════════════════════════
  // **والخلفيّةُ تبدأ في التحميل مع أوّل بايتٍ من الصفحة**
  // ══════════════════════════════════════════════════════════════════
  //
  // (شكوى المالك ٢٠٢٦-٠٨-١٦: «يجب أن يتمّ تحميلها بسرعة رغم ضعف
  //  الإنترنت — يعني ما تتأخّر بالتحميل».)
  //
  // **وكانت تنتظر أربعَ خطوات**: الورقةُ ثمّ حزمةُ الجافاسكربت ثمّ
  // إحياءُ رياكت ثمّ نداءُ الإعدادات — **ثمّ** يبدأ تحميلُ الصورة.
  // **وعلى شبكةٍ ضعيفةٍ ذلك ثوانٍ قبل أوّل بايتٍ منها.**
  //
  // **والخادمُ يعرف مسارَها أصلاً** — يقرأ الهويّةَ لكلّ صفحة. **فتُكتب
  // في الورقة نفسِها**: المتصفّحُ يراها وهو يحلّل الترويسة، فيبدأ
  // التحميلَ قبل أن يصل إلى الجسم.
  //
  // **و`preload` فوق الإعلان**: الإعلانُ في `<style>` لا يبدأ تحميلاً حتّى
  // يُطابَق العنصرُ الذي يستعمله، **والوسمُ يبدأ فوراً.**
  const bg = mediaHref(brand.siteBg);
  const bgMobile = mediaHref(brand.siteBgMobile);
  // **ونسخةُ الجوّال إن لم تُرفع لا تُكتب `none`** — **والثيمُ يسقط إلى
  // العريضة بنفسه** (`var(--site-bg-mobile, var(--site-bg, none))`).
  // **وكتابةُ `none` تمنع السقوطَ فيبقى الجوّالُ بلا خلفيّةٍ أصلاً** —
  // وهي الشاشةُ التي يفتح منها أكثرُ الناس.
  /* **واللمحةُ تُرسم تحت الصورة في أوّل رسمة** — (طلبُ المالك
     ٢٠٢٦-٠٨-١٧): **وهي نصٌّ في الورقة نفسِها، فلا رحلةَ لها.**

     **وترتيبُ الطبقتين: الصورةُ فوق اللمحة** — فإذا وصلت غطّتها بلا
     وميض. */
  const blur = brand.siteBgBlur && brand.siteBgBlur.startsWith("data:image/")
    ? brand.siteBgBlur
    : "";
  const bgCss = bg
    ? `:root{--site-bg:${blur ? `url("${bg}"),url("${blur}")` : `url("${bg}")`};` +
      (bgMobile ? `--site-bg-mobile:url("${bgMobile}");` : "") +
      `--site-bg-dim:${brand.siteBgDim / 100}}`
    : "";

  return (
    <html lang={defaultLocale} dir={getDir(defaultLocale)}>
      {bg && (
        <head>
          <link rel="preload" as="image" href={bg} fetchPriority="high" />
          <style dangerouslySetInnerHTML={{ __html: bgCss }} />
        </head>
      )}
      <body className="flex min-h-screen flex-col">
        {/* ══════════════════════════════════════════════════════════
            **تهيئةُ البيئة قبل أيّ شيفرةِ عميل** (دورةُ ٧١و)
            ══════════════════════════════════════════════════════════

            **ومسارٌ لا قيمةٌ مكتوبةٌ هنا**: **هذه الصفحةُ قد تُولَّد
            ساكنةً وقتَ البناء**، **فقيمةٌ فيها تُخبَز** — وهو عينُ
            العطب. **والمسارُ يُنفَّذ عند كلّ طلبٍ ولا يُخزَّن.**

            **و`beforeInteractive` تضمن سبقَه لكلّ مكوّنٍ يقرأه.** */}
        <Script src="/config.js" strategy="beforeInteractive" />
        <PlatformProvider apiBase={API} initial={brand}>
          <AuthProvider>
            {/* **ولا تمسّ زائراً**: من لا حسابَ له يمرّ، ومن لا علَمَ عليه
                يمرّ — **والمحرّكُ يُقنّع العلَمَ حين يكون الخيارُ مُطفأً**
                (`security.force_password_change`، مُطفأٌ افتراضاً بقرار
                المالك)، فلا سطرَ هنا يقرأ إعداداً. */}
            {/* **ونافذةُ تأكيدِ الفعل الشديد** — `ADG-3`. **واحدةٌ
                للوحة كلِّها**: يعترض عميلُ الـAPI طلبَ الخادم فتُسأل
                الكلمةُ مرّةً ثمّ يُعاد النداءُ بإثباته. **والحدُّ في
                الخادم لا هنا.** */}
            <StepUpGate />
            <PasswordGate>{children}</PasswordGate>
          </AuthProvider>
        </PlatformProvider>
      </body>
    </html>
  );
}
