/**
 * ══════════════════════════════════════════════════════════════════════
 * **`/config.js` — تهيئةُ البيئة تُقرأ عند كلّ طلب**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (دورةُ ٧١و.)
 *
 * # ولماذا مسارٌ لا وسمٌ في التخطيط
 *
 * **وصفحاتُ الموقع العامّ تُولَّد ساكنةً وقتَ البناء** — **فوسمُ
 * `<script>` فيه قيمةٌ يُخبَز فيه ما في البيئة لحظةَ البناء**، وهو
 * عينُ العطب الذي نُغلقه.
 *
 * **والمسارُ يُنفَّذ عند كلّ طلب** (`force-dynamic`) — **فيقرأ بيئةَ
 * الحاوية العاملة**، فتصلح الصورةُ الواحدةُ لبيئتين.
 *
 * # ولا يُخزَّن
 *
 * **وتهيئةٌ تُخزَّن تصير تهيئةَ بيئةٍ أخرى بعد نشر** — **أو تبقى
 * تهيئةَ أمسِ في متصفّحٍ فتحه صاحبُه اليوم.** فـ`no-store`.
 *
 * **وهو ملفٌّ صغيرٌ يُطلَب مرّةً لكلّ صفحة** — **وبقيّةُ الأصول تبقى
 * مخزَّنةً كما هي**، فلا يُدفَع ثمنٌ في السرعة.
 *
 * # والفشلُ مغلق
 *
 * **وما نقص من الواجب يُعلَن في المتغيّر نفسِه** — **ولا يُخترَع
 * عنوانٌ ولا يُرتَدُّ إلى `localhost`.** **ومن ارتدّ صامتاً وجّه
 * عميلَ إنتاجٍ إلى تجهيز**، ونداءاتٌ حقيقيّةٌ تذهب إلى قاعدةٍ أخرى
 * ولا يعلم أحد.
 */

import {
  CONFIG_GLOBAL,
  missingConfig,
  readServerConfig,
} from "@/lib/config";

// **ولا توليدَ ساكنٌ لهذا المسار** — وإلّا خُبزت فيه بيئةُ البناء.
export const dynamic = "force-dynamic";
export const revalidate = 0;

export function GET() {
  const cfg = readServerConfig();
  const missing = missingConfig(cfg);

  // **والنقصُ يُحمَل في التهيئة نفسِها** — **فتقرؤه الواجهةُ وتُظهر
  // حالَ عطبٍ معلَناً**، ولا تمضي إلى عنوانٍ مخترَع.
  const payload = missing.length > 0 ? { ...cfg, missing } : cfg;

  const body =
    `window.${CONFIG_GLOBAL}=Object.freeze(${JSON.stringify(payload)});`;

  return new Response(body, {
    // **وحالُ الردّ يقول ما وقع** — ٥٠٠ لتهيئةٍ ناقصةٍ، **فيظهر في
    // سجلّ البوّابة ولا يحتاج أحداً ينظر إلى شاشة.**
    status: missing.length > 0 ? 500 : 200,
    headers: {
      "Content-Type": "application/javascript; charset=utf-8",
      "Cache-Control": "no-store, must-revalidate",
    },
  });
}
