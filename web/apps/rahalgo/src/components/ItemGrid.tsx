"use client";

/**
 * **شبكةُ الأصناف** — شكلٌ واحدٌ لكلّ مكانٍ يُعرض فيه صنف.
 *
 * # لماذا وُجدت
 *
 * `ItemCard` بطاقةٌ واحدةٌ موحَّدة، **لكنّ قلبَ المفضّلة يحتاج قائمةً**:
 * `useFavorites` نداءٌ واحدٌ للصفحة، **وبطاقةٌ تجلب مفضّلتَها بنفسها تعني
 * عشرين نداءً في شبكةٍ من عشرين بطاقة.**
 *
 * **فالشبكةُ تحمل القائمةَ والبطاقاتُ تقرأ منها.**
 *
 * # وصفحةُ القسم خادميّة
 *
 * **و`useFavorites` خطّافٌ لا يعمل في الخادم** — فهذه غلافُها العميل.
 *
 * # وأعمدتُها أعمدةُ الأقسام
 *
 * **من فتح قسماً لا يجد الشبكةَ تغيّرت تحته.** (قرارُ المالك ٢٠٢٦-٠٨-٠٤:
 * «شكلُ العرض للأصناف يجب أن يكون موحّداً».)
 */

import { useRouter } from "next/navigation";
import { useFavorites } from "@rahalgo/ui";
import ItemCard, { type BrowseItem } from "@/components/ItemCard";
import { api } from "@/lib/api";
import { useAuth, isLoggedIn } from "@/lib/auth";

export default function ItemGrid({
  items,
  /** إلى أين يعود بعد الدخول — **ومن ساقه زرٌّ يعود إلى حيث كان.** */
  next = "/",
  favorites,
}: {
  items: BrowseItem[];
  next?: string;
  /**
   * **قائمةٌ جاهزةٌ حين تكون هي المعروضة** — صفحةُ المفضّلة تعرض ما حُفظ،
   * **فلو جلبته الشبكةُ ثانيةً لَصارتا نسختين**: يُنزع القلبُ عن صنفٍ
   * **فتُحدَّث نسخةُ الشبكة وتبقى البطاقةُ معروضة.**
   */
  favorites?: ReturnType<typeof useFavorites<BrowseItem>>;
}) {
  const router = useRouter();
  const { user } = useAuth();
  const signedIn = isLoggedIn(user);
  // **ولا تُجلب مرّتين**: حين تُمرَّر القائمةُ يُعطَّل الجلبُ هنا — **والخطّافُ
  // يُنادى دائماً** لأنّ ترتيبَ الخطّافات لا يحتمل شرطاً.
  const own = useFavorites<BrowseItem>(api, signedIn && !favorites);
  const { has, toggle } = favorites ?? own;

  return (
    /* ══════════════════════════════════════════════════════════════════
       **البطاقةُ لها عرضٌ مقصود — والأعمدةُ تتبعه**
       ══════════════════════════════════════════════════════════════════

       (قرارُ المالك ٢٠٢٦-٠٨-٠٦: «حجم المنتج ما زال كبير — يجب أن يكون أصغر
       بشكلٍ مناسبٍ وأنيقٍ واحترافيّ».)

       # ولماذا كان كبيراً

       **الصفحةُ بلا حدِّ عرض** (قاعدةُ المالك: لا حشوةَ يميناً ويساراً،
       والمحتوى يملأ الشاشة). **فعددٌ ثابتٌ من الأعمدة يعني بطاقةً تكبر بكبر
       الشاشة بلا حدّ**:

           عرضُ الشاشة    ٤ أعمدة    ٦ أعمدة
           ٩٦٠            ٢٢٢        ١٤٣
           ١٤٤٠           ٣٤٢        ٢٢٣
           ١٩٢٠           **٤٦٢**    ٣٠٣

       **وأربعُمئةٍ واثنتان وستّون بكسلاً لبطاقة شاورما** — نصفُ الشاشة لصنفٍ
       واحد. وهو ما رآه المالك.

       # والحلُّ أن يُقاس ما يجب أن يُقاس

       **العرضُ المقصودُ للبطاقة هو القرار، لا عددُ الأعمدة.** فيُقال للشبكة:
       «كلُّ بطاقةٍ لا تقلّ عن ١٧٦ ولا تزيد عن نصيبها» — **وهي تحسب العددَ
       بنفسها في كلّ شاشة**، من هاتفٍ بثلاثمئةٍ إلى شاشةٍ بألفين.

       **فلا سُلَّمَ نقاطِ قياسٍ يُخمَّن ولا شاشةَ تُنسى** — والأرقامُ تصير:

           ٣٩٠  → عمودان بـ١٧٥
           ٧٦٨  → أربعةٌ بـ١٧٤
           ١٤٤٠ → ثمانيةٌ بـ١٦٣
           ١٩٢٠ → عشرةٌ بـ١٧٦

       **و`auto-fill` لا `auto-fit`**: الثانيةُ تمدّ البطاقاتِ لتملأ الصفَّ
       حين تقلّ، **فصنفان في قسمٍ يصيران بطاقتين بعرض نصف الشاشة.** والأولى
       تُبقي مقاسَها وتترك الفراغَ.
       ══════════════════════════════════════════════════════════════════ */
    /* ══════════════════════════════════════════════════════════════
       **وثلاثةُ أصنافٍ في سطر الجوّال — لا واحد**
       ══════════════════════════════════════════════════════════════

       (قرارُ المالك ٢٠٢٦-٠٨-١١: «الصنفُ بالجوّال كبيرٌ جدّاً، مو معقول
        الصفحةُ كلُّها ما تاخذ بس نوعَ صنفٍ واحد — لازم ٣ أصنافٍ جنبَ بعض.
        مشروعُنا راح يكون على الجوّال أكثر».)

       **وقِيس**: `minmax(11rem)` = ١٧٦ بكسلاً. على عرض ٣٦٠ — بعد حشوة
       الصفحة — **يسع صنفٌ واحدٌ فقط**، وعلى ٣٩٠ اثنان. **فيصير التصفّحُ
       تمريراً بلا نهاية**، ومن يريد المقارنةَ بين صنفين لا يراهما معاً.

       **و٦٫٥rem تسع ثلاثةً على أضيق شاشة** — ثمّ تكبر الخانةُ وحدَها
       بالشاشة، **فلا يُكتب مقاسٌ لكلّ عرض.**

       **والحاسوبُ لا يتأثّر**: `auto-fill` يملأ ما اتّسع، **وأربعةٌ أو
       خمسةٌ في السطر كما كانت.** */
    <div className="grid grid-cols-[repeat(auto-fill,minmax(6.5rem,1fr))] gap-2 sm:grid-cols-[repeat(auto-fill,minmax(11rem,1fr))] sm:gap-4">
      {items.map((it) => (
        <ItemCard
          key={it.id}
          item={it}
          favorite={has(it.id)}
          onFavorite={signedIn ? toggle : undefined}
          onRequireLogin={
            signedIn ? undefined : () => router.push("/app")
          }
        />
      ))}
    </div>
  );
}
