"use client";

/**
 * **أقسامُ الزبون أسفلَ الشاشة** — على الجوّال وحدَه.
 *
 * # ولماذا هذه الأربعة
 *
 * رحلةُ الزبون أربعُ محطّاتٍ لا أكثر:
 *
 *	تصفّحٌ  ←  طلبٌ  ←  تتبّعٌ  ←  عودةٌ إلى ما أحبّ
 *
 * **والرئيسيّةُ والطلباتُ يوميّتان**، والمفضّلةُ هي ما يختصر التصفّحَ في
 * المرّة القادمة، والحسابُ بابُ المحفظة والعناوين.
 *
 * **وما بقي في الشريط العلويّ**: الإشعاراتُ والرصيدُ والعروضُ والدعوةُ
 * والشكاوى — **تُفتح مرّةً في الأسبوع، ولا تستحقّ ثُمنَ الشاشة الدائم.**
 *
 * # والسلّةُ ليست بنداً
 *
 * **هي عربةٌ عائمةٌ بقرار المالك** (`FloatingCart`) — «العربةُ تُلتقط عند
 * الباب لا بعد اختيار أوّل صنف». **فتُرفع فوق الشريط ولا تُستبدل به.**
 *
 * # ولا يظهر لزائرٍ لم يدخل
 *
 * **ثلاثةٌ من أربعةٍ تسوقه إلى الدخول** — وشريطٌ كلُّه أبوابٌ مقفلةٌ يُقرأ
 * حاجزاً لا تنقّلاً. **والزائرُ يتصفّح أوّلاً**، فإن أراد شيئاً ساقه الفعلُ
 * نفسُه إلى الدخول.
 */

import Link from "next/link";
import { usePathname } from "next/navigation";
import { getMessages, defaultLocale } from "@rahalgo/i18n";
import {
  MobileNav,
  MobileNavSpacer,
  usePlatform,
  IconGrid,
  IconStore,
  IconOrder,
  IconChat,
  IconUser,
  IconOverview,
  type NavItem,
} from "@rahalgo/ui";
import { portalFor } from "@rahalgo/auth";
import { useAuth, isLoggedIn } from "@/lib/auth";

const m = getMessages(defaultLocale);

/* ══════════════════════════════════════════════════════════════════
   **وأقسامُ الحساب حُذفت من الويب** — (قرارُ المالك ٢٠٢٦-٠٨-٢٦:
   «كلّ شخص عنده تطبيقه، والويب صار للإدارة وتصفّح الموقع فقط».)

   **وشريطٌ يقود إلى صفحةٍ محذوفةٍ أسوأُ من شريطٍ قصير** — أربعمئةٌ
   وأربعة تُقرأ عطباً في المنصّة لا قراراً فيها. */
const ITEMS: readonly NavItem[] = [
  { href: "/", label: m.site.nav.home, icon: IconGrid },
  { href: "/shop", label: m.site.nav.shop, icon: IconStore },
  { href: "/offers", label: m.customer.offers.title, icon: IconOrder },
  { href: "/app", label: m.site.appGate.title, icon: IconUser },
];

export function BottomNav() {
  const pathname = usePathname();
  const { user } = useAuth();
  const { showShop } = usePlatform();
  if (!user || !isLoggedIn(user)) return null;
  /* ══════════════════════════════════════════════════════════════════
     **و«الرئيسيّة» للزبون، و«لوحتي» لمن له لوحة**
     ══════════════════════════════════════════════════════════════════

     (قرارُ المالك ٢٠٢٦-٠٨-١١: «الرئيسيّةُ تظهر فقط للزبون، أمّا الباقي
      يظهر مكانَها لوحتي — وتختفي من التوب بار. لأنّ الصفحةَ الرئيسيّةَ
      أوّلاً لا تفيد بشيءٍ ولا يوجد بها شيء، والثانية أنّه بالضغط على
      الأيقونة يمكنه الوصولُ إلى الصفحة الرئيسيّة».)

     **وخمسةُ مواضعَ لا سادسَ لها** — عرضُ الهاتف يحكم. **وموضعٌ يذهب إلى
     صفحةٍ يصلها بضغطة على الشعار موضعٌ ضائع.**

     **والسائقُ والمتجرُ والمندوبُ يدخلون السوقَ زبائنَ ويعودون إلى
     عملهم** — **والعودةُ كانت حبّةً في الشريط العلويّ** يزاحمها الجرسُ
     والمحفظةُ والتطبيق. **وهي أكثرُ ما يُضغط عندهم.**

     **والزبونُ لا لوحةَ له** — فتبقى رئيسيّتُه كما هي. */
  /* **و`portalFor` تعيد المسارَ جاهزاً** — و`homeFor` تعيد كائناً فيه
     أصلٌ ومسار. **وكتبتُ `String(homeFor(...))` فصار الرابطُ
     `[object Object]`** — زرٌّ يقود إلى صفحةٍ غيرِ موجودة. (كشفه المالك
     ٢٠٢٦-٠٨-١١ حين سأل: «تحقّق إذا كان زرُّ لوحتي يعمل بشكلٍ صحيح».) */
  const portal = portalFor(user.roles);
  const base: readonly NavItem[] = portal
    ? [
        { href: portal, label: m.site.nav.backToDashboard, icon: IconOverview },
        ...ITEMS.slice(1),
      ]
    : ITEMS;
  /* ══════════════════════════════════════════════════════════════════
     **وبابُ التسوّق يُخفى هنا أيضاً**
     ══════════════════════════════════════════════════════════════════

     (طلبُ المالك ٢٠٢٦-٠٨-١٧: «زرٌّ لإخفاء زرّ تسوّق».)

     **وهو البابُ الأوسعُ لا الأضيق**: أكثرُ الناس يفتحون من الجوّال،
     **وهذا شريطُهم.** **ومن أخفاه من الشريط العلويّ وحدَه لم يُخفِ
     شيئاً** — يبقى في أسفل الشاشة حيث يصل الإبهامُ أوّلاً. */
  const items = showShop ? base : base.filter((i) => i.href !== "/shop");
  return <MobileNav items={items} active={pathname} Link={Link} />;
}

/** الفراغُ تحت المحتوى — **بلاه يختفي آخرُ سطرٍ خلف الشريط.** */
export function BottomNavSpacer() {
  const { user } = useAuth();
  if (!isLoggedIn(user)) return null;
  return <MobileNavSpacer />;
}
