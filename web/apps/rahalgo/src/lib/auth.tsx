"use client";

/**
 * ══════════════════════════════════════════════════════════════════════
 * **حرّاسُ الأدوار — في ملفٍّ واحدٍ لأنّ اللوحاتِ صارت بيتاً واحداً**
 * ══════════════════════════════════════════════════════════════════════
 *
 * (قرارُ المالك ٢٠٢٦-٠٨-١٠: «بابٌ واحدٌ للجميع».)
 *
 * **كانت خمسةَ ملفّاتٍ في خمسة تطبيقات**، كلٌّ يعرّف حارسَ لوحته وحدَها
 * (`canAccessPanel` · `canAccessPortal` · `isRep` · `isDriver`).
 * **وخمسةُ ملفّاتٍ تُقرأ خمسَ قراءاتٍ ولا تُقارَن** — فمن بدّل قاعدةً في
 * واحدٍ لم يعلم أنّ لها أخواتٍ أربعاً.
 *
 * **والمنطقُ كلُّه في `hasRole`** — وهذه أسماءٌ تقول من يدخل أين.
 */

import { hasRole, isWebAuthorized, type AuthUser } from "@rahalgo/auth";

export { AuthProvider, useAuth, isLoggedIn, hasRole } from "@rahalgo/auth";

/**
 * **بابُ اللوحة — قدرةٌ أو دورٌ من القائمة القديمة.**
 *
 * # ما وقع (٢٠٢٦-٠٩-١٢، قِيس في متصفّحٍ على التجهيز)
 *
 * **حسابُ الرصد `customer + observability` رُدَّ إلى `/app`** برسالة
 * «حسابك يُفتح من التطبيق» — **فبابُ القائمة بالقدرة عديمُ الأثر ما
 * دام بابُ اللوحة نفسِه باسم الدور.**
 *
 * `PANEL_ROLES` = `admin · ops · finance` — **ثلاثةُ أسماءٍ مُصرَّفة**،
 * **ودورٌ يُمنَح قدرةً اليومَ لا يدخل حتّى يُكتب اسمُه هنا.**
 *
 * # والقاعدةُ الجامعة
 *
 * **من ملك قدرةً إداريّةً واحدةً دخل القشرةَ** — **وما يراه فيها
 * قدراتُه**، وكلُّ صفحةٍ محروسةٌ في المحرّك على كلّ حال.
 *
 * **ولا يفتح هذا باباً لأحدٍ جديد**: قِيس أنّ `customer` و`driver`
 * و`merchant` و`sales` **صفرُ قدرات** — **والقدرةُ لا تُمنَح إلّا
 * بمسارٍ مخوَّلٍ بتأكيدٍ وقيدِ تدقيق.**
 *
 * **والقائمةُ القديمةُ تبقى شبكةَ أمان**: لو تعذّرت قراءةُ القدرات
 * لم يُحبَس الأدمنُ خارجَ لوحته.
 */
export function canAccessPanel(
  user: AuthUser | null,
  capabilities: readonly string[] = [],
): boolean {
  // ══════════════════════════════════════════════════════════════
  // **وموضعُ القرار واحدٌ** (`WEBA`، ٢٠٢٦-٠٩-١٣)
  // ══════════════════════════════════════════════════════════════
  //
  // **وكان هذا البابُ قد صُلِّح وبقي بابُ التوجيه على الأسماء** —
  // **فباب يُفتح وطريقٌ لا يؤدّي إليه.** **وصارا يقرآن دالّةً
  // واحدة.**
  if (!user) return false;
  return isWebAuthorized(user.roles, capabilities);
}

/** لوحةُ المتجر — لصاحبه وحدَه. */
export function canAccessPortal(user: AuthUser | null): boolean {
  return hasRole(user, "merchant");
}

/** لوحةُ المندوب. */
export function isRep(user: AuthUser | null): boolean {
  return hasRole(user, "sales");
}

/** لوحةُ السائق. */
export function isDriver(user: AuthUser | null): boolean {
  return hasRole(user, "driver");
}
