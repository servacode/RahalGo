#!/usr/bin/env bash
# ══════════════════════════════════════════════════════════════════════
#  ترقيةُ أثرٍ مبنيٍّ — اختيارٌ لا بناء
# ══════════════════════════════════════════════════════════════════════
#
# (دورةُ ٧١.)
#
# # العقد
#
#     EXPECTED_IMAGE_ID == ACTUAL_IMAGE_ID   قبلَ النشر وبعدَه
#
# **ونشرٌ لا يقارن ينشر ما لم يُختبَر وهو يظنّه ترقية.**
#
# # ولا بناءَ صامتٌ بديلاً
#
# **و`--no-build` ليست زينةً**: **`compose` يبني حين لا يجد الصورةَ**
# — **فلو غاب الأثرُ لَبُني غيرُه ونُشر.** **والفشلُ مغلقٌ هنا: إن لم
# يوجد الأثرُ يقف الأمر.**
#
# # والهويّةُ تُقرأ من المحرّك نفسِه بعد الإقلاع
#
# **ومعرّفُ الصورة يقول «أيُّ طبقاتٍ تعمل»** — **و`/public/identity`
# يقول «أيُّ مصدرٍ بُنيت منه».** **والاثنان معاً يُغلقان البابَ على
# صورةٍ وُسمت خطأً.**
#
# الاستعمال:
#   deploy/promote.sh <compose-file> <env-file> <image-ref> <health-url> [expected-image-id]
set -euo pipefail

COMPOSE="${1:?ملفُّ التركيب مطلوب}"
ENVFILE="${2:?ملفُّ البيئة مطلوب}"
IMAGE="${3:?مرجعُ الأثر مطلوب — وسمُ إصدارٍ ثابتٌ أو معرّفُ صورة}"
HEALTH="${4:?عنوانُ الهويّة مطلوب}"
EXPECT="${5:-}"

# ══════════════════════════════════════════════════════════════════════
# **والبيئةُ المقصودةُ تُقال صراحةً** (`ENVG`، ٢٠٢٦-٠٩-١٣)
# ══════════════════════════════════════════════════════════════════════
#
# # ما وقع
#
# **رُقّي الإنتاجُ ورابطُ التحقّق منفذُ التجهيز** — **فطبعت البوّابةُ
# هويّةَ التجهيز شاهداً على الإنتاج.** (أُثبت الإنتاجُ منفصلاً بالنطاق
# العامّ فقُبلت الدفعة — **والحارسُ يمنع التكرار.**)
#
# # ولماذا لا يُقسَّى العنوانُ
#
# **العناوينُ تتبدّل والمنافذُ تُنقَل** — **وقائمةُ «عناوينِ تجهيزٍ
# ممنوعةٍ» تشيخ صامتة.** **وردُّ الهويّة نفسُه هو الحقيقة**: من قال
# `environment` غيرَ المقصودة فليس هو.
TARGET_ENV="${TARGET_ENV:?TARGET_ENV مطلوب — production أو staging}"
case "$TARGET_ENV" in
	production|staging) ;;
	*) echo "TARGET_ENV غيرُ معروفة: $TARGET_ENV" >&2; exit 1 ;;
esac

fail() { echo "✗ $*" >&2; exit 1; }

# ── ١ · الوسمُ المتحرّكُ ليس هويّة ───────────────────────────────────
#
# **و`latest` تقول «آخرُ ما بُني على هذا الخادم» لا «ما اعتُمد».**
case "$IMAGE" in
	# **والعلامةُ المائلةُ الخلفيّةُ تُفسَّر أمراً في النصّ المزدوج** —
	# فالرسالةُ بنصٍّ مفرد.
	*:latest|*latest) fail '**latest ليست هويّةَ إصدار** — استعمل وسمَ release-<commit> أو معرّفَ الصورة.' ;;
esac

# ── ٢أ · **ورابطُ التحقّق يجب أن يكون رابطَ البيئة المقصودة** ───────
#
# **ويُسأل قبل التبديل**: **البيئةُ القائمةُ على هذا الرابط هي التي
# سيبدّلها النشر** — **فإن قالت غيرَ المقصودة فالرابطُ ليس رابطَها.**
#
# **وهذا ما يمنع حادثَ ٢٠٢٦-٠٩-١٣**: `TARGET_ENV=production` ورابطٌ
# يردّ بيئةَ تجهيزٍ ⇒ **وقوفٌ قبل `up`.**
#
# **ولا يُمضى على رابطٍ لا يردّ إلّا بإذنٍ صريحٍ معلَن** — **أوّلُ نشرةٍ
# في بيئةٍ لا سلفَ لها** — فتُمرَّر `ALLOW_UNVERIFIED_TARGET=1`.
PRE_BODY="$(curl -fsS -m 10 "$HEALTH" 2>/dev/null || true)"
if [ -z "$PRE_BODY" ]; then
	if [ "${ALLOW_UNVERIFIED_TARGET:-0}" = "1" ]; then
		echo "PREFLIGHT_TARGET_ENV=$TARGET_ENV (بلا سلفٍ — بإذنٍ صريح)"
	else
		fail "**رابطُ التحقّق لا يردّ قبل التبديل**: $HEALTH — **ولا تُبدَّل بيئةٌ لا يُعرَف أنّها هي.**"
	fi
else
	PREENV="$(printf '%s' "$PRE_BODY" | grep -o '"environment":"[^"]*"' | cut -d'"' -f4)"
	[ -n "$PREENV" ] || fail "**ردُّ الهويّة بلا حقل بيئة**: $HEALTH"
	[ "$PREENV" = "$TARGET_ENV" ] || fail "**رابطُ التحقّق يخصُّ بيئةً أخرى**: المقصودةُ $TARGET_ENV · والرابطُ يقول $PREENV — **وقوفٌ قبل النشر.**"
	echo "PREFLIGHT_TARGET_ENV=$PREENV"
fi

# ── ٢ب · الأثرُ موجودٌ فعلاً — وإلّا وقف ──────────────────────────────
ACTUAL="$(docker image inspect "$IMAGE" --format '{{.Id}}' 2>/dev/null)" \
	|| fail "**الأثرُ غيرُ موجودٍ في مخزن الصور**: $IMAGE — **ولا يُبنى بديلٌ عنه.**"

if [ -n "$EXPECT" ] && [ "$ACTUAL" != "$EXPECT" ]; then
	fail "**تفاوتٌ قبلَ النشر**: المنتظَرُ $EXPECT · والموجودُ $ACTUAL"
fi
echo "PREFLIGHT_IMAGE_ID=$ACTUAL"

# ── ٢ج · **ولا يُبدَّل الإنتاجُ إلى أثرٍ لا يقول ما هو** (٢٠٢٦-٠٩-١٣)
#
# **وحارسُ الهويّة كان بعدَ `up -d`** — **فيكشف العطبَ والإنتاجُ صار
# عليه.** **وكشفٌ بعد الوقوع إنذارٌ لا منع.**
#
# **ويُسأل الأثرُ نفسُه قبل التبديل** — بلا قاعدةٍ ولا شبكةٍ ولا
# إعداد: `-identity` يخرج بـ٣ إن كان الختمُ فارغاً.
#
# **وقِيس ٢٠٢٦-٠٩-١٣**: أثرٌ رُقّي إلى الإنتاج بهويّةٍ فارغة لأنّ
# سكربتاً عارضاً تجاوز `build-artifact.sh`. **ولم يقف شيءٌ في وجهه
# قبل التبديل.**
IDOUT="$(docker run --rm --entrypoint /app/api "$IMAGE" -identity 2>&1)" || {
	echo "$IDOUT" | sed 's/^/    /' >&2
	fail "**أثرٌ بلا هويّةٍ مختومة**: $IMAGE — **ولا يُرقَّى ما لا يقول ما هو.**"
}
PREC="$(printf '%s' "$IDOUT" | grep -o '"source_commit": *"[^"]*"' | cut -d'"' -f4)"
PREB="$(printf '%s' "$IDOUT" | grep -o '"build_id": *"[^"]*"' | cut -d'"' -f4)"
[ "${#PREC}" -eq 40 ] || fail "**ختمُ الالتزام ليس بصمةً كاملة**: '$PREC'"
[ -n "$PREB" ] || fail "**ختمُ البناء فارغ.**"
echo "PREFLIGHT_SOURCE_COMMIT=$PREC"
echo "PREFLIGHT_BUILD_ID=$PREB"

# ── ٣ · النشرُ — المحرّكُ وحدَه، بلا بناءٍ وبلا تبعيّات ──────────────
export RAHALGO_API_IMAGE="$IMAGE"
docker compose -f "$COMPOSE" --env-file "$ENVFILE" up -d --no-build --no-deps api

# ── ٤ · التحقّقُ بعدَ النشر ──────────────────────────────────────────
CID="$(docker compose -f "$COMPOSE" --env-file "$ENVFILE" ps -q api)"
[ -n "$CID" ] || fail "**لا حاويةَ محرّكٍ بعد النشر.**"
RUNNING="$(docker inspect "$CID" --format '{{.Image}}')"
[ "$RUNNING" = "$ACTUAL" ] \
	|| fail "**تفاوتٌ بعدَ النشر**: العاملُ $RUNNING · والمنشورُ $ACTUAL"
echo "RUNNING_IMAGE_ID=$RUNNING"

# **ومهلةٌ للإقلاع** — الهجراتُ تُطبَّق عند الإقلاع.
for _ in $(seq 1 60); do
	BODY="$(curl -fsS "$HEALTH" 2>/dev/null)" && break
	sleep 1
done
[ -n "${BODY:-}" ] || fail "**المحرّكُ لم يُجب على $HEALTH بعد النشر.**"
echo "IDENTITY=$BODY"

# **ولا يُقبَل إقلاعٌ بلا هويّة** — صورةٌ بُنيت بلا حقنٍ تردّ فراغاً.
echo "$BODY" | grep -q '"source_commit":"[0-9a-f]\{40\}"' \
	|| fail "**هويّةُ المصدر غائبةٌ أو ناقصة** — **أثرٌ بُني بلا حقن.**"

# **وبعد النشر تُطابَق البيئةُ ثانياً** — **فردٌّ من بيئةٍ أخرى ليس
# شاهداً على هذه**، ولو مرّ الحارسُ الأوّل.
POSTENV="$(printf '%s' "$BODY" | grep -o '"environment":"[^"]*"' | cut -d'"' -f4)"
[ "$POSTENV" = "$TARGET_ENV" ] 	|| fail "**ردُّ ما بعد النشر من بيئةٍ أخرى**: المقصودةُ $TARGET_ENV · والردُّ $POSTENV"

echo "✓ رُقّي الأثرُ عينُه — بلا بناء."
