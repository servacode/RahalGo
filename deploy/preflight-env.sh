#!/usr/bin/env bash
# ══════════════════════════════════════════════════════════════════════
#  الهدفُ يقول من هو — **قبل أن يُمَسَّ شيء**
# ══════════════════════════════════════════════════════════════════════
#
# # ما وقع (٢٠٢٦-٠٩-١٥)
#
# **و`promote.sh` يسأل الهويّةَ قبل التبديل منذ ٢٠٢٦-٠٩-١٣** — **لكنّ
# `staging/deploy.sh` كان يرفع `caddy web postgres redis` قبل أن يبلغه**:
# **فلو كان المكدّسُ المقصودُ إنتاجاً لَمُسّ قبل أن يسأله أحدٌ من هو.**
#
# **والسؤالُ يسبق كلَّ مَسّ** — **وكشفٌ بعد الوقوع إنذارٌ لا منع.**
#
# # ولا يُقسَّى عنوانٌ ولا منفذ
#
# **والمنافذُ تُنقَل والعناوينُ تتبدّل** — **وقائمةُ «عناوينَ ممنوعةٍ»
# تشيخ صامتة.** **وردُّ الهويّة نفسُه هو الحقيقة.**
#
# # والصامتُ ليس إنتاجاً
#
# **وهدفٌ لا يردّ قد يكون مكدّساً لم يُقلع بعد** — **وأوّلُ نشرٍ لا
# سلفَ له.** **فيُسمَح بالصمت ما لم يُطلب التشدّد** (`STRICT=1`)،
# **ويُمنَع القولُ بغير البيئة المقصودة دائماً.**
#
#	preflight-env.sh <رابطُ الهويّة> <البيئةُ المقصودة>
#
#	0  ⇒ الهدفُ هو المقصود (أو صامتٌ بلا تشدّد)
#	7  ⇒ **الهدفُ بيئةٌ أخرى** — **ولا يُمَسّ**
#	8  ⇒ ردٌّ بلا حقل بيئة، أو صمتٌ مع `STRICT=1`
set -euo pipefail

URL="${1:?رابطُ الهويّة مطلوب}"
WANT="${2:?البيئةُ المقصودة مطلوبة — production أو staging}"

case "$WANT" in
	production | staging) ;;
	*)
		echo "✗ بيئةٌ غيرُ معروفة: $WANT" >&2
		exit 8
		;;
esac

BODY="$(curl -fsS -m 10 "$URL" 2>/dev/null || true)"

if [ -z "$BODY" ]; then
	if [ "${STRICT:-0}" = "1" ]; then
		echo "✗ الهدفُ لا يردّ ولا يُقبَل الصمت: $URL" >&2
		exit 8
	fi
	echo "PREFLIGHT_TARGET=صامت (مكدّسٌ لم يُقلع بعد) — $URL"
	exit 0
fi

GOT="$(printf '%s' "$BODY" | grep -o '"environment":"[^"]*"' | cut -d'"' -f4)"
if [ -z "$GOT" ]; then
	echo "✗ ردُّ الهويّة بلا حقل بيئة: $URL" >&2
	exit 8
fi

if [ "$GOT" != "$WANT" ]; then
	echo "✗ **الهدفُ يقول إنّه $GOT والمقصودُ $WANT** — **وقوفٌ قبل أن يُمَسّ شيء.**" >&2
	echo "  $URL" >&2
	exit 7
fi

echo "PREFLIGHT_TARGET_ENV=$GOT"
